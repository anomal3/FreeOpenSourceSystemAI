//! Сценарии стенда: что именно проверяется прогоном.
//!
//! # Правило проверок
//!
//! Утверждения делаются **только по серийной линии**. Снимок экрана
//! доказательством не является: он показывает последний нарисованный кадр, а не
//! текущее состояние, и после падения отстаёт на два-три экрана. Снимки здесь
//! отвечают на вопрос «как это выглядело», журнал — на вопрос «что произошло».
//!
//! # Почему сценарии — код, а не файлы данных
//!
//! Потому что их пишет тот же человек, который меняет ядро, и в тот же момент.
//! Формат файла пришлось бы разбирать и проверять, а его ошибки вылезали бы во
//! время прогона; здесь опечатку в имени клавиши ловит компилятор.

use super::aim::{self, Aim};
use crate::arch::Arch;
use crate::qemu::DiskBus;

/// Носитель, с которого грузится сценарий.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Target {
    /// Каталог хоста, выданный за FAT-раздел: самый быстрый цикл, но разметки
    /// не существует, и проверять на ней нечего, кроме самой системы.
    Live,
    /// Настоящий образ диска: наша разметка, наша файловая система.
    Image,
    /// Установочный носитель плюс чистый целевой диск.
    Installer,
    /// Диск, на который ставил установщик.
    Installed,
    /// Загрузочный ISO, подключённый приводом — ровно так, как его подключит
    /// человек в VirtualBox.
    Iso,
    /// Система грузится с каталога хоста, а рядом подключён диск, на который
    /// ставил установщик.
    ///
    /// Нужно там, где проверяется **драйвер диска**, а не загрузка с него.
    /// Прошивка `ArmVirtQemu` не умеет SATA вовсе (`map: No mapping found`), так
    /// что подключить установленный диск по AHCI и ждать, что она с него
    /// стартует, можно только на x86-64 — а драйвер в ядре один на обе
    /// архитектуры, и проверять его надо на обеих. Здесь загрузка идёт тем
    /// путём, который прошивка умеет всегда, а проверяемый диск оказывается
    /// вторым носителем: ядро обязано найти корень **на нём**, перебрав оба.
    LiveAndDisk,
}

impl Target {
    pub const fn needs_installer(self) -> bool {
        matches!(self, Target::Installer)
    }

    /// Работает ли сценарий с тем самым диском, на который ставил установщик.
    ///
    /// По этому признаку параллельный прогон собирает сценарии в неделимую
    /// цепочку. Диск здесь — общая память между сценариями, причём в обе
    /// стороны: `install` его пишет, `installed` и `write` читают, `persist`
    /// проверяет записанное **отдельной загрузкой**, `rollback` и `update`
    /// меняют активный слот, а `install4k` пересоздаёт его целиком с сектором
    /// в 4096 байт. Разложить такое по воркерам нельзя: у каждого воркера свой
    /// диск, и сценарий, уехавший к соседу, читал бы либо чужую установку,
    /// либо пустой файл.
    pub const fn shares_target_disk(self) -> bool {
        matches!(
            self,
            Target::Installer | Target::Installed | Target::LiveAndDisk
        )
    }

    pub const fn title(self) -> &'static str {
        match self {
            Target::Live => "каталог хоста через VVFAT",
            Target::Image => "образ диска GPT + FAT32",
            Target::Installer => "установочный носитель и чистый диск",
            Target::Installed => "диск после установки",
            Target::Iso => "загрузочный ISO в приводе",
            Target::LiveAndDisk => "каталог хоста плюс диск после установки",
        }
    }
}

/// Шаг сценария.
pub enum Step {
    /// Дождаться подстроки в серийной линии (мс).
    ///
    /// Поиск идёт от места, где закончилось прошлое ожидание: приглашение
    /// `freeos> ` встречается в выводе десятки раз, и поиск с начала считал бы
    /// выполненным то, что ещё не началось.
    Await(&'static str, u64),
    /// Дождаться подстроки и запомнить число, стоящее сразу за ней.
    ///
    /// Запомненное подставляется вместо `{}` в последующих [`Step::Await`],
    /// [`Step::Expect`], [`Step::Absent`] и [`Step::Line`].
    ///
    /// Существует потому, что номер задачи — не свойство сценария, а свойство
    /// системы: одна служебная задача, заведённая в ядре, сдвигает нумерацию, и
    /// сценарий с числом в строке начинает проверять не то, что собирался.
    Capture(&'static str, u64),
    /// То же, но во **вторую** ячейку: подставляется вместо `{2}`.
    ///
    /// Одной ячейки хватало ровно до того дня, когда прогон пошёл в несколько
    /// потоков. Сценарий одновременности запускает две копии программы и ждёт
    /// конца каждой; первая ищется по своему номеру где угодно в выводе, а
    /// вторая ждалась «следующей строкой с `: done`» — то есть в предположении,
    /// что копии заканчиваются в том порядке, в котором запущены. Под нагрузкой
    /// вторая копия досчитала раньше первой, её строка оказалась позади
    /// курсора, и сценарий упал, доказывая обратное тому, что проверяет.
    Capture2(&'static str, u64),
    /// Дождаться подстроки **где угодно** в выводе, в том числе позади курсора.
    ///
    /// Нужно там, где сценарий ждёт события от двух задач сразу: порядок, в
    /// котором они допишут свои строки, ему не подчиняется, а обычное ожидание
    /// ищет только вперёд и теряет то, что уже напечатано. Подставлять сюда
    /// стоит строку с номером задачи из [`Step::Capture`] — иначе одно и то же
    /// совпадение засчитается дважды.
    AwaitAny(&'static str, u64),
    /// Дождаться числа за подстрокой и сверить его с часами **хоста**.
    ///
    /// Число — секунды эпохи Unix; допуск задаётся в секундах. Существует
    /// потому, что «система напечатала дату» и «система знает, который час» —
    /// разные утверждения: напечатать правдоподобную дату можно и не зная
    /// ничего, а совпасть с часами хоста с точностью до минуты, не прочитав их
    /// у прошивки, нельзя.
    ///
    /// Заодно это единственная проверка часового пояса, которая ловит ошибку в
    /// знаке: сдвиг на целый час здесь не проходит.
    Clock(&'static str, u64, u64),
    /// Дождаться числа за подстрокой и проверить, что оно не больше предела.
    ///
    /// Отличается от [`Step::Clock`] тем, что не спрашивает часы хоста, а
    /// значит проверяет систему саму по себе: «файл помечен тем временем,
    /// которое система считает текущим» — утверждение о её внутренней
    /// согласованности, и внешние часы для него не нужны.
    AtMost(&'static str, u64, u64),
    /// Дождаться числа за подстрокой и проверить, что оно не меньше предела.
    ///
    /// Нужно там, где проверяется, что что-то вообще происходит: счётчик
    /// прерываний, оставшийся нулём, — это работающая система, которая делает
    /// то же самое другим способом, и никакая проверка «работает ли» её не
    /// отличит.
    AtLeast(&'static str, u64, u64),
    /// Проверить, что подстрока встречалась хоть раз за прогон.
    Expect(&'static str),
    /// Проверить, что подстроки не было ни разу.
    Absent(&'static str),
    /// Нажать клавишу на **настоящей** клавиатуре (имя в терминах QEMU).
    Key(&'static str),
    /// Нажать клавишу несколько раз.
    Repeat(&'static str, u32),
    /// Набрать текст на клавиатуре.
    Type(&'static str),
    /// Отправить строку в серийную линию, завершив переводом строки.
    Line(&'static str),
    /// Отправить в серийную линию байты как есть.
    Raw(&'static [u8]),
    /// Сдвинуть мышь на приращение. Абсолютных координат у мыши нет.
    Move(i32, i32),
    /// Навести мышь на то, что гость сам описал в журнале.
    Aim(aim::Aim),
    /// Нажать левую кнопку и отпустить её там же.
    Click,
    /// Щелчок правой кнопкой — меню рабочего стола.
    RightClick,
    /// Нажать левую кнопку и **не** отпускать — начало перетаскивания.
    Press,
    /// Отпустить все кнопки.
    Release,
    /// Подключить устройство к работающей машине (аргументы `device_add`).
    Plug(&'static str),
    /// Выдернуть устройство по его идентификатору.
    Unplug(&'static str),
    /// Подождать (мс).
    Wait(u64),
    /// Снять экран.
    Shot(&'static str),
    /// Сбросить машину, ничего не спрашивая у гостя (`system_reset` монитора).
    ///
    /// Это и есть «выдернули шнур»: система не получает ни уведомления, ни
    /// возможности что-нибудь дописать. Единственный способ проверить, что
    /// брошенный том действительно объявляется грязным при следующей загрузке —
    /// корректное выключение проверяет ровно противоположное утверждение.
    Reset,
    /// Нажать кнопку питания (`system_powerdown` монитора).
    ///
    /// Не то же самое, что команда `shutdown`: команду выполняет оболочка, а
    /// кнопку — обработчик прерывания и служебная задача, и путь от чипсета до
    /// сброса тома на диск проверяется только так.
    PowerButton,
    /// Подключиться к гостю **с хоста** по проброшенному порту, отправить текст
    /// и убедиться, что он вернулся тем же.
    ///
    /// Это единственная проверка стенда, которая ничего не читает в серийной
    /// линии, и в этом весь смысл: сюда стучится обычный клиент TCP из обычной
    /// стандартной библиотеки — то есть чужая реализация протокола, ничего не
    /// знающая о том, как он написан у нас. Сойдётся окно, номера, контрольные
    /// суммы и закрытие — обмен состоится; ошибёмся в любом из них — соединение
    /// либо не установится, либо повиснет.
    TcpEcho(&'static str, u64),
    /// То же, но большим потоком: сколько килобайт отправить туда и обратно.
    ///
    /// Отдельным шагом, потому что проверяет другое. Короткая строка проходит
    /// одним сегментом, и на ней не видно ни окна, ни продолжения потока;
    /// килобайты идут несколькими сегментами, требуют подтверждений по ходу и
    /// упираются в буфер приёма на той стороне.
    TcpBulk(usize, u64),
    /// Позвать **настоящий** `ssh` с хоста и проверить, что он сказал.
    ///
    /// Самая честная проверка SSH, какая существует: клиент OpenSSH придирчив к
    /// деталям формата, и всё, в чём мы ошиблись, он назовёт вслух и оборвёт
    /// соединение. Никакой наш код в этой проверке не участвует.
    Ssh(SshRun),
    /// Дождаться, пока **процесс QEMU завершится сам** (мс).
    ///
    /// Самая сильная проверка выключения из возможных: до этой фазы стенд
    /// всегда снимал QEMU принудительно, потому что гость не умел гаснуть. Если
    /// процесс ушёл сам — значит гость действительно выполнил команду ACPI (или
    /// PSCI), а не просто напечатал, что собирается.
    Exits(u64),
}

/// С каким ключом стенд стучится к гостю.
///
/// Ключи делает `ssh-keygen` на машине разработчика при первом прогоне, а
/// открытая половина `Authorized` попадает в `authorized_keys` гостя — см.
/// [`super::sshkeys`].
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Identity {
    /// Ключа нет вовсе: клиент дойдёт до отказа во входе и там остановится.
    None,
    /// Ключ, записанный в `authorized_keys` гостя.
    Authorized,
    /// Ключ, которого гость не знает.
    ///
    /// Без этой проверки все остальные ничего не доказывают: сервер, пускающий
    /// по любому ключу, проходит проверку «вошли с правильным ключом» ровно так
    /// же успешно, как правильный.
    Stranger,
}

/// Один запуск настоящего `ssh` с хоста.
///
/// Полями, а не позициями: их шесть, и строка вида `Ssh(&[...], "", "", &[], 60_000)`
/// читалась бы гаданием.
pub struct SshRun {
    pub identity: Identity,
    /// Команда для удалённой стороны. Пусто — сеанс без команды, то есть
    /// оболочка.
    pub command: &'static str,
    /// Что подать клиенту на вход. Построчный сеанс читает это как команды —
    /// так проверяется оболочка, которой некому набирать.
    pub stdin: &'static str,
    /// Что обязано найтись в выводе `ssh` (он пишет диагностику в поток ошибок,
    /// а вывод удалённой команды — в обычный; проверяются оба).
    pub expect: &'static [&'static str],
    /// Чего в выводе быть не должно.
    ///
    /// Проверка отказа состоит из двух половин, и вторая здесь: мало увидеть
    /// слово «отказано» — надо убедиться, что содержимого файла в ответе нет.
    pub absent: &'static [&'static str],
    pub timeout_ms: u64,
}

pub struct Scenario {
    pub name: &'static str,
    pub about: &'static str,
    pub target: Target,
    pub steps: &'static [Step],
    /// Дополнительные аргументы QEMU.
    pub extra: &'static [&'static str],
    /// Ввод должен идти именно через USB.
    ///
    /// На x86-64 к машине подключены и PS/2, и USB, а `sendkey` доходит ровно
    /// до одной клавиатуры — QEMU выбирает PS/2. Без отключения i8042 сценарий
    /// «проверяем USB HID» молча проверял бы совсем другой драйвер.
    pub usb_only: bool,
    /// Вместо мыши к машине подключён планшет.
    ///
    /// Это другое устройство, а не та же мышь другими словами: планшет не
    /// объявляет boot-протокола и сообщает координаты вместо приращений. Ровно
    /// такой манипулятор VirtualBox предлагает по умолчанию, поэтому путь через
    /// разбор дескриптора отчётов проверяется здесь, а не на чужой машине.
    ///
    /// Заодно меняется способ управления: абсолютное событие посылается через
    /// QMP, потому что в HMP такой команды нет (см. [`super::qmp`]).
    pub tablet: bool,
    /// Устройства ввода подключены через OHCI, а не через xHCI.
    ///
    /// Это другой драйвер в ядре, а не другая настройка эмулятора. Сценарий
    /// существует потому, что у VirtualBox по умолчанию включён только OHCI:
    /// без него единственной проверкой драйвера была бы чужая машина, на
    /// которой нет журнала.
    pub ohci: bool,
    /// Чем подключён диск сценария.
    ///
    /// Проверяется этим не эмулятор, а **другой драйвер в ядре**. Пока в
    /// FreeOS был один дисковый драйвер, вся цепочка «система находит свой
    /// корень» проверялась исключительно на virtio-blk — то есть на
    /// контроллере, которого нет ни в VirtualBox по умолчанию, ни в настоящем
    /// компьютере. Сценарий с другой шиной берёт тот же самый установленный
    /// диск и подключает его по SATA или по NVMe: образ не меняется ни на байт,
    /// меняется только то, чем ядро до него добирается.
    pub disk_bus: DiskBus,
    /// Подключить к машине сетевую карту в пользовательскую сеть QEMU.
    ///
    /// По умолчанию карты нет, и это не экономия: машина без сети — это ещё и
    /// проверка того, что система без карты поднимается молча и без жалоб. Сеть
    /// включается там, где её проверяют.
    pub network: bool,
    /// Порт гостя, который стенд пробрасывает с хоста. Ноль — не пробрасывать.
    ///
    /// Нужен там, где проверяется **входящее** соединение. Через SLIRP иначе
    /// никак: сеть за трансляцией адресов, и снаружи внутрь не проходит ничего,
    /// о чём не попросили заранее.
    pub guest_port: u16,
    /// Поднять на хосте эхо-сервер, к которому подключается **гость**.
    ///
    /// Обратное направление к [`Scenario::guest_port`], и оно проверяет другую
    /// половину автомата: активное открытие, где `SYN` посылаем мы. Гость видит
    /// хост как `10.0.2.2` — так устроена пользовательская сеть QEMU, а номер
    /// порта пишется в команде как `{echo}`: у каждого воркера параллельного
    /// прогона своя четвёрка портов, и число, набранное здесь буквой, увело бы
    /// гостя к серверу соседнего прогона.
    pub host_echo: bool,
    /// Поднять на хосте **сервер обновлений** и подготовить гостю его адрес.
    ///
    /// Три вещи разом, и порознь они бессмысленны: собрать каталог репозитория
    /// (образы, индекс, подпись), раздавать его по HTTP на порту воркера и
    /// положить гостю `/etc/update.cfg`, где этот адрес назван. Последнее — на
    /// раздел состояния и до запуска, тем же приёмом, что [`Scenario::ssh_key`]:
    /// набирать адрес по серийной линии значило бы проверять, как гость
    /// принимает длинную строку, а не как он обновляется.
    ///
    /// Рядом с годным репозиторием кладётся подкаталог `x/` — тот же образ,
    /// подписанный чужим ключом, с правильно подписанным индексом. Без него
    /// проверка «обновление поставилось» ничего не доказывает.
    pub host_repo: bool,
    /// Архитектуры, на которых сценарий имеет смысл. Пусто — все.
    pub arches: &'static [Arch],
    /// Сценарий **намеренно** перезагружает машину.
    ///
    /// Обычно стенд запускает QEMU с `-no-reboot`, и это правильно: перезагрузка
    /// в сценарии, который её не заказывал, означает тройную ошибку, а без флага
    /// она превратилась бы в бесконечный цикл загрузок вместо внятного отказа.
    /// Ровно один сценарий проверяет саму перезагрузку — ему флаг мешает, потому
    /// что с ним QEMU завершается там, где машина должна подняться заново.
    pub reboots: bool,
    /// Положить в образ установленной системы контейнеры обновления.
    ///
    /// Стенд делает это **до** запуска и на хосте: открывает корневой раздел
    /// того же образа, на который ставил установщик, и кладёт в `/media` два
    /// файла — годное обновление и заведомо неисправное. Ровно то же сделал бы
    /// человек, принёсший обновление на флешке.
    ///
    /// Через установочный носитель это стоило бы двух лишних переносов
    /// шестидесяти мегабайт на каждой установке — ради файла, который нужен
    /// двум сценариям из тридцати.
    pub updates: bool,
    /// Положить открытый ключ стенда в `authorized_keys` гостя.
    ///
    /// Тем же приёмом и по той же причине, что [`Scenario::updates`]: файл
    /// пишется на **раздел состояния** уже установленного образа, а не в
    /// initrd. Ключ, попавший в initrd, уехал бы в выпущенный ISO — и всякий,
    /// кто его скачал, получил бы систему, пускающую владельца ключа из
    /// `build/test/`. Подробности — в [`super::sshkeys`].
    pub ssh_key: bool,
}

impl Scenario {
    pub fn runs_on(&self, arch: Arch) -> bool {
        self.arches.is_empty() || self.arches.contains(&arch)
    }

    /// Аргументы QEMU, зависящие от архитектуры.
    pub fn qemu_args(&self, arch: Arch) -> &'static [&'static str] {
        match (self.usb_only, arch) {
            // Опции машины накапливаются: `-machine q35` уже задан, здесь
            // добавляется свойство. На `virt` PS/2 не существует вовсе.
            (true, Arch::X86_64) => &["-machine", "i8042=off"],
            _ => &[],
        }
    }
}

