//! Вывод в терминал, пригодный для нескольких прогонов сразу.
//!
//! # Зачем понадобился отдельный модуль
//!
//! Пока стенд гонял сценарии по одному, `println!` был совершенно достаточен.
//! Параллельный прогон ломает его двумя разными способами, и оба выглядят как
//! испорченный журнал:
//!
//! 1. **Строки перемешиваются между воркерами.** «ждём "login:"» без указания,
//!    кто ждёт, бесполезно: сценариев в работе четыре, и понять, чей это шаг,
//!    нельзя. Поэтому у каждого потока-воркера есть метка (`[w2] `), и она
//!    приписывается **к каждой** строке, включая строки многострочного текста.
//! 2. **Многострочный вывод рвётся посередине.** `println!` берёт замок на
//!    stdout на время одного вызова, но сообщение из трёх строк — это три
//!    вызова у соседнего воркера между первой и второй. Здесь весь текст
//!    выводится под одним замком, поэтому блок остаётся блоком.
//!
//! # Почему макрос, а не функция
//!
//! Потому что заменить `println!` на `say!` во всём xtask — это правка одного
//! слова в каждой строке; переписывать сто шестьдесят вызовов на
//! `out::emit(&format!(...))` значило бы менять каждую из них по существу.
//! В однопоточном режиме метка пуста, и вывод байт в байт тот же, что был.

use std::cell::RefCell;
use std::io::Write as _;
use std::sync::Mutex;

thread_local! {
    /// Метка этого потока: `"[w2] "` у воркера, пусто у всех остальных.
    static TAG: RefCell<String> = const { RefCell::new(String::new()) };
}

/// Замок на весь вывод.
///
/// Отдельный от того, что берёт `stdout().lock()`: тот держится на время одной
/// записи, а нам нужно на время целого сообщения.
static PEN: Mutex<()> = Mutex::new(());

/// Пометить этот поток: с этого мгновения его строки идут с меткой.
pub fn set_tag(tag: String) {
    TAG.with(|slot| *slot.borrow_mut() = tag);
}

/// Есть ли у этого потока метка — то есть идёт ли параллельный прогон.
///
/// По этому признаку [`crate::util::run`] решает, перехватывать ли вывод
/// дочернего процесса: непрерывный поток от четырёх cargo сразу нечитаем.
pub fn tagged() -> bool {
    TAG.with(|slot| !slot.borrow().is_empty())
}

/// Напечатать текст, приписав метку к каждой его строке.
pub fn emit(text: &str) {
    let tag = TAG.with(|slot| slot.borrow().clone());
    let _pen = PEN.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
    let stdout = std::io::stdout();
    let mut out = stdout.lock();
    if tag.is_empty() {
        let _ = writeln!(out, "{text}");
        return;
    }
    for line in text.split('\n') {
        // Метка приписывается и к пустой строке: так видно, что пустая строка
        // тоже чья-то, а не разрыв между воркерами.
        let _ = writeln!(out, "{tag}{line}");
    }
}

/// То же, что `println!`, но с меткой воркера и целым сообщением под замком.
macro_rules! say {
    () => {
        $crate::out::emit("")
    };
    ($($arg:tt)*) => {
        $crate::out::emit(&format!($($arg)*))
    };
}
