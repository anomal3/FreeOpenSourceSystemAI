/* Программа на C, которая переполняет буфер на стеке нарочно.
 *
 * # Что она доказывает
 *
 * Что канарейка стека есть и у программ на C, собранных нашим набором: `clang`
 * ставит её (`-fstack-protector-strong`), эталон читает по тому же символу
 * `__stack_chk_guard` из той же страницы процесса, что и программы на Rust, а
 * падение зовёт `__stack_chk_fail` из стартового кода `crt0.c`.
 *
 * Стенд ждёт строки `stack smashing detected` и кода 134 — а не «killed by»,
 * которым кончился бы возврат по адресу из одних букв `A` без канарейки.
 *
 * # Почему до отметки, а не «столько-то байт»
 *
 * Расстояние от буфера до канарейки зависит от сборки, а эта собирается с
 * `-O2`, где кадр мал и буфер лежит у самой вершины стека. Фиксированное число
 * байт перелетело бы вершину и дало бы отказ страницы **раньше** проверки
 * канарейки. Поэтому верхнюю границу задаёт `main`: адрес своей переменной,
 * лежащей в кадре над `overrun`. Он выше и канарейки, и адреса возврата, но
 * ниже вершины стека — запись затирает канарейку и не выходит за отображённое.
 * Тот же приём, что в `smash.rs`.
 */

#include <stdint.h>
#include <stdio.h>
#include <string.h>

/* Переполнить буфер на своём стеке до отметки `top`.
 *
 * Не встраивается: у функции должен быть свой кадр со своей канарейкой и свой
 * возврат — проверка стоит в эпилоге.
 *
 * Одним `memset`, а не циклом, и по той же причине, что в `smash.rs`: счётчик
 * цикла компилятор вправе положить в стек сразу над буфером, и тогда запись
 * затирает его самого — счётчик становится числом из букв `A`, цикл кончается
 * досрочно, и до канарейки дело не доходит. У `memset` состояние лежит в её
 * кадре, ниже нашего буфера, и записью вверх его не достать. */
__attribute__((noinline)) static void overrun(uintptr_t top) {
    unsigned char buffer[16];
    uintptr_t base = (uintptr_t)buffer;
    memset(buffer, 'A', top > base ? (size_t)(top - base) : 0);
}

int main(int argc, char **argv) {
    (void)argc;
    (void)argv;

    printf("csmash: overrunning a 16-byte stack buffer past its frame\n");
    fflush(stdout);

    /* Отметка в кадре `main`: выше кадра `overrun`, то есть выше его канарейки
     * и адреса возврата, но ниже вершины стека. */
    volatile unsigned char marker = 0;
    uintptr_t top = (uintptr_t)&marker;
    overrun(top);

    /* Сюда доходят только без канарейки. */
    printf("csmash: returned from the overrun at %p\n", (void *)top);
    return 1;
}
