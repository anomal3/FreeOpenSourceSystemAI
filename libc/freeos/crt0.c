/* Точка входа программы на C.
 *
 * # Что делает ядро до нас
 *
 * Кладёт аргументы на стек программы и передаёт управление по адресу из
 * ELF-заголовка, положив `argc` и `argv` в первые два регистра соглашения
 * (`rdi`/`rsi` на x86-64, `x0`/`x1` на AArch64) — то есть ровно так, как если бы
 * звало обычную функцию двух аргументов. Поэтому `_start` объявлен функцией, а
 * не голым куском ассемблера: соглашение о вызове здесь уже соблюдено.
 *
 * Стек выровнен ядром на шестнадцать байт. Проверять это здесь нечем и незачем:
 * невыровненный стек ломает не нас, а первую же инструкцию с вектором внутри
 * `printf`, и выглядит это как отказ в чужом коде.
 *
 * # Чего ядро НЕ делает, а мы полагаемся, что сделано
 *
 * `.bss` обнулён. Это не догадка: кадры под образ программы аллокатор ядра
 * выдаёт чистыми по своему договору, и там это записано именно как условие для
 * `.bss`. Поэтому цикла обнуления здесь нет — он затирал бы уже нулевое.
 *
 * # Почему `exit`, а не `_exit`
 *
 * Потому что `main`, вернувшая значение, обязана пройти тот же путь, что и
 * `exit()`, позванная руками: сброс буферов stdio и вызов всего, что записано
 * через `atexit`. Программа, которая напечатала строку в буфер и вернулась из
 * `main`, иначе не напечатала бы ничего — и выглядело бы это как неработающий
 * `printf`.
 */

#include <stdlib.h>

/* Конструкторы: `__attribute__((constructor))` и статические объекты C++.
 * picolibc собирает их указатели в секцию, а зовёт вот этим. Объявлено здесь, а
 * не взято из заголовка, потому что заголовка у этой функции нет — она часть
 * договора между компоновщиком и стартовым кодом. */
extern void __libc_init_array(void);

extern int main(int argc, char **argv);

void _start(int argc, char **argv);

void _start(int argc, char **argv) {
    __libc_init_array();
    exit(main(argc, argv));
}
