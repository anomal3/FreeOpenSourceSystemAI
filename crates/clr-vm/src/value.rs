//! Значения на стеке вычислений.
//!
//! ECMA-335 (III.1.1) знает на стеке шесть видов: `int32`, `int64`,
//! `native int`, `F` (число с плавающей точкой), ссылку на объект и управляемый
//! указатель. Всё меньшее — `bool`, `char`, `byte`, `short` — на стеке
//! становится `int32` и сужается только при записи в поле, элемент или по
//! указателю. Седьмой вид здесь — значение структуры (фаза N3a).
//!
//! # Как живёт структура
//!
//! Поля структуры лежат в куче отдельным объектом, а на стеке, в переменной или
//! в поле — [`Value::Struct`] с его номером. Копирование по значению держится на
//! одном правиле: **у каждого такого объекта ровно один владелец**. Чтение из
//! места (`ldloc`, `ldfld`, `ldelem`, `dup`…) кладёт на стек копию, а запись в
//! место переписывает поля объекта, который там уже лежит, не меняя его номера.
//! Первое гарантирует, что `b = a; b.Move()` не тронет `a`; второе — что
//! указатель `ref Point p = ref points[2]` остаётся верным, какое бы значение ни
//! записали в `points[2]` потом.

/// Значение на стеке вычислений, в аргументе, в локальной переменной или в поле.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Value {
    I32(i32),
    I64(i64),
    /// `native int` — на 64-битных машинах, где работает FreeOS, это 64 бита.
    Native(i64),
    F(f64),
    /// Ссылка на объект; `None` — `null`.
    Obj(Option<ObjRef>),
    /// Значение структуры: объект с её полями, у которого один владелец.
    Struct(ObjRef),
    /// Управляемый указатель (`&`).
    Ptr(Pointer),
    /// Указатель на метод (`ldftn`) — номер метода среды. Отдельный вид, а не
    /// `native int`: число, случайно совпавшее с номером, не должно становиться
    /// вызываемым.
    Fn(u32),
}

/// Номер объекта в куче.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct ObjRef(pub u32);

/// Куда указывает управляемый указатель.
///
/// Номером кадра, а не адресом: вектор кадров перевыделяется, и адрес
/// локальной переменной в нём не живёт дольше одного вызова. Номер кадра
/// стабилен, пока кадр жив, а указатель на переменную умершего кадра IL
/// создать не может — это запрещает верификатор.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Pointer {
    Local { frame: u32, index: u32 },
    Arg { frame: u32, index: u32 },
    Element { array: ObjRef, index: u32 },
    /// Поле объекта класса или структуры.
    Field { object: ObjRef, index: u32 },
    /// Статическое поле: номер типа среды и номер поля среди его статических.
    Static { ty: u32, index: u32 },
    /// Значение внутри упакованного числа (`unbox` на `int`).
    Boxed(ObjRef),
    /// Сама структура, у которой нет другого места: `this` конструктора в
    /// `newobj` и содержимое упакованной структуры.
    Struct(ObjRef),
}
