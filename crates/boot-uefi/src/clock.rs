//! Время прошивки и монотонный счётчик, снятые одним движением.
//!
//! # Почему это делается в последний момент
//!
//! Потому что всё, что происходит между чтением часов и первым тиком ядра,
//! иначе становится вечным отставанием. Загрузка образа ядра с диска, снятие
//! карты памяти, `ExitBootServices`, прыжок, разбор карты, куча, таблицы
//! страниц — под эмуляцией это секунды. Замерено стендом: семь.
//!
//! Отставание убирается тем, что вместе со временем снимается показание
//! счётчика тактов — того же самого регистра, который ядро потом читает само.
//! Регистр один на обе стороны хэндоффа и в промежутке не сбрасывается, так что
//! ядро может вычесть интервал, который иначе было бы нечем измерить.
//!
//! Часы при этом всё равно читаются как можно позже: разрыв, который мы умеем
//! измерить, лучше сделать маленьким, чем полагаться на арифметику.

use boot_info::BootInfo;

/// Прочитать часы прошивки и счётчик тактов и записать оба в хэндофф.
///
/// Вызывается непосредственно перед `ExitBootServices`, пока runtime-сервисы
/// ещё отвечают по физическим адресам: после выхода `GetTime` требует
/// `SetVirtualAddressMap`, которого мы не делаем.
///
/// Часы могут быть не выставлены или отсутствовать — тогда в хэндофф уходит
/// ноль, и система честно скажет, что даты не знает.
///
/// # Safety
///
/// `info` обязан указывать на инициализированный [`BootInfo`] в памяти,
/// переживающей выход из boot services.
pub unsafe fn record(info: *mut BootInfo) -> u64 {
    let Ok(time) = uefi::runtime::get_time() else {
        return 0;
    };

    let civil = calendar::DateTime::new(
        i32::from(time.year()),
        time.month(),
        time.day(),
        time.hour(),
        time.minute(),
        time.second(),
    );
    // `EFI_TIME` описывает местное время и отдельно сообщает смещение в
    // минутах; UTC получается прибавлением этого смещения. Когда прошивка
    // отвечает `EFI_UNSPECIFIED_TIMEZONE`, смещение неизвестно, и время
    // принимается за UTC — так делают Linux и GRUB, и так же настроен QEMU по
    // умолчанию (`-rtc base=utc`). Ошибка здесь не осталась бы незамеченной:
    // сценарий `clock` сверяет время гостя с часами хоста, и сдвиг на час
    // провалил бы его.
    let offset_minutes = i64::from(time.time_zone().unwrap_or(0));
    let seconds = u64::try_from(civil.to_unix() + offset_minutes * 60).unwrap_or(0);

    // Счётчик снимается сразу за часами — между ними ничего не должно
    // происходить, иначе теряется смысл всей затеи.
    let counter = counter();

    // SAFETY: контракт функции требует валидного указателя на живой `BootInfo`.
    unsafe {
        (*info).wall_clock = seconds;
        (*info).wall_clock_counter = counter;
    }
    seconds
}

/// Монотонный счётчик той же архитектуры, что прочитает ядро.
///
/// На x86-64 это `rdtsc`, на AArch64 — `CNTPCT_EL0`. Значение само по себе
/// ничего не означает — важна лишь разность между этим замером и тем, который
/// ядро сделает позже.
#[must_use]
fn counter() -> u64 {
    #[cfg(target_arch = "x86_64")]
    {
        let low: u32;
        let high: u32;
        // SAFETY: `rdtsc` не трогает память и не меняет флаги.
        unsafe {
            core::arch::asm!(
                "rdtsc",
                out("eax") low,
                out("edx") high,
                options(nomem, nostack, preserves_flags)
            );
        }
        (u64::from(high) << 32) | u64::from(low)
    }

    #[cfg(target_arch = "aarch64")]
    {
        let value: u64;
        // SAFETY: чтение `CNTPCT_EL0` побочных эффектов не имеет. UEFI-приложение
        // на этой платформе исполняется на EL1 или EL2, и регистр доступен на
        // обоих.
        unsafe {
            core::arch::asm!(
                "mrs {}, cntpct_el0",
                out(reg) value,
                options(nomem, nostack, preserves_flags)
            );
        }
        value
    }
}
