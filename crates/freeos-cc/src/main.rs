//! Обёртка компилятора: то, что чужой проект видит как `cc`.
//!
//! Тонкая нарочно. Вся логика — в библиотеке того же крейта, потому что её же
//! подключает `xtask`: правила сборки C обязаны быть в одном месте, иначе
//! программы, собранные нашей командой, и программы, собранные чужим `make`,
//! разъедутся флагами, и разница проявится не сборкой, а поведением.

fn main() -> std::process::ExitCode {
    let argv: Vec<String> = std::env::args().collect();
    let code = freeos_cc::run(argv);
    // `ExitCode::from` берёт байт, а код возврата инструмента бывает больше:
    // приводим к тому, что переживает границу процесса, не теряя «не ноль».
    std::process::ExitCode::from(u8::try_from(code).unwrap_or(1))
}
