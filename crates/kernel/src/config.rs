//! Настройки: правка человека в `/etc`, эталон — в образе.
//!
//! # Зачем два места
//!
//! Затем, что `/etc` живёт на **разделе состояния**, а обновление системы до
//! него не дотягивается: оно пишет корневой образ в свободный слот и переключает
//! указатель, а состояние остаётся тем же самым. Пока умолчания лежали в `/etc`,
//! это означало ровно одно: настройка, которую принесла новая версия, не
//! появлялась ни у кого. Служба, которую в неё дописали, не запускалась — на
//! машине, обновившейся до версии, где эта служба есть.
//!
//! Лечение — то же, что в любой системе с неизменяемым образом: эталонный файл
//! едет в образе (`/usr/share/defaults/etc/<имя>`), а чтение идёт **сначала** в
//! `/etc` и только потом к эталону. Тогда:
//!
//! * новые умолчания доезжают сами, вместе с образом;
//! * в `/etc` лежит ровно то, что человек изменил, — и это видно списком;
//! * «сброс к заводским» — это удалить файл, а не вспомнить, что там было.
//!
//! # Почему не слияние
//!
//! Потому что слияние требует понимать формат, а форматов здесь три и они
//! разные. Файл берётся целиком: правил либо человек, либо образ. Цена честная и
//! названа вслух — правка одной строки в `/etc/services` замораживает **весь**
//! список служб на той версии, когда её сделали. Это неприятно и это лучше, чем
//! система, которая сама придумала, какую половину чужого файла заменить.

use alloc::format;
use alloc::vec::Vec;

use crate::fs;

/// Где лежат правки человека.
pub const ETC: &str = "/etc";

/// Где лежит эталон, приехавший с образом.
pub const DEFAULTS: &str = "/usr/share/defaults/etc";

/// Откуда взялась настройка.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// Из `/etc`: этот файл кто-то менял.
    Etc,
    /// Из образа: файл такой, каким его выпустили.
    Defaults,
}

/// Прочитать настройку по имени файла (`passwd`, `services`, `system.cfg`).
///
/// `None` означает, что её нет ни там, ни там, — обычное состояние живого
/// носителя, а не отказ.
#[must_use]
pub fn read(name: &str, limit: usize) -> Option<(Vec<u8>, Source)> {
    for (prefix, source) in [(ETC, Source::Etc), (DEFAULTS, Source::Defaults)] {
        // Читается мимо проверки прав: спрашивает ядро, а не программа. То же
        // рассуждение, что у `/etc/passwd` в [`crate::user::session`].
        if let Some(Ok((bytes, _))) = fs::read(&format!("{prefix}/{name}"), limit) {
            return Some((bytes, source));
        }
    }
    None
}

/// Есть ли такая настройка вообще.
///
/// Отдельно от [`read`] потому, что спрашивают об этом до того, как есть кому
/// читать: ядро решает, запускать ли супервизор, а разбирает описание служб уже
/// он сам, в третьем кольце.
#[must_use]
pub fn exists(name: &str) -> Option<Source> {
    read(name, 1).map(|(_, source)| source)
}

/// Полный путь, по которому настройку прочитает программа.
///
/// Нужен для сообщений: «взято оттуда-то» без пути — это утверждение, которое
/// человеку нечем проверить.
#[must_use]
pub fn path(name: &str, source: Source) -> alloc::string::String {
    match source {
        Source::Etc => format!("{ETC}/{name}"),
        Source::Defaults => format!("{DEFAULTS}/{name}"),
    }
}
