//! Настройки: правка человека в `/etc`, эталон — в образе.
//!
//! # Зачем два места
//!
//! Затем, что `/etc` живёт на **разделе состояния**, а обновление системы до
//! него не дотягивается: оно пишет корневой образ в свободный слот и переключает
//! указатель, а состояние остаётся тем же самым. Пока умолчания лежали в `/etc`,
//! это означало ровно одно: настройка, которую принесла новая версия, не
//! появлялась ни у кого. Служба, которую в неё дописали, не запускалась — на
//! машине, обновившейся до версии, где эта служба есть.
//!
//! Лечение — то же, что в любой системе с неизменяемым образом: эталонный файл
//! едет в образе (`/usr/share/defaults/etc/<имя>`), а чтение идёт **сначала** в
//! `/etc` и только потом к эталону. Тогда:
//!
//! * новые умолчания доезжают сами, вместе с образом;
//! * в `/etc` лежит ровно то, что человек изменил, — и это видно списком;
//! * «сброс к заводским» — это удалить файл, а не вспомнить, что там было.
//!
//! # Почему не слияние
//!
//! Потому что слияние требует понимать формат, а форматов здесь три и они
//! разные. Файл берётся целиком: правил либо человек, либо образ. Цена честная и
//! названа вслух — правка одной строки в `/etc/services` замораживает **весь**
//! список служб на той версии, когда её сделали. Это неприятно и это лучше, чем
//! система, которая сама придумала, какую половину чужого файла заменить.

use alloc::format;
use alloc::vec::Vec;

use crate::fs;

/// Где лежат правки человека.
pub const ETC: &str = "/etc";

/// Где лежит эталон, приехавший с образом.
pub const DEFAULTS: &str = "/usr/share/defaults/etc";

/// Откуда взялась настройка.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    /// Из `/etc`: этот файл кто-то менял.
    Etc,
    /// Из образа: файл такой, каким его выпустили.
    Defaults,
}

/// Прочитать настройку по имени файла (`passwd`, `services`, `system.cfg`).
///
/// `None` означает, что её нет ни там, ни там, — обычное состояние живого
/// носителя, а не отказ.
#[must_use]
pub fn read(name: &str, limit: usize) -> Option<(Vec<u8>, Source)> {
    for (prefix, source) in [(ETC, Source::Etc), (DEFAULTS, Source::Defaults)] {
        // Читается мимо проверки прав: спрашивает ядро, а не программа. То же
        // рассуждение, что у `/etc/passwd` в [`crate::user::session`].
        if let Some(Ok((bytes, _))) = fs::read(&format!("{prefix}/{name}"), limit) {
            return Some((bytes, source));
        }
    }
    None
}

/// Есть ли такая настройка вообще.
///
/// Отдельно от [`read`] потому, что спрашивают об этом до того, как есть кому
/// читать: ядро решает, запускать ли супервизор, а разбирает описание служб уже
/// он сам, в третьем кольце.
#[must_use]
pub fn exists(name: &str) -> Option<Source> {
    read(name, 1).map(|(_, source)| source)
}

/// Полный путь, по которому настройку прочитает программа.
///
/// Нужен для сообщений: «взято оттуда-то» без пути — это утверждение, которое
/// человеку нечем проверить.
#[must_use]
pub fn path(name: &str, source: Source) -> alloc::string::String {
    match source {
        Source::Etc => format!("{ETC}/{name}"),
        Source::Defaults => format!("{DEFAULTS}/{name}"),
    }
}

/// Записать настройку в `/etc` — то есть на раздел состояния.
///
/// Пишется **всегда в `/etc`** и никогда в эталон: эталон живёт в корневом
/// образе, а тот при обновлении заменяется целиком. Запись туда пропала бы при
/// следующем обновлении, и пропала бы молча — ровно тот отказ, ради которого
/// эти два места и разведены (см. заголовок модуля).
///
/// # Почему пишет ядро, а не программа
///
/// Потому что зовут это из окна «Параметры», а оно — часть ядра, и своей
/// личности у него нет. Права проверять не у кого и не за кого: окно уже
/// открыто тем, кто вошёл, и рисуется поверх его же сеанса. Ровно то же
/// рассуждение, по которому ядро читает `/etc/passwd` мимо проверки прав.
///
/// # Почему файл усекается, а не переписывается заново
///
/// Потому что «удалить и создать» — это две операции, между которыми настроек
/// нет вовсе. Питание, пропавшее между ними, оставило бы систему без часового
/// пояса и без адреса. Усечение с последующей записью оставляет файл коротким,
/// но существующим, и худшее, что из этого выходит, — пустая настройка, то есть
/// возврат к эталону.
pub fn write(name: &str, contents: &str) -> Result<(), crate::vfs::VfsError> {
    use crate::vfs::perm::{Access, Credentials};
    use crate::vfs::VfsError;

    let full = format!("{ETC}/{name}");
    let node = match fs::resolve_as(Credentials::ROOT, &full, Access::WRITE) {
        Some(Ok(node)) => {
            node.truncate(0)?;
            node
        }
        Some(Err(VfsError::NotFound)) => {
            // `0644`: настройки читает всякий, меняет владелец. Те же права,
            // что ставит установщик, и не случайно — файл, появившийся из окна,
            // не должен отличаться от файла, приехавшего с носителем.
            match fs::create_as(Credentials::ROOT, &full, 0o644) {
                Some(result) => result?,
                None => return Err(VfsError::NotFound),
            }
        }
        Some(Err(err)) => return Err(err),
        None => return Err(VfsError::NotFound),
    };
    node.write_at(0, contents.as_bytes())?;
    // Сброс сразу, а не когда-нибудь: настройка, которую человек только что
    // задал, обязана пережить выключение кнопкой, а не только команду
    // `shutdown`. Цена — одна запись на диск за нажатие, и она того стоит.
    let _ = fs::sync_root();
    Ok(())
}

/// Убрать правку человека: настройка возвращается к эталону из образа.
///
/// Возвращает `true`, если файл был и удалён. Отсутствие файла — не ошибка:
/// «сбросить к заводским» на нетронутой настройке обязано быть тихой удачей, а
/// не отказом.
pub fn reset(name: &str) -> Result<bool, crate::vfs::VfsError> {
    use crate::vfs::perm::Credentials;
    use crate::vfs::VfsError;

    let full = format!("{ETC}/{name}");
    match fs::remove_as(Credentials::ROOT, &full) {
        Some(Ok(())) => {
            let _ = fs::sync_root();
            Ok(true)
        }
        Some(Err(VfsError::NotFound)) | None => Ok(false),
        Some(Err(err)) => Err(err),
    }
}

/// Прочитать настройку целиком как текст. Пустая строка — файла нет.
///
/// Удобство поверх [`read`], и не только удобство: всякий, кому нужен один
/// ключ, иначе писал бы эти четыре строки заново, а `from_utf8` — то место, где
/// легко молча вернуть пустоту вместо отказа.
#[must_use]
pub fn text(name: &str, limit: usize) -> alloc::string::String {
    read(name, limit)
        .and_then(|(bytes, _)| alloc::string::String::from_utf8(bytes).ok())
        .unwrap_or_default()
}

