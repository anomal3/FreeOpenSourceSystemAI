//! Терминал: то, что стоит между клавиатурой и программой.
//!
//! # Зачем нужен отдельный модуль
//!
//! До этой фазы у программы был только выход: `write` печатал в окно оболочки, а
//! обратного направления не существовало вовсе. Добавить его «в лоб» — отдать
//! программе очередь [`crate::input`] — нельзя по двум причинам сразу. Очередь
//! одна на систему, и программа, читающая из неё, забирала бы нажатия у
//! оболочки и у рабочего стола. И очередь несёт **клавиши**, а программе нужны
//! **байты**: `read(0, …)` возвращает то, что набрал человек, а не позицию
//! клавиши на клавиатуре.
//!
//! Поэтому здесь то же, что в Unix называется драйвером терминала: буфер
//! готовых к чтению байтов, признак конца ввода и знание о том, какая задача
//! сейчас на переднем плане.
//!
//! # Кто наполняет буфер
//!
//! Задача оболочки, и только она. Она и так единственная, кто разбирает очередь
//! ввода (см. [`crate::shell::task`]), и с этой фазы, запустив программу не в
//! фоне, она не засыпает в ожидании её конца, а продолжает разбирать очередь —
//! только отдаёт разобранное не своему редактору строки, а сюда. Это и есть
//! ответ на вопрос «кому достаётся нажатие»: тому, кого оболочка считает
//! программой переднего плана, и только если рабочий стол отдал событие окну
//! терминала.
//!
//! Разделение обязанностей получается ровно такое же, как в Unix: дисциплина
//! линии (сборка строки, эхо, стирание) живёт в [`crate::input::line`] и
//! работает в задаче оболочки, а здесь — только очередь байтов между двумя
//! задачами.
//!
//! # Два режима
//!
//! **Канонический** (по умолчанию) — строка собирается редактором с эхом и
//! уезжает сюда целиком по Enter. Так работает всякая программа, которая просто
//! спрашивает у человека строку.
//!
//! **Прямой** — каждое нажатие превращается в байты немедленно и без эха: так
//! читает клавиатуру полноэкранная программа, которой нужны стрелки и F-клавиши
//! (`mc`). Специальные клавиши кодируются теми же escape-последовательностями,
//! которые прислал бы настоящий терминал, — см. [`encode`]. Из этого следует
//! приятное: программе всё равно, набрано ли нажатие в окне или пришло по
//! серийной линии от чужого терминала.

use core::sync::atomic::{AtomicBool, AtomicU32, AtomicU64, Ordering};

use crate::input::{KeyCode, KeyEvent, Modifiers, keymap};
use crate::sched::TaskId;
use crate::sync::SpinLock;

/// Сколько байт ввода терминал держит непрочитанными.
///
/// 256 — это строка редактора целиком плюс запас. Больше не нужно: буфер
/// существует между двумя задачами одной машины, и если программа не успевает
/// читать быстрее, чем человек печатает, дело не в размере буфера.
const CAPACITY: usize = 256;

/// Значение [`FOREGROUND`], означающее «программы переднего плана нет».
///
/// Отдельное число, а не `Option` в атомике: атомарных `Option<TaskId>` не
/// бывает, а номер задачи — `u32`, и старшее значение под задачу выдано быть не
/// может (таблица задач — тридцать два слота).
const NO_TASK: u32 = u32::MAX;

struct Buffer {
    bytes: [u8; CAPACITY],
    /// Откуда читать следующий байт.
    head: usize,
    /// Сколько байт лежит непрочитанными.
    len: usize,
    /// Пришёл конец ввода — Ctrl+D. Снимается только сменой программы
    /// переднего плана: одна программа не должна получать чужой конец ввода.
    eof: bool,
    /// Сколько байт потеряно из-за переполнения.
    dropped: u64,
}

impl Buffer {
    const fn new() -> Self {
        Self { bytes: [0; CAPACITY], head: 0, len: 0, eof: false, dropped: 0 }
    }

    fn push(&mut self, byte: u8) -> bool {
        if self.len == CAPACITY {
            // Теряется **новый** байт, а не самый старый, — по той же причине,
            // что и в очереди клавиш: начало ввода уже показано эхом, и выбросив
            // его, мы получили бы строку, не совпадающую с тем, что видит
            // человек.
            self.dropped += 1;
            return false;
        }
        let tail = (self.head + self.len) % CAPACITY;
        self.bytes[tail] = byte;
        self.len += 1;
        true
    }

    fn pop(&mut self) -> Option<u8> {
        if self.len == 0 {
            return None;
        }
        let byte = self.bytes[self.head];
        self.head = (self.head + 1) % CAPACITY;
        self.len -= 1;
        Some(byte)
    }
}

static BUFFER: SpinLock<Buffer> = SpinLock::new(Buffer::new());

/// Задача, которой достаётся ввод. [`NO_TASK`] — никакой.
static FOREGROUND: AtomicU32 = AtomicU32::new(NO_TASK);

/// Прямой режим: нажатия едут байтами, без сборки строки и без эха.
static RAW: AtomicBool = AtomicBool::new(false);

/// Сколько байт программы прочитали за всё время работы.
///
/// Счётчик существует для журнала: «программа прочитала ввод» и «программа
/// напечатала то, что и так знала» выглядят снаружи одинаково, а различить их
/// обязано что-то, кроме доверия к тексту программы.
static READ_BYTES: AtomicU64 = AtomicU64::new(0);

/// Объявить, какая задача сейчас на переднем плане.
///
/// **Запуск** программы очищает буфер: непрочитанные байты набирались для
/// прошлой, и отдать их следующей значило бы, что `mc` открывается с уже
/// нажатой клавишей.
///
/// **Освобождение** буфер не трогает, и это не симметрия ради симметрии. Пока
/// программа работает, человек вправе набирать следующую команду — и в любом
/// tty набранное достаётся следующему читателю, то есть оболочке. Очистка здесь
/// означала бы, что команда, набранная на секунду раньше возврата приглашения,
/// молча пропадает; ровно это и происходило, пока эта строка стояла в обеих
/// ветках.
pub fn set_foreground(task: Option<TaskId>) {
    if task.is_some() {
        let mut buffer = BUFFER.lock();
        buffer.head = 0;
        buffer.len = 0;
        buffer.eof = false;
    }
    RAW.store(false, Ordering::Relaxed);
    FOREGROUND.store(task.map_or(NO_TASK, TaskId::as_u32), Ordering::Relaxed);
    // Строка в журнале — единственное, чем снаружи видно, кому достаётся ввод.
    // Снимок экрана этого не показывает, а без неё «клавиша уехала в программу»
    // и «клавиша потерялась» выглядят одинаково.
    match task {
        Some(id) => crate::kprintln!("  tty         : foreground {id}"),
        None => crate::kprintln!("  tty         : foreground released"),
    }
}

/// Какая задача сейчас на переднем плане.
#[must_use]
pub fn foreground() -> Option<TaskId> {
    match FOREGROUND.load(Ordering::Relaxed) {
        NO_TASK => None,
        raw => Some(TaskId::new(raw)),
    }
}

/// Перевести терминал в прямой режим или вернуть в канонический.
pub fn set_raw(raw: bool) {
    RAW.store(raw, Ordering::Relaxed);
    crate::kprintln!("  tty         : {} mode", if raw { "raw" } else { "canonical" });
}

/// В прямом ли режиме терминал.
#[must_use]
pub fn is_raw() -> bool {
    RAW.load(Ordering::Relaxed)
}

/// Положить байты, набранные человеком, и разбудить того, кто их ждёт.
///
/// Порядок обязателен: сначала байты, потом пробуждение. При обратном ждущий
/// проснулся бы, ничего не нашёл и уснул бы снова — до срока.
pub fn push(bytes: &[u8]) {
    {
        let mut buffer = BUFFER.lock();
        for byte in bytes {
            buffer.push(*byte);
        }
    }
    crate::sched::wake_input();
}

/// Отметить конец ввода: Ctrl+D на пустой строке.
///
/// Не то же самое, что снятие программы: `read` вернёт ноль, и программа сама
/// решит, что с этим делать. Так же ведёт себя всякий tty, и разница
/// осмысленная — «ввод кончился» и «тебя убили» требуют от программы разного.
pub fn push_eof() {
    BUFFER.lock().eof = true;
    crate::sched::wake_input();
}

/// Прочитать в буфер. Ноль означает либо «пока нечего», либо конец ввода —
/// различить их можно по [`at_eof`].
pub fn read(out: &mut [u8]) -> usize {
    let mut written = 0;
    let mut buffer = BUFFER.lock();
    while written < out.len() {
        let Some(byte) = buffer.pop() else {
            break;
        };
        out[written] = byte;
        written += 1;
    }
    drop(buffer);
    if written > 0 {
        READ_BYTES.fetch_add(written as u64, Ordering::Relaxed);
    }
    written
}

/// Забрать всё непрочитанное, включая незаконченную строку.
///
/// Возвращает, сколько байт записано в `out`. Нужно ровно в одном месте:
/// программа переднего плана закончилась, а в буфере осталось набранное,
/// которое она не прочла. Это ввод оболочки, и разобрать его обязана она —
/// целиком, вместе с хвостом без перевода строки. Отдать только законченные
/// строки было бы хуже, чем не отдавать ничего: команда, у которой начало
/// набрано до конца программы, а конец после, разъехалась бы на две.
pub fn take_all(out: &mut [u8]) -> usize {
    let mut buffer = BUFFER.lock();
    let mut written = 0;
    while written < out.len() {
        let Some(byte) = buffer.pop() else { break };
        out[written] = byte;
        written += 1;
    }
    written
}

/// Есть ли что читать прямо сейчас — включая конец ввода.
///
/// Один ответ на оба случая намеренно: спрашивает это тот, кто решает, засыпать
/// ли, а засыпать нельзя ни при непрочитанных байтах, ни при конце ввода.
#[must_use]
pub fn ready() -> bool {
    let buffer = BUFFER.lock();
    buffer.len != 0 || buffer.eof
}

/// Кончился ли ввод.
#[must_use]
pub fn at_eof() -> bool {
    BUFFER.lock().eof
}

/// Сколько байт программы прочитали с начала работы.
#[must_use]
pub fn read_bytes() -> u64 {
    READ_BYTES.load(Ordering::Relaxed)
}

/// Сколько байт потеряно переполнением.
#[must_use]
pub fn dropped() -> u64 {
    BUFFER.lock().dropped
}

/// Сколько байт может занять одно нажатие в прямом режиме.
///
/// Самая длинная последовательность здесь — `ESC [ 2 4 ~` (F12), пять байт.
/// Запас до восьми взят потому, что предел проверяется в [`encode`] один раз, а
/// таблица ниже ещё будет расти.
pub const MAX_ENCODED: usize = 8;

/// Перевести нажатие в байты так, как их прислал бы настоящий терминал.
///
/// Возвращает, сколько байт записано в `out`; ноль означает, что нажатие байтов
/// не даёт (модификатор, отпускание, клавиша без символа).
///
/// # Почему escape-последовательности, а не собственный код клавиши
///
/// Потому что второй источник ввода — серийная линия, и оттуда стрелка приходит
/// именно как `ESC [ A`. Придумав свою кодировку, мы получили бы программу,
/// которая по-разному ведёт себя в окне и в терминале, — и вторую таблицу
/// перевода в придачу. Здесь же обе дороги сходятся в один поток байтов ещё до
/// программы.
#[must_use]
pub fn encode(event: KeyEvent, out: &mut [u8; MAX_ENCODED]) -> usize {
    if !event.pressed {
        return 0;
    }

    // Escape-последовательности проверяются до раскладки: у стрелок и
    // F-клавиш символа нет вовсе, а Backspace и Escape символ имеют, но не тот,
    // который ждёт терминал.
    let sequence: &[u8] = match event.code {
        KeyCode::Up => b"\x1b[A",
        KeyCode::Down => b"\x1b[B",
        KeyCode::Right => b"\x1b[C",
        KeyCode::Left => b"\x1b[D",
        KeyCode::Home => b"\x1b[H",
        KeyCode::End => b"\x1b[F",
        KeyCode::PageUp => b"\x1b[5~",
        KeyCode::PageDown => b"\x1b[6~",
        KeyCode::Insert => b"\x1b[2~",
        KeyCode::Delete => b"\x1b[3~",
        // F1–F4 приехали из VT100, где они назывались PF1–PF4 и кодировались
        // через `ESC O`; остальные — из VT220 с его нумерацией через `~`.
        // Дыры в нумерации (16, 22) не наши: их оставил DEC.
        KeyCode::F1 => b"\x1bOP",
        KeyCode::F2 => b"\x1bOQ",
        KeyCode::F3 => b"\x1bOR",
        KeyCode::F4 => b"\x1bOS",
        KeyCode::F5 => b"\x1b[15~",
        KeyCode::F6 => b"\x1b[17~",
        KeyCode::F7 => b"\x1b[18~",
        KeyCode::F8 => b"\x1b[19~",
        KeyCode::F9 => b"\x1b[20~",
        KeyCode::F10 => b"\x1b[21~",
        KeyCode::F11 => b"\x1b[23~",
        KeyCode::F12 => b"\x1b[24~",
        KeyCode::Escape => b"\x1b",
        // Терминалы присылают на Backspace именно 0x7F, а не 0x08: так делает
        // xterm по умолчанию, и наш разбор в `input::ascii` принимает оба.
        KeyCode::Backspace => b"\x7f",
        KeyCode::Enter | KeyCode::KeypadEnter => b"\n",
        KeyCode::Tab => b"\t",
        _ => {
            let Some(ch) = keymap::char_for_code(event.code, event.mods) else {
                return 0;
            };
            let mut utf8 = [0u8; 4];
            let encoded = ch.encode_utf8(&mut utf8).as_bytes();
            out[..encoded.len()].copy_from_slice(encoded);
            return encoded.len();
        }
    };

    out[..sequence.len()].copy_from_slice(sequence);
    sequence.len()
}

/// Означает ли нажатие «снять программу переднего плана».
///
/// Ctrl+C, и только он. Проверка живёт здесь, а не в оболочке, потому что
/// ответ зависит от режима: в прямом режиме программа читает клавиши сама, но
/// Ctrl+C всё равно остаётся за терминалом — иначе полноэкранная программа,
/// ушедшая в цикл, не снималась бы ничем.
#[must_use]
pub fn is_interrupt(event: KeyEvent) -> bool {
    event.pressed
        && event.mods.contains(Modifiers::CTRL)
        && matches!(event.code, KeyCode::C)
}
