//! Несколько процессоров: сколько их, как их запустить и как остановить.
//!
//! # Что здесь общее, а что нет
//!
//! Способ разбудить процессор у двух архитектур разный до последнего бита. На
//! x86-64 это посылка `INIT` и два `SIPI` через локальный APIC и код, который
//! проснувшийся процессор исполняет в реальном режиме по адресу ниже мегабайта.
//! На AArch64 это одна просьба к прошивке — `PSCI CPU_ON` с адресом входа, — а
//! проснувшийся процессор стоит в EL1 с выключенным MMU. Всё это живёт в
//! `arch::smp`.
//!
//! Общее — порядок: найти процессоры в MADT, завести каждому стек и холостую
//! задачу, запускать по одному и дождаться, пока запущенный сам скажет, что
//! работает. Молчание сверх срока — не «наверное, заработал», а отказ, о
//! котором говорится вслух.
//!
//! # Номер процессора
//!
//! [`cpu`] — самый частый вопрос во всём ядре: его задаёт каждый захват
//! [`crate::sync::SpinLock`]. Отвечать на него обязаны без лока и без памяти,
//! которая может быть чужой, поэтому ответ лежит в регистре, который пишет
//! только ядро: `TPIDR_EL1` на AArch64 и регистр задачи (`TR`) на x86-64, где
//! у каждого процессора свой TSS в своей записи GDT.
//!
//! Пока второго процессора нет, регистр не читается вовсе: до первого запуска
//! ответ всегда ноль. Это не оптимизация, а условие корректности — `TR` до
//! установки GDT и `TPIDR_EL1` до первой записи содержат то, что оставила
//! прошивка.
//!
//! # Чего здесь нет, и почему этого не нужно
//!
//! Сброса TLB на чужих процессорах. План фазы его требовал, и требование верно
//! для системы, где одно адресное пространство исполняется на двух процессорах
//! сразу — то есть для потоков. Здесь программа — это одна задача, а задача в
//! каждый момент живёт не больше чем на одном процессоре. Процессор, с которого
//! её сняли, переключил таблицы на следующую задачу и тем самым сбросил свои
//! трансляции (запись `CR3` на x86-64, `tlbi vmalle1` на AArch64); к моменту,
//! когда программа освобождает страницу на новом процессоре, старых трансляций
//! этой страницы нет нигде. Появятся потоки — появится и рассылка сброса, и её
//! место будет ровно здесь.
//!
//! Будильника для простаивающих процессоров тоже нет: холостой процессор
//! просыпается на собственном тике таймера, то есть не позже чем через десять
//! миллисекунд, и сам находит готовую задачу. Межпроцессорное прерывание
//! сократило бы эту задержку ценой выхода из гостя на каждое пробуждение; пока
//! задержки не видно ни в одном сценарии, платить нечем.

use core::sync::atomic::{AtomicBool, AtomicUsize, Ordering};

use crate::{arch, kprintln, sched, time};

/// Сколько процессоров ядро берётся вести.
///
/// Предел, а не догадка о железе: таблицы «на процессор» (TSS, стеки двойного
/// отказа, состояние планировщика) лежат массивами фиксированного размера,
/// потому что заводятся раньше, чем появляется куча, и потому, что обращаются к
/// ним из обработчиков, где выделять память нельзя. Процессоры сверх предела
/// остаются спать, и это говорится в журнале.
pub const MAX_CPUS: usize = 8;

/// Запущен ли хоть один процессор, кроме загрузочного.
///
/// Пока нет — [`cpu`] отвечает нулём, не спрашивая регистр. Взводится **до**
/// первого запуска: к этому моменту загрузочный процессор уже записал свой
/// номер туда, откуда его читают, а новый процессор не берёт ни одного лока,
/// пока не запишет свой.
static ACTIVE: AtomicBool = AtomicBool::new(false);

/// Сколько процессоров работает прямо сейчас.
static ONLINE: AtomicUsize = AtomicUsize::new(1);

/// Номер процессора, на котором исполняется вызывающий код.
///
/// Ответ верен ровно до ближайшего переключения задач: задачу могут перенести
/// на другой процессор между этим вызовом и следующей строкой. Поэтому
/// спрашивать его имеет смысл либо с запрещёнными прерываниями, либо ради
/// диагностики.
#[inline]
#[must_use]
pub fn cpu() -> usize {
    if !ACTIVE.load(Ordering::Relaxed) {
        return 0;
    }
    arch::smp::current_index()
}

/// Сколько процессоров работает.
#[must_use]
pub fn online() -> usize {
    ONLINE.load(Ordering::Relaxed)
}

/// Что нашлось в таблицах прошивки.
pub struct Found {
    /// Аппаратные номера: идентификатор локального APIC на x86-64, `MPIDR` на
    /// AArch64. Нулевой элемент — загрузочный процессор.
    pub ids: [u64; MAX_CPUS],
    /// Второе число о процессоре, если архитектуре оно нужно: адрес его
    /// redistributor'а у GICv3. Ноль — не нужно или неизвестно.
    pub extra: [u64; MAX_CPUS],
    /// Сколько из них ядро будет вести (не больше [`MAX_CPUS`]).
    pub count: usize,
    /// Сколько включённых процессоров объявила прошивка.
    pub total: usize,
}

impl Found {
    /// Только загрузочный процессор с номером `boot`.
    #[must_use]
    pub const fn only(boot: u64) -> Self {
        let mut ids = [0; MAX_CPUS];
        ids[0] = boot;
        Self { ids, extra: [0; MAX_CPUS], count: 1, total: 1 }
    }

    /// Добавить процессор, если его ещё нет и в таблицах есть место.
    ///
    /// Повтор не считается дважды: прошивка вправе описать один процессор и
    /// записью локального APIC, и записью x2APIC, — а загрузочный встречается в
    /// таблице наравне с остальными.
    pub fn push(&mut self, id: u64, extra: u64) {
        if let Some(known) = self.ids[..self.count].iter().position(|&seen| seen == id) {
            if extra != 0 {
                self.extra[known] = extra;
            }
            return;
        }
        self.total += 1;
        if self.count < MAX_CPUS {
            self.ids[self.count] = id;
            self.extra[self.count] = extra;
            self.count += 1;
        }
    }
}

/// Сколько ждать, пока запущенный процессор скажет, что работает.
///
/// Секунда — с запасом в сотни раз: под эмуляцией без ускорения путь от первой
/// инструкции до строки в журнале занимает миллисекунды. Срок нужен не для
/// медленных машин, а для той, где процессор не проснётся вовсе: без него
/// загрузка остановилась бы здесь навсегда.
const START_TIMEOUT_MS: u64 = 1000;

/// Найти остальные процессоры и запустить их.
///
/// Вызывается один раз, на загрузочном процессоре, когда уже работают таймер,
/// куча и монотонные часы, но задач ещё нет. Раньше нельзя — ожидание
/// запуска меряется часами, а стек нового процессора берётся из кучи. Позже
/// незачем: запущенные процессоры до [`sched::run`] простаивают, а после него
/// сразу берут работу.
pub fn start() {
    kprintln!();
    kprintln!("---- processors -------------------------------------------------");

    let found = arch::smp::discover();
    if found.total > found.count {
        kprintln!(
            "  smp         : firmware lists {} processors, only {MAX_CPUS} are supported",
            found.total
        );
    }
    if found.count <= 1 {
        kprintln!("  smp         : 1 of {} processors online", found.total);
        return;
    }

    if let Err(reason) = arch::smp::prepare() {
        kprintln!("  smp         : secondary processors stay asleep: {reason}");
        kprintln!("  smp         : 1 of {} processors online", found.total);
        return;
    }
    ACTIVE.store(true, Ordering::Release);

    for index in 1..found.count {
        let id = found.ids[index];
        let Some(stack_top) = sched::prepare_cpu(index) else {
            kprintln!("  smp         : no kernel heap for the stack of cpu {index}");
            break;
        };

        let before = online();
        if !arch::smp::start_cpu(index, id, found.extra[index], stack_top) {
            // Процессор не принял просьбу — значит и стек его не понадобится.
            // Отдать его можно только здесь: процессор, который так и не
            // запустился, на нём не исполняется.
            sched::forget_cpu(index);
            continue;
        }

        let deadline = time::uptime_ms() + START_TIMEOUT_MS;
        while online() == before && time::uptime_ms() < deadline {
            core::hint::spin_loop();
        }
        if online() == before {
            // Стек **не** отдаётся: процессор мог проснуться с опозданием и уже
            // стоять на нём. Утечка в тридцать два килобайта дешевле, чем два
            // процессора на одном стеке.
            kprintln!(
                "  smp         : cpu {index} ({} {id:#x}) did not report within {START_TIMEOUT_MS} ms",
                arch::smp::ID_NAME
            );
        }
    }

    kprintln!("  smp         : {} of {} processors online", online(), found.total);
}

/// Последний шаг запуска, общий для обеих архитектур.
///
/// Арх-слой зовёт его на новом процессоре, когда тот уже умеет принимать
/// прерывания: GDT, векторы, контроллер и таймер заведены. Возврата нет —
/// дальше процессор навсегда становится холостой задачей планировщика.
pub fn secondary_main(index: usize) -> ! {
    ONLINE.fetch_add(1, Ordering::AcqRel);
    kprintln!("  smp         : cpu {index} online");

    arch::interrupts::enable();
    // Тот же холостой цикл, что у загрузочного процессора в `sched::run`, без
    // проверки «все ли закончились»: останавливать машину решает загрузочный.
    loop {
        sched::schedule();
        arch::wait_for_interrupt();
    }
}

/// Остановить все процессоры, кроме текущего. Возвращает, скольким послали.
///
/// Нужна там, где машина кончается: паника, неисправимый отказ, выключение.
/// Без неё остановка процессора, заметившего беду, означала бы, что остальные
/// продолжают работать — дописывать том, уже помеченный чистым, или печатать
/// поверх сообщения о панике.
///
/// Процессор, держащий [`crate::sync::SpinLock`], остановится не сразу, а
/// когда отпустит его: прерывания у него запрещены. Это верный порядок — иначе
/// он остановился бы с занятым локом вывода, и сообщение о причине не
/// напечаталось бы уже никогда.
pub fn stop_others() -> usize {
    if !ACTIVE.load(Ordering::Relaxed) {
        return 0;
    }
    let others = online().saturating_sub(1);
    if others > 0 {
        arch::smp::stop_others();
    }
    others
}

/// Обработчик просьбы остановиться. Не возвращается.
pub fn on_stop() -> ! {
    ONLINE.fetch_sub(1, Ordering::AcqRel);
    arch::halt()
}
