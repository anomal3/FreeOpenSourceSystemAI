//! Кто и надолго ли отнимает у системы право переключать задачи.
//!
//! # Зачем
//!
//! Открытый с 21.09.2026 дефект: задача драйвера USB разбужена прерыванием и
//! готова, а процессор получает через четыреста миллисекунд и позже. Вытеснение
//! в ядре есть — оно срабатывает в конце каждого внешнего прерывания (см.
//! [`crate::sched::preempt_point`]), — и не срабатывало в двух случаях: пока
//! прерывания закрыты (любой [`crate::sync::SpinLock`] и `without_interrupts`)
//! и пока кто-то попросил не отбирать процессор. Значит, опоздание — это чей-то
//! длинный участок одного из двух видов, и вопрос только в том, чей.
//!
//! Ответ пришёл с первого же прогона: закрытые прерывания — не больше 13 мс, а
//! просьба не вытеснять — **961 мс** в `shell::print`. Просьба снята (почему —
//! там же), и меряется теперь только первый вид: он остаётся, и следующий
//! длинный участок назовёт себя сам.
//!
//! Прежде у этого вопроса были ответы-догадки: сборка кадра, печать, лок
//! вывода. Та же семья дефектов уже дважды оказывалась не там, где её искали
//! (см. «печать делает машину глухой» в ROADMAP), поэтому здесь не догадка, а
//! замер: самый долгий участок каждого вида и **место в коде**, где он начался.
//!
//! # Что меряется и чего нет
//!
//! Только участки, начатые **после** включения вытеснения. Загрузка честно
//! держит прерывания закрытыми секундами — монтирует корень холостым циклом до
//! появления планировщика, — и без этого условия её участок стоял бы первым в
//! любом отчёте, ничего не говоря о дефекте.
//!
//! Только **внешний** участок: вложенный лок под уже закрытыми прерываниями
//! времени глухоты не добавляет, его покрывает внешний.
//!
//! Не меряются обработчики прерываний и исключений: процессор входит в них с
//! закрытыми прерываниями сам, без нашего кода. Их длительность видна другим
//! путём — строкой о потерянных тиках в `tasks`.
//!
//! # Чем за это платим
//!
//! Одно чтение счётчика процессора при захвате лока и одно при освобождении —
//! `rdtsc` или `CNTVCT_EL0`, десятки тактов, без обращения к памяти. Место
//! запоминается указателем на `Location`, который компилятор кладёт в
//! `.rodata` сам (`#[track_caller]`). Сравнение с рекордом — одна загрузка
//! атомика.
//!
//! Пара «длительность + место» пишется двумя атомиками, а не одним, и может
//! на миг разойтись, когда два процессора ставят рекорд одновременно. Для
//! диагностики, которую читают глазами, это приемлемо; для чего-то, что
//! принимает решения, — нет, и решений на этом числе не строить.

use core::panic::Location;
use core::ptr;
use core::sync::atomic::{AtomicPtr, AtomicU64, Ordering};

use crate::{arch, kprintln};

/// Самый долгий участок одного вида и где он начался.
struct Record {
    /// В единицах счётчика процессора — переводить в миллисекунды дёшево только
    /// при печати, а не на каждом освобождении лока.
    longest: AtomicU64,
    at: AtomicPtr<Location<'static>>,
}

impl Record {
    const fn new() -> Self {
        Self { longest: AtomicU64::new(0), at: AtomicPtr::new(ptr::null_mut()) }
    }

    fn note(&self, since: u64, at: &'static Location<'static>) {
        if since == 0 {
            return;
        }
        let took = arch::monotonic::counter().wrapping_sub(since);
        // `fetch_max`, а не «прочитать — сравнить — записать»: второй
        // процессор с меньшим числом не затрёт рекорд, пришедший между
        // чтением и записью.
        if self.longest.fetch_max(took, Ordering::Relaxed) < took {
            self.at.store(ptr::from_ref(at).cast_mut(), Ordering::Relaxed);
        }
    }

    fn print(&self, what: &str) {
        let hz = arch::monotonic::frequency();
        let longest = self.longest.load(Ordering::Relaxed);
        let at = self.at.load(Ordering::Relaxed);
        if hz == 0 {
            kprintln!("  latency    : {what}: not measured, the processor counter has no known rate");
            return;
        }
        if at.is_null() {
            kprintln!("  latency    : {what}: never since scheduling started");
            return;
        }
        // SAFETY: указатель записан только в `note` и только из
        // `&'static Location<'static>`, то есть ведёт в данные, живущие всё
        // время работы ядра.
        let at = unsafe { &*at };
        let micros = (u128::from(longest) * 1_000_000 / u128::from(hz)) as u64;
        kprintln!(
            "  latency    : {what} at most {}.{:03} ms, from {}:{}",
            micros / 1000,
            micros % 1000,
            at.file(),
            at.line()
        );
    }
}

static IRQ_OFF: Record = Record::new();

/// Отметка начала участка: значение счётчика, либо ноль, если мерить не надо.
///
/// Ноль — «вытеснение ещё не включено». Настоящий счётчик нулём не бывает:
/// к моменту, когда планировщик запущен, он давно ушёл от сброса.
#[must_use]
pub fn start() -> u64 {
    if crate::sched::preemption_on() { arch::monotonic::counter() } else { 0 }
}

/// Кончился участок с закрытыми прерываниями, начатый в `since` в месте `at`.
pub fn irq_off_ended(since: u64, at: &'static Location<'static>) {
    IRQ_OFF.note(since, at);
}

/// Строка для `tasks`.
pub fn report() {
    IRQ_OFF.print("interrupts held off");
}
