//! Договор с сетевой картой — то, что от неё нужно стеку, и ничего сверх.
//!
//! # Зачем он появился
//!
//! Пока карта была одна (virtio-net), стек звал её методы напрямую, и это было
//! честно: слой, у которого ровно одна реализация, — не слой, а лишний файл.
//! Эту эпоху закончил ноутбук ASUS K53SD. В нём стоит Atheros, virtio там нет и
//! быть не может, а «система должна запускаться на любом компьютере» означает
//! ровно одно: драйверов столько, сколько семейств карт, и стек не должен знать,
//! с каким из них он сейчас разговаривает.
//!
//! # Почему кадр копируется, а не отдаётся ссылкой
//!
//! Потому что у разных карт он лежит по-разному: virtio отдаёт буфер из своей
//! приёмной очереди, e1000 — буфер из кольца дескрипторов, а карта с
//! прерываниями отдаст его из обработчика. Ссылка в память устройства обязывала
//! бы стек вернуть её раньше, чем буфер понадобится карте, — и первая же
//! задержка в разборе превращалась бы либо в потерянный кадр, либо в чтение
//! того, что устройство уже перезаписало. Копия кадра стоит полторы тысячи байт
//! на пакет и снимает весь этот класс ошибок целиком.
//!
//! # Чего в договоре намеренно нет
//!
//! **Прерываний.** Их сегодня нет ни у одной карты в системе: приёмная задача
//! опрашивает очередь каждые пять миллисекунд (см. [`super::POLL_INTERVAL_MS`]).
//! Договор, в котором прерывания названы, но не работают, хуже договора, где
//! о них не сказано.
//!
//! **Смены аппаратного адреса, списков многоадресной рассылки и режима
//! «слушать всё».** Ничего этого стек не просит, а метод, который никто не
//! зовёт, у второго же драйвера окажется невызываемой заглушкой.

use core::fmt;

/// Наибольший кадр Ethernet без контрольной суммы: заголовок и 1500 байт данных.
pub const FRAME_MAX: usize = 1514;

/// Счётчики, по которым видно, что происходит на проводе.
///
/// Считает их сама карта, а не стек: кадр, потерянный из-за переполненной
/// очереди, до стека не доходит вовсе, и посчитать его может только тот, кто
/// видел, как он пропал.
#[derive(Debug, Clone, Copy, Default)]
pub struct Stats {
    pub rx_frames: u64,
    pub rx_bytes: u64,
    /// Кадры, которые устройство отдало, а мы не смогли принять: слишком
    /// длинные или пришедшие с непонятной длиной.
    pub rx_dropped: u64,
    pub tx_frames: u64,
    pub tx_bytes: u64,
    /// Кадры, которые не удалось отправить: очередь не освободилась.
    pub tx_dropped: u64,
}

/// Чем карта может отказать в отправке.
///
/// Три причины, и это не упрощение: отказ карты интересует стек только тем,
/// стоит ли повторять. «Слишком длинный» повторять бессмысленно, «занята» —
/// осмысленно, «остановлена» — бессмысленно до вмешательства человека.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CardError {
    /// Кадр длиннее, чем помещается в буфер карты.
    TooLong(usize),
    /// Все дескрипторы в полёте: устройство не успевает забирать.
    Busy,
    /// Карта остановлена или перестала отвечать.
    Stopped,
}

impl fmt::Display for CardError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::TooLong(len) => write!(f, "{len} bytes do not fit in a frame buffer"),
            Self::Busy => f.write_str("every transmit descriptor is still in flight"),
            Self::Stopped => f.write_str("the card is stopped"),
        }
    }
}

/// Сетевая карта — то, что от неё нужно стеку.
///
/// `Send` обязателен: интерфейс живёт под замком, а замок ядра переезжает между
/// процессорами вместе с задачей, которая его взяла.
pub trait Card: Send {
    /// Имя драйвера для журнала и для диспетчера устройств: `virtio-net`,
    /// `e1000`, `atl1c`. Оно же — ответ на вопрос «чем эта карта поднята»,
    /// который человек задаёт первым на чужой машине.
    fn name(&self) -> &'static str;

    /// Аппаратный адрес карты.
    fn mac(&self) -> [u8; 6];

    /// Отправить кадр. Не блокирует: занятая очередь — это отказ, а не ожидание.
    fn send(&mut self, frame: &[u8]) -> Result<(), CardError>;

    /// Забрать пришедший кадр, если он есть. `None` — приёмная очередь пуста.
    fn receive(&mut self, frame: &mut [u8; FRAME_MAX]) -> Option<usize>;

    /// Счётчики карты.
    fn stats(&self) -> Stats;
}
