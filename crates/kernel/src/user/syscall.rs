//! Обработка системных вызовов — единственная дверь из программы в ядро.
//!
//! # Что здесь главное
//!
//! Проверка аргументов. Всё, что приходит сюда, выбрала программа, а она —
//! недоверенная сторона: номер вызова может быть любым, указатель может
//! указывать в ядро, длина может переполнять сложение. Ни одно из этих значений
//! не должно приводить ни к чему, кроме кода ошибки.
//!
//! Особенно указатели. Программа не может прочитать память ядра сама — ей не
//! дадут страницы, — но может **попросить об этом ядро**, передав адрес
//! ядерной структуры в `write`. Поэтому каждый адрес проверяется на
//! принадлежность окну программы ([`super::owns`]), и проверка эта защищает
//! ядро, а не программу.
//!
//! # Почему вызовов четыре
//!
//! Потому что больше нечем воспользоваться. `write` и `exit` делают программу
//! возможной, `yield` — обязательным для кооперативного планировщика, а
//! `uptime` существует ради одного: показать, что данные проходят границу и
//! **внутрь**, а не только наружу. Файловые вызовы появятся вместе с проверкой
//! прав — там они и получат смысл, потому что проверять `mode`/`uid`/`gid`
//! можно только у того, кто их спрашивает.

use core::fmt::Write as _;

use user_abi::{
    ERR_BAD_ADDRESS, ERR_NO_SYSCALL, FD_STDOUT, SYS_EXIT, SYS_UPTIME, SYS_WRITE, SYS_YIELD,
};

use crate::{irq, sched};

/// Разобрать системный вызов. Возвращает то, что уедет в регистр результата.
///
/// # Safety
///
/// Вызывать только из обработчика ловушки, пришедшей из пользовательского
/// режима: [`SYS_EXIT`] не возвращается, а уходит в точку запуска программы.
pub unsafe fn handle(number: usize, a0: usize, a1: usize, a2: usize) -> i64 {
    match number {
        SYS_WRITE => write(a0, a1, a2),
        SYS_EXIT => {
            // SAFETY: контракт функции.
            unsafe { crate::arch::return_to_kernel(a0 as i64) }
        }
        SYS_YIELD => {
            // Планировщик кооперативный: без этого вызова программа, считающая
            // в цикле, не отдала бы процессор никому.
            sched::yield_now();
            0
        }
        SYS_UPTIME => irq::uptime_ms() as i64,
        _ => ERR_NO_SYSCALL,
    }
}

/// `write(fd, ptr, len)`.
fn write(fd: usize, ptr: usize, len: usize) -> i64 {
    if fd != FD_STDOUT {
        return ERR_NO_SYSCALL;
    }
    if len == 0 {
        return 0;
    }
    if !super::owns(ptr, len) {
        return ERR_BAD_ADDRESS;
    }

    // SAFETY: диапазон проверен на принадлежность окну программы, а окно
    // отображено на всё время её работы. Ядро и программа исполняются на одном
    // процессоре по очереди, поэтому изменить эти байты во время чтения
    // некому.
    let bytes = unsafe { core::slice::from_raw_parts(ptr as *const u8, len) };

    // Двоичный мусор в окно оболочки не выводится: управляющие байты испортили
    // бы и сетку символов, и терминал на другом конце линии. Это ограничение
    // вывода, а не проверка программы, — поэтому не ошибка.
    match core::str::from_utf8(bytes) {
        Ok(text) => {
            let _ = write!(&mut crate::shell::Out, "{text}");
            len as i64
        }
        Err(_) => ERR_BAD_ADDRESS,
    }
}
