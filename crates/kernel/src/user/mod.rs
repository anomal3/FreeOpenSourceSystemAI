/// От чьего имени исполняется то, что просит ядро прямо сейчас.
///
/// Личность **программы**, а не сеанса, и это разные вещи с Phase 33: службу
/// запускает супервизор от root, а исполняется она от своего пользователя. Все
/// проверки прав в системных вызовах спрашивают отсюда.
///
/// Сеанс остаётся ответом по умолчанию — для задач ядра, у которых программы
/// нет вовсе: оболочка, чтение `/etc/passwd` при загрузке, файловый менеджер до
/// того, как стал программой. Личность сеанса тоже спрашивается, а не
/// подставляется root: у кода в кольце ноль права всё равно ничего не отнимут,
/// но `echo > /root/x` от имени обычного пользователя обязан получить тот же
/// отказ, что и программа.
#[must_use]
pub fn credentials() -> Credentials {
    with_current(|program| program.cred).unwrap_or_else(session::credentials)
}

/// Права пакета, которому принадлежит файл по этому пути.
///
/// # Зачем это вдобавок к правам запуска
///
/// Права едут с запуском, потому что пакет запускается строкой `start=`, и у
/// программы на .NET эта строка ведёт в `/bin/dotnet` — файл системный, к
/// пакету отношения не имеющий. Но у обратного случая своя дыра: файл
/// `/opt/hello/bin/greet` принадлежит пакету, а запущенный из оболочки получал
/// бы всё, и «программа ограничена» значило бы «ограничена, пока её запускают
/// из меню».
///
/// Поэтому правил два, и они **сужают** оба: набор запуска пересекается с
/// набором того пакета, в чьём каталоге лежит исполняемый файл. Программа
/// пакета ограничена, кто бы её ни запустил; программа из `/bin`, запущенная
/// от имени пакета, ограничена правами пакета.
///
/// Всё, что лежит не в `/opt/<имя>/`, прав не ограничивает: [`Rights::ALL`].
fn rights_of_path(path: &str) -> Rights {
    /// Реестр установленного: в нём лежит манифест как есть.
    const REGISTRY: &str = "/var/lib/pkg";
    /// Предел манифеста в контейнере — он же предел записи реестра.
    const LIMIT: usize = 32 * 1024;

    let Some(rest) = path.strip_prefix("/opt/") else {
        return Rights::ALL;
    };
    // Имя пакета — первый кусок пути. Файл прямо в `/opt` пакету не
    // принадлежит: пакеты раскладываются по каталогам.
    let Some((name, _)) = rest.split_once('/') else {
        return Rights::ALL;
    };
    if name.is_empty() || !fpk::is_safe_component(name) {
        return Rights::ALL;
    }

    let record = alloc::format!("{REGISTRY}/{name}.pkg");
    // Записи нет или она не читается — значит каталог в `/opt` создан не
    // пакетом. Ограничивать нечем: реестр и есть то место, где права названы.
    let Some(Ok((bytes, _))) = crate::fs::read(&record, LIMIT) else {
        return Rights::ALL;
    };
    let Ok(text) = core::str::from_utf8(&bytes) else {
        return Rights::ALL;
    };
    // Непонятое имя права даёт пустой набор, а не «всё»: «не понял, значит
    // можно» — ровно та ошибка, ради которой всё это затевалось.
    sysconf::value(text, "permissions")
        .map_or(Rights::NONE, |list| Rights::parse(list).unwrap_or(Rights::NONE))
}

/// Что разрешено программе, исполняющейся сейчас.
///
/// Программы может не быть вовсе — вызов пришёл из оболочки или из задачи
/// ядра; тогда разрешено всё, и это не поблажка: оболочка и есть система.
#[must_use]
pub fn rights() -> Rights {
    with_current(|program| program.rights).unwrap_or(Rights::ALL)
}

/// Отказать, если у исполняющейся программы нет права `need`.
///
/// Возвращает `false` и печатает строку — печатает **всегда**, и это не
/// многословие. Отказ по правам выглядит для программы так же, как любой
/// другой отказ вызова, и человек, у которого «программа не работает», иначе
/// не узнает, что её остановила система, а не сеть. Строку читает и стенд:
/// «вызов вернул ошибку» и «вызов был запрещён» — разные утверждения.
#[must_use]
pub fn allow(need: Rights) -> bool {
    let mine = rights();
    if mine.contains(need) {
        return true;
    }
    let mut asked = [0u8; 32];
    let asked = need.write_names(&mut asked);
    let mut has = [0u8; 32];
    let has = mine.write_names(&mut has);
    kprintln!(
        "  user        : {} refused {asked}: the package asked for {has}",
        sched::current()
    );
    false
}

/// Виртуальный адрес кадра в прямом отображении — через него ядро пишет в
/// память программы.
///
/// Пишет именно так, а не по адресам самой программы: её окно в таблицах ядра
/// не отображено, и обращение к [`WINDOW_BASE`] из ядра — это отказ страницы, а
/// не запись в образ.
fn frame_bytes(frame: PhysAddr) -> *mut u8 {
    frame.to_direct_map().as_mut_ptr::<u8>()
}

/// Разложить аргументы в верхней странице стека программы.
///
/// Возвращает `(argc, адрес массива argv, новую вершину стека)` — всё в
/// адресах программы.
///
/// # Раскладка
///
/// Сверху вниз: сначала сами строки (каждая с завершающим нулём), под ними
/// массив указателей на них, и всё это — выше новой вершины стека. Программа
/// получает `argc` и адрес массива регистрами, а не находит их на стеке: у двух
/// архитектур это были бы два разных соглашения, а регистры одинаковы —
/// System V и AAPCS64 передают первые два аргумента одинаково по смыслу.
///
/// Строки заканчиваются нулём, потому что иначе их длину пришлось бы передавать
/// отдельным массивом: программе нужен `&str`, а `&str` — это адрес и длина.
/// Ноль в конце — тот же способ, которым это решает C, и здесь он выбран не из
/// уважения к традиции, а потому что второй массив пришлось бы держать в том же
/// стеке и объяснять его формат в договоре.
///
/// **Сам массив тоже заканчивается нулём** — `argv[argc]` равен нулевому
/// указателю. Это требование языка C (C11, 5.1.2.2.1), а не украшение: чужая
/// программа вправе идти по `argv`, пока не встретит ноль, и многие идут именно
/// так — `argc` они при этом не смотрят вовсе. До Lua этого никто не замечал:
/// наши программы читают `argc`, и массив без завершителя их устраивал. Lua
/// пошла по указателям и прочитала то, что лежало за массивом, — падение
/// выглядело как `#GP` в разборе своих же аргументов.
///
/// # Что если не помещается
///
/// Лишние аргументы отбрасываются, а не роняют запуск. Ограничение — одна
/// страница на всё; аргумент, который в неё не влез, — это командная строка в
/// четыре килобайта, и она встречается там, где кто-то её подставил, а не там,
/// где человек её набрал.
fn place_args(frame: PhysAddr, args: &[&str]) -> (usize, usize, usize) {
    /// Сколько места отдано аргументам: вся верхняя страница стека.
    const AREA: usize = PAGE_SIZE;
    /// Выравнивание вершины стека, которого требуют оба соглашения о вызовах.
    const ALIGN: usize = 16;

    // Смещение внутри страницы; растёт сверху вниз, как и сам стек.
    let mut top = AREA;
    // Кадр принадлежит стеку этой программы и доступен через прямое отображение
    // ядра; писать в него до входа в третье кольцо некому больше.
    let page = frame_bytes(frame);

    let mut pointers = Vec::new();
    if pointers.try_reserve_exact(args.len()).is_err() {
        return (0, 0, STACK_TOP - ALIGN);
    }

    for arg in args {
        let needed = arg.len() + 1;
        // Место под массив указателей резервируется здесь же: без этой проверки
        // строки могли бы занять страницу целиком, и массиву не осталось бы
        // ничего.
        let reserved = (pointers.len() + 1) * size_of::<usize>() + ALIGN;
        if top < needed + reserved {
            break;
        }
        top -= needed;
        // SAFETY: `top` и длина проверены выше — запись целиком внутри страницы.
        unsafe {
            core::ptr::copy_nonoverlapping(arg.as_ptr(), page.add(top), arg.len());
            page.add(top + arg.len()).write(0);
        }
        pointers.push(STACK_TOP - AREA + top);
    }

    // Массив указателей — под строками, выровненный по размеру указателя.
    // Слотов на один больше, чем аргументов: последний — завершающий ноль.
    // Место под него зарезервировано в цикле выше (`pointers.len() + 1`).
    top &= !(size_of::<usize>() - 1);
    let array_bytes = (pointers.len() + 1) * size_of::<usize>();
    top -= array_bytes;
    for (index, pointer) in pointers.iter().enumerate() {
        // SAFETY: место под массив зарезервировано в цикле выше.
        unsafe {
            page.add(top + index * size_of::<usize>())
                .cast::<usize>()
                .write_unaligned(*pointer);
        }
    }
    // SAFETY: слот под завершитель посчитан в `array_bytes` и лежит внутри
    // страницы — как и все предыдущие.
    unsafe {
        page.add(top + pointers.len() * size_of::<usize>())
            .cast::<usize>()
            .write_unaligned(0);
    }

    let argv = STACK_TOP - AREA + top;
    let stack = (argv - ALIGN) & !(ALIGN - 1);
    (pointers.len(), argv, stack)
}

/// Выделить кадр под страницу программы.
fn take_frame() -> Result<PhysAddr, Error> {
    crate::mm::frame::with(|frames| frames.allocate())
        .flatten()
        .ok_or(Error::OutOfMemory)
}

/// Вернуть в пул кадр, который не попал в таблицы программы.
///
/// Нужно ровно на одном пути: отображение отказало уже после выделения кадра.
/// Такой кадр не принадлежит ни одному дереву, и разбор адресного пространства
/// его не найдёт — вернуть его может только тот, кто его взял.
fn return_frame(frame: PhysAddr) {
    crate::mm::frame::with(|pool| {
        // SAFETY: кадр выдан этим же аллокатором, отображения на него не
        // создано (иначе он сюда не попал бы), и больше его никто не держит.
        unsafe { pool.free(frame) };
    });
}

/// Прочитать заголовки программы: заголовок файла и таблицу сегментов.
///
/// Читает **ядро**, а не программа, и права на чтение файла для этого не
/// требуются — так же, как в Unix, где `execve` довольствуется битом `x`.
/// Разница осмысленная: содержимое исполняемого файла не отдаётся тому, кто его
/// запустил, оно отдаётся процессору — и с фазы 54 отдаётся по страницам, по
/// мере того как процессор до них доходит. Здесь читаются только заголовки
/// ([`HEADER_BYTES`]); если таблица сегментов в них не поместилась, чтение
/// повторяется до её конца.
///
/// Возвращает прочитанное и полную длину файла: по ней разбор проверяет, что
/// каждый сегмент внутри файла, не читая его.
fn read_header(node: &dyn crate::vfs::Node) -> Result<(Vec<u8>, usize), Error> {
    let meta = node.metadata();
    if meta.kind != crate::vfs::NodeKind::File {
        return Err(Error::Read(crate::vfs::VfsError::WrongKind));
    }
    let size = meta.size as usize;
    let mut want = size.min(HEADER_BYTES);
    loop {
        let mut bytes = Vec::new();
        // `try_reserve_exact`, а не `vec![]`: размер пришёл с носителя, и отказ
        // аллокатора обязан стать ошибкой, а не паникой.
        bytes.try_reserve_exact(want).map_err(|_| Error::OutOfMemory)?;
        bytes.resize(want, 0);
        let read = node.read_at(0, &mut bytes).map_err(Error::Read)?;
        bytes.truncate(read);
        match elf::Image::parse(&bytes, size) {
            // Таблица сегментов за прочитанным — дочитать, пока есть что.
            Err(elf::ElfError::Truncated) if want < size => want = (want * 4).min(size),
            _ => return Ok((bytes, size)),
        }
    }
}

/// Прочитать все страницы сегмента при запуске (см. [`IMAGE_PAGED_ON_DEMAND`]).
///
/// То же, что делает отказ страницы, только заранее и без замков: программы
/// ещё нет в таблице, и спорить за неё некому. Прочитанные страницы в
/// `resident` не попадают — вытеснять их нельзя, иначе обращение к ним снова
/// пошло бы через отказ, который здесь и обходится.
fn prefetch(space: &mut Space, region: &mut Mapping) -> Result<(), Error> {
    let Source::Image(image) = &mut region.source else {
        return Ok(());
    };
    for page in 0..region.pages {
        let start = page * PAGE_SIZE;
        let want = image.file_bytes.saturating_sub(start).min(PAGE_SIZE);
        let frame = take_frame()?;
        // SAFETY: кадр только что выдан под эту программу, обнулён по договору
        // аллокатора и виден через прямое отображение.
        let buffer = unsafe { core::slice::from_raw_parts_mut(frame_bytes(frame), PAGE_SIZE) };
        if want > 0 {
            if let Err(err) = image.node.read_at(image.offset + start as u64, &mut buffer[..want]) {
                return_frame(frame);
                return Err(Error::Read(err));
            }
        }
        // SAFETY: кадр наш, адрес внутри области этой программы.
        if let Err(err) = unsafe { space.map(VirtAddr::new(region.base + start), frame, image.flags) } {
            return_frame(frame);
            return Err(Error::Map(err));
        }
        image.reads += 1;
    }
    Ok(())
}

/// Что получилось из разложенного образа: точка входа, верхняя страница стека
/// и области, из которых сегменты будут читаться по обращению.
///
/// Кадр стека нужен снаружи, чтобы записать туда аргументы. Писать их через
/// адреса программы было бы нельзя: к моменту, когда пространство активно, и
/// возможно только через прямое отображение.
struct Loaded {
    entry: usize,
    stack_top_frame: PhysAddr,
    mappings: Vec<Mapping>,
}

/// Разложить программу по её адресному пространству и вернуть точку входа.
///
/// «Разложить» с фазы 54 значит записать сегменты в таблицу областей: ни одна
/// страница образа здесь не читается и не отображается — первое обращение к
/// ней придёт отказом страницы, и [`Program::fault_in`] прочитает её из файла.
/// Стек — исключение: его верхняя страница нужна сразу, под аргументы, а
/// остальные дешевле выдать здесь, чем ловить шестнадцать отказов на первом
/// же вызове.
fn load(
    space: &mut Space,
    node: &Arc<dyn Node>,
    header: &[u8],
    file_len: usize,
) -> Result<Loaded, Error> {
    let image = elf::Image::parse(header, file_len).map_err(Error::Elf)?;

    // Сегменты по возрастанию адреса. Права уже в понятиях страниц.
    struct Seg {
        vaddr: usize,
        memsz: usize,
        file_offset: usize,
        filesz: usize,
        flags: PageFlags,
    }
    let mut segs: Vec<Seg> = Vec::new();
    for segment in image.segments((WINDOW_BASE, WINDOW_BASE + IMAGE_LIMIT_BYTES)) {
        let segment = segment.map_err(Error::Elf)?;
        let flags = PageFlags::from_segment_flags(segment.flags).union(PageFlags::USER);
        // Проверка до первой записи в таблицу, а не в отказе страницы:
        // отказать на середине запуска значит оставить программу без половины
        // сегментов, о которых уже никто не спрашивал.
        if flags.contains(PageFlags::WRITE) && flags.contains(PageFlags::EXEC) {
            return Err(Error::WriteExecute((segment.vaddr - WINDOW_BASE) / PAGE_SIZE));
        }
        if segs.len() >= MAX_MAPPINGS / 2 {
            return Err(Error::TooManySegments);
        }
        segs.try_reserve(1).map_err(|_| Error::OutOfMemory)?;
        segs.push(Seg {
            vaddr: segment.vaddr,
            memsz: segment.memsz,
            file_offset: segment.file_offset,
            filesz: segment.filesz,
            flags,
        });
    }
    if segs.is_empty() {
        return Err(Error::Elf(elf::ElfError::NoSegments));
    }
    segs.sort_by_key(|seg| seg.vaddr);

    // Страница, которую делят два сегмента (`.rodata` кончается и `.data`
    // начинается внутри одной страницы — компоновщик вправе так уложить
    // программу, собранную не нашим сценарием), читается **сразу**, из обоих
    // сегментов, и отображается с объединёнными правами — как делал прежний
    // загрузчик для всех страниц. По обращению читаются только страницы,
    // принадлежащие одному сегменту: у страницы из файла одно смещение, а у
    // общей страницы их два.
    let page_of = |addr: usize| addr / PAGE_SIZE;
    let first_page = |seg: &Seg| page_of(seg.vaddr);
    let last_page = |seg: &Seg| page_of(seg.vaddr + seg.memsz - 1);
    let covers = |seg: &Seg, page: usize| first_page(seg) <= page && page <= last_page(seg);
    let mut shared: Vec<usize> = Vec::new();
    for (index, left) in segs.iter().enumerate() {
        for right in &segs[index + 1..] {
            let from = first_page(left).max(first_page(right));
            let to = last_page(left).min(last_page(right));
            for page in from..=to {
                if shared.len() >= MAX_SHARED_PAGES {
                    // Сегменты лежат друг на друге не страницей, а массивом —
                    // это не раскладка, а противоречивый заголовок.
                    return Err(Error::Elf(elf::ElfError::BadSegment));
                }
                if !shared.contains(&page) {
                    shared.try_reserve(1).map_err(|_| Error::OutOfMemory)?;
                    shared.push(page);
                }
            }
        }
    }
    for &page in &shared {
        let mut flags = PageFlags::USER;
        for seg in segs.iter().filter(|seg| covers(seg, page)) {
            flags = flags.union(seg.flags);
        }
        if flags.contains(PageFlags::WRITE) && flags.contains(PageFlags::EXEC) {
            return Err(Error::WriteExecute(page - WINDOW_BASE / PAGE_SIZE));
        }
        let frame = take_frame()?;
        // SAFETY: кадр только что выдан под эту программу, обнулён по договору
        // аллокатора и виден через прямое отображение.
        let buffer = unsafe { core::slice::from_raw_parts_mut(frame_bytes(frame), PAGE_SIZE) };
        let page_start = page * PAGE_SIZE;
        for seg in segs.iter().filter(|seg| covers(seg, page)) {
            let from = seg.vaddr.max(page_start);
            let to = (seg.vaddr + seg.filesz).min(page_start + PAGE_SIZE);
            if from >= to {
                continue;
            }
            let offset = (seg.file_offset + (from - seg.vaddr)) as u64;
            let read = node.read_at(offset, &mut buffer[from - page_start..to - page_start]).map_err(Error::Read);
            if let Err(err) = read {
                return_frame(frame);
                return Err(err);
            }
        }
        // SAFETY: кадр наш, адрес внутри окна образа этой программы.
        if let Err(err) = unsafe { space.map(VirtAddr::new(page_start), frame, flags) } {
            return_frame(frame);
            return Err(Error::Map(err));
        }
    }

    // Остальные страницы — областями: каждый непрерывный пробег страниц
    // сегмента, не задетых другим сегментом, становится своей областью.
    let mut mappings: Vec<Mapping> = Vec::new();
    for seg in &segs {
        let mut run: Option<(usize, usize)> = None;
        for page in first_page(seg)..=last_page(seg) + 1 {
            let inside = page <= last_page(seg) && !shared.contains(&page);
            match (run, inside) {
                (None, true) => run = Some((page, page)),
                (Some((from, _)), true) => run = Some((from, page)),
                (Some((from, to)), false) => {
                    run = None;
                    let base = from * PAGE_SIZE;
                    // Байт `base + n` лежит в файле по смещению `offset + n`:
                    // смещение и адрес у сегмента сравнимы по модулю страницы,
                    // этого требует ELF. Область, начавшаяся позже сегмента
                    // (общая страница впереди), теряет столько же файловой части.
                    let skipped = base.saturating_sub(seg.vaddr);
                    let lead = seg.vaddr.saturating_sub(base);
                    let Some(offset) = (seg.file_offset + skipped).checked_sub(lead) else {
                        return Err(Error::Elf(elf::ElfError::BadSegment));
                    };
                    let file_bytes = (lead + seg.filesz).saturating_sub(skipped);
                    if mappings.len() >= MAX_MAPPINGS / 2 {
                        return Err(Error::TooManySegments);
                    }
                    mappings.try_reserve(1).map_err(|_| Error::OutOfMemory)?;
                    mappings.push(Mapping {
                        base,
                        pages: to - from + 1,
                        blocks: 0,
                        source: Source::Image(ImageBacking {
                            node: Arc::clone(node),
                            offset: offset as u64,
                            file_bytes,
                            flags: seg.flags,
                            resident: VecDeque::new(),
                            reads: 0,
                            evictions: 0,
                        }),
                    });
                }
                (None, false) => {}
            }
        }
    }
    // Таблица областей упорядочена по адресу — этого ждут `find_gap` и
    // `remember`, а порядок сегментов в файле никто не обещал.
    mappings.sort_by_key(|region| region.base);
    if !IMAGE_PAGED_ON_DEMAND {
        for region in &mut mappings {
            prefetch(space, region)?;
        }
    }

    let mut stack_top_frame = PhysAddr::new(0);
    for page in 0..STACK_PAGES {
        let frame = take_frame()?;
        // Верхняя страница — та, в которую упирается `STACK_TOP`, и именно в
        // неё лягут аргументы.
        if page == STACK_PAGES - 1 {
            stack_top_frame = frame;
        }
        // SAFETY: кадр только что выделен под эту программу и больше никому не
        // принадлежит; при разборе пространства он вернётся в пул. Стек —
        // обычная память программы на чтение и запись.
        let mapped = unsafe {
            space.map(
                VirtAddr::new(STACK_BASE + page * PAGE_SIZE),
                frame,
                PageFlags::READ.union(PageFlags::WRITE).union(PageFlags::USER),
            )
        };
        if let Err(err) = mapped {
            // Отображения не появилось — значит поддерево окна этот кадр не
            // содержит, и вернуть его надо здесь.
            return_frame(frame);
            return Err(Error::Map(err));
        }
    }

    // Страница процесса: эталон канарейки стека. Заполняется **до** входа в
    // программу и отображается без права записи — программа читает его по
    // символу `__stack_chk_guard` в прологе каждой функции с массивом на стеке,
    // и подделать его переполнением ей нечем. Остаток страницы — нули: кадры
    // выдаются чистыми, и это тот же договор, на который полагается `.bss`.
    let frame = take_frame()?;
    {
        // SAFETY: кадр только что выделен под эту программу и доступен через
        // прямое отображение ядра; в третьем кольце его ещё никто не видел.
        let random = unsafe {
            core::slice::from_raw_parts_mut(frame_bytes(frame), user_abi::PROCESS_PAGE_RANDOM_BYTES)
        };
        // Источник не называется вслух: канарейка — не ключ, ей достаточно
        // быть непредсказуемой для программы, а не для наблюдателя снаружи.
        let _ = crate::random::fill(random);
        // Канарейка-терминатор: младший байт — ноль, чтобы строковые функции,
        // переполняющие буфер, останавливались на нём, не дописав остаток.
        random[0] = 0;
    }
    // SAFETY: кадр принадлежит этой программе и вернётся в пул при разборе
    // пространства вместе со стеком; отображение — только на чтение.
    let mapped = unsafe {
        space.map(
            VirtAddr::new(PROCESS_PAGE),
            frame,
            PageFlags::READ.union(PageFlags::USER),
        )
    };
    if let Err(err) = mapped {
        return_frame(frame);
        return Err(Error::Map(err));
    }

    Ok(Loaded { entry: image.entry, stack_top_frame, mappings })
}

/// Напечатать то, ради чего фаза затевалась: где лежит программа и чего о ней
/// не знает ядро.
///
/// Строки читает не только человек — их читает стенд (`cargo xtask test`).
/// Утверждение «окно программы в таблицах ядра отсутствует» иначе нечем
/// проверить: снимок экрана его не покажет, а отсутствие отказа доказывает
/// только то, что ядро туда не обращалось.
fn report(space: &Space, entry: usize, mappings: &[Mapping]) {
    // Точка входа ещё не отображена — и не должна быть: с фазы 54 её страница
    // придёт по первому же обращению процессора. Утверждать здесь можно другое:
    // что она лежит внутри исполняемого сегмента, записанного в таблицу областей.
    let segment = mappings.iter().find(|region| {
        entry >= region.base && entry < region.base + region.pages * PAGE_SIZE
    });
    match segment {
        Some(Mapping { base, source: Source::Image(image), .. }) if image.flags.contains(PageFlags::EXEC) => {
            kprintln!(
                "  user        : space {:?}, entry is paged on demand from the segment at {base:#018x} {:?}",
                space.root(),
                image.flags
            );
        }
        _ => kprintln!("  user        : WARNING: the entry point is not inside an executable segment"),
    }

    match space::kernel_maps(VirtAddr::new(entry)) {
        None => kprintln!("  user        : the kernel space maps nothing at {entry:#018x}"),
        Some((frame, flags)) => kprintln!(
            "  user        : WARNING: the kernel space maps {entry:#018x} to {frame:?} {flags:?}"
        ),
    }
}

/// Загрузить программу по пути и исполнить её в текущей задаче.
///
/// Возвращает код, с которым программа завершилась.
fn run(
    path: &str,
    args: &[&str],
    cred: Credentials,
    rights: Rights,
    stdin: Option<pipe::Reader>,
    stdout: Option<pipe::Writer>,
) -> Result<i64, Error> {
    // Право исполнить спрашивается до чтения файла, и спрашивается от имени
    // **той личности, с которой программа будет исполняться**. Это тот же
    // вопрос, который в Unix задаёт `execve`, и задавать его обязано ядро:
    // программа, которой не дали бы прочитать файл, не должна получать его в
    // виде исполняемого кода. Отсюда же и [`Access::SEARCH`] на самом файле —
    // бит `x`, а не `r`.
    //
    // Порядок здесь имеет значение: спросить от имени запускающего, а
    // исполнить от имени другого — это ровно та дыра, ради закрытия которой
    // права запуска и стали свойством программы.
    let node = match crate::fs::resolve_as(cred, path, Access::SEARCH) {
        Some(Ok(node)) => node,
        Some(Err(err)) => return Err(Error::Read(err)),
        None => return Err(Error::NoFilesystem),
    };
    // Узел переезжает в `Arc`: с фазы 54 его держат области сегментов, и файл
    // программы обязан жить, пока живёт она сама.
    let node: Arc<dyn Node> = Arc::from(node);
    let (header, file_len) = read_header(&*node)?;

    let mut space = Space::new().map_err(Error::Map)?;
    let loaded = load(&mut space, &node, &header, file_len)?;
    let entry = loaded.entry;
    let root = space.root();

    // Аргументы кладутся в стек программы до входа в третье кольцо. Вершина
    // стека при этом опускается под них и выравнивается на 16: этого требуют
    // оба соглашения о вызовах, и невыровненный стек ломается не сразу, а на
    // первой же операции с вектором.
    let (argc, argv, stack) = place_args(loaded.stack_top_frame, args);

    let id = sched::current();
    kprintln!(
        "  user        : {id} '{path}' as {cred}, entry {entry:#018x}, stack {stack:#018x}, \
         stack guard read-only at {PROCESS_PAGE:#018x}"
    );
    // Права печатаются отдельной строкой и **всегда**, даже когда их все:
    // «чего этой программе разрешено» иначе не видно снаружи ничем, а
    // проверять модель прав надо именно снаружи. Строку читает стенд.
    {
        let mut names = [0u8; 32];
        kprintln!("  user        : {id} may use {}", rights.write_names(&mut names));
    }
    report(&space, entry, &loaded.mappings);

    let slot = sched::current_slot();
    {
        let mut table = PROGRAMS.lock();
        let Some(entry) = table.get_mut(slot) else {
            return Err(Error::AlreadyRunning);
        };
        if entry.is_some() {
            // Задача уже исполняет программу. Вложенного входа в третье кольцо
            // не бывает: стек возврата у задачи один, и второй вход затёр бы
            // его.
            return Err(Error::AlreadyRunning);
        }
        *entry = Some(Arc::new(Mutex::new(Program {
            space,
            files: files::Table::new(),
            kill_requested: false,
            cred,
            rights,
            path: alloc::string::String::from(path),
            stdin,
            stdout,
            mappings: loaded.mappings,
        })));
    }
    // Признак поднимается после того, как процесс попал в таблицу: обработчик
    // отказа читает его без лока и вправе увидеть `true` только тогда, когда
    // программу уже есть где найти.
    IN_USER[slot].store(true, Ordering::Release);

    // Планировщик узнаёт о пространстве до того, как процессор на него
    // переключится, — и с Phase 13b этот порядок стал обязательным, а не
    // предусмотрительным: между двумя строками задачу могут вытеснить. Знание,
    // записанное первым, переживает вытеснение (вернувшись, планировщик сам
    // поставит нужный корень); действие, сделанное первым, — нет.
    sched::set_current_space(Some(root));
    // SAFETY: корень построен копией ядерного и содержит все его отображения;
    // возврат на таблицы ядра — сразу после выхода из программы, до того как
    // пространство будет разобрано.
    unsafe { arch::activate_space(root) };

    // SAFETY: точка входа и стек лежат в окне, только что отображённом
    // доступным из пользовательского режима; стек ловушки выставит сам вход в
    // третье кольцо.
    let code = unsafe { arch::enter_user(entry, stack, argc, argv) };

    // Сюда возвращаются оба пути: и `exit`, и снятие программы после отказа.
    //
    // Порядок здесь обратный запуску и по той же причине: сначала знание, потом
    // действие. Скажи мы процессору раньше, чем планировщику, — вытеснение между
    // двумя строками вернуло бы задачу с корнем **программы** в регистре, и
    // разбор пространства несколькими строками ниже отдал бы в пул кадры,
    // по которым процессор в этот момент ходит.
    sched::set_current_space(None);
    // SAFETY: таблицы ядра активированы при запуске системы и никуда не делись
    // — пространство программы построено их копией.
    unsafe { arch::activate_kernel_space() };

    // Окно снимается **здесь** — до того, как пространство будет разобрано, и
    // это единственное место, где такой порядок ещё возможен (см.
    // [`reclaim_window`]). Программа, закрывшая окно сама, ничего здесь не
    // стоит: снимать уже нечего.
    reclaim_window();

    // Программа забирается из таблицы и уничтожается здесь: `Drop` её
    // пространства возвращает окно в пул кадров, а таблица дескрипторов
    // закрывает всё, что программа не закрыла сама. Снятая отказом закрыть их и
    // не могла.
    IN_USER[slot].store(false, Ordering::Release);
    let process = {
        let mut table = PROGRAMS.lock();
        table.get_mut(slot).and_then(Option::take)
    };
    // Владение теперь считается ссылками, и последняя ушедшая уничтожает
    // процесс. Пока поток у процесса один, последняя — эта; когда потоков
    // станет несколько (фаза 55b), здесь останется ждать остальных. Сторож
    // говорит вслух, если ссылка не единственная: молчаливое `Drop`, не
    // случившееся вовремя, выглядит потом как утечка кадров.
    if let Some(process) = process.as_ref() {
        let others = Arc::strong_count(process) - 1;
        if others > 0 {
            kprintln!("  user        : the process still has {others} live reference(s) at exit");
        }
    }
    let leaked = process.as_ref().map_or(0, |process| process.lock().files.open_count());
    if leaked > 0 {
        kprintln!("  user        : closed {leaked} file(s) the program left open");
    }
    // Сколько страниц образа программа прочитала и сколько из них пришлось
    // выбросить (фаза 54). Числа стоят сразу за неизменной подстрокой — их
    // читает стенд: обход образа обязан стоить по одному чтению на страницу.
    if let Some(process) = &process {
        let program = process.lock();
        let (reads, evictions) = program.mappings.iter().fold((0u64, 0u64), |sum, region| match &region.source {
            Source::Image(image) => (sum.0 + image.reads, sum.1 + image.evictions),
            _ => sum,
        });
        kprintln!("  user        : program image released, {reads} reads and {evictions} evictions");
    }
    // Процесс уничтожается здесь — точнее, здесь уходит последняя ссылка на
    // него, и `Drop` пространства возвращает в пул всё, что под ним лежит: и
    // стек, и прочитанные страницы образа. Разница с прежним «уничтожается
    // здесь» не словесная: порядок теперь обеспечивает счётчик ссылок, а не
    // текст этой функции.
    drop(process);

    // Сокеты закрываются здесь же и по той же причине: программа, снятая по
    // `kill` или отказавшая, ничего не закрывает сама, а незакрытый сокет
    // держит за собой порт — и следующая попытка запустить ту же службу
    // упёрлась бы в «порт занят» тем, кого уже нет.
    let sockets = crate::net::close_owner(sched::current());
    if sockets > 0 {
        kprintln!("  user        : closed {sockets} socket(s) the program left open");
    }

    Ok(code)
}

/// Сколько стека ядра отводится задаче, исполняющей программу.
///
/// Вдвое больше обычной задачи, и не про запас. На этом стеке лежит всё сразу:
/// разбор ELF, кадр входа в третье кольцо, кадр ловушки от каждого системного
/// вызова и весь путь вывода — от `write` до перерисовки окна оболочки. Раньше
/// последние два жили на отдельном общем стеке ловушек; с появлением второй
/// программы общий стек перестал быть возможен (см. [`sched::UserMachine`]), и
/// глубина переехала сюда.
const PROGRAM_STACK_SIZE: usize = 64 * 1024;

/// Командная строка в том виде, в каком её получает новая задача.
///
/// Массив, а не `String`: аргумент задачи — одно машинное слово, значит строка
/// уезжает через кучу, а выделение под неё обязано уметь отказать вместо паники.
/// `String::into_boxed_str` этого не умеет.
///
/// Хранится целиком, вместе с аргументами, и разбирается уже в новой задаче.
/// Разобрать её здесь и передать `&[&str]` было бы нельзя: срезы указывали бы в
/// память вызывающего, а он к моменту запуска давно вернулся из `spawn`.
#[repr(C)]
struct Request {
    line: [u8; MAX_LINE],
    len: usize,
    /// От чьего имени исполнять. Едет вместе со строкой, а не спрашивается в
    /// новой задаче: спросить там значило бы спросить у **её** программы,
    /// которой ещё нет, и получить личность сеанса вместо заказанной.
    cred: Credentials,
    /// Права новой программы. Едут в заявке по той же причине, что и личность:
    /// спросить их в новой задаче значило бы спросить у её же программы,
    /// которой ещё нет.
    rights: Rights,
    /// Считать ли новую задачу служебной — см. [`spawn_with`].
    daemon: bool,
    /// Концы каналов, которые новая задача получит стандартным вводом и
    /// выводом. Едут в самой заявке: передать их иначе нечем — задача
    /// принимает одно машинное слово, и это слово уже занято заявкой.
    stdin: Option<pipe::Reader>,
    stdout: Option<pipe::Writer>,
}

/// Самая длинная командная строка, которую принимает [`spawn`].
const MAX_LINE: usize = 255;

/// Сколько аргументов программа получает самое большее.
///
/// Восемь — не свойство программы, а предел на разбор: аргументы разбираются в
/// массив на стеке ядра, и брать его длину из того, что набрал человек, значило
/// бы отдать ему глубину этого стека.
const MAX_ARGS: usize = 8;

/// Запустить программу отдельной задачей.
///
/// Возвращает идентификатор задачи — по нему её можно дождаться
/// ([`sched::wait`]) или просто оставить работать. Именно здесь программа
/// перестала быть вызовом внутри оболочки: у неё своя задача, свой стек ядра,
/// своё адресное пространство и свои открытые файлы, и пока она считает,
/// оболочка отвечает.
pub fn spawn(line: &str, cred: Credentials) -> Result<sched::TaskId, Error> {
    spawn_with(line, cred, false)
}

/// То же, но задача объявляется служебной.
///
/// Служебная задача не считается [`sched::alive`] — то есть не удерживает
/// систему от остановки и не заставляет оболочку ждать. Ровно это и есть
/// служба: она работает, пока работает система, и сама по себе поводом ей
/// работать не является.
///
/// Без этого различия первая же служба сломала бы две вещи сразу: оболочка
/// ждёт, пока договорят остальные задачи, прежде чем напечатать приглашение, а
/// `exit` останавливает машину, когда живых задач не осталось. Служба,
/// работающая вечно, отменила бы и то и другое.
pub fn spawn_with(line: &str, cred: Credentials, daemon: bool) -> Result<sched::TaskId, Error> {
    spawn_rights(line, cred, Rights::ALL, daemon)
}

/// То же, но с явным набором прав.
///
/// Этим запускают пакет: набор берётся из его манифеста. Всё остальное идёт
/// через [`spawn_with`] и получает [`Rights::ALL`] — команда оболочки, служба
/// и системная программа ограничению не подлежат.
///
/// Права сужаются правами **запускающего**: программа без сети, позвавшая
/// `/bin/fetch`, не должна получить сеть его руками. Пересечение делается
/// здесь, в задаче того, кто просит, — в новой задаче спросить уже не у кого.
pub fn spawn_rights(
    line: &str,
    cred: Credentials,
    rights: Rights,
    daemon: bool,
) -> Result<sched::TaskId, Error> {
    spawn_streams_rights(line, cred, rights, daemon, None, None)
}

/// То же, но стандартный ввод и вывод новой задачи привязаны к каналам.
///
/// `None` означает «как было»: ввод с терминала, вывод в окно оболочки. Это и
/// есть вся разница между `run /bin/ls` и `ssh … /bin/ls` — сама программа о
/// ней не знает и знать не должна.
pub fn spawn_streams(
    line: &str,
    cred: Credentials,
    daemon: bool,
    stdin: Option<pipe::Reader>,
    stdout: Option<pipe::Writer>,
) -> Result<sched::TaskId, Error> {
    spawn_streams_rights(line, cred, Rights::ALL, daemon, stdin, stdout)
}

/// То же, но с явным набором прав.
pub fn spawn_streams_rights(
    line: &str,
    cred: Credentials,
    rights: Rights,
    daemon: bool,
    stdin: Option<pipe::Reader>,
    stdout: Option<pipe::Writer>,
) -> Result<sched::TaskId, Error> {
    // Сужение правами запускающего. Программы может не быть вовсе (запускает
    // оболочка или служба супервизора) — тогда сужать не от чего.
    let rights = match with_current(|program| program.rights) {
        Some(mine) => rights.intersect(mine),
        None => rights,
    };
    if line.len() > MAX_LINE {
        return Err(Error::Read(crate::vfs::VfsError::BadPath));
    }

    let layout = core::alloc::Layout::new::<Request>();
    // SAFETY: `Request` непустой, поэтому размер положителен. Глобальный
    // аллокатор ядра при нехватке памяти возвращает null, а не паникует.
    let raw = unsafe { alloc::alloc::alloc(layout) }.cast::<Request>();
    if raw.is_null() {
        return Err(Error::OutOfMemory);
    }
    let mut request =
        Request { line: [0; MAX_LINE], len: line.len(), cred, rights, daemon, stdin, stdout };
    request.line[..line.len()].copy_from_slice(line.as_bytes());
    // SAFETY: блок только что выделен под `Request` с нужными размером и
    // выравниванием и никому больше не принадлежит.
    unsafe { core::ptr::write(raw, request) };

    match sched::spawn_raw("program", PROGRAM_STACK_SIZE, program_entry, raw as usize) {
        Ok(id) => {
            if daemon {
                sched::mark_daemon(id);
            }
            Ok(id)
        }
        Err(err) => {
            // Задачи не будет — значит некому и разобрать запрос.
            // SAFETY: блок выделен этим же аллокатором и этим же `Layout`,
            // ссылок на него больше нет.
            unsafe { alloc::alloc::dealloc(raw.cast::<u8>(), layout) };
            Err(match err {
                sched::SpawnError::OutOfMemory => Error::OutOfMemory,
                sched::SpawnError::TooManyTasks => Error::TooManyTasks,
            })
        }
    }
}

/// Ключ ожидания на адресе — физический адрес слова в памяти программы.
///
/// `None`, если адрес программе не принадлежит, лежит не в её собственной
/// памяти или по нему сейчас нет страницы.
///
/// # Почему физический, а не тот, что дала программа
///
/// Потому что ждущий и будящий вправе смотреть на одну страницу по разным
/// адресам: сегодня это два потока одного процесса (у них адрес совпадёт), а
/// завтра — два процесса, отобразившие общий кусок. Виртуальный ключ развёл бы
/// их по разным очередям, и разбудивший не нашёл бы никого.
///
/// # Почему отображённый файл не годится
///
/// Потому что его страницы ядро вправе вытеснить и прочитать заново в другой
/// кадр. Физический адрес тогда переедет, а ждущий останется на прежнем ключе —
/// и не проснётся уже никогда. Проверка смотрит на вид области, а не надеется.
pub fn futex_key(addr: usize) -> Option<usize> {
    if addr % 4 != 0 {
        return None;
    }
    if !space::user_can(addr, 4, PageFlags::READ | PageFlags::WRITE | PageFlags::USER) {
        return None;
    }
    let own_memory = with_current(|program| {
        program.mappings.iter().any(|region| {
            addr >= region.base
                && addr < region.base + region.pages * PAGE_SIZE
                && matches!(region.source, Source::Anonymous | Source::ThreadStack)
        })
    })
    .unwrap_or(false);
    // Стек и данные самой программы в таблицу областей не записаны — они не
    // выдавались по запросу. Для них ответ даёт раскладка: всё, что ниже
    // [`MMAP_BASE`], принадлежит образу и стеку, и вытеснению не подлежит,
    // кроме страниц образа только на чтение — а писать в них программа всё
    // равно не может, и `user_can` выше это уже отверг.
    if !own_memory && addr >= MMAP_BASE {
        return None;
    }
    let root = current_space_root()?;
    arch::translate(root, VirtAddr::new(addr)).map(|(phys, _)| phys.as_u64() as usize + addr % PAGE_SIZE)
}

/// Почему поток завести не удалось.
#[derive(Debug, Clone, Copy)]
pub enum ThreadError {
    /// Задача, которая просит, программы не исполняет.
    NoProgram,
    /// Точка входа или размер стека бессмысленны.
    BadRequest,
    /// Под стек потока не нашлось памяти или места в адресном пространстве.
    NoMemory,
    /// В таблице планировщика нет свободного слота.
    TooManyTasks,
}

impl core::fmt::Display for ThreadError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::NoProgram => f.write_str("this task runs no program"),
            Self::BadRequest => f.write_str("the entry point or the stack size makes no sense"),
            Self::NoMemory => f.write_str("no room for the thread stack"),
            Self::TooManyTasks => f.write_str("the task table is full"),
        }
    }
}

/// Наименьший стек потока: одна страница сверх сторожевой.
const THREAD_STACK_MIN: usize = PAGE_SIZE;

/// Наибольший стек потока.
///
/// Тот же порядок, что у главного стека программы. Предел здесь не про память,
/// а про то, что область выдаётся целиком и сразу.
const THREAD_STACK_MAX: usize = 8 * 1024 * 1024;

/// Что новая задача должна знать о потоке, который ей предстоит исполнять.
///
/// Уезжает к ней одним указателем — больше `spawn_raw` передать не умеет, — и
/// она же его уничтожает. Ссылка на процесс лежит **здесь**, а не берётся
/// новой задачей из таблицы: до того, как она проснётся, в её слоте ещё пусто.
struct ThreadStart {
    process: Arc<Mutex<Program>>,
    entry: usize,
    arg: usize,
    /// Начало области, выданной под стек, — вместе со сторожевой страницей.
    region: usize,
    /// Сколько байт занимает вся область, считая сторожевую страницу.
    region_bytes: usize,
    /// Вершина стека, уже выровненная.
    stack_top: usize,
}

/// Завести поток в адресном пространстве исполняющейся программы.
///
/// Стек выделяет ядро, а не программа, и это часть договора: под стеком обязана
/// быть **сторожевая страница**, а положить её может только тот, кто
/// распоряжается областями. Переполнение стека потока кончается снятием
/// программы, а не тихой порчей соседней области.
pub fn spawn_thread(entry: usize, arg: usize, stack_bytes: usize) -> Result<sched::TaskId, ThreadError> {
    if entry == 0 || stack_bytes < THREAD_STACK_MIN || stack_bytes > THREAD_STACK_MAX {
        return Err(ThreadError::BadRequest);
    }
    let process = current_process().ok_or(ThreadError::NoProgram)?;

    // Стек выдаётся под локом процесса, а задача создаётся уже без него:
    // `spawn_raw` трогает кучу и лок планировщика, и держать на это время ещё и
    // процесс незачем.
    let (region, region_bytes, stack_top) = {
        let mut program = process.lock();
        program.map_thread_stack(stack_bytes).map_err(|_| ThreadError::NoMemory)?
    };

    let start = alloc::boxed::Box::new(ThreadStart {
        process: Arc::clone(&process),
        entry,
        arg,
        region,
        region_bytes,
        stack_top,
    });
    let raw = alloc::boxed::Box::into_raw(start);

    match sched::spawn_raw("thread", PROGRAM_STACK_SIZE, thread_entry, raw as usize) {
        Ok(id) => Ok(id),
        Err(err) => {
            // Задачи не будет — значит некому ни исполнять поток, ни вернуть
            // его стек. Оба действия здесь, и в обратном порядке.
            // SAFETY: указатель получен из `Box::into_raw` строкой выше и
            // больше никому не отдавался.
            drop(unsafe { alloc::boxed::Box::from_raw(raw) });
            let _ = process.lock().munmap(region, region_bytes);
            Err(match err {
                sched::SpawnError::OutOfMemory => ThreadError::NoMemory,
                sched::SpawnError::TooManyTasks => ThreadError::TooManyTasks,
            })
        }
    }
}

/// Точка входа задачи, исполняющей поток.
///
/// Отличается от [`program_entry`] ровно тем, чем поток отличается от
/// программы: образ не читается, пространство не строится, личность и права не
/// выбираются — всё это у процесса уже есть, и задача просто становится ещё
/// одним его исполнителем.
extern "C" fn thread_entry(arg: usize) -> ! {
    // Тот же инвариант, что у прочих батутов: задача начинает с запрещёнными
    // прерываниями, и разрешить их некому, кроме неё самой.
    arch::interrupts::enable();

    // SAFETY: указатель выделен в `spawn_thread` и передан ровно один раз
    // ровно этой задаче.
    let start = unsafe { alloc::boxed::Box::from_raw(arg as *mut ThreadStart) };
    let slot = sched::current_slot();
    let root = start.process.lock().space.root();

    {
        let mut table = PROGRAMS.lock();
        if let Some(entry) = table.get_mut(slot) {
            *entry = Some(Arc::clone(&start.process));
        }
    }
    IN_USER[slot].store(true, Ordering::Release);

    kprintln!(
        "  thread      : {} runs at {:#018x} on a {} KiB stack, guard page below",
        sched::current(),
        start.entry,
        (start.region_bytes - PAGE_SIZE) / 1024
    );

    // Тот же порядок, что в `run`: сначала знание планировщика, потом действие
    // процессора. Вытеснение между двумя строками переживает только первое.
    sched::set_current_space(Some(root));
    // SAFETY: корень принадлежит живому процессу — ссылка на него у нас в
    // руках, и уйти он не может.
    unsafe { arch::activate_space(root) };

    // SAFETY: точка входа и стек проверены `spawn_thread`: стек выдан ядром в
    // этом же пространстве, а вход — адрес, доступный третьему кольцу.
    let code = unsafe { arch::enter_user(start.entry, start.stack_top, start.arg, 0) };

    IN_USER[slot].store(false, Ordering::Release);
    sched::set_current_space(None);
    // SAFETY: таблицы ядра активированы при запуске системы.
    unsafe { arch::activate_kernel_space() };

    // Стек возвращается процессу — **после** ухода с его таблиц, и это не
    // предосторожность, а условие: снимать отображение стека, на котором
    // стоишь, нельзя.
    let _ = start.process.lock().munmap(start.region, start.region_bytes);
    {
        let mut table = PROGRAMS.lock();
        if let Some(entry) = table.get_mut(slot) {
            *entry = None;
        }
    }
    kprintln!("  thread      : {} finished with code {code}", sched::current());
    // Последнее действие — отпустить ссылку на процесс. Уйди она раньше, и
    // процесс мог бы быть уничтожен, пока мы ещё ходим по его пространству.
    drop(start);
    sched::exit_current_with(code)
}

/// Точка входа задачи, исполняющей программу.
extern "C" fn program_entry(arg: usize) -> ! {
    // Задача начинает исполняться с запрещёнными прерываниями: их запретил
    // планировщик перед переключением, и вернуть «как было» здесь некому. Тот
    // же инвариант, что у обычного батута задач.
    arch::interrupts::enable();

    // SAFETY: `arg` — указатель, выделенный в `spawn` и переданный ровно один
    // раз ровно этой задаче.
    let mut request = unsafe { alloc::boxed::Box::from_raw(arg as *mut Request) };
    // Концы каналов вынимаются сразу, до разбора строки: дальше `request`
    // остаётся заимствованным строкой аргументов и тронуть его будет нельзя.
    let (stdin, stdout) = (request.stdin.take(), request.stdout.take());
    let cred = request.cred;
    let rights = request.rights;
    // Задача помечает себя служебной сама, хотя это же сделал и [`spawn_with`].
    // Дублирование не лишнее: пометка снаружи успевает не всегда — между
    // возвратом `spawn_raw` и ней задачу могут вытеснить, — а всё, что эта
    // задача запустит дальше, наследует признак по **её** состоянию. Пометка
    // изнутри стоит одного взятия лока и закрывает эту щель целиком.
    if request.daemon {
        sched::mark_daemon(sched::current());
    }
    let line = core::str::from_utf8(&request.line[..request.len]).unwrap_or("");

    // Разбор здесь, а не в `spawn`: срезы указывают внутрь `request`, который
    // живёт ровно столько, сколько эта задача. Первое слово — путь, остальные —
    // аргументы программы; кавычек и экранирования нет, и обещать их, сделав
    // разбиение по пробелам, было бы хуже, чем не обещать.
    let mut words = line.split_whitespace();
    let path = words.next().unwrap_or("");
    let mut args: [&str; MAX_ARGS] = [""; MAX_ARGS];
    let mut argc = 0;
    // Нулевым аргументом идёт сам путь — так его видит всякая программа в Unix,
    // и программе, печатающей своё имя в сообщении об ошибке, взять его больше
    // неоткуда.
    args[argc] = path;
    argc += 1;
    for word in words {
        if argc == MAX_ARGS {
            break;
        }
        args[argc] = word;
        argc += 1;
    }

    // Концы здесь **перемещаются**, а не копируются, и это не мелочь: копия
    // осталась бы в заявке, а заявка живёт до конца задачи, которая уже не
    // вернётся из `exit_current_with`. Пока жив хоть один писатель, читатель на
    // другом конце не видит конца файла — то есть ждёт вечно.
    // Сужение правами пакета, которому принадлежит сам файл. Второе из двух
    // правил (см. [`rights_of_path`]); оба только сужают.
    let rights = rights.intersect(rights_of_path(path));
    let code = match run(path, &args[..argc], cred, rights, stdin, stdout) {
        Ok(code) => {
            if code == user_abi::EXIT_KILLED {
                report_line(path, "killed by request");
            } else if code == user_abi::EXIT_FAULTED {
                report_line(path, "killed by the kernel, see the serial log");
            } else {
                let text = CodeText::new(code);
                report_line(path, text.as_str());
            }
            code
        }
        Err(err) => {
            crate::shell::print(format_args!("  {} {path}: {err}\n", sched::current()));
            user_abi::EXIT_FAULTED
        }
    };

    sched::exit_current_with(code)
}

/// Напечатать в окно оболочки строку об окончании программы.
///
/// `shell::print`, а не `write!` по частям: с вытеснением строка, собираемая из
/// кусков, разрывается чужим выводом посередине.
fn report_line(path: &str, what: &str) {
    crate::shell::print(format_args!("  {} {path}: {what}\n", sched::current()));
}

/// Текст «exited with code N» без выделения памяти.
///
/// Печатать код возврата приходится из задачи программы, а форматирование в
/// `String` требовало бы кучи ровно там, где программа только что могла её
/// исчерпать.
struct CodeText {
    buffer: [u8; 32],
    len: usize,
}

impl CodeText {
    fn new(code: i64) -> Self {
        let mut this = Self { buffer: [0; 32], len: 0 };
        let mut out = CodeWriter { text: &mut this };
        let _ = write!(&mut out, "exited with code {code}");
        this
    }

    fn as_str(&self) -> &str {
        core::str::from_utf8(&self.buffer[..self.len]).unwrap_or("exited")
    }
}

/// Приёмник для `write!`, складывающий байты в [`CodeText`].
struct CodeWriter<'a> {
    text: &'a mut CodeText,
}

impl core::fmt::Write for CodeWriter<'_> {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        for byte in s.bytes() {
            if self.text.len == self.text.buffer.len() {
                return Err(core::fmt::Error);
            }
            let at = self.text.len;
            self.text.buffer[at] = byte;
            self.text.len += 1;
        }
        Ok(())
    }
}

/// Границы памяти, доступной программе.
///
/// Нужны системным вызовам: указатель, пришедший из третьего кольца, обязан
/// быть проверен. Проверка не про безопасность программы, а про безопасность
/// ядра — иначе `write` с адресом ядерной структуры заставил бы ядро самому
/// прочитать то, до чего программа не дотянулась бы.
///
/// Диапазоны заданы константами, а не спрошены у таблиц: обращение к таблицам
/// на каждом системном вызове стоило бы обхода четырёх уровней, а окно у всех
/// программ одно и то же по построению.
///
/// Память по запросу этого свойства не портит, хотя и выглядит как исключение:
/// у всех программ одинакова **область**, а не то, что в ней занято. Поэтому
/// здесь названа вся область целиком — и ответ остаётся тем же дешёвым
/// сравнением, — а вопрос «отображён ли этот адрес на самом деле» решается там,
/// где он и решался: в [`space::user_can`], который всё равно идёт по таблицам
/// за правами. Незанятая страница области не имеет записи, и ответ на неё —
/// отказ, а не чтение чужого.
#[must_use]
pub fn owns(ptr: usize, len: usize) -> bool {
    let Some(end) = ptr.checked_add(len) else {
        return false;
    };
    let in_image = ptr >= WINDOW_BASE && end <= WINDOW_BASE + IMAGE_LIMIT_BYTES;
    let in_stack = ptr >= STACK_BASE && end <= STACK_TOP;
    let in_mmap = ptr >= MMAP_BASE && end <= MMAP_BASE + MMAP_MAX_BYTES;
    in_image || in_stack || in_mmap
}


/// Достроить отображение под адресом, по которому программа только что
/// отказала. `true` — достроено, инструкцию можно повторять.
///
/// Вызывается из обработчика отказа **до** того, как он решит снимать
/// программу, и потому обязан быть быстрым в отказе: адрес, за который никто не
/// отвечает, — это обычный путь, а не исключительный.
///
/// # Условия вызова
///
/// Прерывания открыты, и это не пожелание: подкачка читает с диска, а путь
/// чтения берёт засыпающие мьютексы. Вызывающий обязан их открыть — на x86-64
/// шлюз исключения их закрывает.
///
/// Сам обработчик при этом **не имеет права** обращаться к подкачиваемой
/// памяти: страницу он наполняет через прямое отображение кадра, а не по
/// адресу программы. Иначе первый же отказ вложился бы сам в себя.
/// Лок [`PROGRAMS`] берётся здесь и не должен быть взят вызывающим: он не
/// входит сам в себя, и второй захват той же задачей — это сон без пробуждения.
/// Отсюда правило для [`space::user_can`], который тоже сюда ходит: его нельзя
/// звать изнутри [`with_current`]. Сегодня ни один системный вызов так не
/// делает, и это проверено, а не предположено.
#[must_use]
pub fn fault_in(addr: usize, write: bool, present: bool) -> bool {
    // Страница на месте, а обращение не прошло — это нарушение прав, и
    // подкачка тут ни при чём.
    if present {
        return false;
    }
    let page_addr = addr & !(PAGE_SIZE - 1);

    // Шаг первый, под замком: что читать.
    let Some(plan) = with_current(|program| program.fault_plan(page_addr, write)).flatten() else {
        return false;
    };

    // Шаг второй, без замка: кадр и чтение. Замок пула отпускается до чтения:
    // путь чтения берёт засыпающие мьютексы, а держать под ними `SpinLock`,
    // запрещающий прерывания, — прямая дорога в тупик. Замок программ
    // отпущен тоже — иначе программа, отказавшая в это же время, ждала бы не
    // носитель, а этот замок, внутри своего обработчика.
    let Some(frame) = take_frame_reserved() else {
        return false;
    };
    // SAFETY: кадр только что выдан аллокатором, принадлежит нам одним и
    // виден через прямое отображение. Читаем в него **мимо** адресов
    // программы: обращение по `page_addr` вызвало бы тот же отказ, который
    // мы сейчас и обрабатываем.
    let buffer = unsafe { core::slice::from_raw_parts_mut(frame_bytes(frame), PAGE_SIZE) };
    let read = if plan.want == 0 {
        // Страница целиком за файловой частью сегмента — чистый `.bss`.
        0
    } else {
        match plan.node.read_at(plan.offset, &mut buffer[..plan.want]) {
            Ok(read) => read,
            Err(_) => {
                return_frame(frame);
                return false;
            }
        }
    };
    // Хвост последней страницы файла обязан быть нулём, а не тем, что лежало
    // в кадре: чтение за концом возвращает короткий счёт и остаток буфера не
    // трогает. Кадр приходит обнулённым, так что делать тут нечего — но
    // проверить стоит: первая же выдача кадров без обнуления открыла бы
    // программе чужие данные, и молча.
    debug_assert!(buffer[read..].iter().all(|byte| *byte == 0));

    // Шаг третий, снова под замком: отобразить и учесть.
    let mapped = with_current(|program| program.fault_commit(page_addr, frame, &plan)).unwrap_or(false);
    if !mapped {
        return_frame(frame);
    }
    mapped
}

/// Исполняет ли текущая задача код в третьем кольце.
#[must_use]
pub fn is_running() -> bool {
    IN_USER[sched::current_slot()].load(Ordering::Acquire)
}

/// Почему задачу не удалось снять.
#[derive(Debug, Clone, Copy)]
pub enum KillError {
    /// Задачи с таким номером нет — или уже нет.
    NoSuchTask,
    /// Задача уже завершилась сама.
    AlreadyFinished,
    /// Задача есть, но программы не исполняет.
    ///
    /// Снять можно только программу, и это не половина работы, а граница
    /// возможного: у программы есть точка, в которую ядро умеет вернуться —
    /// кадр `enter_user` на её стеке. У задачи ядра такой точки нет, и «снять»
    /// её означало бы бросить её стек, её локи и её незаконченную работу
    /// неизвестно в каком состоянии.
    NotAProgram,
    /// Программа чужая: снять её вправе только владелец и root.
    NotAllowed,
}

impl core::fmt::Display for KillError {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            // Формулировки продолжают фразу «task #5 ...»: сообщение об ошибке
            // собирается там, где известен номер, а не здесь.
            Self::NoSuchTask => f.write_str("does not exist"),
            Self::AlreadyFinished => f.write_str("has already finished"),
            Self::NotAProgram => f.write_str("is not running a program; only programs can be stopped"),
            Self::NotAllowed => f.write_str("belongs to another user"),
        }
    }
}

/// Путь и uid программы в слоте — для диспетчера задач. `None` — слот не
/// исполняет программу.
#[must_use]
pub fn program_facts(slot: usize) -> Option<(alloc::string::String, u32)> {
    // Ссылка клонируется под локом таблицы, а читается уже без него: печать
    // этой строки идёт из `tasks`, и держать на ней лок, который ждёт каждый
    // системный вызов, незачем.
    let process = {
        let table = PROGRAMS.lock();
        table.get(slot)?.as_ref()?.clone()
    };
    let program = process.lock();
    Some((program.path.clone(), program.cred.uid))
}

/// Как [`request_kill`], но от имени `who`: чужую программу снимает только
/// root. Проверка здесь, а не в [`request_kill`], по той же причине, что и у
/// `spawn`: внутри ядра оболочке проверять нечего, граница — системный вызов.
pub fn request_kill_as(id: sched::TaskId, who: Credentials) -> Result<(), KillError> {
    if !who.is_root() {
        let (slot, _) = sched::lookup(id).ok_or(KillError::NoSuchTask)?;
        // Замок отпускается до [`request_kill`]: тот берёт его сам.
        let owner = program_facts(slot).map(|(_, uid)| uid);
        match owner {
            Some(uid) if uid == who.uid => {}
            Some(_) => return Err(KillError::NotAllowed),
            None => return Err(KillError::NotAProgram),
        }
    }
    request_kill(id)
}

/// Попросить снять программу задачи `id`.
///
/// Возврат `Ok` означает «просьба принята», а не «программа снята»: снимет её
/// [`check_kill`] на ближайшем возврате в третье кольцо — то есть не позже
/// следующего тика таймера, если программа исполняет свой код. Программа,
/// застрявшая **внутри** ядра, не снимется до тех пор, пока оттуда не выйдет; в
/// этом ядре системные вызовы не блокируются, поэтому выйдет она сразу, но
/// обещать это на будущее нельзя.
pub fn request_kill(id: sched::TaskId) -> Result<(), KillError> {
    // Холостая задача — задача ядра, и отказ ей полагается тот же, что задаче
    // USB или питания: «это не программа». До фазы 43 так и было; с появлением
    // нескольких процессоров холостые слоты перестали отдаваться поиском, и
    // `kill 0` стал отвечать «такой задачи нет» — про задачу, которую `tasks`
    // печатает первой строкой.
    if sched::is_idle(id) {
        return Err(KillError::NotAProgram);
    }
    let (slot, state) = sched::lookup(id).ok_or(KillError::NoSuchTask)?;
    if state == sched::TaskState::Finished {
        return Err(KillError::AlreadyFinished);
    }

    let process = {
        let table = PROGRAMS.lock();
        table.get(slot).and_then(Option::as_ref).cloned()
    };
    match process {
        Some(process) => {
            process.lock().kill_requested = true;
            // Программа могла спать, а снятие происходит на возврате в третье
            // кольцо — то есть спящая не снялась бы, пока не проснётся сама.
            // Пробуждение здесь и делает `kill` работающим на программе,
            // которая ничего не делает.
            //
            // Двух вызовов, а не одного: `wake_input` будит **всех**, кто ждёт
            // ввода, — это нужно оболочке, чтобы она разобрала очередь и
            // заметила снятие. `wake` будит именно снимаемую, чем бы она ни
            // была занята: `sleep_ms` в службе, отзывающейся раз в полминуты,
            // иначе откладывал бы снятие на полминуты, и `kill` выглядел бы как
            // команда, которая не работает. Ровно так это и выглядело.
            sched::wake_input();
            sched::wake(id);
            Ok(())
        }
        None => Err(KillError::NotAProgram),
    }
}

/// Просили ли снять программу текущей задачи.
///
/// Спрашивает [`syscall`] в тех вызовах, которые умеют ждать долго: снятие
/// произойдёт на возврате в третье кольцо, но до возврата надо ещё дойти, а
/// ожидание ввода само по себе не кончается никогда.
#[must_use]
pub fn kill_pending() -> bool {
    with_current(|program| program.kill_requested).unwrap_or(false)
}

/// Снять текущую программу, если её просили снять.
///
/// Вызывается арх-слоем на возврате из ловушки в третье кольцо (см.
/// [`crate::irq::on_trap_return`]) и не возвращается, если снятие состоялось.
///
/// Почему именно это место: здесь ядро заведомо не держит ни одного лока и не
/// оставляет незаконченной работы — вся она закончилась вместе с обработчиком.
/// Снять программу в произвольной точке ядра было бы нельзя: `return_to_kernel`
/// бросает стек обработчика целиком, и вместе с ним пропал бы любой охранник
/// лока, который на нём лежал.
///
/// # Safety
///
/// Вызывать только тогда, когда прерванный код исполнялся в третьем кольце: это
/// и есть доказательство того, что кадр [`arch::enter_user`] на стеке этой
/// задачи цел.
pub unsafe fn check_kill() {
    if !is_running() {
        return;
    }
    if !with_current(|program| program.kill_requested).unwrap_or(false) {
        return;
    }

    kprintln!("  user        : killed by request, task {}", sched::current());
    IN_USER[sched::current_slot()].store(false, Ordering::Release);
    // SAFETY: контракт функции плюс проверенный `running` — программа
    // действительно исполняется, значит `enter_user` на стеке и вернуться есть
    // куда.
    unsafe { arch::return_to_kernel(user_abi::EXIT_KILLED) }
}

/// Снять программу после отказа.
///
/// Вызывается обработчиком исключений, когда отказ пришёл из пользовательского
/// режима. Не возвращается: управление уходит в точку, из которой программа
/// была запущена, — то есть в [`run`], который вернёт процессор на таблицы ядра
/// и разберёт её адресное пространство.
///
/// # Safety
///
/// Вызывать только тогда, когда [`is_running`] отвечает `true`.
pub unsafe fn faulted(what: &str, at: usize, addr: usize) -> ! {
    // Номер задачи стоит в конце строки, а не в начале, и это не вкус: начало
    // строки читает стенд, и сдвинуть его значит переписать проверки, которые
    // про номер задачи ничего не спрашивают.
    kprintln!(
        "  user        : killed by {what} at {at:#018x} (address {addr:#018x}), task {}",
        sched::current()
    );
    IN_USER[sched::current_slot()].store(false, Ordering::Release);
    // SAFETY: контракт функции — программа запущена, значит `enter_user`
    // действительно исполняется и его кадр на стеке ядра цел.
    unsafe { arch::return_to_kernel(user_abi::EXIT_FAULTED) }
}
