/// Начало окна программы: 512 ГиБ.
///
/// Тот же адрес записан в компоновочном сценарии `crates/user-progs/user.ld`;
/// разъехаться они не могут незаметно — сегмент за пределами окна отвергается
/// загрузчиком с [`elf::ElfError::OutOfWindow`].
///
/// Выравнено на границу записи корневой таблицы намеренно: вся память программы
/// обязана лежать под одной такой записью, иначе освобождение пространства
/// перестало бы быть обходом одного поддерева (см. [`space::WINDOW_SLOT`]).
pub const WINDOW_BASE: usize = 0x0000_0080_0000_0000;

/// Сколько адресов отведено под образ программы.
///
/// Гибибайт — и это предел адресов, а не памяти. С фазы 54 образ **не
/// раскладывается заранее**: сегменты ELF записываются в таблицу областей
/// программы так же, как отображённый файл (фаза 41), и страница читается с
/// носителя при первом обращении к ней. Программа занимает столько кадров,
/// сколько страниц тронула, а размер файла ограничен только этим окном и
/// самим носителем.
///
/// История числа стоит того, чтобы её помнить. До фазы 54 здесь стояло число
/// страниц, и кадры под них выделялись целиком при запуске: полмегабайта до
/// `sshd` (фаза 37), полтора до `sysupdate` с TLS (фаза 39a), три после. Каждый
/// раз предел находил не размер, а его следствие: ядро дочитывало файл до
/// предела, а загрузчик жаловался на «сегмент, противоречащий сам себе», и
/// искать шли в формат ELF. Роман потребовал снять предел вовсе: «программы
/// могут быть большие», — и снят он не константой побольше, а загрузкой по
/// обращению.
///
/// Верхняя граница по-прежнему не произвольна: за окном образа лежит
/// неотображённая полоса, за ней стек, за ним — память по запросу.
const IMAGE_LIMIT_BYTES: usize = 1 << 30;
/// Сколько страниц отведено под стек программы.
///
/// Было восемь, стало шестнадцать — и подняты они не «на всякий случай».
/// В 32 КиБ не помещается проверка подписи Ed25519: `sshd`, дойдя до подписи
/// клиента, уходил за нижнюю страницу стека и снимался ядром как испортивший
/// память. Со стороны это выглядит как оборвавшееся соединение — клиент уже
/// услышал «ключ подойдёт, пришлите подпись» и не дождался ответа.
///
/// Цена — 32 КиБ на программу. Фаза 40 её не вернула: память по запросу выдаётся
/// туда, куда указывает программа, а стек растёт вниз сам собой, и заметить это
/// может только обработчик отказа страницы — то есть фаза 41. Пока его нет,
/// число остаётся честной константой, а не обещанием: программе, которой мало
/// стека, теперь есть что попросить (`SYS_MMAP`), но попросить она обязана
/// вслух.
const STACK_PAGES: usize = 16;

/// Вершина стека программы. Отстоит от конца окна образа на четыре мегабайта —
/// чтобы переполнение стека упиралось в неотображённые страницы, а не в конец
/// образа.
///
/// Полоса между самым большим возможным образом и низом стека — почти четыре
/// мегабайта неотображённой памяти. Она и есть та проверка, которой нет в самом
/// стеке: программа, ушедшая за свой кадр, получает отказ страницы, а не тихо
/// портит собственный `.bss`. У обычной программы полоса много шире: образ
/// кончается там, где кончается её последний сегмент.
pub const STACK_TOP: usize = WINDOW_BASE + IMAGE_LIMIT_BYTES + 0x0040_0000;
/// Низ стека.
const STACK_BASE: usize = STACK_TOP - STACK_PAGES * PAGE_SIZE;

/// Начало области, которую программа получает по запросу (`SYS_MMAP`).
///
/// **На четыре мегабайта выше вершины стека**. Полоса между ними не забыта, а
/// поставлена: она продолжает ту же мысль, что и полоса между образом и
/// стеком, — программа, ушедшая за свой стек, обязана упереться в
/// неотображённое, а не в чужие данные. Без неё переполнение стека молча
/// писало бы в первую выданную по запросу страницу, и выглядело бы это как
/// испорченные данные, а не как ошибка в программе. Начало кратно двум
/// мегабайтам: крупные страницы (фаза 42) требуют этого от адреса.
pub const MMAP_BASE: usize = STACK_TOP + 0x0040_0000;

/// Сколько памяти по запросу отведено **одной** задаче.
///
/// Полгигабайта. Это и есть то ограничение, без которого фазу нельзя считать
/// сделанной: программа, попросившая всю память, не должна уносить с собой
/// систему. Считается оно по адресам, а не по страницам, и потому неотделимо
/// от области — занять больше, чем в неё влезает, нечем.
///
/// Число выбрано так, чтобы проверка фазы (256 МиБ) проходила с запасом, а не
/// впритык: предел, совпадающий с проверкой, проверяет сам себя.
///
/// Одного этого предела мало, и это важно сказать вслух: у гостя памяти обычно
/// столько же, сколько здесь названо, так что предел на задачу не мешает ей
/// выбрать машину досуха. От этого защищает [`RESERVE_FRAMES`] — предел и запас
/// отвечают на разные вопросы: «сколько дать одному» и «сколько не отдавать
/// никому».
pub const MMAP_MAX_BYTES: usize = 512 * 1024 * 1024;

/// Страница процесса — [`user_abi::PROCESS_PAGE`]: одна страница только на
/// чтение выше всего, что программа может занять, и через ту же полосу в четыре
/// мегабайта после конца памяти по запросу, что и между остальными областями.
///
/// Ядро отображает её каждой программе до входа в неё и кладёт в начало
/// случайные байты — эталон канарейки стека, который компилятор читает по
/// символу `__stack_chk_guard` (см. `user.ld`). Адрес — часть договора, и
/// программы собраны под него; поэтому он не выводится отсюда, а сверяется с
/// договором на этапе компиляции: сдвинь кто-нибудь `MMAP_MAX_BYTES`, сборка
/// ядра остановится здесь, а не программа — на первом возврате из функции.
const PROCESS_PAGE: usize = MMAP_BASE + MMAP_MAX_BYTES + 0x0040_0000;
const _: () = assert!(
    PROCESS_PAGE == user_abi::PROCESS_PAGE,
    "user_abi::PROCESS_PAGE has to sit four megabytes past the end of the mmap area"
);

/// Сколько кадров ядро не отдаёт по запросу ни при каких условиях.
///
/// Восемь мегабайт. Запас не «на всякий случай», а на конкретную работу:
/// запустить программу стоит корень, три-четыре таблицы, 768 страниц образа и
/// 16 страниц стека — около трёх мегабайт, — и столько же примерно нужно,
/// чтобы оболочка дожила до сообщения об ошибке и приняла следующую команду.
///
/// Без запаса отказ выделения был бы не отказом, а концом: `mmap` вернул бы
/// ошибку, программа честно сообщила бы о ней — и на этом система осталась бы
/// без единого кадра, то есть без возможности запустить хоть что-нибудь. «Сбой
/// виден» требует, чтобы после сбоя было кому его показать.
pub const RESERVE_FRAMES: usize = 8 * 1024 * 1024 / PAGE_SIZE;

/// Сколько отдельных областей может держать одна задача.
///
/// Тридцать две. Число маленькое намеренно: таблица лежит прямо в [`Program`],
/// обходится линейно, и обход её — цена каждого `mmap` и каждого отказа
/// страницы. Программе, которой не хватило областей, отказывают тем же
/// ответом, что и упёршейся в [`MMAP_MAX_BYTES`]: с её стороны это одно и то
/// же — «больше не дадут». Было шестнадцать; с фазы 54 в той же таблице лежат
/// и сегменты самого образа (обычно три-четыре), и столько же осталось
/// программе на её собственные области.
const MAX_MAPPINGS: usize = 32;

/// Сколько страниц одной отображённой области ядро держит в памяти сразу.
///
/// Тысяча двадцать четыре, то есть четыре мегабайта. Число выбрано не по одной
/// области, а по худшему случаю: областей у задачи бывает до [`MAX_MAPPINGS`],
/// и предел на область надо умножать на шестнадцать, прежде чем сравнивать с
/// машиной. Четыре мегабайта дают шестьдесят четыре на задачу — заметную, но
/// не пугающую долю от пятисот двенадцати. Шестнадцать, стоявшие здесь
/// сначала, давали двести пятьдесят шесть, то есть **половину машины у одной
/// задачи**, и это была бы не подкачка, а её отсутствие в рассрочку.
///
/// Общего вытеснения — такого, которое отняло бы страницы у той области, что
/// их не просила, — в системе нет. Пока его нет, предел на область и есть
/// единственный способ вообще ограничить отображённую память, и потому он
/// обязан быть скромным.
///
/// Это и есть то, ради чего фаза затевалась: файл перестаёт помещаться в
/// память целиком, потому что ему это больше и не нужно. Программа, прошедшая
/// по шестнадцати мегабайтам, займёт четыре — остальное будет прочитано,
/// показано и выброшено.
///
/// Выброшенная страница ничего не стоит: отображение **только на чтение**,
/// значит страница чиста по построению, и вытеснение — это снять и вернуть
/// кадр, без обратной записи и без вопроса о согласованности с обычной записью
/// в файл. Именно поэтому вытеснение помещается в эту фазу, а запись в
/// отображение — нет.
///
/// Известная цена подкачки — не в отказе страницы, а в чтении: ядро берёт по
/// одной странице, и таблицы косвенности ext2 перечитываются на каждый вызов,
/// потому что кеша блоков в системе нет вовсе. У файла за двойной косвенностью
/// это три обращения к диску вместо одного. Отсюда и рычаг, если он
/// понадобится: читать вперёд и кешировать таблицы, а не уменьшать предел.
const RESIDENT_MAX_PAGES: usize = 1024;

/// Через сколько подкачек ядро печатает, сколько их уже было.
///
/// Строка в журнале на каждую страницу утопила бы серийную линию и сама стала
/// бы главной статьёй расхода; раз в тысячу двадцать четыре — это несколько
/// строк на обход и достаточно, чтобы увидеть темп.
const PROGRESS_EVERY: u64 = 1024;

/// Чем наполнена область.
enum Source {
    /// Ничем. Страницы выданы сразу и целиком, и лежат в них нули (фаза 40).
    Anonymous,
    /// Стеком потока (фаза 55b): то же, что безымянная область, но её **нижняя
    /// страница не отображена** — это сторож.
    ///
    /// Отдельный вид, а не признак у безымянной, по той же причине, по которой
    /// вообще существует это перечисление: разбор в `munmap` обязан ответить,
    /// сколько кадров область должна вернуть, и ответ здесь другой — на один
    /// меньше числа страниц. Скажи мы «столько же», и всякое освобождение
    /// стека потока печатало бы предупреждение о потерянной странице.
    ThreadStack,
    /// Файлом: страницы подкачиваются по обращению (фаза 41).
    File(FileBacking),
    /// Сегментом программы (фаза 54): страницы читаются из файла программы
    /// при первом обращении, а за концом файловой части лежат нули (`.bss`).
    /// Страницы на запись после первого чтения — свои, и их не вытесняют;
    /// страницы кода и данных только на чтение — чистые, и вытесняются, как у
    /// отображённого файла.
    Image(ImageBacking),
    /// Поверхностью окна: подряд идущие кадры, выданные под пиксели (фаза 47a).
    ///
    /// Внутри — физический адрес первого кадра, потому что вернуть их можно
    /// только всем куском сразу: выданы они [`allocate_contiguous`], и ядро
    /// читает их одним срезом через прямое отображение.
    ///
    /// Главное отличие от остальных двух — **владелец**. Кадры под поверхностью
    /// принадлежат окну, а не программе, и поэтому область живёт по особым
    /// правилам: `munmap` на неё отвечает отказом, а разбор пространства обязан
    /// пройти мимо неё — иначе первая же снятая программа оставит композитору
    /// ссылку на кадры, уже отданные в пул.
    ///
    /// Второе число — номер окна у программы (фаза N7c): окон может быть
    /// несколько, и снимать надо поверхность того, которое закрыли.
    ///
    /// [`allocate_contiguous`]: crate::mm::frame::BitmapFrameAllocator::allocate_contiguous
    Surface(PhysAddr, u32),
}

/// Файл, стоящий за областью, и всё, что нужно знать о её страницах.
struct FileBacking {
    /// Узел. `Arc`, потому что дескриптор, из которого он взят, программа
    /// вправе закрыть в следующей же строке.
    node: Arc<dyn Node>,
    /// Смещение в файле, отвечающее началу области.
    offset: u64,
    /// Номера подкачанных страниц в порядке подкачки.
    ///
    /// Очередь, а не множество: вытесняем самую старую, и порядок — это и есть
    /// всё, что нужно знать. FIFO, а не «недавно использованная»: отличить
    /// использованную от лежащей без дела можно только по биту обращения в
    /// записи таблицы, а его чтение стоит обхода всех страниц области. При
    /// последовательном проходе — а это тот случай, ради которого фаза, — FIFO
    /// и LRU выбирают одну и ту же страницу.
    resident: VecDeque<usize>,
    /// Сколько раз страницу пришлось читать с диска.
    reads: u64,
    /// Сколько раз страницу выбросили, чтобы освободить место.
    evictions: u64,
}

/// Сегмент образа программы, стоящий за областью (фаза 54).
struct ImageBacking {
    /// Файл программы.
    node: Arc<dyn Node>,
    /// Смещение в файле, отвечающее началу области (первой её странице).
    offset: u64,
    /// Сколько байт от начала области приходит из файла; дальше — нули.
    file_bytes: usize,
    /// Права сегмента: чтение, запись, исполнение — плюс третье кольцо.
    flags: PageFlags,
    /// Подкачанные страницы **без права записи**, в порядке подкачки: они
    /// чистые, и вытеснять их можно так же, как у отображённого файла.
    /// Страницы на запись сюда не попадают — выброшенная страница данных
    /// вернулась бы из файла в исходном виде.
    resident: VecDeque<usize>,
    /// Сколько раз страницу пришлось читать с носителя.
    reads: u64,
    /// Сколько раз страницу выбросили, чтобы освободить место.
    evictions: u64,
}

/// Одна область, выданная по запросу.
///
/// Хранится в [`Program`] по возрастанию адреса. Нужна трём вещам: найти, куда
/// положить следующую, узнать в `SYS_MUNMAP`, что именно просят снять, и —
/// с фазы 41 — ответить обработчику отказа, чем наполнять страницу.
///
/// Освобождению при выходе задачи она **не** нужна — то ходит по таблицам
/// страниц и возвращает всё, что под ними лежит, не спрашивая, кто это заказал.
struct Mapping {
    /// Адрес начала. Всегда кратен странице.
    base: usize,
    /// Длина в страницах. Всегда в обычных, 4 КиБ, даже когда часть области
    /// отображена крупными: страница — единица учёта, а не единица записи.
    pages: usize,
    /// Сколько крупных страниц ушло на эту область.
    ///
    /// Ноль — обычная область. Нужно двум вещам: сказать в журнале, чем она
    /// отображена (без этого «крупные страницы работают» и «крупные страницы
    /// молча не получились» выглядят одинаково), и сойтись в `munmap`, где
    /// возвращённые кадры считаются, а блок стоит пятисот двенадцати.
    blocks: usize,
    /// Чем наполнять её страницы.
    source: Source,
}

/// Почему память по запросу не выдана.
#[derive(Debug, Clone, Copy)]
pub enum MmapError {
    /// Просьба бессмысленна: нулевая длина, невыровненное смещение, или снять
    /// просят не то, что выдавали.
    BadRequest,
    /// Задаче столько не полагается — [`MMAP_MAX_BYTES`] или [`MAX_MAPPINGS`].
    Limit,
    /// Кадров в машине не осталось — с учётом [`RESERVE_FRAMES`].
    NoMemory,
    /// Дескриптор не годится: его нет, или за ним не обычный файл.
    BadFile(files::FileError),
}

/// Сколько байт файла программы ядро читает при запуске.
///
/// Только заголовки: заголовок файла и таблица сегментов лежат в начале, и
/// шестидесяти четырёх килобайт хватает любому компоновщику с большим запасом.
/// Если таблица всё же не поместилась, дочитывается ровно до её конца. Сами
/// сегменты при запуске **не читаются** (фаза 54): их страницы приходят по
/// обращению, и поэтому у размера программы больше нет предела, о который она
/// упиралась бы при запуске.
const HEADER_BYTES: usize = 64 * 1024;

/// Читать ли страницы образа по обращению, а не при запуске.
///
/// `false` — и это временно. Механизм чтения по обращению написан и работает
/// (образ `big` в шесть мегабайт проходит стенд на обеих архитектурах), но
/// полный прогон нашёл дефект, который он вскрывает, а не порождает.
///
/// Падали **все** сценарии, где программа стартует с ext2 на virtio (`sysmon`,
/// `cdemo`, `mc`, `files.dll`, `winforms`, `logger` при загрузке), на обеих
/// архитектурах, а живые с initrd проходили. Общий знаменатель — чтение внутри
/// обработчика отказа, которое **засыпает**: на диске или на чужом `Mutex`, когда
/// две программы стартуют разом. Сон внутри системного вызова работает, сон
/// внутри обработчика отказа — нет: на AArch64 уснувшая задача после
/// пробуждения делает `eret` по адресу внутри ядра (`killed by an instruction
/// abort at 0x5a78aff8` — адрес один и тот же при разном смещении ядра, то есть
/// это не код ядра, а вершина чьего-то стека минус восемь), на x86-64 машина
/// молча встаёт. Прежняя запись «`ls` в `userspace` вешает машину» была неверна:
/// журнал того прогона показывает, что `ls` прошёл. Что именно портит кадр,
/// не найдено; искать — в сне из `fault_in` (`block_on_irq`/`block_on_lock`)
/// при кадре ловушки на стеке задачи, и начать с `is_running()`, который в
/// обоих обработчиках берёт спящий `PROGRAMS` **до** `enable()`.
///
/// Пока это не разобрано, страницы читаются при запуске **тем же кодом
/// областей** ([`prefetch`]): предела размера у программы больше нет, а
/// память она занимает по размеру файла, как и до фазы 54. Переключить на
/// чтение по обращению — одна константа, и стенд (`install` + `installed`,
/// `services`, `mc`) покажет, жив ли дефект.
const IMAGE_PAGED_ON_DEMAND: bool = false;

/// Сколько страниц образа могут делить два сегмента.
///
/// Обычно одна-две: конец `.rodata` и начало `.data`, крошечный `.data` и
/// `.bss` за ним. Больше — не раскладка, а противоречивый заголовок.
const MAX_SHARED_PAGES: usize = 64;

/// Почему программа не запустилась.
#[derive(Debug, Clone, Copy)]
pub enum Error {
    /// Файловой системы нет.
    NoFilesystem,
    /// Файл не прочитался.
    Read(crate::vfs::VfsError),
    /// Файл не является пригодной программой.
    Elf(elf::ElfError),
    /// Не хватило кадров под окно программы.
    OutOfMemory,
    /// Не удалось построить адресное пространство или отобразить страницу.
    Map(crate::mm::MapError),
    /// Страница получилась одновременно записываемой и исполняемой.
    WriteExecute(usize),
    /// Задача уже исполняет программу. Вложенного входа в третье кольцо не
    /// бывает: стек возврата у задачи один, и второй вход затёр бы его.
    AlreadyRunning,
    /// В таблице планировщика нет места под ещё одну задачу.
    TooManyTasks,
    /// Сегментов в файле больше, чем полагается одной программе областей.
    TooManySegments,
}

impl core::fmt::Display for Error {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::NoFilesystem => f.write_str("no filesystem is mounted"),
            Self::Read(err) => write!(f, "{err}"),
            Self::Elf(err) => write!(f, "{err}"),
            Self::OutOfMemory => f.write_str("not enough memory for the program window"),
            Self::Map(err) => write!(f, "building the address space failed: {err}"),
            Self::WriteExecute(page) => write!(
                f,
                "page {page} of the image would be writable and executable at once"
            ),
            Self::AlreadyRunning => f.write_str("this task already runs a program"),
            Self::TooManyTasks => f.write_str("the task table is full"),
            Self::TooManySegments => f.write_str("the program has more loadable segments than a task may hold"),
        }
    }
}

/// Процесс: всё, что у программы общее, чем бы её ни исполняли.
///
/// Адресное пространство, таблица открытых файлов, личность, права, окна и
/// области. С фазы 55a задача этим **не владеет**, а ссылается: таблица по
/// слотам хранит `Arc`, и процесс живёт, пока жива хоть одна ссылка. Отсюда и
/// пойдут потоки — вторая задача с той же ссылкой.
///
/// Чего здесь больше нет — признака «сейчас исполняется код в третьем кольце»
/// ([`IN_USER`]). Он принадлежит задаче: у процесса с двумя потоками один
/// может стоять в системном вызове, пока другой исполняет свой код, и одного
/// признака на двоих не хватило бы.
///
/// Имя пока прежнее. Переименование в `Process` тронуло бы сорок четыре места
/// вызова и ничего бы не доказало; оно уместно тогда, когда рядом появится
/// `Thread`, то есть в 55b.
pub struct Program {
    space: Space,
    /// Открытые файлы. Публично, потому что ими распоряжаются системные вызовы
    /// ([`syscall`]), а прятать таблицу за парой одинаковых методов означало бы
    /// переписать её интерфейс дважды.
    pub files: files::Table,
    /// Просили ли снять эту программу.
    ///
    /// Флаг, а не немедленное снятие, по той же причине, по которой вытеснение
    /// отложено до конца прерывания: тот, кто просит, исполняется в другой
    /// задаче и о состоянии этой не знает ничего. Разбирает флаг [`check_kill`]
    /// — на границе возврата в третье кольцо, где заведомо нет ни удерживаемого
    /// лока, ни половины начатой работы.
    kill_requested: bool,
    /// От чьего имени исполняется **эта** программа.
    ///
    /// С Phase 33 личность перестала быть свойством системы и стала свойством
    /// программы. Причина конкретная: супервизор служб исполняется от root, а
    /// служба — от того, кто записан в её описании, и общая на всех личность
    /// сеанса сделала бы это описание украшением. Отсюда же следует, что
    /// проверка прав в системном вызове обязана спрашивать **программу**, а не
    /// сеанс, — см. [`credentials`].
    cred: Credentials,
    /// Что этой программе **разрешено** сверх того, что разрешено человеку.
    ///
    /// Личность отвечает на вопрос «кому можно», права — на вопрос «чего этой
    /// программе нужно». Разница видна на калькуляторе: сеть ему не нужна, а
    /// учётная запись человека её разрешает, и до сих пор его от сети не
    /// удерживало ничто, кроме намерений автора.
    ///
    /// Набор берётся из манифеста пакета и едет с запуском, а не выводится из
    /// пути к файлу. Причина названа: пакет запускается строкой `start=`, и у
    /// программы на .NET эта строка — `/bin/dotnet /opt/имя/имя.dll`, то есть
    /// исполняемый файл лежит в системном каталоге и принадлежит не пакету.
    /// Права по пути дали бы такой программе всё, а по запуску — ровно то, что
    /// пакет попросил.
    ///
    /// Всё, что запущено **не** как пакет, получает [`Rights::ALL`]: команда
    /// оболочки, служба, системная программа из `/bin` — это и есть система, и
    /// ограничивать её этим набором нечем.
    rights: Rights,
    /// Откуда программа запущена — то, что диспетчер задач показывает как
    /// «расположение файла». До фазы С5 путь жил только в строке журнала.
    pub path: alloc::string::String,
    /// Откуда программа читает стандартный ввод.
    ///
    /// `None` — с терминала, как было всегда. `Some` — из канала: так её
    /// запустил тот, кто хочет кормить её сам. Поле здесь, а не в таблице
    /// дескрипторов, по двум причинам: программа не должна знать, чем её ввод
    /// оказался сегодня, и чтение из канала обязано **ждать**, а ждать под
    /// локом таблицы нельзя.
    pub stdin: Option<pipe::Reader>,
    /// Куда уходит стандартный вывод. `None` — в окно оболочки.
    pub stdout: Option<pipe::Writer>,
    /// Области, выданные по запросу, по возрастанию адреса.
    ///
    /// В фазе 40 здесь стоял массив, и стоял он там по названной причине: куча
    /// внутри выдачи памяти выглядит как выделение памяти внутри выделения
    /// памяти. Причина оказалась верной ровно наполовину — та куча и этот пул
    /// кадров разные, — и держаться за неё дальше нечем: область, отображающая
    /// файл, несёт `Arc` на его узел, а он не `Copy`, и массив, который двигают
    /// сдвигом, для него больше не подходит.
    ///
    /// Длина ограничена [`MAX_MAPPINGS`] по-прежнему: предел здесь не про
    /// память, а про то, что таблица обходится линейно на каждом отказе.
    mappings: Vec<Mapping>,
}

impl Program {
    /// Выдать программе `len` байт безымянной памяти. Возвращает её адрес.
    ///
    /// Память выделяется **сразу и целиком**, и после фазы 41 это уже выбор, а
    /// не безвыходность: обработчик отказа появился, лениться есть чем. Выбор
    /// остаётся жадным потому, что у безымянной памяти нечего подкачивать —
    /// страница из ниоткуда наполняется нулями, то есть «отложить» тут значит
    /// отложить обнуление кадра, а не чтение с диска. Выигрыш был бы только у
    /// того, кто просит больше, чем трогает; цена — отказ на каждой первой
    /// странице. Отображению файла откладывать есть что, и оно откладывает.
    ///
    /// Прав у страниц ровно двое — чтение и запись из третьего кольца.
    /// Исполнять безымянную память нельзя, и не потому, что здесь так решили:
    /// отображение с `WRITE | EXEC` отвергает сам построитель таблиц
    /// ([`crate::mm::MapError::WriteExecute`]).
    fn mmap(&mut self, len: usize, flags: usize) -> Result<usize, MmapError> {
        let huge = flags & MAP_HUGE != 0;
        // Крупные страницы требуют выравнивания и по виртуальному адресу тоже,
        // а не только по физическому: запись покрывает 2 МиБ от границы, и
        // область, начавшаяся мимо неё, не получит ни одного блока, сколько бы
        // непрерывной памяти ни нашлось.
        let align = if huge { HUGE_PAGE_SIZE } else { PAGE_SIZE };
        let (base, pages) = self.reserve(len, align)?;

        // SAFETY: `reserve` вернул адрес внутри области запроса, не
        // пересекающийся ни с одной уже выданной; образ и стек лежат ниже
        // [`MMAP_BASE`].
        let blocks = unsafe {
            self.space.map_anon(
                VirtAddr::new(base),
                pages,
                PageFlags::READ | PageFlags::WRITE | PageFlags::USER,
                huge,
            )
        }
        .map_err(|_| MmapError::NoMemory)?;

        if huge {
            // Оба числа, и всегда, когда крупные страницы просили. Отступление
            // на обычные — законный исход, но исход **другой**, и молчать о нём
            // нельзя: программа, получившая всё обычными страницами, работает
            // так же и стоит столько же, сколько до этой фазы, — а выглядит как
            // успех.
            // Счётчики стоят раньше адреса намеренно: адрес здесь — примета
            // для человека, а числа читает стенд, и число сразу за неизменной
            // подстрокой он достать умеет, а из середины строки — нет.
            kprintln!(
                "  user        : mmap: {blocks} huge and {} small pages at {base:#x}",
                pages - blocks * HUGE_PAGE_FRAMES
            );
        }

        self.remember(Mapping { base, pages, blocks, source: Source::Anonymous });
        Ok(base)
    }

    /// Выдать стек потоку: область на `bytes` плюс сторожевая страница под ней.
    ///
    /// Возвращает начало **всей** области (её нижняя страница — сторож),
    /// её размер и выровненную вершину стека.
    ///
    /// # Почему сторож получается сам собой
    ///
    /// Потому что область записана в таблицу целиком, вместе со сторожевой
    /// страницей, а отображена — без неё. Отказ внутри безымянной области
    /// [`Program::fault_plan`] не заполняет намеренно: «таблицы разошлись с
    /// записью» — повод снять программу, а не подложить ей чистую страницу.
    /// Переполнение стека потока приходит ровно в этот случай.
    ///
    /// Записать область целиком нужно ещё и затем, чтобы сторож не достался
    /// кому-то другому: [`Program::find_gap`] укладывает области вплотную и
    /// отдал бы дыру в одну страницу следующей же просьбе такого размера.
    fn map_thread_stack(&mut self, bytes: usize) -> Result<(usize, usize, usize), MmapError> {
        let want = bytes.next_multiple_of(PAGE_SIZE);
        let (base, pages) = self.reserve(want + PAGE_SIZE, PAGE_SIZE)?;
        let stack_base = base + PAGE_SIZE;
        let stack_pages = pages - 1;

        // SAFETY: `reserve` вернул диапазон внутри области запроса, не
        // пересекающийся ни с одной уже выданной; отображаем его без нижней
        // страницы.
        unsafe {
            self.space.map_anon(
                VirtAddr::new(stack_base),
                stack_pages,
                PageFlags::READ | PageFlags::WRITE | PageFlags::USER,
                false,
            )
        }
        .map_err(|_| MmapError::NoMemory)?;

        self.remember(Mapping { base, pages, blocks: 0, source: Source::ThreadStack });

        // Вершина выравнивается на 16: этого требуют оба соглашения о вызовах,
        // и невыровненный стек ломается не сразу, а на первой же операции с
        // вектором.
        let top = (stack_base + stack_pages * PAGE_SIZE) & !0xF;
        Ok((base, pages * PAGE_SIZE, top))
    }

    /// Отобразить `len` байт файла `fd`, начиная с `offset`. Возвращает адрес.
    ///
    /// Ни одной страницы при этом не выделяется и ни одного байта не читается:
    /// область заводится пустой, и наполняет её [`Program::fault_in`] по мере
    /// того, как программа до неё дотрагивается. Этим она и отличается от
    /// [`Program::mmap`] — и ради этого отличия фаза существует: файл, который
    /// вчетверо больше памяти, отображается за то же время, что и пустой,
    /// потому что времени тратится ровно ноль.
    ///
    /// Только на чтение. Записать в отображение — значит рано или поздно
    /// записать в файл, а это вытеснение грязных страниц и согласованность с
    /// обычной записью через `write`, то есть отдельный разговор.
    fn mmap_file(&mut self, fd: usize, offset: u64, len: usize) -> Result<usize, MmapError> {
        // Смещение обязано быть кратно странице: отображение сдвигает файл на
        // целые страницы и никак иначе. Округлить его молча значило бы отдать
        // программе не тот файл, который она просила, — и обнаружилось бы это
        // сдвинутыми данными, а не отказом.
        if offset % PAGE_SIZE as u64 != 0 {
            return Err(MmapError::BadRequest);
        }

        let node = self.files.node(fd).map_err(MmapError::BadFile)?;
        // Обычные страницы, и крупных здесь не будет. Подкачка работает
        // постранично, а вытеснить четверть блока нечем; читать же 2 МиБ на
        // один отказ — ровно та жадность, от которой фаза 41 уходила.
        let (base, pages) = self.reserve(len, PAGE_SIZE)?;

        self.remember(Mapping {
            base,
            pages,
            blocks: 0,
            source: Source::File(FileBacking {
                node,
                offset,
                resident: VecDeque::new(),
                reads: 0,
                evictions: 0,
            }),
        });
        Ok(base)
    }

    /// Отвести место под поверхность окна и отобразить в неё свежие кадры.
    ///
    /// Возвращает адрес поверхности в памяти программы и физический адрес
    /// первого кадра. Кадры берутся **подряд**: ядро читает поверхность одним
    /// срезом через прямое отображение, как обычный массив пикселей, а не по
    /// странице за раз.
    ///
    /// Область записывается в ту же таблицу, что и `mmap`, и это не небрежность,
    /// а два нужных следствия разом: [`Program::find_gap`] обойдёт её, выдавая
    /// адрес следующему `mmap`, а [`Program::munmap`] найдёт её и откажет —
    /// ровно то, что обещает договор.
    fn attach_surface(&mut self, pages: usize, slot: u32) -> Result<(usize, PhysAddr), MmapError> {
        if self.mappings.len() == MAX_MAPPINGS {
            return Err(MmapError::Limit);
        }
        let Some(bytes) = pages.checked_mul(PAGE_SIZE) else {
            return Err(MmapError::BadRequest);
        };
        let base = self.find_gap(bytes, PAGE_SIZE).ok_or(MmapError::Limit)?;

        // Запас пула соблюдается и здесь, наравне с обычной выдачей: окно — это
        // мегабайты, и программа, попросившая окно размером с экран, не должна
        // оставлять систему без кадров, которыми ей же об этом сообщат.
        let phys = crate::mm::frame::with(|frames| {
            if frames.stats().free <= RESERVE_FRAMES + pages {
                return None;
            }
            frames.allocate_contiguous(pages)
        })
        .flatten()
        .ok_or(MmapError::NoMemory)?;

        // SAFETY: кадры только что выданы пулом подряд и живы, пока живо окно;
        // адрес подобран `find_gap`, то есть свободен и лежит в окне программы.
        let mapped = unsafe {
            self.space.map_frames(
                VirtAddr::new(base),
                phys,
                pages,
                PageFlags::READ | PageFlags::WRITE | PageFlags::USER,
            )
        };
        if mapped.is_err() {
            crate::mm::frame::with(|pool| {
                // SAFETY: кадры выданы этим же пулом, отображение не состоялось,
                // и держать их больше некому.
                unsafe { pool.free_contiguous(phys, pages) };
            });
            return Err(MmapError::NoMemory);
        }

        self.remember(Mapping { base, pages, blocks: 0, source: Source::Surface(phys, slot) });
        Ok((base, phys))
    }

    /// Номера окон, у которых есть поверхность, — битовая маска.
    fn window_slots(&self) -> u32 {
        self.mappings.iter().fold(0, |mask, region| match &region.source {
            Source::Surface(_, slot) => mask | (1 << *slot),
            _ => mask,
        })
    }

    /// Свободный номер для следующего окна; `None` — окон уже
    /// [`user_abi::MAX_WINDOWS`].
    fn free_window_slot(&self) -> Option<u32> {
        let taken = self.window_slots();
        (0..user_abi::MAX_WINDOWS).find(|slot| taken & (1 << slot) == 0)
    }

    /// Снять поверхность окна: убрать отображение и вернуть кадры в пул.
    ///
    /// Возвращает число возвращённых кадров или `None`, если поверхности не
    /// было. Порядок обеспечивает вызывающий: к этому моменту окно обязано быть
    /// уже снято со стола, иначе композитор читал бы пиксели из кадров, только
    /// что отданных другому.
    /// Есть ли у программы поверхность окна.
    ///
    /// Дешёвый вопрос, на который отвечает сама программа, и задают его **до**
    /// того, как пойдут к столу. Порядок здесь не стилистический: программ без
    /// окна подавляющее большинство, и спрашивать о них стол значило бы лезть
    /// на каждом выходе `ls` под замок, который держит сборка кадра.
    fn has_surface(&self) -> bool {
        self.window_slots() != 0
    }

    /// Адрес поверхности окна `slot` в памяти программы.
    fn surface_base(&self, slot: u32) -> Option<usize> {
        self.mappings
            .iter()
            .find(|region| matches!(region.source, Source::Surface(_, owner) if owner == slot))
            .map(|region| region.base)
    }

    fn detach_surface(&mut self, slot: u32) -> Option<usize> {
        let base = self.surface_base(slot)?;
        self.detach_surface_at(base)
    }

    /// Снять поверхность по адресу. Нужна смене размера (фаза N7d): на миг у
    /// окна две поверхности с одним номером, и снять надо именно прежнюю.
    fn detach_surface_at(&mut self, base: usize) -> Option<usize> {
        let index = self
            .mappings
            .iter()
            .position(|region| region.base == base && matches!(region.source, Source::Surface(..)))?;
        let region = self.mappings.remove(index);
        let Source::Surface(phys, _) = region.source else {
            unreachable!("область только что опознана поверхностью");
        };

        // SAFETY: область принадлежит этой программе и отображена
        // `map_frames`. Кадры здесь в пул **не** уезжают — в этом всё отличие
        // от `unmap_range`; их вернёт строка ниже, одним куском и ровно раз.
        let removed =
            unsafe { self.space.unmap_range_keep(VirtAddr::new(region.base), region.pages) };
        if removed != region.pages {
            kprintln!(
                "  user        : WARNING: the window surface gave back {removed} pages of {}",
                region.pages
            );
        }
        crate::mm::frame::with(|pool| {
            // SAFETY: кадры выданы `allocate_contiguous` этого же пула, сняты с
            // отображения строкой выше, и смотреть на них больше некому: окно
            // ушло со стола раньше, чем сюда пришли.
            unsafe { pool.free_contiguous(phys, region.pages) };
        });
        Some(region.pages)
    }

    /// Вернуть системе область, выданную [`Program::mmap`] или
    /// [`Program::mmap_file`].
    ///
    /// Снять можно только область целиком и ровно ту, что выдавали: адрес в
    /// адрес, длина в длину. Кусок области снять нечем, и это сказано вслух, а
    /// не обойдено молчанием — разрезать область значит завести вместо одной
    /// записи две, а вместе с ними вопрос, что делать, когда записи кончились
    /// посреди `munmap`. Ни одному потребителю в системе это пока не нужно;
    /// понадобится — будет отдельной работой, а не побочным эффектом этой.
    fn munmap(&mut self, addr: usize, len: usize) -> Result<(), MmapError> {
        if len == 0 {
            return Err(MmapError::BadRequest);
        }
        let pages = len.div_ceil(PAGE_SIZE);
        let index = self
            .mappings
            .iter()
            .position(|region| region.base == addr && region.pages == pages)
            .ok_or(MmapError::BadRequest)?;

        // Поверхность окна этим вызовом не снимается, и сказано это не здесь, а
        // в договоре ([`user_abi::SYS_WINOPEN`]): кадры под ней принадлежат
        // окну. `unmap_range` ниже вернул бы их в пул, следующая выдача отдала
        // бы их второму владельцу — и композитор продолжал бы рисовать из чужой
        // памяти. Вернуть поверхность можно только вместе с окном.
        if matches!(self.mappings[index].source, Source::Surface(..)) {
            return Err(MmapError::BadRequest);
        }
        // Сегмент собственного образа программа не снимает: код, который
        // исполняется, и данные, по которым он ходит, уходят вместе с ней.
        if matches!(self.mappings[index].source, Source::Image(..)) {
            return Err(MmapError::BadRequest);
        }

        // SAFETY: область выдана этой же программе и записана в её таблице, то
        // есть кадры под ней принадлежат ей одной.
        let freed = unsafe { self.space.unmap_range(VirtAddr::new(addr), pages) };

        let region = self.mappings.remove(index);
        // Сколько страниц обязано было вернуться — вопрос к источнику: у
        // безымянной области отображены все, у отображённого файла только
        // подкачанные. Разница между «страниц меньше, потому что их и не
        // читали» и «страниц меньше, потому что они потерялись» — это как раз
        // то, что здесь различается.
        let owed = match &region.source {
            // Крупная страница возвращается пятьюстами двенадцатью кадрами, и
            // в счёт они идут поштучно: единица учёта здесь кадр, а не запись
            // таблицы. Поэтому число то же самое, чем бы область ни была
            // отображена, — и именно поэтому оно ничего не скрывает.
            Source::Anonymous => region.pages,
            // Сторожевая страница не отображалась никогда, значит и вернуться
            // ей неоткуда.
            Source::ThreadStack => region.pages - 1,
            Source::File(file) => file.resident.len(),
            // Сюда не приходят: поверхность и сегмент образа отсеяны проверками
            // выше. Ветки существуют затем, чтобы новый вид области нельзя было
            // завести, не ответив на вопрос, сколько кадров он обязан вернуть.
            Source::Surface(..) | Source::Image(..) => region.pages,
        };
        if freed != owed {
            kprintln!(
                "  user        : WARNING: region at {addr:#x} gave back {freed} pages of {owed}"
            );
        }
        if let Source::File(file) = &region.source {
            // Счётчики стоят раньше адреса намеренно: адрес здесь — примета
            // для человека, а числа читает стенд, и число, стоящее сразу за
            // неизменной подстрокой, он умеет доставать, а из середины строки —
            // нет.
            kprintln!(
                "  user        : file mapping released, {} reads and {} evictions, at {addr:#x}",
                file.reads,
                file.evictions
            );
        }
        Ok(())
    }

    /// Подобрать место под область в `len` байт и проверить пределы.
    ///
    /// Общее начало обоих `mmap`: до того, как выяснится, чем область будет
    /// наполнена, вопросы к ней одни и те же.
    fn reserve(&self, len: usize, align: usize) -> Result<(usize, usize), MmapError> {
        if len == 0 {
            return Err(MmapError::BadRequest);
        }
        let pages = len.div_ceil(PAGE_SIZE);
        // Длина, от которой округление вверх переполнило бы адрес, — это не
        // «слишком много памяти», а бессмыслица, и отвечать на неё пределом
        // значило бы обещать, что при других обстоятельствах столько дадут.
        let Some(bytes) = pages.checked_mul(PAGE_SIZE) else {
            return Err(MmapError::BadRequest);
        };
        if bytes > MMAP_MAX_BYTES {
            return Err(MmapError::Limit);
        }
        if self.mappings.len() == MAX_MAPPINGS {
            return Err(MmapError::Limit);
        }
        let base = self.find_gap(bytes, align).ok_or(MmapError::Limit)?;
        Ok((base, pages))
    }

    /// Найти в области запроса свободное место под `bytes` байт.
    ///
    /// Первое подходящее снизу, а не следующее за последним выданным. Разница
    /// видна там, где программа берёт и отдаёт по кругу: счётчик, ползущий
    /// вверх, упёрся бы в конец области, ни разу не заняв её целиком, — то есть
    /// предел на задачу считал бы не занятую память, а прожитую жизнь.
    fn find_gap(&self, bytes: usize, align: usize) -> Option<usize> {
        // Начало области уже кратно двум мегабайтам ([`MMAP_BASE`]), так что
        // первый кандидат выравнивания не требует. Требуют следующие: области
        // укладываются вплотную, и конец предыдущей приходится где угодно.
        let mut candidate = MMAP_BASE.next_multiple_of(align);
        for region in &self.mappings {
            if region.base >= candidate && region.base - candidate >= bytes {
                return Some(candidate);
            }
            let end = region.base + region.pages * PAGE_SIZE;
            candidate = candidate.max(end).next_multiple_of(align);
        }
        (MMAP_BASE + MMAP_MAX_BYTES)
            .checked_sub(candidate)
            .is_some_and(|room| room >= bytes)
            .then_some(candidate)
    }

    /// Записать область в таблицу, сохранив порядок по адресу.
    fn remember(&mut self, region: Mapping) {
        let at = self
            .mappings
            .iter()
            .position(|other| other.base > region.base)
            .unwrap_or(self.mappings.len());
        self.mappings.insert(at, region);
    }

    /// Наполнить страницу, на которой программа отказала.
    ///
    /// Возвращает `true`, если после этого по адресу есть что читать. `false` —
    /// это «за такой адрес никто не отвечает», обычный ответ, а не поломка:
    /// разыменованный ноль и указатель мимо области выглядят здесь одинаково.
    ///
    /// Читается **ровно одна страница**, а не окрестность. Упреждающее чтение
    /// напрашивается (последовательный проход — главный случай) и сюда не
    /// попало намеренно: у блока ext2 в корневом разделе размер ровно страницы,
    /// то есть одна подкачка — это один запрос к диску и ни одного лишнего
    /// байта, а угадывать за программу, куда она пойдёт дальше, — работа с
    /// собственными измерениями, которых у этой фазы нет.
    /// Первая половина отказа — под замком: чем наполнять страницу.
    ///
    /// Возвращает откуда читать, сколько байт (остальное — нули), с какими
    /// правами отобразить и чистая ли страница после этого (то есть можно ли
    /// её потом выбросить и прочитать заново). `None` — «за такой адрес никто
    /// не отвечает», обычный ответ, а не поломка: разыменованный ноль и
    /// указатель мимо области выглядят здесь одинаково.
    ///
    /// Само чтение идёт **без** замка ([`fault_in`]): под ним нельзя спать, а
    /// путь чтения спит, и вторая программа, отказавшая в это время, ждала бы
    /// не носитель, а чужой замок.
    fn fault_plan(&self, page_addr: usize, write: bool) -> Option<FaultPlan> {
        let region = self.mappings.iter().find(|region| {
            page_addr >= region.base && page_addr < region.base + region.pages * PAGE_SIZE
        })?;
        let page = (page_addr - region.base) / PAGE_SIZE;
        match &region.source {
            Source::File(file) => {
                // Отображение только на чтение, и попытка записи — не отказ
                // подкачки, а именно то, о чём договор предупреждал.
                if write {
                    return None;
                }
                Some(FaultPlan {
                    node: Arc::clone(&file.node),
                    offset: file.offset + (page as u64) * PAGE_SIZE as u64,
                    want: PAGE_SIZE,
                    flags: PageFlags::READ | PageFlags::USER,
                    clean: true,
                })
            }
            Source::Image(image) => {
                // Запись в сегмент кода или данных только на чтение — ошибка
                // программы, а не повод подложить ей страницу.
                if write && !image.flags.contains(PageFlags::WRITE) {
                    return None;
                }
                let start = page * PAGE_SIZE;
                // Файловая часть сегмента кончается где угодно внутри
                // страницы; всё, что за ней, обязано быть нулём (`.bss`) — а
                // не тем, что лежит в файле дальше.
                Some(FaultPlan {
                    node: Arc::clone(&image.node),
                    offset: image.offset + start as u64,
                    want: image.file_bytes.saturating_sub(start).min(PAGE_SIZE),
                    flags: image.flags,
                    clean: !image.flags.contains(PageFlags::WRITE),
                })
            }
            // Безымянная область отображена целиком с самого начала, поверхность
            // окна — тоже. Отказ внутри них означает, что таблицы разошлись с
            // этой записью, и молчать об этом нельзя: снять программу
            // правильнее, чем тихо подложить ей чистую страницу вместо той, что
            // потерялась.
            // Отказ в стеке потока — это переполнение, пришедшее в сторожевую
            // страницу, и подкладывать ему память значило бы отменить сторожа.
            Source::Anonymous | Source::Surface(..) | Source::ThreadStack => None,
        }
    }

    /// Вторая половина отказа — снова под замком: отобразить прочитанный
    /// кадр и учесть его. `false` — области уже нет или отобразить не вышло;
    /// кадр тогда возвращает вызывающий.
    fn fault_commit(&mut self, page_addr: usize, frame: PhysAddr, plan: &FaultPlan) -> bool {
        let Some(index) = self.mappings.iter().position(|region| {
            page_addr >= region.base && page_addr < region.base + region.pages * PAGE_SIZE
        }) else {
            return false;
        };
        let base = self.mappings[index].base;
        let page = (page_addr - base) / PAGE_SIZE;

        // SAFETY: кадр наш, адрес лежит в области этой программы, и страницы
        // под ним сейчас нет — с неё и начался отказ.
        if unsafe { self.space.map(VirtAddr::new(page_addr), frame, plan.flags) }.is_err() {
            return false;
        }

        let (what, resident, reads, evictions) = match &mut self.mappings[index].source {
            Source::File(file) => ("file mapping", &mut file.resident, &mut file.reads, &mut file.evictions),
            Source::Image(image) => {
                ("program image", &mut image.resident, &mut image.reads, &mut image.evictions)
            }
            _ => return true,
        };
        *reads += 1;

        // Счётчик подкачек виден в журнале, и не только ради отчёта: по нему
        // отличают «медленно» от «по кругу». Обход файла вперёд обязан стоить
        // ровно одну подкачку на страницу, и если строк приходит больше, чем в
        // файле страниц, значит вытеснение выбрасывает то, что ещё нужно, —
        // а снаружи это выглядит просто как долгая работа.
        if *reads % PROGRESS_EVERY == 0 {
            kprintln!("  user        : {what} paging, {} reads and {} evictions", *reads, *evictions);
        }

        // Страница на запись — своя с этого момента: в файле её нет в том виде,
        // в каком её оставит программа, и выбрасывать её нельзя.
        if !plan.clean {
            return true;
        }
        resident.push_back(page);

        if resident.len() > RESIDENT_MAX_PAGES {
            // Место кончилось — выбрасываем самую давнюю. Страница чиста
            // (отображение на чтение), поэтому «выбросить» — это снять и
            // вернуть кадр: ни записи на диск, ни согласования ни с кем.
            if let Some(old) = resident.pop_front() {
                *evictions += 1;
                let victim = VirtAddr::new(base + old * PAGE_SIZE);
                // SAFETY: страница принадлежит этой области, то есть этой
                // программе; понадобится — прочитается с диска заново.
                unsafe { self.space.unmap_range(victim, 1) };
            }
        }

        true
    }
}

/// Чем наполнить отказавшую страницу — ответ [`Program::fault_plan`].
struct FaultPlan {
    node: Arc<dyn Node>,
    offset: u64,
    want: usize,
    flags: PageFlags,
    clean: bool,
}

/// Взять кадр, не трогая запас, который ядро держит для себя.
///
/// Отдельно от [`take_frame`]: тот отвечает на «дай кадр под образ программы»,
/// где отказ означает, что программа не запустится, а этот — на «дай кадр под
/// подкачку», где отказ означает, что подкачка не состоялась. Второе случается
/// на живой системе штатно, и запас существует именно для того, чтобы в этот
/// момент у ядра ещё оставалось, чем работать.
fn take_frame_reserved() -> Option<PhysAddr> {
    crate::mm::frame::with(|frames| {
        if frames.stats().free <= RESERVE_FRAMES {
            return None;
        }
        frames.allocate()
    })
    .flatten()
}

/// Программы по слотам задач планировщика.
///
/// Таблица, а не поле задачи, и это разделение обязанностей: планировщику от
/// программы нужны три машинных числа ([`sched::UserMachine`]), которые он
/// обязан переставлять сам, а всё остальное — дело этого модуля, и знать о нём
/// планировщику незачем.
static PROGRAMS: Mutex<[Option<Arc<Mutex<Program>>>; sched::MAX_TASKS]> =
    Mutex::new([const { None }; sched::MAX_TASKS]);

/// Исполняется ли прямо сейчас код третьего кольца в этом слоте.
///
/// По слоту, а не в [`Program`], и это первая половина разделения процесса и
/// потока. Ответ на вопрос «мы сейчас в третьем кольце» принадлежит **задаче**:
/// потоков у процесса будет несколько, и один может стоять в системном вызове,
/// пока другой исполняет свой код.
///
/// Атомик, а не поле под локом, и это важнее, чем кажется. Спрашивает отсюда
/// обработчик отказа страницы — тому нельзя ни ждать, ни засыпать, а прежний
/// ответ брал спящий лок таблицы программ **до** разрешения прерываний.
static IN_USER: [AtomicBool; sched::MAX_TASKS] =
    [const { AtomicBool::new(false) }; sched::MAX_TASKS];

/// Процесс исполняющейся задачи — ссылкой, а не заимствованием.
///
/// Лок таблицы держится ровно на время клонирования ссылки. Это и есть цена
/// разделения: раньше лок таблицы удерживался на всё время работы с программой,
/// то есть **каждый системный вызов каждой задачи** выстраивался в одну
/// очередь на единственном локе.
fn current_process() -> Option<Arc<Mutex<Program>>> {
    let slot = sched::current_slot();
    let table = PROGRAMS.lock();
    table.get(slot).and_then(Option::as_ref).cloned()
}

/// Сделать что-нибудь с программой текущей задачи.
///
/// `None`, если задача программы не исполняет, — например, когда системный
/// вызов пришёл неизвестно откуда.
pub fn with_current<R>(f: impl FnOnce(&mut Program) -> R) -> Option<R> {
    // Порядок локов всегда один: таблица, потом процесс, — и второй берётся
    // после того, как первый отпущен. Два лока одновременно не удерживаются
    // нигде, поэтому вопроса об их порядке не возникает вовсе.
    let process = current_process()?;
    let mut program = process.lock();
    Some(f(&mut program))
}

/// Сколько байт поверхности окна ядро согласно выдать.
///
/// Четыре мегабайта — это ровно 1024×1024 точки. Предел здесь не про адреса, а
/// про кадры: поверхность выдаётся **подряд**, целиком и сразу, и просьба
/// размером с экран в шестнадцать миллионов точек означала бы шестьдесят
/// четыре мегабайта непрерывной памяти у одной программы — кусок, которого на
/// раздробленной памяти может не найтись вовсе.
const WINDOW_MAX_BYTES: usize = 4 * 1024 * 1024;

/// Сколько ждать занятый стол, снимая окно за умершей программой.
///
/// Две секунды — заведомо больше самой долгой сборки кадра (сотни миллисекунд в
/// отладочной сборке на 1920×1080). Ждём **сном**, а не уступкой процессора:
/// уступка возвращается к нам сразу же и на занятом столе превращается в
/// холостой круг, а не в ожидание.
const RECLAIM_WAIT_MS: u64 = 2_000;

/// Пауза между попытками снять окно.
const RECLAIM_PAUSE_MS: u64 = 20;

/// Почему окно программе не досталось.
#[derive(Debug, Clone, Copy)]
pub enum WindowError {
    /// Размер бессмысленный или больше [`WINDOW_MAX_BYTES`].
    BadSize,
    /// Задача не исполняет программы.
    NoProgram,
    /// Памяти под поверхность не нашлось.
    Memory(MmapError),
    /// Стол окна не дал.
    Desktop(crate::ui::WindowError),
    /// Окон у программы уже [`user_abi::MAX_WINDOWS`].
    TooMany,
}

/// Завести окно текущей программе. Возвращает адрес поверхности в её памяти и
/// номер окна у программы.
///
/// # Почему здесь два захода под лок таблицы программ, а не один
///
/// Потому что между ними работает стол, а он собирает кадр — сотни миллисекунд
/// в отладочной сборке. Лок таблицы программ ждёт **каждый** системный вызов
/// **каждой** задачи, и удерживать его на время перерисовки значило бы
/// останавливать систему на каждое открытое окно. Поэтому память выдаётся под
/// локом, окно заводится без него, а неудача откатывается третьим заходом.
///
/// Гонки между заходами нет, и это не везение: между ними программа стоит
/// внутри этого самого вызова, а её области трогает только она.
pub fn open_window(title: &str, width: u32, height: u32) -> Result<(usize, u32), WindowError> {
    let pages = surface_pages(width, height)?;

    let (slot, base, phys) = with_current(|program| {
        let slot = program.free_window_slot().ok_or(WindowError::TooMany)?;
        let (base, phys) = program.attach_surface(pages, slot).map_err(WindowError::Memory)?;
        Ok((slot, base, phys))
    })
    .ok_or(WindowError::NoProgram)??;

    // SAFETY: кадры выданы подряд, живы, пока живо окно, и видны ядру через
    // прямое отображение. Второй ссылки на них нет: программа получила адрес
    // строкой выше и всё ещё стоит в этом вызове, а стол увидит поверхность
    // только после того, как она уедет в окно.
    let surface = unsafe {
        mini_ui::Surface::from_raw(phys.to_direct_map().as_mut_ptr::<u32>(), width, height)
    };
    let task = sched::current().as_u32();
    let opened = match surface {
        Some(surface) => crate::ui::open_window(task, slot, title, surface),
        None => Err(crate::ui::WindowError::NoMemory),
    };
    if let Err(err) = opened {
        // Окна не будет — значит и поверхности быть не должно. Оставить её
        // значило бы отдать программе память, которой она не просила, и
        // держать кадры до самого её конца.
        with_current(|program| program.detach_surface(slot));
        return Err(WindowError::Desktop(err));
    }
    Ok((base, slot))
}

/// Сколько страниц под поверхность такого размера; бессмысленный размер или
/// больше [`WINDOW_MAX_BYTES`] — отказ.
fn surface_pages(width: u32, height: u32) -> Result<usize, WindowError> {
    if width == 0 || height == 0 {
        return Err(WindowError::BadSize);
    }
    let bytes = (width as usize)
        .checked_mul(height as usize)
        .and_then(|points| points.checked_mul(4))
        .ok_or(WindowError::BadSize)?;
    if bytes > WINDOW_MAX_BYTES {
        return Err(WindowError::BadSize);
    }
    Ok(bytes.div_ceil(PAGE_SIZE))
}

/// Сменить размер окна `slot` текущей программы (фаза N7d). Возвращает адрес
/// новой поверхности; прежняя снята.
///
/// Порядок тот же, что у открытия и закрытия: новые кадры выдаются под локом
/// таблицы программ, стол переходит на них без лока, и только потом снимаются
/// прежние — пока стол держит окно, композитор вправе читать его пиксели. При
/// отказе снимается новая поверхность, а окно остаётся прежним.
pub fn resize_window(slot: u32, width: u32, height: u32) -> Result<usize, WindowError> {
    let pages = surface_pages(width, height)?;
    let (old, base, phys) = with_current(|program| {
        let old = program
            .surface_base(slot)
            .ok_or(WindowError::Desktop(crate::ui::WindowError::NoWindow))?;
        let (base, phys) = program.attach_surface(pages, slot).map_err(WindowError::Memory)?;
        Ok((old, base, phys))
    })
    .ok_or(WindowError::NoProgram)??;

    // SAFETY: как в [`open_window`] — кадры выданы подряд, живы, пока живо окно,
    // и второй ссылки на них нет, пока программа стоит в этом вызове.
    let surface = unsafe {
        mini_ui::Surface::from_raw(phys.to_direct_map().as_mut_ptr::<u32>(), width, height)
    };
    let task = sched::current().as_u32();
    let resized = match surface {
        Some(surface) => crate::ui::resize_window(task, slot, surface),
        None => Err(crate::ui::WindowError::NoMemory),
    };
    let dropped = if resized.is_ok() { old } else { base };
    with_current(|program| program.detach_surface_at(dropped));
    resized.map_err(WindowError::Desktop)?;
    Ok(base)
}

/// Показать на экране то, что программа нарисовала в окне `slot`. `None` — всё
/// окно.
pub fn commit_window(slot: u32, area: Option<mini_ui::Rect>) -> Result<(), WindowError> {
    crate::ui::commit_window(sched::current().as_u32(), slot, area).map_err(WindowError::Desktop)
}

/// Забрать событие окна `slot` текущей программы.
pub fn window_event(slot: u32) -> Option<user_abi::WinEvent> {
    crate::ui::next_window_event(sched::current().as_u32(), slot)
}

/// Закрыть окно `slot` текущей программы и вернуть его память.
pub fn close_window(slot: u32) -> Result<(), WindowError> {
    // Сначала окно уходит со стола, и только потом освобождаются кадры: пока
    // окно на столе, композитор вправе читать его пиксели.
    crate::ui::close_window(sched::current().as_u32(), slot).map_err(WindowError::Desktop)?;
    with_current(|program| program.detach_surface(slot)).ok_or(WindowError::NoProgram)?;
    Ok(())
}

/// Снять окно программы, которая его не закрыла.
///
/// Зовётся из [`run`] **до** того, как пространство программы будет разобрано, и
/// в этом весь смысл вызова. Разбор освобождает поддерево окна рекурсивно, не
/// различая, чьи кадры под ним лежат, — а поверхность принадлежит не программе.
///
/// Заметить смерть задачи позже нельзя в принципе, и это стоит сказать прямо:
/// [`sched::exit_current_with`] помечает задачу законченной уже после того, как
/// `run` вернул пространство в пул. Тот, кто взялся бы «обойти мёртвые задачи и
/// убрать их окна», опоздал бы всегда — кадры поверхности к этому времени уже
/// выданы кому-то другому, а композитор всё ещё из них рисует.
fn reclaim_window() {
    // Первый вопрос — **программе**, а не столу, и это исправление, а не
    // предусмотрительность. Сначала здесь стоял безусловный поход к столу, и
    // первый же прогон напечатал «окно задачи #10 потеряно» про задачу, у
    // которой окна никогда не было: путь выхода обычного `ls` натыкался на
    // стол, занятый сборкой кадра, и жаловался на утечку несуществующего окна.
    if with_current(|program| program.has_surface()) != Some(true) {
        return;
    }
    // Окон у программы может быть несколько (фаза N7c) — снимается каждое.
    let slots = with_current(|program| program.window_slots()).unwrap_or(0);
    for slot in 0..user_abi::MAX_WINDOWS {
        if slots & (1 << slot) != 0 {
            reclaim_slot(slot);
        }
    }
}

/// Снять одно окно умершей программы — см. [`reclaim_window`].
fn reclaim_slot(slot: u32) {
    let task = sched::current().as_u32();
    let deadline = crate::time::uptime_ms().saturating_add(RECLAIM_WAIT_MS);
    loop {
        match crate::ui::close_window(task, slot) {
            Ok(()) => break,
            // Окна нет вовсе: графики на машине не было, а поверхность у
            // программы всё равно есть. Кадры возвращаются как обычно.
            Err(crate::ui::WindowError::NoWindow | crate::ui::WindowError::NoDesktop) => break,
            // Стол занят сборкой кадра — подождём.
            Err(_) => {}
        }
        if crate::time::uptime_ms() >= deadline {
            // Кадры **не** освобождаются: окно всё ещё на столе, и вернуть их
            // в пул значило бы отдать их другому владельцу прямо под рукой
            // композитора. Громкая утечка лучше молчаливой порчи памяти —
            // поэтому строка кричит, а кадры остаются на месте.
            kprintln!(
                "  user        : WARNING: the desktop stayed busy; the window of {} is leaked",
                sched::current()
            );
            return;
        }
        sched::sleep_ms(RECLAIM_PAUSE_MS);
    }

    let Some(Some(pages)) = with_current(|program| program.detach_surface(slot)) else {
        return;
    };
    kprintln!(
        "  user        : reclaimed {pages} frame(s) of the window of {}",
        sched::current()
    );
}

/// Корень таблиц страниц программы текущей задачи.
#[must_use]
