//! Адресное пространство программы: клон корня ядра с окном под неё.
//!
//! # Почему клон, а не пустое дерево
//!
//! Ядро исполняется в тех же таблицах, по которым транслируются адреса
//! программы: на x86-64 `CR3` описывает обе половины сразу, на AArch64 образ
//! ядра identity-отображён через `TTBR0_EL1` — тот самый регистр, который здесь
//! и переключается. Пустое дерево выбило бы из-под ядра его собственный код:
//! первая же ловушка из программы ушла бы по неотображённому адресу и стала бы
//! не системным вызовом, а тройной ошибкой.
//!
//! Поэтому корень программы — побайтовая копия корня ядра, в которой обнулена
//! ровно одна запись: та, под которой лежит окно программы. Изоляцию это не
//! ослабляет: записи ядра не помечены доступными из третьего кольца (EL0), и
//! отказывает в доступе блок управления памятью, а не проверка в коде.
//!
//! # Что отсюда следует для освобождения
//!
//! Всё, что принадлежит **программе**, лежит под одной записью корня. Поэтому
//! разбор пространства — это обход одного поддерева, а не поиск «наших» страниц
//! среди чужих. Ядерные записи — копии, таблицы под ними общие с ядром, и
//! трогать их нельзя.
//!
//! Снятие отдельной страницы ([`Space::unmap_range`]) появилось позже и уборке
//! ничего не должно: оно обслуживает `SYS_MUNMAP`, где память отдаёт **живая**
//! программа. Разбор при выходе к нему не обращается и обходится без него по
//! той же причине, что и раньше, — ему нечего искать.
//!
//! Освобождение выполняет [`Drop`], а не отдельный вызов, и это важнее, чем
//! кажется: программу снимают два разных пути — штатное завершение и отказ, —
//! и второй возвращается в ядро не оттуда, откуда уходил. Уборка, написанная
//! в конце удачного пути, на втором просто не исполнилась бы.

use crate::mm::{AddressSpace, FrameAllocator, MapError, PAGE_SIZE, PageFlags, PhysAddr, VirtAddr};
use crate::{arch, kprintln};

/// Номер уровня корневой таблицы в нумерации [`VirtAddr::table_index`].
///
/// Три на обеих архитектурах: четыре уровня по девять бит при грануле 4 КиБ —
/// это и PML4 на x86-64, и L0 в терминах ARM.
const ROOT_LEVEL: usize = 3;

/// Запись корневой таблицы, под которой живёт программа.
///
/// Считается из [`super::WINDOW_BASE`], а не пишется числом: окно и слот обязаны
/// соответствовать друг другу, а вычисленное значение разъехаться с базой не
/// может. Одной записи корня хватает на 512 ГиБ — вся память программы
/// помещается в неё с колоссальным запасом, и это не расточительство, а условие
/// дешёвого освобождения (см. доккомментарий модуля).
pub const WINDOW_SLOT: usize = VirtAddr::new(super::WINDOW_BASE).table_index(ROOT_LEVEL);

/// Адресное пространство одной программы.
pub struct Space {
    root: PhysAddr,
}

impl Space {
    /// Создать пространство поверх ядерного.
    pub fn new() -> Result<Self, MapError> {
        // SAFETY: таблицы ядра активны — пользовательские программы
        // запускаются много позже `take_over_memory`, и на них же исполняется
        // этот код.
        let root = crate::mm::frame::with(|frames| unsafe {
            arch::new_user_space(WINDOW_SLOT, frames)
        })
        // Аллокатора кадров нет — значит взять кадр под корень неоткуда, что
        // для вызывающего неотличимо от исчерпания пула.
        .unwrap_or(Err(MapError::OutOfFrames))?;

        Ok(Self { root })
    }

    /// Отобразить страницу в память программы.
    ///
    /// # Safety
    ///
    /// `phys` обязан быть кадром, выделенным под эту программу и не
    /// принадлежащим больше никому: при разборе пространства он вернётся в пул
    /// вместе с остальным окном.
    pub unsafe fn map(
        &mut self,
        virt: VirtAddr,
        phys: PhysAddr,
        flags: PageFlags,
    ) -> Result<(), MapError> {
        // SAFETY: корень принадлежит этому объекту и жив, пока жив он; таблицы
        // ядра активны, и записи правятся через прямое отображение.
        let mut space = unsafe { arch::space_at(self.root) };
        crate::mm::frame::with(|frames| {
            // SAFETY: адрес лежит в окне программы, которое ядро ни подо что
            // другое не использует, — увести из-под работающего кода это
            // отображение не может.
            unsafe { space.map(virt, phys, flags, frames) }
        })
        .unwrap_or(Err(MapError::OutOfFrames))
    }

    /// Чем отображён адрес в этом пространстве.
    #[must_use]
    pub fn translate(&self, virt: VirtAddr) -> Option<(PhysAddr, PageFlags)> {
        arch::translate(self.root, virt)
    }

    /// Физический адрес корневой таблицы — то, что уезжает в `CR3`/`TTBR0_EL1`.
    #[must_use]
    pub fn root(&self) -> PhysAddr {
        self.root
    }

    /// Занять `pages` страниц подряд и отобразить их с адреса `base`.
    ///
    /// Работа идёт **порциями** по [`CHUNK_PAGES`] страниц, и каждая порция
    /// берёт замок пула заново. Причина не в экономии, а в том, что
    /// [`crate::sync::SpinLock`] запрещает прерывания на всё время удержания:
    /// одна порция на весь запрос означала бы для 256 МиБ несколько секунд с
    /// закрытыми прерываниями — потерянные тики таймера, отставшие часы,
    /// пропущенный ввод и молчащая сеть. Ничего из этого не выглядит как
    /// ошибка памяти, и искали бы причину долго.
    ///
    /// Обратная крайность — брать замок на каждую страницу — стоила бы 131 072
    /// захватов на те же 256 МиБ. [`CHUNK_PAGES`] стоит между ними.
    ///
    /// **Отказ не оставляет программе половины памяти.** Всё, что успело
    /// отобразиться, снимается и возвращается в пул: программа получает ошибку,
    /// а не диапазон, действительный до середины.
    ///
    /// Промежуточные таблицы, достроенные по дороге, при этом **остаются** — их
    /// вернёт разбор пространства при выходе. То есть неудавшийся `mmap` стоит
    /// программе несколько страниц до конца её жизни, и на проверку фазы это не
    /// влияет только потому, что считают её после выхода.
    ///
    /// Ядру оставляется [`super::RESERVE_FRAMES`] кадров: программа, попросившая
    /// всю память, обязана получить отказ, а не забрать с собой машину.
    ///
    /// # Safety
    ///
    /// `base` обязан лежать в окне программы и не пересекаться с тем, что уже
    /// отображено: повторное отображение занятого адреса — это потерянный кадр.
    pub unsafe fn map_anon(
        &mut self,
        base: VirtAddr,
        pages: usize,
        flags: PageFlags,
    ) -> Result<(), MapError> {
        let root = self.root;
        // SAFETY: корень принадлежит этому объекту и жив, пока жив он; записи
        // правятся через прямое отображение, которое есть и в дереве программы
        // — оно копия ядерного.
        let mut space = unsafe { arch::space_at(root) };

        let mut done = 0;
        while done < pages {
            let want = CHUNK_PAGES.min(pages - done);

            let (made, failure) = crate::mm::frame::with(|frames| {
                let mut made = 0;
                while made < want {
                    let virt = VirtAddr::new(base.as_usize() + (done + made) * PAGE_SIZE);

                    // Запас проверяется на каждой странице, а не один раз до
                    // цикла: отображение само берёт кадры под промежуточные
                    // таблицы, и посчитать их заранее значило бы угадывать,
                    // сколько уровней придётся достроить.
                    if frames.stats().free <= super::RESERVE_FRAMES {
                        return (made, Some(MapError::OutOfFrames));
                    }
                    let Some(phys) = frames.allocate() else {
                        return (made, Some(MapError::OutOfFrames));
                    };
                    // SAFETY: кадр только что выдан аллокатором и не принадлежит
                    // больше никому; адрес лежит в окне программы.
                    if let Err(err) = unsafe { space.map(virt, phys, flags, frames) } {
                        // Кадр отображён не был — вернуть его обязаны мы, иначе
                        // он не достанется ни программе, ни пулу.
                        // SAFETY: кадр выдан этим же аллокатором и никуда не ушёл.
                        unsafe { frames.free(phys) };
                        return (made, Some(err));
                    }
                    made += 1;
                }
                (made, None)
            })
            // Аллокатора кадров нет — для вызывающего это неотличимо от
            // исчерпания пула.
            .unwrap_or((0, Some(MapError::OutOfFrames)));

            done += made;

            if let Some(err) = failure {
                // SAFETY: снимается ровно то, что отображено этим вызовом.
                unsafe { self.unmap_range(base, done) };
                return Err(err);
            }
        }

        Ok(())
    }

    /// Снять `pages` страниц с адреса `base` и вернуть их кадры в пул.
    ///
    /// Возвращает, сколько кадров действительно вернулось. Меньше `pages`
    /// означает дыру в диапазоне — сама по себе она не ошибка (страница могла
    /// не отобразиться), но и молчать о ней нельзя: это число печатает
    /// вызывающий.
    ///
    /// Порциями по той же причине, что и [`Space::map_anon`], и это не
    /// симметрия ради симметрии: вернуть 256 МиБ — столько же обращений к пулу,
    /// сколько их занять, и прерывания на это время закрылись бы ровно так же.
    ///
    /// # Safety
    ///
    /// Диапазон обязан принадлежать этой программе и не быть ничем другим:
    /// кадры уезжают в пул, и второй владелец получил бы чужую память.
    pub unsafe fn unmap_range(&mut self, base: VirtAddr, pages: usize) -> usize {
        let root = self.root;
        let mut freed = 0;
        let mut done = 0;

        while done < pages {
            let want = CHUNK_PAGES.min(pages - done);
            freed += crate::mm::frame::with(|frames| {
                let mut got = 0;
                for index in 0..want {
                    let virt = VirtAddr::new(base.as_usize() + (done + index) * PAGE_SIZE);
                    // SAFETY: дерево принадлежит этому объекту; кадр под адресом
                    // принадлежит одной этой программе — условие делегировано выше.
                    if let Some(phys) = unsafe { arch::unmap(root, virt) } {
                        // SAFETY: кадр пришёл из этого же дерева, ссылок на него
                        // в таблицах не осталось, а TLB сброшен внутри `unmap`.
                        unsafe { frames.free(phys) };
                        got += 1;
                    }
                }
                got
            })
            .unwrap_or(0);
            done += want;
        }

        freed
    }
}

/// Сколько страниц обрабатывается за один захват замка пула кадров.
///
/// Шестьдесят четыре, то есть четверть мегабайта за раз. Число выбрано не
/// измерением, а порядком величин, и оба края названы в
/// [`Space::map_anon`]: порция должна быть достаточно мала, чтобы прерывания
/// не оставались закрытыми заметное время, и достаточно велика, чтобы захват
/// замка не стал дороже самой работы.
const CHUNK_PAGES: usize = 64;

impl Drop for Space {
    fn drop(&mut self) {
        // SAFETY: пространство больше не активно — `run` возвращает процессор
        // на таблицы ядра сразу после выхода из программы, на обоих путях; сам
        // корень выдан `new_user_space` и никем не разделяется.
        let freed = crate::mm::frame::with(|frames| unsafe {
            arch::free_user_space(self.root, WINDOW_SLOT, frames)
        });

        match freed {
            Some((tables, pages)) => kprintln!(
                "  user        : space released, {pages} pages and {tables} tables returned"
            ),
            // Единственная причина — аллокатор кадров недоступен, то есть
            // система уже разбирается на части. Молчать всё равно нельзя: это
            // ровно та утечка, ради отсутствия которой всё пространство и
            // строилось поверх одной записи корня.
            None => kprintln!("  user        : WARNING: no frame allocator, the space is leaked"),
        }
    }
}

/// Вправе ли исполняющаяся программа обратиться к `[ptr, ptr + len)` так, как
/// описано в `need`.
///
/// # Зачем этого мало — проверить попадание в окно
///
/// Окно программы задано константами, и [`super::owns`] отвечает на вопрос «мог
/// бы этот адрес принадлежать программе». Но ядру нужен другой ответ: «отдаст
/// ли MMU эту страницу программе на такое обращение». Разница видна на записи.
/// Ядро пишет в память программы **своими** привилегиями, и страница, доступная
/// программе только на чтение, для ядра всё равно записываемая — на x86-64 её
/// защищает `CR0.WP`, но защищает отказом, а отказ в ядре означает остановку
/// машины. То есть программа, передавшая в `read` адрес своего же кода, могла бы
/// уронить систему. Проверка по таблицам эту дыру закрывает: право спрашивается
/// у той же записи, у которой его спросил бы процессор.
///
/// Проверяется каждая страница диапазона: непрерывный в виртуальных адресах
/// буфер запросто пересекает границу с другими правами.
#[must_use]
pub fn user_can(ptr: usize, len: usize, need: PageFlags) -> bool {
    if len == 0 {
        return true;
    }
    if !super::owns(ptr, len) {
        return false;
    }
    let Some(root) = super::current_space_root() else {
        // Программы у этой задачи нет — значит нет и памяти, которая могла бы
        // ей принадлежать. Такой вызов означает испорченное состояние, и
        // единственный безопасный ответ на него — «нельзя».
        return false;
    };

    let first = ptr / PAGE_SIZE;
    let last = (ptr + len - 1) / PAGE_SIZE;
    for page in first..=last {
        let virt = VirtAddr::new(page * PAGE_SIZE);

        let flags = match arch::translate(root, virt) {
            Some((_, flags)) => flags,
            // Страницы нет — но это больше не обязательно отказ. С фазы 41
            // программа вправе держать адрес, за которым лежит файл, а не
            // память, и «ещё не прочитано» — не то же самое, что «не твоё».
            //
            // Подкачивает **ядро, до обращения**, а не отказ страницы во время
            // него, и это главное решение здесь. Ядро пишет в память программы
            // с правами кольца ноль: его собственный отказ страницы не снимает
            // программу, а останавливает машину. Поэтому буфер приводится в
            // порядок заранее, там, где на неудачу ещё можно ответить кодом
            // ошибки, — и ловушка «отказ страницы внутри системного вызова»
            // перестаёт существовать, вместо того чтобы обрабатываться.
            None => {
                if !super::fault_in(virt.as_usize(), need.contains(PageFlags::WRITE), false) {
                    return false;
                }
                match arch::translate(root, virt) {
                    Some((_, flags)) => flags,
                    // Подкачка сказала «сделано», а страницы нет. Верить ей на
                    // слово нельзя: соврала бы она — ядро следующей же строкой
                    // писало бы в неотображённую память.
                    None => return false,
                }
            }
        };

        if !flags.contains(need) || !flags.contains(PageFlags::USER) {
            return false;
        }
    }
    true
}

/// Отображён ли адрес в пространстве **ядра**.
///
/// Нужно ровно для одного утверждения, и утверждение это — главный итог фазы:
/// память программы в таблицах ядра отсутствует. Проверять его обходом таблиц, а
/// не рассуждением, стоит потому, что рассуждение здесь легко оказывается
/// верным для одной архитектуры и неверным для другой.
#[must_use]
pub fn kernel_maps(virt: VirtAddr) -> Option<(PhysAddr, PageFlags)> {
    arch::translate(arch::kernel_root(), virt)
}
