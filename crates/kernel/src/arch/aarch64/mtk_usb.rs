//! Контроллер USB телефона в режиме **устройства**.
//!
//! # Зачем он нужен раньше всего остального
//!
//! Потому что у аппарата нет линии, и журнал существует только на экране —
//! доли секунды, пока его не закроет рабочий стол. Каждый вопрос к машине стоит
//! прошивки и снимка экрана, сделанного руками; за один вечер таких кругов
//! вышло полтора десятка. Для задачи, сузившейся до одной цепочки, это неверная
//! форма цикла.
//!
//! Телефон, представившийся компьютеру устройством, отдаёт журнал по тому же
//! кабелю, который и так воткнут. Опыт занимает секунды вместо минут, и человек
//! в нём не участвует.
//!
//! Это же первая половина сети: поверх работающего USB поднимется сетевой
//! интерфейс, и на телефон можно будет зайти по SSH.
//!
//! # Чем притворяться
//!
//! Загрузчиком в режиме fastboot — тем самым `18D1:D00D`. Не из хитрости: на
//! машине Романа драйвер для него уже установлен и проверен работой, программа
//! `fastboot` уже есть, а её протокол — текстовые команды по обычным точкам
//! приёма и передачи. Всё остальное потребовало бы ставить драйвер под Windows,
//! то есть решать одну задачу, чтобы взяться за другую.
//!
//! # Что здесь уже есть
//!
//! Приведение физического уровня в чувство и подключение к шине. Этого хватает
//! на первый вопрос — видит ли компьютер, что к нему что-то подключили. Разбор
//! запросов и сам протокол пишутся следующим шагом: пока не доказано, что
//! провода живы, писать поверх них нечего.
//!
//! Числа взяты из открытого драйвера MediaTek для этого кристалла
//! (`drivers/misc/mediatek/usb20/mt6765/usb20_phy.c`), а не выведены.

use core::ptr;

use fdt::Fdt;

/// Смещения регистров контроллера (Mentor USB, он же MUSB).
///
/// Раскладка общая для всего семейства и описана в его документации; MediaTek
/// берёт блок как есть.
const POWER: usize = 0x01;
const INTRUSB: usize = 0x0a;
const DEVCTL: usize = 0x60;

/// `DEVCTL`, бит 0: открыть сессию.
///
/// В режиме устройства контроллер обязан взводить его сам, когда увидит
/// напряжение на кабеле. Он не взвёл — регистр читается нулём, — а значит либо
/// напряжения он не видит, либо ждёт, чтобы сессию открыли за него. Второе
/// стоит одной записи, первое — целого расследования, и начинать надо с
/// дешёвого.
const DEVCTL_SESSION: u8 = 1 << 0;

/// `POWER`, бит 6: подтянуть линию данных и тем заявить о себе шине.
///
/// До этой записи компьютер не видит на кабеле ничего — и это правильно: пока
/// устройство не готово отвечать на запросы, лучше, чтобы его не спрашивали.
const POWER_SOFTCONN: u8 = 1 << 6;
/// Бит 5: соглашаться на высокую скорость.
const POWER_HSENAB: u8 = 1 << 5;

/// Регистры физического уровня лежат в своём окне (`usb_sif`), а не в окне
/// контроллера. Смещения — из драйвера MediaTek.
mod phy {
    /// Управление режимом: годность питания, стороны кабеля, подтяжки.
    pub const MODE: usize = 0x6c;
    /// Принудительные состояния линий — их надо снять все до единого.
    pub const FORCE: usize = 0x68;
    /// Обнаружение зарядного устройства и сравнение напряжения на шине.
    pub const CHARGER: usize = 0x18;
    /// Управление выводами физического уровня.
    pub const GPIO: usize = 0x20;
    /// Проверка подтяжек — её тоже надо снять.
    pub const BIST: usize = 0x1c;
}

/// Поднять USB и заявить о себе шине.
///
/// Возвращает состояние двух регистров, по которым видно, ожил ли контроллер:
/// его собственное состояние подключения и признаки шины. Значения печатаются
/// вызывающим — на аппарате без линии это единственный отчёт.
///
/// # Safety
///
/// Таблицы ядра активны; окна отображаются здесь же.
pub unsafe fn start(fdt: &Fdt<'_>) -> Option<(u8, u8)> {
    let controller = window(fdt, "/usb0@11200000", "mediatek,mt6765-usb20")?;
    let sif = window(fdt, "/usb_sif@11210000", "mediatek,usb_sif")?;

    // SAFETY: оба окна отображены как память устройства.
    unsafe {
        recover(sif);
        device_mode(sif);

        // Высокая скорость и подключение к шине. Порядок обязателен: заявить о
        // себе раньше, чем физический уровень готов, значит получить запрос,
        // на который нечем ответить, — и компьютер объявит устройство
        // неисправным, а не отсутствующим.
        let power = read8(controller, POWER);
        write8(controller, POWER, power | POWER_HSENAB | POWER_SOFTCONN);

        // Сессия — явно. См. [`DEVCTL_SESSION`].
        let devctl = read8(controller, DEVCTL);
        write8(controller, DEVCTL, devctl | DEVCTL_SESSION);

        // Регистр режима физического уровня печатается вместе с остальным:
        // запись в него ничем не подтверждена, а прочитанное назад — это
        // разница между «настроили» и «писали в никуда».
        crate::kprintln!(
            "  usb         : phy mode {:#010x}, force {:#010x}",
            ptr::read_volatile((sif + phy::MODE) as *const u32),
            ptr::read_volatile((sif + phy::FORCE) as *const u32)
        );

        Some((read8(controller, POWER), read8(controller, DEVCTL)))
    }
}

/// Снять с физического уровня всё принудительное, что оставил загрузчик.
///
/// Загрузчик держит линии в заданном состоянии, пока сам ими пользуется, и
/// оставляет их так же. Каждый из этих битов по отдельности означает «не слушай
/// шину, слушай меня», и хотя бы один невыключенный делает устройство немым.
///
/// # Safety
///
/// `sif` — отображённое окно регистров физического уровня.
unsafe fn recover(sif: usize) {
    // SAFETY: контракт функции.
    unsafe {
        // Проверка подтяжек — ею контроллер питания определяет тип зарядки.
        clear(sif, phy::BIST, 1 << 12);

        // Режим последовательной линии: у MediaTek те же провода умеют быть
        // отладочным портом, и если это включено, шины USB на них нет вовсе.
        clear(sif, phy::FORCE, 1 << 26);
        clear(sif, phy::MODE, 1 << 16);
        clear(sif, phy::GPIO, (1 << 9) | (1 << 8));

        // Принудительный сон.
        clear(sif, phy::FORCE, 1 << 18);
        // Подтяжки линий данных вниз — они нужны стороне, которая опрашивает,
        // а мы отвечаем.
        clear(sif, phy::FORCE, (1 << 6) | (1 << 7));
        // Выбор приёмопередатчика и типа сигнала.
        clear(sif, phy::FORCE, 0x3 << 4);
        clear(sif, phy::FORCE, 1 << 2);
        // Принудительные данные на линиях.
        clear(sif, phy::FORCE, 0xf << 10);
        // И все признаки «значение навязано», разом.
        clear(
            sif,
            phy::FORCE,
            (1 << 20) | (1 << 21) | (1 << 19) | (1 << 17) | (1 << 23),
        );

        // Обнаружение зарядки выключить, сравнение напряжения на шине включить:
        // без него контроллер не узнает, что кабель воткнут.
        clear(sif, phy::CHARGER, 1 << 23);
        set(sif, phy::CHARGER, 1 << 20);
    }
}

/// Объявить физическому уровню, что мы — устройство, а не хозяин шины.
///
/// Значения из драйвера MediaTek и означают набор признаков разом: питание на
/// шине годно, сессия открыта, сторона кабеля — устройство.
///
/// # Safety
///
/// См. [`recover`].
unsafe fn device_mode(sif: usize) {
    // SAFETY: контракт функции.
    unsafe {
        clear(sif, phy::MODE, 0x10);
        set(sif, phy::MODE, 0x2f);
        // Старшая половина — признаки «эти значения навязаны нами», без них
        // младшая не действует.
        set(sif, phy::MODE, 0x3f << 8);
    }
}

/// Найти и отобразить окно регистров по имени узла или по совместимости.
fn window(fdt: &Fdt<'_>, path: &str, compatible: &str) -> Option<usize> {
    let node = fdt.find(path).or_else(|| fdt.find_compatible(compatible))?;
    let (address_cells, size_cells) = root_cells(fdt);
    let region = node.reg(address_cells, size_cells).next()?;
    if region.address == 0 || !super::mtk_touch::map_device_page(region.address) {
        return None;
    }
    Some(region.address as usize)
}

/// Размеры ячеек корня — те же, что у всех остальных читателей дерева.
fn root_cells(fdt: &Fdt<'_>) -> (usize, usize) {
    let Some(root) = fdt.nodes().next() else {
        return (2, 1);
    };
    (
        root.property_u64("#address-cells").unwrap_or(2) as usize,
        root.property_u64("#size-cells").unwrap_or(1) as usize,
    )
}

/// # Safety
///
/// `base + offset` обязан принадлежать отображённому окну регистров.
unsafe fn read8(base: usize, offset: usize) -> u8 {
    // SAFETY: контракт; volatile обязателен — значение меняет устройство.
    unsafe { ptr::read_volatile((base + offset) as *const u8) }
}

/// # Safety
///
/// См. [`read8`].
unsafe fn write8(base: usize, offset: usize, value: u8) {
    // SAFETY: контракт; volatile обязателен.
    unsafe { ptr::write_volatile((base + offset) as *mut u8, value) };
}

/// # Safety
///
/// См. [`read8`].
unsafe fn set(base: usize, offset: usize, bits: u32) {
    // SAFETY: контракт; чтение-правка-запись, регистр тридцатидвухбитный.
    unsafe {
        let address = (base + offset) as *mut u32;
        let value = ptr::read_volatile(address);
        ptr::write_volatile(address, value | bits);
    }
}

/// # Safety
///
/// См. [`read8`].
unsafe fn clear(base: usize, offset: usize, bits: u32) {
    // SAFETY: контракт; чтение-правка-запись, регистр тридцатидвухбитный.
    unsafe {
        let address = (base + offset) as *mut u32;
        let value = ptr::read_volatile(address);
        ptr::write_volatile(address, value & !bits);
    }
}

/// Признаки шины, замеченные контроллером с момента прошлого чтения.
///
/// Читается **после** подключения и через заметную паузу: сброс шины,
/// подключение и запрос дескриптора приходят именно сюда, и ненулевое значение
/// означает, что компьютер нас заметил и заговорил.
///
/// # Safety
///
/// `controller` — отображённое окно регистров контроллера.
pub unsafe fn traffic(controller: usize) -> u8 {
    // SAFETY: контракт функции.
    unsafe { read8(controller, INTRUSB) }
}
