//! Прошивка тачскрина: положить её в кристалл, потому что своей у него нет.
//!
//! # Открытие, ради которого написан этот файл
//!
//! NT36525B на этом аппарате **не хранит прошивку**. Ни во внутренней флеш-
//! памяти, ни где-либо ещё: при включении в нём поднимается только загрузчик
//! кристалла — тот, что называет себя `0b 00 00 25 65 03` и умеет ровно две
//! вещи, принять образ и запустить его. Сам образ каждый раз кладёт в его ОЗУ
//! хозяин, по той же шине SPI, по которой потом читает касания. У изготовителя
//! это называется «host download», и в заводском драйвере оно делается не
//! только при загрузке, но и при каждом пробуждении панели.
//!
//! Пока этого не знаешь, картина выглядит издевательски правдоподобной: кристалл
//! опознаётся, отвечает на любой вопрос о себе, в буфере событий лежит верное
//! состояние `0xa3` («работаю нормально») и верные сведения о прошивке —
//! `720x1600`, версия `0x0a`, сходящаяся контрольная сумма. И только отчёта о
//! касаниях нет: область `0x21C00..0x21C3F` читается сплошными `0xff`, и не
//! меняется от того, лежит на экране палец или нет.
//!
//! Разгадка в том, что всё верное в этом буфере — **мусор, оставшийся от
//! Android**. Питания кристалл не терял, ОЗУ сохранило содержимое прошлой
//! жизни, а наш собственный программный сброс (`0x69` в `SWRST_N8`) выбил из
//! него исполняющуюся прошивку и вернул его в загрузчик. Доказано это одним
//! опытом: байт состояния обнулили руками, сбросили кристалл — и он остался
//! нулём целую секунду. Живая прошивка подняла бы его за десятки миллисекунд.
//!
//! # Что здесь сделано
//!
//! Разбор заголовка образа и запись его частей в ОЗУ кристалла — ровно тем
//! порядком, каким это делает `nvt_download_firmware_hw_crc` изготовителя:
//!
//! 1. сброс в загрузчик кристалла;
//! 2. запись всех частей образа по их адресам в ОЗУ;
//! 3. заполнение регистров проверки: откуда, сколько и какая сумма — отдельно
//!    для кода (ILM) и для данных (DLM);
//! 4. включение аппаратной проверки суммы;
//! 5. очистка байта состояния и включение проверки суммы прошивкой;
//! 6. запись признака готовности — вот она и запускает прошивку;
//! 7. ожидание, пока прошивка заявит о себе.
//!
//! Шаг третий и четвёртый — не перестраховка. У этого кристалла проверка суммы
//! аппаратная (`hw_crc = 1`), и загрузчик **не запустит** образ, чья сумма не
//! сошлась с записанной эталонной. Пропустить их значит получить ровно то же
//! молчание, с которого всё началось.
//!
//! # Откуда берётся образ
//!
//! Из `firmware/novatek/`, которой в хранилище нет: прошивка чужая и несвободная
//! (см. `firmware/README.md`). Нет её — нет и тачскрина, а сборка ядра не
//! страдает: признак `touch-firmware` выключается, и здесь остаётся пустая
//! таблица, о чём журнал говорит прямым текстом.

use super::mtk_spi;
use super::mtk::gpio_output;

/// Один образ и панель, для которой он предназначен.
pub struct Blob {
    /// Как поставщик панели называется в имени, которое даёт загрузчик.
    pub vendor: &'static str,
    pub data: &'static [u8],
}

/// Образы, вкомпилированные в ядро.
///
/// Четыре, потому что Xiaomi ставила в этот аппарат панели четырёх поставщиков,
/// а прошивка у каждого своя. Выбирается по имени панели из командной строки
/// загрузчика — см. [`choose`].
#[cfg(feature = "touch-firmware")]
pub const BLOBS: [Blob; 4] = [
    Blob { vendor: "dijing", data: include_bytes!("../../../../../firmware/novatek/novatek_ts_djn_fw.bin") },
    Blob { vendor: "helitai", data: include_bytes!("../../../../../firmware/novatek/novatek_ts_hlt_fw.bin") },
    Blob { vendor: "shengchao", data: include_bytes!("../../../../../firmware/novatek/novatek_ts_ebbg_fw.bin") },
    Blob { vendor: "truly", data: include_bytes!("../../../../../firmware/novatek/novatek_ts_truly_fw.bin") },
];

#[cfg(not(feature = "touch-firmware"))]
pub const BLOBS: [Blob; 0] = [];

/// Выбрать образ по имени панели из командной строки загрузчика.
///
/// Загрузчик MediaTek кладёт туда `lcm=1-nt36525b_vdo_hdp_boe_dijing_drv` и
/// подобное; заводской драйвер сравнивает это имя целиком со своим списком.
/// Мы ищем в нём подстроку поставщика — так же надёжно и не разваливается от
/// лишнего суффикса, которых у этих имён по три штуки.
///
/// Не нашлось — не беда: перебрать четыре образа по кабелю дешевле, чем ещё раз
/// собирать ядро (`fastboot oem tfw <номер>`).
#[must_use]
pub fn choose(bootargs: &str) -> Option<usize> {
    BLOBS.iter().position(|blob| bootargs.contains(blob.vendor))
}

/// Часть образа: откуда взять, куда положить, сколько и какая сумма.
#[derive(Clone, Copy, Default)]
struct Part {
    from: u32,
    to: u32,
    size: u32,
    crc: u32,
}

/// Сколько частей разбирается. У этого образа их пятнадцать: код, данные и
/// тринадцать описанных в заголовке. Двадцать четыре — с запасом на соседние
/// прошивки того же семейства, и всё равно это массив на стеке, а не куча.
const MAX_PARTS: usize = 24;

/// Прочитать четыре байта младшим вперёд.
fn word(data: &[u8], at: usize) -> u32 {
    if at + 4 > data.len() {
        return 0;
    }
    u32::from(data[at])
        | (u32::from(data[at + 1]) << 8)
        | (u32::from(data[at + 2]) << 16)
        | (u32::from(data[at + 3]) << 24)
}

/// Разобрать заголовок образа.
///
/// # Как он устроен
///
/// Первые четыре байта — адрес, с которого начинается код, он же длина всего
/// заголовка. Дальше по двенадцать байт на код и данные (откуда, куда,
/// сколько), их суммы отдельно по `0x18` и `0x1C`. С `0x30` и до конца
/// заголовка — по шестнадцать байт на каждую прочую часть, и там порядок полей
/// **другой**: куда, сколько, откуда, сумма. Перепутать их местами — значит
/// записать образ по адресам, которые в нём же и лежат, и получить кристалл,
/// не проходящий проверку суммы.
fn parse(data: &[u8]) -> Option<([Part; MAX_PARTS], usize)> {
    /// Код и данные — всегда первые две части, и заголовок описывает их иначе,
    /// чем остальные.
    const CODE_AND_DATA: usize = 2;

    let end = word(data, 0) as usize;
    if end < 0x30 || end > data.len() {
        return None;
    }
    let described = (end - 0x30) / 0x10;

    // Наложения: старший полубайт байта `0x28` говорит, есть ли они, младший —
    // сколько. Их описания лежат не в заголовке, а в начале части данных.
    let overlay_present = (data.get(0x28).copied().unwrap_or(0) & 0x10) != 0;
    let overlays = if overlay_present {
        usize::from(data[0x28] & 0x0f)
    } else {
        0
    };

    let count = CODE_AND_DATA + described + overlays;
    if count > MAX_PARTS {
        return None;
    }

    let mut parts = [Part::default(); MAX_PARTS];
    for index in 0..count {
        let part = if index < CODE_AND_DATA {
            Part {
                from: word(data, index * 12),
                to: word(data, 4 + index * 12),
                size: word(data, 8 + index * 12),
                crc: word(data, 0x18 + index * 4),
            }
        } else {
            let at = if index < CODE_AND_DATA + described {
                0x30 + 0x10 * (index - CODE_AND_DATA)
            } else {
                // Описания наложений лежат по адресу, где в образе начинаются
                // данные, — то есть в поле, разобранном на предыдущем витке.
                parts[1].from as usize + 0x10 * (index - CODE_AND_DATA - described)
            };
            Part {
                to: word(data, at),
                size: word(data, at + 4),
                from: word(data, at + 8),
                crc: word(data, at + 12),
            }
        };

        // Часть, вылезающая за образ, — это разъехавшийся разбор, а не
        // необычная прошивка. Записывать её значит слать кристаллу случайную
        // память ядра.
        if part.from as usize + part.size as usize > data.len() {
            return None;
        }
        parts[index] = part;
    }
    Some((parts, count))
}

/// Адреса управляющих регистров кристалла (`NT36672A_memory_map` вендора —
/// именно на неё указывает наш идентификатор в его таблице).
const BOOT_READY: u32 = 0x3_F10D;
const CODE_LENGTH: u32 = 0x3_F118;
const DATA_LENGTH: u32 = 0x3_F130;
const CODE_DESTINATION: u32 = 0x3_F128;
const DATA_DESTINATION: u32 = 0x3_F12C;
const CODE_CHECKSUM: u32 = 0x3_F100;
const DATA_CHECKSUM: u32 = 0x3_F104;
const CHECK_ENABLE: u32 = 0x3_F30E;

/// Сколько байт полезной нагрузки уходит за одну посылку.
///
/// Шестнадцать — не осторожность, а предел: память передачи контроллера SPI у
/// MediaTek вмещает тридцать два байта вместе со служебными, а страница у
/// кристалла — сто двадцать восемь. Шестнадцать делит сто двадцать восемь
/// нацело, поэтому ни одна посылка не пересекает границу страницы, и выбирать
/// её приходится ровно по разу на посылку.
const CHUNK: usize = 16;

/// Чем кончилась загрузка.
pub enum Outcome {
    /// Прошивка поднялась; сколько миллисекунд на это ушло.
    Up(u32),
    /// Образ записан, но прошивка о себе не заявила: последнее состояние.
    Silent(u8),
    /// Образ не разобрался.
    Broken,
}

/// Положить образ в кристалл и запустить его.
///
/// # Safety
///
/// Шина настроена вызывающим, окна отображены, выводы принадлежат `spi3`.
pub unsafe fn download(
    bus: &mtk_spi::Bus,
    pins: Option<u64>,
    reset_pin: u32,
    event_buffer: u32,
    blob: &Blob,
    pad: u32,
    mode: u8,
) -> Outcome {
    let Some((parts, count)) = parse(blob.data) else {
        return Outcome::Broken;
    };

    // Сначала — дать компьютеру перечислить устройство, и только потом браться
    // за шину.
    //
    // Это заплата поверх порядка загрузки, и она честнее, чем выглядит. USB
    // поднимается раньше тачскрина, хост начинает спрашивать сразу, как увидел
    // подтяжку, и ждёт ответа на служебный запрос миллисекунды. Запись образа —
    // это тысячи посылок по медленной шине; уйти в неё, не дав хосту
    // договорить, значит сорвать перечисление, а второго захода он не делает.
    //
    // Проверено дорого: аппарат простоял восемь часов, показывая журнал, и не
    // отозвался по кабелю ни разу — при том что USB был поднят и исправен.
    let handshake = crate::time::uptime_ms() + 2000;
    while crate::time::uptime_ms() < handshake {
        super::mtk_usb::poll();
        core::hint::spin_loop();
    }

    // Аппаратный сброс перед записью: заводской драйвер поднимает вывод сброса
    // до загрузки, и на то есть причина — пока кристалл прижат, он принимает
    // только инженерный сброс и ничего больше.
    if let Some(pins) = pins {
        // SAFETY: контракт функции.
        unsafe { gpio_output(pins, reset_pin, true) };
    }

    // Сброс в загрузчик кристалла. Именно он останавливает то, что там
    // исполнялось, и открывает ОЗУ на запись.
    // SAFETY: см. выше.
    unsafe {
        setup(bus, pad, mode);
        super::mtk_touch::write_addr(bus, 0x3_F0FE, 0x69);
    }
    wait_ms(40);

    let mut sent = 0u32;
    let mut retried = 0u32;
    let mut failed = 0u32;
    let started = crate::time::uptime_ms();
    for part in parts.iter().take(count) {
        if part.size == 0 {
            continue;
        }
        // Байт сверх размера — так делает изготовитель, и так же считается
        // сумма: по `size + 1` байту. Обрезать его значит не сойтись с
        // эталоном ровно на единицу.
        let size = part.size as usize + 1;
        let mut written = 0;
        while written < size {
            let to = part.to + written as u32;
            // Кусок обрезается по границе страницы кристалла: части образа
            // начинаются где придётся, и посылка, начатая под конец страницы,
            // ушла бы за её край.
            let len = CHUNK.min(size - written).min(0x80 - (to as usize & 0x7f));
            let from = part.from as usize + written;
            // SAFETY: окна отображены, выводы принадлежат `spi3`.
            let (packets, ok) = unsafe { put(bus, pad, mode, to, blob, from, len) };
            sent += packets;
            retried += packets.saturating_sub(1);
            if !ok {
                failed += 1;
            }
            written += len;

            // Обмен с компьютером — раз в шестнадцать кусков.
            //
            // Не после каждого, и это измерено: один опрос кабеля стоит около
            // шести миллисекунд против неполной миллисекунды на саму посылку,
            // то есть впятеро дороже работы, ради которой всё затевалось. Пять
            // тысяч посылок из-за него заняли тридцать четыре секунды.
            //
            // Раз в шестнадцать безопасно ровно потому, что перечисление к
            // этому мигу уже позади: его пропускает двухсекундное окно перед
            // записью. Дальше хост говорит, только когда его спросят, и
            // повторяет запрос столько раз, сколько нужно.
            if sent % 16 == 0 {
                super::mtk_usb::poll();
            }
        }
    }

    // Сколько это заняло — в журнал, одной строкой.
    //
    // Не любопытство: запись идёт по медленной шине тысячами посылок, а рядом
    // хост ждёт перечисления. Если однажды окажется, что она занимает не
    // полсекунды, а минуту, — это будет видно сразу и здесь, а не выведено из
    // того, что аппарат не отозвался.
    crate::kprintln!(
        "  touch       : {} packets in {} ms, {} rewritten, {} still wrong",
        sent,
        crate::time::uptime_ms().saturating_sub(started),
        retried,
        failed
    );

    // Сверяющий проход: он ловит то, чего проверка на месте не может.
    // SAFETY: см. выше.
    let (checked, repaired) = unsafe { sweep(bus, pad, mode, blob, &parts[..count]) };
    crate::kprintln!("  touch       : swept {checked} chunks, repaired {repaired}");

    // Регистры проверки: откуда, сколько и какая сумма — для кода и для данных.
    // SAFETY: см. выше.
    unsafe {
        check_bank(bus, pad, mode, CODE_DESTINATION, CODE_LENGTH, CODE_CHECKSUM, &parts[0]);
        check_bank(bus, pad, mode, DATA_DESTINATION, DATA_LENGTH, DATA_CHECKSUM, &parts[1]);
    }

    // Аппаратная проверка суммы: старший разряд взводится, остальные — чужие,
    // и потому регистр сначала читается.
    // SAFETY: см. выше.
    unsafe {
        setup(bus, pad, mode);
        let _ = bus.transfer(&page_of(CHECK_ENABLE), &mut []);
        let request = [(CHECK_ENABLE as u8) & 0x7f, 0, 0];
        let mut answer = [0u8; 3];
        let _ = bus.transfer(&request, &mut answer);
        setup(bus, pad, mode);
        let _ = bus.transfer(&page_of(CHECK_ENABLE), &mut []);
        let _ = bus.transfer(&[(CHECK_ENABLE as u8) | 0x80, answer[2] | 0x80], &mut []);
    }

    // Байт состояния обнуляется, и это единственный способ отличить «прошивка
    // поднялась» от «в ОЗУ лежит прошлогоднее число». Следом — команда включить
    // проверку суммы самой прошивкой.
    // SAFETY: см. выше.
    unsafe {
        setup(bus, pad, mode);
        super::mtk_touch::write_addr(bus, event_buffer | 0x60, 0x00);
        setup(bus, pad, mode);
        super::mtk_touch::write_addr(bus, event_buffer | 0x50, 0xae);
    }

    // Признак готовности. Вот эта запись и запускает прошивку.
    // SAFETY: см. выше.
    unsafe {
        setup(bus, pad, mode);
        super::mtk_touch::write_addr(bus, BOOT_READY, 0x01);
    }
    wait_ms(5);

    let mut rounds = 0;
    let mut state = 0u8;
    while rounds < 100 {
        wait_ms(10);
        rounds += 1;
        // SAFETY: см. выше.
        state = unsafe {
            setup(bus, pad, mode);
            super::mtk_touch::read_event(bus, event_buffer, 0x60, 6).0[0]
        };
        if (0xa0..=0xaf).contains(&state) {
            return Outcome::Up(rounds * 10);
        }
    }
    Outcome::Silent(state)
}

/// Записать кусок и убедиться, что он лёг.
///
/// # Почему без проверки нельзя
///
/// Потому что шина врёт, и это измерено на аппарате: около полутора процентов
/// шестнадцатибайтовых кусков ложатся в память с одним искажённым байтом, а
/// примерно столько же чтений возвращают нули вместо данных. Для человека это
/// незаметная доля; для аппаратной проверки суммы, которой загрузчик кристалла
/// решает, запускать ли образ, достаточно одного байта, чтобы отказать.
///
/// Обе неисправности случайны и не повторяются на том же месте, поэтому лечатся
/// одинаково: писать и перечитывать, пока не совпадёт. Восемь попыток — это уже
/// не помеха, а что-то устойчивое, и молча биться в неё значит превратить
/// загрузку в зависание.
///
/// Возвращает число сделанных посылок и сошлось ли в итоге.
///
/// # Safety
///
/// Окна отображены, выводы принадлежат `spi3`.
unsafe fn put(
    bus: &mtk_spi::Bus,
    pad: u32,
    mode: u8,
    to: u32,
    blob: &Blob,
    from: usize,
    len: usize,
) -> (u32, bool) {
    /// Сколько раз пробовать один и тот же кусок.
    const ATTEMPTS: u32 = 8;

    let mut packet = [0u8; CHUNK + 1];
    packet[0] = (to as u8) | 0x80;
    for (slot, byte) in packet[1..=len].iter_mut().enumerate() {
        *byte = blob.data.get(from + slot).copied().unwrap_or(0);
    }

    let mut check = [0u8; CHUNK];
    for attempt in 1..=ATTEMPTS {
        // SAFETY: контракт функции; настройка восстанавливается перед каждой
        // посылкой — контроллер сбрасывает себя на любой неудаче.
        unsafe {
            setup(bus, pad, mode);
            let _ = bus.transfer(&page_of(to), &mut []);
            let _ = bus.transfer(&packet[..=len], &mut []);
            setup(bus, pad, mode);
            read_at(bus, to, len, &mut check);
        }
        if check[..len] == packet[1..=len] {
            return (attempt, true);
        }
    }
    (ATTEMPTS, false)
}

/// Пройти по всему образу и починить то, что всё-таки разъехалось.
///
/// # Зачем он нужен, если каждый кусок уже сверен
///
/// Затем, что сверен он был в тот миг, когда его писали. Потерянная посылка
/// выбора страницы уводит **запись** в чужую страницу — то есть портит место,
/// которое к тому времени могло быть уже проверено и оставлено позади. Такое
/// не ловится проверкой на месте по построению, и единственный способ о нём
/// узнать — пройти всё ещё раз, когда запись кончилась.
///
/// # Safety
///
/// См. [`put`].
unsafe fn sweep(
    bus: &mtk_spi::Bus,
    pad: u32,
    mode: u8,
    blob: &Blob,
    parts: &[Part],
) -> (u32, u32) {
    let mut checked = 0u32;
    let mut repaired = 0u32;
    for part in parts {
        if part.size == 0 {
            continue;
        }
        let size = part.size as usize + 1;
        let mut at = 0;
        while at < size {
            let to = part.to + at as u32;
            let len = CHUNK.min(size - at).min(0x80 - (to as usize & 0x7f));
            let from = part.from as usize + at;
            let mut check = [0u8; CHUNK];
            // SAFETY: контракт функции.
            unsafe {
                setup(bus, pad, mode);
                read_at(bus, to, len, &mut check);
            }
            checked += 1;
            let same = (0..len)
                .all(|i| check[i] == blob.data.get(from + i).copied().unwrap_or(0));
            if !same {
                // Разошлось — но чтение врёт не реже записи, так что сначала
                // перечитать, и только потом переписывать.
                // SAFETY: см. выше.
                unsafe {
                    setup(bus, pad, mode);
                    read_at(bus, to, len, &mut check);
                }
                let same = (0..len)
                    .all(|i| check[i] == blob.data.get(from + i).copied().unwrap_or(0));
                if !same {
                    // SAFETY: см. выше.
                    let _ = unsafe { put(bus, pad, mode, to, blob, from, len) };
                    repaired += 1;
                }
            }
            at += len;
            if checked % 16 == 0 {
                super::mtk_usb::poll();
            }
        }
    }
    (checked, repaired)
}

/// Заполнить одну тройку регистров проверки: адрес, длина, эталонная сумма.
///
/// Все три лежат в одной странице кристалла, и выбирается она **один раз** —
/// так делает изготовитель, и повторять выбор между записями не только лишнее,
/// но и опасно: страница у него шириной в сто двадцать восемь байт, а адреса
/// разбросаны по ней.
///
/// # Safety
///
/// См. [`download`].
unsafe fn check_bank(
    bus: &mtk_spi::Bus,
    pad: u32,
    mode: u8,
    destination: u32,
    length: u32,
    checksum: u32,
    part: &Part,
) {
    // SAFETY: контракт функции.
    unsafe {
        setup(bus, pad, mode);
        let _ = bus.transfer(&page_of(destination), &mut []);
        let _ = bus.transfer(
            &[
                (destination as u8) | 0x80,
                part.to as u8,
                (part.to >> 8) as u8,
                (part.to >> 16) as u8,
            ],
            &mut [],
        );
        let _ = bus.transfer(
            &[(length as u8) | 0x80, part.size as u8, (part.size >> 8) as u8],
            &mut [],
        );
        let _ = bus.transfer(
            &[
                (checksum as u8) | 0x80,
                part.crc as u8,
                (part.crc >> 8) as u8,
                (part.crc >> 16) as u8,
                (part.crc >> 24) as u8,
            ],
            &mut [],
        );
    }
}

/// Настроить контроллер заново — перед **каждой** посылкой, без исключений.
///
/// Не осторожность: контроллер MediaTek на неудавшейся передаче сбрасывает сам
/// себя, и сброс уносит и режим, и делитель, и набор выводов. Одна такая
/// передача посреди семи тысяч — и остаток образа уходит в никуда, а
/// отчитывается всё об успехе.
///
/// # Safety
///
/// Окно регистров отображено.
unsafe fn setup(bus: &mtk_spi::Bus, pad: u32, mode: u8) {
    // SAFETY: контракт функции.
    unsafe {
        bus.prepare(
            mtk_spi::Timing::Enhanced,
            mode,
            pad,
            super::mtk_touch::clock_half(),
        )
    };
}

/// Прочитать байты по полному адресу — чтобы сверить записанное.
///
/// # Зачем сверять
///
/// Затем, что запись **врёт**, и это измерено, а не предположено. Из пяти
/// тысяч посылок три легли в ОЗУ искажёнными: `0x80` стало `0x8c`, `0x65` —
/// `0x71`, `0xcd` — `0xf9`. Три байта на пятьдесят шесть килобайт, и все три
/// устойчивы: перечитывание даёт то же самое, то есть в памяти кристалла
/// действительно лежит не то, что посылали.
///
/// Для человека такая доля незаметна. Для аппаратной проверки суммы, которой
/// загрузчик кристалла решает, запускать ли образ, одного байта достаточно,
/// чтобы отказать, — и он отказывал, а выглядело это как «прошивка не та».
///
/// # Safety
///
/// Окна отображены, выводы принадлежат `spi3`.
unsafe fn read_at(bus: &mtk_spi::Bus, address: u32, len: usize, out: &mut [u8]) {
    let mut request = [0u8; 32];
    let mut answer = [0u8; 32];
    request[0] = (address as u8) & 0x7f;
    // SAFETY: контракт функции.
    unsafe {
        let _ = bus.transfer(&page_of(address), &mut []);
        let _ = bus.transfer(&request[..len + 2], &mut answer[..len + 2]);
    }
    out[..len].copy_from_slice(&answer[2..len + 2]);
}

/// Посылка выбора страницы. Та же, что у соседа по модулю, — здесь она своя
/// только потому, что тот файл о прошивке ничего не знает.
fn page_of(address: u32) -> [u8; 3] {
    [0xff, ((address >> 15) & 0xff) as u8, ((address >> 7) & 0xff) as u8]
}

fn wait_ms(ms: u64) {
    let until = crate::time::uptime_ms() + ms;
    while crate::time::uptime_ms() < until {
        core::hint::spin_loop();
    }
}
