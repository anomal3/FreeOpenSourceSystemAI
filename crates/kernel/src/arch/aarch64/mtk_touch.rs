//! Тачскрин телефона: найти контроллер на шине и читать с него касания.
//!
//! # Почему поиск, а не адрес в коде
//!
//! Заводское дерево устройств про тачскрин молчит: узел `/touch` несёт одно
//! свойство `compatible = "mediatek,touch"` — ни шины, ни адреса. Так у
//! MediaTek устроено всё семейство: контроллер регистрируется платформенным
//! кодом, а какой чип впаян в эту партию, дерево не знает. У `dandelion`
//! возможны три (Focaltech, Novatek, Himax), и в разных партиях стоят разные.
//!
//! Значит, вбитый в код адрес был бы ядром, работающим на части аппаратов и
//! молча не работающим на остальных. Поэтому шины опрашиваются.
//!
//! # Что делается с найденным
//!
//! Полностью читаются два семейства, у которых протокол короткий и целиком
//! опубликован: Focaltech и Goodix. Остальные, если отзовутся, называются в
//! журнале по адресу и не трогаются: наполовину угаданный протокол хуже
//! отсутствующего — он даёт координаты, и они неверны.
//!
//! # Опрос, а не прерывание
//!
//! Прерывание тачскрина приходит через вывод общего назначения, и чтобы его
//! разрешить, нужны и контроллер выводов, и таблица их назначения, и разбор
//! `interrupts` у узла, которого нет. Опрос раз в несколько миллисекунд стоит
//! одной короткой посылки по I²C и снимает всё это целиком.

use super::mtk_i2c::{self, Bus, Error, Layout};
use super::mtk::{gpio_input, gpio_output};
use super::mtk_spi;
use crate::input::{Buttons, post_pointer_at};
use crate::sync::SpinLock;
use core::sync::atomic::{AtomicU32, AtomicU8, Ordering};
use fdt::Fdt;

/// Кого умеем читать.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Kind {
    /// FT5x06 и родня: карта регистров плоская, координаты с восьмого байта.
    Focaltech,
    /// GT9xx: регистры шестнадцатибитные, признак касания надо снимать самим.
    Goodix,
}

/// Адреса, на которых стоит спрашивать, и кем они окажутся.
///
/// Список закрытый, и это осознанно: полный обход ста двенадцати адресов на
/// семи шинах занимает время и находит вдобавок контроллер питания, датчики и
/// зарядку — всё то, чему наш вопрос безразличен, но чей ответ пришлось бы
/// отличать от нужного.
const KNOWN: [(u8, Kind); 4] = [
    (0x38, Kind::Focaltech),
    (0x70, Kind::Focaltech),
    (0x5d, Kind::Goodix),
    (0x14, Kind::Goodix),
];

/// Адреса, которые стоит назвать, даже не умея с ними говорить.
///
/// Найденный, но не прочитанный контроллер — это половина ответа, и она дороже
/// молчания: в следующий раз известно, какой протокол писать, и не надо снова
/// идти к аппарату.
const NAMED: [(u8, &str); 4] = [
    (0x62, "Novatek"),
    (0x01, "Novatek"),
    (0x48, "Himax"),
    (0x49, "Himax"),
];

/// Найденный тачскрин.
struct Touch {
    bus: Bus,
    address: u8,
    kind: Kind,
    /// Последнее состояние: было ли касание. Нужно, чтобы отпускание
    /// отправлялось ровно один раз, а не каждым опросом.
    down: bool,
    /// Где палец был в последний раз, уже в долях экрана. Отпускание шлётся
    /// сюда же: курсор, уехавший в угол на снятие пальца, означал бы, что щелчок
    /// достаётся не тому, по чему щёлкнули.
    last: (u16, u16),
}

static TOUCH: SpinLock<Option<Touch>> = SpinLock::new(None);

/// Панель Novatek на SPI — та, что стоит в этом аппарате.
///
/// Отдельно от [`TOUCH`], а не ещё одним значением `Kind`, потому что общего у
/// них ровно ничего: другая шина, другой тип, другой протокол. Свести их под
/// один тип значило бы завести поле, которое у половины значений не имеет
/// смысла, — и первую же ошибку, которую компилятор не поймает.
struct SpiTouch {
    bus: mtk_spi::Bus,
    /// Блок настройки выводов — нужен, чтобы спросить линию прерывания.
    pins: Option<u64>,
    /// Набор выводов и режим такта, на которых кристалл отозвался.
    ///
    /// Хранятся не для порядка. Контроллер MediaTek на неудавшейся передаче
    /// **сбрасывает себя** (`CMD_RST`), а сброс уносит и режим, и делитель, и
    /// набор выводов. Одна такая передача — и шина до конца работы читает нули
    /// с полной невозмутимостью. Поэтому настройка не ставится один раз при
    /// поиске, а восстанавливается перед каждым обменом.
    pad: u32,
    mode: u8,
    /// Палец на экране. Нужно, чтобы отпускание уходило ровно один раз.
    down: bool,
    /// Сколько непустых отчётов уже напечатано.
    seen: u8,
    /// Проходов опроса с начала работы — чтобы печатать не чаще, чем изредка.
    ticks: u32,
    /// Где палец был в последний раз, в долях экрана.
    last: (u16, u16),
    /// Счётчики опроса. Живут здесь, а не в журнале, по прозаичной причине:
    /// опрос идёт сотнями раз в секунду, и печатать каждый проход — значит
    /// утопить журнал, ради которого делался USB. А спросить «сколько раз ты
    /// вообще сходил к панели и чем это кончилось» надо в любой миг.
    polls: u32,
    stalled: u32,
    live: u32,
    asserted: u32,
    /// Последний непустой отчёт — тот самый, ради которого всё.
    last_report: [u8; 12],
}

static SPI_TOUCH: SpinLock<Option<SpiTouch>> = SpinLock::new(None);

/// Буфер событий прошивки у этого кристалла (`NT36672A_memory_map`).
///
/// Переменная, а не постоянная, и это не украшение. В таблице изготовителя
/// идентификатор `25 65 03` встречается дважды, и вторая запись указывает на
/// другую карту памяти (`NT36525_memory_map`, `0x11A00`). Какая из двух верна
/// для этой партии, из аппарата не вычитать — только спросить его самого. А
/// каждый вопрос, зашитый в постоянную, стоит прошивки, перезагрузки и двух
/// нажатий питания живым человеком. Здесь он стоит одной строки в консоли ПК.
static EVENT_BASE: AtomicU32 = AtomicU32::new(0x2_1C00);

/// Текущий адрес буфера событий.
fn event_base() -> u32 {
    EVENT_BASE.load(Ordering::Relaxed)
}

/// Адрес регистра программного сброса. Взят из описания панели в исходниках
/// ядра Xiaomi для этого аппарата (`novatek,swrst-n8-addr`).
const RESET_ADDRESS: u32 = 0x3_F0FE;
/// Значение, которое этот регистр понимает как «перезапустись».
const RESET_VALUE: u8 = 0x69;
/// Инженерный сброс — единственная посылка, которую кристалл принимает, пока
/// его держат в аппаратном сбросе (`ENG_RST_ADDR` в драйвере).
const ENGINEERING_RESET_ADDRESS: u32 = 0x7F_FF80;
const ENGINEERING_RESET_VALUE: u8 = 0x5a;
/// Быстрое чтение. Изготовитель выключает его сразу после сброса: пока оно
/// включено, обмен идёт по другому договору, чем весь остальной драйвер.
const FAST_READ_ADDRESS: u32 = 0x3_F310;
/// Вывод, которым кристалл держится в сбросе (`novatek,reset-gpio`).
const RESET_PIN: u32 = 174;
/// Вывод прерывания панели (`novatek,irq-gpio` в описании аппарата).
/// Тринадцатый номер, стоящий там же в `interrupts`, принадлежит другому
/// описанию того же узла — Focaltech, — и к этому кристаллу отношения не имеет.
const IRQ_PIN: u32 = 0;

/// Смещения внутри буфера событий, как их называет изготовитель.
const EVENT_MAP_HOST_CMD: u32 = 0x50;
const EVENT_MAP_HANDSHAKE: u32 = 0x51;
const EVENT_MAP_RESET_COMPLETE: u32 = 0x60;
const EVENT_MAP_FWINFO: u32 = 0x78;

/// Кто опрашивает панель: разряд 0 — задача USB, разряд 1 — задача тачскрина.
///
/// Переключается по кабелю, и ради этого и заведено. Долгое время считалось,
/// что чтение из задачи тачскрина «не выходит на провод», а из задачи USB
/// выходит, — и опрос был перенесён туда подпоркой. Обе задачи при этом
/// продолжали опрашивать, то есть предполагаемая разница между ними ни разу не
/// была измерена в чистом виде. Теперь измеряется одной командой.
static POLL_SOURCE: AtomicU8 = AtomicU8::new(1);

/// Слать ли события указателя наверх. Ноль означает «читать и считать, но
/// курсором не двигать» — нужно, пока разбор отчёта под вопросом.
static REPORTING: AtomicU8 = AtomicU8::new(1);

/// Половина периода такта шины, в единицах контроллера.
///
/// Восемь — не догадка, а измерение на аппарате. Здесь стояло `0x40`, взятое
/// заведомо большим на тот случай, если кристалл окажется привередлив, и оно
/// давало около двадцати килогерц против девяти с половиной мегагерц у
/// изготовителя. Пока по шине читали по десятку байт, цена была не видна;
/// запись прошивки — пять тысяч посылок, и она заняла тридцать четыре секунды.
///
/// Перебор по кабелю (`oem tclk`, тридцать чтений на каждое значение) показал:
/// `0x40`, `0x10`, `0x08`, `0x06` и `0x04` читаются без единой ошибки, `0x02`
/// не читается вовсе. Взято `0x08` — восьмикратное ускорение и четырёхкратный
/// запас до края, а не значение, стоящее на нём.
///
/// Переменной остаётся намеренно: следующий аппарат может оказаться другим, и
/// узнать это будет стоить одной команды, а не сборки с перепрошивкой.
static SPI_HALF: AtomicU32 = AtomicU32::new(0x08);

/// Текущая половина периода такта.
pub fn clock_half() -> u32 {
    SPI_HALF.load(Ordering::Relaxed)
}

/// Сменить её.
pub fn set_clock_half(half: u32) {
    SPI_HALF.store(half.clamp(2, 0x400), Ordering::Relaxed);
}

/// Поднялась ли прошивка панели.
///
/// Отдельно от «кристалл найден», и разница здесь не бухгалтерская. Кристалл мы
/// берём всегда — даже молчащий, чтобы к нему можно было обратиться по кабелю.
/// Но наверх, в ответ на вопрос «есть ли у этой машины ввод», годится только
/// работающая панель: от этого ответа зависит, отдать ли экран рабочему столу.
///
/// Отдать его напрасно — не косметическая ошибка. Отрисовка стола занимает
/// секунды сплошной работы с памятью устройства, в которые шину USB опрашивать
/// некому, и хост объявляет разрыв насовсем. То есть машина променяла бы
/// единственный работающий канал наружу на картинку, по которой нечем нажать.
static FIRMWARE_UP: AtomicU8 = AtomicU8::new(0);

/// Размер панели. Координаты контроллер отдаёт в точках экрана, но врать он
/// умеет, и обрезка по этим числам дешевле, чем курсор, уехавший за буфер.
const SCREEN: (u16, u16) = (
    super::fdt_boot::DEFAULT_SCREEN.0 as u16,
    super::fdt_boot::DEFAULT_SCREEN.1 as u16,
);

/// Обойти шины и найти тачскрин. Возвращает `true`, если нашёлся читаемый.
///
/// # Safety
///
/// Таблицы ядра активны, дерево ещё не переиспользовано.
pub unsafe fn probe(fdt: &Fdt<'_>) -> bool {
    let mut found = None;

    // Такт — раньше опроса. Четыре шины из семи молчат вовсе, а молчащий блок
    // без такта неотличим от блока, на котором никого нет.
    // SAFETY: таблицы ядра активны, окно отображается внутри.
    unsafe { super::mtk::ungate_infra(fdt) };

    for window in super::fdt_boot::i2c_buses(fdt) {
        let Some(window) = window else { continue };
        let base = window.base;
        // Окно регистров надо отобразить: карта памяти описывает ОЗУ и
        // зарезервированное, а регистры контроллеров в неё не входят.
        if !map_device_page(base) {
            continue;
        }

        for layout in [mtk_i2c::V1, mtk_i2c::V2] {
            // SAFETY: окно отображено выше как память устройства.
            let bus = unsafe { Bus::new(base as usize, layout) };
            // SAFETY: то же окно, доступ к этому контроллеру только отсюда.
            let virgin = unsafe { bus.prepare() };

            // Первый вопрос задаётся одному адресу и служит проверкой самой
            // раскладки: если контроллер не отвечает даже отказом, значит либо
            // раскладка не та, либо шина не тактируется. И то и другое означает
            // «здесь спрашивать нечего», и сто двенадцать адресов подряд стоило
            // бы это выяснять втрое дольше.
            // SAFETY: см. выше.
            let alive = unsafe { bus.transfer(0x38, &[], &mut [0u8; 1]) } != Err(Error::Timeout);
            if !alive {
                // Молчание тоже надо назвать: иначе шина, которой не подведён
                // такт, выглядит как отсутствующая, и её не станут искать.
                if layout.name == "v2" {
                    crate::kprintln!("  touch       : i2c {base:#010x} does not answer at all");
                }
                continue;
            }

            // Шина ответила — но прежде, чем верить её ответам, надо убедиться,
            // что она умеет отвечать «нет». Первый заход этого не сделал, и
            // поиск доложил о четырёх контроллерах на каждой из трёх шин:
            // неподтверждение не ловилось, и «да» приходило на любой адрес.
            // SAFETY: см. выше.
            let honest = unsafe { mtk_i2c::trustworthy(&bus) };
            if !honest {
                // Сырое состояние и настройка выводов печатаются здесь, а не
                // прячутся: «шина подтверждает всё» — это симптом, у которого
                // две разные причины. Либо передача честно вышла на провода и
                // ей ответили (тогда виноваты выводы: не переключённые на I²C,
                // они читаются нулём, а ноль на линии данных — это и есть
                // подтверждение), либо передача не вышла вовсе и контроллер
                // отчитался за пустоту. Одно число различает их сразу.
                // SAFETY: см. выше.
                let status = unsafe { bus.probe_status(0x7f) };
                crate::kprintln!(
                    "  touch       : i2c {base:#010x} ({}) acks everything, status {status:#06x}",
                    layout.name
                );
                report_pins(&window);
                // Обход всё равно делается: даже врущая шина отвечает не
                // одинаково, и увидеть это дешевле, чем не увидеть. Верить её
                // находкам нельзя, и они помечены.
            }

            if virgin {
                crate::kprintln!(
                    "  touch       : i2c at {base:#010x} was not set up by the bootloader"
                );
            }

            // Полный обход шины здесь когда-то был и своё дело сделал: он и
            // доказал, что тачскрина на I²C нет. Держать его в каждой загрузке
            // незачем — он занимает секунды и полтора десятка строк экрана, а
            // отвечает на вопрос, который уже закрыт. Знакомые адреса
            // опрашиваются по-прежнему: аппараты этой модели бывают разных
            // партий, и на другой панель вполне может оказаться на шине.
            for (address, kind) in KNOWN {
                // SAFETY: см. выше.
                if honest && unsafe { bus.present(address) } {
                    crate::kprintln!(
                        "  touch       : {kind:?} at {address:#04x} on i2c {base:#010x} ({})",
                        layout.name
                    );
                    if found.is_none() {
                        found = Some(Touch {
                            bus,
                            address,
                            kind,
                            down: false,
                            last: (0, 0),
                        });
                    }
                }
            }
            for (address, name) in NAMED {
                // SAFETY: см. выше.
                if honest && unsafe { bus.present(address) } {
                    crate::kprintln!(
                        "  touch       : {name} at {address:#04x} on i2c {base:#010x}, protocol not written"
                    );
                }
            }

            // Раскладка подошла — вторую на этой шине проверять незачем.
            break;
        }
    }

    // SPI — там, где тачскрин у этого аппарата и оказался. Опрашивается после
    // I²C, а не вместо: у соседних партий панель бывает и на шине.
    // SAFETY: таблицы ядра активны, окна отображаются внутри.
    unsafe { probe_spi(fdt) };

    // Панель на SPI — тоже найденный тачскрин, и сказать об этом обязательно:
    // от этого ответа зависит, заведётся ли задача опроса и появится ли на
    // машине источник событий вообще. Без него ядро считает, что нажимать
    // нечем, и не поднимает ни оболочку, ни рабочий стол.
    let on_spi = SPI_TOUCH.lock().is_some() && FIRMWARE_UP.load(Ordering::Relaxed) != 0;

    let Some(touch) = found else {
        return on_spi;
    };
    *TOUCH.lock() = Some(touch);
    true
}

/// Напечатать настройку выводов шины — то немногое, что о ней говорит дерево.
///
/// Узлов состояния выводов у шин I²C в этом дереве нет, но каждая называет свой
/// блок настройки (`gpio_start`) и номера линий данных и такта. Значений режима
/// мы не знаем — таблица режимов принадлежит конкретному кристаллу, а её у нас
/// нет, — но сырые слова сравнимы между собой: у шины, которой загрузчик
/// пользовался, и у нетронутой они обязаны различаться. Это и есть следующий
/// вопрос, и задать его дешевле сейчас, чем ещё одним заходом к аппарату.
fn report_pins(window: &super::fdt_boot::I2cBus) {
    let Some(pins) = window.pins else {
        return;
    };
    if !map_device_page(pins) {
        return;
    }
    let mut words = [0u32; 4];
    for (slot, word) in words.iter_mut().enumerate() {
        // SAFETY: блок назван самим деревом и отображён строкой выше как память
        // устройства; читаются первые четыре слова — там у MediaTek лежит режим.
        *word = unsafe { ((pins as usize + slot * 4) as *const u32).read_volatile() };
    }
    crate::kprintln!(
        "  touch       :   pins sda {} scl {}, cfg {pins:#010x} = {:08x} {:08x} {:08x} {:08x}",
        window.sda,
        window.scl,
        words[0],
        words[1],
        words[2],
        words[3]
    );
}

/// Спросить у каждого контроллера SPI, не Novatek ли на нём.
///
/// # Что именно спрашивается
///
/// Идентификатор кристалла — шесть байт, которые Novatek кладёт по адресу
/// `0x3F004` своей внутренней памяти. Читается он в два приёма, и оба взяты из
/// опубликованного драйвера Novatek, а не выведены:
///
/// 1. посылка `FF 07 E0` выбирает страницу: `0xFF` — команда «дальше адрес»,
///    следующие два байта — тот же `0x3F004`, сдвинутый на 15 и на 7;
/// 2. посылка, начинающаяся с `0x84`, читает: младшие семь бит — смещение
///    внутри страницы, старший бит означает чтение.
///
/// Ответ смещён на два байта — так устроен обмен у этого чипа, и первые два
/// байта в нём мусорные. Печатаются они всё равно: увидеть `00 00 00 ...` или
/// `ff ff ff ...` полезно, это два разных отказа. Первое означает молчащую
/// линию данных, второе — отсутствующее устройство.
///
/// # Safety
///
/// Таблицы ядра активны.
unsafe fn probe_spi(fdt: &Fdt<'_>) {
    /// Адрес идентификатора внутри чипа.
    ///
    /// `0x1F64E`, а не `0x3F004`: второе стояло здесь раньше и взято не из
    /// драйвера этого кристалла. Читать оттуда — всё равно что спрашивать не по
    /// тому адресу и делать выводы из молчания.
    const TRIM_ADDRESS: u32 = 0x1_F64E;
    /// Выводы шины `spi3`: данные к нам, выбор кристалла, данные от нас, такт.
    const SPI3_PINS: [u32; 4] = [21, 22, 23, 24];
    /// Функция, под которой эти выводы принадлежат `spi3`.
    const SPI3_FUNCTION: u32 = 1;
    /// Контроллер, на котором висит панель: `spi3` из того же описания. Совпал
    /// с единственным, чья линия данных имеет подтяжку, — то есть измерение и
    /// исходники сошлись независимо.
    const TOUCH_SPI: u64 = 0x1101_3000;

    // Отпустить сброс — то, без чего всё остальное бессмысленно. Кристалл до
    // этого момента выключен, и линия данных читается подтяжкой: `ff ff ff ...`
    // на нужном контроллере и `00` на всех прочих. Именно это мы и видели.
    let pins = fdt
        .find("/gpio@10005000")
        .or_else(|| fdt.find_compatible("mediatek,mt6765-pinctrl"))
        .and_then(|node| {
            let (address_cells, size_cells) = root_cells(fdt);
            node.reg(address_cells, size_cells).next().map(|region| region.address)
        });
    match pins {
        Some(pins) if map_device_page(pins) => {
            // Сначала выводы шины, потом сброс. Порядок важен: кристалл,
            // отпущенный на линиях, которые ещё никуда не подключены, успевает
            // проснуться в пустоту.
            //
            // SAFETY: окно отображено; номера выводов и номер функции взяты из
            // описания кристалла, а не угаданы.
            let mut modes = [0u32; 4];
            unsafe {
                for (slot, pin) in SPI3_PINS.into_iter().enumerate() {
                    modes[slot] = super::mtk::gpio_mode(pins, pin, SPI3_FUNCTION);
                }
            }
            crate::kprintln!(
                "  touch       : spi3 pins 21-24 now read back as {} {} {} {}",
                modes[0], modes[1], modes[2], modes[3]
            );
        }
        _ => crate::kprintln!("  touch       : no pin controller, cannot set up the bus"),
    }

    let Some(base) = super::fdt_boot::spi_buses(fdt).into_iter().flatten().find(|base| *base == TOUCH_SPI)
    else {
        crate::kprintln!("  touch       : no spi controller at {TOUCH_SPI:#010x}");
        return;
    };
    if !map_device_page(base) {
        return;
    }

    // SAFETY: окно отображено выше как память устройства.
    let bus = unsafe { mtk_spi::Bus::new(base as usize) };
    // Четыре режима фазы такта и четыре набора выводов.
    //
    // Перебирались они и раньше, и ничего не значили: выводы тогда ещё не были
    // закреплены за шиной, и наружу не выходило ничего, какой режим ни ставь.
    // Теперь выходит — регистр режима читается обратно единицами, а время
    // передачи меняется вместе с делителем такта, — и опыт наконец задаёт
    // вопрос, а не повторяет сам себя.
    /// Сколько раз спросить одну и ту же комбинацию, прежде чем счесть её
    /// негодной. Столько же делает родной драйвер.
    const ATTEMPTS: u8 = 5;

    for pad in 0..2u32 {
        for mode in 0..4u8 {
        for attempt in 0..ATTEMPTS {
            // SAFETY: окно отображено; параметры перебираются.
            unsafe { bus.prepare(mtk_spi::Timing::Enhanced, mode, pad, 0x40) };

            // Последовательность запуска целиком, как у изготовителя. Каждый её
            // шаг по отдельности выглядит необязательным, и раньше мы делали
            // только последний — оттого и молчание.
            //
            // Повторяется она до пяти раз, и это тоже из драйвера. Причина
            // видна на соседних загрузках одной и той же машины: то верный
            // ответ с первой попытки, то нули. Кристалл поднимается не за
            // фиксированное время, и единственная попытка превращает исправное
            // железо в случайную величину.
            //
            // SAFETY: см. выше; окна отображены, выводы принадлежат шине.
            unsafe {
                // Кристалл держится в сбросе — и **в этом состоянии** принимает
                // ровно одну посылку, инженерный сброс. Она выводит его из того,
                // во что его оставил загрузчик.
                if let Some(pins) = pins {
                    super::mtk::gpio_output(pins, RESET_PIN, false);
                }
                write_addr(&bus, ENGINEERING_RESET_ADDRESS, ENGINEERING_RESET_VALUE);
                wait_ms(1);

                // Сброс отпускается, и кристаллу дают подняться.
                if let Some(pins) = pins {
                    super::mtk::gpio_output(pins, RESET_PIN, true);
                }
                wait_ms(10);

                // Перезапуск загрузчика кристалла и отключение быстрого чтения:
                // с ним обмен идёт по другому договору.
                write_addr(&bus, RESET_ADDRESS, RESET_VALUE);
                wait_ms(5);
                write_addr(&bus, FAST_READ_ADDRESS, 0x00);
            }

            // SAFETY: см. выше.
            let _ = unsafe { bus.transfer(&page_command(TRIM_ADDRESS), &mut []) };
            // Чтение: разряд направления **снят**, и передача на байт длиннее
            // запрошенного — первый принятый байт кристалл тратит на разгон.
            // Полезное начинается с третьего.
            let request = [read_command(TRIM_ADDRESS), 0, 0, 0, 0, 0, 0, 0];
            let mut answer = [0u8; 8];
            // SAFETY: см. выше.
            let _ = unsafe { bus.transfer(&request, &mut answer) };

            crate::kprintln!(
                "  touch       : pad {pad} mode {mode} id {:02x} {:02x} {:02x} {:02x} {:02x} {:02x}",
                answer[2], answer[3], answer[4], answer[5], answer[6], answer[7]
            );
            // Кристалл считается найденным, только если назвал **себя**.
            //
            // Прежний признак — «хоть один байт не ноль и не единицы» — слишком
            // слаб, и это выяснилось на аппарате: набор выводов с неверной
            // фазой такта выдал `85 80 00 12 b2 81`, признак сработал, и всё
            // дальнейшее читалось из мусора с полной уверенностью в успехе.
            // Мусор отличается от ответа не тем, что он не пустой, а тем, что
            // он не совпадает с известным.
            if identified(&answer[2..8]) {
                crate::kprintln!("  touch       : NT36525B answered on pad {pad} mode {mode}");
                // Имя панели даёт загрузчик, и по нему выбирается образ
                // прошивки: панелей у этого аппарата четыре разновидности, и
                // прошивка у каждой своя.
                let bootargs = fdt
                    .find("/chosen")
                    .and_then(|chosen| chosen.property_str("bootargs"))
                    .unwrap_or("");
                // SAFETY: шина настроена, кристалл опознан.
                unsafe { interrogate(&bus, pins, RESET_PIN, pad, mode, bootargs) };
                return;
            }

            // Не опознан — попробовать ещё раз ту же комбинацию, кристалл
            // поднимается не за фиксированное время.
            wait_ms(10);
        }
        }
    }

    // Контроллер сказал всё, что мог. Последнее слово — за обменом вручную.
    let Some(pins) = pins else { return };
    let mut answer = [0u8; 8];
    // SAFETY: окно отображено выше; выводы принадлежат `spi3`, и контроллер
    // этой шины больше не работает — мы забираем их себе.
    unsafe {
        bitbang(pins, &page_command(RESET_ADDRESS), &mut []);
        bitbang(pins, &[write_command(RESET_ADDRESS), RESET_VALUE], &mut []);
    }
    wait_ms(40);
    // SAFETY: см. выше.
    unsafe {
        bitbang(pins, &page_command(TRIM_ADDRESS), &mut []);
        bitbang(pins, &[read_command(TRIM_ADDRESS), 0, 0, 0, 0, 0, 0, 0], &mut answer);
    }
    crate::kprintln!(
        "  touch       : by hand, {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x}",
        answer[0], answer[1], answer[2], answer[3], answer[4], answer[5], answer[6], answer[7]
    );

    // Версия первая: **не отпускать выбор кристалла** между командой и чтением.
    // Родной драйвер отпускает, но у него между посылками работает вся остальная
    // машинерия ядра, а у нас голый обмен — и чип вполне может терять команду на
    // разрыве.
    //
    // Версия вторая: скорость. Мы идём на десятках килогерц, вендор — на 9,6 МГц.
    // Некоторые чипы на слишком медленном такте засыпают между битами.
    for slow in [1u32, 8] {
        let mut held = [0u8; 8];
        // SAFETY: окно отображено; выводы наши.
        unsafe {
            bitbang_select(pins, true);
            bitbang_bytes(pins, &page_command(TRIM_ADDRESS), &mut [], slow);
            bitbang_bytes(
                pins,
                &[read_command(TRIM_ADDRESS), 0, 0, 0, 0, 0, 0, 0],
                &mut held,
                slow,
            );
            bitbang_select(pins, false);
        }
        crate::kprintln!(
            "  touch       : cs held, slow {slow}, {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x}",
            held[0], held[1], held[2], held[3], held[4], held[5], held[6], held[7]
        );
    }

    // Версия третья: чип уже работает и ему есть что сказать — линия прерывания
    // прижата. Значит, спрашивать надо не «кто ты» (это вопрос загрузчику
    // кристалла), а «что у тебя есть»: буфер событий текущей страницы.
    let mut events = [0u8; 8];
    // SAFETY: см. выше.
    unsafe {
        bitbang_select(pins, true);
        bitbang_bytes(pins, &[0x80, 0, 0, 0, 0, 0, 0, 0], &mut events, 1);
        bitbang_select(pins, false);
    }
    crate::kprintln!(
        "  touch       : events, {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x}",
        events[0], events[1], events[2], events[3], events[4], events[5], events[6], events[7]
    );

    // Последнее непроверенное звено — и оно наше собственное. Что выводы шины
    // переключились, доказано чтением обратно; что **вывод сброса поднялся** —
    // ничем. Линия, которую держит внизу кто-то ещё, выглядит снаружи ровно как
    // отпущенная: запись проходит, а уровень не меняется.
    //
    // Заодно спрашивается вывод прерывания: живой кристалл после сброса дёргает
    // его сам, и его уровень — независимое свидетельство.
    // SAFETY: окно отображено; читается состояние, ничего не меняется.
    let (reset_high, irq_high) = unsafe {
        super::mtk::gpio_output(pins, RESET_PIN, true);
        wait_ms(20);
        (
            super::mtk::gpio_level(pins, RESET_PIN),
            super::mtk::gpio_input(pins, 0),
        )
    };
    crate::kprintln!(
        "  touch       : reset line reads {}, irq line reads {}",
        u8::from(reset_high),
        u8::from(irq_high)
    );
}

/// Обмен по SPI руками, без контроллера.
///
/// # Зачем такое вообще пишут
///
/// Затем, что иначе не отличить «кристалл молчит» от «блок, который с ним
/// говорит, настроен не так». Всё, что можно было измерить у контроллера,
/// измерено и работает: такт бежит и меняется вместе с делителем, выводы
/// закреплены и читаются обратно, сброс отпущен, режимы перебраны. И всё равно
/// линия данных стоит на подтяжке.
///
/// Обмен вручную выкидывает контроллер из цепочки целиком: такт, выбор
/// кристалла и данные выставляются как обычные выводы, по одному биту. Медленно
/// — но здесь скорость и не нужна, нужен ответ на один вопрос.
///
/// # Safety
///
/// `pins` — отображённое окно контроллера выводов; выводы принадлежат `spi3` и
/// в этот момент никем больше не используются.
unsafe fn bitbang(pins: u64, tx: &[u8], rx: &mut [u8]) {
    // SAFETY: контракт функции.
    unsafe {
        bitbang_select(pins, true);
        bitbang_bytes(pins, tx, rx, 1);
        bitbang_select(pins, false);
    }
}

/// Выводы шины `spi3`, вынесенные из тела: их спрашивают три разные функции.
const MISO: u32 = 21;
const CS: u32 = 22;
const MOSI: u32 = 23;
const CLK: u32 = 24;

/// Прижать или отпустить выбор кристалла.
///
/// Отдельно от передачи — чтобы можно было провести **две** посылки, не отпуская
/// его между ними. Родной драйвер отпускает, но родной драйвер и работает; у нас
/// же это одна из трёх оставшихся версий, и проверяется она одной строкой.
///
/// # Safety
///
/// См. [`bitbang`].
unsafe fn bitbang_select(pins: u64, active: bool) {
    // SAFETY: контракт функции. Выбор активен низким уровнем.
    unsafe {
        gpio_output(pins, CS, !active);
        gpio_output(pins, CLK, false);
        gpio_output(pins, MOSI, false);
        let _ = gpio_input(pins, MISO);
    }
    bitbang_tick(4);
}

/// Пауза между фронтами. `slow` умножает её — на медленном такте прощаются
/// длинные провода, на быстром чип не успевает заснуть между битами.
fn bitbang_tick(slow: u32) {
    for _ in 0..(50 * slow) {
        core::hint::spin_loop();
    }
}

/// Прокачать байты, не трогая выбор кристалла.
///
/// # Safety
///
/// См. [`bitbang`]; выбор кристалла должен быть уже прижат.
unsafe fn bitbang_bytes(pins: u64, tx: &[u8], rx: &mut [u8], slow: u32) {

    // SAFETY: контракт функции.
    unsafe {
        for index in 0..tx.len().max(rx.len()) {
            let byte = tx.get(index).copied().unwrap_or(0);
            let mut received = 0u8;
            for bit in (0..8).rev() {
                gpio_output(pins, MOSI, byte >> bit & 1 != 0);
                bitbang_tick(slow);
                gpio_output(pins, CLK, true);
                // Читается на фронте — так велит режим 0.
                if gpio_input(pins, MISO) {
                    received |= 1 << bit;
                }
                bitbang_tick(slow);
                gpio_output(pins, CLK, false);
            }
            if let Some(slot) = rx.get_mut(index) {
                *slot = received;
            }
        }
    }
}

/// Дёрнуть вывод сброса: прижать, выдержать, отпустить.
///
/// # Safety
///
/// `pins` — отображённое окно контроллера выводов, `pin` — вывод сброса.
unsafe fn gpio_reset(pins: u64, pin: u32) {
    // SAFETY: контракт функции.
    unsafe { super::mtk::gpio_output(pins, pin, false) };
    wait_ms(20);
    // SAFETY: см. выше.
    unsafe { super::mtk::gpio_output(pins, pin, true) };
    wait_ms(50);
}

/// Размеры ячеек корня — те же, что у всех остальных читателей дерева.
fn root_cells(fdt: &Fdt<'_>) -> (usize, usize) {
    let Some(root) = fdt.nodes().next() else {
        return (2, 1);
    };
    (
        root.property_u64("#address-cells").unwrap_or(2) as usize,
        root.property_u64("#size-cells").unwrap_or(1) as usize,
    )
}

/// Посылка «дальше говорим по этому адресу».
///
/// Первый байт — **`0x7f`**, и это не опечатка вместо `0xff`.
///
/// В драйвере Novatek команда выбора страницы записана как `0xFF`, но уходит
/// она через обёртку записи, а та накладывает маску `& 0x7f`. Старший бит у
/// этого чипа означает направление: взведённый — чтение. Отправленный `0xff`
/// поэтому значит не «переключись на страницу», а «прочитай регистр `0x7f`», и
/// страница не переключается вовсе.
///
/// Стоило это нескольких заходов к аппарату: чип отвечал молчанием совершенно
/// законно, а искали то питание, то сброс, то выводы. Ошибка была в одном бите
/// одного байта, и списана она прямо из исходника — но из той его строки, где
/// значение ещё не прошло через маску.
///
/// Следующие два байта — адрес, сдвинутый на пятнадцать и на семь.
fn page_command(address: u32) -> [u8; 3] {
    // Первый байт — `0xff`, а не `0x7f`. Разряд 7 у этого кристалла означает
    // «это запись», и посылка выбора страницы — тоже запись. Со снятым разрядом
    // чип читает её как чтение по адресу `0x7f` и страницу не меняет: всё
    // последующее уходит в ту, что была.
    [0xff, ((address >> 15) & 0xff) as u8, ((address >> 7) & 0xff) as u8]
}

/// Первый байт посылки: адрес плюс направление.
///
/// # Почему это отдельные функции, а не два места в коде
///
/// Потому что один раз они уже разъехались, и разъехались наоборот: чтение
/// уходило с разрядом записи, запись — без него. Кристалл в ответ на «запиши по
/// адресу идентификатора» честно молчал, а выглядело это как мёртвая шина, и
/// поиск ушёл в питание, выводы и тактирование по очереди.
///
/// Названия здесь — как у изготовителя (`SPI_READ_MASK`, `SPI_WRITE_MASK`),
/// чтобы следующий читатель мог сверить их глазами, не разбираясь в битах.
const fn read_command(address: u32) -> u8 {
    (address as u8) & 0x7f
}

const fn write_command(address: u32) -> u8 {
    (address as u8) | 0x80
}

/// Тот ли это кристалл.
///
/// Сверка идёт по таблице изготовителя и по его же маске: значимы первый байт и
/// последние три, средние два кристалл заполняет по-разному от партии к партии.
/// Именно так отличается ответ от мусора — не тем, что он не пустой.
fn identified(id: &[u8]) -> bool {
    /// `NT36525B` из `trim_id_table`: `{0x0B, 0xFF, 0xFF, 0x25, 0x65, 0x03}`
    /// с маской `{1, 0, 0, 1, 1, 1}`.
    const EXPECTED: [(usize, u8); 4] = [(0, 0x0b), (3, 0x25), (4, 0x65), (5, 0x03)];

    EXPECTED
        .iter()
        .all(|(at, value)| id.get(*at).is_some_and(|byte| byte == value))
}

/// Расспросить опознанный кристалл: готова ли прошивка и что она о себе знает.
///
/// # Зачем отдельный проход
///
/// Опознание доказало, что обмен работает, — но опознание отвечает загрузчик
/// кристалла, а касания считает прошивка. Между ними целое состояние: прошивка
/// поднимается после сброса не мгновенно и заявляет о готовности в своём
/// буфере событий. Спрашивать координаты, не дождавшись её, — значит читать
/// мусор и принимать его за касания.
///
/// Здесь всё это только **читается и печатается**. Разбирать отчёт и слать
/// события будет следующий шаг: наполовину угаданный протокол хуже
/// отсутствующего — он даёт координаты, и они неверны.
///
/// # Safety
///
/// Шина настроена, окна отображены, выводы принадлежат `spi3`.
unsafe fn interrogate(
    bus: &mtk_spi::Bus,
    pins: Option<u64>,
    reset_pin: u32,
    pad: u32,
    mode: u8,
    bootargs: &str,
) {
    const FIRMWARE_INFO: u32 = EVENT_MAP_FWINFO;

    // Аппаратный сброс. Дальше — не ожидание прошивки, а её **загрузка**.
    //
    // Ждать её здесь бессмысленно, и это выяснено опытом, а не выведено:
    // своей прошивки у кристалла нет вовсе, при включении в нём поднимается
    // только загрузчик. Прежний код ждал её секунду и объявлял кристалл
    // негодным — на исправном железе, которому просто не дали, что исполнять.
    // SAFETY: контракт функции.
    unsafe {
        if let Some(pins) = pins {
            gpio_output(pins, reset_pin, false);
            wait_ms(10);
            gpio_output(pins, reset_pin, true);
            wait_ms(10);
        }
    }

    let count = super::mtk_touch_fw::BLOBS.len();
    if count == 0 {
        crate::kprintln!(
            "  touch       : no firmware compiled in -- run `cargo xtask phone-firmware`"
        );
        return;
    }
    let chosen = super::mtk_touch_fw::choose(bootargs).unwrap_or(0);
    crate::kprintln!(
        "  touch       : no firmware of its own; loading image {} of {} ({})",
        chosen,
        count,
        super::mtk_touch_fw::BLOBS[chosen].vendor
    );
    // SAFETY: см. выше; настройка шины восстанавливается внутри перед каждой
    // посылкой.
    let outcome = unsafe {
        super::mtk_touch_fw::download(
            bus,
            pins,
            reset_pin,
            event_base(),
            &super::mtk_touch_fw::BLOBS[chosen],
            pad,
            mode,
        )
    };
    let up = match outcome {
        super::mtk_touch_fw::Outcome::Up(ms) => {
            crate::kprintln!("  touch       : firmware came up after {ms} ms");
            FIRMWARE_UP.store(1, Ordering::Relaxed);
            true
        }
        super::mtk_touch_fw::Outcome::Silent(state) => {
            crate::kprintln!(
                "  touch       : firmware written but silent, state {state:02x} (checksum refused?)"
            );
            false
        }
        super::mtk_touch_fw::Outcome::Broken => {
            crate::kprintln!("  touch       : the firmware image did not parse");
            false
        }
    };

    // Сведения о прошивке читаются с повтором, и это не перестраховка. Первое
    // чтение сразу после её подъёма приходит то полным, то пустым: прошивка в
    // этот миг ещё раскладывает свой буфер. Родной драйвер повторяет трижды, и
    // без повтора одна и та же машина то опознаёт панель, то нет — на соседних
    // загрузках, без единой правки в коде.
    let mut info = [0u8; 30];
    let mut sane = false;
    for _ in 0..3 {
        // SAFETY: см. выше.
        info = unsafe { read_event(bus, event_base(), FIRMWARE_INFO, 17) }.0;
        // Версия и её дополнение до 0xff — проверка, которую делает и родной
        // драйвер: сведения читаются по одному байту, и сбитый обмен даёт
        // правдоподобные числа, не сходящиеся между собой.
        sane = (u16::from(info[0]) + u16::from(info[1])) == 0xff;
        if sane {
            break;
        }
        wait_ms(10);
    }
    crate::kprintln!(
        "  touch       : firmware {:#04x}, panel {}x{}, {} nodes, {} keys, checksum {}",
        info[0],
        (u16::from(info[4]) << 8) | u16::from(info[5]),
        (u16::from(info[6]) << 8) | u16::from(info[7]),
        info[2],
        info[10],
        if sane { "ok" } else { "BROKEN" }
    );

    // Кристалл берётся **и тогда, когда прошивка не поднялась**, и это не
    // небрежность. Пока он у нас, к нему можно обратиться по кабелю: положить
    // другой из четырёх образов, перечитать регистры, пересбросить. Отказаться
    // от него здесь значило бы запереть себя без единой возможности спросить —
    // ровно та ошибка, которая стоила этой задаче нескольких вечеров.
    if !up {
        crate::kprintln!(
            "  touch       : keeping the chip anyway -- try `fastboot oem tfw <0..{}>`",
            count - 1
        );
    }
    // Несошедшиеся сведения — не повод отказываться от панели. Родной драйвер
    // в этом случае берёт размеры по умолчанию и работает дальше, и он прав:
    // координаты приходят не отсюда, а из отчёта о касаниях, и панель этого
    // аппарата всё равно 720x1600. Отказ здесь означал бы машину без ввода
    // из-за одного неудачно прочитанного байта.

    *SPI_TOUCH.lock() = Some(SpiTouch {
        bus: *bus,
        pins,
        pad,
        mode,
        down: false,
        seen: 0,
        ticks: 0,
        last: (0, 0),
        polls: 0,
        stalled: 0,
        live: 0,
        asserted: 0,
        last_report: [0; 12],
    });
    crate::kprintln!("  touch       : NT36525B on spi3 is ours; polling for fingers");
}

/// Сырой отчёт панели — для расспроса по кабелю.
///
/// Существует ради одного вопроса, на который иначе не ответить: человек держит
/// палец на экране **сейчас**, и надо увидеть, что панель говорит об этом
/// именно сейчас. Журнал для этого не годится — он рассказывает о прошлом, а
/// печатать в него на каждом опросе значит утопить всё остальное.
#[must_use]
pub fn raw_report() -> Option<[u8; 30]> {
    let guard = SPI_TOUCH.lock();
    let touch = guard.as_ref()?;
    // SAFETY: окна отображены, выводы наши; настройка восстанавливается внутри.
    Some(unsafe { touch.read(0x00, 13) }.0)
}

/// Прочитать по кабелю произвольное смещение буфера событий.
///
/// Нужно ровно затем, зачем и [`raw_report`]: спрашивать живой кристалл в тот
/// миг, когда человек держит палец. Смещение приходит снаружи, потому что
/// вопрос «а что лежит вот здесь» возникает по одному на заход, и городить под
/// каждый свою переменную — это по прошивке на вопрос.
#[must_use]
pub fn raw_at(offset: u32, len: usize) -> Option<[u8; 30]> {
    let guard = SPI_TOUCH.lock();
    let touch = guard.as_ref()?;
    // SAFETY: см. [`raw_report`].
    Some(unsafe { touch.read(offset, len) }.0)
}

impl SpiTouch {
    /// Прочитать из буфера событий, восстановив настройку шины.
    ///
    /// # Safety
    ///
    /// Окна отображены, выводы принадлежат `spi3`.
    unsafe fn read(&self, offset: u32, len: usize) -> ([u8; 30], bool) {
        // SAFETY: контракт функции. Настройка ставится заново каждый раз — см.
        // объяснение у полей `pad` и `mode`.
        unsafe {
            self.bus
                .prepare(mtk_spi::Timing::Enhanced, self.mode, self.pad, clock_half());
            read_event(&self.bus, event_base(), offset, len)
        }
    }

    /// Настроить шину заново — перед любым обменом, всегда.
    ///
    /// # Safety
    ///
    /// Окно отображено, выводы принадлежат `spi3`.
    unsafe fn setup(&self) {
        // SAFETY: контракт функции.
        unsafe {
            self.bus
                .prepare(mtk_spi::Timing::Enhanced, self.mode, self.pad, clock_half());
        }
    }
}

/// Что вернуло чтение по произвольному адресу.
///
/// Число опросов возвращается наружу, а не выбрасывается, потому что оно
/// отвечает на вопрос, который иначе не задать: **шли ли биты по проводам**.
/// Ноль означает, что передача не завершилась вовсе, а не что кристалл ответил
/// нулями, — и это две совершенно разные неисправности, выглядящие снаружи
/// одинаково.
pub struct Probe {
    pub bytes: [u8; 30],
    pub len: usize,
    /// Опросов на посылке выбора страницы; ноль — не завершилась.
    pub page_spins: u32,
    /// Опросов на посылке чтения; ноль — не завершилась.
    pub data_spins: u32,
}

/// Прочитать байты по **полному** адресу внутри кристалла.
///
/// # Чем отличается от [`raw_at`]
///
/// Тем, что адрес полный, а не смещение внутри буфера событий. Буфер событий —
/// это догадка (их две в таблице изготовителя), и проверить догадку, умея
/// читать только внутри неё, нельзя по построению.
#[must_use]
pub fn read_raw(address: u32, len: usize) -> Option<Probe> {
    let guard = SPI_TOUCH.lock();
    let touch = guard.as_ref()?;
    let len = len.clamp(1, 30);
    let mut request = [0u8; 32];
    let mut answer = [0u8; 32];
    request[0] = read_command(address);
    // SAFETY: окна отображены, выводы принадлежат `spi3`.
    let (page_spins, data_spins) = unsafe {
        touch.setup();
        let page = touch.bus.transfer(&page_command(address), &mut []);
        let data = touch
            .bus
            .transfer(&request[..len + 2], &mut answer[..len + 2]);
        (page.unwrap_or(0), data.unwrap_or(0))
    };
    let mut bytes = [0u8; 30];
    bytes[..len].copy_from_slice(&answer[2..len + 2]);
    Some(Probe { bytes, len, page_spins, data_spins })
}

/// Записать байт по **полному** адресу внутри кристалла.
///
/// # Чем это опасно и почему всё-таки есть
///
/// Тем, что кристаллу можно сказать лишнее. Опасность ограничена тем, что
/// прошивка живёт во внешней памяти и пишется только особой
/// последовательностью, которой здесь нет: всё, до чего дотягивается эта
/// функция, — оперативная память кристалла и его управляющие регистры, и
/// худшее, что выйдет, — сброс.
///
/// А без неё не проверить ни одной догадки о том, чего прошивка ждёт, чтобы
/// начать докладывать о касаниях, — а именно на этом всё и стоит.
#[must_use]
pub fn write_raw(address: u32, value: u8) -> bool {
    let guard = SPI_TOUCH.lock();
    let Some(touch) = guard.as_ref() else {
        return false;
    };
    // SAFETY: окна отображены, выводы принадлежат `spi3`.
    unsafe {
        touch.setup();
        write_addr(&touch.bus, address, value);
    }
    true
}

/// Сменить адрес буфера событий, которым пользуются опрос и чтение по кабелю.
pub fn set_event_base(address: u32) {
    EVENT_BASE.store(address, Ordering::Relaxed);
}

/// Кто опрашивает панель и слать ли события наверх.
pub fn set_poll_source(mask: u8) {
    POLL_SOURCE.store(mask & 0x03, Ordering::Relaxed);
}

pub fn set_reporting(on: bool) {
    REPORTING.store(u8::from(on), Ordering::Relaxed);
}

/// Пересбросить кристалл и дождаться, пока прошивка заявит о готовности.
///
/// `hard` означает «дёрнуть вывод сброса»; иначе делается только программный
/// сброс загрузчика кристалла. Возвращает состояние и число миллисекунд, за
/// которое оно стало годным, — а если так и не стало, полное время ожидания.
#[must_use]
pub fn reset_chip(hard: bool) -> Option<([u8; 30], u32)> {
    let guard = SPI_TOUCH.lock();
    let touch = guard.as_ref()?;
    // SAFETY: окна отображены, выводы принадлежат `spi3`.
    unsafe {
        touch.setup();
        if hard {
            if let Some(pins) = touch.pins {
                // Пока вывод сброса прижат, кристалл принимает ровно одну
                // посылку — инженерный сброс. Порядок взят у изготовителя
                // целиком: каждый его шаг по отдельности выглядит лишним.
                gpio_output(pins, RESET_PIN, false);
                write_addr(&touch.bus, ENGINEERING_RESET_ADDRESS, ENGINEERING_RESET_VALUE);
                wait_ms(1);
                gpio_output(pins, RESET_PIN, true);
                wait_ms(10);
            }
        }
        write_addr(&touch.bus, RESET_ADDRESS, RESET_VALUE);
        wait_ms(5);
        write_addr(&touch.bus, FAST_READ_ADDRESS, 0x00);
    }

    let mut state = [0u8; 30];
    let mut rounds = 0u32;
    while rounds < 100 {
        wait_ms(10);
        rounds += 1;
        // SAFETY: см. выше.
        state = unsafe { touch.read(EVENT_MAP_RESET_COMPLETE, 6) }.0;
        if (0xa0..=0xaf).contains(&state[0]) {
            break;
        }
    }
    Some((state, rounds * 10))
}

/// Сказать прошивке, в каком режиме работать, — и подтвердить готовность хоста.
///
/// Это `nvt_change_mode` изготовителя целиком: команда в `0x50`, а для обычного
/// режима ещё и рукопожатие `0xBB` в `0x51` через двадцать миллисекунд. Второй
/// половины у нас не было ни разу, а прошивка вполне может ждать именно её,
/// прежде чем начать складывать отчёты в буфер.
#[must_use]
pub fn change_mode(mode: u8) -> bool {
    let base = event_base();
    if !write_raw(base | EVENT_MAP_HOST_CMD, mode) {
        return false;
    }
    if mode == 0x00 {
        wait_ms(20);
        let _ = write_raw(base | EVENT_MAP_HANDSHAKE, 0xbb);
        wait_ms(20);
    }
    true
}

pub use super::mtk_touch_fw::Outcome;

/// Положить в кристалл образ прошивки и запустить его.
///
/// # Зачем это вообще нужно
///
/// Затем, что своей прошивки у этого кристалла нет — см. [`super::mtk_touch_fw`].
/// Пока её не положишь, панель отвечает на любой вопрос о себе и молчит о
/// касаниях, и молчание это выглядит как что угодно, только не как отсутствие
/// прошивки.
///
/// Номер образа приходит снаружи, потому что панелей у этого аппарата четыре
/// разновидности, а какая стоит здесь — известно только из имени, которое даёт
/// загрузчик, и не всегда.
#[must_use]
pub fn load_firmware(index: usize) -> Option<Outcome> {
    let guard = SPI_TOUCH.lock();
    let touch = guard.as_ref()?;
    let blob = super::mtk_touch_fw::BLOBS.get(index)?;
    // SAFETY: окна отображены, выводы принадлежат `spi3`; настройка шины
    // восстанавливается внутри перед каждой посылкой.
    let outcome = unsafe {
        super::mtk_touch_fw::download(
            &touch.bus,
            touch.pins,
            RESET_PIN,
            event_base(),
            blob,
            touch.pad,
            touch.mode,
        )
    };
    // Удавшаяся загрузка по кабелю значит ровно то же, что удавшаяся при
    // поиске: панель работает. Стол от этого уже не поедет — его решение
    // принято при загрузке, — но опрос начнёт давать координаты, и увидеть их
    // можно тут же, `oem tstat`.
    if matches!(outcome, Outcome::Up(_)) {
        FIRMWARE_UP.store(1, Ordering::Relaxed);
    }
    Some(outcome)
}

/// Сколько образов прошивки вкомпилировано.
#[must_use]
pub fn firmware_count() -> usize {
    super::mtk_touch_fw::BLOBS.len()
}

/// Счётчики опроса — чтобы спросить по кабелю, что видит опрос сам.
#[derive(Clone, Copy)]
pub struct Stats {
    pub polls: u32,
    /// Проходов, где передача не дошла до провода.
    pub stalled: u32,
    /// Проходов, где отчёт был не пуст.
    pub live: u32,
    /// Проходов, где линия прерывания была прижата.
    pub asserted: u32,
    /// Последний непустой отчёт.
    pub last: [u8; 12],
    pub source: u8,
    pub reporting: bool,
    pub base: u32,
}

#[must_use]
pub fn stats() -> Option<Stats> {
    let guard = SPI_TOUCH.lock();
    let touch = guard.as_ref()?;
    Some(Stats {
        polls: touch.polls,
        stalled: touch.stalled,
        live: touch.live,
        asserted: touch.asserted,
        last: touch.last_report,
        source: POLL_SOURCE.load(Ordering::Relaxed),
        reporting: REPORTING.load(Ordering::Relaxed) != 0,
        base: event_base(),
    })
}

/// Уровень линии прерывания панели.
///
/// У Novatek она активна низким: кристалл тянет её вниз, когда ему есть что
/// сказать. Ноль под пальцем и пустой буфер событий — это разные неисправности,
/// и различает их только это число.
#[must_use]
pub fn irq_level() -> Option<bool> {
    let guard = SPI_TOUCH.lock();
    let pins = guard.as_ref()?.pins?;
    // SAFETY: окно блока выводов отображено при поиске.
    Some(unsafe { gpio_input(pins, IRQ_PIN) })
}

/// Опросить панель из задачи USB, если ей это поручено.
///
/// Кому поручено, решает [`POLL_SOURCE`] и меняется по кабелю. До сих пор
/// опрашивали **обе** задачи разом, а объяснение при этом гласило, что одна из
/// них до провода не доходит: два утверждения, которые не могут быть верны
/// одновременно и ни разу не проверялись по отдельности.
pub fn poll_from_here() {
    if POLL_SOURCE.load(Ordering::Relaxed) & 1 != 0 {
        poll_spi_once();
    }
}

/// Один опрос панели: есть ли палец и где.
///
/// # Формат отчёта
///
/// Шесть байт на палец, подряд, начиная с самого начала буфера событий. У
/// первого байта старшие пять разрядов — номер пальца (нумерация с единицы,
/// ноль означает «этого пальца нет»), младшие три — что с ним происходит:
/// единица и двойка означают «на экране», всё прочее — снят.
///
/// Координата занимает полтора байта: старшие восемь разрядов лежат отдельно,
/// младшие четыре — в половинке общего байта. Собирать их надо именно так, а
/// не брать один старший байт: панель 720 точек шириной, и потеря младших
/// разрядов дала бы курсор, прыгающий шагами по шестнадцать точек.
fn poll_spi_once() {
    let mut guard = SPI_TOUCH.lock();
    let Some(touch) = guard.as_mut() else {
        return;
    };

    touch.polls = touch.polls.wrapping_add(1);
    touch.ticks = touch.ticks.wrapping_add(1);

    // Линия прерывания спрашивается **до** чтения, а не после.
    //
    // У Novatek она прижимается, когда отчёт готов, и отпускается, когда его
    // забрали. Прижата ли она в тот миг, когда мы читаем, — единственное, что
    // отличает «прошивка не докладывает» от «докладывает, а мы приходим не
    // вовремя», и стоит это одного чтения регистра.
    let asserted = match touch.pins {
        // SAFETY: окно блока выводов отображено при поиске.
        Some(pins) => !unsafe { gpio_input(pins, IRQ_PIN) },
        None => false,
    };
    if asserted {
        touch.asserted = touch.asserted.wrapping_add(1);
    }

    // SAFETY: окна отображены, выводы наши; настройка восстанавливается внутри.
    // Двенадцать байт, а не тридцать. Длина здесь не безразлична и проверена
    // опытом: то же самое смещение, прочитанное двенадцатью байтами, отдаёт
    // содержимое, а тридцатью — сплошные единицы, хотя контроллер отчитывается
    // об успешной передаче. Двенадцати хватает на два пальца.
    let (report, reached) = unsafe { touch.read(0x00, 12) };
    if !reached {
        // Передача не вышла на провод — значит панель ничего не сказала, а не
        // сказала «пальца нет». Разница видна на аппарате: около трёх процентов
        // чтений не доходят, и при шестидесяти пяти опросах в секунду это два
        // ложных отпускания в секунду. Посреди перетаскивания окно от такого
        // выскальзывает из-под пальца.
        //
        // Поэтому здесь возврат, а не разбор пустого отчёта: о состоянии пальца
        // судить можно только по тому, что кристалл ответил.
        touch.stalled = touch.stalled.wrapping_add(1);
        return;
    }

    // Отчёт из одних единиц или одних нулей — не отчёт.
    //
    // Единицы означают, что линию данных никто не вёл; нули — что кристалл
    // ответил, но сказать ему нечего. Ни то ни другое не разбирается, но и в
    // журнал больше не печатается: опрос идёт сотни раз в секунду, а спросить,
    // что он видит, теперь можно по кабелю (`fastboot oem tstat`).
    let empty = report[..12].iter().all(|byte| *byte == 0xff)
        || report[..12].iter().all(|byte| *byte == 0x00);
    if !empty {
        touch.live = touch.live.wrapping_add(1);
        touch.last_report.copy_from_slice(&report[..12]);
        if touch.seen < 8 {
            touch.seen += 1;
            crate::kprintln!(
                "  touch       : REPORT {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x} {:02x}",
                report[0], report[1], report[2], report[3],
                report[4], report[5], report[6], report[7]
            );
        }
    }
    if empty {
        if touch.down {
            touch.down = false;
            if REPORTING.load(Ordering::Relaxed) != 0 {
                post_pointer_at(touch.last.0, touch.last.1, 0, Buttons::NONE);
            }
        }
        return;
    }

    let identifier = report[0] >> 3;
    let state = report[0] & 0x07;
    if identifier == 0 || !(state == 0x01 || state == 0x02) {
        if touch.down {
            touch.down = false;
            if REPORTING.load(Ordering::Relaxed) != 0 {
                post_pointer_at(touch.last.0, touch.last.1, 0, Buttons::NONE);
            }
        }
        return;
    }

    let x = (u16::from(report[1]) << 4) | u16::from(report[3] >> 4);
    let y = (u16::from(report[2]) << 4) | u16::from(report[3] & 0x0f);
    if x > SCREEN.0 || y > SCREEN.1 {
        return; // панель врать умеет; за её краем щёлкать нечему
    }

    let point = to_fractions(x, y);
    touch.down = true;
    touch.last = point;
    if REPORTING.load(Ordering::Relaxed) != 0 {
        post_pointer_at(point.0, point.1, 0, Buttons::LEFT);
    }
}

/// Прочитать из буфера событий прошивки.
///
/// Страница выбирается **вместе со смещением** — так делает родной драйвер, и
/// это не украшение: у кристалла адрес разрезан на страницу и смещение, и
/// выбрать страницу без смещения значит попасть в её начало.
///
/// Возвращает до 20 байт полезных данных, уже без двух служебных в начале
/// принятого.
///
/// # Safety
///
/// См. [`interrogate`].
pub(super) unsafe fn read_event(bus: &mtk_spi::Bus, buffer: u32, offset: u32, len: usize) -> ([u8; 30], bool) {
    let mut answer = [0u8; 32];
    let mut request = [0u8; 32];
    // Тридцать — предел не наш, а контроллера: его память передачи вмещает
    // тридцать два байта вместе с двумя служебными.
    let len = len.min(30);
    request[0] = read_command(offset);
    // SAFETY: контракт функции.
    let done = unsafe {
        let page = bus.transfer(&page_command(buffer | offset), &mut []);
        let data = bus.transfer(&request[..len + 2], &mut answer[..len + 2]);
        page.is_some() && data.is_some()
    };
    let mut out = [0u8; 30];
    out[..len].copy_from_slice(&answer[2..len + 2]);
    // Признак возвращается наружу, а не теряется. «Передача не дошла до
    // провода» и «кристалл ответил единицами» — разные вещи, а выглядят
    // одинаково: и там и там на руках `ff`.
    (out, done)
}

/// Записать байт по адресу внутри кристалла.
///
/// Две посылки, и обе — записи: сначала «дальше говорим по этой странице»,
/// потом сам байт. Разделять их нельзя, страница живёт до следующей смены.
///
/// # Safety
///
/// Окно шины отображено, выводы за ней закреплены.
pub(super) unsafe fn write_addr(bus: &mtk_spi::Bus, address: u32, value: u8) {
    // SAFETY: контракт функции.
    unsafe {
        let _ = bus.transfer(&page_command(address), &mut []);
        let _ = bus.transfer(&[write_command(address), value], &mut []);
    }
}

/// Подождать столько миллисекунд, сколько просит чип после сброса.
///
/// По счётчику тиков, а не циклом заданной длины: тактовая частота этой машины
/// нам не принадлежит, и «тридцать пять миллисекунд» превратились бы в три или
/// в триста.
fn wait_ms(ms: u64) {
    let until = crate::time::uptime_ms() + ms;
    while crate::time::uptime_ms() < until {
        core::hint::spin_loop();
    }
}

/// Нашёлся ли читаемый тачскрин.
#[must_use]
pub fn present() -> bool {
    TOUCH.lock().is_some()
        || (SPI_TOUCH.lock().is_some() && FIRMWARE_UP.load(Ordering::Relaxed) != 0)
}

/// Отобразить страницу регистров как память устройства.
pub fn map_device_page(base: u64) -> bool {
    // Округление вниз до страницы обязательно: блок настройки выводов лежит по
    // `0x10002a00`, то есть внутри страницы, а не с её начала, и отображение
    // такого адреса отвергается как невыровненное. Регистры от этого не
    // сдвигаются — по своему полному адресу они и останутся.
    let phys = crate::mm::PhysAddr::new(base).page_align_down();
    let base = phys.as_u64();
    // SAFETY: адрес взят из дерева машины и описывает регистры контроллера;
    // таблицы ядра активны, Device-семантика для регистров обязательна.
    let mapped = unsafe {
        crate::arch::map_active(
            crate::mm::VirtAddr::new(base as usize),
            phys,
            crate::mm::PAGE_SIZE,
            crate::mm::PageFlags::READ
                .union(crate::mm::PageFlags::WRITE)
                .union(crate::mm::PageFlags::DEVICE),
        )
    };
    match mapped {
        Ok(()) => true,
        Err(err) => {
            crate::kprintln!("  touch       : cannot map i2c window {base:#010x}: {err:?}");
            false
        }
    }
}

/// Служебная задача: опрашивать контроллер и превращать касания в события.
///
/// Частота опроса — компромисс, названный вслух: реже двухсот раз в секунду
/// палец начинает «прыгать» по экрану на быстром движении, чаще — шина занята
/// без пользы. Пять миллисекунд между посылками дают двести опросов.
pub fn service_task() {
    loop {
        poll_once();
        crate::sched::sleep_ms(5);
    }
}

fn poll_once() {
    if POLL_SOURCE.load(Ordering::Relaxed) & 2 != 0 {
        poll_spi_once();
    }

    let mut guard = TOUCH.lock();
    let Some(touch) = guard.as_mut() else {
        return;
    };
    match touch.kind {
        Kind::Focaltech => focaltech(touch),
        Kind::Goodix => goodix(touch),
    }
}

/// Focaltech: три байта состояния и четыре байта координат, всё подряд.
///
/// Читается с регистра `0x02`: сначала число касаний, затем старший и младший
/// байты X и Y первой точки. Старшие четыре бита каждого старшего байта заняты
/// не координатой — в X это признак события (нажатие, отпускание, удержание), в
/// Y номер пальца, — и не срезать их значит получить координату, скачущую на
/// тысячи точек.
fn focaltech(touch: &mut Touch) {
    let mut report = [0u8; 5];
    // SAFETY: шина подготовлена при поиске, окно отображено.
    if unsafe { touch.bus.transfer(touch.address, &[0x02], &mut report) }.is_err() {
        return;
    }
    let points = report[0] & 0x0f;
    if points == 0 {
        release(touch);
        return;
    }
    let x = (u16::from(report[1] & 0x0f) << 8) | u16::from(report[2]);
    let y = (u16::from(report[3] & 0x0f) << 8) | u16::from(report[4]);
    press(touch, x, y);
}

/// Goodix: регистры шестнадцатибитные, а признак касания снимает читатель.
///
/// Последнее не мелочь: не сбросить старший бит регистра состояния значит
/// читать одно и то же касание вечно — палец давно отпущен, а контроллер
/// продолжает отдавать ту же точку.
fn goodix(touch: &mut Touch) {
    let mut status = [0u8; 1];
    // SAFETY: см. `focaltech`.
    if unsafe { touch.bus.transfer(touch.address, &[0x81, 0x4e], &mut status) }.is_err() {
        return;
    }
    if status[0] & 0x80 == 0 {
        return; // данных ещё нет — состояние не трогаем
    }
    let points = status[0] & 0x0f;

    let mut report = [0u8; 4];
    // SAFETY: см. выше. Координаты первой точки лежат за номером пальца.
    let read = unsafe { touch.bus.transfer(touch.address, &[0x81, 0x50], &mut report) };

    // Снять признак обязательно, и обязательно в любом случае: выход по ошибке
    // чтения без сброса оставил бы контроллер с невыбранными данными навсегда.
    // SAFETY: см. выше.
    let _ = unsafe { touch.bus.transfer(touch.address, &[0x81, 0x4e, 0x00], &mut []) };

    if read.is_err() || points == 0 {
        release(touch);
        return;
    }
    let x = u16::from(report[0]) | (u16::from(report[1]) << 8);
    let y = u16::from(report[2]) | (u16::from(report[3]) << 8);
    press(touch, x, y);
}

/// Палец на экране: курсор туда и левая кнопка нажата.
///
/// Тачскрин отдаёт положение, а не приращение, поэтому событие абсолютное — то
/// же, чем описывается планшет. Курсор при этом прыгает к пальцу, и это верно:
/// на экране, которого касаются, «плавное подведение» было бы враньём.
fn press(touch: &mut Touch, x: u16, y: u16) {
    let point = to_fractions(x, y);
    touch.down = true;
    touch.last = point;
    post_pointer_at(point.0, point.1, 0, Buttons::LEFT);
}

/// Палец снят. Отправляется один раз: повторное отпускание композитор считал бы
/// новым щелчком, — и отправляется **туда же**, где палец был: иначе отпускание
/// достаётся не тому, по чему щёлкнули.
fn release(touch: &mut Touch) {
    if !touch.down {
        return;
    }
    touch.down = false;
    post_pointer_at(touch.last.0, touch.last.1, 0, Buttons::NONE);
}

/// Перевести точки панели в доли экрана.
///
/// Событие указателя несёт **доли**, а не точки, и это не мелочь: драйвер не
/// знает размера экрана и знать его не обязан, а диапазон у каждого устройства
/// свой. Отдать сюда точки означало бы курсор, жмущийся к левому верхнему углу
/// ровно во столько раз, во сколько экран шире диапазона.
fn to_fractions(x: u16, y: u16) -> (u16, u16) {
    let clamp = |value: u16, span: u16| -> u16 {
        let span = span.max(1);
        let value = u32::from(value.min(span - 1));
        (value * u32::from(u16::MAX) / u32::from(span - 1).max(1)) as u16
    };
    (clamp(x, SCREEN.0), clamp(y, SCREEN.1))
}
