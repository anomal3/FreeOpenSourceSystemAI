//! Тачскрин телефона: найти контроллер на шине и читать с него касания.
//!
//! # Почему поиск, а не адрес в коде
//!
//! Заводское дерево устройств про тачскрин молчит: узел `/touch` несёт одно
//! свойство `compatible = "mediatek,touch"` — ни шины, ни адреса. Так у
//! MediaTek устроено всё семейство: контроллер регистрируется платформенным
//! кодом, а какой чип впаян в эту партию, дерево не знает. У `dandelion`
//! возможны три (Focaltech, Novatek, Himax), и в разных партиях стоят разные.
//!
//! Значит, вбитый в код адрес был бы ядром, работающим на части аппаратов и
//! молча не работающим на остальных. Поэтому шины опрашиваются.
//!
//! # Что делается с найденным
//!
//! Полностью читаются два семейства, у которых протокол короткий и целиком
//! опубликован: Focaltech и Goodix. Остальные, если отзовутся, называются в
//! журнале по адресу и не трогаются: наполовину угаданный протокол хуже
//! отсутствующего — он даёт координаты, и они неверны.
//!
//! # Опрос, а не прерывание
//!
//! Прерывание тачскрина приходит через вывод общего назначения, и чтобы его
//! разрешить, нужны и контроллер выводов, и таблица их назначения, и разбор
//! `interrupts` у узла, которого нет. Опрос раз в несколько миллисекунд стоит
//! одной короткой посылки по I²C и снимает всё это целиком.

use super::mtk_i2c::{self, Bus, Error, Layout};
use crate::input::{Buttons, post_pointer_at};
use crate::sync::SpinLock;
use fdt::Fdt;

/// Кого умеем читать.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Kind {
    /// FT5x06 и родня: карта регистров плоская, координаты с восьмого байта.
    Focaltech,
    /// GT9xx: регистры шестнадцатибитные, признак касания надо снимать самим.
    Goodix,
}

/// Адреса, на которых стоит спрашивать, и кем они окажутся.
///
/// Список закрытый, и это осознанно: полный обход ста двенадцати адресов на
/// семи шинах занимает время и находит вдобавок контроллер питания, датчики и
/// зарядку — всё то, чему наш вопрос безразличен, но чей ответ пришлось бы
/// отличать от нужного.
const KNOWN: [(u8, Kind); 4] = [
    (0x38, Kind::Focaltech),
    (0x70, Kind::Focaltech),
    (0x5d, Kind::Goodix),
    (0x14, Kind::Goodix),
];

/// Адреса, которые стоит назвать, даже не умея с ними говорить.
///
/// Найденный, но не прочитанный контроллер — это половина ответа, и она дороже
/// молчания: в следующий раз известно, какой протокол писать, и не надо снова
/// идти к аппарату.
const NAMED: [(u8, &str); 4] = [
    (0x62, "Novatek"),
    (0x01, "Novatek"),
    (0x48, "Himax"),
    (0x49, "Himax"),
];

/// Найденный тачскрин.
struct Touch {
    bus: Bus,
    address: u8,
    kind: Kind,
    /// Последнее состояние: было ли касание. Нужно, чтобы отпускание
    /// отправлялось ровно один раз, а не каждым опросом.
    down: bool,
    /// Где палец был в последний раз, уже в долях экрана. Отпускание шлётся
    /// сюда же: курсор, уехавший в угол на снятие пальца, означал бы, что щелчок
    /// достаётся не тому, по чему щёлкнули.
    last: (u16, u16),
}

static TOUCH: SpinLock<Option<Touch>> = SpinLock::new(None);

/// Размер панели. Координаты контроллер отдаёт в точках экрана, но врать он
/// умеет, и обрезка по этим числам дешевле, чем курсор, уехавший за буфер.
const SCREEN: (u16, u16) = (
    super::fdt_boot::DEFAULT_SCREEN.0 as u16,
    super::fdt_boot::DEFAULT_SCREEN.1 as u16,
);

/// Обойти шины и найти тачскрин. Возвращает `true`, если нашёлся читаемый.
///
/// # Safety
///
/// Таблицы ядра активны, дерево ещё не переиспользовано.
pub unsafe fn probe(fdt: &Fdt<'_>) -> bool {
    let mut found = None;

    // Такт — раньше опроса. Четыре шины из семи молчат вовсе, а молчащий блок
    // без такта неотличим от блока, на котором никого нет.
    // SAFETY: таблицы ядра активны, окно отображается внутри.
    unsafe { super::mtk::ungate_infra(fdt) };

    for window in super::fdt_boot::i2c_buses(fdt) {
        let Some(window) = window else { continue };
        let base = window.base;
        // Окно регистров надо отобразить: карта памяти описывает ОЗУ и
        // зарезервированное, а регистры контроллеров в неё не входят.
        if !map_device_page(base) {
            continue;
        }

        for layout in [mtk_i2c::V1, mtk_i2c::V2] {
            // SAFETY: окно отображено выше как память устройства.
            let bus = unsafe { Bus::new(base as usize, layout) };
            // SAFETY: то же окно, доступ к этому контроллеру только отсюда.
            let virgin = unsafe { bus.prepare() };

            // Первый вопрос задаётся одному адресу и служит проверкой самой
            // раскладки: если контроллер не отвечает даже отказом, значит либо
            // раскладка не та, либо шина не тактируется. И то и другое означает
            // «здесь спрашивать нечего», и сто двенадцать адресов подряд стоило
            // бы это выяснять втрое дольше.
            // SAFETY: см. выше.
            let alive = unsafe { bus.transfer(0x38, &[], &mut [0u8; 1]) } != Err(Error::Timeout);
            if !alive {
                // Молчание тоже надо назвать: иначе шина, которой не подведён
                // такт, выглядит как отсутствующая, и её не станут искать.
                if layout.name == "v2" {
                    crate::kprintln!("  touch       : i2c {base:#010x} does not answer at all");
                }
                continue;
            }

            // Шина ответила — но прежде, чем верить её ответам, надо убедиться,
            // что она умеет отвечать «нет». Первый заход этого не сделал, и
            // поиск доложил о четырёх контроллерах на каждой из трёх шин:
            // неподтверждение не ловилось, и «да» приходило на любой адрес.
            // SAFETY: см. выше.
            let honest = unsafe { mtk_i2c::trustworthy(&bus) };
            if !honest {
                // Сырое состояние и настройка выводов печатаются здесь, а не
                // прячутся: «шина подтверждает всё» — это симптом, у которого
                // две разные причины. Либо передача честно вышла на провода и
                // ей ответили (тогда виноваты выводы: не переключённые на I²C,
                // они читаются нулём, а ноль на линии данных — это и есть
                // подтверждение), либо передача не вышла вовсе и контроллер
                // отчитался за пустоту. Одно число различает их сразу.
                // SAFETY: см. выше.
                let status = unsafe { bus.probe_status(0x7f) };
                crate::kprintln!(
                    "  touch       : i2c {base:#010x} ({}) acks everything, status {status:#06x}",
                    layout.name
                );
                report_pins(&window);
                // Обход всё равно делается: даже врущая шина отвечает не
                // одинаково, и увидеть это дешевле, чем не увидеть. Верить её
                // находкам нельзя, и они помечены.
            }

            if virgin {
                crate::kprintln!(
                    "  touch       : i2c at {base:#010x} was not set up by the bootloader"
                );
            }

            // Полный обход шины, а не только знакомых адресов.
            //
            // Знакомые кончились: на единственной исправной шине аппарата не
            // отозвался ни один из них, и это ответ, из которого не следует
            // ничего — ни «тачскрин на SPI», ни «мы смотрим не туда». Список
            // того, кто на шине **есть**, следует уже о многом: по адресу
            // контроллер узнаётся, а пустая шина закрывает её целиком.
            //
            // Обход стоит недорого именно потому, что шина исправна: отказ
            // приходит от железа сразу, а не по истечении предела ожидания.
            let mut seen = [0u8; 24];
            let mut count = 0;
            for address in 0x08..=0x77u8 {
                // SAFETY: см. выше.
                if unsafe { bus.present(address) } && count < seen.len() {
                    seen[count] = address;
                    count += 1;
                }
            }
            let mark = if honest { "" } else { " (untrusted)" };
            if count == 0 {
                crate::kprintln!("  touch       : i2c {base:#010x}{mark} is empty, nobody answers");
            } else {
                // Печатается по восемь в строку: экран телефона узкий, а
                // перенос посреди списка адресов читается хуже всего.
                for chunk in seen[..count].chunks(8) {
                    let mut line = [0u8; 8];
                    line[..chunk.len()].copy_from_slice(chunk);
                    crate::kprintln!(
                        "  touch       : i2c {base:#010x}{mark} answers {:#04x} {:#04x} {:#04x} {:#04x} {:#04x} {:#04x} {:#04x} {:#04x}",
                        line[0], line[1], line[2], line[3], line[4], line[5], line[6], line[7]
                    );
                }
            }

            for (address, kind) in KNOWN {
                // SAFETY: см. выше.
                if honest && unsafe { bus.present(address) } {
                    crate::kprintln!(
                        "  touch       : {kind:?} at {address:#04x} on i2c {base:#010x} ({})",
                        layout.name
                    );
                    if found.is_none() {
                        found = Some(Touch {
                            bus,
                            address,
                            kind,
                            down: false,
                            last: (0, 0),
                        });
                    }
                }
            }
            for (address, name) in NAMED {
                // SAFETY: см. выше.
                if honest && unsafe { bus.present(address) } {
                    crate::kprintln!(
                        "  touch       : {name} at {address:#04x} on i2c {base:#010x}, protocol not written"
                    );
                }
            }

            // Раскладка подошла — вторую на этой шине проверять незачем.
            break;
        }
    }

    let Some(touch) = found else {
        return false;
    };
    *TOUCH.lock() = Some(touch);
    true
}

/// Напечатать настройку выводов шины — то немногое, что о ней говорит дерево.
///
/// Узлов состояния выводов у шин I²C в этом дереве нет, но каждая называет свой
/// блок настройки (`gpio_start`) и номера линий данных и такта. Значений режима
/// мы не знаем — таблица режимов принадлежит конкретному кристаллу, а её у нас
/// нет, — но сырые слова сравнимы между собой: у шины, которой загрузчик
/// пользовался, и у нетронутой они обязаны различаться. Это и есть следующий
/// вопрос, и задать его дешевле сейчас, чем ещё одним заходом к аппарату.
fn report_pins(window: &super::fdt_boot::I2cBus) {
    let Some(pins) = window.pins else {
        return;
    };
    if !map_device_page(pins) {
        return;
    }
    let mut words = [0u32; 4];
    for (slot, word) in words.iter_mut().enumerate() {
        // SAFETY: блок назван самим деревом и отображён строкой выше как память
        // устройства; читаются первые четыре слова — там у MediaTek лежит режим.
        *word = unsafe { ((pins as usize + slot * 4) as *const u32).read_volatile() };
    }
    crate::kprintln!(
        "  touch       :   pins sda {} scl {}, cfg {pins:#010x} = {:08x} {:08x} {:08x} {:08x}",
        window.sda,
        window.scl,
        words[0],
        words[1],
        words[2],
        words[3]
    );
}

/// Нашёлся ли читаемый тачскрин.
#[must_use]
pub fn present() -> bool {
    TOUCH.lock().is_some()
}

/// Отобразить страницу регистров как память устройства.
pub fn map_device_page(base: u64) -> bool {
    // Округление вниз до страницы обязательно: блок настройки выводов лежит по
    // `0x10002a00`, то есть внутри страницы, а не с её начала, и отображение
    // такого адреса отвергается как невыровненное. Регистры от этого не
    // сдвигаются — по своему полному адресу они и останутся.
    let phys = crate::mm::PhysAddr::new(base).page_align_down();
    let base = phys.as_u64();
    // SAFETY: адрес взят из дерева машины и описывает регистры контроллера;
    // таблицы ядра активны, Device-семантика для регистров обязательна.
    let mapped = unsafe {
        crate::arch::map_active(
            crate::mm::VirtAddr::new(base as usize),
            phys,
            crate::mm::PAGE_SIZE,
            crate::mm::PageFlags::READ
                .union(crate::mm::PageFlags::WRITE)
                .union(crate::mm::PageFlags::DEVICE),
        )
    };
    match mapped {
        Ok(()) => true,
        Err(err) => {
            crate::kprintln!("  touch       : cannot map i2c window {base:#010x}: {err:?}");
            false
        }
    }
}

/// Служебная задача: опрашивать контроллер и превращать касания в события.
///
/// Частота опроса — компромисс, названный вслух: реже двухсот раз в секунду
/// палец начинает «прыгать» по экрану на быстром движении, чаще — шина занята
/// без пользы. Пять миллисекунд между посылками дают двести опросов.
pub fn service_task() {
    loop {
        poll_once();
        crate::sched::sleep_ms(5);
    }
}

fn poll_once() {
    let mut guard = TOUCH.lock();
    let Some(touch) = guard.as_mut() else {
        return;
    };
    match touch.kind {
        Kind::Focaltech => focaltech(touch),
        Kind::Goodix => goodix(touch),
    }
}

/// Focaltech: три байта состояния и четыре байта координат, всё подряд.
///
/// Читается с регистра `0x02`: сначала число касаний, затем старший и младший
/// байты X и Y первой точки. Старшие четыре бита каждого старшего байта заняты
/// не координатой — в X это признак события (нажатие, отпускание, удержание), в
/// Y номер пальца, — и не срезать их значит получить координату, скачущую на
/// тысячи точек.
fn focaltech(touch: &mut Touch) {
    let mut report = [0u8; 5];
    // SAFETY: шина подготовлена при поиске, окно отображено.
    if unsafe { touch.bus.transfer(touch.address, &[0x02], &mut report) }.is_err() {
        return;
    }
    let points = report[0] & 0x0f;
    if points == 0 {
        release(touch);
        return;
    }
    let x = (u16::from(report[1] & 0x0f) << 8) | u16::from(report[2]);
    let y = (u16::from(report[3] & 0x0f) << 8) | u16::from(report[4]);
    press(touch, x, y);
}

/// Goodix: регистры шестнадцатибитные, а признак касания снимает читатель.
///
/// Последнее не мелочь: не сбросить старший бит регистра состояния значит
/// читать одно и то же касание вечно — палец давно отпущен, а контроллер
/// продолжает отдавать ту же точку.
fn goodix(touch: &mut Touch) {
    let mut status = [0u8; 1];
    // SAFETY: см. `focaltech`.
    if unsafe { touch.bus.transfer(touch.address, &[0x81, 0x4e], &mut status) }.is_err() {
        return;
    }
    if status[0] & 0x80 == 0 {
        return; // данных ещё нет — состояние не трогаем
    }
    let points = status[0] & 0x0f;

    let mut report = [0u8; 4];
    // SAFETY: см. выше. Координаты первой точки лежат за номером пальца.
    let read = unsafe { touch.bus.transfer(touch.address, &[0x81, 0x50], &mut report) };

    // Снять признак обязательно, и обязательно в любом случае: выход по ошибке
    // чтения без сброса оставил бы контроллер с невыбранными данными навсегда.
    // SAFETY: см. выше.
    let _ = unsafe { touch.bus.transfer(touch.address, &[0x81, 0x4e, 0x00], &mut []) };

    if read.is_err() || points == 0 {
        release(touch);
        return;
    }
    let x = u16::from(report[0]) | (u16::from(report[1]) << 8);
    let y = u16::from(report[2]) | (u16::from(report[3]) << 8);
    press(touch, x, y);
}

/// Палец на экране: курсор туда и левая кнопка нажата.
///
/// Тачскрин отдаёт положение, а не приращение, поэтому событие абсолютное — то
/// же, чем описывается планшет. Курсор при этом прыгает к пальцу, и это верно:
/// на экране, которого касаются, «плавное подведение» было бы враньём.
fn press(touch: &mut Touch, x: u16, y: u16) {
    let point = to_fractions(x, y);
    touch.down = true;
    touch.last = point;
    post_pointer_at(point.0, point.1, 0, Buttons::LEFT);
}

/// Палец снят. Отправляется один раз: повторное отпускание композитор считал бы
/// новым щелчком, — и отправляется **туда же**, где палец был: иначе отпускание
/// достаётся не тому, по чему щёлкнули.
fn release(touch: &mut Touch) {
    if !touch.down {
        return;
    }
    touch.down = false;
    post_pointer_at(touch.last.0, touch.last.1, 0, Buttons::NONE);
}

/// Перевести точки панели в доли экрана.
///
/// Событие указателя несёт **доли**, а не точки, и это не мелочь: драйвер не
/// знает размера экрана и знать его не обязан, а диапазон у каждого устройства
/// свой. Отдать сюда точки означало бы курсор, жмущийся к левому верхнему углу
/// ровно во столько раз, во сколько экран шире диапазона.
fn to_fractions(x: u16, y: u16) -> (u16, u16) {
    let clamp = |value: u16, span: u16| -> u16 {
        let span = span.max(1);
        let value = u32::from(value.min(span - 1));
        (value * u32::from(u16::MAX) / u32::from(span - 1).max(1)) as u16
    };
    (clamp(x, SCREEN.0), clamp(y, SCREEN.1))
}
