//! Мастер шины I²C у MediaTek — то, чем нащупывается тачскрин.
//!
//! # Почему без этого не обойтись
//!
//! Дерево устройств про тачскрин не говорит ничего: узел `/touch` несёт одно
//! свойство `compatible = "mediatek,touch"` и ни адреса, ни шины. Так у
//! MediaTek всегда — контроллер регистрируется платформенным кодом, а какой чип
//! стоит в этой партии аппаратов, дерево не знает вовсе. У `dandelion` их три
//! возможных (Focaltech, Novatek, Himax), и различить их можно только одним
//! способом: спросить шину, кто на ней отзывается.
//!
//! # Что здесь сделано и чего сознательно не сделано
//!
//! Сделан минимум, которого хватает, чтобы задать вопрос: передача через FIFO
//! контроллера, без DMA. Восьми байт FIFO хватает и на опрос адреса, и на
//! чтение координат одного касания; блок DMA пришлось бы настраивать отдельно,
//! а он нужен только для длинных чтений, которых у нас нет.
//!
//! **Настройки шины не трогаются.** Ни программного сброса, ни записи в регистр
//! тактирования: загрузчик эти контроллеры уже настроил — он ходит по I²C к
//! контроллеру питания и к зарядке, — и переписать его значения своими,
//! выведенными из неизвестной нам частоты источника, значит сломать работающее
//! и не узнать об этом. Если регистр тактирования читается нулём, шина не
//! настраивалась никем, и тогда — и только тогда — ставится запасное значение,
//! о чём говорится вслух.
//!
//! # Про две раскладки регистров
//!
//! У MediaTek их две, и какая на MT6765 — неизвестно: аппарат не скажет, а
//! исходников его драйвера у нас нет. Совпадают они в главном (данные, адрес,
//! состояние, управление, длины, пуск), расходятся в мелочах — очистка FIFO,
//! настройка выводов, вторая длина. Поэтому поддержаны обе, а выбор делается
//! опытом: та, на которой шина отвечает осмысленно, и есть верная. Догадка
//! здесь стоила бы захода к аппарату, а опыт стоит одного прохода по адресам.

use core::ptr;

/// Смещения регистров одной из двух раскладок.
///
/// Все регистры шестнадцатибитные — это особенность контроллера, а не
/// сокращение: запись словом в половину из них не проходит вовсе.
#[derive(Clone, Copy)]
pub struct Layout {
    pub name: &'static str,
    data_port: usize,
    slave_addr: usize,
    intr_mask: usize,
    intr_stat: usize,
    control: usize,
    transfer_len: usize,
    transac_len: usize,
    delay_len: usize,
    timing: usize,
    start: usize,
    io_config: usize,
    fifo_addr_clr: usize,
    transfer_len_aux: usize,
    softreset: usize,
}

/// Раскладка первого поколения (mt6577 и родня).
pub const V1: Layout = Layout {
    name: "v1",
    data_port: 0x00,
    slave_addr: 0x04,
    intr_mask: 0x08,
    intr_stat: 0x0c,
    control: 0x10,
    transfer_len: 0x14,
    transac_len: 0x18,
    delay_len: 0x1c,
    timing: 0x20,
    start: 0x24,
    io_config: 0x40,
    fifo_addr_clr: 0x38,
    transfer_len_aux: 0x6c,
    softreset: 0x50,
};

/// Раскладка второго поколения (mt2712, mt8183 и родня).
pub const V2: Layout = Layout {
    name: "v2",
    data_port: 0x00,
    slave_addr: 0x04,
    intr_mask: 0x08,
    intr_stat: 0x0c,
    control: 0x10,
    transfer_len: 0x14,
    transac_len: 0x18,
    delay_len: 0x1c,
    timing: 0x20,
    start: 0x24,
    io_config: 0x34,
    fifo_addr_clr: 0x38,
    transfer_len_aux: 0x44,
    softreset: 0x50,
};

// Биты регистра состояния прерываний. Они же — то, чем передача отчитывается:
// прерывания мы не разрешаем, а опрашиваем эти же признаки.
/// Передача завершена целиком.
const INTR_TRANSAC_COMP: u16 = 1 << 0;
/// Устройство не подтвердило адрес или байт. Для опроса шины это **ответ**, а
/// не отказ: именно так молчащий адрес отличается от отзывающегося.
const INTR_ACKERR: u16 = 1 << 1;
/// То же на высокой скорости.
const INTR_HS_NACKERR: u16 = 1 << 2;

// Биты регистра управления.
/// Повторный старт между записью и чтением — без него чтение из регистра
/// устройства невозможно: адрес регистра пришлось бы отдавать отдельной
/// посылкой со стопом, а после стопа устройство про него забывает.
const CONTROL_RS: u16 = 1 << 1;
/// Растягивать такт по требованию устройства.
const CONTROL_CLK_EXT_EN: u16 = 1 << 3;
/// Смена направления внутри посылки — обратная сторона `CONTROL_RS`.
const CONTROL_DIR_CHANGE: u16 = 1 << 4;
/// Замечать неподтверждение. Без этого бита молчащий адрес выглядит как
/// удачная передача, и опрос шины находит все сто двенадцать адресов сразу.
const CONTROL_ACKERR_DET_EN: u16 = 1 << 5;

/// Начать передачу.
const START_TRANSAC: u16 = 1 << 0;
/// Сбросить указатели FIFO.
const FIFO_ADDR_CLR: u16 = 1 << 0;
/// Выводы с открытым стоком — так работает всякая I²C.
const IO_CONFIG_OPEN_DRAIN: u16 = 0x0003;
/// Задержка между посылками, в единицах, которые понимает контроллер.
const DELAY_LEN: u16 = 0x0002;

/// Сбросить блок целиком.
const SOFT_RESET: u16 = 0x0001;

/// Запасное значение тактирования, если загрузчик шину не настраивал.
///
/// Число не выведено, а взято из значений, которые MediaTek ставит своим
/// контроллерам на этом семействе; оно даёт что-то около сотни килогерц.
/// Ставится только вместо нуля и только с оговоркой в журнале: угадывать
/// частоту шины по неизвестной частоте источника — способ получить работающую
/// на вид шину, которая врёт на длинных посылках.
const TIMING_FALLBACK: u16 = 0x0507;

/// Сколько раз опросить состояние, прежде чем счесть передачу зависшей.
///
/// Предел, а не ожидание по часам: этот код работает и до того, как заведён
/// таймер. Молчащая шина обязана отдавать управление, а не останавливать
/// загрузку.
const POLL_LIMIT: u32 = 200_000;

/// Сколько байт помещается в FIFO контроллера.
pub const FIFO: usize = 8;

/// Отзывается ли шина осмысленно вообще.
///
/// Проверка от противного: спрашиваются два адреса из хвоста диапазона,
/// `0x7e` и `0x7f`. Отозвался хоть один — значит, шина отвечает «да» на что
/// угодно, и всё, что она скажет дальше, — выдумка.
///
/// Существует потому, что именно так и вышло: неподтверждение не ловилось, и
/// поиск честно доложил о четырёх контроллерах на каждой из трёх шин. Ответ
/// выглядел как находка, а был отказом измерения.
///
/// # Почему именно эти два адреса
///
/// Оба лежат в хвосте, отведённом под десятибитную адресацию, и обычным
/// устройством не занимаются. Первым вариантом здесь стоял ещё и `0x03` —
/// тоже «зарезервированный», — и он забраковал единственную исправную шину
/// аппарата: кто-то на ней по этому адресу отзывается. Проверка, отвергающая
/// годное, хуже отсутствующей: она прячет находку и выглядит при этом
/// осторожностью.
///
/// # Safety
///
/// См. [`Bus::prepare`], которая должна быть вызвана раньше.
pub unsafe fn trustworthy(bus: &Bus) -> bool {
    // SAFETY: контракт функции.
    unsafe { !bus.present(0x7e) && !bus.present(0x7f) }
}

/// Что пошло не так.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    /// Устройство не подтвердило адрес — по этому адресу никого нет.
    NoAck,
    /// Контроллер не отчитался за отведённое число опросов.
    Timeout,
    /// Просят больше, чем помещается в FIFO.
    TooLong,
}

/// Один контроллер шины.
#[derive(Clone, Copy)]
pub struct Bus {
    base: usize,
    layout: Layout,
}

impl Bus {
    /// # Safety
    ///
    /// `base` обязан быть адресом окна регистров контроллера I²C, отображённым
    /// как память устройства.
    #[must_use]
    pub const unsafe fn new(base: usize, layout: Layout) -> Self {
        Self { base, layout }
    }

    /// Настроить ровно то, что нужно для передачи, и ничего сверх.
    ///
    /// Возвращает `true`, если регистр тактирования пришлось заполнять самим, —
    /// признак того, что этой шиной до нас никто не пользовался.
    ///
    /// # Safety
    ///
    /// Окно регистров отображено, параллельного доступа к этому контроллеру нет.
    pub unsafe fn prepare(&self) -> bool {
        // SAFETY: контракт функции.
        unsafe {
            let virgin = self.read(self.layout.timing) == 0;
            if virgin {
                self.write(self.layout.timing, TIMING_FALLBACK);
            }
            self.write(self.layout.io_config, IO_CONFIG_OPEN_DRAIN);
            self.write(self.layout.delay_len, DELAY_LEN);
            virgin
        }
    }

    /// Вернуть контроллер в исходное состояние после неудачной посылки.
    ///
    /// # Зачем это обязательно
    ///
    /// Неподтверждение обрывает посылку на полуслове: на шине остаётся начатая
    /// передача, а в блоке — состояние, из которого он сам не выходит.
    /// Следующий вопрос он «подтверждает» не глядя, каким бы тот ни был.
    ///
    /// Выглядит это так, что шина отвечает «да» на любой адрес, — и именно так
    /// оно и выглядело: единственная исправная шина аппарата, честно
    /// отказавшая одному адресу, тут же соглашалась со следующим и попадала в
    /// брак по собственной проверке.
    ///
    /// Тактирование при этом сохраняется: сброс обнуляет и его, а восстановить
    /// его нам не из чего — то значение поставил загрузчик, зная частоту
    /// источника, которой мы не знаем.
    ///
    /// # Safety
    ///
    /// См. [`Bus::prepare`].
    unsafe fn recover(&self) {
        // SAFETY: контракт функции.
        unsafe {
            let timing = self.read(self.layout.timing);
            self.write(self.layout.softreset, SOFT_RESET);
            self.write(self.layout.timing, timing);
            self.write(self.layout.io_config, IO_CONFIG_OPEN_DRAIN);
            self.write(self.layout.delay_len, DELAY_LEN);
            self.write(self.layout.intr_stat, INTR_TRANSAC_COMP | INTR_ACKERR | INTR_HS_NACKERR);
            self.write(self.layout.fifo_addr_clr, FIFO_ADDR_CLR);
        }
    }

    /// Сырое слово состояния после опроса адреса — то, чем шина отчиталась.
    ///
    /// Нужно ровно для одного: отличить «устройство подтвердило» от «передача
    /// вообще не вышла на провода». Снаружи эти два исхода неразличимы, а
    /// лечатся по-разному, и один заход к аппарату дешевле любых рассуждений.
    ///
    /// `0xffff` означает, что контроллер не отчитался вовсе.
    ///
    /// # Safety
    ///
    /// См. [`Bus::prepare`].
    pub unsafe fn probe_status(&self, address: u8) -> u16 {
        let mut byte = [0u8; 1];
        // SAFETY: контракт функции.
        unsafe {
            let _ = self.transfer(address, &[], &mut byte);
            self.read(self.layout.intr_stat)
        }
    }

    /// Отозвался ли кто-нибудь по этому адресу.
    ///
    /// Опрос — это чтение одного байта: контроллер выставляет адрес, и либо
    /// получает подтверждение, либо взводит признак неподтверждения. Записью
    /// нулевой длины спросить нельзя — контроллер такой передачи не начинает.
    ///
    /// # Safety
    ///
    /// См. [`Bus::prepare`], которая должна быть вызвана раньше.
    pub unsafe fn present(&self, address: u8) -> bool {
        let mut byte = [0u8; 1];
        // SAFETY: контракт функции.
        matches!(unsafe { self.transfer(address, &[], &mut byte) }, Ok(()))
    }

    /// Записать байты, затем прочитать байты, не отпуская шину.
    ///
    /// Пустая запись означает чтение с текущей позиции устройства, пустое
    /// чтение — запись без ответа.
    ///
    /// # Safety
    ///
    /// См. [`Bus::prepare`], которая должна быть вызвана раньше.
    pub unsafe fn transfer(&self, address: u8, write: &[u8], read: &mut [u8]) -> Result<(), Error> {
        if write.len() > FIFO || read.len() > FIFO {
            return Err(Error::TooLong);
        }
        let regs = &self.layout;

        // Сколько посылок будет на шине: запись и чтение — две, что-то одно —
        // одна. Ошибиться здесь значит получить передачу, которая завершается
        // раньше или не завершается вовсе.
        let phases = u16::from(!write.is_empty()) + u16::from(!read.is_empty());
        if phases == 0 {
            return Ok(());
        }

        let mut control = CONTROL_ACKERR_DET_EN | CONTROL_CLK_EXT_EN;
        if phases == 2 {
            control |= CONTROL_RS | CONTROL_DIR_CHANGE;
        }

        // Младший бит адреса — направление. При записи с последующим чтением
        // ставится ноль: смену направления делает сам контроллер по
        // `CONTROL_DIR_CHANGE`.
        let addressed = (u16::from(address) << 1) | u16::from(write.is_empty() && !read.is_empty());

        // SAFETY: контракт функции; все смещения принадлежат окну регистров.
        unsafe {
            // Маска — это **разрешение**, а не запрет, и в этом всё дело.
            // Незаявленный здесь признак в регистр состояния не попадает вовсе,
            // и «устройство не подтвердило адрес» становится неотличимо от
            // «подтвердило». Стоял ноль — и опрос шины находил на ней все сто
            // двенадцать адресов сразу, включая заведомо пустые. Прерывания при
            // этом никуда не доставляются: их номера у этой шины в дереве нет,
            // а состояние опрашивается тут же, в цикле ниже.
            self.write(regs.intr_mask, INTR_TRANSAC_COMP | INTR_ACKERR | INTR_HS_NACKERR);
            self.write(regs.control, control);
            self.write(regs.slave_addr, addressed);
            self.write(regs.transac_len, phases);
            if write.is_empty() {
                self.write(regs.transfer_len, read.len() as u16);
            } else {
                self.write(regs.transfer_len, write.len() as u16);
                self.write(regs.transfer_len_aux, read.len() as u16);
            }
            // Признаки прошлой передачи снимаются перед пуском, а не после:
            // оставленный признак завершения означал бы, что следующая передача
            // «уже готова» в тот же миг, когда началась.
            self.write(regs.intr_stat, INTR_TRANSAC_COMP | INTR_ACKERR | INTR_HS_NACKERR);
            self.write(regs.fifo_addr_clr, FIFO_ADDR_CLR);

            for byte in write {
                self.write(regs.data_port, u16::from(*byte));
            }

            self.write(regs.start, START_TRANSAC);

            let mut spins = 0u32;
            let status = loop {
                let status = self.read(regs.intr_stat);
                if status & (INTR_TRANSAC_COMP | INTR_ACKERR | INTR_HS_NACKERR) != 0 {
                    break status;
                }
                spins += 1;
                if spins >= POLL_LIMIT {
                    self.recover();
                    return Err(Error::Timeout);
                }
                core::hint::spin_loop();
            };

            if status & (INTR_ACKERR | INTR_HS_NACKERR) != 0 {
                self.recover();
                return Err(Error::NoAck);
            }

            for slot in read.iter_mut() {
                *slot = self.read(regs.data_port) as u8;
            }
        }

        Ok(())
    }

    /// # Safety
    ///
    /// `offset` обязан принадлежать окну регистров этого контроллера.
    unsafe fn read(&self, offset: usize) -> u16 {
        // SAFETY: контракт; volatile обязателен — значение меняет устройство.
        unsafe { ptr::read_volatile((self.base + offset) as *const u16) }
    }

    /// # Safety
    ///
    /// См. [`Bus::read`]; кроме того, запись меняет состояние контроллера.
    unsafe fn write(&self, offset: usize, value: u16) {
        // SAFETY: контракт; volatile обязателен — запись нельзя ни выбросить,
        // ни переставить с соседней.
        unsafe { ptr::write_volatile((self.base + offset) as *mut u16, value) };
    }
}
