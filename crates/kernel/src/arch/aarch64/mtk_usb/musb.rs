//! Регистры контроллера USB (Mentor USB, он же MUSB) в режиме устройства.
//!
//! Раскладка общая для всего семейства и описана в его документации; MediaTek
//! берёт блок как есть. Здесь только то, чем пользуется гаджет: нулевая точка,
//! одна пара объёмных точек и признаки шины.
//!
//! # Индексная модель
//!
//! У точек нет собственных окон: регистр [`reg::INDEX`] выбирает, о какой из
//! них идёт речь, и дальше все читают одни и те же адреса. Это значит, что
//! номер точки — состояние, и переключать его посреди обращения нельзя. Здесь
//! он ставится в начале каждой операции, а сами операции коротки.
//!
//! # Почему опрос, а не прерывание
//!
//! Прерывание USB у MediaTek идёт через собственный уровень (`USB_L1INTM`) и
//! требует разобрать `interrupts` контроллера. Опрос стоит одного чтения
//! двухбайтового регистра и снимает это целиком, а гаджету, чья работа —
//! отдать журнал по кабелю, задержка в миллисекунду безразлична.

use core::ptr;

/// Смещения общих регистров.
pub mod reg {
    /// Адрес устройства на шине, назначенный хостом.
    pub const FADDR: usize = 0x00;
    /// Подключение к шине, скорость, режимы сна.
    pub const POWER: usize = 0x01;
    /// Какие передающие точки чего-то хотят. Разряд 0 — нулевая точка, и он
    /// взводится в том числе на пришедший запрос.
    pub const INTRTX: usize = 0x02;
    /// Признаки шины: сброс, подключение, приостановка.
    ///
    /// Читается с очисткой: увиденное этим чтением больше никому не достанется.
    /// Поэтому читать его надо один раз за проход и в одном месте.
    pub const INTRUSB: usize = 0x0a;
    /// Сессия и сторона кабеля. У MediaTek лежит вне области, описанной в
    /// документации на блок.
    pub const DEVCTL: usize = 0x60;
    /// Настройка шины контроллера, которую изготовитель правит при запуске.
    pub const BUSPERF3: usize = 0x74;
    /// Разрешение признаков шины. См. [`super::INTRUSBE_RESET`].
    pub const INTRUSBE: usize = 0x0b;
    /// Какие передающие точки разрешено слушать.
    pub const INTRTXE: usize = 0x06;
    /// То же для принимающих.
    pub const INTRRXE: usize = 0x08;
    /// Какие принимающие точки чего-то хотят.
    pub const INTRRX: usize = 0x04;
    /// Управление тактами внутри самого контроллера, тридцатидвухбитный.
    ///
    /// Не описан в документации на блок и найден только в коде изготовителя,
    /// одной строкой в `musb_start` с комментарием «disable USB DCM».
    pub const DCM: usize = 0x220;
    /// Какая точка отвечает на обращения ниже.
    pub const INDEX: usize = 0x0e;
    /// Сколько объёмных точек и сколько памяти под них у этого кристалла.
    pub const EPINFO: usize = 0x78;

    /// Размер передающей части памяти выбранной точки.
    pub const TXFIFOSZ: usize = 0x62;
    /// Размер принимающей части.
    pub const RXFIFOSZ: usize = 0x63;
    /// Где она начинается, в восьмибайтовых единицах.
    pub const TXFIFOADD: usize = 0x64;
    /// То же для приёма.
    pub const RXFIFOADD: usize = 0x66;

    /// Регистры выбранной точки лежат за общим смещением.
    pub const EP: usize = 0x10;
    /// Наибольший пакет передачи.
    pub const TXMAXP: usize = EP;
    /// Состояние передачи; для нулевой точки — единственный регистр состояния.
    pub const TXCSR: usize = EP + 0x02;
    /// То же имя для нулевой точки — она одна на оба направления.
    pub const CSR0: usize = TXCSR;
    /// Наибольший пакет приёма.
    pub const RXMAXP: usize = EP + 0x04;
    /// Состояние приёма.
    pub const RXCSR: usize = EP + 0x06;
    /// Сколько байт принято. **Шестнадцать разрядов**: объёмный пакет бывает
    /// до 512 байт, и в один байт такая длина не помещается.
    pub const RXCOUNT: usize = EP + 0x08;
    /// Сколько байт принято нулевой точкой. Тот же адрес — и **восемь
    /// разрядов**, потому что её пакет не длиннее 64.
    ///
    /// Разница не косметическая, и стоила она целого вечера. Прочитанный
    /// шестнадцатью разрядами, счётчик захватывает соседний байт, нулевой
    /// точке не принадлежащий; в нём лежит что придётся. Длина запроса всегда
    /// восемь, проверка на восемь не сходилась никогда — и каждый запрос хоста
    /// молча уходил в ветку «это не запрос». Снаружи это выглядело как
    /// устройство, которое видно на шине и не отвечает на первый же вопрос.
    pub const COUNT0: usize = RXCOUNT;
    /// Признаки кристалла: динамическая память точек, порядок байт.
    pub const CONFIGDATA: usize = EP + 0x0f;

    /// Окно данных точки. Это порт, а не память: адрес не растёт.
    #[must_use]
    pub const fn fifo(endpoint: u8) -> usize {
        0x20 + (endpoint as usize) * 4
    }
}

/// `POWER`: подтянуть линию данных и тем заявить о себе шине.
pub const POWER_SOFTCONN: u8 = 0x40;
/// `POWER`: соглашаться на высокую скорость.
pub const POWER_HSENAB: u8 = 0x20;
/// `POWER`: высокая скорость **состоялась**. Только для чтения, и только после
/// сброса шины: до него это ожидание, а не факт.
pub const POWER_HSMODE: u8 = 0x10;

/// `INTRTX`: разряд нулевой точки.
///
/// Взводится по завершении обмена на ней — в том числе завершающей стадии, у
/// которой нет иного признака: регистр состояния самой точки к этому мигу уже
/// чист, и был чист до него.
pub const INTRTX_EP0: u16 = 0x0001;

/// `INTRUSBE`: слушать сброс шины. В режиме устройства изготовитель разрешает
/// ровно это и ничего больше.
pub const INTRUSBE_RESET: u8 = 0x04;

/// `DCM`: не давать контроллеру гасить собственные такты.
///
/// Найдено в `musb_start` под комментарием «disable USB DCM» и больше нигде.
/// Блок, гасящий такты по своему усмотрению, отвечает на запросы шины не
/// всегда, а «не всегда» на перечислении означает «никогда»: хост спрашивает
/// три раза подряд и уходит.
pub const DCM_DISABLE: u32 = 0x400;

/// `DEVCTL`: открыть сессию.
///
/// В режиме устройства контроллер обязан взводить разряд сам, увидев
/// напряжение на кабеле. Изготовитель всё равно пишет его явно при запуске
/// гаджета (`musb_start`), и мы делаем так же: лишняя запись ничего не стоит, а
/// её отсутствие оставляет устройство немым на машинах, где напряжение
/// появляется раньше, чем мы успеваем посмотреть.
pub const DEVCTL_SESSION: u8 = 0x01;

/// `INTRUSB`: хост сбросил шину.
///
/// Остальные разряды регистра сюда не вынесены, но в отчёте видны как есть:
/// `0x01` — приостановка, `0x02` — пробуждение, `0x08` — кадровый признак,
/// `0x10` и `0x20` — подключение и отключение.
pub const INTR_RESET: u8 = 0x04;

/// `CSR0`: пришёл пакет.
pub const CSR0_RXPKTRDY: u16 = 0x0001;
/// `CSR0`: наш пакет готов к отправке.
pub const CSR0_TXPKTRDY: u16 = 0x0002;
/// `CSR0`: хост прервал передачу, не дослушав.
pub const CSR0_SETUPEND: u16 = 0x0010;
/// `CSR0`: отказать в запросе.
pub const CSR0_SENDSTALL: u16 = 0x0020;
/// `CSR0`: подтвердить принятый пакет — «прочитано, можно следующий».
pub const CSR0_SVDRXPKTRDY: u16 = 0x0040;
/// `CSR0`: подтвердить прерванную передачу.
pub const CSR0_SVDSETUPEND: u16 = 0x0080;
/// `CSR0`: это последний пакет запроса, переходи к завершающей стадии.
pub const CSR0_DATAEND: u16 = 0x0008;

/// `TXCSR`: пакет положен, отправляй.
pub const TXCSR_TXPKTRDY: u16 = 0x0001;
/// `TXCSR`: выбросить всё, что лежит в памяти точки.
pub const TXCSR_FLUSHFIFO: u16 = 0x0008;
/// `TXCSR`: вернуть счётчик чередования к нулю.
pub const TXCSR_CLRDATATOG: u16 = 0x0040;
/// `TXCSR`: точка работает на передачу. Без него общая память точки остаётся
/// за приёмом, и переданное не уходит никуда.
pub const TXCSR_MODE: u16 = 0x2000;

/// `RXCSR`: есть принятый пакет.
pub const RXCSR_RXPKTRDY: u16 = 0x0001;
/// `RXCSR`: выбросить принятое.
pub const RXCSR_FLUSHFIFO: u16 = 0x0010;
/// `RXCSR`: вернуть счётчик чередования к нулю.
pub const RXCSR_CLRDATATOG: u16 = 0x0080;

/// Окно регистров контроллера.
///
/// Как и [`super::phy::Phy`], тип обещает отображённое окно — создать его иначе
/// нельзя, и потому чтение с записью дальше безопасны.
#[derive(Clone, Copy)]
pub struct Musb {
    base: usize,
}

impl Musb {
    /// # Safety
    ///
    /// `base` — начало отображённого окна регистров контроллера (первый `reg`
    /// узла `usb0`).
    pub const unsafe fn new(base: usize) -> Self {
        Self { base }
    }

    #[must_use]
    pub fn read8(self, offset: usize) -> u8 {
        // SAFETY: инвариант типа; volatile обязателен — значение меняет
        // устройство, и компилятору нельзя ни выбросить чтение, ни повторить.
        unsafe { ptr::read_volatile((self.base + offset) as *const u8) }
    }

    pub fn write8(self, offset: usize, value: u8) {
        // SAFETY: см. [`Musb::read8`].
        unsafe { ptr::write_volatile((self.base + offset) as *mut u8, value) };
    }

    #[must_use]
    pub fn read16(self, offset: usize) -> u16 {
        // SAFETY: см. [`Musb::read8`].
        unsafe { ptr::read_volatile((self.base + offset) as *const u16) }
    }

    #[must_use]
    pub fn read32(self, offset: usize) -> u32 {
        // SAFETY: см. [`Musb::read8`].
        unsafe { ptr::read_volatile((self.base + offset) as *const u32) }
    }

    pub fn write32(self, offset: usize, value: u32) {
        // SAFETY: см. [`Musb::read8`].
        unsafe { ptr::write_volatile((self.base + offset) as *mut u32, value) };
    }

    pub fn write16(self, offset: usize, value: u16) {
        // SAFETY: см. [`Musb::read8`].
        unsafe { ptr::write_volatile((self.base + offset) as *mut u16, value) };
    }

    /// Выбрать точку, о которой пойдёт речь дальше.
    pub fn select(self, endpoint: u8) {
        self.write8(reg::INDEX, endpoint);
    }

    /// Забрать принятый пакет из памяти точки.
    ///
    /// Байт за байтом, без попыток читать по четыре. Выигрыш был бы в разы, но
    /// он требует, чтобы приёмник был выровнен, а длина делилась, — а здесь и
    /// то и другое приходит снаружи. Самый длинный наш пакет — 512 байт раз в
    /// несколько миллисекунд.
    pub fn read_fifo(self, endpoint: u8, out: &mut [u8]) {
        let port = self.base + reg::fifo(endpoint);
        for byte in out.iter_mut() {
            // SAFETY: инвариант типа. Адрес намеренно не растёт: это порт, и
            // каждое чтение отдаёт следующий байт очереди.
            *byte = unsafe { ptr::read_volatile(port as *const u8) };
        }
    }

    /// Положить пакет в память точки. Отправку начинает уже регистр состояния.
    pub fn write_fifo(self, endpoint: u8, data: &[u8]) {
        let port = self.base + reg::fifo(endpoint);
        for &byte in data {
            // SAFETY: см. [`Musb::read_fifo`].
            unsafe { ptr::write_volatile(port as *mut u8, byte) };
        }
    }
}
