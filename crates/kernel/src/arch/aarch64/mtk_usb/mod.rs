//! USB телефона в режиме **устройства**: журнал и обратная связь по кабелю.
//!
//! # Зачем он понадобился раньше всего остального
//!
//! У аппарата нет линии наружу, и журнал существует только на экране — доли
//! секунды, пока его не закроет рабочий стол. Каждый вопрос к машине стоит
//! прошивки и снимка экрана, сделанного руками; за один вечер таких кругов
//! вышло полтора десятка. Для задачи, сузившейся до одной цепочки, это неверная
//! форма цикла.
//!
//! Телефон, представившийся компьютеру устройством, отдаёт журнал по тому же
//! кабелю, который и так воткнут: `fastboot oem log`. Опыт занимает секунды
//! вместо минут, и человек в нём не участвует.
//!
//! Это же первая половина сети: поверх работающего USB поднимется сетевой
//! интерфейс, и на телефон можно будет зайти по SSH.
//!
//! # Дефект, который стоил захода и выглядел как отсутствие тактирования
//!
//! Прошлая редакция читала физический уровень по адресу узла
//! `usb_sif@11210000`. Все его регистры читались нулями до и после записи, и
//! отсюда вышел вывод «блоку не подведён такт» — вывод неверный, а поиск ушёл
//! в дерево тактов, где искать было нечего.
//!
//! На деле окно другое, и ошибок в адресе было **две**:
//!
//! 1. Драйвер MediaTek берёт окно физического уровня **вторым `reg` узла
//!    контроллера** (`musb_core.c`: `platform_get_resource(pdev,
//!    IORESOURCE_MEM, 1)` кладётся в `xceiv->io_priv`). У `dandelion` это
//!    `0x11CC0000`, а не `0x11210000`. Что узел `usb_sif` — наследство, видно
//!    и по самому дереву: рядом стоит `usb1p_sif@11210000` с тем же адресом и
//!    тем же размером. Два имени на одно окно означают, что описан блок
//!    прежних кристаллов.
//! 2. К базе прибавляется **`0x800`**: все обращения идут через
//!    `USBPHY_READ32/WRITE32`, а те смещают адрес. Комментарии изготовителя
//!    называют полные адреса и это подтверждают — `USBPHY_CLR32(0x18, …)`
//!    подписано как `0x11F4_0818[23]`.
//!
//! Урок общий и уже знакомый: **ноль читается одинаково у выключенного блока и
//! у несуществующего**. Отличить их можно было только одним — сверив, откуда
//! адрес берёт работающий драйвер, а не откуда его удобно взять нам.

pub mod fastboot;
pub mod gadget;
pub mod musb;
pub mod phy;

use crate::sync::SpinLock;
use fdt::Fdt;
use gadget::Gadget;
use musb::{Musb, reg};
use phy::Phy;

/// Устройство на шине. Заводится один раз при поиске ввода.
static GADGET: SpinLock<Option<Gadget>> = SpinLock::new(None);

/// Что удалось прочитать при запуске. Печатается вызывающим: на аппарате без
/// линии этот отчёт какое-то время остаётся единственным.
pub struct Report {
    /// Куда легло окно физического уровня — то самое, что было перепутано.
    pub phy_window: usize,
    /// Режим и принуждения физического уровня **до** нашего вмешательства.
    pub before: (u32, u32),
    /// Они же после. Разница между парами и есть доказательство, что писали не
    /// в никуда.
    pub after: (u32, u32),
    /// Подключение и скорость.
    pub power: u8,
    /// Сессия и сторона кабеля.
    pub devctl: u8,
    /// Сколько объёмных точек у кристалла.
    pub endpoints: u8,
    /// Признаки кристалла, в том числе делится ли память точек на ходу.
    pub configdata: u8,
}

/// Поднять USB и подключиться к шине.
///
/// # Safety
///
/// Таблицы ядра активны; окна регистров отображаются здесь же.
pub unsafe fn start(fdt: &Fdt<'_>) -> Option<Report> {
    let node = fdt
        .find("/usb0@11200000")
        .or_else(|| fdt.find_compatible("mediatek,mt6765-usb20"))?;
    let (address_cells, size_cells) = root_cells(fdt);
    let mut regions = node.reg(address_cells, size_cells);

    let controller = regions.next()?.address;
    // Второе окно — физический уровень. Его отсутствие означает дерево, в
    // котором мы не разберёмся; угадывать адрес после того, как один угаданный
    // уже стоил захода, не станем.
    let phy_window = regions.next()?.address;
    if controller == 0 || phy_window == 0 {
        return None;
    }
    if !super::mtk_touch::map_device_page(controller) || !super::mtk_touch::map_device_page(phy_window)
    {
        return None;
    }

    // SAFETY: оба окна только что отображены как память устройства.
    let (musb, phy) = unsafe {
        (
            Musb::new(controller as usize),
            Phy::new(phy_window as usize),
        )
    };

    // Заставить контроллер не обращать внимания на «болтовню» — помеху на
    // линии, которую он иначе принимает за ошибку шины и на которую отвечает
    // разрывом. Изготовитель делает эту же запись дважды, при подготовке блока
    // и при запуске гаджета, и объясняет её наводкой от внешних источников.
    let bus = musb.read8(reg::BUSPERF3);
    musb.write8(reg::BUSPERF3, (bus & !0x40) | 0x80);

    let before = phy.state();
    phy.recover();
    let after = phy.state();

    let mut device = Gadget::new(musb);
    device.prepare();

    musb.select(0);
    let report = Report {
        phy_window: phy_window as usize + 0x800,
        before,
        after,
        power: musb.read8(reg::POWER),
        devctl: musb.read8(reg::DEVCTL),
        endpoints: musb.read8(reg::EPINFO),
        configdata: musb.read8(reg::CONFIGDATA),
    };

    *GADGET.lock() = Some(device);
    Some(report)
}

/// Один проход обмена. Безопасно вызывать откуда угодно и как угодно часто.
///
/// Занятый замок означает, что обмен уже идёт в другом месте, — тогда делать
/// нечего и ждать нечего.
pub fn poll() {
    let Some(mut guard) = GADGET.try_lock() else {
        return;
    };
    if let Some(device) = guard.as_mut() {
        device.poll();
    }
}

/// Служебная задача: вести обмен, пока машина работает.
///
/// Миллисекунда между проходами взята из договора шины: назначение адреса —
/// единственное место, где хост ждёт нас в оговорённый срок, и срок этот две
/// миллисекунды. Всё остальное он повторяет столько, сколько нужно.
pub fn service_task() {
    let mut tick = 0u32;
    loop {
        poll();

        // Опрос панели ведётся отсюда, а не из задачи тачскрина, и это
        // временно — до тех пор, пока не выяснится, чем эти два пути
        // отличаются. Отличаются они разительно: одно и то же чтение,
        // сделанное здесь, доходит до кристалла и возвращает данные, а
        // сделанное там не доходит до провода вовсе. Причина неизвестна, а
        // тачскрин нужен сейчас.
        tick = tick.wrapping_add(1);
        if tick % 20 == 0 {
            super::mtk_touch::poll_from_here();
        }

        crate::sched::sleep_ms(1);
    }
}

/// Рассказать в журнале, чем кончился обмен с хостом.
///
/// Печатается до того, как экран заберёт рабочий стол: на аппарате без линии
/// это последний миг, когда журнал видит человек. Строка отвечает на
/// единственный вопрос, который нельзя выяснить с той стороны кабеля, — доходят
/// ли до нас запросы вообще.
pub fn report() -> bool {
    let guard = GADGET.lock();
    let Some(device) = guard.as_ref() else {
        // Устройства нет вовсе — ждать нечего, и держать журнал не для кого.
        return true;
    };
    if device.is_configured() {
        let speed = if device.is_high_speed() {
            "high"
        } else {
            "full"
        };
        crate::kprintln!(
            "  usb         : enumerated at {speed} speed, {} setup requests -- `fastboot oem log` works",
            device.setups
        );
        return true;
    }
    // Всё, что может понадобиться, за один раз. Каждый вопрос к этой машине
    // стоит перезагрузки и снимка экрана, сделанного руками, — значит цена
    // лишнего числа в строке равна нулю, а цена недостающего равна заходу.
    let now = device.snapshot();
    crate::kprintln!(
        "  usb         : no; resets {}, setups {}, replies {}, last {:#04x}/{:#04x}, events {:#04x}",
        device.resets,
        device.setups,
        device.replies,
        device.last.0,
        device.last.1,
        device.seen
    );
    crate::kprintln!(
        "  usb         : power {:#04x} csr0 {:#06x} count0 {} faddr {:#04x} intrtx {:#06x} swrst {:#04x}",
        now.power,
        now.csr0,
        now.count0,
        now.faddr,
        now.intrtx,
        now.swrst
    );
    false
}

/// Перечислил ли нас хост: настройка выбрана, скорость договорена, признаки
/// шины замечены. `None` — устройство не поднималось.
///
/// Замок берётся насовсем, а не попыткой. По этому ответу решается, заводить ли
/// служебную задачу, и «занято» здесь означало бы навсегда остаться без обмена
/// — отказ, который выглядит как отсутствующее устройство и ничем себя не
/// объясняет. Обмен короткий, ждать его нечего.
#[must_use]
pub fn status() -> Option<(bool, bool, u8)> {
    let guard = GADGET.lock();
    let device = guard.as_ref()?;
    Some((device.is_configured(), device.is_high_speed(), device.seen))
}

/// Размеры ячеек корня — те же, что у всех остальных читателей дерева.
fn root_cells(fdt: &Fdt<'_>) -> (usize, usize) {
    let Some(root) = fdt.nodes().next() else {
        return (2, 1);
    };
    (
        root.property_u64("#address-cells").unwrap_or(2) as usize,
        root.property_u64("#size-cells").unwrap_or(1) as usize,
    )
}
