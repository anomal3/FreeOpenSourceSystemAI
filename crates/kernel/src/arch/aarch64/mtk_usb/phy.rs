//! Физический уровень USB: разбудить и объявить себя устройством.
//!
//! # Где он лежит на самом деле
//!
//! Не там, где кажется. У аппарата есть узел `usb_sif@11210000` — и есть
//! `usb1p_sif@11210000` с теми же регистрами по тому же адресу. Два имени на
//! одно окно выдают наследство: узлы описывают блок прежних кристаллов, и на
//! этом их читается ноль. Целый заход был потрачен на вывод «блоку не подведён
//! такт», а блока там просто нет.
//!
//! Настоящее окно драйвер MediaTek берёт **вторым `reg` узла контроллера**
//! (`musb_core.c`: `platform_get_resource(pdev, IORESOURCE_MEM, 1)` кладётся в
//! `xceiv->io_priv`), и у `dandelion` это `0x11CC0000`.
//!
//! Вторая половина той же ошибки — смещение. Все обращения идут через макросы
//! `USBPHY_READ32/WRITE32`, а те прибавляют к базе **`0x800`**. Числа в
//! комментариях изготовителя названы полностью и это подтверждают:
//! `USBPHY_CLR32(0x18, …)` подписано как `0x11F4_0818[23]`. Поэтому здесь
//! [`Phy::new`] прибавляет `0x800` один раз, а смещения дальше выписаны ровно
//! так, как у изготовителя, — чтобы их можно было сверять глазами.
//!
//! # Почему порядок записей нельзя менять
//!
//! Это не набор настроек, а пробуждение аналогового блока: сначала с линий
//! снимается всё принудительное, что оставил загрузчик, затем выдерживается
//! время на установление, и только потом объявляется режим. Порядок и обе
//! выдержки взяты из `usb20_phy.c` (`usb_phy_recover`) и не выведены.

use crate::arch::aarch64::timer;
use core::ptr;

/// Смещения регистров, как их называет изготовитель.
mod reg {
    /// Проверка подтяжек: ею контроллер питания определяет тип зарядки.
    pub const BIST: usize = 0x1c;
    /// Обнаружение зарядного устройства, сравнение напряжения на шине,
    /// порог разрыва и восемь бит ревизии в старшем байте.
    pub const CHARGER: usize = 0x18;
    /// Управление выводами физического уровня.
    pub const GPIO: usize = 0x20;
    /// Принудительные состояния линий — их надо снять все до единого.
    pub const FORCE: usize = 0x68;
    /// Режим: годность питания, сторона кабеля, подтяжки.
    pub const MODE: usize = 0x6c;
}

/// Окно регистров физического уровня.
///
/// Тип существует ради одного обещания: его значение можно создать только
/// [`Phy::new`], а тот требует отображённого окна. Дальше каждое обращение уже
/// безопасно, и `unsafe` не рассыпается по полусотне записей, где он перестал
/// бы что-либо значить.
#[derive(Clone, Copy)]
pub struct Phy {
    base: usize,
}

impl Phy {
    /// # Safety
    ///
    /// `window` — начало отображённого окна `io_priv` (второй `reg` узла
    /// контроллера). Смещение `0x800` до регистров прибавляется здесь.
    pub const unsafe fn new(window: usize) -> Self {
        Self {
            base: window + 0x800,
        }
    }

    fn read(self, offset: usize) -> u32 {
        // SAFETY: инвариант типа — окно отображено как память устройства.
        // volatile обязателен: значение меняет не программа.
        unsafe { ptr::read_volatile((self.base + offset) as *const u32) }
    }

    fn write(self, offset: usize, value: u32) {
        // SAFETY: см. [`Phy::read`].
        unsafe { ptr::write_volatile((self.base + offset) as *mut u32, value) };
    }

    fn clear(self, offset: usize, bits: u32) {
        self.write(offset, self.read(offset) & !bits);
    }

    fn set(self, offset: usize, bits: u32) {
        self.write(offset, self.read(offset) | bits);
    }

    /// Прочитать регистр режима и регистр принуждений — «до» и «после».
    ///
    /// Единственный отчёт, по которому видно разницу между «настроили» и
    /// «писали в никуда». Прежняя редакция этого драйвера писала мимо окна, и
    /// именно эта пара нулей — в отчёте и была тем, что увели в неверную
    /// сторону: ноль читается одинаково и у выключенного блока, и у
    /// несуществующего.
    pub fn state(self) -> (u32, u32) {
        (self.read(reg::MODE), self.read(reg::FORCE))
    }

    /// Снять с линий всё принудительное и привести блок в рабочее состояние.
    ///
    /// Каждый снимаемый бит означает «не слушай шину, слушай меня», и хотя бы
    /// один невыключенный делает устройство немым.
    pub fn recover(self) {
        // Питание могло появиться только что: изготовитель ждёт установления
        // 3,3 и 1,8 вольта, прежде чем трогать регистры.
        timer::delay_us(50);

        // Проверка подтяжек — её ведёт контроллер питания, и пока она идёт,
        // линии заняты не нами.
        self.clear(reg::BIST, 1 << 12);

        // Отладочный порт на тех же проводах. У MediaTek одни и те же выводы
        // умеют быть последовательной линией, и если это включено, шины USB на
        // них нет вовсе — сколько ни настраивай остальное.
        self.clear(reg::FORCE, 1 << 26);
        self.clear(reg::MODE, 1 << 16);
        self.clear(reg::GPIO, (1 << 9) | (1 << 8));

        // Принудительный сон.
        self.clear(reg::FORCE, 1 << 18);
        // Подтяжки линий данных вниз: они нужны стороне, которая опрашивает, а
        // мы отвечаем.
        self.clear(reg::FORCE, (1 << 6) | (1 << 7));
        // Выбор приёмопередатчика и типа сигнала.
        self.clear(reg::FORCE, 0x3 << 4);
        self.clear(reg::FORCE, 1 << 2);
        // Данные, навязанные линиям.
        self.clear(reg::FORCE, 0xf << 10);
        // И все признаки «значение навязано», разом.
        self.clear(
            reg::FORCE,
            (1 << 20) | (1 << 21) | (1 << 19) | (1 << 17) | (1 << 23),
        );

        // Обнаружение зарядки выключить, сравнение напряжения на шине
        // включить: без него блок не узнает, что кабель воткнут.
        self.clear(reg::CHARGER, 1 << 23);
        self.set(reg::CHARGER, 1 << 20);

        // Ревизия блока. Число выглядит настройкой, но ею не является: оно
        // выбирает поведение аналоговой части, и изготовитель ставит его на
        // всех кристаллах этого семейства.
        self.clear(reg::CHARGER, 0xff << 24);
        self.set(reg::CHARGER, 0x40 << 24);

        // Установление после всего снятого. Восемьсот микросекунд — из
        // `usb_phy_recover`; меньше означает объявить режим блоку, который ещё
        // не пришёл в себя.
        timer::delay_us(800);

        self.device_mode();

        // Порог, по которому блок считает кабель выдернутым, — на максимум.
        // Изготовитель поднимает его с заводского значения, и причина видна на
        // столе: с длинным или тонким кабелем устройство иначе отваливается
        // само по себе.
        self.set(reg::CHARGER, 0xf0);
    }

    /// Объявить: мы — устройство, а не хозяин шины.
    ///
    /// Одно значение вместо шести отдельных признаков: питание на шине годно,
    /// сессия открыта, сторона кабеля — устройство. Старшая половина — «эти
    /// значения навязаны нами», и без неё младшая не действует.
    fn device_mode(self) {
        self.clear(reg::MODE, 0x10);
        self.set(reg::MODE, 0x2f);
        self.set(reg::MODE, 0x3f << 8);
    }
}
