//! Переключение контекста задач на AArch64.
//!
//! # Что такое «контекст» и почему он такой маленький
//!
//! [`switch_context`] — обычная функция: её вызывает сама задача (планово, из
//! планировщика) либо код, которому обработчик прерывания передал управление уже
//! в контексте задачи (вытеснение, см. ниже). В обоих случаях действует AAPCS64,
//! и он уже делит регистры на две половины:
//!
//! * `x0`–`x18`, `v0`–`v7`, `v16`–`v31` — caller-saved. Компилятор вокруг любого
//!   `bl` сохраняет те из них, значения которых ему ещё нужны. Сохранять их
//!   здесь второй раз означает копировать полторы сотни байт на каждом
//!   переключении просто так;
//! * `x19`–`x28`, `x29` (FP), `x30` (LR) и младшие 64 бита `v8`–`v15` (то есть
//!   `d8`–`d15`) — callee-saved. Вызывающий вправе считать, что после возврата
//!   они не изменились, а раз «возврат» произойдёт уже в другой задаче —
//!   восстановить их обязаны мы.
//!
//! Плюс `SP`, который здесь и есть суть переключения: указатель стека однозначно
//! задаёт, где лежат кадры всех вызовов задачи. Всё остальное состояние задачи
//! живёт на её собственном стеке.
//!
//! `PSTATE` не сохраняется: арифметические флаги — scratch-состояние между
//! сравнением и переходом, через `bl` его никто не проносит, а маска `DAIF` —
//! свойство процессора, а не задачи (подробнее в [`Context::new`]).
//!
//! # Почему `d8`–`d15` здесь нет
//!
//! Спецификация `aarch64-unknown-none` объявляет таргет hardfloat
//! (`+v8a,+strict-align,+neon`), в отличие от `x86_64-unknown-none` с его
//! `+soft-float`. То есть по умолчанию LLVM вправе разместить в `v8`–`v15`
//! значение, живущее через вызов, и такие регистры пришлось бы сохранять.
//!
//! Вместо этого FP и SIMD запрещены ядру целиком — `-C
//! target-feature=-neon,-fp-armv8` в `.cargo/config.toml`, ровно как Linux
//! собирается с `-mgeneral-regs-only`. Причина не в экономии 64 байт на задачу,
//! а в том, что обработчик прерывания сохраняет только целочисленные регистры:
//! живое значение в `v0`–`v7` испортило бы любое прерывание, независимо от
//! переключения задач. Запрет закрывает обе дыры разом, а ядро арифметики с
//! плавающей точкой не ведёт.
//!
//! # Переключаются оба указателя стека
//!
//! Ядро работает на `SP_EL1` (см. [`super::interrupts`]), поэтому имя `sp` в
//! инструкции означает именно его — стек задачи в кольце ядра. Он и есть суть
//! переключения, и он же остаётся правильным, когда переключение происходит из
//! обработчика исключения: там `sp` означает тот же самый регистр, а не другой.
//! Прежняя раскладка (ядро на `SP_EL0`) этим свойством не обладала, и вызов
//! [`switch_context`] из обработчика записывал бы в `SP_EL1` чужое значение.
//!
//! `SP_EL0` — стек **пользовательской программы**, и он тоже часть состояния
//! задачи. Ядро его не трогает, но регистр один на процессор: две задачи,
//! исполняющие программы по очереди, без сохранения затирали бы друг другу
//! вершину стека. Обнаружилось бы это не отказом, а тем, что программа
//! продолжила работу на чужих данных. Поэтому [`Context`] несёт `sp_el0`, а
//! обращение к нему через `MRS`/`MSR` здесь законно ровно потому, что выбран
//! другой указатель (`SPSel = 1`): читать через `MRS` тот `SP_ELx`, который
//! выбран текущим, архитектурно CONSTRAINED UNPREDICTABLE.
//!
//! # Почему это ассемблер, а не Rust с `asm!`
//!
//! Смена `SP` посреди обычной функции ломает представление компилятора о её
//! кадре: он продолжает адресовать локальные переменные и сохранённые регистры
//! относительно `SP`/`x29`, которые теперь указывают на чужой стек. Никаким
//! `clobber` этого не выразить — `SP` нельзя объявить изменяемым операндом
//! именно потому, что кадр от него зависит. Поэтому функция целиком написана
//! ассемблером (`#[unsafe(naked)]` + [`naked_asm!`]): у неё нет ни пролога, ни
//! эпилога, ни локальных переменных, и вопрос о кадре не возникает вовсе.
//!
//! Между `naked_asm!` и `global_asm!` выбран первый — в отличие от таблицы
//! векторов в [`super::interrupts`], здесь нет требований к взаимному
//! расположению символов, зато есть польза от того, что символ объявлен обычной
//! функцией Rust: у него проверяемая сигнатура, а смещения полей [`Context`]
//! уезжают в ассемблер операндами `const`, то есть текст ссылается на настоящую
//! раскладку структуры, а не на переписанные от руки числа.

// TODO(интеграция): снять, когда планировщик начнёт вызывать переключение.
#![allow(dead_code)]

use crate::mm::VirtAddr;
use core::arch::naked_asm;
use core::mem::{offset_of, size_of};

/// Сохранённое состояние приостановленной задачи.
///
/// Поля читает и пишет только ассемблер [`switch_context`] — по смещениям,
/// вычисленным из этой же структуры (см. константы `OFF_*`).
///
/// Порядок полей выбран так, чтобы соседние регистры ложились парами `stp`/`ldp`
/// с выровненным на 16 смещением: одна инструкция вместо двух и вдвое меньше
/// обращений к памяти.
#[repr(C)]
#[derive(Debug, Default, Clone, Copy)]
pub struct Context {
    /// У ещё не запускавшейся задачи — адрес точки входа (см. [`task_entry`]).
    x19: u64,
    /// У ещё не запускавшейся задачи — аргумент точки входа.
    x20: u64,
    x21: u64,
    x22: u64,
    x23: u64,
    x24: u64,
    x25: u64,
    x26: u64,
    x27: u64,
    x28: u64,
    /// `x29`, указатель кадра. Голова цепочки раскрутки стека.
    fp: u64,
    /// `x30`, адрес возврата. Сюда уйдёт `ret` в конце переключения: у
    /// приостановленной задачи — точка после её собственного вызова
    /// [`switch_context`], у новой — [`task_entry`].
    lr: u64,
    /// `SP_EL1` — указатель стека задачи в кольце ядра.
    sp: u64,
    /// `SP_EL0` — стек пользовательской программы этой задачи. Ноль у задач,
    /// которые программ не запускали: восстанавливать нечего, а ноль в `SP_EL0`
    /// безвреден, пока в EL0 никто не уходит.
    sp_el0: u64,
}

// Смещения, на которые опирается ассемблер. Считаются из структуры, поэтому
// перестановка полей их не рассинхронизирует. Проверки ниже ловят другое: обе
// половины каждой пары `stp`/`ldp` обязаны лежать в соседних словах, иначе одна
// инструкция запишет не то поле, и ассемблер об этом не предупредит.
const OFF_X19: usize = offset_of!(Context, x19);
const OFF_X21: usize = offset_of!(Context, x21);
const OFF_X23: usize = offset_of!(Context, x23);
const OFF_X25: usize = offset_of!(Context, x25);
const OFF_X27: usize = offset_of!(Context, x27);
const OFF_FP: usize = offset_of!(Context, fp);
const OFF_SP: usize = offset_of!(Context, sp);
const OFF_SP_EL0: usize = offset_of!(Context, sp_el0);

const _: () = assert!(OFF_X19 == 0);
const _: () = assert!(offset_of!(Context, x20) == OFF_X19 + 8);
const _: () = assert!(OFF_X21 == 16 && offset_of!(Context, x22) == OFF_X21 + 8);
const _: () = assert!(OFF_X23 == 32 && offset_of!(Context, x24) == OFF_X23 + 8);
const _: () = assert!(OFF_X25 == 48 && offset_of!(Context, x26) == OFF_X25 + 8);
const _: () = assert!(OFF_X27 == 64 && offset_of!(Context, x28) == OFF_X27 + 8);
const _: () = assert!(OFF_FP == 80 && offset_of!(Context, lr) == OFF_FP + 8);
const _: () = assert!(OFF_SP == 96 && OFF_SP_EL0 == 104);
const _: () = assert!(size_of::<Context>() == 112);

// Смещение `stp`/`ldp` для 64-битных регистров кодируется семью битами со
// знаком, умноженными на 8: допустимы -512..=504. Самое дальнее поле сейчас —
// `sp` на 96, но проверка стоит здесь, а не в голове: она сломается ровно тогда,
// когда кто-нибудь допишет в структуру ещё сотню байт и получит невнятную
// ошибку ассемблера вместо внятной ошибки компиляции.
const _: () = assert!(OFF_SP <= 504);

/// Требование к выравниванию `SP` на AArch64.
///
/// Это не рекомендация ABI, а требование железа: при взведённом `SCTLR_EL1.SA`
/// любое обращение к памяти относительно невыровненного `SP` немедленно
/// возбуждает SP alignment fault — не «когда-нибудь потом», а на первой же
/// инструкции пролога новой задачи.
const STACK_ALIGN: usize = 16;

impl Context {
    /// Начальный контекст задачи, которая ещё ни разу не исполнялась.
    ///
    /// # Как устроен начальный кадр
    ///
    /// Восстанавливающая половина [`switch_context`] умеет ровно одно: загрузить
    /// регистры и сделать `ret`. Значит, начальный контекст обязан выглядеть
    /// так, будто задачу уже когда-то приостановили.
    ///
    /// На x86-64 для этого приходится раскладывать кадр на стеке: `ret` там
    /// снимает адрес возврата со стека, и положить его больше некуда. На AArch64
    /// `ret` берёт адрес из `x30`, а `x30` — обычное поле [`Context`]. Поэтому
    /// стек новой задачи остаётся **нетронутым**: достаточно заполнить регистры.
    ///
    /// ```text
    ///   lr  = task_entry   куда уйдёт `ret` при первом переключении
    ///   x19 = entry        точка входа задачи
    ///   x20 = arg          её аргумент
    ///   sp  = stack_top    округлённый вниз до 16
    ///   fp  = 0            конец цепочки кадров
    /// ```
    ///
    /// [`task_entry`] перекладывает `x20` в `x0` (там AAPCS64 ждёт первый
    /// аргумент) и уходит в `entry`. Точка входа и аргумент едут именно в
    /// `x19`/`x20`, потому что это callee-saved регистры — их всё равно
    /// восстанавливает переключение, и батут остаётся двумя инструкциями без
    /// единого обращения к памяти.
    ///
    /// `fp` обнулён намеренно: цепочка кадров задачи начинается здесь, и
    /// раскрутка стека (отладчиком или печатью трассы) обязана на этом
    /// оборваться, а не уйти в мусор над вершиной стека.
    ///
    /// Побочное следствие того, что стек не трогается: `stack_top` не обязан
    /// быть отображён в момент вызова — отображение понадобится только к первому
    /// переключению на эту задачу.
    ///
    /// # Про прерывания
    ///
    /// Задача начинает исполнение с той маской `DAIF`, которая была в момент
    /// переключения на неё: батут её не трогает — сделать это значило бы молча
    /// отменить решение планировщика. Если планировщик переключается, удерживая
    /// [`crate::sync::SpinLock`], точка входа получит управление с запрещёнными
    /// прерываниями и обязана разрешить их сама.
    ///
    /// # Требования к вызывающему
    ///
    /// `stack_top` — вершина области, которая к первому переключению на эту
    /// задачу должна быть отображена на запись. Невыровненное значение
    /// округляется вниз (потерять до 15 байт стека дешевле, чем получить SP
    /// alignment fault на ровном месте).
    #[must_use]
    pub fn new(stack_top: VirtAddr, entry: extern "C" fn(usize) -> !, arg: usize) -> Self {
        let sp = stack_top.as_usize() & !(STACK_ALIGN - 1);

        Self {
            x19: entry as usize as u64,
            x20: arg as u64,
            lr: task_entry as *const () as usize as u64,
            sp: sp as u64,
            ..Self::default()
        }
    }
}

/// Сохранить состояние текущей задачи в `from` и продолжить исполнение `to`.
///
/// Возврат из этого вызова произойдёт тогда, когда кто-нибудь переключится
/// обратно на текущую задачу, — возможно, спустя произвольное время и уже из
/// другого места ядра. Для вызывающего кода это неотличимо от обычного вызова:
/// callee-saved регистры и стек к моменту возврата те же, что были.
///
/// # Safety
///
/// * `from` и `to` — валидные указатели на [`Context`], не освобождаемые до
///   возврата управления;
/// * `to` описывает задачу, чей стек отображён на запись, а сам контекст
///   построен либо [`Context::new`], либо предыдущим вызовом этой функции.
///   Нулевой или чужой [`Context`] здесь — это переход по произвольному адресу с
///   произвольным `SP`, диагностировать который будет уже нечем;
/// * вызывать только при `SPSel = 1`, то есть из кода ядра — как обычного, так
///   и работающего внутри обработчика исключения. Ядро переведено на `SP_EL1`
///   при инициализации прерываний и обратно не переключается.
///
/// Аргументы могут совпадать: сохранение и восстановление одного и того же
/// контекста возвращает управление сразу после вызова.
#[unsafe(naked)]
pub unsafe extern "C" fn switch_context(from: *mut Context, to: *const Context) {
    // AAPCS64: `from` в x0, `to` в x1. Порядок сохранения (по возрастанию
    // смещений) и восстановления (по убыванию) зеркальны, чтобы перекос было
    // видно глазом в дизассемблере.
    //
    // x9 — caller-saved временный регистр: у naked-функции своего кадра нет, и
    // портить его никому не мешает.
    //
    // `SP` меняется ровно одной инструкцией и ровно один раз, и до неё всё
    // исполнение идёт на стеке уходящей задачи: случись здесь прерывание (а оно
    // может — функция не полагается на замаскированный `DAIF`), обработчик уйдёт
    // на свой `SP_EL1` и вернётся, ничего не заметив. После смены `SP` остаются
    // только загрузки из `to` и `ret` — ни одного обращения к стеку.
    naked_asm!(
        "stp x19, x20, [x0, #{off_x19}]",
        "stp x21, x22, [x0, #{off_x21}]",
        "stp x23, x24, [x0, #{off_x23}]",
        "stp x25, x26, [x0, #{off_x25}]",
        "stp x27, x28, [x0, #{off_x27}]",
        "stp x29, x30, [x0, #{off_fp}]",
        // `mov x9, sp`, а не `mrs x9, sp_el0`: при `SPSel = 0` регистр `SP_EL0`
        // выбран текущим, и доступ к нему через `MRS` архитектурно CONSTRAINED
        // UNPREDICTABLE.
        "mov x9, sp",
        "str x9, [x0, #{off_sp}]",
        // `SP_EL0` принадлежит программе этой задачи; при `SPSel = 1` доступ к
        // нему через `MRS`/`MSR` законен (см. заголовок модуля).
        "mrs x10, sp_el0",
        "str x10, [x0, #{off_sp_el0}]",

        "ldr x10, [x1, #{off_sp_el0}]",
        "msr sp_el0, x10",
        "ldr x9, [x1, #{off_sp}]",
        "mov sp, x9",
        "ldp x29, x30, [x1, #{off_fp}]",
        "ldp x27, x28, [x1, #{off_x27}]",
        "ldp x25, x26, [x1, #{off_x25}]",
        "ldp x23, x24, [x1, #{off_x23}]",
        "ldp x21, x22, [x1, #{off_x21}]",
        "ldp x19, x20, [x1, #{off_x19}]",
        "ret",
        off_x19 = const OFF_X19,
        off_x21 = const OFF_X21,
        off_x23 = const OFF_X23,
        off_x25 = const OFF_X25,
        off_x27 = const OFF_X27,
        off_fp = const OFF_FP,
        off_sp = const OFF_SP,
        off_sp_el0 = const OFF_SP_EL0,
    )
}

/// Первая инструкция, которую исполняет новая задача, — батут между
/// соглашением [`switch_context`] и соглашением точки входа.
///
/// Сюда приходит `ret` из [`switch_context`]: [`Context::new`] положил адрес
/// этой функции в `lr`. Точка входа и её аргумент к этому моменту уже
/// восстановлены в `x19`/`x20` — остаётся переложить аргумент в `x0`, куда его
/// ждёт AAPCS64, и уйти в саму задачу.
///
/// `blr`, а не `br`: тип точки входа возврат запрещает, но запрет действует
/// только на стороне Rust, и если он всё же будет нарушен (ассемблерная задача,
/// испорченный `x19`), управление придёт на `udf` строкой ниже — то есть отказ
/// случится здесь и сразу, а не по случайному адресу через неопределённое время.
#[unsafe(naked)]
unsafe extern "C" fn task_entry() -> ! {
    // `udf #0` даёт «Unknown reason» в `ESR_EL1.EC`, что обработчик отказов
    // покажет как `Fault::InvalidOpcode`. `brk` здесь хуже: отладочные
    // исключения ядро держит замаскированными.
    naked_asm!("mov x0, x20", "blr x19", "udf #0")
}
