//! ARM Generic Timer: физический таймер EL1 (`CNTP_*_EL0`).
//!
//! # Почему частота читается, а не задаётся константой
//!
//! Счётчик Generic Timer тикает от системного, а не процессорного генератора, и
//! его частота у каждой платформы своя: 62.5 МГц на QEMU virt, 19.2 МГц на
//! Raspberry Pi, 24 МГц на многих Rockchip и Allwinner. Единственный законный
//! источник — `CNTFRQ_EL0`, куда её обязана записать прошивка. Захардкоженное
//! значение дало бы систему, у которой «секунда» отличается от настоящей в
//! несколько раз, причём молча.
//!
//! # Почему таймер приходится перевзводить
//!
//! `CNTP_TVAL_EL0` — не период, а обратный отсчёт: железо однократно вычисляет
//! `CNTP_CVAL = CNTPCT + TVAL` и поднимает линию прерывания, когда счётчик
//! доходит до этого значения. Дальше условие `CNTPCT >= CVAL` остаётся истинным
//! навсегда, а линия у PPI таймера **уровневая**. Отсюда два следствия:
//!
//! * не перевзведя `TVAL`, следующего тика не будет — будет один бесконечный;
//! * `EOI` без перевзведения не помогает: контроллер снимет active, увидит
//!   всё ещё поднятую линию и тут же выдаст то же прерывание снова, и ядро
//!   уйдёт в цикл подтверждений, не выполнив ни одной полезной инструкции.
//!
//! Поэтому порядок в обработчике ровно такой: сначала [`rearm`], потом учёт
//! тика, потом `EOI`.

// TODO(интеграция): снять вместе с таким же `allow` в соседних модулях.
#![allow(dead_code)]

use core::arch::asm;
use core::sync::atomic::{AtomicU64, Ordering};

/// INTID прерывания физического таймера EL1 на QEMU virt.
///
/// В device tree и документации на машину это «PPI 14», но PPI нумеруются с
/// 16-го INTID, поэтому в регистрах GIC номер равен 30. Путаница между этими
/// двумя числами — классическая причина «таймер настроен, а прерываний нет».
pub const TIMER_INTID: u32 = 30;

/// `CNTP_CTL_EL0`, бит 0: таймер включён.
const CNTP_CTL_ENABLE: u64 = 1 << 0;
/// Бит 1: прерывание замаскировано. Ноль — то, что нам нужно.
const CNTP_CTL_IMASK: u64 = 1 << 1;
/// Бит 2 (только чтение): условие срабатывания выполнено прямо сейчас.
const CNTP_CTL_ISTATUS: u64 = 1 << 2;

/// `CNTP_TVAL_EL0` — 32-битный **знаковый** счётчик, поэтому период больше
/// `i32::MAX` взвести нельзя.
const MAX_TVAL: u64 = i32::MAX as u64;

/// Сколько тиков счётчика приходится на один тик планировщика. Считается один
/// раз в [`init`]: деление на каждом прерывании — расточительство, а частота
/// смениться не может.
static PERIOD: AtomicU64 = AtomicU64::new(0);

/// Частота счётчика в герцах из `CNTFRQ_EL0`.
#[must_use]
pub fn frequency() -> u64 {
    let value: u64;
    // SAFETY: `CNTFRQ_EL0` доступен на чтение с EL1 (и с EL0 при
    // `CNTKCTL_EL1.EL0PCTEN`), побочных эффектов чтение не имеет.
    unsafe {
        asm!("mrs {}, cntfrq_el0", out(reg) value, options(nomem, nostack, preserves_flags));
    }
    value
}

/// Период в тиках счётчика, посчитанный [`init`]. Ноль — таймер не запущен.
#[must_use]
pub fn period() -> u64 {
    PERIOD.load(Ordering::Relaxed)
}

/// Текущее значение счётчика — монотонное время с точностью до [`frequency`].
#[must_use]
pub fn counter() -> u64 {
    let value: u64;
    // SAFETY: чтение `CNTPCT_EL0` побочных эффектов не имеет. `isb` перед
    // чтением не ставим: точность порядка нескольких тактов конвейера здесь
    // никому не нужна, а барьер на каждом чтении времени — заметная цена.
    unsafe {
        asm!("mrs {}, cntpct_el0", out(reg) value, options(nomem, nostack, preserves_flags));
    }
    value
}

/// Почему таймер не запустился.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TimerError {
    /// `CNTFRQ_EL0` равен нулю: прошивка не заполнила регистр, и вычислить
    /// период не из чего. Придумывать частоту нельзя — вся арифметика времени
    /// в ядре стала бы враньём.
    UnknownFrequency,
    /// Частота настолько высока (или [`crate::irq::TIMER_HZ`] настолько мал),
    /// что период не помещается в 32-битный `CNTP_TVAL_EL0`.
    PeriodTooLarge(u64),
}

/// Запустить периодический таймер с частотой [`crate::irq::TIMER_HZ`].
///
/// Возвращает период в тиках счётчика.
///
/// # Safety
///
/// Прерывание [`TIMER_INTID`] должно быть уже разрешено в контроллере, а
/// векторы исключений — установлены: иначе первый же тик уйдёт в обработчик,
/// которого нет. Сами прерывания процессору при этом разрешать не обязательно —
/// таймер спокойно дождётся размаскирования.
pub unsafe fn init() -> Result<u64, TimerError> {
    let freq = frequency();
    if freq == 0 {
        return Err(TimerError::UnknownFrequency);
    }

    let period = freq / u64::from(crate::irq::TIMER_HZ);
    if period == 0 || period > MAX_TVAL {
        return Err(TimerError::PeriodTooLarge(period));
    }
    PERIOD.store(period, Ordering::Relaxed);

    // SAFETY: контракт функции. Порядок важен: сначала взводится отсчёт, и
    // только потом таймер включается — иначе он сработал бы на том значении
    // `TVAL`, которое осталось от прошивки.
    unsafe {
        asm!(
            "msr cntp_tval_el0, {period}",
            "msr cntp_ctl_el0, {ctl}",
            // Запись в системный регистр вступает в силу только после
            // контекстной синхронизации.
            "isb",
            period = in(reg) period,
            ctl = in(reg) CNTP_CTL_ENABLE,
            options(nomem, nostack, preserves_flags),
        );
    }

    Ok(period)
}

/// Взвести отсчёт до следующего тика. Вызывается на каждом прерывании таймера —
/// см. объяснение в заголовке модуля.
///
/// # Safety
///
/// Осмысленно только после успешного [`init`]: до него период равен нулю, и
/// запись нуля в `TVAL` означала бы «сработать немедленно», то есть вечный
/// поток прерываний.
pub unsafe fn rearm() {
    let period = PERIOD.load(Ordering::Relaxed);
    // SAFETY: контракт функции; запись `TVAL` затрагивает только сам таймер.
    unsafe {
        asm!("msr cntp_tval_el0, {}", in(reg) period, options(nomem, nostack, preserves_flags));
    }
}

/// Остановить таймер: выключить и замаскировать его прерывание.
///
/// # Safety
///
/// Побочных эффектов, кроме прекращения тиков, нет; `unsafe` — потому что
/// остановка таймера ломает учёт времени в [`crate::irq`].
pub unsafe fn stop() {
    // SAFETY: контракт функции.
    unsafe {
        asm!(
            "msr cntp_ctl_el0, {}",
            "isb",
            in(reg) CNTP_CTL_IMASK,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// Поднято ли сейчас условие срабатывания (`CNTP_CTL_EL0.ISTATUS`).
///
/// Нужно для диагностики: если после [`init`] бит не поднимается никогда,
/// проблема в таймере, а если поднимается, но прерывания не приходят — в GIC
/// или в маске `DAIF`.
#[must_use]
pub fn fired() -> bool {
    let ctl: u64;
    // SAFETY: чтение `CNTP_CTL_EL0` побочных эффектов не имеет.
    unsafe {
        asm!("mrs {}, cntp_ctl_el0", out(reg) ctl, options(nomem, nostack, preserves_flags));
    }
    ctl & CNTP_CTL_ISTATUS != 0
}
