/// Приоритет прерывания таймера.
///
/// Численно меньше порога `PMR` в GIC (иначе прерывание не пройдёт) и при этом
/// не самый высокий: место над таймером оставлено под источники, которым нельзя
/// опаздывать.
const TIMER_PRIORITY: u8 = 0x80;

/// Установить векторы, поднять контроллер прерываний и таймер.
///
/// Прерывания процессору **не** разрешаются: это отдельное решение вызывающего,
/// принимаемое, когда остальное ядро к ним готово (см. [`enable`]).
///
/// Вызывать с уже отображёнными окнами GIC (это делает
/// [`super::paging::build_kernel_address_space`]) и на том стеке, на котором
/// ядро собирается работать дальше. Повторный вызов безвреден.
pub fn init() {
    // Настройка идёт с запрещёнными прерываниями и восстанавливает маску как
    // была. На первом вызове они и так запрещены, но полагаться на это незачем:
    // половина работы здесь — смена стека и таблицы векторов, и прерывание,
    // пришедшее в середине, увидело бы несогласованное состояние.
    without_interrupts(init_locked);
}

fn init_locked() {
    // SAFETY: таблица собрана в `global_asm!` этого модуля, лежит в
    // исполняемой секции образа и выровнена на 2048 (проверяется внутри).
    unsafe { install_vectors() };

    // SAFETY: прерывания запрещены вызывающей `without_interrupts`, а стек
    // обработчиков — статический массив в данных ядра, отображённый на запись.
    unsafe { install_exception_stack() };

    // SAFETY: окна GIC отображены как Device-память при построении адресного
    // пространства; параллельного доступа к контроллеру нет.
    let version = unsafe { gic::init() };
    match version {
        gic::Version::V2 => {
            kprintln!("  interrupts  : GICv2, distributor {:#010x}", gic::GICD_BASE);
        }
        other => {
            kprintln!(
                "WARNING: unsupported interrupt controller ({other:?}) at {:#010x}",
                gic::GICD_BASE
            );
            kprintln!("         no timer and no device interrupts will be delivered");
            kprintln!("         on QEMU this is fixed by -machine virt,gic-version=2");
            return;
        }
    }

    // SAFETY: контроллер — GICv2 и уже включён.
    unsafe { gic::enable_interrupt(timer::TIMER_INTID, TIMER_PRIORITY) };

    // SAFETY: векторы установлены, прерывание таймера разрешено в контроллере.
    match unsafe { timer::init() } {
        Ok(period) => kprintln!(
            "  timer       : {} Hz counter, {} Hz tick (period {period}, INTID {})",
            timer::frequency(),
            crate::irq::TIMER_HZ,
            timer::TIMER_INTID,
        ),
        Err(err) => {
            kprintln!("WARNING: system timer not started: {err:?}");
            kprintln!("         CNTFRQ_EL0 reads {}", timer::frequency());
        }
    }
}

/// Записать адрес таблицы в `VBAR_EL1`.
///
/// # Safety
///
/// Таблица обязана быть валидным кодом обработчиков и оставаться отображённой
/// на исполнение всё время работы ядра.
unsafe fn install_vectors() {
    // Взятие адреса внешнего символа — безопасная операция: содержимое не
    // читается, а сам символ определён в `global_asm!` этого же модуля.
    let base = (&raw const __exception_vectors) as usize;

    // Проверка не декоративная: `VBAR_EL1` молча отбросил бы младшие 11 бит, и
    // исключения начали бы уходить в произвольное место образа. Поймать это
    // потом почти невозможно — отладчик показал бы «прыжок в никуда» без
    // всякой связи с векторами.
    assert!(base % 2048 == 0, "exception vector table must be 2048-byte aligned");

    // SAFETY: адрес выровнен и указывает на таблицу; запись `VBAR_EL1`
    // затрагивает только маршрутизацию исключений, а `isb` гарантирует, что
    // следующее исключение пойдёт уже по новому адресу.
    unsafe {
        asm!(
            "msr vbar_el1, {}",
            "isb",
            in(reg) base,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// Перевести исполнение ядра на `SP_EL0`, оставив `SP_EL1` под стек
/// обработчиков.
///
/// # Safety
///
/// Вызывать с замаскированными прерываниями: между сменой `SP_EL1` и
/// переключением `SPSel` исключение получило бы наполовину настроенный стек.
/// Повторный вызов безвреден — последовательность идемпотентна.
unsafe fn install_exception_stack() {
    let stack = EXCEPTION_STACK.get() as usize;
    // Стек растёт вниз, поэтому в `SP_EL1` кладётся верхняя граница массива.
    // Выравнивание на 16 обеспечено `#[repr(align(16))]` и кратностью размера.
    let top = stack + EXCEPTION_STACK_SIZE;

    // SAFETY: последовательность обязана быть неделимой относительно обращений
    // к памяти: пока выбран `SP_EL1`, ни одной инструкции, трогающей стек, быть
    // не должно — иначе она ушла бы на стек обработчиков. Значение выбранного
    // `SP` до и после блока одно и то же, поэтому кадр вызывающей функции
    // остаётся действительным; `nostack` не указан именно потому, что блок
    // трогает `SP`.
    //
    // `msr spsel, #1` в середине — не избыточность: при повторном вызове
    // `SPSel` уже равен нулю, и `mov sp, {top}` без него записал бы стек
    // обработчиков в `SP_EL0`, то есть увёл бы с рабочего стека само ядро.
    // С этой инструкцией последовательность идемпотентна.
    unsafe {
        asm!(
            "mov {tmp}, sp",
            "msr sp_el0, {tmp}",
            "msr spsel, #1",
            "mov sp, {top}",
            "msr spsel, #0",
            tmp = out(reg) _,
            top = in(reg) top,
            options(nomem, preserves_flags),
        );
    }

    DEDICATED_STACK.store(true, Ordering::Relaxed);
}

/// Указатель стека пользовательского уровня.
fn sp_el0() -> u64 {
    let value: u64;
    // SAFETY: чтение `SP_EL0` побочных эффектов не имеет.
    unsafe {
        asm!("mrs {}, sp_el0", out(reg) value, options(nomem, nostack, preserves_flags));
    }
    value
}

