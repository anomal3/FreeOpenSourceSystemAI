//! Исключения и прерывания AArch64: таблица векторов, разбор `ESR_EL1`,
//! маскирование `DAIF`.
//!
//! # Устройство таблицы векторов
//!
//! `VBAR_EL1` указывает не на массив адресов (как IDT на x86-64), а на **код**:
//! шестнадцать площадок по 128 байт подряд. Номер площадки определяется не
//! номером прерывания, а тем, *откуда* и *какого рода* исключение пришло:
//!
//! ```text
//!   смещение  источник                        тип
//!   0x000     Current EL, SP_EL0              Synchronous
//!   0x080     Current EL, SP_EL0              IRQ
//!   0x100     Current EL, SP_EL0              FIQ
//!   0x180     Current EL, SP_EL0              SError
//!   0x200     Current EL, SP_ELx              Synchronous
//!   ...
//!   0x400     Lower EL, AArch64               Synchronous
//!   ...
//!   0x600     Lower EL, AArch32               Synchronous
//!   ...
//! ```
//!
//! Отсюда требование выравнивания на 2048 байт: адрес таблицы кладётся в
//! `VBAR_EL1`, младшие 11 бит которого — RES0. Невыровненный адрес не вызовет
//! ошибки, он просто потеряет младшие биты, и процессор начнёт прыгать в
//! середину чужого кода — отказ будет выглядеть как что угодно, кроме
//! неверного `VBAR`.
//!
//! # Почему `global_asm!`, а не `naked_asm!`
//!
//! Записи обязаны лежать одним куском по фиксированным смещениям 0x00, 0x80,
//! 0x100, … Каждая `#[naked]`-функция — отдельный символ, и ни порядок символов
//! в секции, ни отсутствие выравнивающих прокладок между ними язык не
//! гарантирует: линкер вправе переставить их или раздвинуть. `global_asm!`
//! отдаёт весь блок целиком, вместе с `.balign`, и раскладка перестаёт зависеть
//! от чужих решений.
//!
//! # Почему контекст сохраняется целиком
//!
//! Обработчик написан на Rust и вызывается обычным `bl`, то есть по AAPCS64
//! вправе испортить `x0`–`x18` (caller-saved) и через собственный пролог —
//! callee-saved регистры прерванного кода. Прерывание же приходит между двумя
//! произвольными инструкциями: в регистрах в этот момент лежат промежуточные
//! значения любого вычисления. Поэтому заглушка сохраняет `x0`–`x30` целиком,
//! плюс `SP`, `ELR_EL1` и `SPSR_EL1`, и восстанавливает всё перед `eret`.
//! Забытый регистр не проявится сразу: он испортит одно случайное вычисление в
//! стороннем коде спустя произвольное время — самый дорогой в отладке класс
//! ошибок, ради экономии четырёх инструкций.
//!
//! `ELR_EL1`/`SPSR_EL1` сохраняются и восстанавливаются не «на всякий случай»:
//! вложенное исключение перезаписало бы их, а планировщику в следующей фазе
//! именно через них предстоит переключать задачи.
//!
//! # Ядро работает на `SP_EL1`
//!
//! `SPSel = 1` с самого начала и навсегда: имя `sp` в коде ядра всегда означает
//! `SP_EL1`, а `SP_EL0` принадлежит исключительно пользовательской программе.
//! Исключение из EL0 приходит на `SP_EL1`, то есть **на стек той задачи,
//! которая эту программу и запустила**, — прямо под её собственными кадрами.
//! Так устроен Linux на arm64, и так же теперь устроено здесь.
//!
//! Причина в том, что задач с программами стало больше одной (Phase 13a).
//! Раньше ядро жило на `SP_EL0`, а под обработчики был отведён отдельный
//! статический стек, и это работало ровно до тех пор, пока программа была одна.
//! Дальше конструкция рассыпается сразу с двух сторон: общий стек обработчиков
//! означал бы, что кадр одной программы лежит поверх кадра другой, а
//! [`crate::arch::context::switch_context`] переставал бы понимать, какой из
//! двух `SP` он сохраняет — переключение задач из обработчика записало бы
//! `SP_EL1` значением чужого `SP_EL0`. Единственный выбранный `SP` снимает оба
//! вопроса разом.
//!
//! **Чем за это заплачено, стоит сказать прямо.** Отдельный стек обработчиков
//! давал одну полезную вещь: переполнение стека ядра упиралось в страницу-
//! ловушку, и обработчик отказа успевал об этом сообщить, потому что стартовал
//! на другом стеке. Теперь такой отказ попытается сохранить контекст в ту же
//! неотображённую страницу и повторится — то есть переполнение **стека
//! загрузки** (единственного, у которого ловушка настоящая) станет молчаливым
//! зависанием вместо диагностики. Стеки задач это не затрагивает: у них
//! ловушки нет вовсе, их переполнение ловит полоса-сторож на ближайшем
//! переключении (см. [`crate::sched`]). На x86-64 тот же случай по-прежнему
//! ловится через IST.
//!
//! Побочное следствие: исключение из группы «Current EL, SP_ELx» больше не
//! означает «отказ внутри обработчика» — теперь через неё приходят вообще все
//! исключения кода ядра.

