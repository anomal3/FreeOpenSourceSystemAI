/// Точка входа из ассемблерной заглушки.
///
/// `kind` — номер записи таблицы (0…15), `frame` — сохранённый контекст на
/// стеке обработчика.
extern "C" fn trap_handler(kind: u64, frame: *mut TrapFrame) {
    // SAFETY: указатель сформирован заглушкой как `mov x1, sp` сразу после
    // записи всех полей кадра, то есть указывает на инициализированный
    // `TrapFrame`, выровненный по 16 байт и живущий до `eret`. Других ссылок на
    // него не существует: кадр только что создан на стеке обработчика, а
    // прерывания на время обработки замаскированы процессором.
    let frame = unsafe { &mut *frame };

    let source = kind >> KIND_SOURCE_SHIFT;
    match kind & KIND_TYPE_MASK {
        TYPE_SYNC => handle_sync(source, frame),
        TYPE_IRQ => handle_irq(),
        // FIQ ядро не использует: на этой машине все прерывания приходят как
        // IRQ. Единственный способ сюда попасть — чужая настройка контроллера,
        // и продолжать исполнение, не понимая источника, смысла нет.
        TYPE_FIQ => fault::handle(Fault::Other(kind), context(source, frame)),
        // SError — асинхронный отказ шины (обращение по адресу, на который
        // никто не отвечает). Восстановиться после него нельзя: инструкция,
        // которая его вызвала, давно позади.
        TYPE_SERROR => fault::handle(Fault::Other(frame.esr), context(source, frame)),
        _ => unreachable!(),
    }
}

/// Собрать арх-независимое описание места отказа.
fn context(source: u64, frame: &TrapFrame) -> TrapContext {
    // Номер группы векторов и есть ответ на вопрос, каким `SP` пользовался
    // прерванный код. «Current EL, SP_ELx» — единственный случай, когда это тот
    // же самый указатель, что и у обработчика, и его настоящее значение лежит в
    // кадре. Во всех остальных (обычный код ядра на SP_EL0, любой код нижнего
    // EL) прерванный стек — это `SP_EL0`, а `sp` обработчика говорит лишь о
    // стеке обработчика. Взять не тот — значит показать в отчёте адрес внутри
    // статического массива ядра вместо места, где всё сломалось.
    let sp = if source == SOURCE_CURRENT_SPX { frame.sp } else { sp_el0() };
    TrapContext { pc: frame.elr as usize, sp: sp as usize, error: frame.esr }
}

fn handle_sync(source: u64, frame: &TrapFrame) -> ! {
    let ctx = context(source, frame);

    // Отказ, пришедший на SP_ELx, означает, что ядро уже исполнялось на стеке
    // обработчика, — то есть отказ случился внутри обработки другого отказа.
    if source == SOURCE_CURRENT_SPX && DEDICATED_STACK.load(Ordering::Relaxed) {
        fault::handle(Fault::DoubleFault, ctx);
    }

    let esr = frame.esr;
    let ec = (esr >> ESR_EC_SHIFT) & ESR_EC_MASK;
    let iss = esr & ESR_ISS_MASK;

    let fault = match ec {
        EC_DATA_ABORT_LOWER | EC_DATA_ABORT_CURRENT => Fault::PageFault {
            addr: frame.far as usize,
            // При отказе на обслуживании кеша `WnR` выставлен всегда и
            // направление обращения не отражает.
            write: iss & ISS_WNR != 0 && iss & ISS_CM == 0,
            fetch: false,
            protection: is_permission_fault(iss),
        },
        EC_INSTRUCTION_ABORT_LOWER | EC_INSTRUCTION_ABORT_CURRENT => Fault::PageFault {
            addr: frame.far as usize,
            // Выборка инструкции — всегда чтение.
            write: false,
            fetch: true,
            protection: is_permission_fault(iss),
        },
        // «Unknown reason» — сюда попадает и неопознанная инструкция, и
        // исполнение при недопустимом состоянии процессора.
        EC_UNKNOWN | EC_ILLEGAL_STATE => Fault::InvalidOpcode,
        EC_BRK => Fault::Breakpoint,
        other => Fault::Other(other),
    };

    fault::handle(fault, ctx)
}

/// Отказ по правам доступа (страница есть, но обращение ей запрещено) — в
/// отличие от отсутствующей трансляции.
fn is_permission_fault(iss: u64) -> bool {
    (iss & ISS_FSC_MASK) & FSC_KIND_MASK == FSC_KIND_PERMISSION
}

/// Сколько неизвестных источников прерываний показать, прежде чем замолчать.
///
/// Молчать сразу нельзя — потерянный источник придётся искать вслепую; но и
/// печатать на каждом прерывании тоже: неотключаемый источник забил бы UART и
/// сделал систему неотличимой от зависшей.
const UNKNOWN_IRQ_REPORTS: u32 = 4;

static UNKNOWN_IRQS: AtomicU32 = AtomicU32::new(0);

fn handle_irq() {
    // SAFETY: вызывается только из вектора IRQ, то есть контроллер действительно
    // выставил прерывание и ждёт подтверждения.
    let iar = unsafe { gic::acknowledge() };
    let intid = iar & gic::INTID_MASK;

    if intid == gic::SPURIOUS_INTID {
        // Источник исчез до подтверждения. `EOI` в этом случае не отправляется:
        // подтверждать нечего, и лишняя запись сбила бы контроллеру учёт
        // активных прерываний.
        return;
    }

    if intid == timer::TIMER_INTID {
        // Взвести до всего остального: линия таймера уровневая и держится
        // поднятой, пока сравнение не перепрограммировано, — `EOI` без этого
        // немедленно вернул бы нас сюда же.
        // SAFETY: таймер инициализирован (иначе INTID 30 не был бы разрешён).
        unsafe { timer::rearm() };
        crate::irq::on_timer_tick();
    } else {
        let seen = UNKNOWN_IRQS.fetch_add(1, Ordering::Relaxed);
        if seen < UNKNOWN_IRQ_REPORTS {
            kprintln!("WARNING: unexpected interrupt, INTID {intid}");
        }
    }

    // SAFETY: `iar` получен из `acknowledge` выше и используется ровно один раз.
    unsafe { gic::end_of_interrupt(iar) };
}

