/// Текущее значение `DAIF`.
fn daif() -> u64 {
    let value: u64;
    // SAFETY: чтение `DAIF` побочных эффектов не имеет.
    unsafe {
        asm!("mrs {}, daif", out(reg) value, options(nomem, nostack, preserves_flags));
    }
    value
}

/// Разрешить прерывания (снять маску `I`).
///
/// Отладочные исключения, FIQ и SError остаются замаскированными: обработчиков,
/// способных с ними что-то сделать, у ядра нет, а необъяснимая остановка хуже
/// пропущенного события.
pub fn enable() {
    // SAFETY: `daifclr` меняет только маску прерываний в `PSTATE`; векторы к
    // этому моменту обязан установить `init`, иначе исключение ушло бы в
    // векторы прошивки — но это ответственность вызывающего, а не память.
    unsafe {
        asm!(
            "msr daifclr, #{mask}",
            mask = const DAIFCLR_IRQ,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// Запретить прерывания (поднять маску `I`).
pub fn disable() {
    // SAFETY: см. [`enable`].
    unsafe {
        asm!(
            "msr daifset, #{mask}",
            mask = const DAIFCLR_IRQ,
            options(nomem, nostack, preserves_flags),
        );
    }
}

/// Разрешены ли сейчас прерывания.
#[must_use]
pub fn enabled() -> bool {
    daif() & DAIF_I == 0
}

/// Выполнить `f` с запрещёнными прерываниями и вернуть маску в исходное
/// состояние.
///
/// Именно «вернуть как было», а не «разрешить в конце». Вызовы вкладываются:
/// критическая секция внутри другой критической секции, обработчик, взявший
/// тот же замок. Безусловное `enable` во внутреннем вызове открыло бы окно
/// посреди внешней секции — и ошибка проявилась бы как редкое повреждение
/// данных под нагрузкой, воспроизводимое раз в сутки.
pub fn without_interrupts<T>(f: impl FnOnce() -> T) -> T {
    let was_enabled = enabled();
    if was_enabled {
        disable();
    }

    let result = f();

    if was_enabled {
        enable();
    }
    result
}
