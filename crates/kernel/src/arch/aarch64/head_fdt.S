// Второй вход в ядро: тот, по которому запускается Linux на ARM64.
//
// # Зачем он нужен
//
// Первый вход — `kernel_main(*const BootInfo)` — принимает управление от
// **нашего** загрузчика: память уже описана, таблицы страниц уже построены
// прошивкой, MMU включён. Заводской загрузчик телефона (LK у MediaTek) ничего
// этого не делает и делать не будет: у него один договор, и другого не бывает.
//
// К моменту перехода на нас по этому договору:
//
//   * MMU выключен, кэш данных выключен, кэш инструкций может быть включён;
//   * прерывания замаскированы;
//   * в `x0` — физический адрес дерева устройств, в `x1`..`x3` нули;
//   * образ лежит по адресу из заголовка загрузчика, и первые 64 байта образа —
//     заголовок ниже.
//
// Кэши данных загрузчик обязан был вычистить перед переходом — так написано в
// самом договоре. Полагаться на это приходится: обход всех уровней кэша по
// set/way занял бы здесь больше места, чем весь остальной вход.
//
// # Почему заголовок именно такой
//
// Первое слово обязано быть исполнимой инструкцией: часть загрузчиков просто
// переходит по началу образа, ничего не читая. Дальше — смещение, размер, флаги
// и метка `ARM\x64`, по которой загрузчик отличает наш образ от чужого.
//
// `text_offset` обязан совпасть с адресом компоновки минус начало ОЗУ. Ноль в
// этом поле уже стоил дня: образ лёг на 512 КиБ ниже, чем ожидал сам, переходы
// (они PC-относительные) продолжали работать, а всё абсолютное смотрело в
// пустоту. Машина исправно крутилась и молчала.

.section .text.boot, "ax"
.global _phone_start

_phone_start:
    b       phone_entry             // code0: переход через заголовок
    .long   0                       // code1: договором отведено, не используется
    .quad   0x80000                 // text_offset: считая от начала ОЗУ
    // image_size: со стеком и `.bss`. Вычитается адрес метки, определённой
    // здесь же, а не `__image_start` из компоновочного сценария: разность двух
    // внешних символов ассемблер посчитать не может — они станут известны
    // только на компоновке. Значения это не меняет, метка и есть начало образа.
    .quad   __image_end - _phone_start
    .quad   0x0000000000000008      // flags: little-endian, страницы 4 КиБ
    .quad   0                       // res2
    .quad   0                       // res3
    .quad   0                       // res4
    .ascii  "ARM\x64"               // метка: по ней нас узнаю́т
    .long   0                       // смещение заголовка PE, у нас его нет

phone_entry:
    // Дерево устройств — единственное, что нам передали. Стека ещё нет, поэтому
    // не в стек.
    mov     x19, x0

    // --- Уровень исключений ------------------------------------------------
    //
    // Всё ядро написано под EL1: там его таблицы страниц (`TTBR0_EL1`), там его
    // векторы (`VBAR_EL1`), там его таймер. Если загрузчик оставил нас на EL2 —
    // а он вправе, — записи в регистры EL1 будут проходить и не значить ничего:
    // трансляцию в этот момент определяет другой набор таблиц. Отказ выглядит
    // как «MMU включили, и машина исчезла».
    //
    // Поэтому с EL2 спускаемся сами, ровно так же, как это делает Linux.
    mrs     x0, CurrentEL
    lsr     x0, x0, #2
    cmp     x0, #2
    b.ne    el1_ready

    // Дать EL1 доступ к системному счётчику и таймеру, иначе его чтение оттуда
    // будет отдавать исключение, а не время.
    mrs     x0, cnthctl_el2
    orr     x0, x0, #3              // EL1PCTEN | EL1PCEN
    msr     cnthctl_el2, x0
    msr     cntvoff_el2, xzr        // виртуальное время равно физическому

    // EL1 исполняется в AArch64, а не в AArch32.
    movz    x0, #0x8000, lsl #16    // HCR_EL2.RW
    msr     hcr_el2, x0

    // Не перехватывать на EL2 ни векторы, ни отладку, ни обращения к
    // сопроцессорным регистрам: перехватывать их некому.
    movz    x0, #0x33ff
    msr     cptr_el2, x0
    msr     hstr_el2, xzr

    // Сбросовое значение SCTLR_EL1: MMU и кэши выключены, RES1-биты на месте.
    // Без него в регистре осталось бы то, что оставил загрузчик, а там может
    // быть включённый MMU с чужими таблицами.
    movz    x0, #0x0800
    movk    x0, #0x30d0, lsl #16
    msr     sctlr_el1, x0

    // Вернуться на EL1 с собственным стеком (EL1h) и замаскированными
    // прерываниями: обработчиков у нас ещё нет.
    movz    x0, #0x3c5              // DAIF = 1111, M = EL1h
    msr     spsr_el2, x0
    adr     x0, el1_ready
    msr     elr_el2, x0
    eret

el1_ready:
    // Стек. Свой, а не тот, что оставил загрузчик: чужой указатель показывает в
    // память, которую тот же загрузчик считает своей.
    adrp    x1, __stack_top
    add     x1, x1, :lo12:__stack_top
    mov     sp, x1

    // `.bss` в файле не хранится — обнулить обязаны мы. Не сделать этого значит
    // получить статические переменные, набитые тем, что лежало в этой памяти до
    // нас: на телефоне это остатки заставки загрузчика, то есть правдоподобный
    // мусор. Здесь в `.bss` лежат в том числе ранние таблицы страниц.
    adrp    x1, __bss_start
    add     x1, x1, :lo12:__bss_start
    adrp    x2, __bss_end
    add     x2, x2, :lo12:__bss_end
1:  cmp     x1, x2
    b.hs    2f
    str     xzr, [x1], #8
    b       1b
2:

    // Таблица векторов — раньше всего остального, что может отказать. Без неё
    // любое исключение уходит по адресу, который оставил чужой загрузчик, и
    // выглядит это как зависшая машина: ни строки, ни признака. Настоящую
    // таблицу ядра поставит `interrupts::init`, когда появятся куча и вывод;
    // до тех пор действует эта, у которой одна работа — назвать отказ отказом.
    adrp    x1, phone_vectors
    add     x1, x1, :lo12:phone_vectors
    msr     vbar_el1, x1
    isb

    // Разрешить SIMD и плавающую точку. Ядро собрано softfloat-таргетом и само
    // векторных регистров не берёт, но `CPACR_EL1.FPEN` после сброса запрещает
    // их целиком, и один-единственный векторный доступ из чужого кода (или из
    // будущей ветки компилятора) отдал бы исключение класса 0x07 — то самое,
    // которое на `boot-bare` выглядело как «разбор дерева вернул None».
    mrs     x1, cpacr_el1
    orr     x1, x1, #(3 << 20)      // FPEN = 0b11: не перехватывать ни с EL0, ни с EL1
    msr     cpacr_el1, x1
    isb

    mov     x0, x19
    bl      phone_boot

    // `phone_boot` не возвращается. Если вернулся — стоим, а не падаем в мусор
    // за концом образа.
3:  wfe
    b       3b

// Обработчик отказа раннего этапа: собрать номер вектора и синдром и отдать их
// в Rust. Печатать отсюда некуда — линия к этому моменту может быть ещё не
// найдена, а вбитый адрес QEMU на телефоне сам стал бы вторым отказом, причём
// тихим. Куда деть два числа, решает `phone_fault`: у него есть и найденный
// экран, и найденная линия, и на каждой машине сработает то, что там есть.
phone_fault_entry:
    mrs     x1, esr_el1
    bl      phone_fault
4:  wfe
    b       4b

// Шестнадцать векторов по 128 байт, вся таблица выровнена по 2 КиБ — так
// требует процессор, и невыровненную он просто не примет.
.macro PHONE_VECTOR id
    .align  7
    mov     x0, #\id
    b       phone_fault_entry
.endm

    .align  11
phone_vectors:
    PHONE_VECTOR 0
    PHONE_VECTOR 1
    PHONE_VECTOR 2
    PHONE_VECTOR 3
    PHONE_VECTOR 4
    PHONE_VECTOR 5
    PHONE_VECTOR 6
    PHONE_VECTOR 7
    PHONE_VECTOR 8
    PHONE_VECTOR 9
    PHONE_VECTOR 10
    PHONE_VECTOR 11
    PHONE_VECTOR 12
    PHONE_VECTOR 13
    PHONE_VECTOR 14
    PHONE_VECTOR 15
