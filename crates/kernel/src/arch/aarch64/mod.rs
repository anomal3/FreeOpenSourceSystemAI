/// Адрес, по которому ядро **предполагает** последовательный порт.
///
/// # Зачем он отдельной константой
///
/// Ради одной проверки: адрес угадан, а угадать его можно неверно. Она простая и
/// решающая: **если по этому адресу оперативная память, то это не порт**. Карта
/// памяти от прошивки описывает MMIO как `Reserved` либо не описывает вовсе;
/// попадание в область, из которой ядро потом раздаёт кадры, означает ровно
/// одно — там память, а не регистры.
///
/// # Чем это оказалось на деле
///
/// VirtualBox 7.2.14 на Apple Silicon PL011 не создаёт вовсе, а его
/// оперативная память начинается с `0x08000000` и покрывает `0x09000000`
/// целиком. То есть каждый печатаемый символ ядро писало в память, которую
/// распределитель кадров волен отдать под таблицы страниц, кучу или буфер DMA,
/// — а флаг «передатчик занят» читало оттуда же и этому верило. Отказ такого
/// рода не выглядит отказом порта: он выглядит порчей чего угодно другого,
/// спустя произвольное время.
pub const SERIAL_MMIO: u64 = QEMU_VIRT_PL011 as u64;

/// Физический адрес PL011 на QEMU `-machine virt`.
///
/// В отличие от x86_64, где COM1 закреплён за портом 0x3F8 архитектурой
/// платформы, на ARM никакого «общепринятого» адреса UART не существует: у
/// Raspberry Pi это 0x3F20_1000 (BCM2835) или 0xFE20_1000 (BCM2711), у
/// Rockchip — своё, и так далее. Значение ниже верно ровно для одной машины —
/// QEMU virt, — и захардкожено осознанно: на Phase 1 device tree ещё не
/// разбирается, а без вывода в порт отладка после `ExitBootServices` невозможна.
///
/// TODO(Phase 2-3): адрес и тип UART должны приезжать из HAL — из FDT
/// (`BootInfo::device_tree`, узел `/pl011@...`) либо из ACPI SPCR
/// (`BootInfo::acpi_rsdp`). До тех пор ядро запускается только на QEMU virt.
const QEMU_VIRT_PL011: usize = 0x0900_0000;

// Смещения регистров PL011 (ARM PrimeCell UART, DDI0183).
const REG_DR: usize = 0x00; // Data
const REG_FR: usize = 0x18; // Flag
const REG_IBRD: usize = 0x24; // Integer Baud Rate Divisor
const REG_FBRD: usize = 0x28; // Fractional Baud Rate Divisor
const REG_LCRH: usize = 0x2C; // Line Control
const REG_CR: usize = 0x30; // Control
const REG_IMSC: usize = 0x38; // Interrupt Mask Set/Clear
const REG_ICR: usize = 0x44; // Interrupt Clear

const DR_OVERRUN: u32 = 1 << 11; // байт пришёл в полное FIFO и потерян
const FR_RXFE: u32 = 1 << 4; // приёмное FIFO пусто
const FR_TXFF: u32 = 1 << 5; // передающее FIFO заполнено

/// `IMSC`/`ICR`, бит 4: приёмное FIFO дошло до порога заполнения.
const INT_RX: u32 = 1 << 4;
/// Бит 6: тайм-аут приёма — в FIFO что-то лежит, но до порога не дошло и новых
/// байт не приходит. Без этого прерывания одиночное нажатие клавиши осталось бы
/// в FIFO до тех пор, пока пользователь не наберёт ещё несколько символов.
const INT_RX_TIMEOUT: u32 = 1 << 6;

/// Все биты регистров прерываний PL011: одиннадцать источников.
const INT_ALL: u32 = 0x7FF;

const LCRH_FEN: u32 = 1 << 4; // включить FIFO
const LCRH_WLEN_8: u32 = 0b11 << 5; // 8 бит данных

const CR_UARTEN: u32 = 1 << 0;
const CR_TXE: u32 = 1 << 8;
const CR_RXE: u32 = 1 << 9;

/// Делители для 115200 бод при UARTCLK 24 МГц (частота QEMU virt):
/// 24_000_000 / (16 * 115200) = 13.0208 → целая часть 13, дробная 0.0208*64 ≈ 1.
/// QEMU скорость игнорирует, но на настоящем PL011 без этого вывод будет мусором.
const IBRD_115200: u32 = 13;
const FBRD_115200: u32 = 1;

/// Ограничение на опрос флага TXFF — см. те же соображения, что и на x86_64:
/// повиснуть в единственном канале диагностики хуже, чем потерять байт.
const TX_SPIN_LIMIT: u32 = 100_000;

/// Есть ли на этой платформе доступ к PCI через порты ввода-вывода.
///
/// Нет, и не может быть: пространства ввода-вывода у AArch64 не существует как
/// понятия. Конфигурационное пространство здесь бывает только окном в памяти, и
/// машина без MCFG — это машина без PCI вовсе.
pub const HAS_PCI_PORTS: bool = false;

/// Заглушка ради общего интерфейса: на этой архитектуре её никто не вызывает,
/// потому что доступ через порты недоступен ([`HAS_PCI_PORTS`]).
///
/// Возвращает то же, что вернула бы шина, на которой никого нет, — так ошибка
/// в вызывающем коде выглядит как «устройств не найдено», а не как случайные
/// данные.
///
/// # Safety
///
/// Требований нет: функция ничего не делает.
#[allow(dead_code)] // общий интерфейс с x86-64; вызывается только там
pub unsafe fn pci_config_read32(_address: u32) -> u32 {
    u32::MAX
}

/// См. [`pci_config_read32`].
///
/// # Safety
///
/// Требований нет: функция ничего не делает.
#[allow(dead_code)] // общий интерфейс с x86-64
pub unsafe fn pci_config_write32(_address: u32, _value: u32) {}

/// Какой именно порт лежит по адресу.
///
/// Двух хватает на всё, что встречается на ARM. Различаются они не только
/// раскладкой регистров, но и **смыслом** флага готовности: у PL011 бит 5
/// регистра флагов означает «передатчик полон», у 16550 бит 5 регистра
/// состояния — «передатчик пуст». Перепутать их значит либо писать в занятый
/// порт и терять байты, либо ждать вечно.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Kind {
    Pl011,
    /// 16550 и его родня, включая `mediatek,mt6577-uart`. Регистры там разнесены
    /// по четыре байта, поэтому смещение состояния — 0x14, а не 5.
    Ns16550,
}

/// UART, отображённый в память.
#[derive(Clone, Copy)]
pub struct Serial {
    base: usize,
    kind: Kind,
}

impl Serial {
    /// UART, с которого ядро начинает говорить на этой платформе.
    pub const PLATFORM: Self = Self { base: QEMU_VIRT_PL011, kind: Kind::Pl011 };

    /// UART по адресу, который назвала прошивка.
    ///
    /// # Safety
    ///
    /// `base` обязан быть адресом настоящего PL011 в уже отображённом окне с
    /// Device-семантикой.
    #[must_use]
    pub const unsafe fn at(base: usize) -> Self {
        Self { base, kind: Kind::Pl011 }
    }

    /// UART семейства 16550 по адресу из дерева устройств.
    ///
    /// # Safety
    ///
    /// Те же требования, что у [`Serial::at`].
    #[must_use]
    pub const unsafe fn ns16550(base: usize) -> Self {
        Self { base, kind: Kind::Ns16550 }
    }

    /// Адрес окна регистров. Нужен построению таблиц: окно линии обязано быть
    /// отображено **до** переключения на них, иначе первая же строка после
    /// переключения уходит в отказ — а сообщить о нём некуда, потому что
    /// сообщать пришлось бы в ту же линию.
    #[must_use]
    pub const fn base(&self) -> usize {
        self.base
    }

    /// # Safety
    ///
    /// `self.base + offset` обязан указывать на существующий регистр PL011 в
    /// доступном (identity-mapped либо ещё не включённом MMU) адресном
    /// пространстве.
    unsafe fn read(&self, offset: usize) -> u32 {
        // SAFETY: `read_volatile` обязателен для MMIO — компилятору нельзя
        // разрешать кэшировать или выбрасывать чтение регистра состояния,
        // значение которого меняет устройство, а не программа. Адрес выровнен
        // на 4 байта, так как все смещения регистров кратны 4.
        unsafe { ptr::read_volatile((self.base + offset) as *const u32) }
    }

    /// # Safety
    ///
    /// См. [`Serial::read`]. Кроме того, запись в регистр PL011 меняет
    /// состояние устройства, и вызывающий отвечает за корректность значения.
    unsafe fn write(&self, offset: usize, value: u32) {
        // SAFETY: `write_volatile` не даёт компилятору объединить или удалить
        // записи в регистры — для устройства важен и сам факт записи, и порядок.
        unsafe { ptr::write_volatile((self.base + offset) as *mut u32, value) }
    }
}

impl SerialDevice for Serial {
    fn init(&mut self) {
        // 16550 настраивать нечем: скорость задаётся делителем, а делитель
        // считается от тактовой частоты порта, которой в дереве может не быть
        // вовсе. Загрузчик эту линию уже настроил и печатал в неё сам —
        // перенастраивать её наугад значит сломать работающее.
        if self.kind == Kind::Ns16550 {
            return;
        }
        // SAFETY: `self.base` — задокументированный адрес PL011 на QEMU virt.
        // К моменту вызова `ExitBootServices` уже сделан, MMU либо выключен,
        // либо оставлен прошивкой с identity-отображением устройств, поэтому
        // физический адрес доступен напрямую. Порядок операций — из даташита:
        // выключить UART, сбросить все флаги прерываний, задать скорость и
        // формат, замаскировать прерывания, включить обратно.
        unsafe {
            self.write(REG_CR, 0);
            self.write(REG_ICR, INT_ALL);
            self.write(REG_IBRD, IBRD_115200);
            self.write(REG_FBRD, FBRD_115200);
            self.write(REG_LCRH, LCRH_FEN | LCRH_WLEN_8);
            self.write(REG_IMSC, 0);
            self.write(REG_CR, CR_UARTEN | CR_TXE | CR_RXE);
        }
    }

    fn write_byte(&mut self, byte: u8) {
        let mut spins = 0u32;
        loop {
            // SAFETY: чтение регистра состояния не имеет побочных эффектов.
            let ready = unsafe {
                match self.kind {
                    Kind::Pl011 => self.read(REG_FR) & FR_TXFF == 0,
                    Kind::Ns16550 => self.read(NS16550_LSR) & NS16550_THRE != 0,
                }
            };
            if ready {
                break;
            }
            spins += 1;
            if spins >= TX_SPIN_LIMIT {
                return; // UART отсутствует или не разгребает FIFO
            }
        }
        // SAFETY: передатчик свободен (проверено выше), запись в регистр данных
        // ставит байт в очередь и не затрагивает ничего другого. У обоих портов
        // этот регистр лежит по нулевому смещению.
        unsafe { self.write(REG_DR, u32::from(byte)) };
    }
}

/// 16550: регистр состояния линии. Регистры разнесены по четыре байта, поэтому
/// пятый — это смещение 0x14.
const NS16550_LSR: usize = 0x14;
/// Бит 5 того же регистра: регистр передачи пуст, байт можно класть.
const NS16550_THRE: u32 = 1 << 5;

/// Порт, известный без взятия лока.
///
/// Существует ради одного места — печати из обработчика отказа, вклинившейся в
/// уже начатый вывод (см. [`crate::serial::_print`]). Там лок брать нельзя, а
/// печатать надо, и до появления второго вида UART ответом была константа
/// `Serial::PLATFORM`. На телефоне эта константа — адрес, по которому нет
/// ничего: сообщение об отказе стало бы вторым отказом.
static FALLBACK_BASE: core::sync::atomic::AtomicUsize =
    core::sync::atomic::AtomicUsize::new(QEMU_VIRT_PL011);
/// Вид порта из [`FALLBACK_BASE`]: `true` — PL011.
static FALLBACK_PL011: core::sync::atomic::AtomicBool =
    core::sync::atomic::AtomicBool::new(true);

/// Запомнить порт, в который ядро говорит сейчас.
pub fn remember_serial(device: &Serial) {
    FALLBACK_BASE.store(device.base, core::sync::atomic::Ordering::Release);
    FALLBACK_PL011.store(device.kind == Kind::Pl011, core::sync::atomic::Ordering::Release);
}

/// Тот же порт, но без лока. См. [`FALLBACK_BASE`].
#[must_use]
pub fn serial_fallback() -> Serial {
    let base = FALLBACK_BASE.load(core::sync::atomic::Ordering::Acquire);
    let kind = if FALLBACK_PL011.load(core::sync::atomic::Ordering::Acquire) {
        Kind::Pl011
    } else {
        Kind::Ns16550
    };
    Serial { base, kind }
}

/// Адрес окна регистров линии — для построения таблиц страниц.
#[must_use]
pub fn serial_base() -> usize {
    FALLBACK_BASE.load(core::sync::atomic::Ordering::Acquire)
}

/// Разрешить прерывания приёма на PL011.
///
/// Работа с портом идёт напрямую, минуя [`crate::serial`], по той же причине,
/// что и на x86-64: тот держит UART под локом ради целостности вывода, а приём —
/// независимый путь, и брать в обработчике прерывания лок, который может быть
/// занят, нельзя. Копия `Serial::PLATFORM` на стеке безопасна — тип не хранит
/// ничего, кроме адреса окна регистров.
///
/// # Safety
///
/// Окно PL011 должно быть отображено как Device-память (это делает
/// [`paging::build_kernel_address_space`]), а INTID [`input::UART_INTID`] —
/// разрешён в GIC уже после того, как обработчик готов его принять.
pub unsafe fn enable_uart_rx() {
    let uart = serial_fallback();
    // 16550 сюда не заводится: его прерывание разрешается другими регистрами, а
    // вслепую записанный PL011-регистр по адресу 16550 — это настройка чужого
    // устройства. На телефоне линия наружу и не выведена, так что терять нечего.
    if uart.kind != Kind::Pl011 {
        return;
    }
    // SAFETY: адрес — задокументированное окно PL011 на QEMU virt; условия
    // делегированы вызывающему контрактом функции. Сначала снимаются все
    // висящие флаги: прошивка могла оставить свои, и первый же размаскированный
    // источник выдал бы прерывание без причины.
    unsafe {
        uart.write(REG_ICR, INT_ALL);
        uart.write(REG_IMSC, INT_RX | INT_RX_TIMEOUT);
    }
}

/// Забрать из приёмника PL011 всё, что там есть, и отдать подсистеме ввода.
pub fn drain_uart_rx() {
    let uart = serial_fallback();
    if uart.kind != Kind::Pl011 {
        return;
    }
    for _ in 0..32 {
        // SAFETY: чтение регистра флагов побочных эффектов не имеет.
        if unsafe { uart.read(REG_FR) } & FR_RXFE != 0 {
            break;
        }
        // SAFETY: FIFO не пусто; чтение `DR` извлекает байт — побочный эффект
        // ожидаемый и необходимый. Старшие биты слова несут признаки ошибок
        // кадрирования и чётности; данные — только младшие восемь.
        let word = unsafe { uart.read(REG_DR) };
        // Бит 11 того же слова — переполнение приёмника: байт пришёл в полное
        // FIFO и потерян. Считаем по той же причине, что и на x86-64: молча
        // потерянный байт ввода выглядит как «система не приняла команду».
        if word & DR_OVERRUN != 0 {
            crate::input::ascii::note_overrun();
        }
        let byte = word as u8;
        crate::input::ascii::feed(byte);
    }
    // Флаги снимаются после вычитывания. `RXRIS` опускается и сам, когда FIFO
    // опустошено, но `RTRIS` (тайм-аут) — только записью в `ICR`, и без неё
    // прерывание пришло бы снова немедленно.
    // SAFETY: см. выше.
    unsafe { uart.write(REG_ICR, INT_RX | INT_RX_TIMEOUT) };
}

/// Остановить процессор до ближайшего прерывания.
///
/// В отличие от [`halt`], маска `DAIF` не трогается: смысл вызова ровно в том,
/// чтобы дождаться прерывания. `wfi` разбудит процессор и при замаскированном
/// IRQ (маска влияет на доставку, а не на пробуждение), но продолжать
/// исполнение он будет с того же места — поэтому вызывать всё равно следует с
/// разрешёнными прерываниями, иначе разбудившее событие останется
/// необработанным.
///
/// Единственный вызывающий — холостая задача планировщика, которой нечего
/// исполнять до ближайшего события.
pub fn wait_for_interrupt() {
    // SAFETY: `wfi` не трогает ни память, ни стек: это подсказка процессору
    // остановить конвейер до внешнего события.
    unsafe { asm!("wfi", options(nomem, nostack, preserves_flags)) };
}

/// Остановить процессор навсегда.
///
/// `wfi` (wait for interrupt) снимает ядро с конвейера до внешнего события —
/// как и `hlt` на x86_64, это нулевое энергопотребление вместо `loop {}`,
/// который жёг бы 100% CPU. `daifset` предварительно маскирует Debug, SError,
/// IRQ и FIQ: векторов исключений ядро ещё не установило, и пришедшее
/// прерывание ушло бы в мусорный обработчик.
pub fn halt() -> ! {
    // SAFETY: из функции нет возврата, поэтому маскирование прерываний уже
    // ни на какой последующий код повлиять не может.
    unsafe { asm!("msr daifset, #0b1111", options(nomem, nostack, preserves_flags)) };
    loop {
        // SAFETY: `wfi` при замаскированных прерываниях просто останавливает
        // ядро; память и стек не затрагиваются.
        unsafe { asm!("wfi", options(nomem, nostack, preserves_flags)) };
    }
}

