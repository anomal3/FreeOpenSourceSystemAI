//! Мастер шины SPI у MediaTek — то, на чём висит тачскрин этого аппарата.
//!
//! # Почему сюда пришлось идти
//!
//! Потому что на I²C тачскрина нет, и это измерено, а не предположено: семь шин,
//! обе раскладки регистров, все адреса. Три шины отвечают, четыре молчат, и
//! молчат не из-за тактирования — регистры заглушки читаются нулём и до снятия,
//! и после. На единственной честной шине ровно одно устройство, и оно не
//! тачскрин.
//!
//! Зато в дереве шесть контроллеров `mediatek,mt6765-spi`, а панель `dandelion`
//! объявлена как `novatek,NVT-ts-spi`. Отсюда и этот модуль.
//!
//! # Что сделано и чего нет
//!
//! Передача через FIFO контроллера — тридцать два байта в обе стороны за раз.
//! Больше и не нужно: и опознание чипа, и чтение точек касания укладываются в
//! этот предел. DMA не настраивается вовсе; он нужен для длинных посылок,
//! которых у нас не будет.
//!
//! # Про две раскладки тактирования, снова
//!
//! У MediaTek их две, и какая на MT6765 — из аппарата не вычитать. В старой
//! длительности полупериода лежат в `CFG0`, а `CFG2` не используется; в новой
//! («enhance timing») наоборот: в `CFG2` полупериоды, а в `CFG0` — времена
//! выборки и удержания выбора кристалла. Ошибиться значит получить либо
//! неверную частоту, либо не тот сигнал выбора — и в обоих случаях молчание.
//!
//! Поэтому пробуются обе и печатается то, что ответила каждая. Ровно так же
//! был решён вопрос с I²C, и там это сэкономило несколько заходов к аппарату.

use core::ptr;

/// Смещения регистров. У SPI они одни для всего семейства — расходятся не
/// адреса, а смысл двух из них (см. [`Timing`]).
const CFG0: usize = 0x00;
const CFG1: usize = 0x04;
const TX_DATA: usize = 0x10;
const RX_DATA: usize = 0x14;
const CMD: usize = 0x18;
const STATUS0: usize = 0x1c;
const PAD_SEL: usize = 0x24;
const CFG2: usize = 0x28;

/// `CMD`, бит 0: начать передачу.
const CMD_ACT: u32 = 1 << 0;
/// Бит 2: сбросить конечный автомат.
const CMD_RST: u32 = 1 << 2;
/// Биты 12 и 13: старший бит первым — так работает подавляющее большинство
/// устройств, и Novatek в их числе.
const CMD_TXMSBF: u32 = 1 << 12;
const CMD_RXMSBF: u32 = 1 << 13;
/// Биты 8 и 9: фаза и полярность такта. Ноль в обоих — «режим 0», с которого
/// начинает всякое устройство; Novatek работает именно в нём, но проверить
/// дешевле, чем поверить.
const CMD_CPHA: u32 = 1 << 8;
const CMD_CPOL: u32 = 1 << 9;

/// Биты 14 и 15: **переставить** байты внутри каждого слова.
///
/// Взведённые, они переворачивают порядок байт в четвёрке — это нужно машине с
/// обратным порядком байт, а у нас порядок прямой. Здесь они обязаны быть
/// сняты, и это ровно та ошибка, которая стоила захода к аппарату: биты стояли,
/// команды уходили к чипу перевёрнутыми четвёрками, он получал мусор и молчал —
/// совершенно законно. Снаружи это выглядело как «устройство не отвечает», и
/// искали его питание, его сброс и его выводы.
///
/// Имена оставлены для того, чтобы было видно, чего мы **не** делаем.
#[allow(dead_code)]
const CMD_RX_ENDIAN: u32 = 1 << 14;
#[allow(dead_code)]
const CMD_TX_ENDIAN: u32 = 1 << 15;

/// `STATUS0`, бит 0: передача закончилась.
const STATUS0_DONE: u32 = 1 << 0;

/// Сколько байт помещается в FIFO в каждую сторону.
pub const FIFO: usize = 32;

/// Сколько раз опросить состояние, прежде чем счесть передачу зависшей.
const POLL_LIMIT: u32 = 200_000;

/// Половина периода такта в единицах, которые считает контроллер.
///
/// Число заведомо большое: получается медленно, и это именно то, что нужно.
/// Частота источника нам неизвестна, а опознание чипа не требует скорости —
/// зато медленный такт прощает и длинные провода, и неточные времена.
const SCK_HALF: u32 = 0x80;

/// Времена выбора кристалла — тем же порядком и по той же причине.
const CS_TIME: u32 = 0x40;

/// Какая из двух раскладок тактирования.
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Timing {
    /// Старая: полупериоды в `CFG0`.
    Classic,
    /// Новая: полупериоды в `CFG2`, времена выбора кристалла в `CFG0`.
    Enhanced,
}

impl Timing {
    pub fn name(self) -> &'static str {
        match self {
            Self::Classic => "classic",
            Self::Enhanced => "enhanced",
        }
    }
}

/// Один контроллер SPI.
#[derive(Clone, Copy)]
pub struct Bus {
    base: usize,
}

impl Bus {
    /// # Safety
    ///
    /// `base` обязан быть адресом окна регистров контроллера SPI, отображённым
    /// как память устройства.
    #[must_use]
    pub const unsafe fn new(base: usize) -> Self {
        Self { base }
    }

    /// Привести контроллер в состояние, пригодное для передачи.
    ///
    /// Сброс здесь делается, в отличие от I²C: у SPI нет тактирования,
    /// выставленного загрузчиком и неизвестного нам, — вся настройка наша, и
    /// оставлять чужое состояние не в чем.
    ///
    /// # Safety
    ///
    /// Окно регистров отображено, параллельного доступа нет.
    pub unsafe fn prepare(&self, timing: Timing, mode: u8, pad: u32, half: u32) {
        // SAFETY: контракт функции.
        unsafe {
            self.write(CMD, CMD_RST);
            self.write(CMD, 0);
            self.write(PAD_SEL, pad);

            let halves = ((half - 1) << 16) | (half - 1);
            let holds = ((CS_TIME - 1) << 16) | (CS_TIME - 1);
            match timing {
                Timing::Classic => {
                    self.write(CFG0, halves);
                    self.write(CFG2, 0);
                }
                Timing::Enhanced => {
                    self.write(CFG2, halves);
                    self.write(CFG0, holds);
                }
            }

            // Режим передачи: старший бит первым, байты не переставлять, DMA не
            // трогать, прерывания не разрешать — состояние опрашивается.
            let phase = if mode & 1 != 0 { CMD_CPHA } else { 0 };
            let polarity = if mode & 2 != 0 { CMD_CPOL } else { 0 };
            self.write(CMD, CMD_TXMSBF | CMD_RXMSBF | phase | polarity);
        }
    }

    /// Полнодуплексная посылка: столько же байт уходит, сколько приходит.
    ///
    /// У SPI иначе не бывает — за каждый такт бит уходит и бит приходит, — и
    /// это не формальность договора: чтобы **прочитать** у устройства что-то,
    /// надо отправить ему столько же байт, сколько хочешь получить. Отсюда и
    /// холостые байты в запросах.
    ///
    /// # Safety
    ///
    /// См. [`Bus::prepare`], которая должна быть вызвана раньше.
    /// Возвращает число опросов, которое заняло ожидание, — или `None`, если
    /// передача так и не завершилась.
    ///
    /// # Зачем считать опросы
    ///
    /// Это единственный доступный способ узнать, **шли ли биты по проводам**.
    /// Признак завершения взводится и тогда, когда такт стоит: автомат
    /// отрабатывает по шинной частоте и рапортует за пустоту. Отличить это от
    /// настоящей передачи можно только по времени — восемь байт на медленном
    /// такте обязаны занять заметное число опросов, а мгновенное завершение
    /// означает, что тактовый сигнал не бежал.
    pub unsafe fn transfer(&self, tx: &[u8], rx: &mut [u8]) -> Option<u32> {
        let len = tx.len().max(rx.len());
        if len == 0 || len > FIFO {
            return None;
        }

        // SAFETY: контракт функции; все смещения принадлежат окну регистров.
        unsafe {
            // Длина посылки в байтах, минус один: контроллер считает от нуля, и
            // «единица» здесь означала бы два байта.
            let mut cfg1 = self.read(CFG1);
            cfg1 &= !(0x3ff << 16 | 0xff << 8);
            cfg1 |= ((len as u32 - 1) & 0x3ff) << 16;
            self.write(CFG1, cfg1);

            // FIFO заполняется словами; хвост короче слова досылается нулями.
            let mut offset = 0;
            while offset < len {
                let mut word = 0u32;
                for slot in 0..4 {
                    let index = offset + slot;
                    let byte = if index < tx.len() { tx[index] } else { 0 };
                    word |= u32::from(byte) << (slot * 8);
                }
                self.write(TX_DATA, word);
                offset += 4;
            }

            self.write(STATUS0, STATUS0_DONE);
            let command = self.read(CMD);
            self.write(CMD, command | CMD_ACT);

            let mut spins = 0u32;
            while self.read(STATUS0) & STATUS0_DONE == 0 {
                spins += 1;
                if spins >= POLL_LIMIT {
                    self.write(CMD, CMD_RST);
                    return None;
                }
                core::hint::spin_loop();
            }

            let mut offset = 0;
            while offset < rx.len() {
                let word = self.read(RX_DATA);
                for slot in 0..4 {
                    let index = offset + slot;
                    if index < rx.len() {
                        rx[index] = (word >> (slot * 8)) as u8;
                    }
                }
                offset += 4;
            }
            Some(spins)
        }
    }

    /// # Safety
    ///
    /// `offset` обязан принадлежать окну регистров этого контроллера.
    unsafe fn read(&self, offset: usize) -> u32 {
        // SAFETY: контракт; volatile обязателен — значение меняет устройство.
        unsafe { ptr::read_volatile((self.base + offset) as *const u32) }
    }

    /// # Safety
    ///
    /// См. [`Bus::read`]; кроме того, запись меняет состояние контроллера.
    unsafe fn write(&self, offset: usize, value: u32) {
        // SAFETY: контракт; volatile обязателен.
        unsafe { ptr::write_volatile((self.base + offset) as *mut u32, value) };
    }
}
