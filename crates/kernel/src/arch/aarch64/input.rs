//! Ввод на AArch64: приём по PL011 как единственный источник событий.
//!
//! # Почему здесь нет клавиатуры
//!
//! Потому что клавиатуры, специфичной для архитектуры, на ней не существует. У
//! QEMU `-machine virt` нет ни i8042, ни любого другого legacy-контроллера
//! ввода: машина спроектирована как чистая ARM-платформа, где всё, кроме UART и
//! GIC, подключается по PCI или virtio. То же верно и для Raspberry Pi 4 —
//! целевой платы этой ветки: клавиатура там подключена к контроллеру xHCI VL805.
//!
//! Настоящая клавиатура сюда приходит через [`crate::usb::xhci`], и он один и
//! тот же на обеих архитектурах — драйверу USB неоткуда узнать, на какой он
//! работает. Здесь остаётся только приём по серийному порту: путь настоящий, с
//! прерыванием от железа, и единственный, который работает без PCI вовсе.
//!
//! # Что здесь есть
//!
//! Ровно одно: разрешить UART прерывать процессор и разрешить его INTID в GIC.
//! Разбор байтов в события делает [`crate::input::ascii`] — общий для обеих
//! архитектур.

use boot_info::BootInfo;

use super::gic;
use crate::input::Sources;
use crate::kprintln;

/// INTID прерывания PL011 на QEMU virt.
///
/// В device tree машины это `GIC_SPI 1`, а SPI нумеруются с 32-го INTID —
/// отсюда 33. Ровно та же арифметика и та же ловушка, что у таймера (см.
/// [`super::timer::TIMER_INTID`]): «SPI 1» и «INTID 33» — одно число в разных
/// системах отсчёта.
///
/// TODO(HAL): брать из FDT (`BootInfo::device_tree`, узел `pl011@9000000`,
/// свойство `interrupts`), а не из константы. Пока разбора device tree нет, это
/// допущение про одну конкретную машину — как и сам адрес UART.
pub const UART_INTID: u32 = 33;

/// Приоритет прерывания UART.
///
/// Численно больше приоритета таймера (`0x80`), то есть **ниже** его: на GIC
/// меньшее число означает более высокий приоритет. Так и задумано — тик
/// планировщика важнее нажатия клавиши, а обратный порядок дал бы потерю тиков
/// при быстрой печати.
const UART_PRIORITY: u8 = 0xA0;

/// Поднять ввод.
///
/// Хэндофф здесь не нужен — в отличие от x86-64, где из него берётся адрес RSDP
/// для поиска I/O APIC. Аргумент присутствует ради единой подписи: ядро вызывает
/// `arch::input::init(&info)` и не должно знать, кому из архитектур он полезен.
pub fn init(_info: &BootInfo) -> Sources {
    // Тачскрин ищется первым и **независимо** от линии: на телефоне порт не
    // выведен наружу вовсе, и все ветки ниже кончаются ранним возвратом. Найти
    // указатель после них значило бы не найти его никогда — ровно на той
    // машине, ради которой он и написан.
    let mut sources = Sources { keyboard: false, serial: false, mouse: touchscreen() };

    // Обе версии годятся: разница между ними — в том, как разрешается прерывание
    // (у v3 приватные живут в redistributor'е), и это уже спрятано внутри
    // `gic::enable_interrupt`. Отказывать здесь по версии значило бы оставить
    // машину с GICv3 без ввода при полностью рабочем контроллере.
    // Порта на этой машине нет вовсе — по его предполагаемому адресу
    // оперативная память (см. [`crate::serial::silence`]). Разрешать приём
    // означало бы настраивать несуществующее устройство записями в чужую память
    // и разрешать в контроллере линию, которая принадлежит другому устройству:
    // на VirtualBox `INTID 33` — это GPIO, а не порт.
    if crate::serial::absent() {
        kprintln!("  serial in   : no serial port on this machine");
        crate::input::set_sources(sources);
        return sources;
    }

    // Номер прерывания ниже — константа, снятая с одной машины, и верна она
    // ровно там, где порт PL011. На телефоне порт другой (16550 от MediaTek), а
    // `INTID 33` там принадлежит какому-то из его устройств: разрешить его
    // значило бы получать чужие прерывания и считать их нажатиями клавиш.
    // Линия наружу у аппарата всё равно не выведена, так что терять нечего.
    if !super::serial_is_pl011() {
        kprintln!("  serial in   : this port is not PL011; its interrupt number is unknown");
        crate::input::set_sources(sources);
        return sources;
    }

    if !matches!(gic::version(), Some(gic::Version::V2 | gic::Version::V3)) {
        kprintln!("  input       : no usable GIC, the UART interrupt cannot be enabled");
        crate::input::set_sources(sources);
        return sources;
    }

    // Порядок обязателен: сначала UART получает право прерывать, потом GIC
    // получает право доставлять. Обратный порядок безвреден, но при нём между
    // двумя шагами существует состояние «разрешено доставлять то, чего никто не
    // выставляет», а такое состояние нечем отличить от неработающей настройки.
    // SAFETY: окно PL011 отображено как Device-память при построении адресного
    // пространства, а обработчик прерывания установлен `interrupts::init`,
    // который вызывается раньше.
    unsafe { super::enable_uart_rx() };

    // SAFETY: версия контроллера проверена выше, окна GIC отображены.
    unsafe { gic::enable_interrupt(UART_INTID, UART_PRIORITY) };

    kprintln!("  serial in   : PL011 receive on INTID {UART_INTID}");
    kprintln!("  keyboard    : no PS/2 on this machine; the keyboard arrives over USB");
    // Сказано вслух намеренно. На x86-64 кнопка питания — фиксированное событие
    // ACPI, то есть пара битов в регистре чипсета. На этой машине её приносит
    // ACPI GED, а GED описан в AML — байт-коде, интерпретатора которого у нас
    // нет и в этой фазе не будет. Выключение по команде здесь работает, по
    // кнопке — нет, и «работает везде» было бы неправдой.
    kprintln!("  power       : no power button here; it arrives through ACPI GED, described in AML");

    sources.serial = true;
    crate::input::set_sources(sources);
    sources
}

/// Найти тачскрин, если машина описана деревом устройств.
///
/// На UEFI-машине дерева нет, и искать нечего: шины I²C там не описаны никем, а
/// перебирать адреса наугад — это писать в чужие регистры.
fn touchscreen() -> bool {
    // SAFETY: дерево ещё не переиспользовано — ядро забирает его память только
    // после того, как прочитает отсюда всё нужное, а ввод поднимается раньше.
    let Some(fdt) = (unsafe { super::device_tree() }) else {
        return false;
    };

    // USB поднимается здесь же, рядом с остальным вводом, и по той же причине:
    // это будущий канал, по которому машина заговорит. Пока от него нужен один
    // ответ — замечает ли компьютер, что к нему что-то подключили.
    //
    // SAFETY: таблицы ядра активны, окна отображаются внутри.
    match unsafe { super::mtk_usb::start(&fdt) } {
        Some(report) => {
            // Пара «до» и «после» — единственное доказательство, что записи
            // дошли до железа. Прошлая редакция драйвера печатала здесь два
            // нуля и была прочитана как «блок обесточен»; на деле окно было
            // чужим. Числа остаются в отчёте именно поэтому.
            kprintln!(
                "  usb phy     : window {:#010x}, mode {:#010x} -> {:#010x}, force {:#010x} -> {:#010x}",
                report.phy_window,
                report.before.0,
                report.after.0,
                report.before.1,
                report.after.1
            );
            kprintln!(
                "  usb         : power {:#04x}, devctl {:#04x}, endpoints {:#04x}, config {:#04x}",
                report.power,
                report.devctl,
                report.endpoints,
                report.configdata
            );
            // Вывод делается здесь, а не человеком по четырём числам. Прошлый
            // раз ровно эти нули были прочитаны как «блок обесточен», и заход
            // ушёл в дерево тактов, тогда как ошибка была в адресе. Пусть
            // машина называет обе возможности сама.
            if report.after == (0, 0) {
                kprintln!(
                    "  usb         : the phy window reads zero even after writing -- wrong window or no clock"
                );
            } else {
                kprintln!(
                    "  usb         : pretending to be a fastboot device; try `fastboot devices`"
                );
            }
        }
        None => kprintln!("  usb         : no usb controller in the device tree"),
    }
    // SAFETY: таблицы ядра активны, окна шин драйвер отображает сам.
    let found = unsafe { super::mtk_touch::probe(&fdt) };
    if !found {
        kprintln!("  touch       : no touchscreen answered on any i2c bus");
    }
    found
}
