//! Переключение контекста задач на x86-64.
//!
//! # Что такое «контекст» и почему он такой маленький
//!
//! [`switch_context`] — обычная функция, которую задача вызывает сама (планово,
//! из планировщика) либо за неё вызывает обработчик прерывания (вытеснение).
//! В обоих случаях действует System V AMD64 ABI, и он уже делит регистры на
//! две половины:
//!
//! * `rax`, `rcx`, `rdx`, `rsi`, `rdi`, `r8`–`r11` — caller-saved. Компилятор
//!   вокруг любого `call` сохраняет те из них, значения которых ему ещё нужны.
//!   Сохранять их здесь второй раз означает копировать 64 байта на каждом
//!   переключении просто так;
//! * `rbx`, `rbp`, `r12`–`r15` — callee-saved. Вызывающий вправе считать, что
//!   после возврата они не изменились, а раз «возврат» произойдёт уже в другой
//!   задаче — восстановить их обязаны мы.
//!
//! Плюс `rsp`, который здесь и есть суть переключения: указатель стека
//! однозначно задаёт, куда вернётся `ret` и где лежат кадры всех вызовов
//! задачи. Всё остальное состояние задачи живёт на её собственном стеке.
//!
//! Тот же разбор объясняет, почему структура не расширится при появлении
//! вытеснения. Вытесняющее переключение приходит из обработчика таймера,
//! который на входе уже сложил **все** регистры общего назначения в свой
//! [`super::interrupts::TrapFrame`]; ему остаётся вызвать эту же функцию как
//! обычную. Полное состояние прерванного кода при этом хранится в кадре на
//! стеке задачи, а `Context` хранит указатель на этот стек — второй копии не
//! нужно.
//!
//! # Почему не сохраняются флаги
//!
//! `RFLAGS` делится на три части, и ни одна не требует сохранения:
//!
//! * арифметические флаги (`ZF`, `CF`, …) — scratch-состояние, живущее между
//!   сравнением и переходом; через `call` его никто не проносит;
//! * `DF` обязан быть нулём на границе любого вызова по требованию ABI, и
//!   переключение всегда происходит именно на такой границе (пролог
//!   `isr_common` для этого делает `cld`);
//! * `IF` — состояние процессора, а не задачи. Им управляет критическая секция
//!   вокруг переключения ([`crate::sync::SpinLock`] запрещает прерывания до
//!   захвата и возвращает как было при освобождении), причём охранник, который
//!   их вернёт, лежит на стеке возобновляемой задачи — то есть «своё» значение
//!   `IF` каждая задача и так получает обратно вместе со своим стеком.
//!
//! Ассемблер ниже состоит из `mov` и `ret`, которые флагов не трогают, поэтому
//! сохранять нечего и с этой стороны.
//!
//! Одно следствие стоит знать вызывающему: задача, которую запускают в первый
//! раз, начинает исполнение с тем `IF`, который был в момент переключения. Если
//! планировщик переключается, удерживая лок, точка входа получит управление с
//! запрещёнными прерываниями — разрешить их обязан он сам.
//!
//! # Почему это ассемблер, а не Rust с `asm!`
//!
//! Смена `RSP` посреди обычной функции ломает представление компилятора о её
//! кадре: он продолжает адресовать локальные переменные и сохранённые регистры
//! относительно `RSP`/`RBP`, которые теперь указывают на чужой стек. Никакой
//! `clobber` этого не выражает — `RSP` нельзя объявить изменяемым операндом
//! именно потому, что кадр от него зависит. Поэтому функция целиком написана
//! ассемблером (`#[unsafe(naked)]` + [`naked_asm!`]): у неё нет ни пролога, ни
//! эпилога, ни локальных переменных, и вопрос о кадре не возникает вовсе.
//!
//! Между `naked_asm!` и `global_asm!` выбран первый: символ объявляется как
//! обычная функция Rust, с типами аргументов и проверкой на стороне
//! вызывающего, а не как `extern "C"`-заглушка, чью сигнатуру никто не сверяет.
//! Смещения полей `Context` уезжают в ассемблер операндами `const` — так текст
//! ассемблера ссылается на настоящую раскладку структуры, а не на переписанные
//! от руки числа.

// Единственный вызывающий этого модуля — планировщик, и до его появления весь
// контракт выглядит для компилятора мёртвым кодом. Снять, когда `sched` начнёт
// звать `switch_context`.
#![allow(dead_code)]

use crate::mm::VirtAddr;
use core::arch::naked_asm;
use core::mem::{offset_of, size_of};

/// Адрес функции числом.
///
/// Промежуточный `*const ()` не украшательство: `fn as usize` напрямую запрещает
/// лит `function_casts_as_integer`, потому что в таком выражении легко не
/// заметить пропущенный вызов.
fn address_of(f: *const ()) -> u64 {
    f as usize as u64
}

/// Сохранённое состояние приостановленной задачи.
///
/// Поля читает и пишет только ассемблер [`switch_context`] — по смещениям,
/// вычисленным из этой же структуры (см. константы `OFF_*`).
///
/// [`Default`] даёт нулевой контекст, и годится он ровно для одного: быть
/// **приёмником** первого сохранения. Так описывается загрузочная задача — та,
/// что уже исполняется к моменту появления планировщика: своего [`Context::new`]
/// у неё нет и быть не может, потому что её кадр сложится сам при первом уходе с
/// процессора. Переключаться **на** нулевой контекст нельзя: это переход по
/// нулевому адресу с нулевым `RSP`.
#[repr(C)]
#[derive(Debug, Default)]
pub struct Context {
    /// Вершина стека задачи в момент приостановки. По этому адресу лежит адрес
    /// возврата, на который уйдёт `ret` в конце переключения.
    rsp: u64,
    rbx: u64,
    rbp: u64,
    /// У ещё не запускавшейся задачи — адрес точки входа (см. [`task_entry`]).
    r12: u64,
    /// У ещё не запускавшейся задачи — аргумент точки входа.
    r13: u64,
    r14: u64,
    r15: u64,
}

// Смещения, на которые опирается ассемблер. Считаются из структуры, поэтому
// перестановка полей их не рассинхронизирует; проверка ниже ловит другое —
// изменение раскладки, о котором ассемблер знать не обязан, но человек,
// читающий его текст с числами в комментариях, знать должен.
const OFF_RSP: usize = offset_of!(Context, rsp);
const OFF_RBX: usize = offset_of!(Context, rbx);
const OFF_RBP: usize = offset_of!(Context, rbp);
const OFF_R12: usize = offset_of!(Context, r12);
const OFF_R13: usize = offset_of!(Context, r13);
const OFF_R14: usize = offset_of!(Context, r14);
const OFF_R15: usize = offset_of!(Context, r15);

const _: () = assert!(OFF_RSP == 0);
const _: () = assert!(OFF_RBX == 8);
const _: () = assert!(OFF_RBP == 16);
const _: () = assert!(OFF_R12 == 24);
const _: () = assert!(OFF_R13 == 32);
const _: () = assert!(OFF_R14 == 40);
const _: () = assert!(OFF_R15 == 48);
const _: () = assert!(size_of::<Context>() == 56);

/// Сколько байт начального кадра занимает на стеке новой задачи.
///
/// Два слова: адрес [`task_entry`], который снимет `ret`, и под ним адрес
/// [`task_returned`] — фиктивный адрес возврата для самой точки входа.
const INITIAL_FRAME_SIZE: usize = 16;

impl Context {
    /// Начальный контекст задачи, которая ещё ни разу не исполнялась.
    ///
    /// # Как устроен начальный кадр
    ///
    /// Восстанавливающая половина [`switch_context`] умеет ровно одно: загрузить
    /// регистры и сделать `ret`. Значит, у новой задачи на стеке должно лежать
    /// то же самое, что оставила бы после себя приостановленная — адрес, по
    /// которому этот `ret` уйдёт:
    ///
    /// ```text
    ///   stack_top      +----------------+ <- RSP «вызывающего», кратен 16
    ///   stack_top - 8  | task_returned  |    ловушка на случай возврата из entry
    ///   stack_top - 16 | task_entry     | <- Context::rsp, отсюда стартует `ret`
    ///                  +----------------+
    /// ```
    ///
    /// `ret` снимает верхнее слово и передаёт управление [`task_entry`],
    /// оставляя `RSP = stack_top - 8`. Это в точности то состояние, в котором
    /// оказывается функция сразу после `call`: System V требует `RSP ≡ 0 (mod
    /// 16)` в точке вызова, а `call` кладёт восьмибайтный адрес возврата, то
    /// есть на входе в функцию `RSP ≡ 8 (mod 16)`. Отсюда и требование к
    /// `stack_top` быть кратным 16 — иначе первая же инструкция с `xmm` или
    /// любой вложенный вызов, который сам выравнивает стек, получит смещение на
    /// 8 байт и упадёт.
    ///
    /// Адрес самой точки входа и её аргумент передаются не через стек, а в
    /// `r12`/`r13`: это callee-saved регистры, то есть их всё равно
    /// восстанавливает переключение, и [`task_entry`] остаётся двумя
    /// инструкциями без единого обращения к памяти.
    ///
    /// `rbp` обнулён намеренно: цепочка кадров задачи начинается здесь, и
    /// раскрутка стека (отладчиком или печатью трассы) обязана на этом
    /// оборваться, а не уйти в мусор под вершиной стека.
    ///
    /// # Требования к вызывающему
    ///
    /// `stack_top` обязан быть вершиной отображённой на запись области размером
    /// хотя бы в страницу и быть кратным 16. Функция пишет по нему два слова
    /// начального кадра. Сигнатура безопасная — так требует контракт с
    /// планировщиком, — но проверить эти условия компилятору нечем: выравнивание
    /// ловится `assert!` ниже, отображение не ловится ничем, кроме #PF.
    #[must_use]
    pub fn new(stack_top: VirtAddr, entry: extern "C" fn(usize) -> !, arg: usize) -> Self {
        let top = stack_top.as_usize();
        assert!(
            top % 16 == 0,
            "task stack top must be 16-byte aligned for the System V ABI"
        );
        assert!(
            top >= INITIAL_FRAME_SIZE,
            "task stack top is too low for the initial frame"
        );

        let rsp = top - INITIAL_FRAME_SIZE;

        // SAFETY: вызывающий обещал отображённую на запись область, вершиной
        // которой является `stack_top` (см. «Требования к вызывающему»). Оба
        // слова лежат ниже вершины, то есть внутри этой области, и выровнены на
        // 8: `top` кратен 16. Стек ещё никем не используется — задача не
        // запускалась, — поэтому затирать этими записями нечего.
        unsafe {
            (rsp as *mut u64).write(address_of(task_entry as *const ()));
            ((top - 8) as *mut u64).write(address_of(task_returned as *const ()));
        }

        Self {
            rsp: rsp as u64,
            rbx: 0,
            rbp: 0,
            r12: address_of(entry as *const ()),
            r13: arg as u64,
            r14: 0,
            r15: 0,
        }
    }
}

/// Сохранить состояние текущей задачи в `from` и продолжить исполнение `to`.
///
/// Возврат из этого вызова произойдёт тогда, когда кто-нибудь переключится
/// обратно на текущую задачу, — возможно, спустя произвольное время и уже из
/// другого места ядра. Для вызывающего кода это неотличимо от обычного вызова:
/// callee-saved регистры и стек к моменту возврата те же, что были.
///
/// # Safety
///
/// * `from` и `to` — валидные указатели на [`Context`], не освобождаемые до
///   возврата управления;
/// * `to` описывает задачу, чей стек отображён на запись, а сохранённый в нём
///   кадр построен либо [`Context::new`], либо предыдущим вызовом этой функции.
///   Нулевой или чужой `Context` здесь — это переход по произвольному адресу с
///   произвольным `RSP`, диагностировать который будет уже нечем.
///
/// Аргументы могут совпадать: сохранение и восстановление одного и того же
/// контекста возвращает управление сразу после вызова.
///
/// Сама функция не запрещает прерывания и на них не полагается — но как только
/// таймер научится вытеснять, вызывать её нужно будет из критической секции.
/// Иначе вытеснение, случившееся между сохранением `from` и переходом на `to`,
/// увидит наполовину обновлённое состояние планировщика и переключит на задачу,
/// которая с точки зрения `from` ещё исполняется.
#[unsafe(naked)]
pub unsafe extern "C" fn switch_context(from: *mut Context, to: *const Context) {
    // System V: `from` в RDI, `to` в RSI. Порядок сохранения (по возрастанию
    // смещений) и восстановления (по убыванию) зеркальны, чтобы перекос было
    // видно глазом в дизассемблере.
    //
    // `RSP` восстанавливается последним: до этого момента исполнение идёт на
    // стеке уходящей задачи, и любое прерывание, случись оно здесь (а оно может
    // — функция не полагается на `cli`), положит свой кадр на заведомо живой
    // стек. После смены `RSP` не остаётся ни одной инструкции, кроме `ret`.
    naked_asm!(
        "mov [rdi + {off_rsp}], rsp",
        "mov [rdi + {off_rbx}], rbx",
        "mov [rdi + {off_rbp}], rbp",
        "mov [rdi + {off_r12}], r12",
        "mov [rdi + {off_r13}], r13",
        "mov [rdi + {off_r14}], r14",
        "mov [rdi + {off_r15}], r15",

        "mov r15, [rsi + {off_r15}]",
        "mov r14, [rsi + {off_r14}]",
        "mov r13, [rsi + {off_r13}]",
        "mov r12, [rsi + {off_r12}]",
        "mov rbp, [rsi + {off_rbp}]",
        "mov rbx, [rsi + {off_rbx}]",
        "mov rsp, [rsi + {off_rsp}]",
        // Адрес возврата берётся с нового стека: у приостановленной задачи это
        // точка после её собственного вызова `switch_context`, у новой —
        // `task_entry`, положенный туда `Context::new`.
        "ret",
        off_rsp = const OFF_RSP,
        off_rbx = const OFF_RBX,
        off_rbp = const OFF_RBP,
        off_r12 = const OFF_R12,
        off_r13 = const OFF_R13,
        off_r14 = const OFF_R14,
        off_r15 = const OFF_R15,
    )
}

/// Первая инструкция, которую исполняет новая задача.
///
/// Сюда приходит `ret` из [`switch_context`]. Точка входа и её аргумент к этому
/// моменту уже восстановлены в `r12`/`r13` — остаётся переложить аргумент в
/// `rdi`, куда его ждёт System V, и уйти в саму задачу. `jmp`, а не `call`:
/// адрес возврата на стеке уже лежит (его положил [`Context::new`]), и второй
/// сломал бы выравнивание.
#[unsafe(naked)]
unsafe extern "C" fn task_entry() -> ! {
    naked_asm!("mov rdi, r13", "jmp r12")
}

/// Ловушка на случай, если точка входа задачи всё-таки вернулась.
///
/// Тип `extern "C" fn(usize) -> !` такое запрещает, но запрет действует только
/// на стороне Rust: ошибка в ассемблерном коде задачи или испорченный стек
/// приведут ровно сюда — по адресу, который [`Context::new`] положил под
/// начальный кадр. Без этой ловушки `ret` из точки входа снял бы со стека
/// произвольное слово и передал бы на него управление.
#[unsafe(naked)]
unsafe extern "C" fn task_returned() -> ! {
    // Сюда попадают по `ret`, то есть с `RSP ≡ 0 (mod 16)`, тогда как функции
    // System V обещает `RSP ≡ 8 (mod 16)` на входе. Фиктивное слово возвращает
    // ожидаемое смещение, и дальше работает обычный Rust с обычным прологом.
    naked_asm!("push 0", "jmp {report}", report = sym task_returned_report)
}

/// Печать и остановка — вторая половина [`task_returned`], уже на Rust.
extern "C" fn task_returned_report() -> ! {
    panic!("x86_64: a task returned from its entry point; entry functions must never return");
}
