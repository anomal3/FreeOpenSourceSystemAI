//! Монотонный счётчик тактов процессора и его калибровка по таймеру ACPI.
//!
//! # Зачем понадобился второй источник времени
//!
//! Первый — тики таймерного прерывания — считает не время, а **доставленные
//! прерывания**. Пока прерывания запрещены, локальный APIC копит одно на
//! вектор, и всё, что пришло сверх, теряется навсегда. За загрузку так теряются
//! секунды: замер стенда против часов хоста показывал −23 с к появлению
//! приглашения в отладочной сборке и −3 с в выпускной — разница ровно в том,
//! сколько времени сборка проводит с запрещёнными прерываниями.
//!
//! `rdtsc` считает такты процессора и не зависит ни от прерываний, ни от того,
//! разрешены ли они. Часы, построенные на нём, не отстают, сколько бы тиков ни
//! потерял планировщик.
//!
//! # Почему частоту приходится измерять
//!
//! Потому что её негде спросить. `CPUID.15H` сообщает отношение TSC к
//! кристаллу, `CPUID.16H` — базовую частоту в мегагерцах, и оба на многих
//! машинах отсутствуют или отвечают нулями; под QEMU полагаться на них тем
//! более нельзя. Эталон нужен внешний, и он есть: таймер ACPI идёт с частотой
//! 3,579545 МГц, закреплённой спецификацией, и адрес его порта лежит в FADT.
//!
//! Отсюда весь метод: заметить `rdtsc` и показания таймера ACPI, покрутиться,
//! пока таймер не отсчитает известный интервал, заметить оба ещё раз. Отношение
//! разностей и есть частота. Прерывания при этом можно не запрещать — задержка
//! попадает в обе разности одинаково и из отношения уходит.
//!
//! # Что делает эта фаза и чего не делает
//!
//! Не делает: не проверяет `invariant TSC` через `CPUID.80000007H:EDX[8]`.
//! Проверка имела бы смысл там, где процессор меняет частоту или засыпает по
//! C-состояниям, — на машине, которая ничего этого пока не умеет, она
//! отсеивала бы годные конфигурации ради ситуации, в которую система не
//! попадает. Когда управление питанием появится, проверка появится вместе с
//! ним, и это отмечено здесь, чтобы не выяснять потом.

use core::sync::atomic::{AtomicU64, Ordering};

use crate::kprintln;

/// Частота таймера ACPI: 3,579545 МГц. Число не выбрано, а закреплено
/// спецификацией ACPI — это учетверённая частота цветовой поднесущей NTSC,
/// доставшаяся от кварца первых PC.
const PM_TIMER_HZ: u64 = 3_579_545;

/// Сколько времени тратится на калибровку. Пятьдесят миллисекунд — компромисс:
/// при них ошибка в один такт таймера ACPI даёт относительную погрешность около
/// шести миллионных, а на загрузку добавляется время, которого не видно.
const CALIBRATION_MS: u64 = 50;

/// Смещение поля `PM_TMR_BLK` в FADT: порт ввода-вывода таймера.
const FADT_PM_TMR_BLK: usize = 76;
/// Смещение поля `PM_TMR_LEN`. Значение, отличное от четырёх, означает, что
/// таймера нет: спецификация допускает только эту длину.
const FADT_PM_TMR_LEN: usize = 91;
/// Смещение поля `Flags`.
const FADT_FLAGS: usize = 112;
/// `Flags.TMR_VAL_EXT`: счётчик 32-разрядный, а не 24-разрядный.
const FLAG_TMR_VAL_EXT: u32 = 1 << 8;

/// Измеренная частота `rdtsc` в герцах. Ноль — калибровка не удалась, и время
/// придётся считать по тикам, как раньше.
static FREQUENCY_HZ: AtomicU64 = AtomicU64::new(0);

/// Текущее значение счётчика тактов.
#[must_use]
pub fn counter() -> u64 {
    let low: u32;
    let high: u32;
    // SAFETY: `rdtsc` не обращается к памяти и не меняет ничего, кроме `eax` и
    // `edx`. Инструкция есть на любом x86-64: она появилась в Pentium, задолго
    // до длинного режима.
    unsafe {
        core::arch::asm!(
            "rdtsc",
            out("eax") low,
            out("edx") high,
            options(nomem, nostack, preserves_flags)
        );
    }
    (u64::from(high) << 32) | u64::from(low)
}

/// Частота счётчика в герцах; ноль, если она неизвестна.
#[must_use]
pub fn frequency() -> u64 {
    FREQUENCY_HZ.load(Ordering::Relaxed)
}

/// Измерить частоту `rdtsc` по таймеру ACPI и запомнить её.
///
/// Вызывается один раз при загрузке. `rsdp` — физический адрес корневого
/// указателя ACPI из `BootInfo`; ноль означает, что таблиц нет.
///
/// # Safety
///
/// `rsdp` обязан быть либо нулём, либо адресом настоящего RSDP в отображённой
/// памяти: разбор таблиц читает по указателям из них.
pub unsafe fn calibrate(rsdp: u64) {
    let Some(timer) = (unsafe { PmTimer::find(rsdp) }) else {
        kprintln!("  monotonic   : no ACPI timer to calibrate against; time will follow ticks");
        return;
    };

    let Some(hz) = timer.measure() else {
        kprintln!("  monotonic   : the ACPI timer did not advance; time will follow ticks");
        return;
    };

    FREQUENCY_HZ.store(hz, Ordering::Release);
    kprintln!(
        "  monotonic   : TSC at {} MHz, calibrated against the ACPI timer at port {:#06x}",
        hz / 1_000_000,
        timer.port
    );
}

/// Таймер ACPI: порт и разрядность счётчика.
///
/// Виден и соседям по арх-модулю: тем же способом калибруется счётчик
/// локального APIC ([`super::apic`]) на машине, где не удалось измерить его по
/// PIT. Второй разбор FADT ради того же поля был бы вторым местом, где можно
/// ошибиться в смещении.
pub(super) struct PmTimer {
    pub(super) port: u16,
    /// Маска значащих разрядов: счётчик бывает 24- или 32-разрядным, и
    /// вычитание без маски дало бы после переполнения огромное число.
    mask: u32,
}

impl PmTimer {
    /// Найти таймер в FADT.
    ///
    /// # Safety
    ///
    /// См. [`calibrate`].
    pub(super) unsafe fn find(rsdp: u64) -> Option<Self> {
        if rsdp == 0 {
            return None;
        }
        let fadt = unsafe { crate::acpi::find_table(rsdp, b"FACP") }.ok()?;
        if fadt.len() <= FADT_FLAGS + 4 {
            return None;
        }

        let port = crate::acpi::read_u32(fadt, FADT_PM_TMR_BLK);
        let length = fadt[FADT_PM_TMR_LEN];
        // Порт нулевой либо длина не четыре — таймера нет. Это законно:
        // спецификация делает его необязательным.
        if port == 0 || length != 4 {
            return None;
        }
        let port = u16::try_from(port).ok()?;

        let flags = crate::acpi::read_u32(fadt, FADT_FLAGS);
        let mask = if flags & FLAG_TMR_VAL_EXT != 0 { u32::MAX } else { (1 << 24) - 1 };

        Some(Self { port, mask })
    }

    pub(super) fn read(&self) -> u32 {
        // SAFETY: порт получен из FADT и объявлен прошивкой как таймер ACPI;
        // чтение из него побочных эффектов не имеет — счётчик только читается.
        (unsafe { super::inl(self.port) }) & self.mask
    }

    /// Измерить частоту `rdtsc`, дождавшись известного числа тиков таймера.
    fn measure(&self) -> Option<u64> {
        self.measure_against(CALIBRATION_MS, counter)
    }

    /// Измерить частоту любого возрастающего счётчика по таймеру ACPI.
    ///
    /// `counter` обязан **расти**: у локального APIC счётчик считает вниз, и
    /// вычитать его показание из начального обязан вызывающий — иначе разность
    /// получится отрицательной, а в беззнаковой арифметике это огромное число,
    /// которое пройдёт любую проверку на правдоподобие.
    ///
    /// `None`, если таймер стоит: такое бывает на машинах, где прошивка
    /// объявила его, но не включила, и считать по нему было бы нельзя.
    pub(super) fn measure_against(&self, ms: u64, counter: impl Fn() -> u64) -> Option<u64> {
        // Цель в тиках таймера. Она заведомо меньше 24 разрядов — при 50 мс это
        // около 179 000, — то есть счётчик не успевает обернуться, и разность
        // остаётся однозначной даже у самой узкой из допустимых разрядностей.
        let target = (PM_TIMER_HZ * ms / 1000) as u32;

        let start_pm = self.read();
        let start_tsc = counter();

        // Ограничение по числу оборотов — не таймаут, а страховка от стоящего
        // счётчика: без неё загрузка на такой машине не кончилась бы никогда.
        // Порог с большим запасом: столько чтений порта заведомо занимает
        // дольше калибровочного интервала.
        let mut elapsed: u32 = 0;
        let mut spins = 0_u64;
        while elapsed < target {
            elapsed = self.read().wrapping_sub(start_pm) & self.mask;
            spins += 1;
            if spins > 100_000_000 {
                return None;
            }
        }

        let end_tsc = counter();
        let ticks = end_tsc.checked_sub(start_tsc)?;
        if elapsed == 0 || ticks == 0 {
            return None;
        }

        Some(ticks * PM_TIMER_HZ / u64::from(elapsed))
    }
}
