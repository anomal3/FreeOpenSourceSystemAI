//! I/O APIC: маршрутизация прерываний устройств в векторы процессора.
//!
//! # Место в картине
//!
//! Local APIC (см. [`super::apic`]) обслуживает только то, что рождается на
//! самом процессоре: свой таймер, IPI, ошибки. Прерывания устройств приходят
//! снаружи, и путь у них такой:
//!
//! ```text
//!   устройство → линия IRQ → вход I/O APIC (GSI) → вектор → Local APIC → CPU
//! ```
//!
//! I/O APIC — это программируемая таблица переадресации: на каждый вход своя
//! запись, в которой сказано, каким вектором его доставлять, какому процессору,
//! по фронту или по уровню, и не замаскирован ли он. Без записи в эту таблицу
//! нажатие клавиши не доходит до процессора вообще: контроллер по умолчанию
//! маскирует все входы.
//!
//! # Почему не 8259, который проще
//!
//! Он уже отключён — и осознанно, см. заголовок [`super::apic`]. Вернуть его
//! значило бы иметь два контроллера с перекрывающимися векторами, что даёт
//! ровно тот класс ошибок, от которого маскирование 8259 и защищает.
//!
//! # Доступ к регистрам: окно из двух слов
//!
//! У I/O APIC всего два регистра в адресном пространстве: `IOREGSEL` (номер
//! регистра) и `IOWIN` (его значение). То есть каждое обращение — это две
//! записи/чтения подряд, и они **не атомарны**. Прерывание, пришедшее между
//! ними, чей обработчик тоже трогает I/O APIC, испортило бы выбранный номер и
//! прочитало бы чужой регистр. Поэтому все обращения идут с запрещёнными
//! прерываниями (см. [`IoApic::read`]).

use crate::mm::{MapError, PhysAddr};
use core::ptr;

use super::interrupts::without_interrupts;
use super::paging;

/// Смещение регистра выбора внутри окна.
const IOREGSEL: usize = 0x00;
/// Смещение окна данных.
const IOWIN: usize = 0x10;

/// Номера регистров, адресуемых через `IOREGSEL`.
const REG_ID: u32 = 0x00;
const REG_VERSION: u32 = 0x01;
/// Первая запись таблицы переадресации. Каждая занимает два регистра.
const REG_REDIRECTION_BASE: u32 = 0x10;

/// Биты 27:24 регистра `IOAPICID` — идентификатор контроллера.
const ID_SHIFT: u32 = 24;
const ID_MASK: u32 = 0xF;

/// Биты 7:0 `IOAPICVER` — версия аппаратуры.
const VERSION_MASK: u32 = 0xFF;
/// Биты 23:16 — номер последней записи таблицы (число входов минус один).
const VERSION_MAX_ENTRY_SHIFT: u32 = 16;
const VERSION_MAX_ENTRY_MASK: u32 = 0xFF;

/// Запись таблицы, младшее слово: бит 16 — вход замаскирован.
const ENTRY_MASKED: u32 = 1 << 16;
/// Бит 15 — срабатывание по уровню (0 — по фронту).
const ENTRY_LEVEL_TRIGGERED: u32 = 1 << 15;
/// Бит 13 — активный уровень низкий (0 — высокий).
const ENTRY_ACTIVE_LOW: u32 = 1 << 13;
/// Биты 10:8 = 000 — режим доставки «фиксированный»: доставить именно тот
/// вектор, который указан, именно тому процессору, который указан. Остальные
/// режимы (NMI, SMI, INIT, ExtINT) нам не нужны, и ноль здесь — не «по
/// умолчанию», а осознанный выбор.
const ENTRY_DELIVERY_FIXED: u32 = 0;
/// Бит 11 = 0 — физический режим адресации получателя: поле назначения содержит
/// APIC ID, а не битовую маску логической группы. Для одного процессора это
/// единственный вариант, который не требует настраивать логический адрес.
const ENTRY_DEST_PHYSICAL: u32 = 0;

/// Сдвиг поля назначения в старшем слове записи.
const ENTRY_DEST_SHIFT: u32 = 24;

/// Сколько входов у контроллера может быть максимум по спецификации.
///
/// Восемь бит в `IOAPICVER` дают 256 записей; реальные контроллеры имеют 24.
/// Предел нужен, чтобы испорченное чтение регистра не увело цикл маскирования в
/// перебор четверти миллиона несуществующих регистров.
const MAX_ENTRIES: u32 = 256;

/// Один контроллер I/O APIC.
pub struct IoApic {
    /// Виртуальный адрес окна регистров.
    base: usize,
    /// Первый GSI, который обслуживает этот контроллер.
    gsi_base: u32,
    /// Сколько входов у него есть.
    entries: u32,
}

impl IoApic {
    /// Отобразить окно контроллера и привести его в известное состояние: все
    /// входы замаскированы.
    ///
    /// Маскирование при старте обязательно, а не гигиенично: прошивка успела
    /// настроить свои источники (тот же PS/2, которым пользуется её собственный
    /// драйвер клавиатуры), и записи остались в таблице с прошивочными
    /// векторами. Наши векторы уже другие, обработчиков у прошивочных нет — а
    /// линия дёрнется при первом же нажатии.
    ///
    /// # Safety
    ///
    /// Ядро должно исполняться на собственных таблицах страниц (нужно для
    /// доотображения окна), и в это время никто другой не должен править ни
    /// таблицы, ни этот контроллер.
    pub unsafe fn attach(phys: PhysAddr, gsi_base: u32) -> Result<Self, MapError> {
        // Окно регистров занимает 32 байта и лежит внутри одной страницы;
        // выравнивать адрес вниз необходимо, потому что MADT сообщает адрес
        // регистров, а отображать можно только страницу целиком.
        let page = phys.page_align_down();
        // SAFETY: условия делегированы вызывающему контрактом этой функции.
        let virt = unsafe { paging::map_device_page(page)? };
        let base = virt + (phys.as_u64() - page.as_u64()) as usize;

        let mut apic = Self { base, gsi_base, entries: 0 };
        let version = apic.version_register();
        apic.entries =
            (((version >> VERSION_MAX_ENTRY_SHIFT) & VERSION_MAX_ENTRY_MASK) + 1).min(MAX_ENTRIES);

        // SAFETY: окно отображено, число входов прочитано из самого контроллера.
        unsafe { apic.mask_all() };
        Ok(apic)
    }

    /// Прочитать регистр по его номеру.
    ///
    /// Пара «выбрать номер, прочитать окно» неделима — см. заголовок модуля.
    fn read(&self, register: u32) -> u32 {
        without_interrupts(|| {
            // SAFETY: `base` получен из `map_device_page`, то есть окно
            // отображено как Device-память; смещения `IOREGSEL`/`IOWIN` лежат
            // внутри той же страницы. `volatile` обязателен: это регистры, и
            // важен как факт обращения, так и его порядок.
            unsafe {
                ptr::write_volatile((self.base + IOREGSEL) as *mut u32, register);
                ptr::read_volatile((self.base + IOWIN) as *const u32)
            }
        })
    }

    /// Записать регистр по его номеру.
    ///
    /// # Safety
    ///
    /// Значение обязано быть осмысленным для этого регистра: запись в таблицу
    /// переадресации меняет маршрутизацию прерываний, и ошибка здесь означает
    /// вектор без обработчика или замаскированный источник.
    unsafe fn write(&self, register: u32, value: u32) {
        without_interrupts(|| {
            // SAFETY: см. `read`.
            unsafe {
                ptr::write_volatile((self.base + IOREGSEL) as *mut u32, register);
                ptr::write_volatile((self.base + IOWIN) as *mut u32, value);
            }
        });
    }

    fn version_register(&self) -> u32 {
        self.read(REG_VERSION)
    }

    /// Идентификатор контроллера, как его видит сам контроллер.
    #[must_use]
    pub fn id(&self) -> u8 {
        ((self.read(REG_ID) >> ID_SHIFT) & ID_MASK) as u8
    }

    /// Версия аппаратуры.
    #[must_use]
    pub fn version(&self) -> u8 {
        (self.version_register() & VERSION_MASK) as u8
    }

    /// Сколько входов обслуживает контроллер.
    #[must_use]
    pub const fn entries(&self) -> u32 {
        self.entries
    }

    /// Первый GSI этого контроллера.
    #[must_use]
    pub const fn gsi_base(&self) -> u32 {
        self.gsi_base
    }

    /// Обслуживает ли контроллер этот GSI.
    #[must_use]
    pub const fn handles(&self, gsi: u32) -> bool {
        gsi >= self.gsi_base && gsi - self.gsi_base < self.entries
    }

    /// Замаскировать все входы.
    ///
    /// # Safety
    ///
    /// После этого ни одно прерывание устройства доставлено не будет — вызывать
    /// только при настройке.
    pub unsafe fn mask_all(&self) {
        for index in 0..self.entries {
            let register = REG_REDIRECTION_BASE + index * 2;
            // Маскируем, не читая: чтение-модификация-запись сохранила бы
            // прошивочный вектор в замаскированной записи, и снятие маски
            // кем-то позже доставило бы прерывание в никуда.
            // SAFETY: окно отображено, номер регистра внутри таблицы.
            unsafe {
                self.write(register, ENTRY_MASKED);
                self.write(register + 1, 0);
            }
        }
    }

    /// Направить `gsi` в вектор `vector` на процессор с APIC ID `destination` и
    /// снять маску.
    ///
    /// `level` и `active_low` берутся из MADT (см.
    /// [`super::acpi::SourceOverride`]); для входов без переопределения верны
    /// значения по умолчанию для шины ISA — фронт, активный высокий.
    ///
    /// Возвращает `false`, если такого входа у контроллера нет.
    ///
    /// # Safety
    ///
    /// Вектор обязан иметь установленный обработчик в IDT, иначе первое же
    /// прерывание превратится в #GP, а из него — в двойную ошибку.
    pub unsafe fn route(
        &self,
        gsi: u32,
        vector: u8,
        destination: u8,
        level: bool,
        active_low: bool,
    ) -> bool {
        if !self.handles(gsi) {
            return false;
        }
        let index = gsi - self.gsi_base;
        let register = REG_REDIRECTION_BASE + index * 2;

        let mut low = u32::from(vector) | ENTRY_DELIVERY_FIXED | ENTRY_DEST_PHYSICAL;
        if level {
            low |= ENTRY_LEVEL_TRIGGERED;
        }
        if active_low {
            low |= ENTRY_ACTIVE_LOW;
        }
        let high = u32::from(destination) << ENTRY_DEST_SHIFT;

        // Порядок записи: сначала старшее слово (получатель), потом младшее
        // (вектор и снятие маски). Обратный порядок открыл бы окно, в котором
        // вход уже размаскирован, а получатель ещё прошивочный, — прерывание
        // ушло бы неизвестно куда.
        // SAFETY: номер регистра проверен через `handles`, а обработчик вектора
        // обязан установить вызывающий по контракту функции.
        unsafe {
            self.write(register + 1, high);
            self.write(register, low);
        }
        true
    }
}
