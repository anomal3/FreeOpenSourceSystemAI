//! Собственные GDT и TSS, а с ними — отдельные стеки под IST.
//!
//! # Почему нельзя оставить дескрипторы прошивки
//!
//! После `ExitBootServices` UEFI не даёт никаких обещаний насчёт своей GDT:
//! она лежит в памяти типа `BootServicesData`/`BootloaderReclaimable`, которую
//! ядро вправе раздать под что угодно. Пока никто её не перезаписал, всё
//! работает; в тот день, когда аллокатор выдаст этот кадр под таблицу страниц,
//! процессор перезагрузит из него селектор — и получит мусор вместо сегмента.
//! Ошибка при этом проявится не в момент порчи, а при следующем `iretq`.
//!
//! Второй, более прозаический повод: TSS. Без него не работает IST, а без IST
//! не работает обработчик двойной ошибки (см. ниже).
//!
//! # Зачем TSS в 64-битном режиме
//!
//! Аппаратного переключения задач в long mode нет, и от всей структуры TSS
//! реально используются два поля: `RSP0` (стек для перехода из ring 3 в ring 0)
//! и таблица `IST1..IST7` — семь безусловных указателей стека, на которые
//! процессор переключается при входе в вектор, если в его дескрипторе указан
//! номер IST.
//!
//! # Почему двойная ошибка обязана иметь свой стек
//!
//! Самая частая причина #DF — переполнение стека. Выглядит это так: ядро
//! упирается в страницу-ловушку под стеком, процессор пытается доставить #PF,
//! то есть **записать** на стек кадр исключения — а места на стеке уже нет, и
//! запись снова попадает в ловушку. Отказ во время доставки отказа — это и есть
//! #DF. Если у #DF нет своего стека, история повторяется третий раз: тройная
//! ошибка, которую процессор не обрабатывает вовсе, а превращает в аппаратный
//! сброс.
//!
//! IST разрывает этот круг: RSP берётся из TSS, а не с испорченного стека.
//!
//! # И почему у #PF своего стека больше нет
//!
//! **Фаза 41 вернула этот долг, и #PF со своего IST ушёл.** Подкачка по
//! требованию сделала отказ возвратным, а возвратный обработчик обязан
//! исполняться на стеке своей задачи: IST даёт всем один и тот же RSP, поэтому
//! вложенный отказ затёр бы кадр внешнего, а засыпание на диске — увело бы с
//! общего стека другую задачу.
//!
//! Диагностика переполнения при этом не потеряна, а переехала: без своего стека
//! #PF на переполненном стеке немедленно становится #DF, у которого IST остался,
//! и указатель стека в его кадре распознаёт `irq::fault::explain_stack`.
//!
//! # По TSS на процессор (фаза 43)
//!
//! Одна TSS работала, пока процессор был один, и перестала по двум причинам
//! сразу. `RSP0` — стек ловушки задачи, исполняющейся **на этом** процессоре, и
//! у двух процессоров с двумя программами он разный. А стек двойного отказа у
//! двух процессоров, отказавших одновременно, один на двоих — то есть второй
//! кадр лёг бы поверх первого ровно тогда, когда нужнее всего прочитать оба.
//!
//! Поэтому TSS и стеков двойного отказа по одному на процессор, и все TSS
//! описаны в **одной** GDT, каждая в своей записи. Одна таблица на всех, а не
//! таблица на процессор, — ради побочного, но решающего свойства: селектор,
//! загруженный в регистр задачи командой `ltr`, у каждого процессора свой, и
//! `str` отвечает на вопрос «какой я процессор» без единого обращения к памяти
//! и без регистра, который могла бы испортить программа. Номер процессора
//! спрашивает каждый захват лока в ядре, и отвечать на него обязаны дёшево.

use super::interrupts::without_interrupts;
use crate::mm::PAGE_SIZE;
use crate::smp::MAX_CPUS;
use crate::sync::Racy;
use core::arch::{asm, naked_asm};
use core::mem::size_of;
use core::sync::atomic::{AtomicBool, Ordering};

// --- Селекторы ----------------------------------------------------------------

/// Селектор сегмента кода ядра: запись 1, RPL 0.
pub const KERNEL_CODE_SELECTOR: u16 = 1 << 3;
/// Селектор сегмента данных ядра: запись 2, RPL 0.
pub const KERNEL_DATA_SELECTOR: u16 = 2 << 3;
/// Запись GDT с TSS загрузочного процессора (дескриптор системный и занимает
/// две записи).
const BOOT_TSS_ENTRY: usize = 3;
/// Селектор сегмента данных пользователя: запись 5, RPL 3.
///
/// Младшие два бита селектора — запрошенный уровень привилегий, и тройка в них
/// обязательна: `iretq` отказывается уходить в третье кольцо по селектору с
/// RPL 0, а `SS` с RPL, не равным уровню кода, даёт #GP.
pub const USER_DATA_SELECTOR: u16 = (5 << 3) | 3;
/// Селектор сегмента кода пользователя: запись 6, RPL 3.
pub const USER_CODE_SELECTOR: u16 = (6 << 3) | 3;
/// Первая запись с TSS остальных процессоров.
///
/// После пользовательских сегментов, а не сразу за TSS загрузочного: записи 5 и
/// 6 закреплены раскладкой, совместимой с `sysret`, и сдвигать их ради того,
/// чтобы TSS лежали подряд, значило бы менять договор с третьим кольцом.
const SECONDARY_TSS_ENTRY: usize = 7;

/// Номер IST для двойной ошибки. Значение попадает в поле `IST` дескриптора
/// вектора и индексирует `TSS.IST1..IST7` начиная с единицы; ноль означает
/// «не переключать стек».
pub const IST_DOUBLE_FAULT: u8 = 1;

// --- Биты дескрипторов --------------------------------------------------------
//
// Раскладка обычного дескриптора (Intel SDM, Vol. 3A, 3.4.5): базовый адрес и
// предел в long mode игнорируются, значение имеют только биты доступа.

/// `A` — обращались к сегменту. Процессор выставляет его сам при первой
/// загрузке селектора, то есть **пишет в GDT**. Ставим заранее: так таблица
/// остаётся неизменяемой после `lgdt`.
const DESC_ACCESSED: u64 = 1 << 40;
/// Для данных — «доступен на запись», для кода — «доступен на чтение».
const DESC_RW: u64 = 1 << 41;
/// `E` — сегмент исполняемый (код), иначе данные.
const DESC_EXECUTABLE: u64 = 1 << 43;
/// `S` — дескриптор кода или данных, а не системный.
const DESC_CODE_DATA: u64 = 1 << 44;
/// `P` — дескриптор валиден.
const DESC_PRESENT: u64 = 1 << 47;
/// `L` — 64-битный сегмент кода. Обязателен для CS в long mode.
const DESC_LONG_MODE: u64 = 1 << 53;

/// Тип системного дескриптора «доступный 64-битный TSS».
///
/// После `ltr` процессор меняет его на 0xB («занят»), поэтому повторный `ltr`
/// того же селектора даёт #GP — см. защиту в [`init`].
const SYS_TYPE_TSS_AVAILABLE: u64 = 0x9;

/// Сегмент кода ядра: ring 0, 64-битный, читаемый.
const KERNEL_CODE_DESCRIPTOR: u64 =
    DESC_ACCESSED | DESC_RW | DESC_EXECUTABLE | DESC_CODE_DATA | DESC_PRESENT | DESC_LONG_MODE;

/// Сегмент данных ядра: ring 0, записываемый.
const KERNEL_DATA_DESCRIPTOR: u64 = DESC_ACCESSED | DESC_RW | DESC_CODE_DATA | DESC_PRESENT;

/// `DPL = 3` — сегмент доступен из третьего кольца.
const DESC_DPL3: u64 = 3 << 45;

/// Сегмент данных пользователя: ring 3, записываемый.
const USER_DATA_DESCRIPTOR: u64 =
    DESC_ACCESSED | DESC_RW | DESC_CODE_DATA | DESC_PRESENT | DESC_DPL3;

/// Сегмент кода пользователя: ring 3, 64-битный.
const USER_CODE_DESCRIPTOR: u64 = DESC_ACCESSED
    | DESC_RW
    | DESC_EXECUTABLE
    | DESC_CODE_DATA
    | DESC_PRESENT
    | DESC_LONG_MODE
    | DESC_DPL3;

/// Куда процессор переключит стек при следующем входе из третьего кольца.
///
/// Вызывает планировщик на каждом переключении задач и вход в программу, и оба
/// — на том процессоре, где задача продолжит исполняться. Поле `RSP0` **у
/// каждой задачи своё** (Phase 13a): две программы означают два кадра ловушки, и
/// на общем стеке второй лёг бы поверх первого.
///
/// Ноль означает «эта задача программ не исполняет»: обращения из третьего
/// кольца у неё быть не может, и нулём поле оставлено намеренно — чтобы
/// случайная ловушка привела к внятному отказу, а не к записи по чужому адресу.
pub fn set_trap_stack(top: usize) {
    if !INSTALLED.load(Ordering::Relaxed) {
        return;
    }
    let tss = TSS[crate::smp::cpu()].get();
    // SAFETY: TSS этого процессора; пишет в неё только он сам (прерывания
    // запрещены у вызывающего — планировщика или входа в программу под локом).
    // Запись `unaligned` обязательна — структура `packed`.
    unsafe { (&raw mut (*tss).rsp[0]).write_unaligned(top as u64) };
}

// --- Стеки IST ----------------------------------------------------------------

/// Размер стека под один вектор с IST.
///
/// 16 КиБ — с большим запасом: единственное, что делает обработчик на этом
/// стеке, — печатает диагностику и останавливает процессор.
const IST_STACK_SIZE: usize = 4 * PAGE_SIZE;

/// Стек IST. Выравнивание на 16 — требование System V к `RSP` в точке вызова.
#[repr(C, align(16))]
struct IstStack([u8; IST_STACK_SIZE]);

/// Стеки IST лежат в `.bss` образа ядра, а не выделяются кадрами, — по стеку на
/// процессор.
///
/// Соображение одно, зато решающее: этот стек нужен ровно в тот момент, когда
/// доверять состоянию ядра уже нельзя. `.bss` отображён на запись раньше, чем
/// появляется IDT, и ни одного шага, способного отказать, между «ядро
/// запустилось» и «стек готов» не остаётся. Вариант с кадрами добавил бы к
/// обработчику двойной ошибки зависимость от аллокатора — того самого, который
/// вполне мог сломаться и вызвать эту двойную ошибку.
///
/// Чем платим: у этих стеков нет страницы-ловушки, и восемь процессоров стоят
/// образу ста двадцати восьми килобайт `.bss`, большая часть которых на машине
/// с одним процессором не нужна.
static DOUBLE_FAULT_STACKS: [Racy<IstStack>; MAX_CPUS] =
    [const { Racy::new(IstStack([0; IST_STACK_SIZE])) }; MAX_CPUS];

/// Вершина стека: стек растёт вниз, поэтому в IST кладётся адрес **за** концом
/// массива.
fn stack_top(stack: &'static Racy<IstStack>) -> u64 {
    let base = stack.get() as usize;
    debug_assert!(base % 16 == 0);
    (base + IST_STACK_SIZE) as u64
}

// --- TSS ----------------------------------------------------------------------

/// Сегмент состояния задачи в том виде, в каком его читает процессор.
///
/// Поля перечислены по возрастанию смещений (SDM, Vol. 3A, 8.7). Структура
/// `packed`, потому что архитектура её такой и определила.
#[repr(C, packed)]
struct Tss {
    reserved0: u32,
    /// Стеки для входа в ring 0/1/2.
    rsp: [u64; 3],
    reserved1: u64,
    /// `IST1..IST7`. Индексируется полем `IST` дескриптора вектора минус один.
    ist: [u64; 7],
    reserved2: u64,
    reserved3: u16,
    /// Смещение битовой карты портов ввода-вывода. Значение, равное размеру
    /// самой TSS, означает «карты нет»: все порты запрещены для ring 3.
    iomap_base: u16,
}

/// Канонический размер TSS. Проверяется статически: ошибиться в раскладке
/// `packed`-структуры легко, а последствия — #GP на `ltr` без объяснений.
const TSS_SIZE: usize = 104;
const _: () = assert!(size_of::<Tss>() == TSS_SIZE);

impl Tss {
    const fn new() -> Self {
        Self {
            reserved0: 0,
            rsp: [0; 3],
            reserved1: 0,
            ist: [0; 7],
            reserved2: 0,
            reserved3: 0,
            iomap_base: TSS_SIZE as u16,
        }
    }
}

static TSS: [Racy<Tss>; MAX_CPUS] = [const { Racy::new(Tss::new()) }; MAX_CPUS];

/// Собрать младшую половину системного дескриптора TSS.
///
/// В long mode системный дескриптор занимает 16 байт: обычные 8 плюс ещё 8 под
/// старшую половину базового адреса.
fn tss_descriptor_low(base: u64, limit: u32) -> u64 {
    (u64::from(limit) & 0xFFFF)
        | ((base & 0x00FF_FFFF) << 16)
        | (SYS_TYPE_TSS_AVAILABLE << 40)
        | DESC_PRESENT
        | ((u64::from(limit) >> 16 & 0xF) << 48)
        | (((base >> 24) & 0xFF) << 56)
}

/// Первая из двух записей GDT, в которых лежит TSS процессора `cpu`.
const fn tss_entry(cpu: usize) -> usize {
    if cpu == 0 { BOOT_TSS_ENTRY } else { SECONDARY_TSS_ENTRY + 2 * (cpu - 1) }
}

/// Номер процессора по регистру задачи.
///
/// Обратная сторона [`tss_entry`]. Селектор, которого ни один процессор не
/// загружал (прошивка, мусор до `ltr`), даёт ноль: так отвечает и
/// [`crate::smp::cpu`], пока второго процессора нет.
#[must_use]
pub fn current_cpu() -> usize {
    let selector: usize;
    // SAFETY: `str` читает регистр задачи в регистр общего назначения — ни
    // памяти, ни стека, ни флагов. Селектор расширяется нулями до 64 бит.
    unsafe { asm!("str {}", out(reg) selector, options(nomem, nostack, preserves_flags)) };
    let entry = (selector & 0xFFFF) >> 3;
    if entry == BOOT_TSS_ENTRY {
        return 0;
    }
    if entry >= SECONDARY_TSS_ENTRY && (entry - SECONDARY_TSS_ENTRY) % 2 == 0 {
        let cpu = (entry - SECONDARY_TSS_ENTRY) / 2 + 1;
        if cpu < MAX_CPUS {
            return cpu;
        }
    }
    0
}

// --- GDT ----------------------------------------------------------------------

/// Записей в GDT: нулевая, код и данные ядра, две под TSS загрузочного
/// процессора, данные и код пользователя, и по две на TSS каждого следующего.
const GDT_ENTRIES: usize = SECONDARY_TSS_ENTRY + 2 * (MAX_CPUS - 1);

/// GDT выровнена на 16 не по требованию архитектуры, а ради того, чтобы ни один
/// дескриптор не пересекал границу строки кеша.
#[repr(C, align(16))]
struct Gdt([u64; GDT_ENTRIES]);

static GDT: Racy<Gdt> = Racy::new(Gdt([0; GDT_ENTRIES]));

/// Операнд инструкций `lgdt` и `lidt`: предел и базовый адрес таблицы.
///
/// `packed` здесь принципиален — процессор читает ровно 10 байт подряд.
#[repr(C, packed)]
pub struct DescriptorTablePointer {
    /// Размер таблицы в байтах минус один.
    pub limit: u16,
    pub base: u64,
}

const _: () = assert!(size_of::<DescriptorTablePointer>() == 10);

/// Установлены ли уже GDT и TSS загрузочного процессора.
///
/// Не оптимизация: повторный `ltr` того же селектора даёт #GP, потому что после
/// первого дескриптор TSS помечен занятым.
static INSTALLED: AtomicBool = AtomicBool::new(false);

/// Заполнить TSS процессора `cpu` и описать её в GDT.
///
/// # Safety
///
/// Вызывающий гарантирует, что никто другой не пишет в эту TSS и в эти записи
/// GDT одновременно с ним, и что процессор `cpu` ещё не загрузил свой селектор.
unsafe fn describe_tss(cpu: usize) {
    let tss = TSS[cpu].get();
    // SAFETY: условия контракта; запись `unaligned` обязательна — структура
    // `packed`.
    unsafe {
        (&raw mut (*tss).ist[usize::from(IST_DOUBLE_FAULT) - 1])
            .write_unaligned(stack_top(&DOUBLE_FAULT_STACKS[cpu]));
        // `RSP0` оставляется нулевым: он зависит от задачи, и выставляет его
        // вход в третье кольцо и планировщик при переключении.
        (&raw mut (*tss).rsp[0]).write_unaligned(0);
    }
    let base = tss as u64;
    let entry = tss_entry(cpu);
    let gdt = GDT.get();
    // SAFETY: условия контракта; `Gdt` не `packed`, поля выровнены, индекс
    // меньше `GDT_ENTRIES` по построению `tss_entry` при `cpu < MAX_CPUS`.
    unsafe {
        (*gdt).0[entry] = tss_descriptor_low(base, TSS_SIZE as u32 - 1);
        (*gdt).0[entry + 1] = base >> 32;
    }
}

/// Указатель на GDT для `lgdt` — один на все процессоры.
fn gdt_pointer() -> DescriptorTablePointer {
    DescriptorTablePointer { limit: (size_of::<Gdt>() - 1) as u16, base: GDT.get() as u64 }
}

/// Построить и загрузить GDT, TSS и стеки IST загрузочного процессора.
///
/// Идемпотентна: повторный вызов ничего не делает.
pub fn init() {
    // Установка идёт с запрещёнными прерываниями: между `lgdt` и перезагрузкой
    // селекторов процессор какое-то время смотрит на новую таблицу старыми
    // сегментными регистрами.
    without_interrupts(|| {
        if INSTALLED.load(Ordering::Relaxed) {
            return;
        }
        // SAFETY: ядро на этом этапе однопоточно (остальные процессоры ещё
        // спят), прерывания запрещены, селектор загрузочного TSS не загружен.
        unsafe { describe_tss(0) };

        let gdt = GDT.get();
        // SAFETY: та же статика при тех же условиях эксклюзивности.
        unsafe {
            (*gdt).0[0] = 0; // нулевой дескриптор: загрузка его селектора обнуляет сегмент
            (*gdt).0[1] = KERNEL_CODE_DESCRIPTOR;
            (*gdt).0[2] = KERNEL_DATA_DESCRIPTOR;
            // Порядок «сначала данные, потом код» соответствует тому, которого
            // требует `sysret`. Сам `sysret` здесь не используется — системные
            // вызовы приходят ловушкой, — но раскладка, совместимая с ним,
            // ничего не стоит и снимает будущую перестановку таблицы.
            (*gdt).0[5] = USER_DATA_DESCRIPTOR;
            (*gdt).0[6] = USER_CODE_DESCRIPTOR;
        }

        let pointer = gdt_pointer();
        // SAFETY: таблица заполнена выше, лежит в статике с временем жизни
        // 'static и содержит корректные сегменты ядра. Записи под TSS остальных
        // процессоров пока нулевые, то есть «нет дескриптора», и никто их не
        // загружает.
        unsafe { load_gdt(&raw const pointer) };

        // SAFETY: дескриптор загрузочного TSS построен выше и помечен как
        // «доступный»; флаг гарантирует, что этот `ltr` — первый.
        unsafe { load_tss(tss_selector(0)) };
        INSTALLED.store(true, Ordering::Relaxed);
    });
}

/// Подготовить TSS процессора `cpu` — на загрузочном, до того как тот проснётся.
///
/// Готовит загрузочный, а не сам проснувшийся, и это не вкус: GDT общая, и
/// правка её записей тем, кто в неё уже смотрит, — это запись в таблицу, по
/// которой сосед прямо сейчас может загружать селекторы. Запуск идёт по
/// одному, поэтому здесь писатель гарантированно один.
pub fn prepare_secondary(cpu: usize) {
    if cpu == 0 || cpu >= MAX_CPUS {
        return;
    }
    // SAFETY: процессоры запускаются строго по одному, и вызывает это
    // загрузочный до запуска `cpu`; ни один процессор не держит этот селектор.
    unsafe { describe_tss(cpu) };
}

/// Загрузить общую GDT и свой TSS — первое, что делает проснувшийся процессор.
///
/// # Safety
///
/// Вызывать ровно один раз, на процессоре `cpu`, после [`prepare_secondary`] для
/// него и до первого захвата любого лока: до `ltr` номер процессора читается из
/// регистра, в котором ещё ничего нет.
pub unsafe fn load_secondary(cpu: usize) {
    let pointer = gdt_pointer();
    // SAFETY: таблица та же, что у загрузочного процессора, и содержит сегменты
    // ядра; запись TSS этого процессора подготовлена `prepare_secondary`.
    unsafe {
        load_gdt(&raw const pointer);
        load_tss(tss_selector(cpu));
    }
}

/// Селектор TSS процессора `cpu`.
const fn tss_selector(cpu: usize) -> u16 {
    (tss_entry(cpu) << 3) as u16
}

/// Загрузить GDT и перезарядить все сегментные регистры.
///
/// # Почему это `naked`, а не обычная функция с `asm!`
///
/// Из-за метки `2:`. `CS` нельзя загрузить обычным `mov`: единственный способ
/// сменить его в long mode — межсегментный переход, здесь это `retfq`, которому
/// на стек кладут новый `RIP` (адрес метки) и новый `CS`. Метка обязана
/// существовать, а числовая метка в блоке `asm!` — ловушка: компилятор вправе
/// **продублировать** блок, встроив функцию в несколько мест. Так и произошло:
/// в release-сборке блок оказался в образе дважды, ссылка `2f` разъехалась с
/// меткой, и `retfq` уходил по адресу за концом образа — тройная ошибка на
/// первой же загрузке GDT.
///
/// `#[naked]` закрывает вопрос по построению: такая функция не встраивается и
/// не дублируется.
///
/// `FS` и `GS` обнуляются: их базы ядро не использует, а оставлять там селекторы
/// прошивки — значит держать ссылку на таблицу, которой больше нет.
///
/// # Safety
///
/// `pointer` обязан описывать корректную GDT, в которой селектор
/// [`KERNEL_CODE_SELECTOR`] — 64-битный сегмент кода ring 0, а
/// [`KERNEL_DATA_SELECTOR`] — сегмент данных ring 0. Таблица должна пережить
/// вызов: процессор обращается к ней при каждой загрузке селектора.
#[unsafe(naked)]
unsafe extern "C" fn load_gdt(pointer: *const DescriptorTablePointer) {
    // System V: `pointer` приезжает в RDI. `rax` портится свободно — она
    // caller-saved, а своего кадра у naked-функции нет.
    naked_asm!(
        "lgdt [rdi]",
        "push {code}",
        "lea rax, [rip + 2f]",
        "push rax",
        // Дальний возврат: в Intel-синтаксисе LLVM он называется `retfq`
        // (в AT&T тот же код записывается как `lretq`).
        "retfq",
        "2:",
        "mov ax, {data}",
        "mov ds, ax",
        "mov es, ax",
        "mov ss, ax",
        "xor eax, eax",
        "mov fs, ax",
        "mov gs, ax",
        "ret",
        code = const KERNEL_CODE_SELECTOR as u32,
        data = const KERNEL_DATA_SELECTOR as u32,
    )
}

/// Указать процессору, где лежит его TSS.
///
/// # Safety
///
/// В действующей GDT по `selector` должен лежать корректный дескриптор
/// доступного (не занятого) 64-битного TSS, и это должен быть первый `ltr` для
/// него.
unsafe fn load_tss(selector: u16) {
    // SAFETY: см. контракт функции.
    unsafe {
        asm!("ltr {0:x}", in(reg) selector, options(nomem, nostack, preserves_flags));
    }
}
