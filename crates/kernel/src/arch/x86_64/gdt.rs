//! Собственные GDT и TSS, а с ними — отдельные стеки под IST.
//!
//! # Почему нельзя оставить дескрипторы прошивки
//!
//! После `ExitBootServices` UEFI не даёт никаких обещаний насчёт своей GDT:
//! она лежит в памяти типа `BootServicesData`/`BootloaderReclaimable`, которую
//! ядро вправе раздать под что угодно. Пока никто её не перезаписал, всё
//! работает; в тот день, когда аллокатор выдаст этот кадр под таблицу страниц,
//! процессор перезагрузит из него селектор — и получит мусор вместо сегмента.
//! Ошибка при этом проявится не в момент порчи, а при следующем `iretq`.
//!
//! Второй, более прозаический повод: TSS. Без него не работает IST, а без IST
//! не работает обработчик двойной ошибки (см. ниже).
//!
//! # Зачем TSS в 64-битном режиме
//!
//! Аппаратного переключения задач в long mode нет, и от всей структуры TSS
//! реально используются два поля: `RSP0` (стек для перехода из ring 3 в ring 0,
//! понадобится вместе с пользовательскими процессами) и таблица `IST1..IST7` —
//! семь безусловных указателей стека, на которые процессор переключается при
//! входе в вектор, если в его дескрипторе указан номер IST.
//!
//! # Почему двойная ошибка обязана иметь свой стек
//!
//! Самая частая причина #DF — переполнение стека. Выглядит это так: ядро
//! упирается в страницу-ловушку под стеком, процессор пытается доставить #PF,
//! то есть **записать** на стек кадр исключения — а места на стеке уже нет, и
//! запись снова попадает в ловушку. Отказ во время доставки отказа — это и есть
//! #DF. Если у #DF нет своего стека, история повторяется третий раз: тройная
//! ошибка, которую процессор не обрабатывает вовсе, а превращает в аппаратный
//! сброс. Ядро при этом не успевает напечатать ни байта, и с точки зрения
//! пользователя машина «просто перезагрузилась».
//!
//! IST разрывает этот круг: RSP берётся из TSS, а не с испорченного стека.
//!
//! # И почему свой стек нужен ещё и странице-ловушке
//!
//! Тот же сценарий, но на шаг раньше. Ловить переполнение имеет смысл только
//! если о нём можно рассказать — а рассказать может лишь обработчик #PF,
//! которому [`crate::irq::fault`] отдельно распознаёт адрес страницы-ловушки.
//! На общем стеке он до печати не доживёт: до неё нужно ещё положить кадр
//! исключения и полтора десятка регистров, то есть ~180 байт ниже той границы,
//! на которой всё и сломалось. Поэтому #PF тоже уходит на свой IST, и
//! переполнение стека диагностируется по имени, а не как безымянный #DF.
//!
//! Долг: как только появится подкачка по требованию, #PF перестанет быть
//! фатальным и сможет вкладываться сам в себя — а вложенный отказ на IST
//! затрёт кадр внешнего, потому что RSP каждый раз берётся один и тот же.
//! TODO(Phase 4): снять IST с #PF, когда обработчик научится возвращаться.

use super::interrupts::without_interrupts;
use crate::mm::PAGE_SIZE;
use crate::sync::Racy;
use core::arch::asm;
use core::mem::size_of;
use core::sync::atomic::{AtomicBool, Ordering};

// --- Селекторы ----------------------------------------------------------------

/// Селектор сегмента кода ядра: запись 1, RPL 0.
pub const KERNEL_CODE_SELECTOR: u16 = 1 << 3;
/// Селектор сегмента данных ядра: запись 2, RPL 0.
pub const KERNEL_DATA_SELECTOR: u16 = 2 << 3;
/// Селектор TSS: запись 3 (дескриптор системный и занимает две записи).
const TSS_SELECTOR: u16 = 3 << 3;

/// Номер IST для двойной ошибки. Значение попадает в поле `IST` дескриптора
/// вектора и индексирует `TSS.IST1..IST7` начиная с единицы; ноль означает
/// «не переключать стек».
pub const IST_DOUBLE_FAULT: u8 = 1;
/// Номер IST для отказа страницы.
pub const IST_PAGE_FAULT: u8 = 2;

// --- Биты дескрипторов --------------------------------------------------------
//
// Раскладка обычного дескриптора (Intel SDM, Vol. 3A, 3.4.5): базовый адрес и
// предел в long mode игнорируются, значение имеют только биты доступа.

/// `A` — обращались к сегменту. Процессор выставляет его сам при первой
/// загрузке селектора, то есть **пишет в GDT**. Ставим заранее: так таблица
/// остаётся неизменяемой после `lgdt`, и её можно будет когда-нибудь положить
/// в страницу только для чтения.
const DESC_ACCESSED: u64 = 1 << 40;
/// Для данных — «доступен на запись», для кода — «доступен на чтение».
const DESC_RW: u64 = 1 << 41;
/// `E` — сегмент исполняемый (код), иначе данные.
const DESC_EXECUTABLE: u64 = 1 << 43;
/// `S` — дескриптор кода или данных, а не системный.
const DESC_CODE_DATA: u64 = 1 << 44;
/// `P` — дескриптор валиден.
const DESC_PRESENT: u64 = 1 << 47;
/// `L` — 64-битный сегмент кода. Обязателен для CS в long mode.
const DESC_LONG_MODE: u64 = 1 << 53;

/// Тип системного дескриптора «доступный 64-битный TSS».
///
/// После `ltr` процессор меняет его на 0xB («занят»), поэтому повторный `ltr`
/// того же селектора даёт #GP — см. защиту в [`init`].
const SYS_TYPE_TSS_AVAILABLE: u64 = 0x9;

/// Сегмент кода ядра: ring 0, 64-битный, читаемый.
const KERNEL_CODE_DESCRIPTOR: u64 =
    DESC_ACCESSED | DESC_RW | DESC_EXECUTABLE | DESC_CODE_DATA | DESC_PRESENT | DESC_LONG_MODE;

/// Сегмент данных ядра: ring 0, записываемый.
///
/// Бит `L` здесь не ставится — он определён только для кода. Всё остальное
/// (база, предел, разрядность) в long mode для данных игнорируется, но `P` и
/// `S` обязаны стоять, иначе загрузка селектора в `SS` даёт #GP.
const KERNEL_DATA_DESCRIPTOR: u64 = DESC_ACCESSED | DESC_RW | DESC_CODE_DATA | DESC_PRESENT;

// --- Стеки IST ----------------------------------------------------------------

/// Размер стека под один вектор с IST.
///
/// 16 КиБ — с большим запасом: единственное, что делает обработчик на этом
/// стеке, — печатает диагностику и останавливает процессор. Форматирование
/// `core::fmt` кладёт на стек несколько сотен байт, дальше вызовов нет.
const IST_STACK_SIZE: usize = 4 * PAGE_SIZE;

/// Стек IST. Выравнивание на 16 — требование System V к `RSP` в точке вызова;
/// процессор при входе в исключение и так округляет `RSP` вниз до 16, но
/// выровненный сам по себе стек экономит те же 8 байт и не даёт удивиться
/// сдвигу при отладке.
#[repr(C, align(16))]
struct IstStack([u8; IST_STACK_SIZE]);

/// Стеки IST лежат в `.bss` образа ядра, а не выделяются кадрами.
///
/// Соображение одно, зато решающее: этот стек нужен ровно в тот момент, когда
/// доверять состоянию ядра уже нельзя. `.bss` отображён на запись ещё
/// `map_physical_memory` (identity-отображение всей памяти) и уточнён
/// `map_kernel_image` — то есть к моменту, когда IDT вообще появляется, память
/// под ним гарантированно есть, и ни одного шага, способного отказать
/// (`allocate`, `map`), между «ядро запустилось» и «стек готов» не остаётся.
/// Вариант с кадрами добавил бы к обработчику двойной ошибки зависимость от
/// аллокатора кадров — того самого, который вполне мог сломаться и вызвать эту
/// двойную ошибку.
///
/// Чем платим: у этих стеков нет страницы-ловушки, так что их переполнение
/// молча испортит соседнюю статику. При 16 КиБ на диагностическую печать это
/// теоретическая опасность, но она перестанет быть теоретической, если на IST
/// когда-нибудь окажется что-то, что возвращается и работает долго.
static DOUBLE_FAULT_STACK: Racy<IstStack> = Racy::new(IstStack([0; IST_STACK_SIZE]));
static PAGE_FAULT_STACK: Racy<IstStack> = Racy::new(IstStack([0; IST_STACK_SIZE]));

/// Вершина стека: стек растёт вниз, поэтому в IST кладётся адрес **за** концом
/// массива.
fn stack_top(stack: &'static Racy<IstStack>) -> u64 {
    let base = stack.get() as usize;
    debug_assert!(base % 16 == 0);
    (base + IST_STACK_SIZE) as u64
}

// --- TSS ----------------------------------------------------------------------

/// Сегмент состояния задачи в том виде, в каком его читает процессор.
///
/// Поля перечислены по возрастанию смещений (SDM, Vol. 3A, 8.7). Структура
/// `packed`, потому что архитектура её такой и определила: `RSP0` начинается со
/// смещения 4, то есть ни одно 8-байтное поле не выровнено. Обращаться к полям
/// нужно через `write_unaligned`.
#[repr(C, packed)]
struct Tss {
    reserved0: u32,
    /// Стеки для входа в ring 0/1/2. `RSP0` понадобится с появлением
    /// пользовательского режима; сейчас остаётся нулевым.
    rsp: [u64; 3],
    reserved1: u64,
    /// `IST1..IST7`. Индексируется полем `IST` дескриптора вектора минус один.
    ist: [u64; 7],
    reserved2: u64,
    reserved3: u16,
    /// Смещение битовой карты портов ввода-вывода. Значение, равное размеру
    /// самой TSS, означает «карты нет»: она начиналась бы ровно за пределом
    /// сегмента, и процессор считает все порты запрещёнными для ring 3.
    iomap_base: u16,
}

/// Канонический размер TSS. Проверяется статически: ошибиться в раскладке
/// `packed`-структуры легко, а последствия — #GP на `ltr` без объяснений.
const TSS_SIZE: usize = 104;
const _: () = assert!(size_of::<Tss>() == TSS_SIZE);

impl Tss {
    const fn new() -> Self {
        Self {
            reserved0: 0,
            rsp: [0; 3],
            reserved1: 0,
            ist: [0; 7],
            reserved2: 0,
            reserved3: 0,
            iomap_base: TSS_SIZE as u16,
        }
    }
}

static TSS: Racy<Tss> = Racy::new(Tss::new());

/// Собрать младшую половину системного дескриптора TSS.
///
/// В long mode системный дескриптор занимает 16 байт: обычные 8 плюс ещё 8 под
/// старшую половину базового адреса.
fn tss_descriptor_low(base: u64, limit: u32) -> u64 {
    (u64::from(limit) & 0xFFFF)
        | ((base & 0x00FF_FFFF) << 16)
        | (SYS_TYPE_TSS_AVAILABLE << 40)
        | DESC_PRESENT
        | ((u64::from(limit) >> 16 & 0xF) << 48)
        | (((base >> 24) & 0xFF) << 56)
}

// --- GDT ----------------------------------------------------------------------

/// Записей в GDT: нулевая, код, данные и две под системный дескриптор TSS.
const GDT_ENTRIES: usize = 5;

/// GDT выровнена на 16 не по требованию архитектуры, а ради того, чтобы ни один
/// дескриптор не пересекал границу строки кеша.
#[repr(C, align(16))]
struct Gdt([u64; GDT_ENTRIES]);

static GDT: Racy<Gdt> = Racy::new(Gdt([0; GDT_ENTRIES]));

/// Операнд инструкций `lgdt` и `lidt`: предел и базовый адрес таблицы.
///
/// `packed` здесь принципиален — процессор читает ровно 10 байт подряд, а
/// выровненная раскладка вставила бы шесть байт набивки между полями.
#[repr(C, packed)]
pub struct DescriptorTablePointer {
    /// Размер таблицы в байтах минус один.
    pub limit: u16,
    pub base: u64,
}

const _: () = assert!(size_of::<DescriptorTablePointer>() == 10);

/// Установлены ли уже GDT и TSS.
///
/// Не оптимизация: повторный `ltr` того же селектора даёт #GP, потому что после
/// первого дескриптор TSS помечен занятым.
static INSTALLED: AtomicBool = AtomicBool::new(false);

/// Построить и загрузить GDT, TSS и стеки IST.
///
/// Идемпотентна: повторный вызов ничего не делает.
pub fn init() {
    // Установка идёт с запрещёнными прерываниями: между `lgdt` и перезагрузкой
    // селекторов процессор какое-то время смотрит на новую таблицу старыми
    // сегментными регистрами, и прерывание, случившееся в этом окне, ушло бы в
    // обработчик с несогласованным состоянием.
    without_interrupts(|| {
        if INSTALLED.swap(true, Ordering::Relaxed) {
            return;
        }

        let tss = TSS.get();
        // SAFETY: `TSS` — статика этого модуля; ядро однопоточно, а прерывания
        // на время установки запрещены, поэтому другого доступа к ней сейчас
        // нет. Запись `unaligned` обязательна: структура `packed`, и обычная
        // запись через ссылку на поле была бы обращением по невыровненному
        // адресу.
        unsafe {
            (&raw mut (*tss).ist[usize::from(IST_DOUBLE_FAULT) - 1])
                .write_unaligned(stack_top(&DOUBLE_FAULT_STACK));
            (&raw mut (*tss).ist[usize::from(IST_PAGE_FAULT) - 1])
                .write_unaligned(stack_top(&PAGE_FAULT_STACK));
        }

        let tss_base = tss as u64;
        let gdt = GDT.get();
        // SAFETY: та же статика этого модуля при тех же условиях
        // эксклюзивности. `Gdt` не `packed`, поля выровнены.
        unsafe {
            (*gdt).0[0] = 0; // нулевой дескриптор: загрузка его селектора обнуляет сегмент
            (*gdt).0[1] = KERNEL_CODE_DESCRIPTOR;
            (*gdt).0[2] = KERNEL_DATA_DESCRIPTOR;
            (*gdt).0[3] = tss_descriptor_low(tss_base, TSS_SIZE as u32 - 1);
            (*gdt).0[4] = tss_base >> 32;
        }

        let pointer = DescriptorTablePointer {
            limit: (size_of::<Gdt>() - 1) as u16,
            base: gdt as u64,
        };

        // SAFETY: таблица заполнена выше, лежит в статике с временем жизни
        // 'static и содержит корректный 64-битный сегмент кода по селектору
        // `KERNEL_CODE_SELECTOR` и сегмент данных по `KERNEL_DATA_SELECTOR`.
        unsafe { load_gdt(&pointer) };

        // SAFETY: дескриптор TSS построен выше в записях 3-4 только что
        // загруженной GDT, помечен как «доступный» (не занятый), а флаг
        // `INSTALLED` гарантирует, что этот `ltr` — первый.
        unsafe { load_tss() };
    });
}

/// Загрузить GDT и перезарядить все сегментные регистры.
///
/// # Safety
///
/// `pointer` обязан описывать корректную GDT, в которой селектор
/// [`KERNEL_CODE_SELECTOR`] — 64-битный сегмент кода ring 0, а
/// [`KERNEL_DATA_SELECTOR`] — сегмент данных ring 0. Таблица должна пережить
/// вызов: процессор обращается к ней при каждой загрузке селектора.
unsafe fn load_gdt(pointer: &DescriptorTablePointer) {
    // SAFETY: корректность таблицы — на вызывающем (контракт выше).
    //
    // `CS` нельзя загрузить обычным `mov`: единственный способ сменить его в
    // long mode — межсегментный переход. Здесь это `lretq`, которому на стек
    // положены новый `RIP` (адрес метки `2:`) и новый `CS`; она же служит
    // точкой, с которой код исполняется уже в новом сегменте.
    //
    // `FS` и `GS` обнуляются: их базы (`FS.base`/`GS.base`) ядро пока не
    // использует, а оставлять там селекторы прошивки — значит держать ссылку на
    // таблицу, которой больше нет.
    unsafe {
        asm!(
            "lgdt [{pointer}]",
            "push {code:r}",
            "lea {tmp}, [rip + 2f]",
            "push {tmp}",
            // Дальний возврат: в Intel-синтаксисе LLVM он называется `retfq`
            // (в AT&T тот же код записывается как `lretq`).
            "retfq",
            "2:",
            "mov ds, {data:x}",
            "mov es, {data:x}",
            "mov ss, {data:x}",
            "mov fs, {zero:x}",
            "mov gs, {zero:x}",
            pointer = in(reg) pointer,
            code = in(reg) u64::from(KERNEL_CODE_SELECTOR),
            data = in(reg) KERNEL_DATA_SELECTOR,
            zero = in(reg) 0u16,
            tmp = lateout(reg) _,
            options(preserves_flags),
        );
    }
}

/// Указать процессору, где лежит TSS.
///
/// # Safety
///
/// В действующей GDT по селектору [`TSS_SELECTOR`] должен лежать корректный
/// дескриптор доступного (не занятого) 64-битного TSS, и это должен быть первый
/// `ltr` для него.
unsafe fn load_tss() {
    // SAFETY: см. контракт функции.
    unsafe {
        asm!("ltr {0:x}", in(reg) TSS_SELECTOR, options(nomem, nostack, preserves_flags));
    }
}
