pub const ARCH_NAME: &str = "x86_64";

/// Та же архитектура в кодировке хэндоффа — для сверки с тем, что заявил
/// загрузчик.
pub const ARCH_ID: Arch = Arch::X86_64;

/// Базовый порт COM1. На PC-совместимых машинах (включая QEMU `-machine q35`)
/// он зафиксирован архитектурой платформы ещё со времён IBM PC, и прошивка его
/// не переносит — в отличие от aarch64, здесь константа не является допущением
/// про конкретную плату.
const COM1: u16 = 0x3F8;

// Регистры 16550 адресуются как смещения от базового порта.
const REG_DATA: u16 = 0; // RBR/THR, а при DLAB=1 — младший байт делителя
const REG_IER: u16 = 1; // Interrupt Enable, а при DLAB=1 — старший байт делителя
const REG_FCR: u16 = 2; // FIFO Control (запись)
const REG_LCR: u16 = 3; // Line Control
const REG_MCR: u16 = 4; // Modem Control
const REG_LSR: u16 = 5; // Line Status

const LCR_DLAB: u8 = 0x80; // открывает доступ к делителю вместо IER/RBR
const LCR_8N1: u8 = 0x03; // 8 бит данных, без чётности, 1 стоп-бит
const LSR_DATA_READY: u8 = 0x01; // в приёмном буфере есть байт
const LSR_OVERRUN: u8 = 0x02; // байт пришёл в полное FIFO и потерян
const LSR_THR_EMPTY: u8 = 0x20; // регистр передатчика готов принять байт

/// `IER`, бит 0: прерывание по приходу байта. Остальные биты (передатчик
/// освободился, изменение состояния линии и модема) не нужны: передача идёт
/// опросом, а на ошибки линии ядру всё равно ответить нечем.
const IER_DATA_AVAILABLE: u8 = 0x01;

/// Делитель тактовой частоты 1.8432 МГц: 115200 бод = 1843200 / (16 * 1).
const BAUD_DIVISOR: u16 = 1;

/// Сколько раз опросить LSR перед тем, как признать порт неработающим.
///
/// Без этого ограничения ядро на машине без COM1 (LSR читается как 0xFF или
/// 0x00) зависло бы в первом же `println` — а это единственная диагностика,
/// которая у нас есть. Лучше потерять байт, чем всё ядро.
const TX_SPIN_LIMIT: u32 = 100_000;

/// Запись байта в порт ввода-вывода.
///
/// # Safety
///
/// Запись в порт — это обращение к устройству: вызывающий обязан гарантировать,
/// что по адресу `port` находится именно тот регистр, который он собирается
/// изменить, и что запись в него не нарушит работу остальной системы.
unsafe fn outb(port: u16, value: u8) {
    // SAFETY: инструкция `out` не трогает память (`nomem`) и стек (`nostack`)
    // и не меняет флаги (`preserves_flags`); корректность самого адреса порта —
    // на совести вызывающего, см. контракт функции.
    unsafe {
        asm!("out dx, al", in("dx") port, in("al") value, options(nomem, nostack, preserves_flags));
    }
}

/// Запись слова в порт ввода-вывода.
///
/// # Safety
///
/// См. [`outb`]. Регистры ACPI шириной в слово (`PM1_CNT`) обязаны писаться
/// одним обращением: два байтовых дадут два разных состояния регистра, из
/// которых первое может оказаться командой.
unsafe fn outw(port: u16, value: u16) {
    // SAFETY: те же условия, что и в `outb`.
    unsafe {
        asm!("out dx, ax", in("dx") port, in("ax") value, options(nomem, nostack, preserves_flags));
    }
}

/// Чтение байта из порта ввода-вывода.
///
/// # Safety
///
/// См. [`outb`]. Дополнительно: у некоторых устройств чтение регистра имеет
/// побочный эффект (сброс флага, извлечение байта из FIFO), поэтому читать
/// произвольные порты «на пробу» нельзя.
unsafe fn inb(port: u16) -> u8 {
    let value: u8;
    // SAFETY: те же условия, что и в `outb`.
    unsafe {
        asm!("in al, dx", out("al") value, in("dx") port, options(nomem, nostack, preserves_flags));
    }
    value
}

/// Чтение слова из порта ввода-вывода.
///
/// # Safety
///
/// См. [`inb`]. Регистры фиксированных событий ACPI (`PM1_STS`, `PM1_EN`,
/// `PM1_CNT`) объявлены шириной в слово, и читать их по байту нельзя: между
/// двумя обращениями чипсет может изменить второй байт, а признак события —
/// это то, что меняется само.
unsafe fn inw(port: u16) -> u16 {
    let value: u16;
    // SAFETY: те же условия, что и в `outb`.
    unsafe {
        asm!("in ax, dx", out("ax") value, in("dx") port, options(nomem, nostack, preserves_flags));
    }
    value
}

/// Чтение двойного слова из порта ввода-вывода.
///
/// # Safety
///
/// См. [`inb`]. Ширина обращения обязана совпадать с той, которую объявляет
/// устройство: таймер ACPI — единственный, кто читается так, и его регистр
/// ровно четырёхбайтовый.
unsafe fn inl(port: u16) -> u32 {
    let value: u32;
    // SAFETY: те же условия, что и в `outb`.
    unsafe {
        asm!("in eax, dx", out("eax") value, in("dx") port, options(nomem, nostack, preserves_flags));
    }
    value
}

/// Переждать такт шины ввода-вывода.
///
/// Старые контроллеры (в первую очередь 8259) не успевают принять следующую
/// команду сразу за предыдущей: между записями в их регистры нужна пауза
/// порядка микросекунды. Канонический для PC способ её получить — запись в
/// порт 0x80, который на всех машинах отдан под POST-код и не имеет побочных
/// эффектов; сама запись стоит примерно один цикл шины.
fn io_wait() {
    // SAFETY: порт 0x80 (диагностический POST-код) на PC-совместимых машинах
    // никем не читается, и запись в него ни на что не влияет.
    unsafe { outb(0x80, 0) };
}

/// Результат инструкции `CPUID`.
#[derive(Clone, Copy)]
struct Cpuid {
    eax: u32,
    #[allow(dead_code)] // нужен не всем листам, но выкидывать поле — терять смысл
    ebx: u32,
    ecx: u32,
    edx: u32,
}

/// `CPUID` для листа `leaf` с подлистом `subleaf`.
fn cpuid(leaf: u32, subleaf: u32) -> Cpuid {
    let (eax, ebx, ecx, edx);
    // SAFETY: `cpuid` — инструкция без побочных эффектов, доступная на любом
    // x86-64 и в любом кольце. Единственная тонкость — `RBX`: Rust не отдаёт
    // этот регистр inline-ассемблеру (LLVM держит его как возможный base
    // pointer), поэтому его значение сохраняется в свободный регистр и
    // возвращается на место через `xchg`. Так обходимся без стека, в отличие от
    // варианта с `push rbx`/`pop rbx`.
    unsafe {
        asm!(
            "mov {tmp:r}, rbx",
            "cpuid",
            "xchg {tmp:r}, rbx",
            tmp = out(reg) ebx,
            inlateout("eax") leaf => eax,
            inlateout("ecx") subleaf => ecx,
            lateout("edx") edx,
            options(nomem, nostack, preserves_flags),
        );
    }
    Cpuid { eax, ebx, ecx, edx }
}

/// Чтение MSR.
///
/// # Safety
///
/// Номер регистра должен быть реализован на этом процессоре: чтение
/// несуществующего MSR даёт #GP.
unsafe fn rdmsr(msr: u32) -> u64 {
    let (low, high): (u32, u32);
    // SAFETY: инструкция читает MSR в EDX:EAX, память и стек не затрагивает,
    // флаги не меняет; корректность номера — на вызывающем.
    unsafe {
        asm!(
            "rdmsr",
            in("ecx") msr,
            out("eax") low,
            out("edx") high,
            options(nomem, nostack, preserves_flags),
        );
    }
    (u64::from(high) << 32) | u64::from(low)
}

/// Запись MSR.
///
/// # Safety
///
/// Помимо требований [`rdmsr`]: записываемое значение должно быть допустимым
/// для этого MSR (резервированные биты дают #GP), а изменение — не ломать
/// работающий код. `IA32_EFER` управляет режимом трансляции целиком, а
/// `IA32_APIC_BASE` — местом и режимом работы локального APIC.
unsafe fn wrmsr(msr: u32, value: u64) {
    // SAFETY: см. контракт функции.
    unsafe {
        asm!(
            "wrmsr",
            in("ecx") msr,
            in("eax") value as u32,
            in("edx") (value >> 32) as u32,
            options(nomem, nostack, preserves_flags),
        );
    }
}

