/// Есть ли на этой платформе доступ к PCI через порты ввода-вывода.
///
/// Есть, и это единственный способ добраться до шины на машине, которая не
/// объявила MCFG. VirtualBox с чипсетом PIIX3 — а это его умолчание — именно
/// такая: ECAM там нет вовсе, и ядро, знающее только его, не видело ни xHCI, ни
/// мыши, ни диска. Устройства при этом были на месте.
pub const HAS_PCI_PORTS: bool = true;

/// Порт адреса и порт данных механизма конфигурации №1.
const PCI_CONFIG_ADDRESS: u16 = 0xCF8;
const PCI_CONFIG_DATA: u16 = 0xCFC;

/// Прочитать двойное слово конфигурационного пространства через порты.
///
/// `address` — уже собранное значение для порта 0xCF8: бит 31 разрешает
/// обращение, дальше идут номера шины, устройства, функции и смещение,
/// выровненное на четыре байта.
///
/// # Safety
///
/// Чтение конфигурационного пространства побочных эффектов не имеет, но
/// вызывающий обязан гарантировать, что между записью адреса и чтением данных
/// никто не влезет с другим адресом — то есть что вызовы не пересекаются.
pub unsafe fn pci_config_read32(address: u32) -> u32 {
    // SAFETY: порты 0xCF8/0xCFC закреплены за конфигурационным механизмом №1 на
    // всех PC-совместимых машинах и больше ничем не заняты.
    unsafe {
        outl(PCI_CONFIG_ADDRESS, address);
        inl(PCI_CONFIG_DATA)
    }
}

/// Записать двойное слово конфигурационного пространства через порты.
///
/// # Safety
///
/// См. [`pci_config_read32`]; запись меняет поведение устройства на шине.
pub unsafe fn pci_config_write32(address: u32, value: u32) {
    // SAFETY: см. выше.
    unsafe {
        outl(PCI_CONFIG_ADDRESS, address);
        outl(PCI_CONFIG_DATA, value);
    }
}

/// Запись двойного слова в порт.
///
/// # Safety
///
/// См. [`outb`]; ширина обращения обязана совпадать с той, которую объявляет
/// устройство.
unsafe fn outl(port: u16, value: u32) {
    // SAFETY: те же условия, что и в `outb`.
    unsafe {
        asm!("out dx, eax", in("dx") port, in("eax") value, options(nomem, nostack, preserves_flags));
    }
}

/// Адрес порта в **памяти**. Ноль: на этой платформе UART адресуется портами
/// ввода-вывода, а не памятью, и перепутать его с оперативной памятью нельзя в
/// принципе — пространство ввода-вывода отдельное. Проверка, ради которой
/// константа существует на AArch64 (см. `arch::aarch64::SERIAL_MMIO`), здесь
/// поэтому всегда проходит.
pub const SERIAL_MMIO: u64 = 0;

/// UART 16550, адресуемый через порты ввода-вывода.
pub struct Serial {
    base: u16,
}

impl Serial {
    /// UART, с которого ядро начинает говорить на этой платформе.
    pub const PLATFORM: Self = Self { base: COM1 };
}

/// Завести служебные задачи, которые нужны поднятому вводу.
///
/// На этой архитектуре их нет: и клавиатура, и манипулятор приходят по
/// прерыванию — от i8042 или от контроллера USB, — и опрашивать некого.
/// Функция существует ради общего интерфейса с AArch64, где тачскрин телефона
/// читается опросом.
pub fn spawn_input_services() {}

/// Запомнить порт, в который ядро говорит сейчас.
///
/// На этой архитектуре запоминать нечего: COM1 закреплён за портом 0x3F8
/// платформой, и другого адреса у консоли не бывает. Функция существует ради
/// общего интерфейса с AArch64, где адрес UART не закреплён ничем и приезжает
/// из ACPI или из дерева устройств.
pub fn remember_serial(_device: &Serial) {}

/// Тот же порт, но без взятия лока, — для печати из обработчика отказа.
#[must_use]
pub fn serial_fallback() -> Serial {
    Serial::PLATFORM
}

impl SerialDevice for Serial {
    fn init(&mut self) {
        let base = self.base;
        // SAFETY: `base` — COM1, стандартный для PC диапазон портов 0x3F8..0x3FF;
        // последовательность соответствует даташиту 16550: запретить прерывания,
        // открыть делитель (DLAB=1), задать скорость, вернуть DLAB=0 вместе с
        // форматом 8N1, включить и очистить FIFO, поднять DTR/RTS/OUT2.
        // Никакое другое устройство в системе эти порты не использует, поэтому
        // записи ни на что больше не влияют.
        unsafe {
            outb(base + REG_IER, 0x00);
            outb(base + REG_LCR, LCR_DLAB);
            outb(base + REG_DATA, (BAUD_DIVISOR & 0xFF) as u8);
            outb(base + REG_IER, (BAUD_DIVISOR >> 8) as u8);
            outb(base + REG_LCR, LCR_8N1);
            // 0xC7 = FIFO вкл + сброс приёмного и передающего FIFO + порог 14 байт.
            outb(base + REG_FCR, 0xC7);
            // 0x0B = DTR | RTS | OUT2. OUT2 нужен, чтобы линия прерывания UART
            // вообще доходила до PIC; прерывания мы не включаем, но состояние
            // порта оставляем каноническим для следующих фаз.
            outb(base + REG_MCR, 0x0B);
        }
    }

    fn write_byte(&mut self, byte: u8) {
        let base = self.base;
        let mut spins = 0u32;
        loop {
            // SAFETY: чтение LSR (0x3FD) не имеет побочных эффектов — это
            // регистр состояния, и его опрос является штатным способом дождаться
            // освобождения передатчика.
            let status = unsafe { inb(base + REG_LSR) };
            if status & LSR_THR_EMPTY != 0 {
                break;
            }
            spins += 1;
            if spins >= TX_SPIN_LIMIT {
                return; // порта нет либо он завис — молча теряем байт
            }
        }
        // SAFETY: THR свободен (проверено выше), запись байта в 0x3F8 при DLAB=0
        // отправляет его в линию и ничего больше не затрагивает.
        unsafe { outb(base + REG_DATA, byte) };
    }
}

/// Разрешить прерывание по приходу байта на COM1.
///
/// Функция работает с портом напрямую, минуя [`crate::serial`], и это осознанно:
/// тот держит UART под локом ради целостности **вывода**, а приём — независимый
/// путь. Взять тот же лок в обработчике прерывания значило бы уметь ждать
/// освобождения в контексте, в котором ждать нельзя.
///
/// # Safety
///
/// Порт должен быть уже проинициализирован (`DLAB = 0`, иначе запись уйдёт в
/// старший байт делителя и испортит скорость), а вход IRQ 4 — маршрутизирован в
/// вектор с установленным обработчиком.
pub unsafe fn enable_serial_rx() {
    // SAFETY: 0x3F9 — регистр разрешения прерываний COM1; условия делегированы
    // вызывающему контрактом функции.
    unsafe { outb(COM1 + REG_IER, IER_DATA_AVAILABLE) };
}

/// Забрать из приёмника COM1 всё, что там есть, и отдать подсистеме ввода.
///
/// Вычитывается весь буфер, а не один байт: FIFO у 16550 глубиной 16, и
/// прерывание выставляется по достижению порога, а не на каждый байт.
pub fn drain_serial_rx() {
    for _ in 0..32 {
        // SAFETY: чтение LSR (0x3FD) — регистр состояния, побочных эффектов не
        // имеет.
        let status = unsafe { inb(COM1 + REG_LSR) };
        // Переполнение приёмника: байт пришёл, когда FIFO было полно, и он
        // потерян безвозвратно. Замечать это обязательно — потерянный байт
        // выглядит как «система не приняла команду», и без счётчика отличить
        // это от неисправности разбора нечем. Ровно так и вышло: команда
        // `kill 11` доходила как `kill`, сценарий падал, и три захода ушли на
        // то, чтобы понять, что виноват не он.
        if status & LSR_OVERRUN != 0 {
            crate::input::ascii::note_overrun();
        }
        if status == 0xFF || status & LSR_DATA_READY == 0 {
            return;
        }
        // SAFETY: байт есть; чтение RBR извлекает его из FIFO — ровно то, что
        // нужно, иначе прерывание никогда не снялось бы.
        let byte = unsafe { inb(COM1 + REG_DATA) };
        crate::input::ascii::feed(byte);
    }
}

/// Остановить процессор до ближайшего прерывания.
///
/// В отличие от [`halt`], прерывания **не** запрещаются: смысл вызова ровно в
/// том, чтобы дождаться одного из них. Вызывать поэтому можно только с
/// разрешёнными прерываниями — иначе процессор остановится навсегда.
///
/// Единственный вызывающий — холостая задача планировщика, которой нечего
/// исполнять до ближайшего события.
pub fn wait_for_interrupt() {
    // SAFETY: `hlt` не трогает ни память, ни стек. При разрешённых прерываниях
    // процессор просыпается на первом же из них; при запрещённых остановился бы
    // навсегда, и это записано в контракте функции.
    unsafe { asm!("hlt", options(nomem, nostack, preserves_flags)) };
}

/// Остановить процессор навсегда.
///
/// `hlt` переводит ядро в спящее состояние до следующего прерывания, поэтому
/// цикл `cli; hlt` не потребляет ни такта — в отличие от `loop {}`, который
/// крутил бы CPU на 100% и грел хост под QEMU. `cli` обязателен: таблицы
/// прерываний ещё нет, и любое пришедшее прерывание превратилось бы в
/// тройную ошибку с перезагрузкой машины.
pub fn halt() -> ! {
    // SAFETY: возврата из этой функции не предусмотрено, поэтому запрет
    // прерываний ничего не ломает — никакой код после неё не выполнится.
    unsafe { asm!("cli", options(nomem, nostack, preserves_flags)) };
    loop {
        // SAFETY: `hlt` при запрещённых прерываниях лишь останавливает конвейер;
        // память и стек не затрагиваются.
        unsafe { asm!("hlt", options(nomem, nostack, preserves_flags)) };
    }
}

pub use power::{power_off, reboot};
