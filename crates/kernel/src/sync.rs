//! Примитивы синхронизации ядра.
//!
//! # Почему обычного спинлока недостаточно
//!
//! Ядро само себя прерывает. Обработчик таймера исполняется в контексте того
//! кода, который он прервал, и если тот держал спинлок, а обработчику нужен
//! тот же лок — ждать освобождения будет некому: держатель не продолжится,
//! пока не завершится обработчик. Взаимная блокировка на одном процессоре, без
//! всякой многоядерности.
//!
//! Поэтому [`SpinLock::lock`] запрещает прерывания **до** захвата и возвращает
//! их в прежнее состояние при освобождении. Именно в прежнее, а не «включает»:
//! вложенный захват не должен разрешать прерывания раньше, чем отпустит внешний.

use core::cell::UnsafeCell;
use core::ops::{Deref, DerefMut};
use core::sync::atomic::{AtomicBool, Ordering};

/// Глобальная переменная, к которой обращаются через сырой указатель.
///
/// Оставлен для состояния, к которому обращается только код запуска — до того,
/// как появились прерывания и задачи. Для всего остального нужен [`SpinLock`]:
/// допущение «исполнение однопоточное, прерывания запрещены» перестало быть
/// верным с Phase 3.
///
/// Потребитель остался один — арх-слой x86-64 (GDT, TSS и стеки IST), поэтому
/// на AArch64 тип целиком мёртв. Глушим предупреждение здесь: разводить его по
/// `cfg` значило бы вписать в общий примитив синхронизации знание о том, какая
/// архитектура им сегодня пользуется.
#[allow(dead_code)]
pub struct Racy<T> {
    cell: UnsafeCell<T>,
}

// SAFETY: тип не раздаёт `&mut` автоматически — наружу выходит только сырой
// указатель, разыменование которого уже требует `unsafe` и обоснования на
// месте использования. Обязанность не допускать гонок лежит на вызывающем.
unsafe impl<T> Sync for Racy<T> {}

impl<T> Racy<T> {
    pub const fn new(value: T) -> Self {
        Self { cell: UnsafeCell::new(value) }
    }

    /// Указатель на содержимое. Безопасен сам по себе; опасно разыменование.
    pub const fn get(&self) -> *mut T {
        self.cell.get()
    }
}

/// Взаимное исключение через активное ожидание, с запретом прерываний на время
/// удержания.
///
/// Ожидание активное намеренно: блокировать задачу негде — планировщик сам
/// защищён этим же типом, и попытка уснуть внутри лока была бы рекурсией.
/// Критические секции здесь короткие ровно поэтому.
pub struct SpinLock<T> {
    locked: AtomicBool,
    value: UnsafeCell<T>,
}

// SAFETY: доступ к `value` возможен только через `SpinGuard`, который выдаётся
// после успешного захвата `locked` и существует в единственном экземпляре.
unsafe impl<T: Send> Sync for SpinLock<T> {}
unsafe impl<T: Send> Send for SpinLock<T> {}

impl<T> SpinLock<T> {
    pub const fn new(value: T) -> Self {
        Self { locked: AtomicBool::new(false), value: UnsafeCell::new(value) }
    }

    /// Захватить лок, дождавшись освобождения.
    #[must_use = "лок освобождается при уничтожении охранника; проигнорировать его значит сразу же отпустить"]
    pub fn lock(&self) -> SpinGuard<'_, T> {
        // Прерывания запрещаются до захвата, а не после: иначе между этими
        // двумя действиями остаётся окно, в котором обработчик застаёт лок
        // уже занятым и упирается в вечное ожидание.
        let irq_was_enabled = crate::arch::interrupts::enabled();
        crate::arch::interrupts::disable();

        while self
            .locked
            .compare_exchange_weak(false, true, Ordering::Acquire, Ordering::Relaxed)
            .is_err()
        {
            // Пока лок занят, читаем обычной загрузкой, не пытаясь занять шину
            // атомарной операцией на каждом витке.
            while self.locked.load(Ordering::Relaxed) {
                core::hint::spin_loop();
            }
        }

        SpinGuard { lock: self, irq_was_enabled }
    }

    /// Попытаться захватить лок, не дожидаясь освобождения.
    ///
    /// Нужен там, где ожидание недопустимо — например в обработчике отказа,
    /// который обязан напечатать диагностику даже если лок занят навсегда.
    pub fn try_lock(&self) -> Option<SpinGuard<'_, T>> {
        let irq_was_enabled = crate::arch::interrupts::enabled();
        crate::arch::interrupts::disable();

        if self
            .locked
            .compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed)
            .is_ok()
        {
            Some(SpinGuard { lock: self, irq_was_enabled })
        } else {
            // Захват не удался — состояние прерываний надо вернуть, иначе
            // неудачная попытка молча оставила бы их запрещёнными.
            if irq_was_enabled {
                crate::arch::interrupts::enable();
            }
            None
        }
    }
}

/// Доступ к содержимому [`SpinLock`] на время удержания.
pub struct SpinGuard<'a, T> {
    lock: &'a SpinLock<T>,
    /// Были ли прерывания разрешены до захвата. Восстанавливается как было —
    /// вложенный захват не должен разрешать их раньше времени.
    irq_was_enabled: bool,
}

impl<T> Deref for SpinGuard<'_, T> {
    type Target = T;

    fn deref(&self) -> &T {
        // SAFETY: охранник существует только при удержанном локе, поэтому
        // других ссылок на значение сейчас нет.
        unsafe { &*self.lock.value.get() }
    }
}

impl<T> DerefMut for SpinGuard<'_, T> {
    fn deref_mut(&mut self) -> &mut T {
        // SAFETY: см. `Deref`; `&mut self` охранника гарантирует, что и вторая
        // ссылка из этого же охранника не возникнет.
        unsafe { &mut *self.lock.value.get() }
    }
}

impl<T> Drop for SpinGuard<'_, T> {
    fn drop(&mut self) {
        // Порядок обратный захвату: сначала отпустить лок, потом вернуть
        // прерывания. Иначе обработчик успел бы прийти на ещё удерживаемый лок.
        self.lock.locked.store(false, Ordering::Release);
        if self.irq_was_enabled {
            crate::arch::interrupts::enable();
        }
    }
}

/// Взаимное исключение, которое останавливает **задачу**, а не машину.
///
/// # Зачем понадобился второй примитив
///
/// [`SpinLock`] запрещает прерывания на всё время удержания, и для короткой
/// критической секции это правильно: обработчик прерывания, которому нужен тот
/// же лок, иначе повесил бы систему. Но той же ценой платят и длинные секции — а
/// они появились: перерисовка окна в отладочной сборке идёт под локом
/// композитора десятки миллисекунд, а правка ext2 — это десятки обращений к
/// диску, каждое со ожиданием устройства.
///
/// Пока такая секция держится, машина глуха. Не идёт таймер: локальный APIC и
/// GIC копят по одному прерыванию на вектор, и лишние тики теряются, а с ними
/// уезжает и время, и кванты. Не вычитывается UART: у PL011 приёмный FIFO 32
/// байта, и всё, что пришло сверх, теряется молча — серийная линия, единственный
/// внешний канал диагностики, начинает рвать команды посередине. И не работает
/// вытеснение, ради которого затевалась Phase 13b.
///
/// Этот тип прерывания не трогает. Задача, не сумевшая захватить лок, уходит в
/// состояние [`crate::sched::Wait::Lock`], а отпускающий её будит. Всё
/// остальное — таймер, ввод, другие задачи — работает как обычно.
///
/// # Чего им нельзя защищать
///
/// Всё, к чему обращается обработчик прерывания. Обработчик не имеет права
/// заблокироваться — ему негде: он исполняется в контексте прерванной задачи, и
/// «уснуть» означало бы усыпить её вместо себя. Такое состояние по-прежнему
/// защищает [`SpinLock`], и это не временное решение, а разделение по существу:
/// одно защищает данные от **прерывания**, другое — от **другой задачи**.
///
/// # Правило вложенности, нарушение которого вешает систему
///
/// Взяв [`SpinLock`], **нельзя** пытаться взять [`Mutex`]: прерывания запрещены,
/// значит держатель мьютекса не получит процессора и не отпустит его никогда.
/// Обратный порядок безопасен. Поэтому цепочки локов переводятся целиком, а не
/// по одному звену: вывод оболочки → композитор → файловая система.
pub struct Mutex<T> {
    locked: AtomicBool,
    value: UnsafeCell<T>,
}

// SAFETY: доступ к `value` возможен только через `MutexGuard`, который выдаётся
// после успешного захвата `locked` и существует в единственном экземпляре.
unsafe impl<T: Send> Sync for Mutex<T> {}
unsafe impl<T: Send> Send for Mutex<T> {}

impl<T> Mutex<T> {
    pub const fn new(value: T) -> Self {
        Self { locked: AtomicBool::new(false), value: UnsafeCell::new(value) }
    }

    /// Захватить лок, уснув, если он занят.
    #[must_use = "лок освобождается при уничтожении охранника; проигнорировать его значит сразу же отпустить"]
    pub fn lock(&self) -> MutexGuard<'_, T> {
        loop {
            if self
                .locked
                .compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed)
                .is_ok()
            {
                return MutexGuard { lock: self };
            }

            // Лок занят. Засыпаем — но проверку «а не освободился ли он»
            // выполняет планировщик под своим локом, и это закрывает гонку
            // целиком: пока он удерживается, прерывания запрещены, а держатель
            // мьютекса — другая задача, которой в это время не дадут ни такта.
            // Значит, состояние лока между проверкой и засыпанием измениться не
            // может, и потерянного пробуждения не бывает.
            crate::sched::block_on_lock(self.address(), || {
                !self.locked.load(Ordering::Relaxed)
            });
        }
    }

    /// Чем этот лок отличается от остальных для планировщика.
    ///
    /// Адрес самого лока: он уникален, неизменен и не требует ни счётчика
    /// идентификаторов, ни таблицы. Планировщик его не разыменовывает — для него
    /// это просто число, по которому он находит ждущих.
    fn address(&self) -> usize {
        core::ptr::from_ref(self).addr()
    }
}

/// Доступ к содержимому [`Mutex`] на время удержания.
pub struct MutexGuard<'a, T> {
    lock: &'a Mutex<T>,
}

impl<T> Deref for MutexGuard<'_, T> {
    type Target = T;

    fn deref(&self) -> &T {
        // SAFETY: охранник существует только при удержанном локе.
        unsafe { &*self.lock.value.get() }
    }
}

impl<T> DerefMut for MutexGuard<'_, T> {
    fn deref_mut(&mut self) -> &mut T {
        // SAFETY: см. `Deref`.
        unsafe { &mut *self.lock.value.get() }
    }
}

impl<T> Drop for MutexGuard<'_, T> {
    fn drop(&mut self) {
        self.lock.locked.store(false, Ordering::Release);
        // Будим после освобождения, а не до: разбуженная задача первым делом
        // попробует захватить лок, и застать его ещё занятым значило бы отправить
        // её спать второй раз.
        crate::sched::wake_lock(self.lock.address());
    }
}
