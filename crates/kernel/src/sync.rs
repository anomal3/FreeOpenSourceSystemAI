//! Минимальная замена глобальным `static mut`.
//!
//! В edition 2024 брать ссылку на `static mut` — жёсткая ошибка компиляции, а
//! настоящих примитивов синхронизации у нас пока нет: ядро на этом этапе
//! однопоточное, прерывания не включены, вторичные ядра (AP/секондари) не
//! стартовали. Поэтому глобальное изменяемое состояние оформлено как
//! `UnsafeCell` с ручной пометкой `Sync` — компилятор перестаёт мешать, а
//! обязанность не допускать гонок остаётся на вызывающей стороне.
//!
//! TODO(Phase 2): заменить на настоящий спинлок, как только появятся прерывания
//! и SMP — тогда допущение «однопоточно» перестанет быть верным.

use core::cell::UnsafeCell;

/// Глобальная переменная, к которой обращаются через сырой указатель.
pub struct Racy<T> {
    cell: UnsafeCell<T>,
}

// SAFETY: ядро на Phase 1 исполняется в один поток на одном ядре с
// выключенными прерываниями, поэтому одновременного доступа физически не
// возникает. Тип не раздаёт `&mut` автоматически: наружу выходит только сырой
// указатель, разыменование которого — уже unsafe и требует обоснования на
// месте использования.
unsafe impl<T> Sync for Racy<T> {}

impl<T> Racy<T> {
    pub const fn new(value: T) -> Self {
        Self { cell: UnsafeCell::new(value) }
    }

    /// Указатель на содержимое. Безопасен сам по себе; опасно разыменование.
    pub const fn get(&self) -> *mut T {
        self.cell.get()
    }
}
