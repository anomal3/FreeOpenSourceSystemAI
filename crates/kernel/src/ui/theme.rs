//! Палитра и размеры рабочего стола.
//!
//! Всё в одном месте по той же причине, по которой [`mini_ui`] существует
//! отдельным крейтом: установщик и система обязаны выглядеть как одна программа,
//! а не как две. Здесь — часть, которая относится только к столу; общие цвета
//! диалогов живут в [`mini_ui::widget::DARK`].
//!
//! Цвета подобраны так, чтобы яркость росла снизу вверх по слоям: фон стола
//! темнее панели, панель темнее окна, окно темнее заголовка активного окна. Это
//! не вкусовщина — на экране без теней и полупрозрачности порядок по глубине
//! читается только по яркости.

use mini_ui::Color;

/// Верх фона рабочего стола.
pub const DESKTOP_TOP: Color = Color::rgb(0x0C, 0x1B, 0x30);
/// Низ фона рабочего стола.
pub const DESKTOP_BOTTOM: Color = Color::rgb(0x03, 0x07, 0x0F);
/// Точки разметки на фоне.
pub const DESKTOP_DOT: Color = Color::rgb(0x17, 0x2A, 0x42);

/// Фон панели задач.
pub const PANEL_BG: Color = Color::rgb(0x07, 0x11, 0x1D);
/// Светлая линия по верхнему краю панели: она отделяет панель от фона там, где
/// оба тёмные.
pub const PANEL_EDGE: Color = Color::rgb(0x22, 0x40, 0x5E);

/// Фон окна.
pub const WINDOW_BG: Color = Color::rgb(0x0A, 0x1C, 0x2E);
/// Рамка окна — одна на активное и неактивное.
///
/// Цвет рамки не зависит от фокуса намеренно. Признак активного окна — цвет
/// полосы заголовка, и этого достаточно; если бы от фокуса зависела ещё и рамка,
/// каждое переключение окон означало бы перерисовку всей рамки, то есть всей
/// площади окна, вместо одной полосы сверху.
pub const FRAME: Color = Color::rgb(0x24, 0x46, 0x66);
/// Основной текст.
pub const TEXT: Color = Color::rgb(0xD8, 0xE2, 0xEC);
/// Второстепенный текст: подписи, размеры, подсказки.
pub const DIM: Color = Color::rgb(0x76, 0x8C, 0xA2);
/// Рамка и заголовок активного окна, выделение в списках.
pub const ACCENT: Color = Color::rgb(0x3C, 0x8C, 0xC8);
/// Текст на фоне [`ACCENT`].
pub const ON_ACCENT: Color = Color::rgb(0x06, 0x10, 0x18);
/// Фон выделенной строки списка.
pub const SELECT_BG: Color = Color::rgb(0x1B, 0x3B, 0x59);
/// Кнопка закрытия окна.
pub const CLOSE: Color = Color::rgb(0xC0, 0x4C, 0x50);
/// Каталог в списке файлов — чтобы он отличался от файла без значков.
pub const DIRECTORY: Color = Color::rgb(0x7A, 0xC8, 0xA0);

/// Толщина рамки окна.
pub const BORDER: u32 = 2;
/// Отступ содержимого от рамки.
pub const PADDING: u32 = 4;

/// Приглушить цвет к фону рабочего стола — так получается «неактивный» вариант
/// любого цвета, а не подобранный отдельно третий.
#[must_use]
pub fn inactive(color: Color) -> Color {
    color.mix(DESKTOP_TOP, 150)
}

/// Масштаб глифа для экрана такой ширины.
///
/// Шрифт 8×8, и множитель выбирается так, чтобы буква на экране была примерно
/// того же размера, что в обычном терминале: 16 точек. Тройной масштаб (24
/// точки) отдавался экрану 1920×1080 и выглядел там плакатом — в окно оболочки
/// помещалось 49 символов, и любая строка системы переносилась посередине
/// слова. Он остаётся для экранов от 2560 точек, где 16 точек уже мелко.
///
/// Правило одно на весь стол, иначе панель и окна разъезжаются по размеру.
#[must_use]
pub const fn scale_for(width: u32) -> u32 {
    if width >= 2560 {
        3
    } else if width >= 1024 {
        2
    } else {
        1
    }
}
