//! Разбор путей: строка вида `/boot/kernel.elf` — в последовательность имён,
//! которые [`Node::lookup`](super::Node::lookup) ищет по одному.
//!
//! # Что именно считается путём
//!
//! Путь абсолютный, разделитель — `/`. Относительных путей не бывает, потому
//! что не от чего отсчитывать: текущего каталога у ядра нет и до появления
//! пользовательских процессов не будет. Поэтому непустой путь обязан начинаться
//! с разделителя, а пустая строка допускается как синоним корня — это удобно
//! вызывающему, который отрезал от пути известный префикс и остался ни с чем.
//!
//! Правила разбора:
//!
//! * повторяющиеся разделители схлопываются: `/a//b` и `/a/b` — одно и то же;
//! * завершающий разделитель игнорируется: `/a/` — это `/a`;
//! * `.` пропускается;
//! * `..` снимает предыдущий компонент;
//! * пустого имени компонента не существует — оно может появиться только из
//!   схлопнутого разделителя и там же исчезает.
//!
//! # Почему `..` выше корня — ошибка, а не «остались в корне»
//!
//! Юникс-семантика говорит, что `/..` — это `/`, и соблазн повторить её велик.
//! Но она безопасна ровно потому, что там корень процесса и есть настоящая
//! граница: `chroot` переставляет её, а ядро сверяет каждый шаг с ней.
//!
//! Здесь такой сверки нет и в ближайшее время не будет, зато будет код, который
//! приписывает префикс к имени, пришедшему снаружи (`/mnt/` + аргумент), и
//! считает результат заведомо лежащим внутри поддерева. Молчаливое схлопывание
//! превращает `../../etc/shadow` в валидный путь наружу поддерева, и заметить
//! это по возвращённому узлу невозможно — узел настоящий, просто не тот.
//! Ошибка же обрывает разбор в единственном месте, где ещё видно, что путь
//! пытался подняться выше, чем ему позволено.
//!
//! Цена — ровно ноль: honest-путь `..` выше корня не нужен никому.
//!
//! # Разрешение лексическое, а не пошаговое
//!
//! `..` снимается со стека компонентов до всякого обращения к файловой системе,
//! то есть `/a/../b` превращается в `/b` независимо от того, существует ли `/a`.
//! Это допустимо потому, что ни FAT32, ни собственная ФС на горизонте не имеют
//! символьных ссылок: без них лексический и пошаговый разбор дают один и тот же
//! узел, а лексический дешевле (не ходит в каталоги, которые всё равно
//! отбросит). Когда появятся ссылки, разбор придётся делать пошаговым — и это
//! будет заметное изменение, а не тихое расхождение.
//!
//! # Об ограничениях
//!
//! Три предела заданы намеренно, и ни один не декоративен.
//!
//! [`MAX_COMPONENT`] — длина имени. 255 байт это и предел длинного имени FAT32
//! (255 символов UTF-16), и разумный предел любой ФС, которую ядро заведёт
//! потом. Имя длиннее просто не может существовать на носителе, поэтому дешевле
//! отвергнуть его здесь, чем гонять заведомо безрезультатный поиск по каталогу
//! и объяснять потом `NotFound` вместо честного «имя невозможной длины».
//!
//! [`MAX_PATH`] — длина всего пути. Нужен как граница работы на один вызов:
//! путь приезжает как `&str` от вызывающего, а вызывающим со временем станет
//! системный вызов, то есть строка окажется под контролем пользователя. 4096 —
//! то же значение, что `PATH_MAX` в Linux, и оно заведомо больше всего, что
//! встречается на практике.
//!
//! [`MAX_DEPTH`] — глубина вложенности. В отличие от первых двух, он вынужденный:
//! `..` требует уметь снять уже разобранный компонент, значит компоненты надо
//! где-то держать, а разбор пути не то место, где стоит зависеть от кучи и
//! обрабатывать нехватку памяти. Стек фиксированного размера снимает и то и
//! другое; 32 уровня — это глубже любой мыслимой раскладки загрузочного образа
//! (`/usr/lib/firmware/...` — это 4), а стоит массив 512 байт на кадре стека.
//!
//! Все три нарушения дают [`VfsError::BadPath`]: отдельного варианта на
//! «слишком длинно» в [`VfsError`] нет, а заводить его ради разницы, на которую
//! вызывающий всё равно не реагирует иначе, незачем.

use crate::vfs::{VfsError, VfsResult};

/// Разделитель компонентов пути.
pub const SEPARATOR: char = '/';

/// Наибольшая длина имени одного компонента в байтах.
pub const MAX_COMPONENT: usize = 255;

/// Наибольшая длина пути целиком в байтах.
pub const MAX_PATH: usize = 4096;

/// Наибольшая глубина вложенности после разрешения `.` и `..`.
pub const MAX_DEPTH: usize = 32;

/// Разобранный путь: имена компонентов от корня вниз.
///
/// Хранит подстроки исходного пути, поэтому ничего не копирует и не выделяет.
#[derive(Debug, Clone)]
pub struct Components<'a> {
    /// Стек компонентов; заполнены первые `len`.
    stack: [&'a str; MAX_DEPTH],
    len: usize,
    /// Сколько уже выдано итератором.
    taken: usize,
}

impl<'a> Components<'a> {
    /// Сколько компонентов осталось от корня до цели.
    #[must_use]
    pub fn depth(&self) -> usize {
        self.len
    }

    /// Путь указывает на сам корень.
    #[must_use]
    pub fn is_root(&self) -> bool {
        self.len == 0
    }

    /// Имя последнего компонента: `None` у корня.
    #[must_use]
    pub fn file_name(&self) -> Option<&'a str> {
        self.len.checked_sub(1).map(|last| self.stack[last])
    }
}

impl<'a> Iterator for Components<'a> {
    type Item = &'a str;

    fn next(&mut self) -> Option<&'a str> {
        if self.taken >= self.len {
            return None;
        }
        let name = self.stack[self.taken];
        self.taken += 1;
        Some(name)
    }

    fn size_hint(&self) -> (usize, Option<usize>) {
        let left = self.len - self.taken;
        (left, Some(left))
    }
}

impl ExactSizeIterator for Components<'_> {}

/// Разобрать абсолютный путь на компоненты.
///
/// Корень (`""` или `"/"`) даёт пустую последовательность: идти от корня никуда
/// не надо, и [`FileSystem::resolve`](super::FileSystem::resolve) на такой
/// последовательности возвращает сам корневой узел.
///
/// # Ошибки
///
/// [`VfsError::BadPath`], если путь не начинается с разделителя, содержит `..`
/// выше корня, содержит имя с нулевым байтом или выходит за любой из пределов
/// [`MAX_PATH`], [`MAX_COMPONENT`], [`MAX_DEPTH`].
pub fn components(path: &str) -> VfsResult<Components<'_>> {
    if path.len() > MAX_PATH {
        return Err(VfsError::BadPath);
    }
    if !path.is_empty() && !path.starts_with(SEPARATOR) {
        return Err(VfsError::BadPath);
    }

    let mut parsed = Components { stack: [""; MAX_DEPTH], len: 0, taken: 0 };

    for name in path.split(SEPARATOR) {
        match name {
            // Пустая строка между разделителями — это и есть схлопывание: её
            // даёт как `//` в середине, так и `/` в начале и в конце.
            "" | "." => {}
            ".." => {
                // См. заголовок модуля: подъём выше корня — ошибка.
                parsed.len = parsed.len.checked_sub(1).ok_or(VfsError::BadPath)?;
            }
            _ => {
                if name.len() > MAX_COMPONENT {
                    return Err(VfsError::BadPath);
                }
                // Нулевой байт внутри имени `&str` допускает, а всё, что ниже
                // (записи каталога, будущий пользовательский ABI), обрывает по
                // нему строку. Имя, которое на разных слоях означает разное, —
                // готовая дыра, и место отвергнуть его здесь.
                if name.as_bytes().contains(&0) {
                    return Err(VfsError::BadPath);
                }
                if parsed.len == MAX_DEPTH {
                    return Err(VfsError::BadPath);
                }
                parsed.stack[parsed.len] = name;
                parsed.len += 1;
            }
        }
    }

    Ok(parsed)
}
