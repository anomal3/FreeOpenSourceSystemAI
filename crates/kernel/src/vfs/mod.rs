//! Виртуальная файловая система: единый интерфейс поверх любой ФС.
//!
//! Слой существует ради того, чтобы остальное ядро — а позже и пользовательские
//! программы — не знали, какая именно файловая система под ними. Сейчас
//! реализация одна (FAT32 на RAM-диске), и соблазн обойтись без абстракции
//! велик; но по дорожной карте корневой ФС станет собственная inode-based, а
//! FAT32 останется только на загрузочном разделе, который требует спецификация
//! UEFI. То есть двух реализаций не избежать, и дешевле развести их сразу.
//!
//! # Метаданные
//!
//! [`Metadata`] с самого начала несёт `mode`, `uid` и `gid`, хотя FAT32 их не
//! хранит и подставляет значения по умолчанию. Причина та же, что заставила
//! завести эти поля в формате собственной ФС: добавить права после того, как на
//! диске появились пользовательские данные, значит менять формат и мигрировать.
//!
//! С Phase 12c эти поля проверяются — см. [`perm`]. Проверяются там, где
//! спрашивает пользовательская программа; код ядра ходит мимо, и почему именно
//! так, написано там же.

// Часть контракта пока без вызывающих: запись появится вместе с собственной
// корневой ФС, `VfsError::Io` — вместе с реальным контроллером диска (RAM-диск
// отказать не может), геометрия тома нужна будет монтировщику. Это
// спроектированный интерфейс, а не забытый код; глушим предупреждение здесь,
// чтобы шум не скрывал по-настоящему новые.
#![allow(dead_code)]

pub mod path;
pub mod perm;
pub mod ramdisk;

use alloc::boxed::Box;
use alloc::string::String;
use alloc::vec::Vec;
use core::fmt;

/// Размер блока, которым оперируют устройства. Совпадает с сектором и с тем,
/// что ожидает FAT.
pub const BLOCK_SIZE: usize = 512;

/// Что пошло не так при обращении к файловой системе.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VfsError {
    /// Такого файла или каталога нет.
    NotFound,
    /// Ожидался каталог, а это файл (или наоборот).
    WrongKind,
    /// Путь синтаксически некорректен.
    BadPath,
    /// Носитель отдал не то, что обещал: испорченная структура на диске.
    Corrupt,
    /// Чтение за пределами устройства или файла.
    OutOfBounds,
    /// Устройство отказало.
    Io,
    /// Операция не поддерживается этой реализацией (например запись в
    /// смонтированный только на чтение образ).
    Unsupported,
    /// Не хватило памяти.
    OutOfMemory,
    /// Права не позволяют — самому файлу или каталогу на пути к нему.
    ///
    /// Отличается от [`VfsError::NotFound`] сознательно: скрывать существование
    /// файла за «нет такого» имеет смысл там, где важнее секретность, а здесь
    /// важнее, чтобы человек понял, что делать дальше.
    PermissionDenied,
    /// Такое имя уже занято.
    Exists,
    /// Каталог не пуст.
    NotEmpty,
    /// На носителе кончилось место — блоки либо inode.
    NoSpace,
}

impl fmt::Display for VfsError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let text = match self {
            Self::NotFound => "no such file or directory",
            Self::Exists => "the name already exists",
            Self::NotEmpty => "the directory is not empty",
            Self::NoSpace => "no space left on the device",
            Self::WrongKind => "path component is not of the expected kind",
            Self::BadPath => "malformed path",
            Self::Corrupt => "on-disk structure is inconsistent",
            Self::OutOfBounds => "read past the end of the device or file",
            Self::Io => "device error",
            Self::Unsupported => "operation not supported by this filesystem",
            Self::OutOfMemory => "out of memory",
            Self::PermissionDenied => "permission denied",
        };
        f.write_str(text)
    }
}

pub type VfsResult<T> = Result<T, VfsError>;

/// Источник блоков фиксированного размера.
///
/// Намеренно отделён от файловой системы: одна и та же ФС должна одинаково
/// работать поверх RAM-диска, раздела на SD-карте и файла-образа, а различаются
/// они только тем, откуда берутся блоки.
pub trait BlockDevice: Send + Sync {
    /// Прочитать `buf.len() / BLOCK_SIZE` блоков, начиная с `block`.
    ///
    /// Длина буфера обязана быть кратна [`BLOCK_SIZE`].
    fn read_blocks(&self, block: u64, buf: &mut [u8]) -> VfsResult<()>;

    /// Записать блоки. Устройство только для чтения возвращает
    /// [`VfsError::Unsupported`].
    fn write_blocks(&self, block: u64, buf: &[u8]) -> VfsResult<()>;

    /// Сколько всего блоков на устройстве.
    fn block_count(&self) -> u64;
}

/// Тип узла файловой системы.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NodeKind {
    File,
    Directory,
}

/// Права и владение — в терминах, которые FAT32 не хранит, а собственная ФС
/// будет хранить. См. заголовок модуля.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Metadata {
    pub kind: NodeKind,
    pub size: u64,
    /// Права в unix-нотации: `rwxrwxrwx` в младших девяти битах.
    pub mode: u16,
    pub uid: u32,
    pub gid: u32,
    /// Время последнего изменения, секунды эпохи Unix, UTC. Ноль означает
    /// «неизвестно» — так помечены и файлы на ФС, которая времени не хранит, и
    /// файлы, созданные системой, у которой не было часов.
    pub mtime: u32,
}

impl Metadata {
    /// Значения по умолчанию для ФС, которая прав не хранит: владелец root,
    /// чтение и исполнение всем, запись владельцу.
    ///
    /// Бит исполнения стоит и на файлах, и это не небрежность. FAT не хранит
    /// его вовсе — не «хранит нулём», а не имеет для него места, — поэтому
    /// подставленное значение выражает не право, а его отсутствие в формате.
    /// Linux решает то же самое так же: `vfat` по умолчанию монтируется с
    /// `fmask=0022`, то есть с файлами `0755`. Выбор виден: с `0644` ни одна
    /// программа с такого тома не запустилась бы — не потому, что кто-то
    /// запретил, а потому, что разрешать было нечему.
    #[must_use]
    pub const fn defaults(kind: NodeKind, size: u64) -> Self {
        Self { kind, size, mode: 0o755, uid: 0, gid: 0, mtime: 0 }
    }
}

/// Запись в каталоге.
///
/// Права и владение лежат здесь, а не только в [`Metadata`], потому что иначе
/// перечисление каталога с показом прав означало бы отдельное чтение inode на
/// каждое имя. ФС, которая прав не хранит, подставляет значения по умолчанию —
/// и это видно по тому, что они у всех записей одинаковые.
#[derive(Debug, Clone)]
pub struct DirEntry {
    pub name: String,
    pub kind: NodeKind,
    pub size: u64,
    pub mode: u16,
    pub uid: u32,
    pub gid: u32,
    /// Время последнего изменения — см. [`Metadata::mtime`].
    pub mtime: u32,
}

/// Узел файловой системы — файл или каталог.
///
/// Возвращается в `Box`, а не по значению: конкретный тип узла зависит от
/// реализации ФС, а вызывающий обязан работать с любой.
pub trait Node: Send + Sync {
    fn metadata(&self) -> Metadata;

    /// Прочитать до `buf.len()` байт, начиная со смещения. Возвращает, сколько
    /// прочитано: у конца файла это меньше запрошенного, и это не ошибка.
    ///
    /// Каталог возвращает [`VfsError::WrongKind`].
    fn read_at(&self, offset: u64, buf: &mut [u8]) -> VfsResult<usize>;

    /// Перечислить содержимое каталога. Файл возвращает [`VfsError::WrongKind`].
    fn list(&self) -> VfsResult<Vec<DirEntry>>;

    /// Найти запись по имени в этом каталоге. Имя — один компонент пути, без
    /// разделителей.
    fn lookup(&self, name: &str) -> VfsResult<Box<dyn Node>>;

    // --- запись ------------------------------------------------------------
    //
    // У всего, что ниже, есть реализация по умолчанию, и она отказывает. Это не
    // заглушка: файловая система на чтение — не недоделанная, а другая. Образ
    // initrd лежит в оперативной памяти и исчезает с выключением, писать в него
    // бессмысленно; RAM-диск существует ради проверки самого VFS. Требовать от
    // них методов записи значило бы заставить их отказывать вручную — то есть
    // то же самое, но в трёх местах вместо одного.

    /// Записать байты, начиная со смещения. Возвращает, сколько записано.
    ///
    /// Смещение за концом файла допустимо: промежуток остаётся дырой и читается
    /// нулями.
    fn write_at(&self, _offset: u64, _data: &[u8]) -> VfsResult<usize> {
        Err(VfsError::Unsupported)
    }

    /// Изменить длину файла.
    fn truncate(&self, _size: u64) -> VfsResult<()> {
        Err(VfsError::Unsupported)
    }

    /// Создать в этом каталоге пустой файл и вернуть его.
    fn create(&self, _name: &str, _mode: u16, _uid: u32, _gid: u32) -> VfsResult<Box<dyn Node>> {
        Err(VfsError::Unsupported)
    }

    /// Создать в этом каталоге подкаталог.
    fn mkdir(&self, _name: &str, _mode: u16, _uid: u32, _gid: u32) -> VfsResult<Box<dyn Node>> {
        Err(VfsError::Unsupported)
    }

    /// Удалить файл по имени. Каталог этим не удаляется — см. [`Node::rmdir`].
    fn unlink(&self, _name: &str) -> VfsResult<()> {
        Err(VfsError::Unsupported)
    }

    /// Удалить пустой подкаталог.
    fn rmdir(&self, _name: &str) -> VfsResult<()> {
        Err(VfsError::Unsupported)
    }
}

/// Смонтированная файловая система.
pub trait FileSystem: Send + Sync {
    /// Человекочитаемое имя для диагностики: `"FAT32"`, и так далее.
    fn name(&self) -> &'static str;

    /// Корневой каталог.
    fn root(&self) -> VfsResult<Box<dyn Node>>;

    /// Найти узел по абсолютному пути.
    ///
    /// Реализация по умолчанию разбирает путь на компоненты и идёт от корня
    /// через [`Node::lookup`]; переопределять её стоит только там, где ФС умеет
    /// это быстрее.
    fn resolve(&self, path: &str) -> VfsResult<Box<dyn Node>> {
        let mut node = self.root()?;
        for component in path::components(path)? {
            node = node.lookup(component)?;
        }
        Ok(node)
    }
}
