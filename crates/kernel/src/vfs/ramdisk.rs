//! RAM-диск: блочное устройство поверх образа, загруженного в память.
//!
//! Загрузчик читает образ файловой системы с того же тома, с которого стартовал
//! сам, и передаёт его ядру как [`Initrd`] — физический адрес и размер. Отсюда
//! ядро получает файлы, не имея ни одного драйвера контроллера: AHCI, NVMe и
//! SD — самая платформозависимая работа из оставшихся, и ставить «ядро умеет
//! открыть файл» в зависимость от неё значит остановить всё, что строится
//! сверху.
//!
//! Устройство получается вырожденное, и это его главное свойство: задержек нет,
//! очереди запросов нет, отказать оно не может ничем, кроме выхода за границу
//! образа. Всё, что здесь есть, — проверка границ и копирование.
//!
//! # Как ядро добирается до памяти образа
//!
//! Адрес от загрузчика — физический. Прямо сейчас его можно было бы разыменовать
//! как есть: ядро исполняется по identity-отображению, и виртуальный адрес равен
//! физическому. Но identity — временная конструкция, которую снимут вместе с
//! переездом ядра в верхнюю половину (см. `TODO(Phase 3)` в `mm`), а прямое
//! отображение `PHYS_MAP_BASE + phys` переживёт это без единой правки. Поэтому
//! адрес пересчитывается через [`PhysAddr::to_direct_map`] — ровно тем же
//! способом, каким аллокатор кадров дотягивается до своей битовой карты после
//! `use_direct_map` (см. `mm::frame`). Отсюда же требование в контракте
//! [`RamDisk::new`]: прямое отображение к моменту вызова обязано быть активно.
//!
//! # Почему запись не поддерживается
//!
//! Технически образ лежит в обычной оперативной памяти и пишется не хуже, чем
//! читается. Но записанное некуда девать: перезагрузка возвращает исходный
//! образ, а инструменты, которые его собирают (`xtask`), об изменениях не знают.
//! Разрешить запись значит получить файловую систему, которая на любой `write`
//! отвечает «готово», исправно показывает записанное до конца сеанса и теряет
//! его молча — самый неудобный вид ошибки, потому что проявляется он не там, где
//! сделан.
//!
//! Отказ же на уровне устройства виден сразу и в единственном месте: драйвер ФС
//! получит [`VfsError::Unsupported`] на первой попытке изменить хоть что-нибудь
//! и не станет строить логику на предположении, что носитель записываемый. Когда
//! появится настоящий блочный драйвер, запись будет отлаживаться на устройстве,
//! которое умеет её сохранить, а не на образе, где успех ничего не значит.
//! Снять запрет — одна строка, и решение легко пересмотреть; обратно, после
//! кода, привыкшего к работающей записи, — уже нет.

use crate::mm::{HEAP_BASE, PHYS_MAP_BASE, PhysAddr, VirtAddr};
use crate::sync::SpinLock;
use crate::vfs::{BLOCK_SIZE, BlockDevice, VfsError, VfsResult};
use boot_info::Initrd;
use core::fmt;

/// Порция, которой копируется образ.
///
/// Побайтовое копирование здесь было бы не только медленным: память образа
/// помечена в карте как `Reserved`, а такие регионы ядро отображает с
/// [`PageFlags::DEVICE`](crate::mm::PageFlags::DEVICE). На AArch64 это
/// `Device-nGnRnE`, где невыровненный доступ даёт alignment fault, а обычный
/// `memcpy` от компилятора невыровненных обращений к источнику не избегает.
/// Поэтому чтение идёт словами по восемь байт с гарантированным выравниванием
/// (адрес образа выровнен на восемь, смещение блока кратно 512), а запись в
/// буфер вызывающего — уже без ограничений: он лежит в обычной памяти.
const WORD: usize = size_of::<u64>();

/// Сколько физической памяти видно через прямое отображение: от
/// [`PHYS_MAP_BASE`] до начала кучи. Образ выше этой границы через `phys +
/// PHYS_MAP_BASE` не адресуется — там уже куча, — и код подкачки такой регион
/// не отображает вовсе. Та же граница, что `PHYS_MAP_LIMIT` в арх-коде.
const DIRECT_MAP_WINDOW: u64 = (HEAP_BASE - PHYS_MAP_BASE) as u64;

/// Почему образ не годится в качестве блочного устройства.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum RamDiskError {
    /// Загрузчик не передал образ: нулевой адрес или нулевой размер.
    Absent,
    /// Адрес образа не выровнен на границу слова.
    Misaligned { base: u64 },
    /// Размер не кратен [`BLOCK_SIZE`].
    NotBlockMultiple { size: u64 },
    /// Образ не помещается в окно прямого отображения.
    OutOfRange { base: u64, size: u64 },
}

impl fmt::Display for RamDiskError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Absent => f.write_str("bootloader passed no filesystem image"),
            Self::Misaligned { base } => {
                write!(f, "image at {base:#018x} is not {WORD}-byte aligned")
            }
            Self::NotBlockMultiple { size } => {
                write!(f, "image size {size} is not a multiple of the {BLOCK_SIZE}-byte block")
            }
            Self::OutOfRange { base, size } => {
                write!(f, "image at {base:#018x} of {size} bytes is outside the direct map")
            }
        }
    }
}

/// Образ файловой системы в памяти, представленный как блочное устройство.
///
/// Тип копируемый, и это осознанно: всё его состояние — адрес и число блоков,
/// оба неизменны после создания, а сам образ доступен только на чтение. Копия
/// поэтому неотличима от оригинала, и владение устройством никому не мешает
/// (см. [`device`]).
///
/// # Инварианты
///
/// * `base` — адрес первого байта образа в прямом отображении, выровненный на
///   [`WORD`];
/// * от `base` доступны `blocks * BLOCK_SIZE` байт, и эта память живёт до конца
///   работы ядра и никем не изменяется.
#[derive(Debug, Clone, Copy)]
pub struct RamDisk {
    base: VirtAddr,
    blocks: u64,
}

impl RamDisk {
    /// Построить устройство поверх образа, переданного загрузчиком.
    ///
    /// Размер обязан быть кратен [`BLOCK_SIZE`], а не округляться вниз. Образ
    /// собирает `xtask`, и любой нормальный инструмент выдаёт файловую систему
    /// целым числом секторов; некратный размер означает не «файл такой», а
    /// недочитанный при загрузке хвост. Отбросив его молча, ядро смонтировало бы
    /// усечённую ФС, и проявилось бы это далеко от причины: резервная копия
    /// загрузочного сектора FAT, последний кластер файла или конец таблицы FAT
    /// прочитались бы как мусор или как `OutOfBounds` где-то в середине разбора.
    /// Отказ в момент монтирования, с размером в сообщении, показывает прямо на
    /// загрузчик.
    ///
    /// # Safety
    ///
    /// * прямое отображение физической памяти обязано быть построено и активно
    ///   (то есть вызов идёт после `AddressSpace::activate`), и покрывать весь
    ///   диапазон `[base, base + size)`;
    /// * память образа должна оставаться доступной всё время работы ядра —
    ///   загрузчик помечает её `MemoryKind::Reserved` именно поэтому, — и никто
    ///   не должен в неё писать: устройство раздаёт её содержимое как
    ///   неизменное.
    pub unsafe fn new(initrd: &Initrd) -> Result<Self, RamDiskError> {
        if !initrd.is_present() {
            return Err(RamDiskError::Absent);
        }
        let (base, size) = (initrd.base, initrd.size);
        if base % WORD as u64 != 0 {
            // На практике условие выполняется всегда: `AllocatePages` отдаёт
            // страницы, то есть адрес кратен 4096. Проверка стоит здесь ради
            // копирования словами (см. `WORD`), которое иначе оказалось бы
            // невыровненным.
            return Err(RamDiskError::Misaligned { base });
        }
        if size % BLOCK_SIZE as u64 != 0 {
            return Err(RamDiskError::NotBlockMultiple { size });
        }
        // Заодно закрывает переполнение при пересчёте в виртуальный адрес:
        // внутри окна `PHYS_MAP_BASE + base + size` заведомо не заворачивается.
        match base.checked_add(size) {
            Some(end) if end <= DIRECT_MAP_WINDOW => {}
            _ => return Err(RamDiskError::OutOfRange { base, size }),
        }

        Ok(Self {
            base: PhysAddr::new(base).to_direct_map(),
            blocks: size / BLOCK_SIZE as u64,
        })
    }

    /// Размер образа в байтах.
    #[must_use]
    pub fn size_bytes(&self) -> u64 {
        self.blocks * BLOCK_SIZE as u64
    }
}

impl BlockDevice for RamDisk {
    fn read_blocks(&self, block: u64, buf: &mut [u8]) -> VfsResult<()> {
        if buf.len() % BLOCK_SIZE != 0 {
            // Устройство блочное: половины блока у него не существует. Это
            // ошибка вызывающего, а не носителя, но паниковать из-за неё нельзя
            // — драйвер ФС считает размеры из структур на диске, которые могут
            // быть повреждены.
            return Err(VfsError::Unsupported);
        }
        let count = (buf.len() / BLOCK_SIZE) as u64;
        let end = block.checked_add(count).ok_or(VfsError::OutOfBounds)?;
        if end > self.blocks {
            return Err(VfsError::OutOfBounds);
        }

        // Умножение не переполняется: `block < blocks`, а `blocks * BLOCK_SIZE`
        // укладывалось в `u64` ещё в конструкторе; `usize` здесь 64-битный.
        let offset = block as usize * BLOCK_SIZE;
        let src = (self.base.as_usize() + offset) as *const u8;
        let dst = buf.as_mut_ptr();

        let mut done = 0usize;
        while done < buf.len() {
            // SAFETY: `done < buf.len()`, а `offset + buf.len()` не выходит за
            // образ — это только что проверено через `end > self.blocks`. Адрес
            // выровнен на восемь байт: `base` проверен в конструкторе, `offset`
            // кратен 512, `done` кратен восьми. Обращение `volatile`, чтобы
            // компилятор не собрал из соседних итераций доступ шире или уже
            // слова — память образа отображена как device-память, и там это не
            // безразлично (см. `WORD`).
            let word = unsafe { src.add(done).cast::<u64>().read_volatile() };
            // SAFETY: `buf` даёт `buf.len()` байт на запись, а `done + WORD` их
            // не превосходит — длина кратна `BLOCK_SIZE`, то есть и `WORD`.
            // Выравнивание не требуется: запись невыровненная.
            unsafe { dst.add(done).cast::<u64>().write_unaligned(word) };
            done += WORD;
        }

        Ok(())
    }

    fn write_blocks(&self, _block: u64, _buf: &[u8]) -> VfsResult<()> {
        // Образ смонтирован только на чтение намеренно; разбор причин — в
        // заголовке модуля.
        Err(VfsError::Unsupported)
    }

    fn block_count(&self) -> u64 {
        self.blocks
    }
}

/// Смонтированный RAM-диск ядра. `None`, пока не вызван [`init`].
static RAMDISK: SpinLock<Option<RamDisk>> = SpinLock::new(None);

/// Подключить образ из хэндоффа как устройство ядра.
///
/// Возвращает готовое устройство — тем же значением, которое потом отдаёт
/// [`device`], так что вызывающему не нужно повторно ходить в глобальное
/// состояние, чтобы напечатать размер.
///
/// # Safety
///
/// Условия [`RamDisk::new`]: активное прямое отображение и память образа,
/// живущая до конца работы ядра.
pub unsafe fn init(initrd: &Initrd) -> Result<RamDisk, RamDiskError> {
    // SAFETY: условие делегировано вызывающему контрактом функции.
    let disk = unsafe { RamDisk::new(initrd) }?;
    *RAMDISK.lock() = Some(disk);
    Ok(disk)
}

/// Устройство, подключённое [`init`], или `None`, если образа нет.
///
/// Отдаётся копией, а не ссылкой: описатель — два слова, и копия под локом
/// снимает вопрос о том, как выдать `&'static` из-под охранника, не удерживая
/// лок на всё время работы файловой системы.
#[must_use]
pub fn device() -> Option<RamDisk> {
    *RAMDISK.lock()
}

/// Есть ли у ядра образ, с которого можно читать.
#[must_use]
pub fn is_present() -> bool {
    device().is_some()
}
