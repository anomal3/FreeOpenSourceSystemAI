//! Кто спрашивает и что ему разрешено.
//!
//! # Модель взята у Unix целиком
//!
//! Девять бит прав, три класса — владелец, группа, остальные, — и класс
//! выбирается **первым совпавшим**, а не объединением. Это не мелочь и не
//! оптимизация: `mode 0604` означает «владельцу нельзя, остальным можно», и
//! владелец файла получит отказ. Модель, где права классов объединяются, вела
//! бы себя иначе на тех же числах — а числа эти пишет установщик и читают
//! чужие инструменты, для которых ext2 значит ровно то, что написано в его
//! спецификации.
//!
//! # Где эта проверка стоит и где не стоит
//!
//! Стоит там, где спрашивает **недоверенная сторона**: системные вызовы
//! пользовательской программы и запуск программы на исполнение. Не стоит на
//! пути кода ядра — `cat` в оболочке, файловый менеджер, чтение `/etc/passwd`
//! при загрузке идут мимо. Это не забывчивость: оболочка исполняется в самом
//! привилегированном режиме, проверять её означало бы проверять того, кто в
//! любом случае может прочитать диск сектор за сектором. Граница проходит по
//! кольцу привилегий, а не по слою кода.

use core::fmt;

use super::Metadata;

/// От чьего имени выполняется обращение.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Credentials {
    pub uid: u32,
    pub gid: u32,
}

impl Credentials {
    /// Суперпользователь.
    pub const ROOT: Self = Self { uid: 0, gid: 0 };

    #[must_use]
    pub const fn new(uid: u32, gid: u32) -> Self {
        Self { uid, gid }
    }

    /// Суперпользователь ли это.
    ///
    /// Проверяется только `uid`: группа 0 никаких особых прав не даёт, и это
    /// именно то, чего ждёт всякий, кто видел Unix.
    #[must_use]
    pub const fn is_root(self) -> bool {
        self.uid == 0
    }
}

impl fmt::Display for Credentials {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "uid {} gid {}", self.uid, self.gid)
    }
}

/// Что собираются сделать с узлом.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Access(u8);

impl Access {
    /// Ничего с самим узлом: так спрашивает `stat`, которому нужно лишь дойти
    /// до файла по каталогам, не заглядывая внутрь.
    pub const NONE: Self = Self(0);
    /// Прочитать содержимое файла или перечислить каталог.
    pub const READ: Self = Self(0b100);
    /// Записать. Спрашивается у каталога при создании и удалении имени, и у
    /// файла при открытии на запись — с тех пор, как корневой раздел перестал
    /// быть доступен только на чтение.
    pub const WRITE: Self = Self(0b010);
    /// Исполнить файл; для каталога — **пройти сквозь него** к тому, что внутри.
    ///
    /// Два смысла у одного бита достались от Unix, и второй здесь важнее
    /// первого: именно он делает каталог `0700` непроницаемым для чужого,
    /// сколько бы прав ни стояло на файлах внутри.
    pub const SEARCH: Self = Self(0b001);

    #[must_use]
    pub const fn bits(self) -> u8 {
        self.0
    }
}

impl fmt::Display for Access {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self.0 {
            0b100 => "read",
            0b010 => "write",
            0b001 => "execute or search",
            _ => "access",
        })
    }
}

/// Разрешено ли `cred` сделать `want` с узлом, у которого такие метаданные.
#[must_use]
pub fn permits(cred: Credentials, meta: &Metadata, want: Access) -> bool {
    if cred.is_root() {
        // Суперпользователь читает и пишет что угодно. Но исполнять он вправе
        // только то, у чего хоть где-то стоит бит исполнения: файл данных не
        // становится программой оттого, что его открыл root. Тем же правилом
        // живёт Linux, и оно не декоративное — оно единственное, что мешает
        // «запустить» случайно выбранный файл.
        if want == Access::SEARCH && meta.kind == super::NodeKind::File {
            return meta.mode & 0o111 != 0;
        }
        return true;
    }

    // Первый совпавший класс, а не объединение — см. заголовок модуля.
    let shift = if cred.uid == meta.uid {
        6
    } else if cred.gid == meta.gid {
        3
    } else {
        0
    };
    let allowed = (meta.mode >> shift) as u8 & 0b111;
    allowed & want.bits() == want.bits()
}
