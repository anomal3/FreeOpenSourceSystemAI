//! Кольцевой журнал ядра: то же, что печатается, ещё и запоминается.
//!
//! # Зачем он появился
//!
//! На машине с последовательной линией журнал уходит в файл и перечитывается
//! когда угодно. У телефона линии наружу нет: экран — единственное место, где
//! журнал существовал, и жил он ровно до того мига, когда экран забирает
//! рабочий стол. Всё, что печаталось после, не видел никто.
//!
//! Здесь тот же текст оседает в памяти. Его забирает [`fastboot`] по кабелю, и
//! человеку больше не нужно ловить строку снимком экрана.
//!
//! [`fastboot`]: crate::arch::aarch64::mtk_usb
//!
//! # Почему кольцо, а не «пишем, пока не кончится»
//!
//! Журнал не имеет конца: оболочка, сеть и опрос устройств печатают всё время
//! работы. Буфер, который заполняется и замолкает, хранил бы первые секунды
//! жизни машины и терял бы ровно тот кусок, ради которого его открывают, —
//! последний. Кольцо теряет старое, а старое к этому мигу уже прочитано.
//!
//! # Почему позиция считается от начала времён
//!
//! Читатель хранит не индекс в буфере, а число байт, напечатанных машиной с
//! запуска. Индекс пришлось бы сверять с моментом перезаписи, и читатель,
//! отставший на круг, тихо получил бы кашу из старого и нового. Абсолютная
//! позиция делает отставание видимым: она просто оказывается меньше самой
//! старой сохранившейся, и чтение начинается с той.

use core::fmt::{self, Write};

use crate::sync::SpinLock;

/// Ёмкость кольца.
///
/// Журнал загрузки этой машины — около четырёх килобайт. Тридцать два дают
/// запас на то, что печатается уже под рабочим столом, и стоят одной страницы
/// с небольшим в `.bss`, где нули ничего не весят и в образе.
pub const CAPACITY: usize = 32 * 1024;

struct Ring {
    bytes: [u8; CAPACITY],
    /// Сколько байт напечатано с запуска. Позиция в буфере — остаток от
    /// деления, а само число не переполняется за время жизни машины.
    written: u64,
}

static RING: SpinLock<Ring> = SpinLock::new(Ring {
    bytes: [0; CAPACITY],
    written: 0,
});

impl Ring {
    fn push(&mut self, bytes: &[u8]) {
        for &byte in bytes {
            let at = (self.written % CAPACITY as u64) as usize;
            self.bytes[at] = byte;
            self.written += 1;
        }
    }
}

/// Обёртка ради [`Write`]: `format_args!` умеет писать только в него.
struct Sink<'a>(&'a mut Ring);

impl Write for Sink<'_> {
    fn write_str(&mut self, text: &str) -> fmt::Result {
        self.0.push(text.as_bytes());
        Ok(())
    }
}

/// Запомнить то, что печатается. Не вызывать напрямую — это делает
/// [`kprintln!`](crate::kprintln).
///
/// Занятый замок означает, что печатает кто-то ещё — или что нас прервали
/// посреди записи. Строка теряется, и это верный размен: журнал существует
/// ради разбора неисправностей, а вечный цикл внутри лока — сама неисправность,
/// причём такая, после которой уже нечего разбирать.
#[doc(hidden)]
pub fn _print(args: fmt::Arguments<'_>) {
    let Some(mut ring) = RING.try_lock() else {
        return;
    };
    let _ = Sink(&mut ring).write_fmt(args);
}

/// Сколько байт напечатано с запуска.
#[must_use]
pub fn written() -> u64 {
    RING.lock().written
}

/// Самая старая позиция, которая ещё сохранилась.
#[must_use]
pub fn oldest() -> u64 {
    RING.lock().written.saturating_sub(CAPACITY as u64)
}

/// Прочитать журнал начиная с позиции `from`.
///
/// Возвращает, сколько байт положено в `out` и с какой позиции читать дальше.
/// Читатель, отставший больше чем на круг, молча переносится к самому старому
/// сохранившемуся байту: отдать ему затёртое всё равно нечего, а притвориться,
/// что там было пусто, значит соврать.
pub fn read(from: u64, out: &mut [u8]) -> (usize, u64) {
    let ring = RING.lock();
    let oldest = ring.written.saturating_sub(CAPACITY as u64);
    let mut at = from.max(oldest);
    let mut count = 0;
    while at < ring.written && count < out.len() {
        out[count] = ring.bytes[(at % CAPACITY as u64) as usize];
        count += 1;
        at += 1;
    }
    (count, at)
}
