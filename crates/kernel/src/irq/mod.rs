//! Прерывания и исключения.
//!
//! Модуль задаёт арх-независимую часть: как выглядит отказ, что делать при
//! отказе и как считаются тики таймера. Всё платформенное — таблица векторов,
//! контроллер прерываний, таймер — живёт в [`crate::arch`] и обязано
//! приводить свои события к типам отсюда.
//!
//! # Зачем это нужно именно сейчас
//!
//! До этой фазы любая ошибка обращения к памяти означала молчаливую тройную
//! ошибку и перезагрузку. Хуже всего это било по странице-ловушке под стеком:
//! механизм, поставленный ловить переполнение, сам не мог о нём сообщить.
//! Обработчик отказов превращает такие случаи в внятное сообщение с адресом.

pub mod fault;

use core::sync::atomic::{AtomicU64, Ordering};

/// Частота системного таймера. 100 Гц — компромисс: достаточно мелкое зерно для
/// планировщика в следующей фазе и достаточно редкие прерывания, чтобы их
/// обработка не съедала заметную долю времени под эмуляцией.
pub const TIMER_HZ: u32 = 100;

static TICKS: AtomicU64 = AtomicU64::new(0);

/// Счётчик тиков с момента запуска таймера.
#[must_use]
pub fn ticks() -> u64 {
    TICKS.load(Ordering::Relaxed)
}

/// Сколько миллисекунд прошло с запуска таймера.
#[must_use]
pub fn uptime_ms() -> u64 {
    ticks() * 1000 / u64::from(TIMER_HZ)
}

/// Вызывается арх-обработчиком таймера на каждом тике.
///
/// Держать эту функцию короткой существенно: она исполняется с запрещёнными
/// прерываниями, и всё, что здесь затянется, отложит остальную систему. Поэтому
/// планировщик здесь только считает квант — переключение задач откладывается до
/// [`preempt_point`].
pub fn on_timer_tick() {
    TICKS.fetch_add(1, Ordering::Relaxed);
    crate::sched::on_timer_tick();
}

/// Вызывается арх-обработчиком в конце внешнего прерывания — и **только** после
/// того, как прерывание подтверждено контроллеру.
///
/// `from_user` — исполнялся ли прерванный код в третьем кольце (EL0).
///
/// Здесь происходят обе вещи, которые ядро делает не «по ходу», а на границе
/// возврата из ловушки, и обе по одной причине: в этой точке заведомо нет ни
/// удерживаемого лока, ни начатой и не законченной работы.
///
/// * **Снятие программы** ([`crate::user::check_kill`]) — только при
///   `from_user`: доказательством того, что кадр входа в третье кольцо цел,
///   служит сам факт, что ловушка пришла оттуда. Не возвращается, если снятие
///   состоялось.
/// * **Вытеснение** ([`crate::sched::preempt_point`]) — если у задачи кончился
///   квант.
///
/// Требование к порядку относительно подтверждения не формальность: до него
/// прерывание остаётся активным и закрывает собой всё, что не выше его
/// приоритета, а уход в другую задачу унёс бы подтверждение с собой — и таймер
/// замолчал бы, пока управление случайно не вернулось бы в покинутый
/// обработчик. Разбор — в заголовке [`crate::sched`].
///
/// Вызывается в конце **любого** внешнего прерывания, а не только таймерного:
/// флаги всё равно поднимает кто-то другой, а лишняя проверка атомика стоит
/// дешевле, чем правило «в этих обработчиках звать, а в тех нет».
pub fn on_trap_return(from_user: bool) {
    if from_user {
        // SAFETY: `from_user` означает, что прерванный код исполнялся в третьем
        // кольце, то есть `enter_user` этой задачи действительно исполняется.
        unsafe { crate::user::check_kill() };
    }
    crate::sched::preempt_point();
}
