//! Отчёты HID → события ввода.
//!
//! # Два способа узнать, что лежит в отчёте
//!
//! **Boot protocol.** Формат задан спецификацией: восемь байт у клавиатуры, три
//! у мыши, и знать про устройство больше ничего не нужно. Так работали и
//! работают все устройства, которые должны отвечать в меню загрузки.
//!
//! **Report descriptor.** Устройство описывает свои отчёты само, и его описание
//! приходится разбирать (крейт [`usb_hid`]). Дороже, но иначе не читается
//! ничего, кроме двух перечисленных случаев, — а планшет, который VirtualBox
//! предлагает вместо мыши, boot-протокола не объявляет вовсе.
//!
//! Разница между ними кончается здесь: [`Keyboard`] и [`Mouse`] в обоих случаях
//! получают отчёт и приводят его к событиям одинаково. Карта, если она есть,
//! лишь переводит байты в те же величины, что boot-протокол даёт даром.

use usb_hid::{KeyboardMap, Motion, PointerMap};

use crate::input::{Buttons, KeyCode, post, post_pointer, post_pointer_at};
use crate::usb::key_for_usage;

/// Длина отчёта boot-протокола клавиатуры.
pub const REPORT_LEN: usize = 8;

/// Сколько клавиш вмещает отчёт.
const KEYS_IN_REPORT: usize = 6;

/// Смещение первой клавиши.
const KEYS_OFFSET: usize = 2;

/// Модификаторы в байте 0 и соответствующие им клавиши. Порядок — из
/// спецификации: биты идут слева направо от левого Ctrl к правому Meta.
const MODIFIERS: [KeyCode; 8] = [
    KeyCode::LeftCtrl,
    KeyCode::LeftShift,
    KeyCode::LeftAlt,
    KeyCode::LeftMeta,
    KeyCode::RightCtrl,
    KeyCode::RightShift,
    KeyCode::RightAlt,
    KeyCode::RightMeta,
];

/// Состояние клавиатуры: последний разобранный отчёт.
///
/// # Что присылает клавиатура
///
/// Восемь байт (HID 1.11, приложение B.1):
///
/// ```text
///   байт 0   битовая карта модификаторов
///   байт 1   зарезервирован
///   байт 2-7 до шести usage ID нажатых клавиш, 0 — пусто
/// ```
///
/// Клавиатура, описанная собственным дескриптором, присылает то же самое, но по
/// другим смещениям и, возможно, с номером отчёта впереди; приведением занимается
/// [`KeyboardMap::decode`], и дальше по коду разницы уже нет.
///
/// # Почему нужно сравнение с прошлым отчётом
///
/// Отчёт сообщает **состояние**, а не событие: «сейчас нажаты A и Shift». О том,
/// что клавишу отпустили, клавиатура не сообщает никак — она просто перестаёт её
/// упоминать. Значит нажатия и отпускания приходится вычислять сравнением двух
/// последовательных отчётов, и хранение предыдущего — не оптимизация, а
/// единственный способ вообще узнать об отпускании.
///
/// Порядок клавиш в отчёте при этом произволен: спецификация разрешает
/// клавиатуре перекладывать их между отчётами, поэтому сравнивать надо
/// множества, а не позиции. Отсюда поиск по массиву, а не поэлементное сравнение
/// — на шести элементах это дешевле любой хеш-таблицы.
///
/// # Потерянные отчёты
///
/// Если отчёт потерян (переполнилась очередь событий, задача не успела), одно
/// отпускание пропадёт, и клавиша останется «нажатой» до следующего отчёта, в
/// котором её нет. Сравнение состояний это само и исправит на следующем же
/// отчёте — в отличие от потока событий, где потеря «отпустили» залипает
/// навсегда.
pub struct Keyboard {
    /// Карта отчёта; `None` — устройство говорит на boot-протоколе.
    map: Option<KeyboardMap>,
    /// Битовая карта модификаторов из прошлого отчёта.
    modifiers: u8,
    /// Usage ID клавиш из прошлого отчёта.
    keys: [u8; KEYS_IN_REPORT],
    /// Сколько отчётов разобрано — для диагностики.
    reports: u64,
}

impl Keyboard {
    /// Клавиатура boot-протокола.
    #[must_use]
    pub const fn boot() -> Self {
        Self { map: None, modifiers: 0, keys: [0; KEYS_IN_REPORT], reports: 0 }
    }

    /// Клавиатура, разобранная по собственному дескриптору.
    #[must_use]
    pub const fn described(map: KeyboardMap) -> Self {
        Self { map: Some(map), modifiers: 0, keys: [0; KEYS_IN_REPORT], reports: 0 }
    }

    /// Сколько отчётов пришло с момента запуска.
    #[must_use]
    pub const fn reports(&self) -> u64 {
        self.reports
    }

    /// Разобрать отчёт и отправить события в подсистему ввода.
    ///
    /// Короткий отчёт игнорируется целиком: разобрать половину — значит выдать
    /// отпускание клавиш, о которых устройство ничего не сказало.
    pub fn handle_report(&mut self, report: &[u8]) {
        let report = match self.map {
            Some(map) => match map.decode(report) {
                Some(bytes) => bytes,
                // Отчёт с чужим номером — это отчёт другой части устройства, а
                // не потерянные клавиши: разбирать его нашей картой нельзя.
                None => return,
            },
            None => {
                if report.len() < REPORT_LEN {
                    return;
                }
                let mut bytes = [0u8; REPORT_LEN];
                bytes.copy_from_slice(&report[..REPORT_LEN]);
                bytes
            }
        };
        self.reports += 1;

        let modifiers = report[0];
        let changed = modifiers ^ self.modifiers;
        for (bit, code) in MODIFIERS.iter().enumerate() {
            let mask = 1u8 << bit;
            if changed & mask != 0 {
                post(*code, modifiers & mask != 0);
            }
        }
        self.modifiers = modifiers;

        let mut keys = [0u8; KEYS_IN_REPORT];
        keys.copy_from_slice(&report[KEYS_OFFSET..KEYS_OFFSET + KEYS_IN_REPORT]);

        // Отпускания — первыми. Порядок виден потребителю: если клавишу
        // отпустили и в том же отчёте нажали другую, естественнее увидеть
        // «отпустили, нажали», чем наоборот.
        for old in self.keys {
            if old != 0 && !keys.contains(&old) {
                if let Some(code) = key_for_usage(old) {
                    post(code, false);
                }
            }
        }
        for new in keys {
            if new != 0 && !self.keys.contains(&new) {
                if let Some(code) = key_for_usage(new) {
                    post(code, true);
                }
            }
        }

        self.keys = keys;
    }
}

impl Default for Keyboard {
    fn default() -> Self {
        Self::boot()
    }
}

/// Наименьшая длина отчёта мыши boot-протокола.
pub const MOUSE_REPORT_LEN: usize = 3;

/// Указатель: мышь boot-протокола либо любое устройство, описавшее себя само.
///
/// # Что присылает мышь boot-протокола
///
/// Три байта (HID 1.11, приложение B.2):
///
/// ```text
///   байт 0   битовая карта кнопок: 0 — левая, 1 — правая, 2 — средняя
///   байт 1   смещение по X, знаковое
///   байт 2   смещение по Y, знаковое; положительное — **вниз**
/// ```
///
/// Четвёртый байт с колесом спецификацией boot-протокола не предусмотрен, но
/// его шлют почти все мыши, включая эмулируемую QEMU. Читается, если он есть:
/// требовать ровно три байта значило бы выбрасывать колесо у всех.
///
/// # Здесь не нужно сравнение с прошлым отчётом
///
/// В отличие от клавиатуры, мышь сообщает **событие**, а не состояние: смещение
/// с прошлого отчёта. Помнить нужно только кнопки — про отпускание мышь тоже
/// молчит, она просто перестаёт упоминать кнопку в битовой карте, — и помнит их
/// очередь событий, а не драйвер.
///
/// # Ось Y
///
/// В HID положительное смещение по Y — это вниз, и совпадает с направлением
/// строк экрана. Никакого переворота здесь нет и быть не должно; ошибка «мышь
/// ездит наоборот» рождается из попытки этот переворот добавить.
pub struct Mouse {
    /// Карта отчёта; `None` — устройство говорит на boot-протоколе.
    map: Option<PointerMap>,
    /// Сколько отчётов разобрано — для диагностики.
    reports: u64,
}

impl Mouse {
    /// Мышь boot-протокола.
    #[must_use]
    pub const fn boot() -> Self {
        Self { map: None, reports: 0 }
    }

    /// Указатель, разобранный по собственному дескриптору.
    #[must_use]
    pub const fn described(map: PointerMap) -> Self {
        Self { map: Some(map), reports: 0 }
    }

    #[must_use]
    pub const fn reports(&self) -> u64 {
        self.reports
    }

    /// Разобрать отчёт и отправить событие в подсистему ввода.
    pub fn handle_report(&mut self, report: &[u8]) {
        if let Some(map) = self.map {
            let Some(decoded) = map.decode(report) else {
                return;
            };
            self.reports += 1;
            // Крейт разбора не знает про подсистему ввода и отдаёт кнопки
            // битовой картой — в том же порядке, в каком их кладёт в свой байт
            // boot-протокол. Поэтому перевод здесь один и тот же для обоих
            // путей.
            let buttons = Buttons::from_bits(decoded.buttons);
            match decoded.motion {
                Motion::Relative { dx, dy } => {
                    post_pointer(dx, dy, decoded.wheel, buttons);
                }
                // Планшет сообщает точку, а не сдвиг, и превратить одно в другое
                // здесь нельзя: для этого надо знать, где курсор, — то есть
                // знать размер экрана, чего драйверу знать не положено.
                Motion::Absolute { x, y } => {
                    post_pointer_at(x, y, decoded.wheel, buttons);
                }
            }
            return;
        }

        if report.len() < MOUSE_REPORT_LEN {
            return;
        }
        self.reports += 1;

        let buttons = Buttons::from_bits(report[0]);
        let dx = i32::from(report[1] as i8);
        let dy = i32::from(report[2] as i8);
        let wheel = report.get(3).map_or(0, |byte| i32::from(*byte as i8));

        // Отчёт без движения и без изменения кнопок отправлять не нужно, но
        // проверять это здесь нельзя: изменились кнопки или нет, знает очередь —
        // она хранит их прошлое состояние. Поэтому пустым считается только
        // полностью нулевой отчёт при отпущенных кнопках, а решение о том,
        // что изменилось, принимает `post_pointer`.
        post_pointer(dx, dy, wheel, buttons);
    }
}

impl Default for Mouse {
    fn default() -> Self {
        Self::boot()
    }
}
