//! Кому эта машина верит, когда ей приносят обновление.
//!
//! # Ключи лежат в образе, а не в ядре
//!
//! Файл `/os-keys` — часть **корневого образа**, рядом с `/os-release`, и по той
//! же причине: оба описывают образ, а не машину, и оба заменяются вместе с ним.
//! Отсюда свойство, ради которого всё и устроено так: новая версия может
//! принести новый рабочий ключ, а старой не нужно знать о нём заранее.
//!
//! `/etc` для этого не годится, хотя выглядит подходящим местом: он живёт на
//! разделе состояния, обновление до него не дотягивается, и ключ, положенный
//! туда однажды, остался бы там навсегда.
//!
//! Ключи не вкомпилированы в ядро и по второй причине, приземлённой: закрытая
//! половина тогда обязана была бы существовать до сборки ядра — то есть лежать
//! в репозитории. Закрытый ключ в открытом репозитории — это закрытый ключ,
//! которого больше нет, и цена здесь выше, чем у любого другого: им
//! подписывается система, которую машина запишет себе в корень.
//!
//! # Формат
//!
//! Текст, по строке на ключ: `ed25519 <64 шестнадцатеричных знака> <комментарий>`.
//! Пустые строки и строки с `#` пропускаются. Формат текстовый намеренно —
//! читать его будет и человек, спросивший «а чьи обновления берёт эта машина».
//!
//! # Пустой список — это отказ, а не разрешение
//!
//! Машина без `/os-keys` не обновляется вовсе. Это единственное безопасное
//! умолчание: «ключей нет, значит проверять нечего, значит ставим» — ровно та
//! ошибка, ради которой подпись и заводится.

use alloc::vec::Vec;

use crate::fs;

/// Где лежат доверенные ключи.
const PATH: &str = "/os-keys";

/// Сколько байт файла ядро согласно прочитать.
///
/// Четыре килобайта — это около полусотни ключей; больше означает не «много
/// ключей», а не тот файл.
const LIMIT: usize = 4 * 1024;

/// Имя алгоритма в файле.
const ALGORITHM: &str = "ed25519";

/// Прочитать доверенные ключи. Пустой список — обновления запрещены.
#[must_use]
pub fn keys() -> Vec<[u8; 32]> {
    let mut out = Vec::new();
    // Читается **мимо проверки прав**, и это то же рассуждение, что у
    // `/etc/passwd`: спрашивает ядро, а не программа, и права здесь ни при чём.
    let Some(Ok((bytes, _))) = fs::read(PATH, LIMIT) else {
        return out;
    };
    let Ok(text) = core::str::from_utf8(&bytes) else {
        return out;
    };

    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.split_whitespace();
        if fields.next() != Some(ALGORITHM) {
            // Ключ другого вида — не ошибка файла, а ключ, который эта система
            // не умеет проверять. Пропускается молча, как и в `authorized_keys`.
            continue;
        }
        let Some(encoded) = fields.next() else {
            continue;
        };
        if let Some(key) = parse_hex(encoded) {
            // Место в списке резервируется заранее: отказ выделения посреди
            // разбора оставил бы половину ключей, то есть машину, которая
            // отвергает своё же обновление.
            if out.try_reserve(1).is_err() {
                return Vec::new();
            }
            out.push(key);
        }
    }
    out
}

/// Сходится ли подпись хоть с одним из доверенных ключей.
///
/// Перебор, а не поиск по идентификатору: ключей два (рабочий и запасной), и
/// поле «каким ключом подписано» в контейнере было бы подсказкой злоумышленнику
/// и лишним разбором для нас. Две проверки Ed25519 стоят миллисекунды.
#[must_use]
pub fn verifies(digest: &[u8; 32], signature: &[u8], keys: &[[u8; 32]]) -> bool {
    use ed25519_dalek::{Signature, Verifier, VerifyingKey};

    if signature.len() != 64 {
        return false;
    }
    let mut bytes = [0u8; 64];
    bytes.copy_from_slice(signature);
    let signature = Signature::from_bytes(&bytes);

    keys.iter().any(|key| {
        VerifyingKey::from_bytes(key)
            .map(|verifying| verifying.verify(digest, &signature).is_ok())
            .unwrap_or(false)
    })
}

/// Разобрать 32 байта, записанные шестнадцатеричными цифрами.
fn parse_hex(text: &str) -> Option<[u8; 32]> {
    if text.len() != 64 {
        return None;
    }
    let bytes = text.as_bytes();
    let mut out = [0u8; 32];
    for (at, pair) in bytes.chunks_exact(2).enumerate() {
        out[at] = (digit(pair[0])? << 4) | digit(pair[1])?;
    }
    Some(out)
}

const fn digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}
