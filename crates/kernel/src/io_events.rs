//! Общий счётчик событий ввода-вывода: «что-то стало готово» (фаза 65a).
//!
//! # Зачем
//!
//! Сокет-дескриптор ждёт — данных, места, соединения, — а `SYS_POLL` ждёт
//! сразу многого: сокетов, каналов, терминала. Своих очередей ожидания у
//! источников нет, и до фазы 65a `poll` просыпался раз в 100 мс, чтобы
//! посмотреть снова. Здесь — одно поколение на всю систему: всякий, у кого
//! что-то стало готово (сетевая задача, канал), увеличивает его и будит
//! ждущих; ждущий запоминает поколение, проверяет свои источники и засыпает,
//! только если поколение с тех пор не сменилось.
//!
//! Будятся при этом все ждущие, а не те, кого событие касается, — и это
//! осознанно: ждущих единицы, проверка дешёвая, а очередь на каждый источник
//! — это ещё одно место, где пробуждение может потеряться.
//!
//! # Почему без потерь
//!
//! Условие «поколение то же» проверяется под замком планировщика
//! ([`crate::sched::block_on_futex`]): событие, случившееся между проверкой
//! источников и засыпанием, сменило поколение, и задача не уснёт.

use core::sync::atomic::{AtomicU64, Ordering};

/// Поколение событий.
static GENERATION: AtomicU64 = AtomicU64::new(0);

/// Ключ ожидания: адрес счётчика. Адреса ядра лежат в верхней половине и с
/// ключами программ (физическими адресами их слов) не пересекаются.
fn key() -> usize {
    core::ptr::addr_of!(GENERATION) as usize
}

/// Нынешнее поколение — запомнить **до** проверки источников.
#[must_use]
pub fn generation() -> u64 {
    GENERATION.load(Ordering::Acquire)
}

/// Что-то стало готово: сменить поколение и разбудить ждущих.
///
/// Из обработчика прерывания не звать: пробуждение берёт замок планировщика.
pub fn notify() {
    GENERATION.fetch_add(1, Ordering::AcqRel);
    crate::sched::wake_futex(key(), 0);
}

/// Уснуть, пока поколение равно `seen`, но не дольше `until` (мс работы
/// системы). Проснувшийся проверяет свои источники сам: пробуждение значит
/// «что-то случилось», а не «случилось твоё».
pub fn wait(seen: u64, until: Option<u64>) {
    crate::sched::block_on_futex(key(), until, || GENERATION.load(Ordering::Acquire) != seen);
}
