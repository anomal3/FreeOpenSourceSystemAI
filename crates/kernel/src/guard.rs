//! Канарейка стека у самого ядра.
//!
//! У программ в ring-3 она есть с пункта 1 очереди второго разбора: эталон
//! кладёт ядро в страницу процесса, доступную только на чтение. У ядра такого
//! «кого-то снаружи» нет — класть эталон некому, кроме него самого, и в этом
//! вся разница между двумя канарейками.
//!
//! # Почему эталон сначала константа, а потом случайное число
//!
//! Компилятор ставит проверку в каждую функцию со стековым массивом, и первая
//! такая функция вызывается задолго до того, как в системе появляется хоть
//! какая-то случайность: пул набирает её из дрожания прерываний, а прерывания
//! включаются на середине загрузки. Эталона, которого нет, не бывает — было бы
//! чтение нуля, то есть канарейка, которую подделает переполнение нулями.
//!
//! Поэтому эталон — константа в `.data`, и она **однажды** заменяется на
//! случайную. Цена названа: функции, отработавшие до замены, защищены
//! известным значением. Это разбор загрузочных структур — карты памяти, таблиц
//! ACPI, дерева устройств, — и чужих байтов среди них нет ни одного: всё это
//! оставила прошивка той же машины. Байты из сети, с диска и из файлов
//! приходят позже, когда эталон уже случаен.
//!
//! # Главная ловушка: кто именно меняет эталон
//!
//! Замена происходит **между** прологом и эпилогом той функции, которая её
//! делает: пролог положил в кадр старое значение, эпилог сверит его с новым и
//! объявит переполнение, которого не было. Значит, менять эталон не вправе ни
//! одна функция, которая **возвращается**.
//!
//! Отсюда всё устройство модуля:
//!
//! - [`fresh`] только считает значение и возвращает его. Канарейка у неё есть,
//!   и это правильно: и пролог, и эпилог видят ещё старый эталон.
//! - [`arm`] пишет эталон и **не имеет пролога вовсе** — это голая функция из
//!   двух команд ассемблера (`#[unsafe(naked)]`, как [`crate::arch`] делает
//!   переключение контекста). Не «функция, у которой канарейки не оказалось»,
//!   а функция, у которой её не может быть; попытка обойтись обычной
//!   написанной на Rust показала ровно обратное — компилятор поставил проверку
//!   и туда.
//! - Звать [`arm`] может только тот, кто сам не возвращается. Сегодня это
//!   `resume_on_kernel_stack`, уходящий в планировщик.
//!
//! # Почему вокруг замены выключаются прерывания
//!
//! По той же причине, что и выше, но для чужого кадра: обработчик, пролог
//! которого успел прочитать старый эталон, а эпилог прочитал бы новый, объявил
//! бы переполнение на ровном месте. Окно — несколько команд, но тик таймера
//! приходит и в него. Второго процессора в этот момент ещё нет: `smp::start`
//! идёт заметно позже, и это не совпадение, а условие.

use core::arch::naked_asm;
use core::sync::atomic::{AtomicBool, Ordering};

/// Эталон канарейки — тот самый символ, который ищет компилятор.
///
/// Значение до замены выбрано не «красивое»: младший байт — ноль
/// (канарейка-терминатор, на ней останавливается всё, что копирует строку до
/// нуля), остальные байты непечатны и не похожи ни на длину, ни на указатель,
/// ни на счётчик — то есть не появятся в кадре сами собой.
#[unsafe(no_mangle)]
pub static mut __stack_chk_guard: usize = 0x9e3f_a7c1_5bd2_8400;

/// Заменён ли эталон на случайный.
static ARMED: AtomicBool = AtomicBool::new(false);

/// Посчитать новое значение эталона. Возвращает его и источник случайности.
///
/// Здесь эталон только считается, но не ставится: ставить его функция, которая
/// возвращается, не вправе — см. заголовок модуля.
pub fn fresh() -> (usize, crate::random::Source) {
    let mut bytes = [0u8; core::mem::size_of::<usize>()];
    let source = crate::random::fill(&mut bytes);
    // Младший байт — ноль, по той же причине, что и у константы выше.
    (usize::from_ne_bytes(bytes) & !0xff, source)
}

/// Записать эталон. **У функции нет ни пролога, ни эпилога** — она голая.
///
/// # Safety
///
/// Звать разрешено ровно из функции, которая **не возвращается**, ровно один
/// раз и с выключенными прерываниями. Нарушение любого из трёх условий даёт не
/// порчу памяти, а ложное срабатывание канарейки — то есть панику ядра на
/// исправном коде, и найти её причину по сообщению будет нечем.
#[cfg(target_arch = "x86_64")]
#[unsafe(naked)]
pub unsafe extern "sysv64" fn arm(value: usize) {
    naked_asm!(
        "mov qword ptr [rip + {guard}], rdi",
        "ret",
        guard = sym __stack_chk_guard,
    )
}

/// То же на AArch64: адрес собирается парой `adrp`/`add` — образ
/// позиционно-независим, и абсолютного адреса у переменной нет.
///
/// # Safety
///
/// Те же три условия, что и у варианта для x86-64.
#[cfg(target_arch = "aarch64")]
#[unsafe(naked)]
pub unsafe extern "C" fn arm(value: usize) {
    naked_asm!(
        "adrp x1, {guard}",
        "add x1, x1, :lo12:{guard}",
        "str x0, [x1]",
        "ret",
        guard = sym __stack_chk_guard,
    )
}

/// Отметить, что эталон заменён. Отдельно от [`arm`]: у голой функции нет
/// места, куда это дописать, а сама отметка — обычный атомик.
pub fn mark_armed() {
    ARMED.store(true, Ordering::Relaxed);
}

/// Заменён ли эталон на случайный.
#[must_use]
pub fn is_armed() -> bool {
    ARMED.load(Ordering::Relaxed)
}

/// Компилятор зовёт это, когда канарейка в кадре не совпала с эталоном.
///
/// Паника, а не возврат с ошибкой: кадр уже испорчен, адрес возврата лежит в
/// нём рядом с канарейкой, и «аккуратно вернуться» отсюда означало бы вернуться
/// туда, куда написал тот, кто это устроил. Значение эталона в сообщение не
/// попадает — напечатать его значило бы раздать его всякому, кто читает
/// журнал, то есть отменить.
#[unsafe(no_mangle)]
pub extern "C" fn __stack_chk_fail() -> ! {
    panic!("stack smashing detected in the kernel");
}
