/// Сколько задач помещается в таблицу.
///
/// Таблица фиксированного размера, а не `Vec`, сознательно: `Vec` при росте
/// переносит содержимое, а планировщик держит сырые указатели на `Context`
/// задач — и, что важнее, `Vec::push` паникует при нехватке памяти, тогда как
/// [`spawn`] обязан вернуть ошибку. `Box` внутри слота решает первую проблему
/// (переезжает указатель, а не сама задача), фиксированный размер — вторую.
pub const MAX_TASKS: usize = 32;

/// Слот холостой задачи.
const IDLE_SLOT: usize = 0;

/// Длина кванта в тиках таймера. При `TIMER_HZ = 100` это 50 мс — заметно
/// больше, чем стоит переключение, и заметно меньше, чем человек замечает.
const SLICE_TICKS: u32 = 5;

/// Длина кванта в миллисекундах — то же число, но в единицах, которые понимает
/// читающий журнал загрузки.
pub const SLICE_MS: u64 = SLICE_TICKS as u64 * 1000 / crate::irq::TIMER_HZ as u64;

/// Разрешено ли вытеснение по таймеру.
///
/// Отдельный флаг, а не `const`: включение вытеснения — это изменение
/// поведения, которое надо уметь откатить в рантайме, когда что-то пойдёт не
/// так. По умолчанию выключено — до [`run`] переключаться всё равно не на что,
/// а загрузка идёт в одном потоке управления; включает его [`set_preemption`].
static PREEMPTION: AtomicBool = AtomicBool::new(false);

/// Истёк ли квант текущей задачи.
///
/// Флаг, а не немедленное переключение: поднимает его обработчик таймера,
/// разбирает — [`preempt_point`] в конце прерывания. Почему именно так, см.
/// «Вытеснение» в заголовке модуля.
static NEED_RESCHED: AtomicBool = AtomicBool::new(false);

/// Почему происходит переключение.
///
/// Различие нужно ровно для одного: счётчика снятий не по своей воле. Он и есть
/// то, чем вытеснение вообще можно наблюдать снаружи — у программы, не делающей
/// системных вызовов, других поводов сменить задачу не существует.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Cause {
    /// Задача уступила процессор сама: `yield`, ожидание, завершение.
    Voluntary,
    /// У задачи кончился квант.
    Preempted,
}

/// Всё изменяемое состояние планировщика.
struct Scheduler {
    tasks: [Option<Box<Task>>; MAX_TASKS],
    /// Слот исполняющейся задачи.
    current: usize,
    /// Откуда брать следующий идентификатор. Не совпадает с номером слота:
    /// слоты переиспользуются, идентификаторы — нет.
    next_id: u32,
    /// Сколько всего было переключений контекста.
    switches: u64,
    /// Сколько из них произошло не по воле задачи, а по истёкшему кванту.
    forced: u64,
    /// Сколько тиков таймера застали холостую задачу, то есть прошли впустую.
    idle_ticks: u64,
    /// Сколько тиков осталось текущей задаче до конца кванта.
    slice_left: u32,
    /// Запущено ли планирование. До [`run`] переключаться не на что и не с чего.
    running: bool,
}

static SCHED: SpinLock<Scheduler> = SpinLock::new(Scheduler::new());

impl Scheduler {
    const fn new() -> Self {
        Self {
            tasks: [const { None }; MAX_TASKS],
            current: IDLE_SLOT,
            next_id: 1,
            switches: 0,
            forced: 0,
            idle_ticks: 0,
            slice_left: SLICE_TICKS,
            running: false,
        }
    }

    /// Куда положить новую задачу.
    ///
    /// Сначала пустой слот, потом — самый давний из завершённых. Второй проход
    /// появился вместе с программами-задачами: раньше задачи заводились по
    /// одному разу при загрузке, а теперь каждая команда `run` создаёт новую, и
    /// таблица из тридцати двух слотов кончилась бы на тридцать второй
    /// программе. Завершённая задача при этом теряется из списка `tasks` — цена
    /// за то, чтобы система не переставала запускать программы.
    fn free_slot(&self) -> Option<usize> {
        // Слот 0 не предлагается: он принадлежит холостой задаче.
        if let Some(empty) = (1..MAX_TASKS).find(|&i| self.tasks[i].is_none()) {
            return Some(empty);
        }
        (1..MAX_TASKS)
            .filter(|&i| {
                self.tasks[i]
                    .as_ref()
                    .is_some_and(|task| task.state == TaskState::Finished)
            })
            .min_by_key(|&i| self.tasks[i].as_ref().map_or(u32::MAX, |task| task.id.as_u32()))
    }

    /// Кого исполнять следующим.
    ///
    /// Round-robin: обход от слота за текущим по кругу, первая готовая задача
    /// побеждает. Текущая задача в обход не входит (`1..MAX_TASKS`, а не
    /// `1..=MAX_TASKS`) — переключение «сам в себя» сохранило бы контекст в тот
    /// же адрес, куда тут же его и восстановило бы, что в лучшем случае
    /// бессмысленно, а в общем случае зависит от того, как арх-слой упорядочил
    /// сохранение и восстановление.
    ///
    /// `None` означает «оставить всё как есть».
    fn pick_next(&self) -> Option<usize> {
        for step in 1..MAX_TASKS {
            let slot = (self.current + step) % MAX_TASKS;
            if slot == IDLE_SLOT {
                continue;
            }
            if let Some(task) = &self.tasks[slot] {
                if task.state == TaskState::Ready {
                    return Some(slot);
                }
            }
        }
        // Готовых задач нет. Если мы не в холостой — вернуться в неё: именно так
        // `run()` узнаёт, что работа кончилась. Если уже в ней — переключаться
        // некуда и незачем.
        if self.current == IDLE_SLOT { None } else { Some(IDLE_SLOT) }
    }

    /// Разбудить всех, чей срок ожидания вышел.
    ///
    /// Проход по всей таблице на каждом переключении — это тридцать два
    /// сравнения, то есть заметно дешевле одного обращения к памяти мимо кеша.
    /// Очередь по срокам здесь была бы структурой данных ради структуры данных:
    /// её пришлось бы поддерживать в каждом пробуждении, а выигрыш начинается с
    /// сотен задач.
    ///
    /// Возвращает `true`, если кто-то проснулся.
    fn wake_expired(&mut self, now: u64) -> bool {
        let mut woke = false;
        for task in self.tasks.iter_mut().flatten() {
            let due = match task.state {
                TaskState::Blocked(Wait::Until(tick) | Wait::Input(tick)) => now >= tick,
                _ => false,
            };
            if due {
                task.state = TaskState::Ready;
                woke = true;
            }
        }
        woke
    }

    /// Разбудить тех, кто ждал завершения задачи `id`.
    fn wake_waiters(&mut self, id: TaskId) {
        for task in self.tasks.iter_mut().flatten() {
            if task.state == TaskState::Blocked(Wait::Task(id)) {
                task.state = TaskState::Ready;
            }
        }
    }

    /// Освободить стеки завершённых задач.
    ///
    /// Текущая задача пропускается — и это не оптимизация, а условие
    /// корректности: если завершившаяся задача ещё исполняется (а она исполняется
    /// ровно до конца своего последнего `switch_context`), её стек — та самая
    /// земля под ногами.
    ///
    /// Возвращает число освобождённых стеков.
    fn reap(&mut self) -> usize {
        let current = self.current;
        let mut freed = 0;
        for (slot, entry) in self.tasks.iter_mut().enumerate() {
            if slot == current {
                continue;
            }
            if let Some(task) = entry {
                if task.state == TaskState::Finished && task.stack.is_some() {
                    // Вот здесь и происходит освобождение: `Drop for Stack`
                    // возвращает блок куче.
                    task.stack = None;
                    freed += 1;
                }
            }
        }
        freed
    }

    /// Сколько задач (не считая холостой и служебных) ещё не завершились.
    ///
    /// Служебные не считаются, и это не деталь учёта: по этому числу [`run`]
    /// решает, что работы больше нет и машину пора остановить. Задача опроса
    /// USB не заканчивается никогда — считай её, и `exit` перестал бы
    /// останавливать систему.
    fn alive(&self) -> usize {
        self.tasks
            .iter()
            .enumerate()
            .filter(|(slot, entry)| {
                *slot != IDLE_SLOT
                    && entry
                        .as_ref()
                        .is_some_and(|t| !t.daemon && t.state != TaskState::Finished)
            })
            .count()
    }
}

/// Создать задачу.
///
/// `entry` — обычная `fn()`, которой позволено вернуться: возврат перехватит
/// [`trampoline`].
///
/// # Ошибки
///
/// [`SpawnError::OutOfMemory`] при нехватке кучи (под стек или под саму задачу),
/// [`SpawnError::TooManyTasks`] при исчерпании таблицы. Паники нет ни в одном из
/// путей: не сумев создать задачу, ядро продолжает работать с уже созданными.
pub fn spawn(name: &'static str, entry: fn()) -> Result<TaskId, SpawnError> {
    // Точка входа уезжает батуту аргументом: `Context::new` умеет передать
    // ровно одно машинное слово, а `fn()` в него помещается целиком.
    spawn_raw(name, TASK_STACK_SIZE, trampoline, entry as usize)
}

/// Создать служебную задачу — ту, которая работает, пока работает система, и
/// сама по себе поводом ей работать не является.
///
/// Отличается от [`spawn`] ровно этим: [`alive`] её не считает, и `exit`
/// останавливает машину, не дожидаясь её завершения — которого и не будет.
///
/// # Ошибки
///
/// Те же, что у [`spawn`].
pub fn spawn_daemon(name: &'static str, entry: fn()) -> Result<TaskId, SpawnError> {
    let id = spawn(name, entry)?;
    let mut sched = SCHED.lock();
    if let Some(task) = sched.tasks.iter_mut().flatten().find(|task| task.id == id) {
        task.daemon = true;
    }
    Ok(id)
}

/// Создать задачу с собственной точкой входа и своим размером стека.
///
/// Нужно программам вне ядра: их точка входа не возвращается вовсе (она сама
/// завершает задачу), а стека им требуется заметно больше — на нём лежит и
/// разбор ELF, и кадр входа в третье кольцо, и весь системный вызов вместе с
/// выводом в окно оболочки.
///
/// # Ошибки
///
/// [`SpawnError::OutOfMemory`] при нехватке кучи (под стек или под саму задачу),
/// [`SpawnError::TooManyTasks`] при исчерпании таблицы. Паники нет ни в одном из
/// путей.
pub fn spawn_raw(
    name: &'static str,
    stack_size: usize,
    entry: extern "C" fn(usize) -> !,
    arg: usize,
) -> Result<TaskId, SpawnError> {
    // Стек выделяется до захвата лока: аллокатор кучи при отказе печатает
    // многострочную диагностику, и делать это, удерживая лок планировщика,
    // значит растягивать критическую секцию на скорость UART.
    let stack = Stack::allocate(stack_size).ok_or(SpawnError::OutOfMemory)?;

    let mut sched = SCHED.lock();
    let Some(slot) = sched.free_slot() else {
        // `stack` уничтожается после охранника (обратный порядок объявления
        // локальных), то есть куча трогается уже без лока.
        return Err(SpawnError::TooManyTasks);
    };

    let id = TaskId::new(sched.next_id);
    let task = Task::new(id, name, stack, entry, arg);
    let boxed = box_task(task).ok_or(SpawnError::OutOfMemory)?;

    sched.next_id += 1;
    sched.tasks[slot] = Some(boxed);
    Ok(id)
}

/// Номер слота исполняющейся задачи.
///
/// Слот, а не идентификатор: по нему индексируются таблицы, которые ведут о
/// задаче другие модули — адресное пространство программы и её открытые файлы
/// (см. [`crate::user`]). Идентификатор для этого не годится, он растёт без
/// предела.
#[must_use]
pub fn current_slot() -> usize {
    SCHED.lock().current
}

/// Слот и состояние задачи по её идентификатору.
///
/// `None` означает «такой задачи нет»: либо она никогда не создавалась, либо её
/// слот уже переиспользован под другую. Различить эти два случая нечем, и
/// придумывать различие не стоит — для вызывающего они одинаковы.
///
/// Возвращаются оба значения сразу, а не по отдельному вызову на каждое: между
/// двумя вызовами задача успела бы завершиться, и ответ описывал бы два разных
/// момента времени.
#[must_use]
pub fn lookup(id: TaskId) -> Option<(usize, TaskState)> {
    let sched = SCHED.lock();
    sched
        .tasks
        .iter()
        .enumerate()
        .find_map(|(slot, entry)| match entry {
            Some(task) if task.id == id => Some((slot, task.state)),
            _ => None,
        })
}

/// Объявить, в каком адресном пространстве исполняется текущая задача.
///
/// `None` возвращает её в пространство ядра. Значение переставляет процессор не
/// здесь, а на ближайшем переключении задач; сам переход выполняет вызывающий,
/// потому что он же и знает, в какой момент это безопасно.
pub fn set_current_space(root: Option<crate::mm::PhysAddr>) {
    let mut sched = SCHED.lock();
    let current = sched.current;
    if let Some(task) = sched.tasks[current].as_mut() {
        task.user.space_root = root;
    }
}

/// Завершилась ли задача, и с каким кодом.
///
/// `None` — задача ещё жива либо её слот уже переиспользован под другую.
#[must_use]
pub fn result_of(id: TaskId) -> Option<i64> {
    let sched = SCHED.lock();
    sched
        .tasks
        .iter()
        .flatten()
        .find(|task| task.id == id && task.state == TaskState::Finished)
        .map(|task| task.result)
}

/// Дождаться завершения задачи и вернуть её код.
///
/// `None` означает, что ждать нечего: задачи с таким номером в таблице нет —
/// либо не было, либо её слот уже переиспользован. Раньше этот случай выглядел
/// как вечная уступка процессора, то есть был неотличим от «задача ещё
/// работает»; с блокировкой он стал бы вечным сном, и потому назван.
pub fn wait(id: TaskId) -> Option<i64> {
    loop {
        // Проверка результата и блокировка — под одним локом. Между ними задача
        // успела бы завершиться, и разбудить ждущего стало бы некому: тот, кто
        // будит, проходит по таблице ровно один раз, в момент завершения.
        {
            let mut sched = SCHED.lock();
            let found = sched
                .tasks
                .iter()
                .flatten()
                .find(|task| task.id == id)
                .map(|task| (task.state, task.result));
            match found {
                Some((TaskState::Finished, code)) => return Some(code),
                None => return None,
                Some(_) => {
                    let current = sched.current;
                    if let Some(task) = sched.tasks[current].as_mut() {
                        task.state = TaskState::Blocked(Wait::Task(id));
                    }
                }
            }
        }
        schedule();
    }
}

/// Уснуть на указанное число миллисекунд.
///
/// Округление вверх — до целого тика: вернуться раньше срока хуже, чем
/// проспать лишние девять миллисекунд. Ноль означает «не спать вовсе», а не
/// «уступить»: для уступки есть [`yield_now`], и подменять одно другим значит
/// сделать `sleep(0)` тихо неотличимым от неё.
pub fn sleep_ms(ms: u64) {
    if ms == 0 {
        return;
    }
    let hz = u64::from(crate::irq::TIMER_HZ);
    let ticks = ms.saturating_mul(hz).div_ceil(1000).max(1);
    sleep_until(crate::irq::ticks().saturating_add(ticks));
}

/// Уснуть до тика с указанным номером.
pub fn sleep_until(tick: u64) {
    {
        let mut sched = SCHED.lock();
        if !sched.running {
            // До запуска планирования спать не на чем и некому: уснувшая
            // задача — единственная, и будить её будет нечем.
            return;
        }
        let current = sched.current;
        if let Some(task) = sched.tasks[current].as_mut() {
            task.state = TaskState::Blocked(Wait::Until(tick));
        }
    }
    schedule();
}

/// Заблокироваться до события ввода, но не дольше тика `until`.
///
/// `changed` вызывается **под локом планировщика**: если он отвечает `true`,
/// блокировки не происходит. Это и есть защита от потерянного пробуждения:
/// событие, пришедшее между «очередь пуста» и «я заснул», иначе разбудило бы
/// того, кто ещё не спит, и ждущий проспал бы до срока. Проверка под локом
/// закрывает окно целиком — прерывания в нём запрещены, а значит и положить
/// событие в этот момент некому.
pub fn block_on_input(until: u64, changed: impl FnOnce() -> bool) {
    {
        let mut sched = SCHED.lock();
        if !sched.running || changed() {
            return;
        }
        let current = sched.current;
        if let Some(task) = sched.tasks[current].as_mut() {
            task.state = TaskState::Blocked(Wait::Input(until));
        }
    }
    schedule();
}

/// Заблокироваться до освобождения лока по адресу `address`.
///
/// `free` вызывается **под локом планировщика**: если он отвечает `true`, лок
/// уже свободен и засыпать нельзя. Проверка именно здесь и закрывает гонку: пока
/// этот лок удерживается, прерывания запрещены, а держатель мьютекса — другая
/// задача, которой в это время не дадут ни такта. Состояние между проверкой и
/// засыпанием измениться не может.
///
/// Срока у ожидания нет намеренно — см. [`Wait::Lock`].
pub fn block_on_lock(address: usize, free: impl FnOnce() -> bool) {
    {
        let mut sched = SCHED.lock();
        if !sched.running || free() {
            return;
        }
        let current = sched.current;
        if let Some(task) = sched.tasks[current].as_mut() {
            task.state = TaskState::Blocked(Wait::Lock(address));
        }
    }
    schedule();
}

/// Заблокироваться до прерывания от источника `source`.
///
/// `ready` вызывается **под локом планировщика** и отвечает, не пришло ли
/// событие уже. Проверка именно здесь закрывает гонку с обработчиком: пока этот
/// лок удерживается, прерывания запрещены, а значит обработчик не может ни
/// выставить признак, ни разбудить задачу между «проверил» и «уснул».
///
/// Без этой проверки драйвер вставал бы намертво, и не всегда, а под нагрузкой:
/// событие, пришедшее в промежутке, не разбудило бы никого, потому что будить
/// было ещё некого, а задача уснула бы, потому что на момент проверки события
/// не было.
pub fn block_on_irq(source: u32, ready: impl FnOnce() -> bool) {
    {
        let mut sched = SCHED.lock();
        if !sched.running || ready() {
            return;
        }
        let current = sched.current;
        if let Some(task) = sched.tasks[current].as_mut() {
            task.state = TaskState::Blocked(Wait::Irq(source));
        }
    }
    schedule();
}

/// Разбудить тех, кто ждёт прерывания от источника `source`.
///
/// Вызывается из обработчика прерывания, поэтому делает ровно одно: переводит
/// ждущих в готовые. Разбор события — работа задачи, а не обработчика: пока он
/// исполняется, прерывания запрещены, и всё, что он делает сверх необходимого,
/// прямо отнимается у остальной системы.
pub fn wake_irq(source: u32) {
    let mut sched = SCHED.lock();
    for task in sched.tasks.iter_mut().flatten() {
        if task.state == TaskState::Blocked(Wait::Irq(source)) {
            task.state = TaskState::Ready;
        }
    }
}

/// Разбудить тех, кто ждёт лок по адресу `address`.
///
/// Будятся **все** ждущие, а не один: выбрать одного значило бы завести очередь
/// и порядок в ней, а с ними и вопрос о справедливости. Проснувшиеся попробуют
/// захватить лок по очереди, и не сумевшие уснут снова — лишний виток дешевле
/// структуры данных, которой пока нечего упорядочивать.
pub fn wake_lock(address: usize) {
    let mut sched = SCHED.lock();
    for task in sched.tasks.iter_mut().flatten() {
        if task.state == TaskState::Blocked(Wait::Lock(address)) {
            task.state = TaskState::Ready;
        }
    }
}

/// Разбудить всех, кто ждёт ввода.
///
/// Вызывается драйвером, положившим событие в очередь, — как правило из
/// обработчика прерывания. Поэтому `try_lock`: обработчик не имеет права ждать
/// освобождения лока. Неудача здесь не теряет событие, а лишь откладывает
/// пробуждение до срока, который в [`Wait::Input`] есть всегда именно ради
/// этого случая.
pub fn wake_input() {
    let Some(mut sched) = SCHED.try_lock() else {
        return;
    };
    for task in sched.tasks.iter_mut().flatten() {
        if matches!(task.state, TaskState::Blocked(Wait::Input(_))) {
            task.state = TaskState::Ready;
        }
    }
}

/// Добровольно уступить процессор.
///
/// Безопасно вызывать до [`run`] и вне любой задачи: [`schedule`] в этом случае
/// просто ничего не делает. Так код, который умеет уступать, не обязан знать,
/// поднят ли уже планировщик.
pub fn yield_now() {
    schedule();
}

/// Единственная точка переключения контекста в ядре.
///
/// Не важно, что послужило поводом — добровольная уступка, завершение задачи
/// или истёкший квант: все они приходят сюда.
pub fn schedule() {
    schedule_with(Cause::Voluntary);
}

/// Переключиться, помня, по чьей воле это происходит.
fn schedule_with(cause: Cause) {
    // Прерывания запрещаются здесь, а не полагаясь на `SpinLock`, и остаются
    // запрещёнными на всё переключение. Почему именно так — подробно в
    // заголовке модуля («Главная ловушка»); коротко: `SpinGuard` при
    // уничтожении вернул бы их «как было», а «как было» между обновлением
    // `current` и `switch_context` — это открытое окно для повторного входа.
    let irq_was_enabled = arch::interrupts::enabled();
    arch::interrupts::disable();

    let mut from: *mut Context = ptr::null_mut();
    let mut to: *const Context = ptr::null();

    {
        let mut sched = SCHED.lock();
        if sched.running {
            sched.reap();
            // Сроки проверяются здесь, а не в обработчике таймера, и это тот же
            // приём, что и с вытеснением: обработчик обязан быть коротким и не
            // имеет права ждать лока, а переключение и так происходит на каждом
            // тике, у которого кончился квант.
            sched.wake_expired(crate::irq::ticks());

            if let Some(next) = sched.pick_next() {
                let current = sched.current;

                // Полосу-сторож проверяем у той задачи, которую покидаем, и
                // именно сейчас: её стек только что перестал расти, а через
                // мгновение мы уже не будем знать, чей он был.
                if let Some(task) = sched.tasks[current].as_ref() {
                    if let Some(stack) = task.stack.as_ref() {
                        if !stack.guard_intact() {
                            report_overflow(task.name, task.id);
                        }
                    }
                }

                // Указатели берутся по очереди, а не одновременно: два
                // одновременных заимствования одного массива компилятор не
                // пропустит, а последовательные заканчиваются каждое до
                // следующего. Адреса устойчивы — при перекладывании слота
                // переезжает `Box`, а не сама задача.
                if let Some(target) = sched.tasks[next].as_ref() {
                    to = target.context.as_ptr();
                }
                if let Some(source) = sched.tasks[current].as_mut() {
                    from = source.context.as_mut_ptr();
                }

                // Машинное состояние программы переставляется здесь же, под
                // локом и с запрещёнными прерываниями: между «стек возврата уже
                // чужой» и «контекст ещё свой» не должно быть ни одного
                // наблюдателя. Порядок — сохранить своё, поставить чужое.
                if !from.is_null() && !to.is_null() {
                    let next_user = sched.tasks[next].as_ref().map_or_else(
                        task::UserMachine::default,
                        |task| task.user,
                    );
                    let saved = arch::swap_user_return_stack(next_user.return_stack);
                    if let Some(task) = sched.tasks[current].as_mut() {
                        task.user.return_stack = saved;
                    }
                    // Стек ловушки и стек возврата — один и тот же адрес: кадр
                    // ловушки ложится прямо под кадром, который оставил вход в
                    // третье кольцо.
                    arch::set_trap_stack(next_user.return_stack);

                    // Адресное пространство. У задачи без программы его нет, и
                    // тогда процессор возвращается на таблицы ядра: оставить
                    // чужие означало бы, что задача ядра работает в дереве,
                    // которое вот-вот разберут.
                    // SAFETY: любой корень программы построен копией ядерного и
                    // содержит все его отображения, поэтому переключение не
                    // уводит из-под ног ни код, ни стек — оба лежат в памяти
                    // ядра.
                    unsafe {
                        match next_user.space_root {
                            Some(root) => arch::activate_space(root),
                            None => arch::activate_kernel_space(),
                        }
                    }
                }

                // Состояние правится последним и только если переключение
                // действительно состоится. `pick_next` возвращает лишь занятые
                // слоты, так что пустым тут быть нечему, — но если инвариант
                // всё же нарушен, не переключиться безопаснее, чем оставить
                // `current` указывающим в пустой слот.
                if !from.is_null() && !to.is_null() {
                    if let Some(task) = sched.tasks[current].as_mut() {
                        if task.state == TaskState::Running {
                            task.state = TaskState::Ready;
                        }
                        // Счётчик снятий висит на **покидаемой** задаче: вопрос,
                        // на который он отвечает, — уступает ли она сама.
                        if cause == Cause::Preempted {
                            task.preempted += 1;
                        }
                    }
                    if let Some(task) = sched.tasks[next].as_mut() {
                        task.state = TaskState::Running;
                        task.switches += 1;
                    }
                    sched.current = next;
                    sched.switches += 1;
                    if cause == Cause::Preempted {
                        sched.forced += 1;
                    }
                    sched.slice_left = SLICE_TICKS;
                }
            }
        }
        // Охранник уничтожается здесь — до `switch_context`. Прерывания при
        // этом не включаются: `lock()` застал их уже запрещёнными.
    }

    if !from.is_null() && !to.is_null() {
        // SAFETY: оба указателя ведут в `MaybeUninit<Context>` внутри живых
        // `Box<Task>`, которые никто не освободит до возврата: единственное
        // место, где задачи исчезают, — этот же файл, а прерывания запрещены и
        // ядро однопроцессорное. `to` описывает задачу с отображённым стеком —
        // либо построенную `Context::new` поверх свежего блока кучи, либо
        // сохранённую предыдущим вызовом этой же функции (обход в `pick_next`
        // отбирает только `Ready`, то есть уже исполнявшиеся или новые). `from`
        // указывает на память, в которую переключение только пишет, поэтому её
        // неинициализированность у холостой задачи допустима.
        //
        // TODO(SMP): на нескольких ядрах между `drop(guard)` и этой строкой
        // появится настоящее окно — понадобится либо per-CPU состояние, либо
        // передача лока следующей задаче.
        unsafe { arch::switch_context(from, to) };
    }

    // Сюда управление возвращается уже в контексте задачи, которая когда-то
    // уступила процессор: `irq_was_enabled` прочитан с её собственного стека.
    if irq_was_enabled {
        arch::interrupts::enable();
    }
}

/// Учёт кванта. Предназначено для вызова из `irq::on_timer_tick`.
///
/// Ничего не переключает — только считает и, когда квант истёк, поднимает флаг
/// для [`preempt_point`]. Переключаться отсюда нельзя: прерывание в этот момент
/// ещё не подтверждено контроллеру, и ушедшая задача унесла бы подтверждение с
/// собой (подробно — «Вытеснение» в заголовке модуля).
pub fn on_timer_tick() {
    let mut expired = false;
    {
        // `try_lock`, а не `lock`: обработчик обязан быть коротким и не имеет
        // права зависнуть. Пропущенный тик стоит четверти кванта, зависший
        // обработчик — всей системы. (Захват здесь и не должен срываться:
        // `SpinLock` держит прерывания запрещёнными, так что тик не может
        // прилететь внутрь чужой критической секции. Но полагаться на это
        // рассуждение в обработчике — лишний риск.)
        let Some(mut sched) = SCHED.try_lock() else {
            return;
        };
        if !sched.running {
            return;
        }
        // Тик засчитывается той задаче, которую он застал. Холостая считается
        // отдельно: доля её тиков — единственная мера того, ради чего затевалась
        // Phase 13d, и мерить её снаружи нечем.
        if sched.current == IDLE_SLOT {
            sched.idle_ticks += 1;
        }
        let left = sched.slice_left.saturating_sub(1);
        if left == 0 {
            sched.slice_left = SLICE_TICKS;
            expired = true;
        } else {
            sched.slice_left = left;
        }
    }

    if expired {
        NEED_RESCHED.store(true, Ordering::Relaxed);
    }
}

/// Место, где вытеснение действительно происходит.
///
/// Арх-слой обязан вызывать эту точку в конце обработки внешнего прерывания и
/// **после** того, как подтвердил его контроллеру (`EOI` на x86-64,
/// `end_of_interrupt` в GIC на AArch64). Порядок здесь — условие
/// работоспособности, а не стиль: подтверждение, унесённое в другую задачу,
/// оставляет контроллер с активным прерыванием, а систему — без таймера.
///
/// Вызывать её из обработчика ловушки, пришедшей из третьего кольца, так же
/// законно, как из прерывания в коде ядра: с Phase 13a кадр ловушки лежит на
/// собственном стеке ядра задачи (`TSS.RSP0` на x86-64, `SP_EL1` на AArch64), и
/// переключение сохраняет его вместе со всем остальным.
///
/// Прерывания при вызове запрещены — это состояние входа в обработчик, — и
/// [`schedule`] на них и рассчитывает.
pub fn preempt_point() {
    if !PREEMPTION.load(Ordering::Relaxed) {
        return;
    }
    // `swap`, а не пара «прочитать — сбросить»: флаг поднимает обработчик
    // таймера, и между чтением и сбросом он успел бы прийти ещё раз, а
    // потерянный флаг — это пропущенный квант.
    if !NEED_RESCHED.swap(false, Ordering::Relaxed) {
        return;
    }
    schedule_with(Cause::Preempted);
}

/// Включить или выключить вытеснение по таймеру.
///
/// Включается один раз, перед [`run`]. Флаг существует не для настройки, а для
/// того, чтобы вытеснение можно было снять одной строкой, когда очередная фаза
/// начнёт вести себя странно: разница между «сломалось само» и «сломалось от
/// вытеснения» стоит того, чтобы её можно было проверить за одну пересборку.
///
/// С фазы 27 у него есть и второй, постоянный вызывающий:
/// [`crate::power::shut_down`] снимает вытеснение между сбросом тома на диск и
/// снятием питания — чтобы в этот промежуток никто не успел записать в том,
/// уже помеченный чистым.
pub fn set_preemption(enabled: bool) {
    PREEMPTION.store(enabled, Ordering::Relaxed);
    if !enabled {
        // Иначе поднятый флаг дождался бы обратного включения и сработал бы
        // в совершенно постороннем месте.
        NEED_RESCHED.store(false, Ordering::Relaxed);
    }
}

/// Запустить планирование. Возврата нет: когда все задачи завершатся, ядро
/// печатает сводку и останавливается.
pub fn run() -> ! {
    // Холостая задача создаётся до захвата лока по той же причине, что и стек в
    // `spawn`: диагностика отказа кучи не должна печататься под локом.
    let Some(idle) = box_task(Task::idle()) else {
        kprintln!("sched: FATAL: no heap for the idle task");
        arch::halt();
    };

    {
        let mut sched = SCHED.lock();
        if sched.running {
            kprintln!("sched: FATAL: run() called twice");
            arch::halt();
        }
        sched.tasks[IDLE_SLOT] = Some(idle);
        sched.current = IDLE_SLOT;
        sched.slice_left = SLICE_TICKS;
        sched.running = true;
    }

    // Холостая задача живёт здесь. `schedule()` уводит управление в готовую
    // задачу и возвращает его сюда только когда готовых больше нет.
    //
    // И вот тогда — с Phase 13d — процессор **останавливается** до ближайшего
    // прерывания, вместо того чтобы крутить этот цикл на полной скорости. Пока
    // ждать было нечего (все ожидания были уступками в цикле), разница была
    // незаметна: готовые задачи находились всегда. Теперь спящая задача не
    // готова, и без остановки холостой цикл жёг бы процессор ровно за тем,
    // чтобы тридцать два раза в такт убедиться, что делать нечего.
    loop {
        let alive = {
            let sched = SCHED.lock();
            sched.alive()
        };
        if alive == 0 {
            break;
        }
        schedule();

        // Сюда управление вернулось потому, что готовых задач нет. Гонка между
        // этой проверкой и остановкой безобидна: прерывание, пришедшее в
        // промежутке, разбудит задачу, но `wfi`/`hlt` уже начнётся — и
        // закончится на ближайшем тике таймера, то есть не позже чем через
        // 10 мс. Закрывать это окно запретом прерываний значило бы городить
        // `sti; hlt` в одной архитектуре и `wfi` с маской в другой ради
        // задержки, которой всё равно не видно.
        arch::wait_for_interrupt();
    }

    // Последняя завершившаяся задача уступила процессор холостой, и её стек
    // остался неубранным: `reap` внутри `schedule` пропускает текущую задачу, а
    // текущей на тот момент была она. Теперь текущая — холостая, и стек можно
    // забрать.
    let (freed, switches) = {
        let mut sched = SCHED.lock();
        (sched.reap(), sched.switches)
    };

    kprintln!("  done       : all tasks finished, {switches} switches, {freed} stack(s) reclaimed at exit");
    dump();

    kprintln!();
    kprintln!("All tasks finished, nothing left to schedule. CPU halted.");
    arch::halt();
}

/// Идентификатор исполняющейся задачи.
#[must_use]
pub fn current() -> TaskId {
    let sched = SCHED.lock();
    sched.tasks[sched.current].as_ref().map_or(TaskId::IDLE, |task| task.id)
}

/// Имя исполняющейся задачи.
#[must_use]
pub fn current_name() -> &'static str {
    let sched = SCHED.lock();
    sched.tasks[sched.current].as_ref().map_or("none", |task| task.name)
}

/// Сколько всего было переключений контекста.
#[must_use]
pub fn switch_count() -> u64 {
    SCHED.lock().switches
}

/// Запущено ли планирование.
#[must_use]
pub fn is_running() -> bool {
    SCHED.lock().running
}

/// Сколько задач ещё не завершились, не считая холостой.
///
/// Нужно задачам, которым важно не мешать другим: приглашение ядра ждёт, пока
/// остальные договорят, прежде чем печатать первый символ, — иначе их вывод и
/// набираемая строка перемешались бы в одной консоли.
#[must_use]
pub fn alive() -> usize {
    SCHED.lock().alive()
}

/// Компактный список задач с состояниями.
pub fn dump() {
    // Строки собираются и печатаются под локом. Это допустимо ровно потому, что
    // `kprintln!` не обращается к планировщику: иначе получилась бы рекурсия на
    // неперевходимом локе.
    let sched = SCHED.lock();
    for entry in sched.tasks.iter().flatten() {
        let stack = match entry.stack.as_ref() {
            Some(stack) if stack.guard_intact() => "held",
            Some(_) => "OVERFLOWN",
            None => "freed",
        };
        kprintln!(
            "  {} {:<8} {:<9} {:>3} switches ({} forced), stack {}",
            entry.id,
            entry.name,
            entry.state,
            entry.switches,
            entry.preempted,
            stack
        );
    }
    // Строка о вытеснении печатается здесь, а не в оболочке, по той же причине,
    // что и весь список: формат таблицы задач принадлежит планировщику. Она же —
    // единственный способ убедиться снаружи, что вытеснение действительно
    // включено, а не просто собрано.
    kprintln!(
        "  preemption : {}, {} ms slice, {} forced switch(es)",
        if PREEMPTION.load(Ordering::Relaxed) { "on" } else { "off" },
        SLICE_MS,
        sched.forced
    );
    // Доля простоя — то, ради чего затевалась Phase 13d. До неё она была нулём
    // при любой нагрузке: ждущие задачи уступали процессор, а не спали, и
    // готовая задача находилась всегда.
    let ticks = crate::irq::ticks();
    let percent = if ticks == 0 { 0 } else { sched.idle_ticks * 100 / ticks };
    kprintln!(
        "  idle       : {}% of {ticks} tick(s) with nothing to run",
        percent
    );
}

/// Батут, с которого начинается любая задача.
///
/// Нужен из-за несовпадения двух вещей. Во-первых, `Context::new` умеет
/// передать управление только в `extern "C" fn(usize) -> !`, а пользовательская
/// точка входа — обычная `fn()`. Во-вторых и главное, `fn()` **вправе
/// вернуться**, а возвращаться ей некуда: под её кадром на свежем стеке нет
/// осмысленного адреса возврата. Без батута такой возврат уехал бы по мусорному
/// адресу — то есть в отказ, объяснить который было бы нечем.
extern "C" fn trampoline(arg: usize) -> ! {
    // SAFETY: `arg` — это `fn()`, приведённая к `usize` в `spawn` несколькими
    // строками кода выше по тексту и нигде больше не порождаемая. Приведение
    // указателя на функцию к `usize` и обратно сохраняет значение, а размеры
    // совпадают (оба — машинное слово).
    let entry: fn() = unsafe { core::mem::transmute::<usize, fn()>(arg) };

    // Задача начинает исполняться с запрещёнными прерываниями: их запретил
    // `schedule()` перед переключением, и вернуть «как было» здесь некому —
    // у только что созданной задачи нет кадра, в котором это состояние
    // сохранялось бы. Инвариант планировщика: задачи исполняются с
    // разрешёнными прерываниями, иначе таймер до них не дойдёт.
    arch::interrupts::enable();

    entry();

    exit_current_with(0)
}

/// Завершить текущую задачу с кодом возврата.
///
/// Освободить здесь стек нельзя — на нём в этот момент исполняется вот этот
/// самый код. Поэтому задача лишь помечается завершённой и уступает процессор;
/// стек заберёт следующая задача в `Scheduler::reap`.
pub fn exit_current_with(result: i64) -> ! {
    {
        let mut sched = SCHED.lock();
        let current = sched.current;
        let mut id = TaskId::IDLE;
        if let Some(task) = sched.tasks[current].as_mut() {
            task.state = TaskState::Finished;
            task.result = result;
            id = task.id;
            // Программы у завершившейся задачи больше нет, и её адресное
            // пространство разобрано вызывающим. Отметку надо снять здесь же:
            // иначе ближайшее переключение попыталось бы поставить процессору
            // корень, которого уже не существует.
            task.user = UserMachine::default();
        }
        // Разбудить тех, кто ждал именно эту задачу. Проход по таблице ровно
        // один и ровно здесь: другого момента, когда задача становится
        // завершённой, не существует.
        sched.wake_waiters(id);
    }

    schedule();

    // Возврата сюда быть не может: `pick_next` отбирает только `Ready`, а
    // завершённая задача уже не `Ready`. Если управление всё же вернулось,
    // планировщик рассогласован, и продолжать исполнение на стеке, который
    // уборщик считает вправе освободить, — худшее из возможных решений.
    kprintln!("sched: FATAL: a finished task was resumed");
    arch::halt();
}

/// Сообщить о переполнении стека и остановиться.
///
/// Продолжать нельзя: полоса-сторож испорчена, значит запись ушла ниже дна
/// стека, и что именно она задела — уже неизвестно. Любое «восстановление»
/// здесь было бы работой поверх повреждённой памяти.
fn report_overflow(name: &'static str, id: TaskId) -> ! {
    kprintln!();
    kprintln!("*** TASK STACK OVERFLOW ***");
    kprintln!("  task      : {id} ({name})");
    kprintln!("  stack     : {} KiB usable, {} KiB guard band", TASK_STACK_SIZE / 1024, STACK_GUARD_SIZE / 1024);
    kprintln!("  the guard band below the stack was overwritten; neighbouring heap");
    kprintln!("  memory is likely corrupted, so execution stops here.");
    arch::halt();
}

// ---- демонстрация ------------------------------------------------------------

/// Сколько раз каждая задача демонстрации уступает процессор.
const DEMO_ROUNDS: u32 = 3;

/// Тело задачи демонстрации.
///
/// Все три задачи созданы из одной функции: свою личность задача узнаёт у
/// планировщика, а не получает аргументом, — что заодно проверяет, что
/// `current()` действительно меняется вместе с переключением.
fn demo_task() {
    for round in 1..=DEMO_ROUNDS {
        kprintln!("  {:<7}: round {round} of {DEMO_ROUNDS}", current_name());
        yield_now();
    }
}

/// Создать демонстрационные задачи: несколько задач по очереди печатают себя и
/// завершаются.
///
/// Планирование при этом **не** запускается — [`run`] вызывает тот, кто уже
/// добавил все свои задачи. Разделение появилось на Phase 6: приглашение ядра —
/// такая же задача, и создавать её надо до запуска, а не вместо демонстрации.
///
/// Возвращает число созданных задач.
pub fn spawn_demo_tasks() -> usize {
    let mut spawned = 0;
    for name in ["alpha", "beta", "gamma"] {
        match spawn(name, demo_task) {
            Ok(_) => spawned += 1,
            Err(err) => kprintln!("  spawn {name} failed: {err}"),
        }
    }
    spawned
}
