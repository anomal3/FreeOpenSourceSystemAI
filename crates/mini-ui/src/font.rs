#[cfg(test)]
mod tests {
    use super::*;

    /// Бит 0 обязан быть левым пикселем — иначе весь текст выйдет зеркальным,
    /// и заметно это будет только на экране.
    #[test]
    fn art_puts_bit_zero_on_the_left() {
        let glyph = art([
            "#       ", "        ", "        ", "        ", "        ", "        ", "        ",
            "       #",
        ]);
        assert_eq!(glyph[0], 0b0000_0001);
        assert_eq!(glyph[7], 0b1000_0000);
    }

    /// Таблица обязана покрывать весь диапазон А–я без дыр: пропущенный глиф
    /// проявится пустым местом в середине слова.
    #[test]
    fn every_cyrillic_letter_has_ink() {
        for code in 0x0410u32..=0x044F {
            let ch = char::from_u32(code).expect("кодовая точка кириллицы");
            let bits = glyph(ch);
            assert!(
                bits.iter().any(|&row| row != 0),
                "глиф {ch} (U+{code:04X}) пуст"
            );
        }
        assert!(glyph('Ё').iter().any(|&row| row != 0));
        assert!(glyph('ё').iter().any(|&row| row != 0));
    }

    /// Прописные и строчные обязаны различаться: одинаковые таблицы означают,
    /// что при переносе строк кто-то скопировал не тот блок.
    #[test]
    fn case_pairs_differ() {
        for (upper, lower) in ('А'..='Я').zip('а'..='я') {
            assert_ne!(
                glyph(upper),
                glyph(lower),
                "{upper} и {lower} нарисованы одинаково"
            );
        }
    }

    #[test]
    fn unknown_characters_become_a_question_mark() {
        assert_eq!(glyph('漢'), glyph('?'));
        assert!(!has('漢'));
        assert!(has('я') && has('A'));
    }
}
