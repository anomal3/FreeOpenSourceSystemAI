//! Растровый шрифт 8×8: ASCII из крейта `font8x8` плюс своя кириллица.
//!
//! # Почему кириллицу пришлось рисовать
//!
//! В `font8x8` её нет. Крейт повторяет набор из старого заголовка
//! `font8x8_basic.h`: basic, латиница с диакритикой, греческий, бокс-рисование,
//! хирагана — и ни одного кириллического знака. Установщик же обращается к
//! человеку, а не к разработчику: экран выбора языка, в котором «русский» надо
//! написать латиницей, обещает то, чего нет.
//!
//! Отсюда таблица ниже — 66 глифов (А–Я, а–я, Ё, ё), нарисованных вручную.
//!
//! # Формат
//!
//! Глиф задан восемью строками по восемь символов: `#` — точка, всё
//! остальное — пусто. Это не украшение исходника: 8×8 в шестнадцатеричном виде
//! невозможно ни прочитать, ни проверить глазами, а опечатку в одной строке
//! видно сразу. [`art`] переводит рисунок в тот же формат, что и `font8x8`, —
//! бит 0 соответствует **левому** пикселю строки (порядок унаследован от
//! C-заголовка), поэтому рисующему коду всё равно, откуда взят глиф.

use font8x8::legacy::BASIC_LEGACY;

/// Размер глифа.
pub const GLYPH_W: u32 = 8;
pub const GLYPH_H: u32 = 8;

/// Перевести рисунок из восьми строк в строки бит.
const fn art(rows: [&str; 8]) -> [u8; 8] {
    let mut out = [0u8; 8];
    let mut y = 0;
    while y < 8 {
        let bytes = rows[y].as_bytes();
        let mut x = 0;
        while x < bytes.len() && x < 8 {
            if bytes[x] == b'#' {
                out[y] |= 1 << x;
            }
            x += 1;
        }
        y += 1;
    }
    out
}

/// Глиф символа.
///
/// Символ, которого в таблицах нет, показывается как `?`: молча пропустить его
/// значит потерять текст, а нарисовать пустоту — сделать вид, что там ничего и
/// не было.
#[must_use]
pub fn glyph(ch: char) -> [u8; 8] {
    let code = ch as u32;
    if code < 0x80 {
        return BASIC_LEGACY[code as usize];
    }
    match ch {
        'Ё' => CYRILLIC_YO_UPPER,
        'ё' => CYRILLIC_YO_LOWER,
        'А'..='я' => CYRILLIC[(code - 0x0410) as usize],
        _ => BASIC_LEGACY[b'?' as usize],
    }
}

/// Умеет ли шрифт показать этот символ.
///
/// Нужно тому, кто выбирает язык интерфейса: предлагать язык, который
/// невозможно отобразить, нельзя.
#[must_use]
pub fn has(ch: char) -> bool {
    let code = ch as u32;
    code < 0x80 || ch == 'Ё' || ch == 'ё' || ('А'..='я').contains(&ch)
}

