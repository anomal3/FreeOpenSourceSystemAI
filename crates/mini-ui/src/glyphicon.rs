/// Нарисовать значок вписанным в квадрат со стороной `size`, левым верхним
/// углом в `(x, y)`.
///
/// Толщина штриха следует за размером: 1.4 точки при стороне 16. Иначе значок
/// в 24 точки выглядел бы нарисованным другим — более тонким — пером, чем
/// значок в 16, и ряд из них рассыпался бы.
pub fn draw(surface: &mut Surface, icon: Icon, x: i32, y: i32, size: u32, color: Color, alpha: u8) {
    if size == 0 || alpha == 0 {
        return;
    }
    // Толщина в десятых точки. Единица снизу — не осторожность ради
    // осторожности: значок в две точки шириной дал бы ноль, и штрих исчез бы
    // целиком вместо того, чтобы стать тонким.
    let weight = (size * 14 / 16).max(1);
    let pen = Pen { ox: x, oy: y, size, weight, color, alpha };

    for stroke in icon.strokes() {
        match *stroke {
            Stroke::Line(x1, y1, x2, y2) => pen.line(surface, (x1, y1), (x2, y2)),
            Stroke::Rect(rx, ry, rw, rh, r) => pen.rect(surface, (rx, ry), (rw, rh), r),
            Stroke::Circle(cx, cy, r) => pen.circle(surface, (cx, cy), r),
            Stroke::Arc(cx, cy, r, from, to) => pen.arc(surface, (cx, cy), r, from, to),
            Stroke::Dot(dx, dy) => pen.dot(surface, (dx, dy)),
        }
    }
}

/// Перо: всё, что одинаково для всех штрихов одного значка.
///
/// Собрано в структуру не ради красоты — иначе каждая рисующая функция брала бы
/// по десятку одних и тех же аргументов, и перепутать в них два соседних `i32`
/// было бы делом времени.
struct Pen {
    /// Левый верхний угол значка на поверхности.
    ox: i32,
    oy: i32,
    /// Сторона значка в точках.
    size: u32,
    /// Толщина штриха в десятых точки.
    weight: u32,
    color: Color,
    alpha: u8,
}

impl Pen {
    /// Точка сетки значка → точка поверхности.
    fn at(&self, x: i32, y: i32) -> (i32, i32) {
        (self.ox + scale(x, self.size), self.oy + scale(y, self.size))
    }

    fn line(&self, surface: &mut Surface, from: (i16, i16), to: (i16, i16)) {
        let a = self.at(i32::from(from.0), i32::from(from.1));
        let b = self.at(i32::from(to.0), i32::from(to.1));
        draw::line(surface, a, b, self.weight, self.color, self.alpha);
    }

    fn rect(&self, surface: &mut Surface, at: (i16, i16), size: (i16, i16), radius: i16) {
        let (left, top) = self.at(i32::from(at.0), i32::from(at.1));
        // Правый и нижний край считаются от своих координат в сетке, а не как
        // «левый плюс ширина»: иначе округление ширины и округление начала
        // складывались бы, и соседние прямоугольники значка расходились бы на
        // точку.
        let (right, bottom) = self.at(
            i32::from(at.0) + i32::from(size.0),
            i32::from(at.1) + i32::from(size.1),
        );
        let w = (right - left).max(1) as u32;
        let h = (bottom - top).max(1) as u32;
        // Скругление больше половины стороны — не ошибка вызывающего, а
        // следствие масштаба: у значка в 12 точек радиус 1.5 клетки почти
        // равен половине высоты полоски диска.
        let radius = (scale(i32::from(radius), self.size).max(0) as u32).min(w / 2).min(h / 2);
        draw::rounded_outline(
            surface,
            Rect::new(left, top, w, h),
            radius,
            self.weight,
            self.color,
            self.alpha,
        );
    }

    fn circle(&self, surface: &mut Surface, centre: (i16, i16), radius: i16) {
        let (cx, cy) = self.at(i32::from(centre.0), i32::from(centre.1));
        let r = scale(i32::from(radius), self.size).max(1) as u32;
        draw::circle_outline(surface, cx, cy, r, self.weight, self.color, self.alpha);
    }

    /// Дуга ломаной. Шаг подбирается по радиусу в точках, а не по углу: у дуги
    /// в три точки радиусом хватает четырёх звеньев, у дуги в двадцать четыре —
    /// нет, и постоянный шаг был бы либо гранёным, либо расточительным.
    fn arc(&self, surface: &mut Surface, centre: (i16, i16), radius: i16, from: u16, to: u16) {
        let r = i32::from(radius);
        if r <= 0 {
            return;
        }
        let pixels = scale(r, self.size).max(1) as u32;
        // Стрелка прогиба звена ≈ r·Δ²/8; шаг ниже держит её около одной
        // восьмой точки на всех разумных радиусах.
        let step = (256 / (4 + pixels * 2)).max(1);
        let start = u32::from(from) % 256;
        let end = u32::from(to) % 256;
        let sweep = match (end + 256 - start) % 256 {
            0 => 256,
            other => other,
        };
        let steps = sweep.div_ceil(step).max(1);

        let mut prev = self.on_circle(centre, r, start);
        for i in 1..=steps {
            // Угол считается от начала, а не накоплением шага: накопление
            // уводило бы конец дуги от заданного на остаток деления.
            let next = self.on_circle(centre, r, start + sweep * i / steps);
            draw::line(surface, prev, next, self.weight, self.color, self.alpha);
            prev = next;
        }
    }

    /// Точка на окружности сетки значка, уже переведённая в точки поверхности.
    fn on_circle(&self, centre: (i16, i16), radius: i32, angle: u32) -> (i32, i32) {
        let x = i32::from(centre.0) + (radius * cos(angle)) / UNIT;
        let y = i32::from(centre.1) + (radius * sin(angle)) / UNIT;
        self.at(x, y)
    }

    /// Кружок диаметром в толщину штриха.
    ///
    /// Отрезок нулевой длины, а не отдельная фигура: у [`draw::line`] это
    /// оговорённое поведение — проекция на вырожденный отрезок зажимается в его
    /// начало, и поле расстояний превращается в расстояние до точки, то есть в
    /// круг. Значит, кружок здесь сглажен ровно так же, как круглый торец любого
    /// другого штриха рядом, — а нарисованный своими руками отличался бы от
    /// соседей на глаз.
    fn dot(&self, surface: &mut Surface, at: (i16, i16)) {
        let point = self.at(i32::from(at.0), i32::from(at.1));
        draw::line(surface, point, point, self.weight, self.color, self.alpha);
    }
}

/// Клетка сетки значка → точки, с округлением к ближайшему.
///
/// Округление симметрично относительно нуля: центр дуги меридиана в `Network`
/// лежит левее значка, и обычное целочисленное деление, отбрасывающее дробь к
/// нулю, сдвигало бы его иначе, чем правую половину той же дуги.
fn scale(value: i32, size: u32) -> i32 {
    let size = size as i32;
    if value >= 0 {
        (value * size + 128) / 256
    } else {
        -((-value * size + 128) / 256)
    }
}

/// Единица неподвижной точки тригонометрии: синус прямого угла.
const UNIT: i32 = 4096;

/// Синус для четверти оборота: `SIN[i] = sin(i·2π/256)·4096`, `i` от 0 до 64.
///
/// Шестьдесят пять значений, а не шестьдесят четыре: последнее — сам прямой
/// угол, и без него симметрия `128 - i` не давала бы точного нуля на 128.
#[rustfmt::skip]
const SIN: [i32; 65] = [
        0,   101,   201,   301,   401,   501,   601,   700,
      799,   897,   995,  1092,  1189,  1285,  1380,  1474,
     1567,  1660,  1751,  1842,  1931,  2019,  2106,  2191,
     2276,  2359,  2440,  2520,  2598,  2675,  2751,  2824,
     2896,  2967,  3035,  3102,  3166,  3229,  3290,  3349,
     3406,  3461,  3513,  3564,  3612,  3659,  3703,  3745,
     3784,  3822,  3857,  3889,  3920,  3948,  3973,  3996,
     4017,  4036,  4052,  4065,  4076,  4085,  4091,  4095,
     4096,
];

/// Синус угла, заданного в 1/256 оборота.
fn sin(angle: u32) -> i32 {
    let a = (angle % 256) as usize;
    match a {
        0..=64 => SIN[a],
        65..=128 => SIN[128 - a],
        129..=192 => -SIN[a - 128],
        _ => -SIN[256 - a],
    }
}

/// Косинус — тот же синус, сдвинутый на четверть оборота.
fn cos(angle: u32) -> i32 {
    sin(angle + 64)
}
