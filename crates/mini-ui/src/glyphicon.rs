//! Штриховые значки интерфейса, нарисованные кодом.
//!
//! # Почему не картинки
//!
//! Растровый значок привязан сразу к двум вещам, которые в этой системе не
//! постоянны: к размеру и к цвету. Размер меняется потому, что один и тот же
//! значок стоит и в строке меню (16 точек), и на кнопке панели задач (20), и в
//! заголовке карточки (24); экран телефона и экран 2560 точек шириной просят
//! ещё два масштаба сверх этого. Цвет меняется потому, что тем две, а внутри
//! темы значок бывает обычным, приглушённым, выделенным и предупреждающим —
//! это не оттенки одной картинки, это разные цвета из палитры.
//!
//! Картинка отвечает на это одним способом: держать по файлу на каждое
//! сочетание. Тридцать пять значков × четыре размера × два цвета — почти три
//! сотни таблиц в образе, и любое изменение палитры означает пересборку их
//! всех. Штрих же — это несколько отрезков; масштаб задаётся при рисовании,
//! цвет приходит параметром, а в образе лежат только координаты.
//!
//! Есть и вторая причина, менее очевидная. Уменьшенная растровая картинка
//! мылится: 32×32, сжатые до 16×16, дают кашу вместо линий. Штрих в 16 точек
//! рисуется как штрих в 16 точек — линия остаётся линией на любом размере.
//!
//! # Система координат
//!
//! Значок описан в квадрате 16×16 — это viewBox макета. Чтобы обойтись целыми
//! числами, все координаты умножены на 16: квадрат становится 256×256, а
//! «1.5» из макета записывается как 24. Шестнадцатая доля точки — запас
//! достаточный: при отрисовке в 16–24 точки ошибка округления не доходит и до
//! десятой части пикселя.
//!
//! # Почему углы в 1/256 оборота, а не в градусах
//!
//! Потому что 256 делится на четыре нацело, и симметрия окружности сводится к
//! сравнению с 64, 128 и 192. В градусах пришлось бы делить на 90 с остатком в
//! каждой из четырёх ветвей. Плавающей точки здесь нет и быть не может — ядро
//! работает без FPU-контекста, — поэтому синус берётся из таблицы в
//! неподвижной точке 1/4096.

