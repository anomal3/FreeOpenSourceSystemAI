/// Один штрих значка. Координаты — в собственной сетке ×16 (см. заголовок).
///
/// Кривых Безье здесь нет намеренно. Всё, что в макете нарисовано кривой, —
/// это либо скругление угла (четверть окружности), либо пологая дуга; и то и
/// другое разложено вручную в [`Stroke::Arc`] или в цепочку отрезков. Разбор
/// Безье в ядре стоил бы кубического уравнения на каждый штрих ради точности,
/// которую всё равно не видно в шестнадцати точках.
#[derive(Clone, Copy)]
enum Stroke {
    /// Отрезок: `x1, y1, x2, y2`.
    Line(i16, i16, i16, i16),
    /// Скруглённый прямоугольник контуром: `x, y, w, h, радиус`.
    Rect(i16, i16, i16, i16, i16),
    /// Окружность контуром: `cx, cy, радиус`.
    Circle(i16, i16, i16),
    /// Дуга: `cx, cy, радиус, начальный угол, конечный угол`.
    ///
    /// Углы — в 1/256 полного оборота, ноль смотрит вправо, дуга идёт от
    /// начального к конечному по часовой стрелке (ось Y направлена вниз).
    /// Равные углы означают полный оборот.
    Arc(i16, i16, i16, u16, u16),
    /// Точка: штрих нулевой длины. В макете это `M4 7h.01` — приём, которым в
    /// SVG рисуют кружок толщиной обводки, не заводя отдельной фигуры.
    Dot(i16, i16),
}

