//! X.509 без кучи: разбор сертификата, проверка подписи и проверка цепочки.
//!
//! # Зачем это в системе, которая доверяет подписи, а не каналу
//!
//! Фаза 39 сделала обновления по HTTP с подписью Ed25519 — по образцу Debian:
//! доверие даёт подпись под содержимым, а не защищённость канала. Это решение в
//! силе и здесь ничего не отменяет. TLS нужен по другой причине, приземлённой:
//! **GitHub отдаёт только по HTTPS**, а запасной канал обновлений живёт именно
//! там. Система с одним сервером обновлений — это обещание, которое держится на
//! одной машине.
//!
//! Отсюда и мера строгости. Мы проверяем цепочку по-настоящему — имя, сроки,
//! подписи, корень из хранилища, — но не проверяем отзыв (см. `chain`). Если
//! TLS обманут, обновление всё равно не встанет: контейнер проверяет ядро
//! ключом из `/os-keys`.
//!
//! # Что здесь есть
//!
//! * [`der`] — чтение DER;
//! * [`cert`] — сертификат: поля, расширения, проверка подписи под ним;
//! * [`chain`] — цепочка от сервера до корня;
//! * [`store`] — хранилище корней (PEM);
//! * [`rsa`], [`ecdsa`], [`bigint`], [`hash`] — арифметика подписей.
//!
//! # Чего здесь нет
//!
//! Нет подписи — только проверка: закрытых ключей RSA и ECDSA у этой системы
//! нет. Нет отзыва (CRL, OCSP). Нет `nameConstraints` — но сертификат, у
//! которого это расширение помечено критическим, отвергается, а не принимается
//! молча. Нет DSA, нет кривых, кроме P-256 и P-384, нет SHA-1: подпись SHA-1
//! отвергается вместе с алгоритмом, потому что коллизию к ней научились считать
//! в 2017 году.

