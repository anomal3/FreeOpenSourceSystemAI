/// Разобрать `N` байт, записанных шестнадцатеричными цифрами.
///
/// Общая для ключа (32 байта) и подписи (64): формат один, и две почти
/// одинаковые функции разошлись бы в обработке заглавных букв или нечётной
/// длины — то есть в том, чего никто не проверяет глазом.
#[must_use]
pub fn from_hex<const N: usize>(text: &str) -> Option<[u8; N]> {
    if text.len() != N * 2 {
        return None;
    }
    let bytes = text.as_bytes();
    let mut out = [0u8; N];
    for (at, pair) in bytes.chunks_exact(2).enumerate() {
        out[at] = (digit(pair[0])? << 4) | digit(pair[1])?;
    }
    Some(out)
}

const fn digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}

/// Записать байты шестнадцатеричными цифрами.
///
/// Есть и на стороне разбора, а не только у сборщика: этим же способом
/// программа печатает хеш, который не сошёлся, — а сравнивать человеку придётся
/// именно с тем, что написано в индексе.
#[cfg(feature = "build")]
#[must_use]
pub fn to_hex(bytes: &[u8]) -> alloc::string::String {
    use alloc::string::String;

    let digits = b"0123456789abcdef";
    let mut out = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(digits[(byte >> 4) as usize] as char);
        out.push(digits[(byte & 0xF) as usize] as char);
    }
    out
}

/// Имя алгоритма в обоих текстовых файлах — и в `/os-keys`, и в `index.sig`.
pub const ALGORITHM: &str = "ed25519";

/// Новее ли `offered`, чем `have`.
///
/// Сравнение почисловое, по точкам: `0.1.9` меньше `0.1.10`, хотя строкой это
/// не так. Кусок, который не разбирается числом, сравнивается как строка — иначе
/// версия вида `0.2.0-rc1` останавливала бы обновления вовсе.
///
/// Правило здесь, а не в ядре, потому что спрашивают об этом двое и в разное
/// время: программа — глядя в индекс, чтобы решить, качать ли; ядро — глядя в
/// контейнер, чтобы решить, ставить ли. Разойдись они, машина скачивала бы
/// обновление, которое сама же потом отвергает, — и объяснить это было бы нечем.
#[must_use]
pub fn newer(offered: &str, have: &str) -> bool {
    let mut left = offered.split('.');
    let mut right = have.split('.');
    loop {
        match (left.next(), right.next()) {
            (None, None) => return false,
            (Some(_), None) => return true,
            (None, Some(_)) => return false,
            (Some(a), Some(b)) => match (a.parse::<u64>(), b.parse::<u64>()) {
                (Ok(a), Ok(b)) if a != b => return a > b,
                (Ok(_), Ok(_)) => {}
                _ if a != b => return a > b,
                _ => {}
            },
        }
    }
}
