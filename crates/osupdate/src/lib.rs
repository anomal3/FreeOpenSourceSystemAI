//! Кому машина верит, когда ей приносят обновление, и где она его берёт.
//!
//! # Зачем это отдельный крейт
//!
//! Потому что оба формата читаются **по обе стороны границы привилегий**, и
//! читать их обязаны одинаково. `/os-keys` разбирает ядро (проверяя контейнер
//! при `apply`) и программа `/bin/sysupdate` (проверяя подпись индекса, прежде
//! чем тащить по сети десятки мегабайт). Индекс разбирает программа, а
//! составляет `xtask` на машине сборки. Три читателя, два из которых собраны
//! порознь, — ровно тот случай, когда две копии разбора расходятся молча, а
//! выглядит это как «сервер отдаёт испорченный файл».
//!
//! Логика здесь общая **намеренно**, в отличие от `user-abi`, где общего кода
//! нет принципиально. Разница в том, что там договор о вызовах между кольцами, а
//! здесь разбор текста, который обе стороны получают из одного и того же файла:
//! ошибиться в нём порознь можно, а вот разойтись — уже нет.
//!
//! # Ничего не выделяет
//!
//! Ни одна функция разбора не просит памяти: ключи ложатся в массив
//! фиксированной длины, поля индекса — срезами поверх буфера вызывающего. Иначе
//! пользоваться этим не смогла бы программа, у которой аллокатора нет вовсе.

