//! Знакомый вид для того, кто пришёл с Windows: `C:\etc` и «Программы».
//!
//! # Что здесь есть и чего здесь принципиально нет
//!
//! Раскладка системы остаётся юниксовой и **единственной настоящей**. Здесь
//! только слой перевода поверх неё, и он делает ровно две вещи:
//!
//! * [`accept`] понимает путь, написанный по-виндовому, и отдаёт юниксовый;
//! * [`label`] даёт каталогу знакомое имя для показа.
//!
//! Каталоги при этом не переименованы, ссылок не заведено, второго корня не
//! появилось. Почему именно так — разобрано в `ROADMAP.md` (фаза 48a), и там же
//! названы два отвергнутых варианта: переименовать `/bin` в «Программы» (ломает
//! всякую портированную программу и всякую инструкцию из интернета) и завести
//! буквы томов как модель (переписывание разбора путей целиком ради косметики).
//!
//! # Почему буква только `C:`
//!
//! Потому что корень один. `D:\` в Windows — **другой том со своим корнем**, и
//! перевести его в тот же `/` значило бы соврать: `D:\etc` и `C:\etc` указывали
//! бы на один файл. Поэтому чужая буква — это отказ с внятным словом, а не
//! молчаливое совпадение.
//!
//! # Где этот перевод применять, а где нельзя
//!
//! Только к тому, что **набрал человек**. Всё, что система складывает сама
//! (`/mnt/` + аргумент, путь в журнале, имя в сообщении об ошибке), работает с
//! настоящими именами: иначе два написания одного пути разойдутся в журнале, и
//! отличить их будет не по чему.

use alloc::borrow::Cow;
use alloc::string::String;

/// Буква тома, за которой стоит наш единственный корень.
pub const DRIVE: char = 'C';

/// Что удалось сделать с тем, что набрал человек.
#[derive(Clone, PartialEq, Eq, Debug)]
pub enum Accepted<'a> {
    /// Путь уже юниксовый — ничего не переписано, брать как есть.
    ///
    /// Отдельный случай, а не «переписали в то же самое»: подавляющее
    /// большинство путей юниксовые, и выделять под каждый строку в куче ради
    /// перевода, которого не было, — это плата за всех ради нескольких.
    AsIs(&'a str),
    /// Переписан из виндового написания.
    Translated(String),
    /// Такой буквы тома в этой системе нет.
    NoSuchDrive(char),
}

impl Accepted<'_> {
    /// Путь, каким его увидит файловая система. `None` — буква чужая.
    #[must_use]
    pub fn path(&self) -> Option<&str> {
        match self {
            Accepted::AsIs(path) => Some(path),
            Accepted::Translated(path) => Some(path.as_str()),
            Accepted::NoSuchDrive(_) => None,
        }
    }
}

/// Понять путь, набранный человеком.
///
/// Переводятся три написания, и все три — то, что человек с Windows наберёт не
/// задумываясь:
///
/// ```text
///   C:\etc\system.cfg   ->  /etc/system.cfg
///   C:/etc              ->  /etc
///   \etc\system.cfg     ->  /etc/system.cfg
/// ```
///
/// Обратная косая **внутри** пути тоже становится прямой, но только если путь
/// уже опознан как виндовый: иначе имя файла с обратной косой (ext2 такое
/// допускает) переставало бы открываться.
#[must_use]
pub fn accept(path: &str) -> Accepted<'_> {
    // Буква тома: `X:` в начале. Проверяется по байтам, а не по символам, —
    // буква тома в Windows всегда латинская.
    let bytes = path.as_bytes();
    if bytes.len() >= 2 && bytes[1] == b':' && bytes[0].is_ascii_alphabetic() {
        let letter = bytes[0] as char;
        if !letter.eq_ignore_ascii_case(&DRIVE) {
            return Accepted::NoSuchDrive(letter.to_ascii_uppercase());
        }
        let rest = &path[2..];
        // `C:` без продолжения — это корень. `C:etc` (без косой) в Windows
        // означает «относительно текущего каталога тома C», а текущего каталога
        // у этой системы нет вовсе; читаем как от корня — единственное
        // толкование, которое здесь имеет смысл.
        let rest = rest.strip_prefix('\\').or_else(|| rest.strip_prefix('/')).unwrap_or(rest);
        let mut out = String::from("/");
        out.push_str(&rest.replace('\\', "/"));
        return Accepted::Translated(out);
    }

    // Одиночная обратная косая в начале: «от корня» в виндовом написании.
    if path.starts_with('\\') {
        return Accepted::Translated(path.replace('\\', "/"));
    }

    Accepted::AsIs(path)
}

/// Тот же перевод, но одной строкой: чужая буква возвращается как есть.
///
/// Для тех мест, где отказ рассказать нечем, — например, при показе пути,
/// который уже открыт.
#[must_use]
pub fn to_unix(path: &str) -> Cow<'_, str> {
    match accept(path) {
        Accepted::AsIs(path) => Cow::Borrowed(path),
        Accepted::Translated(path) => Cow::Owned(path),
        Accepted::NoSuchDrive(_) => Cow::Borrowed(path),
    }
}

/// Как записать юниксовый путь по-виндовому. Нужно для показа рядом с настоящим.
#[must_use]
pub fn to_windows(path: &str) -> String {
    let mut out = String::new();
    out.push(DRIVE);
    out.push(':');
    if !path.starts_with('/') {
        out.push('\\');
    }
    out.push_str(&path.replace('/', "\\"));
    out
}

/// Знакомое имя каталога. `None` — имени нет, показывать надо настоящее.
///
/// # Почему таблица, а не правило
///
/// Потому что знакомых имён ровно столько, сколько их есть в Windows, и
/// придумать остальные нельзя: «Мои документы» — это `/home/<кто-то>`, а
/// `/usr/lib` не называется никак, и назвать его «Библиотеки» значило бы
/// сочинить перевод, которого человек нигде не видел.
///
/// # Почему подпись не заменяет путь
///
/// Она украшает, а не прячет. Настоящий путь обязан оставаться на виду — в
/// строке состояния файлового менеджера, в журнале, в сообщении об ошибке.
/// Подпись, вытеснившая путь, превращает «нет такого файла» в загадку.
#[must_use]
pub fn label(path: &str) -> Option<&'static str> {
    let path = path.trim_end_matches('/');
    // Дом пользователя. Сравнивается по приставке: имя человека мы здесь не
    // знаем, а `/home/<кто-то>` — это чей-то дом при любом имени.
    if path.starts_with("/home/") && path[6..].split('/').count() == 1 {
        return Some("Мои документы");
    }
    Some(match path {
        "" | "/" => "Этот компьютер",
        // **Не** «Мои документы»: сеанс чаще всего не от root, и назвать чужой
        // дом своим — это ровно та подпись, из-за которой человек полезет туда
        // за своими файлами и не найдёт их. Подпись обязана уменьшать
        // непонимание, а не создавать новое.
        "/root" => "Документы администратора",
        "/home" => "Пользователи",
        "/bin" => "Программы",
        "/etc" => "Настройки",
        "/media" => "Съёмные носители",
        "/opt" => "Установленные пакеты",
        "/usr" => "Система",
        "/var" => "Служебные данные",
        _ => return None,
    })
}

/// Каталоги, которые новому человеку видеть первым делом незачем.
///
/// Не запрещены, не переименованы и не спрятаны навсегда: показываются по тому
/// же переключателю, что и скрытые файлы. Смысл ровно один — чтобы в корне
/// первым делом были видны свои файлы и программы, а не служебные деревья.
const FOLDED: [&str; 3] = ["/usr/share/doc", "/var/lib", "/opt"];

/// Свёрнут ли этот каталог в обычном виде.
#[must_use]
pub fn is_folded(path: &str) -> bool {
    let path = path.trim_end_matches('/');
    FOLDED.contains(&path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn unix(path: &str) -> String {
        accept(path).path().expect("буква своя").into()
    }

    /// Три написания, которые человек с Windows наберёт не задумываясь.
    #[test]
    fn windows_notation_becomes_a_unix_path() {
        assert_eq!(unix(r"C:\etc\system.cfg"), "/etc/system.cfg");
        assert_eq!(unix("C:/etc"), "/etc");
        assert_eq!(unix(r"\etc\system.cfg"), "/etc/system.cfg");
        assert_eq!(unix(r"c:\bin"), "/bin");
    }

    /// `C:` и `C:\` — это корень, а не пустая строка.
    #[test]
    fn the_drive_alone_is_the_root() {
        assert_eq!(unix("C:"), "/");
        assert_eq!(unix(r"C:\"), "/");
        assert_eq!(unix("C:/"), "/");
    }

    /// Юниксовый путь не переписывается вовсе — ни строки в куче.
    #[test]
    fn a_unix_path_is_left_alone() {
        assert_eq!(accept("/etc/system.cfg"), Accepted::AsIs("/etc/system.cfg"));
        assert_eq!(accept(""), Accepted::AsIs(""));
        // Обратная косая **внутри** юниксового пути — это знак в имени файла, а
        // не разделитель. Переписав её, мы перестали бы открывать такой файл.
        assert_eq!(accept(r"/home/roman/a\b"), Accepted::AsIs(r"/home/roman/a\b"));
    }

    /// Чужая буква — отказ, а не молчаливое совпадение с `C:`.
    ///
    /// `D:\etc` и `C:\etc` — разные места в той системе, откуда человек пришёл.
    /// Открыть по обоим один файл значило бы соврать ему о его же данных.
    #[test]
    fn another_drive_is_refused_by_name() {
        assert_eq!(accept(r"D:\etc"), Accepted::NoSuchDrive('D'));
        assert_eq!(accept("z:/x"), Accepted::NoSuchDrive('Z'));
        assert!(accept(r"D:\etc").path().is_none());
    }

    /// Путь, переведённый туда и обратно, возвращается тем же.
    #[test]
    fn a_path_survives_a_round_trip() {
        for path in ["/", "/etc", "/home/roman/notes", "/usr/share/doc"] {
            assert_eq!(unix(&to_windows(path)), path, "{path}");
        }
    }

    /// Свой дом — «Мои документы»; чужой — нет.
    ///
    /// Куплено снимком экрана: `/root`, подписанный «Мои документы», встречал
    /// человека, вошедшего под своим именем, — то есть звал его за файлами
    /// туда, где их нет.
    #[test]
    fn only_your_own_home_is_my_documents() {
        assert_eq!(label("/home/roman"), Some("Мои документы"));
        assert_eq!(label("/home/anna"), Some("Мои документы"));
        assert_eq!(label("/root"), Some("Документы администратора"));
        assert_eq!(label("/home"), Some("Пользователи"));
        // А вот что **внутри** дома — уже обычные каталоги, и придумывать им
        // имена неоткуда.
        assert_eq!(label("/home/roman/notes"), None);
    }

    #[test]
    fn known_directories_have_names_and_others_do_not() {
        assert_eq!(label("/bin"), Some("Программы"));
        assert_eq!(label("/etc/"), Some("Настройки"));
        assert_eq!(label("/"), Some("Этот компьютер"));
        assert_eq!(label("/usr/lib"), None);
    }

    #[test]
    fn service_directories_are_folded() {
        assert!(is_folded("/var/lib"));
        assert!(is_folded("/opt/"));
        assert!(!is_folded("/home"));
        assert!(!is_folded("/var"));
    }
}
