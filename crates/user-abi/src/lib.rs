//! Договор между ядром и пользовательской программой.
//!
//! Крейт существует затем, чтобы номера системных вызовов были **одним** местом
//! в дереве исходников. Две таблицы констант — в ядре и в программе —
//! расходятся молча: программа просит записать в консоль, ядро понимает это как
//! «завершиться», и найти такое сложнее, чем не допустить.
//!
//! Никакой **логики** здесь нет и быть не должно: ядро и пользовательская
//! программа исполняются на разных уровнях привилегий, и общая функция между
//! ними — это приглашение однажды позвать не ту. Раскладка данных — другое
//! дело: [`Stat`] пересекает границу, и понимать её одинаково обязаны обе
//! стороны. Поэтому здесь есть `repr(C)`-структуры и нет ни одной функции.
//!
//! # Соглашение о вызове
//!
//! Взято у Linux, и не из уважения к традиции, а потому что оно уже описано,
//! разобрано и знакомо:
//!
//! ```text
//!   x86-64    номер в rax, аргументы в rdi, rsi, rdx; результат в rax; int 0x80
//!   aarch64   номер в  x8, аргументы в  x0,  x1,  x2; результат в  x0; svc #0
//! ```
//!
//! `int 0x80`, а не `syscall`, выбран сознательно. `syscall`/`sysret` быстрее,
//! но диктуют раскладку GDT (пара селекторов обязана лежать подряд в строго
//! определённом порядке) и требуют настройки четырёх MSR. Программная ловушка
//! — тот же механизм, которым на AArch64 работает `svc`, то есть одна модель на
//! обе архитектуры вместо двух разных. Скорость системного вызова станет важна
//! тогда, когда их будет миллион в секунду; сейчас их единицы.

// Тесты договора (в конце файла) исполняются на хосте и линкуются с `libtest`,
// а тот требует std. Везде, где крейт собирают по-настоящему — в ядре и в
// программе, — он остаётся `no_std`.
#![cfg_attr(not(test), no_std)]

/// Записать байты в поток. `(fd, ptr, len) -> сколько записано`.
pub const SYS_WRITE: usize = 1;

/// Завершить программу. `(code) -> не возвращается`.
pub const SYS_EXIT: usize = 2;

/// Уступить процессор остальным задачам. `() -> 0`.
///
/// Отдаёт очередь, оставаясь готовой к исполнению, — в отличие от
/// [`SYS_SLEEP`], который из очереди выводит.
pub const SYS_YIELD: usize = 3;

/// Сколько миллисекунд система работает. `() -> миллисекунды`.
///
/// Самый дешёвый вызов, возвращающий **данные ядра**: по нему видно, что через
/// границу привилегий проходит не только направление «наружу».
pub const SYS_UPTIME: usize = 4;

/// Открыть файл. `(ptr, len, flags) -> дескриптор`.
///
/// Флаги — [`O_WRITE`], [`O_CREATE`], [`O_TRUNC`]; ноль означает «на чтение».
/// Они появились в Phase 14b вместе с самой записью: до неё аргумент «режим
/// открытия», из которого допустимо ровно одно значение, был бы обещанием,
/// которого не существует.
pub const SYS_OPEN: usize = 5;

/// Прочитать из дескриптора. `(fd, ptr, len) -> сколько прочитано`.
///
/// Ноль означает конец файла, а не ошибку. Смещение хранит ядро: файл читается
/// подряд, потому что искать по нему пока нечем — `seek` появится тогда, когда
/// у него будет вызывающий.
pub const SYS_READ: usize = 6;

/// Закрыть дескриптор. `(fd) -> 0`.
pub const SYS_CLOSE: usize = 7;

/// Узнать о файле, не открывая его. `(ptr, len, out) -> 0`.
///
/// `out` — адрес [`Stat`] в памяти программы. Отдельный вызов, а не поле в
/// `open`, потому что спросить про файл и получить к нему доступ — разные
/// права: для первого нужен проход по каталогам пути, для второго ещё и чтение
/// самого файла.
pub const SYS_STAT: usize = 8;

/// От чьего имени исполняется программа. `() -> uid`.
pub const SYS_GETUID: usize = 9;

/// Группа, от имени которой исполняется программа. `() -> gid`.
pub const SYS_GETGID: usize = 10;

/// Номер программы. `() -> идентификатор`.
///
/// Он же номер задачи планировщика: программа исполняется задачей, и заводить
/// для тех же объектов второе пространство имён значило бы всё время
/// сопоставлять одно с другим.
pub const SYS_GETPID: usize = 11;

/// Уснуть на указанное число миллисекунд. `(ms) -> 0`.
///
/// Отличается от [`SYS_YIELD`] не длительностью, а тем, что спящая программа
/// **не претендует на процессор**: она выходит из ротации планировщика до
/// срока. Уступка в цикле, которой приходилось изображать сон до Phase 13d,
/// занимала процессор ровно столько же, сколько занимал бы счёт.
pub const SYS_SLEEP: usize = 12;

/// Создать каталог. `(ptr, len, mode) -> 0`.
pub const SYS_MKDIR: usize = 13;

/// Удалить файл или пустой каталог. `(ptr, len) -> 0`.
///
/// Один вызов на оба случая, в отличие от Unix с его `unlink` и `rmdir`.
/// Разделение там историческое: `unlink` на каталоге когда-то оставлял
/// потерянные поддеревья, и запретить его было проще, чем чинить. Здесь
/// удаление каталога и так требует, чтобы он был пуст, а два имени для одного
/// действия — это две дороги к одной ошибке.
pub const SYS_REMOVE: usize = 14;

/// Передвинуть позицию в открытом файле. `(fd, offset, whence) -> позиция`.
///
/// До этого вызова файл можно было читать и писать только подряд, от начала и
/// до конца: позиция двигалась сама и только вперёд. Программе, которой нужен
/// хвост файла или его размер, приходилось прочитать всё остальное — то есть
/// заплатить за содержимое, которое ей не нужно.
///
/// `whence` — одно из [`SEEK_SET`], [`SEEK_CUR`], [`SEEK_END`]; смещение
/// знаковое, поэтому назад двигаться тоже можно. Позиция за концом файла
/// разрешена и ошибкой не является: чтение оттуда вернёт ноль байт, а запись —
/// это дыра, которой в ext2 без поддержки разрежённых файлов не будет, поэтому
/// запись за концом пока просто расширяет файл нулями.
pub const SYS_SEEK: usize = 15;

/// Текущее время в секундах эпохи Unix, UTC. `() -> секунды`.
///
/// Ноль означает, что система времени суток не знает: часов не было ни у
/// прошивки, ни у платы. Это не ошибка вызова, а честный ответ, и программа,
/// которой время нужно для метки, обязана его различать — иначе она поставит
/// 1970 год и будет уверена, что знает, когда это было.
///
/// Отличается от [`SYS_UPTIME`] тем же, чем часы отличаются от секундомера:
/// одно говорит, который час, другое — сколько машина работает.
pub const SYS_TIME: usize = 16;

/// Прочитать очередную запись открытого каталога. `(fd, ptr, len) -> 1 | 0`.
///
/// Единица означает «запись записана по `ptr`», ноль — «каталог кончился».
/// Ошибки, как обычно, отрицательны.
///
/// Каталог для этого открывается тем же [`SYS_OPEN`] — до этой фазы он на
/// каталоге отказывал, потому что читать из полученного дескриптора было
/// нечем. Позиция двигается сама, как у файла: `readdir` в цикле проходит
/// каталог ровно один раз.
///
/// # Что этот вызов обещает и чего не обещает
///
/// Список **фиксируется в момент открытия**: каталог читается целиком, и
/// дальнейшие изменения на диске в уже открытый дескриптор не попадают. Так же
/// ведёт себя `readdir` в POSIX, и по той же причине: перечисление, которое
/// меняется под руками у того, кто его читает, невозможно ни закончить, ни
/// объяснить.
///
/// Порядок записей — тот, в котором они лежат на носителе. Сортировки нет:
/// сортировать — дело того, кто показывает, и делать это в ядре значило бы
/// выбрать за всех одно правило сравнения.
pub const SYS_READDIR: usize = 17;

/// Размер окна программы в знаках. `() -> (столбцы << 32) | строки`.
///
/// Два числа в одном ответе, а не структура по указателю: оба помещаются в
/// регистр результата целиком, и вызов, которому не нужна память программы, не
/// может ошибиться адресом. Нули означают, что окна нет вовсе — система работает
/// в серийной консоли, и программа, рисующая рамку, обязана этот случай
/// различать.
pub const SYS_WINSIZE: usize = 18;

/// Переключить режим терминала. `(режим) -> 0`.
///
/// [`TTY_LINE`] — строка собирается терминалом и приезжает по Enter, с эхом.
/// [`TTY_RAW`] — каждое нажатие приезжает немедленно и без эха.
///
/// Режим принадлежит программе, а не терминалу: ядро возвращает построчный
/// режим само, когда программа заканчивается. Иначе программа, снятая
/// `Ctrl+C` посреди работы, оставила бы оболочку, в которой не видно
/// набираемого.
pub const SYS_TTYMODE: usize = 19;

/// Переименовать файл или каталог. `(ptr, старая длина, общая длина) -> 0`.
///
/// Оба пути лежат **в одном буфере** подряд: у вызова три аргумента, а нужно
/// четыре значения — два адреса и две длины. Склейка дешевле расширения
/// соглашения о вызовах, которое пришлось бы поменять на обеих архитектурах
/// ради одного вызова; а раз буфер всё равно копируется в ядро целиком, второй
/// адрес не дал бы ничего, кроме второй проверки прав доступа.
///
/// Переименование — не «скопировать и удалить»: содержимое не читается вовсе,
/// меняется только имя, под которым оно лежит. Разница видна на файле в
/// гигабайт и на файле, открытом кем-то ещё.
pub const SYS_RENAME: usize = 20;

/// Запустить программу отдельной задачей. `(ptr, len, кто) -> номер задачи`.
///
/// `ptr`/`len` — командная строка целиком: путь, пробел, аргументы. Разбирает её
/// ядро тем же кодом, которым разбирает строку от оболочки, — иначе запуск из
/// программы и запуск из оболочки понимали бы кавычки и пробелы по-разному.
///
/// `кто` — [`SPAWN_INHERIT`] либо `(uid << 32) | gid`. Снизить права вправе
/// кто угодно, повысить — никто: программа, исполняющаяся не от root, получает
/// [`ERR_PERMISSION`] на любой uid, кроме своего. Это и есть механизм, ради
/// которого поле существует: супервизор служб исполняется от root, а служба —
/// от того, кто записан в её описании, и наследование прав запуска от родителя
/// сделало бы описание украшением.
///
/// Возврат — номер задачи, тот же, что показывает `tasks` и что принимает
/// [`SYS_WAIT`]. Ждать запущенного никто не обязан: программа, которой ответ не
/// нужен, просто не спрашивает — так работают службы.
///
/// # Чего здесь нет
///
/// `fork`. Копировать адресное пространство незачем: единственное, ради чего
/// его копируют в Unix, — это `exec` следом, а `exec` здесь и есть весь вызов.
/// Нет и наследования открытых файлов: таблица дескрипторов у новой задачи
/// своя и пустая. Наследование потребовало бы решить, что делать с позицией в
/// общем файле, — вопрос, у которого сегодня нет ни одного задающего.
pub const SYS_SPAWN: usize = 21;

/// Узнать, чем кончилась задача. `(id, флаги) -> код возврата`.
///
/// Без флагов вызов **ждёт**: программа выходит из очереди планировщика до тех
/// пор, пока та задача не закончится. С [`WAIT_NOHANG`] не ждёт вовсе и отвечает
/// [`ERR_AGAIN`], если она ещё работает.
///
/// Второй режим существует ради супервизора, и это не удобство: служб у него
/// несколько, а ожидание блокирует на **одной**. Уснув на первой, он не заметил
/// бы падения второй до тех пор, пока не упадёт первая. «Дождаться любой» было
/// бы третьим вариантом, но он потребовал бы от ядра списка детей — то есть
/// родства, которого в этой системе нет: задача не помнит, кто её запустил.
pub const SYS_WAIT: usize = 22;

/// Создать файл с заданными правами и открыть его на запись. `(ptr, len, mode)
/// -> дескриптор`.
///
/// Отдельный вызов, а не четвёртый аргумент [`SYS_OPEN`]: аргументов у
/// системного вызова три на обеих архитектурах, и расширять соглашение ради
/// одного случая пришлось бы в четырёх местах — в двух вставках ассемблера, в
/// обработчике ловушки и в договоре. Отдельный номер стоит дешевле.
///
/// Существует потому, что `open` с `O_CREATE` создаёт файл правами `0644`, и
/// это правильное умолчание для всех, кроме одного: тот, кто раскладывает
/// пакет, обязан положить программу исполняемой. Права при этом берутся из
/// манифеста, то есть из данных, — поэтому ядро обрезает их до девяти бит и
/// проверяет право писать в каталог так же, как при обычном создании.
///
/// На занятое имя отвечает [`ERR_EXISTS`], а не «обрежу и открою». Разница
/// важна ровно там, где этот вызов и применяется: пакет, ставящийся поверх
/// чужого файла, — это не установка, а порча, и молчаливое перезаписывание
/// скрыло бы её.
pub const SYS_CREATE: usize = 23;

/// Завести сокет UDP. `(kind) -> номер сокета`.
///
/// `kind` сегодня обязан быть [`SOCK_UDP`]. Аргумент существует ради фазы, где
/// появится TCP: вызов, у которого сегодня один вариант, лучше вызова, который
/// завтра придётся заводить второй раз под другим именем.
///
/// Номер сокета — **не** файловый дескриптор: пространства у них разные, и
/// читать сокет через [`SYS_READ`] нельзя. Так сделано потому, что датаграмма —
/// это не поток байт: у неё есть отправитель и границы, и `read`, отдающий её
/// как байты, потерял бы и то и другое.
pub const SYS_SOCKET: usize = 24;

/// Привязать сокет к порту. `(сокет, порт) -> назначенный порт`.
///
/// Ноль означает «дайте любой свободный»: программе, которая только
/// спрашивает, свой порт не важен, а отправлять с нулевого нельзя — ответ
/// приходит на порт отправителя.
pub const SYS_BIND: usize = 25;

/// Запомнить собеседника. `(сокет, адрес, порт) -> назначенный локальный порт`.
///
/// Адрес — четыре байта IPv4 в машинном порядке старшим вперёд, то есть
/// `10.0.2.2` это `0x0A000202`. Соединения UDP не устанавливает: вызов только
/// избавляет от необходимости называть адрес в каждой отправке.
pub const SYS_CONNECT: usize = 26;

/// Отправить датаграмму собеседнику из [`SYS_CONNECT`]. `(сокет, ptr, len) -> len`.
///
/// [`ERR_AGAIN`] означает, что аппаратный адрес получателя ещё выясняется
/// (ARP): запрос уже ушёл, и повторить попытку стоит через несколько
/// миллисекунд. Это не ошибка, а «ещё не сейчас».
pub const SYS_SEND: usize = 27;

/// Забрать датаграмму. `(сокет, ptr, len) -> сколько байт`.
///
/// Не ждёт: пустая очередь — это [`ERR_AGAIN`], а не блокировка. Программа,
/// которой нужно подождать, спит сама и решает сама, сколько; ядро, уснувшее за
/// неё, отняло бы у неё это решение вместе с возможностью сдаться по времени.
///
/// Кто прислал датаграмму, спрашивают через [`SYS_PEER`] — сразу после успешного
/// приёма и до следующего.
pub const SYS_RECV: usize = 28;

/// Кто прислал последнюю принятую датаграмму. `(сокет, out) -> 0`.
///
/// `out` — указатель на [`Peer`].
pub const SYS_PEER: usize = 29;

/// Закрыть сокет. `(сокет) -> 0`.
pub const SYS_CLOSE_SOCKET: usize = 30;

/// Задать настройки сети. `(ptr, len) -> 0`.
///
/// `ptr` — указатель на [`NetConfig`]. Только root: адрес интерфейса — это
/// решение о машине целиком, а не о программе, которая его сообщает.
pub const SYS_NETCONF: usize = 31;

/// Узнать адрес по имени. `(ptr, len, out) -> 0`.
///
/// `out` — указатель на четыре байта, куда ляжет адрес. Резолвер живёт в ядре
/// потому же, почему там живёт стек: спрашивать имя нужно и оболочке, и
/// программе обновления, и службе, а библиотеки, общей для всех троих, у
/// системы пока нет.
pub const SYS_RESOLVE: usize = 32;

/// Узнать состояние сети. `(ptr, len) -> 0`.
///
/// `ptr` — указатель на [`NetInfo`]. Нужен не для красоты: клиент DHCP обязан
/// вписать в свой запрос **собственный аппаратный адрес**, иначе сервер не
/// поймёт, кому отвечать, — а взять его программе больше неоткуда.
pub const SYS_NETINFO: usize = 33;

/// Начать слушать входящие соединения. `(сокет) -> 0`.
///
/// Только для [`SOCK_TCP`] и только после [`SYS_BIND`]: слушать на порту,
/// который назначили случайно, бессмысленно — никто не знает, куда стучаться.
pub const SYS_LISTEN: usize = 34;

/// Забрать установленное соединение. `(сокет) -> номер нового сокета`.
///
/// Не ждёт: [`ERR_AGAIN`] означает, что очередь пуста. Сервер, которому нечем
/// заняться, спит сам — ядро, уснувшее за него, отняло бы у него возможность
/// обслуживать несколько соединений разом.
pub const SYS_ACCEPT: usize = 35;

/// Закрыть свою половину соединения. `(сокет) -> 0`.
///
/// Отправляет `FIN`, когда кончатся неотправленные данные. Читать из
/// соединения после этого всё ещё можно: половины закрываются независимо, и
/// это единственный способ сказать «я всё сказал» тому, кто продолжает
/// отвечать.
pub const SYS_SHUTDOWN: usize = 36;

/// Состояние соединения. `(сокет, out) -> 0`.
///
/// `out` — указатель на [`StreamState`]. Существует потому, что «данных пока
/// нет» и «данных больше не будет» — разные вещи, а [`SYS_RECV`] отвечает на
/// оба одинаково.
pub const SYS_STREAMSTATE: usize = 37;

/// Заполнить буфер случайными байтами. `(ptr, len) -> len`.
///
/// Источник — тот, что описан в [`crate`]-документации ядра: аппаратный
/// генератор процессора, а где его нет — пул, набранный из дрожания прерываний.
/// Программе источник не сообщается намеренно: выбор источника — решение
/// системы, а программа, которая его переспрашивает, всё равно ничего не может
/// с ответом сделать. Что именно использовано, ядро печатает при загрузке.
pub const SYS_RANDOM: usize = 38;

/// Завести канал. `(флаги, 0, 0) -> (читающий << 32) | пишущий`.
///
/// Канал — это байты от одной задачи к другой: то, чего этой системе не хватало
/// ровно для одного, но важного — запускать программы **не для человека за
/// терминалом**. Пока вывод программы уходил только в окно оболочки, `sshd`
/// приходилось носить внутри себя собственные `ls` и `cat` со второй в системе
/// проверкой прав.
///
/// Возвращаются два дескриптора, упакованные в одно число: читающий конец в
/// старшей половине, пишущий — в младшей. Два вызова вместо одного означали бы
/// канал, у которого между ними есть только один конец.
///
/// # Что обязан сделать тот, кто отдал конец другому
///
/// Закрыть свою копию. Конец канала считается живым, пока жив хоть один
/// дескриптор на него: программа, отдавшая пишущий конец запущенной задаче и
/// оставившая его себе, **никогда не увидит конца файла** на другом конце — она
/// сама и есть тот писатель, которого ждут. Так устроены каналы везде, и здесь
/// не сделано исключения.
pub const SYS_PIPE: usize = 39;

/// Запустить программу, назвав её потоки. `(ptr на [`Launch`], 0, 0) -> номер задачи`.
///
/// Отличается от [`SYS_SPAWN`] ровно тем, ради чего существует: стандартный
/// ввод и вывод новой задачи можно привязать к концам каналов. Аргумент —
/// структура в памяти программы, а не три числа: их у системного вызова три, а
/// назвать надо пять вещей.
///
/// Названные дескрипторы обязаны быть концами каналов и остаются открытыми у
/// того, кто запускает: `launch` их не закрывает. См. [`SYS_PIPE`] о том, чем
/// это грозит тому, кто забудет.
pub const SYS_LAUNCH: usize = 40;

/// Поставить обновление системы из контейнера. `(ptr, len, 0) -> слот`.
///
/// `ptr`/`len` — путь к файлу `.fpk`, уже лежащему на носителе. Возврат — номер
/// слота, который станет активным ([`SLOT_A`] или [`SLOT_B`]): его печатает
/// программа, чтобы человек знал, куда он загрузится.
///
/// # Почему это делает ядро
///
/// Потому что запись идёт **мимо файловой системы**: образ корня льётся прямо в
/// сектора неактивного раздела, а ядро и initrd — в файлы на FAT-томе ESP,
/// который никто не монтировал. Отдать это программе значило бы отдать программе
/// блочное устройство, то есть отменить границу, ради которой существует третье
/// кольцо.
///
/// # Почему тогда вызов, а не только команда оболочки
///
/// Потому что качает обновление программа (`/bin/sysupdate`), и без вызова
/// последним шагом её работы была бы просьба к человеку набрать команду руками.
/// Сам вызов ничего нового ядру не позволяет: та же `slot::apply`, которую
/// зовёт оболочка, и та же проверка подписи внутри неё.
///
/// Только для root: обновление — это решение о машине целиком. Всем остальным
/// [`ERR_PERMISSION`].
///
/// Вызов **долгий**: он переливает десятки мегабайт и возвращается через
/// минуты. Задача всё это время стоит в ядре — как и оболочка, когда ту же
/// работу заказывают ей.
pub const SYS_UPDATE: usize = 41;

/// Ответ [`SYS_UPDATE`]: активным станет слот A.
pub const SLOT_A: i64 = 0;
/// Ответ [`SYS_UPDATE`]: активным станет слот B.
pub const SLOT_B: i64 = 1;

/// Попросить у ядра безымянной памяти. `(len, flags) -> адрес`.
///
/// `len` — в байтах, и ядро округляет его вверх до целого числа страниц:
/// меньше страницы отобразить нечего, таблицы страниц другого шага не знают.
/// Возврат — адрес начала области в памяти программы либо отрицательный код:
/// [`ERR_NO_SPACE`], если у машины не осталось свободных кадров, [`ERR_LIMIT`],
/// если столько не дадут **одной** задаче, [`ERR_BAD_ADDRESS`] на нулевую
/// длину.
///
/// # Почему нет `prot` и почему всё-таки есть `flags`
///
/// `prot` различать нечего. Отображение и так запрещает страницу, которая
/// одновременно пишется и исполняется (W^X), а безымянная память, в которую
/// нельзя писать, не нужна никому: программе, которой хватает чтения, хватает
/// и своего сегмента данных. Достижимых состояний остаётся ровно два — «читать
/// и писать» и «ничего», — а два состояния это не слово прав, это наличие или
/// отсутствие самой области.
///
/// Фаза 41 (отображение файлов) обещала дописать ровно те флаги, которые ей
/// понадобятся, и не дописала ни одного — что подтвердило правило, а не
/// нарушило его: различия, которые она принесла, оказались различиями в
/// **аргументах** (дескриптор и смещение против одной длины), а не признаками у
/// тех же трёх чисел. Поэтому у неё свой номер, [`SYS_MMAP_FILE`].
///
/// А фаза 42 флаг завела — [`MAP_HUGE`], — и по той же причине, по которой его
/// не было раньше, только прочитанной в другую сторону. Условие всегда было
/// одно: флаг существует тогда, когда у него есть **второе достижимое
/// значение**. Крупные страницы — это выбор, который программа делает за себя и
/// который ядру не угадать: она одна знает, будет ли она ходить по всей области
/// или по её сотой части, а разница между двумя мегабайтами на запись в TLB и
/// четырьмя килобайтами стоит ровно этого знания.
///
/// Аргумент при этом остаётся необязательным в самом прямом смысле: ноль здесь
/// значит «как раньше», и все программы, написанные до 42-й фазы, передают
/// именно его.
pub const SYS_MMAP: usize = 42;

/// Вернуть ядру область, взятую [`SYS_MMAP`] или [`SYS_MMAP_FILE`].
/// `(addr, len) -> 0`.
///
/// Один вызов на оба вида областей, и правило у них одно. Отдельного
/// `munmap_file` нет потому же, почему [`SYS_REMOVE`] один на файл и каталог:
/// откуда взялась область, помнит ядро — оно ведёт их список, — а программе
/// пришлось бы помнить это самой и однажды позвать не тот вызов.
///
/// Принимается только **точное** совпадение с тем, что вернул [`SYS_MMAP`]: тот
/// же адрес и та же длина. Отдать кусок из середины нельзя, и это названное
/// ограничение, а не недосмотр: частичное освобождение означает деление области
/// надвое, то есть учёт кусков вместо учёта выданного целиком, — а желающих на
/// это пока нет ни одного. Появится первый — предел снимет он, зная, зачем.
///
/// Несовпавшая просьба — [`ERR_BAD_ADDRESS`], а не молчаливое «освобожу, сколько
/// пойму»: программа, промахнувшаяся мимо своей области, должна узнать об этом
/// от ядра, а не по чужой памяти, которая перестала читаться.
pub const SYS_MUNMAP: usize = 43;

/// Отобразить содержимое файла в память программы. `(fd, offset, len) -> адрес`.
///
/// Программа получает адрес, по которому лежит кусок файла, и читает его как
/// обычную память — без [`SYS_READ`], без буфера и без копии. Страницы при этом
/// заводятся не сразу: ядро подкладывает их по отказу обращения, то есть файл в
/// сто мегабайт стоит ровно тех страниц, которых программа коснулась. Это и
/// есть разница с [`SYS_MMAP`], который занимает и обнуляет всё жадно: там
/// содержимого нет, и подкладывать по отказу нечего, а здесь есть — и читать
/// его целиком ради программы, которой нужен один заголовок, было бы платой ни
/// за что.
///
/// # Почему отдельный номер, а не признак у [`SYS_MMAP`]
///
/// Потому что аргументов у системного вызова три — столько регистров названо в
/// соглашении на обеих архитектурах, — и здесь их нужно ровно три: дескриптор,
/// смещение и длина. Признак «это файл» стал бы четвёртым, а четвёртый аргумент
/// — это правка соглашения в двух вставках ассемблера, в обработчике ловушки и
/// в этом файле, ради одного вызова. Отдельный номер стоит дешевле; так же и по
/// той же причине заведён [`SYS_CREATE`] вместо четвёртого аргумента
/// [`SYS_OPEN`].
///
/// И вторая половина того же довода, обещанная у [`SYS_MMAP`] заранее: слова
/// флагов там нет потому, что различать было нечего, и заводить аргумент с
/// одним законным значением отказались вслух. Эта фаза обещанного слова не
/// приносит. Она приносит второй вызов с **другими** аргументами — а не тот же
/// вызов с битом, который в половине случаев обязан быть нулём. Флаги появятся
/// тогда, когда у них будет два значения, означающих разное.
///
/// # Только на чтение, и это названный предел
///
/// Отображение read-only. Запись по такому адресу — отказ страницы, то есть
/// конец программы, ровно как обращение по чужому адресу; программа, желающая
/// поменять файл, открывает его на запись и пишет [`SYS_WRITE`].
///
/// Дело не в лени. Запись в отображение означает грязные страницы, которые
/// когда-то надо слить обратно: нужен учёт того, что изменилось, вытеснение
/// (иначе изменения живут только в памяти и пропадают вместе с задачей) и
/// согласованность с обычной записью в тот же файл — два пути к одним блокам,
/// каждый со своим кэшем. Это отдельная фаза целиком, и сделать её половину,
/// оставив вторую на потом, значит получить систему, которая иногда теряет
/// записанное. Отказ на запись — честнее.
///
/// # Что обязана знать программа
///
/// `offset` — от начала файла и **кратен странице** (4096). Не кратный —
/// [`ERR_BAD_ADDRESS`]: отображение начинается с границы страницы, других шагов
/// таблицы не знают, и сдвинуть содержимое внутри страницы ядру нечем, кроме
/// как скопировав его, — то есть отменив всю выгоду вызова.
///
/// `len` — в байтах, и ядро округляет его вверх до целой страницы, как и
/// [`SYS_MMAP`]. Что лежит в хвосте последней страницы **за концом файла**,
/// договор не обещает: размер файла программа знает и заглядывать дальше него
/// не имеет права. Обещать там нули значило бы обязать ядро их туда положить —
/// то есть трогать страницу, которую иначе можно было бы отдать как есть.
///
/// Отображение **держит файл само**. Закрыть `fd` сразу после вызова можно и
/// нужно: дескриптор нужен был, чтобы назвать файл и проверить право его
/// читать, а дальше область ссылается на файл своими силами. Иначе программа,
/// отобразившая десяток файлов, упёрлась бы в [`MAX_OPEN_FILES`] на ровном
/// месте — и держала бы дескрипторы открытыми ради того, чем уже не пользуется.
///
/// Освобождается область обычным [`SYS_MUNMAP`], и правило там то же самое:
/// адрес и длина обязаны **в точности** совпасть с тем, что просили. Почему
/// именно тем же вызовом, а не своим, сказано у него.
///
/// # Отказы
///
/// [`ERR_BAD_FD`] — такого дескриптора у программы нет. [`ERR_BAD_ADDRESS`] —
/// нулевая длина или смещение не по границе страницы. [`ERR_LIMIT`] — столько
/// не дадут **одной** задаче; [`ERR_NO_SPACE`] — свободных кадров нет у машины
/// (разницу между этими двумя см. у [`ERR_LIMIT`]). [`ERR_UNSUPPORTED`] — этот
/// файл отобразить нельзя: каталог или канал. У последних нет того, на чём
/// держится весь вызов, — блоков на носителе, лежащих по смещению; канал вообще
/// существует только пока его читают.
pub const SYS_MMAP_FILE: usize = 44;

/// На каком процессоре исполняется программа. `() -> номер`.
///
/// Ответ верен на миг вызова и ни на мгновение дольше: планировщик вправе
/// перенести программу на другой процессор сразу после возврата. Поэтому вызов
/// годится для того, чтобы **увидеть**, что процессоров несколько, и не годится
/// для того, чтобы на это рассчитывать, — привязывать программу к процессору
/// ядро не умеет.
///
/// Номер — порядковый, с нуля, в том порядке, в каком ядро запустило
/// процессоры; тот же, что печатает `tasks`. Аппаратный номер (`APIC ID`,
/// `MPIDR`) программе не нужен и не отдаётся.
pub const SYS_GETCPU: usize = 45;

/// Продублировать дескриптор. `(fd, куда) -> новый дескриптор`.
///
/// `куда` — либо [`DUP_ANY`] («самый маленький свободный»), либо номер, который
/// надо занять: занятый при этом сначала закрывается. Два действия под одним
/// номером, а не два номера, потому что вопрос у них один и тот же — «пусть
/// этот файл зовётся ещё и так», — а различает их только то, назван ли второй
/// номер. Ровно так же устроено поле `кто` у [`SYS_SPAWN`], где [`SPAWN_INHERIT`]
/// означает «не называю».
///
/// # Куда продублировать нельзя
///
/// В ноль, единицу и двойку. Стандартные потоки в этой системе — **не** места
/// таблицы дескрипторов: за ними стоит терминал либо конец канала, выданный
/// запускающим, и подменить их записью в таблице нечем. Просьба занять такой
/// номер получает [`ERR_UNSUPPORTED`], а не тихо исполняется мимо цели.
///
/// Это ограничение, а не недосмотр, и у него есть прямая замена: перенаправляет
/// потоки [`SYS_LAUNCH`], называя их у **запускаемой** программы. Классический
/// `dup2(fd, 1)` нужен там, где потоки переставляют себе между `fork` и `exec`;
/// здесь нет ни того, ни другого — `spawn` и есть весь `exec`, и назвать потоки
/// он даёт сразу.
///
/// # Позиция у копий общая, и это не деталь
///
/// Обе копии указывают на **один открытый файл**, а не на два одинаковых.
/// Сдвинул позицию через один дескриптор — она сдвинулась и у второго; дописал
/// через один — второй пишет следом, а не поверх. Так устроен `dup` в POSIX, и
/// иначе нельзя: библиотека, продублировавшая дескриптор ради `FILE*`, стала бы
/// писать двумя буферами в одно место, затирая собственный вывод. Отдельные
/// позиции выглядели бы как работающий `dup` ровно до первой дописи в конец —
/// то есть до случая, который никто не проверяет.
///
/// Что у копий **не** общее — сам номер: закрытие одной оставляет другую живой.
/// Файл закрывается, когда закрылась последняя.
pub const SYS_DUP: usize = 46;

/// Узнать о **открытом** файле. `(fd, out) -> 0`.
///
/// То же, что [`SYS_STAT`], но спрашивает про дескриптор, а не про имя. Разница
/// не в удобстве: имя между `open` и `stat` могло начать указывать на другой
/// файл — его переименовали или подменили, — и программа, проверившая права по
/// имени, а прочитавшая по дескриптору, проверила не тот файл. Дескриптор
/// указывает на то, что действительно открыто.
///
/// `out` — адрес [`Stat`] в памяти программы, и выравнивание обязательно, как у
/// [`SYS_STAT`].
///
/// У канала [`Stat::kind`] равен [`KIND_PIPE`], а `size` — ноль: у канала нет
/// длины, и сочинить её значило бы сказать библиотеке, что перед ней файл,
/// который можно перечитать с начала. Именно этим вызовом libc и отличает
/// «вывод в файл» от «вывод в трубу», выбирая, буферизовать ли ей построчно.
pub const SYS_FSTAT: usize = 47;

/// Терминал ли за этим дескриптором. `(fd) -> 1 | 0`.
///
/// Единица — да, ноль — нет; отрицательное — такого дескриптора нет вовсе, и
/// это третий ответ, а не «нет»: закрытый дескриптор и дескриптор файла требуют
/// от программы разного.
///
/// # Зачем отдельный вызов, если есть [`SYS_FSTAT`]
///
/// Потому что вопрос другой. `fstat` отвечает, **что** за дескриптором лежит, а
/// этот — **куда он в итоге идёт**: стандартный вывод остаётся стандартным
/// выводом и тогда, когда его увели в канал, и различить эти два случая по виду
/// дескриптора нельзя. От ответа зависит поведение всякой libc: на терминал она
/// пишет построчно, чтобы человек видел строку сразу, а в файл или канал —
/// кусками по несколько килобайт, потому что иначе каждая запятая стоила бы
/// системного вызова. Библиотека, которой этого не сказали, выбирает построчно
/// всегда — и медленна ровно там, где её вывод перенаправили.
pub const SYS_ISATTY: usize = 48;

/// Который час — с долями секунды. `(какие часы, out) -> 0`.
///
/// `out` — адрес [`Timespec`]. Часы бывают двое, и путать их нельзя:
/// [`CLOCK_REALTIME`] говорит, который час в мире, и вправе прыгнуть, если
/// систему поправили; [`CLOCK_MONOTONIC`] говорит, сколько система работает, и
/// не убывает никогда. Измерять длительность первыми — классическая ошибка: она
/// даёт отрицательные промежутки ровно тогда, когда часы поправили.
///
/// Отличается от [`SYS_TIME`] разрешением, и ради него и заведён: секунда —
/// слишком грубая единица для библиотеки, которой надо поставить срок или
/// измерить, сколько заняла работа.
///
/// # Чего эти часы не обещают
///
/// Наносекунды в [`Timespec`] — **единица хранения, а не точность**. Настоящее
/// разрешение — то, с каким идёт монотонный счётчик машины; там, где его нет,
/// время считается тиками таймера, и младшие разряды окажутся нулями. Обещать
/// наносекунду там, где её неоткуда взять, значило бы соврать в ту сторону,
/// которую программа не может проверить.
pub const SYS_CLOCK: usize = 49;

/// Уснуть на заданное время. `(секунды, наносекунды) -> 0`.
///
/// Отличается от [`SYS_SLEEP`] единицей, и только ею: тот принимает
/// миллисекунды, а библиотеке нужен `nanosleep`, у которого в договоре
/// наносекунды.
///
/// # Сколько на самом деле
///
/// **Не меньше запрошенного, но с точностью до тика.** Сон в этой системе
/// устроен сроком в тиках таймера, а таймер идёт со своей частотой; просьба
/// поспать микросекунду округляется **вверх** до целого тика. Округление вверх,
/// а не вниз, выбрано намеренно: вернуться раньше срока — это нарушить
/// единственное, что вызов обещает, и поймать такое в программе, которая ждала
/// готовности устройства, почти невозможно. Проспать лишнее — заметно и честно.
///
/// Прерваться этому сну нечем: сигналов в системе нет, поэтому вызов не
/// возвращает остатка и всегда досыпает до конца.
pub const SYS_NANOSLEEP: usize = 50;

/// Подождать, пока хоть один дескриптор будет готов. `(ptr, сколько, срок) ->
/// сколько готовых`.
///
/// `ptr` — массив из `сколько` структур [`PollFd`]; ядро заполняет в каждой
/// поле [`PollFd::ready`]. `срок` — миллисекунды; ноль означает «спросить и не
/// ждать», [`POLL_FOREVER`] — «ждать сколько угодно». Возврат — число
/// дескрипторов, у которых что-нибудь готово; ноль означает, что вышел срок.
///
/// # Зачем это нужно
///
/// Затем, что до сих пор программа умела ждать ровно **одного**: чтение
/// останавливало её на том дескрипторе, который она назвала. Программе,
/// которой надо обслуживать два источника сразу, оставался опрос в цикле — то
/// есть занимать процессор, ничего не делая. Здесь она засыпает и просыпается
/// от первого же события.
///
/// # Чего здесь нет, и это названный предел
///
/// **Сокетов.** Номер сокета — не файловый дескриптор, и сказано это не здесь, а
/// в договоре [`SYS_SOCKET`]: у датаграммы есть отправитель и границы, поэтому
/// сокеты живут в своём пространстве номеров. Свести два пространства в одно —
/// работа отдельная и честная, и делать её половиной ради одного вызова значило
/// бы получить `poll`, который на половину аргументов молча отвечает «не
/// готово». Пока её нет, сокеты спрашивают [`SYS_STREAMSTATE`] и [`SYS_RECV`], а
/// этот вызов принимает только дескрипторы — канал, терминал и файл.
///
/// Обычный файл **всегда готов**: у него нечего ждать: чтение с конца вернёт
/// ноль немедленно. Так же отвечает `poll` везде, где он есть.
pub const SYS_POLL: usize = 51;

/// Сколько процессорного времени истрачено. `(out) -> 0`.
///
/// `out` — адрес [`Times`]. Числа в миллисекундах, а не в «тиках», которые
/// пришлось бы делить на частоту, известную неизвестно откуда: единица, о
/// которой надо спрашивать вторым вызовом, — это приглашение поделить не на то.
///
/// Считается **настоящее** время на процессоре, а не время с запуска: задача,
/// проспавшая час, истратила ноль. Разница между этими двумя числами и есть
/// единственное, ради чего вызов существует, — иначе его заменил бы
/// [`SYS_UPTIME`], вычтенный из самого себя.
///
/// Что здесь **не** различается — время в ядре и время в программе. В POSIX это
/// два разных поля, и заполнять их одинаковым числом было бы ложью, а считать
/// порознь — значит мерить каждый вход в ядро и каждый выход, то есть платить
/// на всяком системном вызове за счётчик, которого никто пока не спрашивает.
/// Поэтому поле одно и названо так, как есть.
pub const SYS_TIMES: usize = 52;

/// Завести окно на рабочем столе. `(ptr на [`WindowSpec`], 0, 0) -> 0`.
///
/// До этой фазы окно было **частью ядра**: чтобы нарисовать своё, программе
/// пришлось бы стать модулем ядра. Здесь она просит окно и получает пиксели.
///
/// # Почему одна структура, а не два вызова
///
/// Потому что назвать надо шесть вещей, а аргументов три, — и потому что ответ
/// тоже двойной: номер окна и адрес поверхности. Структура лежит в памяти
/// программы и доступна ядру **на запись**, так что оба ответа уезжают обратно
/// в неё. Второй вызов «а теперь дай поверхность» означал бы окно, которое
/// между двумя вызовами существует без единого пикселя, — и вопрос, что рисовать
/// на столе всё это время.
///
/// # Что такое поверхность
///
/// Страницы, отображённые в адресное пространство программы: `width * height`
/// пикселей по четыре байта, строка за строкой, без промежутков. Программа
/// пишет в них как в обычную память — ни системного вызова, ни копии на точку.
/// Что она написала, попадёт на экран не само: пока не позван
/// [`SYS_WINCOMMIT`], компоновщик о правке не знает.
///
/// Владеет этими страницами **компоновщик**, а не программа. Отсюда два
/// следствия, и оба названы вслух: [`SYS_MUNMAP`] на поверхность отвечает
/// отказом (вернуть её можно только вместе с окном, [`SYS_WINCLOSE`]), а
/// завершение программы снимает окно и забирает страницы. Обратиться к ним
/// после этого — отказ страницы, то есть конец программы; так же ведёт себя
/// всякий адрес, которого больше нет.
pub const SYS_WINOPEN: usize = 53;

/// Сказать, какая часть окна изменилась. `(id, (x << 32) | y, (w << 32) | h) -> 0`.
///
/// Координаты — внутри поверхности, от её левого верхнего угла. Нулевая ширина
/// или высота означает «всё окно целиком»: это та просьба, которую хочется
/// уметь высказать одним числом, а не четырьмя.
///
/// # Почему компоновщик не смотрит сам
///
/// Потому что смотреть ему пришлось бы на всё: страницы программы меняются без
/// его ведома и без единого системного вызова — в этом весь смысл поверхности.
/// Единственная альтернатива — сравнивать кадр с прошлым, то есть читать всю
/// площадь окна каждый раз, когда изменилась одна точка. Слово программы дешевле
/// на порядки, а цена вранья ограничена: соврала — увидела на экране не то, что
/// нарисовала, и никто, кроме неё, от этого не пострадал.
///
/// Числа упакованы по два в аргумент по той же причине, что и у
/// [`SYS_WINSIZE`]: их четыре, а регистров три, и ради прямоугольника заводить
/// структуру в памяти значило бы добавить проверку указателя к вызову, который
/// зовут на каждый кадр.
pub const SYS_WINCOMMIT: usize = 54;

/// Забрать событие окна. `(id, ptr на [`WinEvent`], 0) -> 1 | 0`.
///
/// Единица — событие записано, ноль — очередь пуста. **Не ждёт**: программа,
/// которой нечем заняться, спит сама и решает сама, сколько. Ядро, уснувшее за
/// неё, отняло бы у неё это решение — ровно тот же довод, что у [`SYS_RECV`].
///
/// Очередь у каждого окна своя и конечная. Переполнение теряет **новые**
/// события, а не старые: [`WIN_CLOSE`] к этому моменту уже лежит в очереди, и
/// выбросить его ради очередного движения мыши значило бы получить окно,
/// которое невозможно закрыть.
pub const SYS_WINEVENT: usize = 55;

/// Закрыть своё окно. `(id) -> 0`.
///
/// Поверхность после этого недействительна: страницы сняты, и обращение к ним —
/// отказ. Закрывать окно перед выходом не обязательно — ядро снимет его само,
/// — но программа, которая продолжает работать, обязана: иначе окно останется
/// на столе, и закрыть его сможет только человек.
pub const SYS_WINCLOSE: usize = 56;

/// Заявка на окно — аргумент [`SYS_WINOPEN`].
///
/// Первые четыре поля заполняет программа, последние два — ядро. Разделение
/// названо здесь, а не подразумевается: структура, половину которой заполняет
/// другая сторона, иначе читается как «передай мусор и надейся».
#[repr(C)]
#[derive(Clone, Copy, Debug, Default)]
pub struct WindowSpec {
    /// Адрес заголовка окна в памяти программы. Заголовок — UTF-8, без нуля.
    pub title: u64,
    /// Его длина в байтах. Длиннее [`MAX_TITLE`] — отказ, а не обрезка: окно с
    /// урезанным именем человек ищет по имени, которого у него нет.
    pub title_len: u64,
    /// **Ответ ядра**: адрес поверхности в памяти программы.
    pub surface: u64,
    /// Ширина окна в точках.
    pub width: u32,
    /// Высота окна в точках.
    pub height: u32,
    /// **Ответ ядра**: номер окна, который принимают остальные вызовы.
    pub id: i64,
}

/// Событие окна — ответ [`SYS_WINEVENT`].
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct WinEvent {
    /// [`WIN_KEY`], [`WIN_POINTER`] или [`WIN_CLOSE`].
    pub kind: u32,
    /// Для [`WIN_KEY`] — **символ**, который даёт клавиша с учётом
    /// модификаторов; для [`WIN_POINTER`] — маска нажатых кнопок.
    ///
    /// Символ, а не код клавиши, и это названный предел. Код — внутреннее дело
    /// ядра: его нумерация не обещана никому и поменяется при первой же новой
    /// раскладке, а обещанное здесь не меняется вовсе. Плата — клавиши без
    /// символа (стрелки, F-ряд) событий не дают: класть им ноль значило бы
    /// сделать их все одной клавишей.
    pub code: u32,
    /// Для [`WIN_POINTER`] — точка **внутри поверхности**, а не на экране.
    ///
    /// Переводит её ядро: окно двигают мышью, и программа, считающая в
    /// экранных координатах, попадала бы мимо собственных кнопок всякий раз,
    /// когда окно сдвинули.
    pub x: i32,
    pub y: i32,
}

/// [`WinEvent::kind`]: нажата клавиша.
pub const WIN_KEY: u32 = 1;
/// [`WinEvent::kind`]: щелчок указателем внутри окна.
pub const WIN_POINTER: u32 = 2;
/// [`WinEvent::kind`]: окно просят закрыть — крестиком или `Ctrl+W`.
///
/// Просьба, а не приказ: закрывает окно [`SYS_WINCLOSE`], то есть сама
/// программа. Так у неё остаётся место спросить «сохранить?» — а у системы
/// остаётся способ снять окно силой, если программа не ответит: её саму снимают
/// `kill`, и окно уходит вместе с ней.
pub const WIN_CLOSE: u32 = 3;

/// Самый длинный заголовок окна, который принимает ядро.
pub const MAX_TITLE: usize = 64;

/// Счётчики системы. `(ptr на [`SysInfo`]) -> 0`.
///
/// # Зачем он понадобился
///
/// Затем, что монитор системы переехал из ядра в программу (фаза 47b). Пока он
/// был модулем ядра, числа он брал прямо из `mm::frame`, `mm::heap` и
/// планировщика — то есть из мест, к которым у программы нет и не должно быть
/// доступа. Вызов и есть та граница, через которую эти числа теперь проходят.
///
/// # Почему одна структура, а не десяток вызовов
///
/// Потому что числа читают **вместе** и показывают **рядом**. Десять вызовов
/// дали бы десять снимков, взятых в разные моменты: свободная память из одного
/// мига, число задач из другого. Для монитора это не придирка — он рисует
/// картину состояния, а картина, склеенная из разных мгновений, врёт тем
/// убедительнее, чем быстрее меняется система.
///
/// # Чего здесь нет, и это названный предел
///
/// **Списка задач.** Одно число «сколько живых» есть, перечисления с именами —
/// нет: это переменное число строк переменной длины, то есть разделяемый буфер
/// и его пределы, а не структура с полями. Работа отдельная и честная; пока её
/// нет, список задач печатает `tasks` в оболочке.
pub const SYS_SYSINFO: usize = 57;

/// Счётчики системы — ответ [`SYS_SYSINFO`].
///
/// Все размеры в **байтах**, всё время в **миллисекундах**: единица, о которой
/// надо спрашивать вторым вызовом, — это приглашение поделить не на то. Поля
/// только растут в конец, как и во всех структурах договора.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct SysInfo {
    /// Сколько система работает.
    pub uptime_ms: u64,
    /// Тиков таймера с запуска.
    pub ticks: u64,
    /// Всего физической памяти под кадры.
    pub frames_total: u64,
    /// Из них свободно.
    pub frames_free: u64,
    /// Размер кучи ядра.
    pub heap_size: u64,
    /// Сколько в ней свободно.
    pub heap_free: u64,
    /// Всего памяти под обмен с устройствами.
    pub dma_total: u64,
    /// Сколько её занято.
    pub dma_used: u64,
    /// Событий клавиатуры принято.
    pub keys_posted: u64,
    /// Событий клавиатуры потеряно: очередь была полна.
    pub keys_dropped: u64,
    /// Отчётов указателя принято.
    pub pointer_moves: u64,
    /// Из них слито в одно движение.
    pub pointer_merged: u64,
    /// Кадров собрано компоновщиком.
    pub frames_composed: u64,
    /// Прямоугольников перерисовано.
    pub rects: u64,
    /// Окон на столе сейчас.
    pub windows: u32,
    /// Живых задач сейчас.
    pub tasks_alive: u32,
    /// Признаки: [`SYSINFO_DARK`].
    pub flags: u32,
    /// В каком виде лежат точки поверхности: [`PIXEL_RGB`] или [`PIXEL_BGR`].
    ///
    /// Без этого числа программа не может нарисовать **ни одного цвета**, и это
    /// не преувеличение: упаковка точки зависит от машины, узнаёт её прошивка, а
    /// программа прошивку не видит. Рисующий наугад перепутает красное с синим
    /// на половине машин — и узнает об этом только глазами.
    ///
    /// Ноль означает «система сама не знает» — так бывает на машине без
    /// графики. Рисовать в этом случае нечего и незачем.
    pub pixel_format: u32,
}

/// [`SysInfo::pixel_format`]: красный лежит в младшем байте точки.
pub const PIXEL_RGB: u32 = 1;
/// [`SysInfo::pixel_format`]: синий лежит в младшем байте точки.
pub const PIXEL_BGR: u32 = 2;

/// [`SysInfo::flags`]: на столе сейчас тёмная тема.
///
/// Признак здесь, а не отдельным вызовом, по той же причине, по которой все
/// числа приехали одной структурой: программа, рисующая окно, спрашивает тему
/// ровно тогда же, когда спрашивает, что в этом окне показать. Без него монитор
/// не узнал бы о смене темы вовсе — своего состояния стола у программы нет, а
/// события «тема изменилась» договор не знает.
pub const SYSINFO_DARK: u32 = 1;

/// Версия договора между ядром и программой.
///
/// # Что эта версия обещает
///
/// Что номера вызовов и раскладки структур **не меняются**. С этой фазы они —
/// не внутреннее дело двух наших крейтов, которые собираются вместе и потому
/// всегда согласны, а договор с программами, собранными когда-то отдельно.
/// Программа, собранная под эту версию, ждёт [`SYS_READ`] под номером шесть и
/// [`Stat`] с размером в первых восьми байтах; ядро, которое передумает,
/// сломает её молча — она попросит прочитать файл и получит, что успеет.
///
/// Отсюда правило, ради которого константа и заведена: **номер, однажды
/// выданный, не переиспользуется, а поля в середине структур не вставляются.**
/// Новый вызов получает следующий свободный номер; отменённый остаётся
/// занятым навсегда и отвечает [`ERR_NO_SYSCALL`]. Новое поле дописывается в
/// конец структуры, и только если её размер при этом растёт — что тоже
/// изменение версии.
///
/// Проверяется это не обещанием, а тестами рядом с константой: они называют
/// каждый номер и каждый размер числом. Тест, который придётся поправить, —
/// это и есть тот разговор, который иначе не состоялся бы.
///
/// Младшая половина растёт, когда вызовы **добавляются**: программа постарше
/// продолжает работать, потому что всё, что она знала, осталось на месте.
/// Старшая — когда что-нибудь меняет смысл; такого пока не случалось, и
/// случаться не должно.
pub const ABI_VERSION: u32 = 0x0001_0000;

/// [`SYS_DUP`]: «дай самый маленький свободный номер».
///
/// Не ноль и не отрицательное: ноль — законный дескриптор (стандартный ввод), а
/// отрицательные заняты кодами ошибок. Тем же значением и по той же причине
/// пользуется [`SPAWN_INHERIT`].
pub const DUP_ANY: usize = usize::MAX;

/// [`SYS_CLOCK`]: часы, показывающие время суток, — секунды эпохи Unix, UTC.
///
/// Могут прыгнуть: система, узнавшая точное время после загрузки, поправит их.
/// Мерить ими длительность нельзя.
pub const CLOCK_REALTIME: usize = 0;

/// [`SYS_CLOCK`]: часы, показывающие время работы системы.
///
/// Не убывают и не прыгают. Именно ими меряют, сколько заняла работа.
pub const CLOCK_MONOTONIC: usize = 1;

/// [`SYS_POLL`]: ждать без срока.
pub const POLL_FOREVER: i64 = -1;

/// [`PollFd::wanted`]: есть что прочитать (или наступил конец).
///
/// Конец файла — это тоже готовность, и путать его с «ничего нет» нельзя:
/// программа, ждущая данных на закрытом канале, иначе ждала бы вечно. Читающий
/// узнает о конце нулём от [`SYS_READ`], как и всегда.
pub const POLL_IN: u32 = 1;

/// [`PollFd::wanted`]: есть куда записать хотя бы байт.
pub const POLL_OUT: u32 = 2;

/// [`PollFd::ready`]: другой конец закрыт.
///
/// Заполняется ядром, даже если его не просили: это не то, чего ждут, а то, что
/// случилось. Так же ведёт себя `poll` в POSIX, и по той же причине — программе,
/// которая ждала возможности записать, надо узнать, что записывать больше
/// некому, а не ждать её до конца срока.
pub const POLL_HUP: u32 = 4;

/// [`PollFd::ready`]: дескриптора нет.
///
/// Тоже заполняется без просьбы, и тоже считается готовностью: иначе `poll` с
/// одним закрытым дескриптором в списке ждал бы полный срок, чтобы ответить
/// «ничего не произошло».
pub const POLL_BAD: u32 = 8;

/// Время с долями секунды — ответ [`SYS_CLOCK`].
///
/// Два поля, а не одно число наносекунд: наносекунды эпохи Unix перестанут
/// помещаться в 64 бита в 2262 году, и система, у которой это записано в
/// договоре, доживёт до собственной ошибки. Секунды отдельно — так же, как во
/// всяком `timespec`.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Timespec {
    /// Секунды. Для [`CLOCK_REALTIME`] — от эпохи Unix; для
    /// [`CLOCK_MONOTONIC`] — с запуска системы.
    pub seconds: u64,
    /// Наносекунды сверх них: всегда меньше миллиарда.
    pub nanos: u32,
    pub _reserved: u32,
}

/// Один дескриптор в вопросе [`SYS_POLL`].
///
/// `#[repr(C)]` и никаких байтов на своё усмотрение: массив этих структур пишет
/// программа, а читает и дополняет ядро.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct PollFd {
    /// О каком дескрипторе спрашиваем. Отрицательный — пропустить эту запись
    /// молча: так удобнее тому, кто держит список постоянным и временно
    /// выключает из него строки.
    pub fd: i64,
    /// Чего ждём: [`POLL_IN`], [`POLL_OUT`] или их сумма.
    pub wanted: u32,
    /// Что готово на самом деле. Заполняет ядро; кроме запрошенного, здесь
    /// может оказаться [`POLL_HUP`] или [`POLL_BAD`].
    pub ready: u32,
}

/// Истраченное процессорное время — ответ [`SYS_TIMES`].
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Times {
    /// Сколько миллисекунд эта программа занимала процессор.
    pub cpu_ms: u64,
    /// Сколько миллисекунд работает система — то же, что [`SYS_UPTIME`].
    ///
    /// Лежит здесь не для красоты: одно число без другого не значит ничего.
    /// «Истрачено двести миллисекунд» — это много или мало, зависит от того,
    /// за какой срок, и спрашивать второй вызов ради знаменателя значило бы
    /// получить его на несколько переключений позже числителя.
    pub uptime_ms: u64,
}

/// [`SYS_MMAP`]: просить крупные страницы, по 2 МиБ вместо 4 КиБ.
///
/// Тот самый флаг, которого у [`SYS_MMAP`] намеренно не было. Заводится он не
/// потому, что передумали, а потому, что появилось **второе достижимое
/// состояние**: до этой фазы выбор был между «читать и писать» и «ничего», и
/// слово флагов с одним допустимым значением было бы обещанием выбора, которого
/// нет. Крупные страницы — выбор настоящий, и у него есть цена.
///
/// Цена такая. Гигабайт обычными страницами — это четверть миллиона записей в
/// TLB, и обход по нему упирается не в память, а в промахи трансляции; тот же
/// гигабайт крупными — пятьсот двенадцать записей. Зато крупная страница
/// требует непрерывных и выровненных двух мегабайт физической памяти, а их на
/// раздробленной машине может не найтись.
///
/// **Отказа при этом не будет.** Не нашлось — ядро отобразит обычными
/// страницами и вернёт тот же адрес: флаг просит, а не требует. Что вышло на
/// самом деле, ядро говорит в журнале, и это единственный способ отличить «дали
/// крупными» от «дали как обычно» — со стороны программы они неразличимы, и в
/// этом весь смысл флага, который можно не проверять.
///
/// Для [`SYS_MMAP_FILE`] флаг бессмысленен и не принимается: подкачка работает
/// постранично, и блок ей нечем ни дочитать, ни вытеснить.
pub const MAP_HUGE: usize = 1;

/// [`Launch::stdin`] / [`Launch::stdout`]: оставить поток как есть.
