//! Договор между ядром и пользовательской программой.
//!
//! Крейт существует затем, чтобы номера системных вызовов были **одним** местом
//! в дереве исходников. Две таблицы констант — в ядре и в программе —
//! расходятся молча: программа просит записать в консоль, ядро понимает это как
//! «завершиться», и найти такое сложнее, чем не допустить.
//!
//! Никакой **логики** здесь нет и быть не должно: ядро и пользовательская
//! программа исполняются на разных уровнях привилегий, и общая функция между
//! ними — это приглашение однажды позвать не ту. Раскладка данных — другое
//! дело: [`Stat`] пересекает границу, и понимать её одинаково обязаны обе
//! стороны. Поэтому здесь есть `repr(C)`-структуры и нет ни одной функции.
//!
//! # Соглашение о вызове
//!
//! Взято у Linux, и не из уважения к традиции, а потому что оно уже описано,
//! разобрано и знакомо:
//!
//! ```text
//!   x86-64    номер в rax, аргументы в rdi, rsi, rdx; результат в rax; int 0x80
//!   aarch64   номер в  x8, аргументы в  x0,  x1,  x2; результат в  x0; svc #0
//! ```
//!
//! `int 0x80`, а не `syscall`, выбран сознательно. `syscall`/`sysret` быстрее,
//! но диктуют раскладку GDT (пара селекторов обязана лежать подряд в строго
//! определённом порядке) и требуют настройки четырёх MSR. Программная ловушка
//! — тот же механизм, которым на AArch64 работает `svc`, то есть одна модель на
//! обе архитектуры вместо двух разных. Скорость системного вызова станет важна
//! тогда, когда их будет миллион в секунду; сейчас их единицы.

#![no_std]

/// Записать байты в поток. `(fd, ptr, len) -> сколько записано`.
pub const SYS_WRITE: usize = 1;

/// Завершить программу. `(code) -> не возвращается`.
pub const SYS_EXIT: usize = 2;

/// Уступить процессор остальным задачам. `() -> 0`.
///
/// Отдаёт очередь, оставаясь готовой к исполнению, — в отличие от
/// [`SYS_SLEEP`], который из очереди выводит.
pub const SYS_YIELD: usize = 3;

/// Сколько миллисекунд система работает. `() -> миллисекунды`.
///
/// Самый дешёвый вызов, возвращающий **данные ядра**: по нему видно, что через
/// границу привилегий проходит не только направление «наружу».
pub const SYS_UPTIME: usize = 4;

/// Открыть файл. `(ptr, len, flags) -> дескриптор`.
///
/// Флаги — [`O_WRITE`], [`O_CREATE`], [`O_TRUNC`]; ноль означает «на чтение».
/// Они появились в Phase 14b вместе с самой записью: до неё аргумент «режим
/// открытия», из которого допустимо ровно одно значение, был бы обещанием,
/// которого не существует.
pub const SYS_OPEN: usize = 5;

/// Прочитать из дескриптора. `(fd, ptr, len) -> сколько прочитано`.
///
/// Ноль означает конец файла, а не ошибку. Смещение хранит ядро: файл читается
/// подряд, потому что искать по нему пока нечем — `seek` появится тогда, когда
/// у него будет вызывающий.
pub const SYS_READ: usize = 6;

/// Закрыть дескриптор. `(fd) -> 0`.
pub const SYS_CLOSE: usize = 7;

/// Узнать о файле, не открывая его. `(ptr, len, out) -> 0`.
///
/// `out` — адрес [`Stat`] в памяти программы. Отдельный вызов, а не поле в
/// `open`, потому что спросить про файл и получить к нему доступ — разные
/// права: для первого нужен проход по каталогам пути, для второго ещё и чтение
/// самого файла.
pub const SYS_STAT: usize = 8;

/// От чьего имени исполняется программа. `() -> uid`.
pub const SYS_GETUID: usize = 9;

/// Группа, от имени которой исполняется программа. `() -> gid`.
pub const SYS_GETGID: usize = 10;

/// Номер программы. `() -> идентификатор`.
///
/// Он же номер задачи планировщика: программа исполняется задачей, и заводить
/// для тех же объектов второе пространство имён значило бы всё время
/// сопоставлять одно с другим.
pub const SYS_GETPID: usize = 11;

/// Уснуть на указанное число миллисекунд. `(ms) -> 0`.
///
/// Отличается от [`SYS_YIELD`] не длительностью, а тем, что спящая программа
/// **не претендует на процессор**: она выходит из ротации планировщика до
/// срока. Уступка в цикле, которой приходилось изображать сон до Phase 13d,
/// занимала процессор ровно столько же, сколько занимал бы счёт.
pub const SYS_SLEEP: usize = 12;

/// Создать каталог. `(ptr, len, mode) -> 0`.
pub const SYS_MKDIR: usize = 13;

/// Удалить файл или пустой каталог. `(ptr, len) -> 0`.
///
/// Один вызов на оба случая, в отличие от Unix с его `unlink` и `rmdir`.
/// Разделение там историческое: `unlink` на каталоге когда-то оставлял
/// потерянные поддеревья, и запретить его было проще, чем чинить. Здесь
/// удаление каталога и так требует, чтобы он был пуст, а два имени для одного
/// действия — это две дороги к одной ошибке.
pub const SYS_REMOVE: usize = 14;

/// Передвинуть позицию в открытом файле. `(fd, offset, whence) -> позиция`.
///
/// До этого вызова файл можно было читать и писать только подряд, от начала и
/// до конца: позиция двигалась сама и только вперёд. Программе, которой нужен
/// хвост файла или его размер, приходилось прочитать всё остальное — то есть
/// заплатить за содержимое, которое ей не нужно.
///
/// `whence` — одно из [`SEEK_SET`], [`SEEK_CUR`], [`SEEK_END`]; смещение
/// знаковое, поэтому назад двигаться тоже можно. Позиция за концом файла
/// разрешена и ошибкой не является: чтение оттуда вернёт ноль байт, а запись —
/// это дыра, которой в ext2 без поддержки разрежённых файлов не будет, поэтому
/// запись за концом пока просто расширяет файл нулями.
pub const SYS_SEEK: usize = 15;

/// Текущее время в секундах эпохи Unix, UTC. `() -> секунды`.
///
/// Ноль означает, что система времени суток не знает: часов не было ни у
/// прошивки, ни у платы. Это не ошибка вызова, а честный ответ, и программа,
/// которой время нужно для метки, обязана его различать — иначе она поставит
/// 1970 год и будет уверена, что знает, когда это было.
///
/// Отличается от [`SYS_UPTIME`] тем же, чем часы отличаются от секундомера:
/// одно говорит, который час, другое — сколько машина работает.
pub const SYS_TIME: usize = 16;

/// Прочитать очередную запись открытого каталога. `(fd, ptr, len) -> 1 | 0`.
///
/// Единица означает «запись записана по `ptr`», ноль — «каталог кончился».
/// Ошибки, как обычно, отрицательны.
///
/// Каталог для этого открывается тем же [`SYS_OPEN`] — до этой фазы он на
/// каталоге отказывал, потому что читать из полученного дескриптора было
/// нечем. Позиция двигается сама, как у файла: `readdir` в цикле проходит
/// каталог ровно один раз.
///
/// # Что этот вызов обещает и чего не обещает
///
/// Список **фиксируется в момент открытия**: каталог читается целиком, и
/// дальнейшие изменения на диске в уже открытый дескриптор не попадают. Так же
/// ведёт себя `readdir` в POSIX, и по той же причине: перечисление, которое
/// меняется под руками у того, кто его читает, невозможно ни закончить, ни
/// объяснить.
///
/// Порядок записей — тот, в котором они лежат на носителе. Сортировки нет:
/// сортировать — дело того, кто показывает, и делать это в ядре значило бы
/// выбрать за всех одно правило сравнения.
pub const SYS_READDIR: usize = 17;

/// Размер окна программы в знаках. `() -> (столбцы << 32) | строки`.
///
/// Два числа в одном ответе, а не структура по указателю: оба помещаются в
/// регистр результата целиком, и вызов, которому не нужна память программы, не
/// может ошибиться адресом. Нули означают, что окна нет вовсе — система работает
/// в серийной консоли, и программа, рисующая рамку, обязана этот случай
/// различать.
pub const SYS_WINSIZE: usize = 18;

/// Переключить режим терминала. `(режим) -> 0`.
///
/// [`TTY_LINE`] — строка собирается терминалом и приезжает по Enter, с эхом.
/// [`TTY_RAW`] — каждое нажатие приезжает немедленно и без эха.
///
/// Режим принадлежит программе, а не терминалу: ядро возвращает построчный
/// режим само, когда программа заканчивается. Иначе программа, снятая
/// `Ctrl+C` посреди работы, оставила бы оболочку, в которой не видно
/// набираемого.
pub const SYS_TTYMODE: usize = 19;

/// Переименовать файл или каталог. `(ptr, старая длина, общая длина) -> 0`.
///
/// Оба пути лежат **в одном буфере** подряд: у вызова три аргумента, а нужно
/// четыре значения — два адреса и две длины. Склейка дешевле расширения
/// соглашения о вызовах, которое пришлось бы поменять на обеих архитектурах
/// ради одного вызова; а раз буфер всё равно копируется в ядро целиком, второй
/// адрес не дал бы ничего, кроме второй проверки прав доступа.
///
/// Переименование — не «скопировать и удалить»: содержимое не читается вовсе,
/// меняется только имя, под которым оно лежит. Разница видна на файле в
/// гигабайт и на файле, открытом кем-то ещё.
pub const SYS_RENAME: usize = 20;

/// Запустить программу отдельной задачей. `(ptr, len, кто) -> номер задачи`.
///
/// `ptr`/`len` — командная строка целиком: путь, пробел, аргументы. Разбирает её
/// ядро тем же кодом, которым разбирает строку от оболочки, — иначе запуск из
/// программы и запуск из оболочки понимали бы кавычки и пробелы по-разному.
///
/// `кто` — [`SPAWN_INHERIT`] либо `(uid << 32) | gid`. Снизить права вправе
/// кто угодно, повысить — никто: программа, исполняющаяся не от root, получает
/// [`ERR_PERMISSION`] на любой uid, кроме своего. Это и есть механизм, ради
/// которого поле существует: супервизор служб исполняется от root, а служба —
/// от того, кто записан в её описании, и наследование прав запуска от родителя
/// сделало бы описание украшением.
///
/// Возврат — номер задачи, тот же, что показывает `tasks` и что принимает
/// [`SYS_WAIT`]. Ждать запущенного никто не обязан: программа, которой ответ не
/// нужен, просто не спрашивает — так работают службы.
///
/// # Чего здесь нет
///
/// `fork`. Копировать адресное пространство незачем: единственное, ради чего
/// его копируют в Unix, — это `exec` следом, а `exec` здесь и есть весь вызов.
/// Нет и наследования открытых файлов: таблица дескрипторов у новой задачи
/// своя и пустая. Наследование потребовало бы решить, что делать с позицией в
/// общем файле, — вопрос, у которого сегодня нет ни одного задающего.
pub const SYS_SPAWN: usize = 21;

/// Узнать, чем кончилась задача. `(id, флаги) -> код возврата`.
///
/// Без флагов вызов **ждёт**: программа выходит из очереди планировщика до тех
/// пор, пока та задача не закончится. С [`WAIT_NOHANG`] не ждёт вовсе и отвечает
/// [`ERR_AGAIN`], если она ещё работает.
///
/// Второй режим существует ради супервизора, и это не удобство: служб у него
/// несколько, а ожидание блокирует на **одной**. Уснув на первой, он не заметил
/// бы падения второй до тех пор, пока не упадёт первая. «Дождаться любой» было
/// бы третьим вариантом, но он потребовал бы от ядра списка детей — то есть
/// родства, которого в этой системе нет: задача не помнит, кто её запустил.
pub const SYS_WAIT: usize = 22;

/// Создать файл с заданными правами и открыть его на запись. `(ptr, len, mode)
/// -> дескриптор`.
///
/// Отдельный вызов, а не четвёртый аргумент [`SYS_OPEN`]: аргументов у
/// системного вызова три на обеих архитектурах, и расширять соглашение ради
/// одного случая пришлось бы в четырёх местах — в двух вставках ассемблера, в
/// обработчике ловушки и в договоре. Отдельный номер стоит дешевле.
///
/// Существует потому, что `open` с `O_CREATE` создаёт файл правами `0644`, и
/// это правильное умолчание для всех, кроме одного: тот, кто раскладывает
/// пакет, обязан положить программу исполняемой. Права при этом берутся из
/// манифеста, то есть из данных, — поэтому ядро обрезает их до девяти бит и
/// проверяет право писать в каталог так же, как при обычном создании.
///
/// На занятое имя отвечает [`ERR_EXISTS`], а не «обрежу и открою». Разница
/// важна ровно там, где этот вызов и применяется: пакет, ставящийся поверх
/// чужого файла, — это не установка, а порча, и молчаливое перезаписывание
/// скрыло бы её.
pub const SYS_CREATE: usize = 23;

/// [`SYS_SPAWN`]: запустить с теми же правами, что у запускающего.
///
/// Не ноль: ноль — это root, и «наследовать» пришлось бы записывать числом,
/// которое означает совсем другое.
pub const SPAWN_INHERIT: usize = usize::MAX;

/// [`SYS_WAIT`]: не ждать; ответить сразу, даже если задача ещё работает.
pub const WAIT_NOHANG: usize = 1;

/// Задача ещё не закончилась — ответ [`SYS_WAIT`] с [`WAIT_NOHANG`].
///
/// Отличается от ошибки намеренно, хотя число отрицательное: это единственный
/// «отказ», который означает, что всё идёт как надо.
pub const ERR_AGAIN: i64 = -17;

/// Задачи с таким номером нет — или уже нет.
///
/// Ждать её бессмысленно, и это не то же самое, что [`ERR_AGAIN`]: там надо
/// спросить ещё раз, здесь — перестать спрашивать.
pub const ERR_NO_TASK: i64 = -18;

/// В таблице задач нет места под ещё одну.
pub const ERR_TOO_MANY_TASKS: i64 = -19;

/// [`SYS_TTYMODE`]: строку собирает терминал, программа получает её по Enter.
pub const TTY_LINE: usize = 0;
/// [`SYS_TTYMODE`]: нажатия приезжают немедленно и без эха.
pub const TTY_RAW: usize = 1;

/// [`SYS_SEEK`]: смещение считается от начала файла.
pub const SEEK_SET: usize = 0;
/// [`SYS_SEEK`]: от текущей позиции.
pub const SEEK_CUR: usize = 1;
/// [`SYS_SEEK`]: от конца файла. Так узнают размер, не читая содержимого.
pub const SEEK_END: usize = 2;

/// Флаг [`SYS_OPEN`]: открыть на запись.
pub const O_WRITE: usize = 1;

/// Флаг [`SYS_OPEN`]: создать, если файла нет.
pub const O_CREATE: usize = 2;

/// Флаг [`SYS_OPEN`]: обрезать существующий файл до нуля.
///
/// Отдельно от [`O_CREATE`] намеренно: «создать, если нет» и «выбросить то, что
/// было» — разные намерения, и программа, желающая дописать в конец, просит
/// только первое.
pub const O_TRUNC: usize = 4;

/// Поток ввода программы.
///
/// Чтение из него останавливает программу, пока человек чего-нибудь не наберёт,
/// и возвращает ноль, когда ввод кончился (`Ctrl+D`). Ноль здесь означает ровно
/// то же, что у файла, — «больше ничего не будет», — и потому не ошибка.
pub const FD_STDIN: usize = 0;

/// Поток вывода программы.
pub const FD_STDOUT: usize = 1;

/// Поток диагностики программы.
///
/// Отличается от [`FD_STDOUT`] адресатом, а не оформлением: он уходит в журнал
/// системы, минуя окно. Полноэкранной программе, которая рисует весь экран
/// целиком, это единственный способ сказать слово, не испортив картинку, — и
/// единственный способ проверить её снаружи, потому что снимок экрана
/// доказательством не является.
pub const FD_STDERR: usize = 2;

/// Первый дескриптор, который выдаёт [`SYS_OPEN`].
///
/// Ноль, единица и двойка зарезервированы за потоками ввода-вывода — так же,
/// как в Unix, и по той же причине: программа, печатающая в дескриптор 1,
/// не должна попасть в файл, открытый первым.
pub const FD_FIRST: usize = 3;

/// Сколько файлов программа может держать открытыми одновременно.
///
/// Предел маленький и намеренно виден в договоре: таблица дескрипторов у ядра
/// одна на программу и не растёт, а вызов, который иногда отказывает, лучше
/// вызова, который иногда съедает всю память ядра.
pub const MAX_OPEN_FILES: usize = 8;

/// Что ядро знает о файле. Ответ [`SYS_STAT`].
///
/// `repr(C)` и только скалярные поля: структура пересекает границу привилегий,
/// то есть её раскладку обязаны одинаково понимать две программы, собранные
/// порознь. Это данные, а не код, — общей логики между кольцами по-прежнему
/// нет (см. заголовок крейта).
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Stat {
    /// Размер в байтах. У каталога — размер его записи на носителе.
    pub size: u64,
    /// Права в unix-нотации: `rwxrwxrwx` в младших девяти битах.
    pub mode: u32,
    pub uid: u32,
    pub gid: u32,
    /// [`KIND_FILE`] или [`KIND_DIRECTORY`].
    pub kind: u32,
}

/// Одна запись каталога. Ответ [`SYS_READDIR`].
///
/// Имя лежит массивом внутри структуры, а не указателем: указатель пришлось бы
/// куда-то положить, а единственная память, общая у ядра и программы, — это
/// буфер, который программа сама и передала. Двести пятьдесят пять байт — тот
/// же предел, что у имени в ext2, поэтому обрезать имена этот вызов не может.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct Dirent {
    /// Размер в байтах; у каталога — размер его записи на носителе.
    pub size: u64,
    /// Время последнего изменения, секунды эпохи Unix. Ноль — «неизвестно».
    pub mtime: u32,
    /// Права в unix-нотации.
    pub mode: u32,
    pub uid: u32,
    pub gid: u32,
    /// [`KIND_FILE`] или [`KIND_DIRECTORY`].
    pub kind: u32,
    /// Сколько байт имени значимы.
    pub name_len: u32,
    /// Имя без завершающего нуля: длина известна из `name_len`.
    pub name: [u8; MAX_NAME],
}

impl Default for Dirent {
    fn default() -> Self {
        Self {
            size: 0,
            mtime: 0,
            mode: 0,
            uid: 0,
            gid: 0,
            kind: 0,
            name_len: 0,
            name: [0; MAX_NAME],
        }
    }
}

impl Dirent {
    /// Имя записи. `None`, если ядро прислало не-UTF-8 или длину сверх буфера —
    /// ни того, ни другого быть не должно, но проверяет это программа, а не
    /// вера в ядро.
    #[must_use]
    pub fn name(&self) -> Option<&str> {
        let len = self.name_len as usize;
        if len > MAX_NAME {
            return None;
        }
        core::str::from_utf8(&self.name[..len]).ok()
    }
}

/// Предел длины имени в [`Dirent`]. Столько же, сколько хранит ext2.
pub const MAX_NAME: usize = 255;

/// Обычный файл в [`Stat::kind`].
pub const KIND_FILE: u32 = 1;
/// Каталог в [`Stat::kind`].
pub const KIND_DIRECTORY: u32 = 2;

/// Код возврата, которым ядро завершает программу, снятую из-за отказа.
///
/// Отрицательное значение отличает «ядро сняло» от любого кода, который
/// программа могла бы вернуть сама.
pub const EXIT_FAULTED: i64 = -1;

/// Код возврата, которым ядро завершает программу, снятую по требованию.
///
/// Отличается от [`EXIT_FAULTED`] намеренно: снятая по команде программа ничего
/// не нарушила, и путать её с той, что обратилась по нулевому адресу, значит
/// потерять единственное различие, которое тут есть. Число взято за концом
/// кодов ошибок системных вызовов — они возвращаются программе, а этот код
/// программа не видит вовсе.
pub const EXIT_KILLED: i64 = -13;

/// Ошибка системного вызова: номера нет.
pub const ERR_NO_SYSCALL: i64 = -2;

/// Такое имя уже занято.
pub const ERR_EXISTS: i64 = -14;

/// Каталог не пуст.
pub const ERR_NOT_EMPTY: i64 = -15;

/// На носителе кончилось место.
