    /// Ни один номер не выдан дважды.
    ///
    /// Отдельно от проверки выше, потому что ловит другое: там сверяются
    /// значения по одному, а здесь — что среди них нет повторов. Два вызова с
    /// одним номером собираются молча, и обнаруживается это тем, что один из
    /// них никогда не исполняется.
    #[test]
    fn syscall_numbers_are_unique() {
        let numbers = [
            SYS_WRITE, SYS_EXIT, SYS_YIELD, SYS_UPTIME, SYS_OPEN, SYS_READ, SYS_CLOSE, SYS_STAT,
            SYS_GETUID, SYS_GETGID, SYS_GETPID, SYS_SLEEP, SYS_MKDIR, SYS_REMOVE, SYS_SEEK,
            SYS_TIME, SYS_READDIR, SYS_WINSIZE, SYS_TTYMODE, SYS_RENAME, SYS_SPAWN, SYS_WAIT,
            SYS_CREATE, SYS_SOCKET, SYS_BIND, SYS_CONNECT, SYS_SEND, SYS_RECV, SYS_PEER,
            SYS_CLOSE_SOCKET, SYS_NETCONF, SYS_RESOLVE, SYS_NETINFO, SYS_LISTEN, SYS_ACCEPT,
            SYS_SHUTDOWN, SYS_STREAMSTATE, SYS_RANDOM, SYS_PIPE, SYS_LAUNCH, SYS_UPDATE,
            SYS_MMAP, SYS_MUNMAP, SYS_MMAP_FILE, SYS_GETCPU, SYS_DUP, SYS_FSTAT, SYS_ISATTY,
            SYS_CLOCK, SYS_NANOSLEEP, SYS_POLL, SYS_TIMES, SYS_WINOPEN, SYS_WINCOMMIT,
            SYS_WINEVENT, SYS_WINCLOSE, SYS_SYSINFO,
        ];
        for (at, number) in numbers.iter().enumerate() {
            assert!(
                !numbers[..at].contains(number),
                "номер {number} выдан второй раз"
            );
        }
    }

    /// Раскладка структур, пересекающих границу привилегий.
    #[test]
    fn structures_keep_their_layout() {
        assert_eq!(size_of::<Stat>(), 24);
        assert_eq!(align_of::<Stat>(), 8);
        assert_eq!(core::mem::offset_of!(Stat, size), 0);
        assert_eq!(core::mem::offset_of!(Stat, mode), 8);
        assert_eq!(core::mem::offset_of!(Stat, uid), 12);
        assert_eq!(core::mem::offset_of!(Stat, gid), 16);
        assert_eq!(core::mem::offset_of!(Stat, kind), 20);

        // Имя лежит массивом внутри структуры, поэтому её размер — это предел
        // имени плюс поля, и он обязан быть виден числом.
        assert_eq!(size_of::<Dirent>(), 288);
        assert_eq!(core::mem::offset_of!(Dirent, name), 32);
        assert_eq!(MAX_NAME, 255);

        assert_eq!(size_of::<Launch>(), 40);
        assert_eq!(core::mem::offset_of!(Launch, stdin), 24);
        assert_eq!(core::mem::offset_of!(Launch, stdout), 32);

        assert_eq!(size_of::<Timespec>(), 16);
        assert_eq!(core::mem::offset_of!(Timespec, nanos), 8);

        assert_eq!(size_of::<PollFd>(), 16);
        assert_eq!(core::mem::offset_of!(PollFd, wanted), 8);
        assert_eq!(core::mem::offset_of!(PollFd, ready), 12);

        assert_eq!(size_of::<Times>(), 16);
        assert_eq!(core::mem::offset_of!(Times, uptime_ms), 8);

        // Заявку на окно половинами заполняют разные стороны, поэтому её
        // раскладка проверяется поимённо: поле, уехавшее на четыре байта,
        // означает окно, которое ядро заведёт не того размера.
        assert_eq!(size_of::<WindowSpec>(), 40);
        assert_eq!(core::mem::offset_of!(WindowSpec, title), 0);
        assert_eq!(core::mem::offset_of!(WindowSpec, title_len), 8);
        assert_eq!(core::mem::offset_of!(WindowSpec, surface), 16);
        assert_eq!(core::mem::offset_of!(WindowSpec, width), 24);
        assert_eq!(core::mem::offset_of!(WindowSpec, height), 28);
        assert_eq!(core::mem::offset_of!(WindowSpec, id), 32);

        assert_eq!(size_of::<WinEvent>(), 16);
        assert_eq!(core::mem::offset_of!(WinEvent, code), 4);
        assert_eq!(core::mem::offset_of!(WinEvent, x), 8);
        assert_eq!(core::mem::offset_of!(WinEvent, y), 12);

        // Счётчики системы: восемнадцать полей, и раскладка у них проверяется
        // по краям — первое поле, первое из четырёхбайтовых и общий размер.
        // Поле, вставленное в середину, сдвинет всё, что за ним, и монитор
        // покажет число задач вместо свободной памяти, ничего об этом не
        // заметив.
        assert_eq!(size_of::<SysInfo>(), 128);
        assert_eq!(align_of::<SysInfo>(), 8);
        assert_eq!(core::mem::offset_of!(SysInfo, uptime_ms), 0);
        assert_eq!(core::mem::offset_of!(SysInfo, frames_total), 16);
        assert_eq!(core::mem::offset_of!(SysInfo, windows), 112);
        assert_eq!(core::mem::offset_of!(SysInfo, tasks_alive), 116);
        assert_eq!(core::mem::offset_of!(SysInfo, flags), 120);
        assert_eq!(core::mem::offset_of!(SysInfo, pixel_format), 124);

        assert_eq!(size_of::<NetConfig>(), 16);
        assert_eq!(size_of::<NetInfo>(), 24);
        assert_eq!(size_of::<Peer>(), 8);
        assert_eq!(size_of::<StreamState>(), 4);
    }

    /// Коды ошибок и прочие числа, которые программа сравнивает с ответом.
    #[test]
    fn constants_keep_their_values() {
        assert_eq!(ABI_VERSION, 0x0001_0000);

        assert_eq!(FD_STDIN, 0);
        assert_eq!(FD_STDOUT, 1);
        assert_eq!(FD_STDERR, 2);
        assert_eq!(FD_FIRST, 3);
        assert_eq!(MAX_OPEN_FILES, 8);

        assert_eq!(KIND_FILE, 1);
        assert_eq!(KIND_DIRECTORY, 2);
        assert_eq!(KIND_PIPE, 3);

        assert_eq!(WIN_KEY, 1);
        assert_eq!(WIN_POINTER, 2);
        assert_eq!(WIN_CLOSE, 3);
        assert_eq!(MAX_TITLE, 64);
        assert_eq!(SYSINFO_DARK, 1);
        // Эти два числа знают оба конца: ядро кладёт их в `SysInfo`, а
        // `mini_ui::use_raw_format` принимает. Разъехавшись, они дали бы окно,
        // в котором красное нарисовано синим.
        assert_eq!(PIXEL_RGB, 1);
        assert_eq!(PIXEL_BGR, 2);

        assert_eq!(O_WRITE, 1);
        assert_eq!(O_CREATE, 2);
        assert_eq!(O_TRUNC, 4);
        assert_eq!(SEEK_SET, 0);
        assert_eq!(SEEK_CUR, 1);
        assert_eq!(SEEK_END, 2);

        assert_eq!(CLOCK_REALTIME, 0);
        assert_eq!(CLOCK_MONOTONIC, 1);
        assert_eq!(POLL_IN, 1);
        assert_eq!(POLL_OUT, 2);
        assert_eq!(POLL_HUP, 4);
        assert_eq!(POLL_BAD, 8);
        assert_eq!(POLL_FOREVER, -1);

        // Отрицательные — все до одного: программа отличает отказ от ответа по
        // знаку, и код, ставший положительным, был бы прочитан как успех.
        for code in [
            ERR_NO_SYSCALL, ERR_BAD_ADDRESS, ERR_NOT_FOUND, ERR_PERMISSION, ERR_BAD_FD,
            ERR_TOO_MANY_FILES, ERR_IO, ERR_UNSUPPORTED, ERR_NO_FILESYSTEM, ERR_BAD_PATH,
            ERR_NO_PROGRAM, ERR_EXISTS, ERR_NOT_EMPTY, ERR_NO_SPACE, ERR_AGAIN, ERR_NO_TASK,
            ERR_TOO_MANY_TASKS, ERR_NO_NETWORK, ERR_BAD_SOCKET, ERR_BROKEN_PIPE,
            ERR_UPDATE_REFUSED, ERR_LIMIT,
        ] {
            assert!(code < 0, "код {code} обязан быть отрицательным");
        }
    }
