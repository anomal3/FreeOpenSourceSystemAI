//! Журнал установщика — в последовательный порт, мимо консоли прошивки.
//!
//! Казалось бы, `println!` крейта `uefi` уже пишет и на экран, и в COM-порт.
//! Именно поэтому он здесь не годится: ConOut на обеих наших машинах — это
//! мультиплексор поверх графической консоли, и каждая строка журнала рисуется
//! прошивкой **поверх** интерфейса установщика. Получилось бы, что программа
//! портит собственный экран тем чаще, чем подробнее её журнал.
//!
//! Поэтому журнал уходит напрямую в `EFI_SERIAL_IO_PROTOCOL`. Побочная выгода
//! важнее исходной задачи: автоматический прогон снимает ровно эти строки с
//! серийной линии QEMU, и по ним видно, что установщик делал, — а на экране в
//! это время остаётся нетронутая картинка, которую можно сфотографировать.
//!
//! Порта может не быть (машина без UART). Это не отказ: журнал просто некуда
//! писать, и установка идёт дальше молча.

use core::cell::UnsafeCell;
use core::fmt::{self, Write};

use uefi::boot::{self, OpenProtocolAttributes, OpenProtocolParams, ScopedProtocol};
use uefi::proto::console::serial::Serial;

/// Ячейка под открытый протокол.
///
/// `UnsafeCell` в обёртке, а не `static mut`: обращение к последнему через
/// ссылку — это `static_mut_refs`, и справедливо. Здесь же оговорка сделана
/// один раз, в одном месте, и её условие проверяемо: установщик однопоточный,
/// прерываний не включает и обращается к ячейке только из кода ниже.
struct PortSlot(UnsafeCell<Option<ScopedProtocol<Serial>>>);

// SAFETY: параллельного доступа не существует — см. комментарий выше.
unsafe impl Sync for PortSlot {}

/// Открытый порт живёт всё время работы установщика: искать его заново на
/// каждую строку — это перебор хендлов протокола на каждый `logln!`.
static PORT: PortSlot = PortSlot(UnsafeCell::new(None));

/// Найти последовательный порт.
///
/// Вызывается один раз, до первой строки журнала.
///
/// Открытие **не** эксклюзивное, и это выяснилось дорогой ценой.
/// Эксклюзивное открытие отбирает порт у самой прошивки, а её консоль (ConOut)
/// на обеих наших машинах выводит в том числе туда. В результате пропадало
/// ровно то, что нужнее всего: сообщение обработчика паники. Установщик молча
/// перезагружал машину, и в журнале не было ни строчки о причине. Здесь
/// достаточно просто писать в порт рядом с прошивкой.
pub fn init() {
    let Ok(handle) = boot::get_handle_for_protocol::<Serial>() else {
        return;
    };
    let params = OpenProtocolParams {
        handle,
        agent: boot::image_handle(),
        controller: None,
    };
    // SAFETY: `GetProtocol` не делает установщик потребителем устройства и
    // потому ничего от него не отключает; указатель используется только для
    // записи байт и живёт не дольше самого приложения.
    let Ok(serial) = (unsafe { boot::open_protocol::<Serial>(params, OpenProtocolAttributes::GetProtocol) })
    else {
        return;
    };
    // SAFETY: единственный поток, и ссылка не переживает эту строку.
    unsafe { *PORT.0.get() = Some(serial) };
}

/// Записать строку в порт, если он есть.
pub fn write_str(text: &str) {
    // SAFETY: см. `PortSlot` — параллельного доступа нет, ссылка не покидает
    // функцию.
    let slot = unsafe { &mut *PORT.0.get() };
    let Some(port) = slot.as_mut() else {
        return;
    };
    // Ошибку записи глотаем сознательно: журнал не та вещь, ради которой стоит
    // прерывать установку.
    let _ = port.write_exact(text.as_bytes());
}

/// Приёмник для `write!`.
pub struct Writer;

impl Write for Writer {
    fn write_str(&mut self, text: &str) -> fmt::Result {
        write_str(text);
        Ok(())
    }
}

/// Строка журнала. Перевод строки дописывается сам, и обязательно `\r\n`:
/// терминал на том конце — не консоль, а сырой порт.
#[macro_export]
macro_rules! logln {
    () => { $crate::log::write_str("\r\n") };
    ($($arg:tt)*) => {{
        use core::fmt::Write as _;
        let _ = write!($crate::log::Writer, $($arg)*);
        $crate::log::write_str("\r\n");
    }};
}
