/// Отказ операции над томом.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    /// Носитель отказал.
    Io,
    /// Раздел меньше, чем требует формат.
    TooSmall,
    /// На диске не то, что ожидалось: подпись, версия или счётчики не сходятся.
    Corrupt,
    /// Контрольная сумма прочитанного блока не сошлась.
    ///
    /// Отдельно от [`Error::Corrupt`] намеренно: это единственная ошибка,
    /// которая говорит «носитель отдал не те байты», а не «структура тома
    /// противоречит себе». Смешать их значит потерять ровно то, ради чего
    /// btrfs здесь и появился.
    BadChecksum,
    /// Пути нет.
    NotFound,
    /// Компонент пути оказался не каталогом.
    NotADirectory,
    /// Операция для файла, а имя оказалось каталогом.
    IsADirectory,
    /// Имя пустое, слишком длинное или содержит `/`.
    BadName,
    /// Том пользуется возможностью, которой здесь нет: сжатием, шифрованием,
    /// несколькими устройствами, RAID, подтомами.
    Unsupported,
    /// Не хватило памяти.
    NoMemory,
}

impl From<disk::Error> for Error {
    fn from(err: disk::Error) -> Self {
        match err {
            disk::Error::TooSmall => Error::TooSmall,
            _ => Error::Io,
        }
    }
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let text = match self {
            Error::Io => "the block device reported a failure",
            Error::TooSmall => "the partition is too small for a btrfs filesystem",
            Error::Corrupt => "on-disk structure is inconsistent",
            Error::BadChecksum => "a block failed its crc32c check",
            Error::NotFound => "no such file or directory",
            Error::NotADirectory => "a path component is not a directory",
            Error::IsADirectory => "the name is a directory",
            Error::BadName => "the name is empty, too long or contains a slash",
            Error::Unsupported => "the volume uses a feature this implementation lacks",
            Error::NoMemory => "out of memory",
        };
        f.write_str(text)
    }
}

pub type Result<T> = core::result::Result<T, Error>;

/// Выделить нулевой буфер, вернув ошибку вместо паники при нехватке памяти.
pub(crate) fn try_zeroed(len: usize) -> Result<alloc::vec::Vec<u8>> {
    let mut out = alloc::vec::Vec::new();
    out.try_reserve_exact(len).map_err(|_| Error::NoMemory)?;
    out.resize(len, 0u8);
    Ok(out)
}
