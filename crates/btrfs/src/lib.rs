//! Файловая система btrfs: чтение тома, созданного `mkfs.btrfs`.
//!
//! # Зачем она, когда есть ext2
//!
//! ext2 выбран под корень за то, что его есть чем проверить снаружи, и это
//! решение не отменяется: ядро и загрузчик читают корень без единой строки
//! отсюда. btrfs нужен ровно за двумя свойствами, которых у ext2 нет и не
//! будет:
//!
//! * **контрольная сумма на каждом секторе данных**, а не только на
//!   метаданных, — то есть тихая порча диска перестаёт быть тихой;
//! * **снимки настроек** — дешёвая копия поддерева, из которой можно откатить
//!   `/etc` после неудачной правки.
//!
//! Снимки *системы* сюда не входят: их работу делает второй слот раздела
//! (фаза 32), и дублировать её файловой системой незачем.
//!
//! # Почему это отдельный крейт, а не модуль ядра
//!
//! По той же причине, что и `ext2`: формат обязан читаться на хосте, чужим
//! процессом, без эмулятора. Тест, который гоняет разбор на образе от
//! `mkfs.btrfs`, стоит секунду; тот же разбор, проверенный только загрузкой
//! системы, стоит полчаса и не показывает, где именно сломалось.
//!
//! # Чем это проверяется
//!
//! Тем же, чем ext2, — **чужим верификатором**. Образ в
//! `crates/btrfs/tests/fixture.img.gz` создан `mkfs.btrfs` v6.8.1 и наполнен
//! ядром Linux; ни один байт в нём не написан этим крейтом. Читатель, который
//! сходится сам с собой, не доказывает ничего — а этот обязан сойтись с
//! реализацией, которой двадцать лет.
//!
//! Пересобирается образ командой `cargo xtask btrfs-fixture` (нужен WSL с
//! `btrfs-progs`); в репозитории он лежит готовым, чтобы тесты шли на машине
//! без Linux вообще.
//!
//! # Что здесь есть и чего нет
//!
//! Есть: суперблок и его копии, дерево кусков и перевод логического адреса в
//! физический, дерево корней, дерево файловой системы, каталоги, inode,
//! экстенты данных (обычные, встроенные и предвыделенные), дыры, и **сверка
//! crc32c на каждом прочитанном блоке** — и метаданных, и данных.
//!
//! Нет: записи (она в фазе 50), подтомов и снимков, сжатия, RAID любого вида,
//! нескольких устройств в томе, журнала (`log tree`), расширенных атрибутов.
//! Каждый пункт отвергается явной ошибкой [`Error::Unsupported`], а не молча:
//! том, который мы не понимаем целиком, обязан сказать об этом, а не показать
//! половину содержимого с уверенным видом.
//!
//! # Единицы измерения, в которых легко ошибиться
//!
//! Их здесь четыре, и они не совпадают:
//!
//! * **сектор носителя** — 512 или 4096 байт, этим оперирует
//!   [`disk::BlockDevice`];
//! * **сектор ФС** (`sectorsize`) — единица данных и контрольной суммы,
//!   обычно 4096;
//! * **узел** (`nodesize`) — блок дерева, обычно 16384;
//! * **логический адрес** — адрес в сквозном пространстве тома, который
//!   **не равен** смещению на диске: перевод делает дерево кусков.
//!
//! Последнее — главный источник ошибок: логический адрес выглядит как обычное
//! смещение и в томе из одного куска почти совпадает с ним. Почти — потому что
//! первый кусок начинается не с нуля, и код, забывший про перевод, читает
//! мусор со смещением ровно в одно значение.

