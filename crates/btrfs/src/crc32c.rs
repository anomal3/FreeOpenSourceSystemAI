//! CRC-32C (Castagnoli) — единственная контрольная сумма, которой пользуется
//! btrfs по умолчанию.
//!
//! # Почему не годится `disk::crc32`
//!
//! Тот считает CRC-32 по многочлену IEEE 802.3 (0xEDB88320 в отражённом виде)
//! — его требует GPT. У btrfs многочлен другой, Castagnoli (0x82F63B78
//! отражённый), и перепутать их нельзя незаметно: длина совпадает, значения
//! расходятся на первом же байте. Отдельная таблица здесь, а не общая с
//! флагом, ровно поэтому: два способа считать «crc32» в одном вызове — это
//! приглашение ошибиться местом вызова.
//!
//! # Две разные функции поверх одной
//!
//! btrfs пользуется этим алгоритмом дважды и **по-разному**:
//!
//! * контрольная сумма блока — с начальным `!0` и отрицанием в конце, то есть
//!   обычный CRC-32C ([`checksum`]);
//! * хеш имени в записи каталога — с начальным `!1` и **без** отрицания
//!   ([`name_hash`]).
//!
//! Второе выглядит произволом, но это буквально то, что делает ядро Linux
//! (`btrfs_name_hash`). Добавить сюда отрицание «для единообразия» значит не
//! найти в каталоге ни одного имени.

/// Отражённый многочлен Castagnoli.
const POLY: u32 = 0x82F6_3B78;

/// Таблица на 256 входов считается компилятором.
///
/// Килобайт постоянных данных в образе ядра — плата за то, чтобы не считать
/// сумму побитово: на чтении файла в мегабайты разница видна.
const TABLE: [u32; 256] = build_table();

const fn build_table() -> [u32; 256] {
    let mut table = [0u32; 256];
    let mut index = 0usize;
    while index < 256 {
        let mut value = index as u32;
        let mut bit = 0;
        while bit < 8 {
            value = if value & 1 != 0 { (value >> 1) ^ POLY } else { value >> 1 };
            bit += 1;
        }
        table[index] = value;
        index += 1;
    }
    table
}

/// Продолжить счёт суммы по очередному куску данных.
///
/// Ни начального, ни конечного отрицания здесь нет намеренно: обе надстройки
/// над этим примитивом делают их по-своему, и спрятать одну из них внутрь
/// значит сломать другую.
#[must_use]
pub(crate) fn update(mut crc: u32, data: &[u8]) -> u32 {
    for &byte in data {
        crc = TABLE[((crc ^ u32::from(byte)) & 0xFF) as usize] ^ (crc >> 8);
    }
    crc
}

/// Контрольная сумма блока в том виде, в каком она лежит на диске.
#[must_use]
pub(crate) fn checksum(data: &[u8]) -> u32 {
    !update(!0, data)
}

/// Хеш имени, по которому запись каталога находится в дереве.
///
/// Возвращается `u64`, потому что именно `u64` занимает поле `offset` ключа;
/// старшая половина всегда нулевая.
#[must_use]
pub(crate) fn name_hash(name: &[u8]) -> u64 {
    u64::from(update(!1, name))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Контрольные значения CRC-32C из RFC 3720 (iSCSI), приложение B.
    ///
    /// Взяты у чужой спецификации намеренно: сверять свою реализацию со своим
    /// же ожиданием — значит проверять, что код не менялся, а не что он верен.
    #[test]
    fn matches_rfc3720_vectors() {
        assert_eq!(checksum(&[0u8; 32]), 0x8A91_36AA);
        assert_eq!(checksum(&[0xFFu8; 32]), 0x62A8_AB43);

        let mut ascending = [0u8; 32];
        for (index, byte) in ascending.iter_mut().enumerate() {
            *byte = index as u8;
        }
        assert_eq!(checksum(&ascending), 0x46DD_794E);
    }

    #[test]
    fn empty_input_is_zero() {
        assert_eq!(checksum(&[]), 0);
    }
}
