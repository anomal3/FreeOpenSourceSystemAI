//! Путь из запроса: развернуть `%XX`, убрать `.` и `..`, не выпустить за корень.
//!
//! # Почему это самое опасное место сервера
//!
//! Потому что здесь чужая строка превращается в имя файла. Ошибка тут — это не
//! неверная страница, а `GET /../../etc/passwd`, то есть отданный наружу файл,
//! который никто не собирался раздавать. Историй, где сервер отдавал чужие
//! файлы, столько же, сколько попыток обойтись «проверкой на две точки»:
//!
//! * проверить `..` **до** разворачивания `%XX` — значит пропустить `%2e%2e`;
//! * проверить `..` и не тронуть `%2f` — значит пропустить `..%2f..%2f`;
//! * склеить корень с путём строками и понадеяться на файловую систему — значит
//!   доверить безопасность тому, кто о ней ничего не знает.
//!
//! Поэтому порядок здесь один и обратного не бывает: **сначала развернуть, а
//! потом разбирать**, причём разбирать по сегментам, а не поиском подстроки.
//! Результат начинается с косой черты, не содержит ни `.`, ни `..`, ни пустых
//! сегментов — и его уже можно дописывать к корню.

/// Сколько сегментов помещается в пути.
///
/// Предел есть потому, что сегменты считает тот, кто прислал запрос. Тридцать
/// два — это `/a/b/c/...` глубиной в тридцать два каталога, чего не бывает у
/// сайта; глубже — отказ, а не молчаливое обрезание.
const MAX_SEGMENTS: usize = 32;

/// Что означает очередной сегмент пути.
#[derive(Clone, Copy)]
enum Segment {
    /// Пустой или `.` — не значит ничего.
    Nothing,
    /// `..` — вернуться на сегмент назад.
    Up,
    /// Имя, которое остаётся в пути.
    Name,
}

/// Путь и строка запроса порознь.
///
/// Строка запроса (`?a=1`) серверу статики не нужна ни для чего, но выбросить
/// её молча нельзя: она часть цели, и прокси передаёт её дальше как есть.
#[must_use]
pub fn split_target(target: &str) -> (&str, &str) {
    match target.split_once('?') {
        Some((path, query)) => (path, query),
        None => (target, ""),
    }
}

/// Развернуть `%XX` и привести путь к каноническому виду.
///
/// Результат пишется в `out` и возвращается как срез в нём. `None` — путь
/// негоден: не с косой черты, битая последовательность `%`, управляющий знак,
/// не UTF-8, слишком глубоко, не помещается в `out` или **выходит за корень**.
/// Отказ один на все причины нарочно: сервер отвечает на них одинаково (`400`),
/// а подробность ответа — это подсказка тому, кто перебирает.
pub fn normalize<'b>(raw: &str, out: &'b mut [u8]) -> Option<&'b str> {
    if !raw.starts_with('/') {
        return None;
    }
    let decoded = decode(raw, out)?;

    // Сегменты складываются в тот же буфер, поверх развёрнутого: готовый путь
    // никогда не длиннее развёрнутого, потому что разбор только выбрасывает.
    let mut write = 0usize;
    // Начало каждого сегмента в готовом пути — чтобы `..` умел вернуться.
    let mut starts = [0usize; MAX_SEGMENTS];
    let mut depth = 0usize;

    let mut read = 1usize; // первый байт — косая черта, она уже учтена
    while read <= decoded {
        let end = match out[read..decoded].iter().position(|byte| *byte == b'/') {
            Some(at) => read + at,
            None => decoded,
        };
        let len = end - read;
        // Сегмент опознаётся до правки буфера: заимствование на чтение и запись
        // в один и тот же массив не уживаются, а копия-признак — уживается.
        let segment = &out[read..end];
        let kind = if segment.is_empty() || segment == b"." {
            Segment::Nothing
        } else if segment == b".." {
            Segment::Up
        } else {
            Segment::Name
        };
        match kind {
            // Пустой сегмент (`//`) и `.` не значат ничего.
            Segment::Nothing => {}
            Segment::Up => {
                // Выход выше корня — отказ, а не «останемся в корне». Второе
                // выглядит безопасным ровно до первой ошибки в этом же разборе.
                depth = depth.checked_sub(1)?;
                write = starts[depth];
            }
            Segment::Name => {
                if depth == MAX_SEGMENTS {
                    return None;
                }
                starts[depth] = write;
                depth += 1;
                out[write] = b'/';
                out.copy_within(read..end, write + 1);
                write += len + 1;
            }
        }
        read = end + 1;
    }

    if write == 0 {
        out[0] = b'/';
        write = 1;
    }
    core::str::from_utf8(&out[..write]).ok()
}

/// Остаток пути под приставкой: `under("/up/x", "/up")` — это `/x`.
///
/// Сравнение идёт **по сегментам**, а не по буквам: иначе приставка `/up`
/// накрыла бы и `/update`, то есть проксировалась бы страница, которую никто
/// проксировать не просил. Ровно `/up` даёт `/`.
#[must_use]
pub fn under<'a>(path: &'a str, prefix: &str) -> Option<&'a str> {
    let prefix = prefix.trim_end_matches('/');
    if prefix.is_empty() {
        return Some(path);
    }
    let rest = path.strip_prefix(prefix)?;
    match rest.as_bytes().first() {
        None => Some("/"),
        Some(b'/') => Some(rest),
        Some(_) => None,
    }
}

/// Развернуть `%XX` в `out`. Возвращает длину развёрнутого.
fn decode(raw: &str, out: &mut [u8]) -> Option<usize> {
    let bytes = raw.as_bytes();
    let mut at = 0usize;
    let mut len = 0usize;
    while at < bytes.len() {
        let byte = if bytes[at] == b'%' {
            let high = digit(*bytes.get(at + 1)?)?;
            let low = digit(*bytes.get(at + 2)?)?;
            at += 3;
            high * 16 + low
        } else {
            let byte = bytes[at];
            at += 1;
            byte
        };
        // Управляющие знаки в имени файла не значат ничего хорошего: `\0`
        // обрезает имя у всякого, кто передаст его дальше строкой C, а `\r` и
        // `\n` уезжают в журнал и рисуют там строку, которой не было.
        // Обратная косая — потому что её понимают как разделитель и наша
        // оболочка, и Windows, а сервер обязан понимать путь одним способом.
        if byte < 0x20 || byte == 0x7f || byte == b'\\' {
            return None;
        }
        *out.get_mut(len)? = byte;
        len += 1;
    }
    Some(len)
}

/// Шестнадцатеричная цифра в число.
fn digit(byte: u8) -> Option<u8> {
    match byte {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}
