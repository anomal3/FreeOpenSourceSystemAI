//! Программа, доказывающая, что память, взятая по запросу, действительно есть.
//!
//! # Что именно она проверяет
//!
//! Просит у ядра сотни мегабайт, трогает **каждую** страницу и сверяет
//! прочитанное с записанным, после чего возвращает область — и дважды получает
//! отказ, каждый раз по своей причине: шестьдесят четыре гигабайта отвергает
//! предел задачи, пятьсот мегабайт — пул кадров машины. Коды у этих отказов
//! разные, и программа требует именно тот, который следует: «памяти нет» вместо
//! «столько не дают» означало бы, что предел не работает, а машина просто мала.
//!
//! До этой фазы у программы был ровно тот кусок памяти, который положил ей
//! загрузчик, и попросить ещё было не у кого. Проверка «попросили — получили —
//! записали — прочитали» падает до неё на первом же шаге, и это единственная
//! форма проверки, которая доказывает, что фаза что-то изменила, — в отличие от
//! «ничего не сломалось», выглядящего одинаково до и после.
//!
//! # Почему узор, а не константа
//!
//! Потому что константа не отличает исправное отображение от испорченного.
//! Ошибка в таблицах страниц, при которой две разные виртуальные страницы ведут
//! на один физический кадр, — не выдумка, а самый вероятный способ ошибиться в
//! этом коде: адрес считается по индексу, и промах в арифметике даёт именно её.
//! Область, залитая одним байтом, после такой ошибки читается идеально: везде
//! лежит то, что клали. Узор, зависящий от смещения, ломается сразу — вторая
//! страница затирает первую своим значением, и первая же сверка это видит.
//!
//! # Почему трогается каждая страница, но не каждый байт
//!
//! Трогается каждая — потому что доказательством существования памяти является
//! именно обращение: страница, которой не касались, могла и не быть отображена,
//! и никто бы не узнал. А внутри страницы пишется одно восьмибайтовое слово:
//! страница отображается целиком или не отображается вовсе, третьего состояния
//! у неё нет, и остальные 4088 байт не проверяют ничего сверх первых восьми.
//! Стоит это разницы между двумя мегабайтами обращений и двумястами
//! пятьюдесятью шестью — на порядок больше времени за ноль новых сведений.

#![no_std]
#![no_main]

use user_progs::{
    Args, ERR_LIMIT, ERR_NO_SPACE, Line, exit, mmap, munmap, println,
};

/// Сколько мегабайт просить, если не сказали иного.
///
/// Число выбрано так, чтобы заведомо не поместиться ни в один кусок, который
/// программа получает при запуске: это должна быть память, которой без вызова
/// не было бы.
const DEFAULT_MIB: u64 = 256;

/// Размер страницы. Продублирован здесь числом: спросить о нём у ядра сейчас
/// нечем, а шаг обхода нужен именно такой — по странице, а не по чему попало.
/// Ошибиться в меньшую сторону безопасно (лишние обращения внутрь той же
/// страницы), в большую — значит пропускать страницы, поэтому 4096 и стоит.
const PAGE: usize = 4096;

/// Множитель, размешивающий номер страницы по всем шестидесяти четырём битам.
///
/// Нечётный (обратим по модулю 2^64), то есть разным номерам отвечают разные
/// значения. Простой `page as u64` тоже был бы узором, но у соседних страниц
/// он отличался бы одним младшим битом — а перепутанные при отображении
/// страницы чаще всего именно соседние.
const MIX: u64 = 0x9E37_79B9_7F4A_7C15;

/// Сколько просить у ядра заведомо сверх всякого предела.
const ABSURD_BYTES: usize = 64 * 1024 * 1024 * 1024;

/// Сколько просить, чтобы упереться в **память машины**, а не в предел задачи.
///
/// Пятьсот мегабайт: меньше предела на задачу (полгигабайта), то есть просьба
/// доходит до настоящего выделения, — и больше, чем бывает свободно у гостя с
/// 512 МиБ, из которых ядро уже своё взяло. Отказать обязан пул кадров, и
/// ответить обязан другим кодом.
///
/// Проверка эта не про отказ, а про то, что происходит **после** него: к этому
/// месту ядро успевает занять и разложить почти полгигабайта, и всё это обязано
/// вернуться в пул. Без такой просьбы откат частичного выделения не исполнялся
/// бы ни разу за прогон — а сверка кадров в конце сценария его и ловит.
const EXHAUST_BYTES: usize = 500 * 1024 * 1024;

#[unsafe(no_mangle)]
pub extern "C" fn _start(argc: usize, argv: *const *const u8) -> ! {
    // SAFETY: значения пришли от ядра в том виде, в каком их описывает договор.
    let args = unsafe { Args::new(argc, argv) };

    let mib = match args.get(1) {
        None => DEFAULT_MIB,
        Some(text) => match parse_u64(text) {
            // Верхний предел — не придирка: `mib << 20` при большом числе
            // переполнит `usize`, и ядро получит просьбу о случайной длине
            // вместо огромной. Отказаться понятной строкой лучше.
            Some(value) if value > 0 && value <= 65_536 => value,
            _ => {
                println("usage: memtest [mib]");
                exit(2);
            }
        },
    };

    let len = (mib as usize) * 1024 * 1024;
    let addr = mmap(len);
    if addr < 0 {
        let mut line = Line::new();
        line.str("memtest: mmap of ").num(mib).str(" MiB refused: ");
        line.signed(addr);
        line.end();
        exit(1);
    }
    let base = addr as usize;

    let mut line = Line::new();
    line.str("memtest: mapped ").num(mib).str(" MiB at ");
    line.num(base as u64);
    line.end();

    let pages = len / PAGE;

    for page in 0..pages {
        let cell = (base + page * PAGE) as *mut u64;
        // SAFETY: адрес лежит внутри области, которую только что отдало ядро:
        // `page` меньше `pages`, а `pages` посчитано из её длины. Выравнивание
        // под `u64` даёт начало области — оно выровнено на страницу, — и шаг,
        // кратный странице.
        //
        // Запись **volatile**, и это не суеверие: обычную запись, за которой
        // следует чтение того же адреса, компилятор вправе выбросить, подставив
        // в сверку записанное значение. Проверка после этого доказывала бы, что
        // работает LLVM, а не что работает память.
        unsafe { core::ptr::write_volatile(cell, pattern(page)) };
    }

    for page in 0..pages {
        let cell = (base + page * PAGE) as *const u64;
        // SAFETY: тот же адрес, что и при записи, по тем же основаниям.
        let got = unsafe { core::ptr::read_volatile(cell) };
        let want = pattern(page);
        if got != want {
            // Печатается **первая** несовпавшая страница, а не их число: узнав
            // номер, можно посчитать адрес и посмотреть, чьё значение туда
            // легло, — а количество не говорит ни о чём, кроме масштаба беды.
            let mut line = Line::new();
            line.str("memtest: page ").num(page as u64);
            line.str(" mismatch: wrote ").num(want);
            line.str(", read ").num(got);
            line.end();
            exit(1);
        }
    }

    let mut line = Line::new();
    line.str("memtest: ").num(mib);
    line.str(" MiB written and read back, no mismatches");
    line.end();

    let freed = munmap(base, len);
    if freed != 0 {
        let mut line = Line::new();
        line.str("memtest: munmap refused: ").signed(freed);
        line.end();
        exit(1);
    }
    println("memtest: unmapped");

    // И то, ради чего половина фазы затевалась: у задачи есть потолок. Без этой
    // проверки система, раздающая память до последнего кадра, выглядела бы
    // исправной ровно до того дня, когда одна программа заберёт её всю.
    let refused = mmap(ABSURD_BYTES);
    if refused != ERR_LIMIT {
        let mut line = Line::new();
        line.str("memtest: 64 GiB was not refused by the limit: ");
        line.signed(refused);
        line.end();
        exit(1);
    }
    println("memtest: the limit refused 64 GiB");

    // А это — отказ по другой причине и с другим кодом: предел задачи пропускает
    // просьбу, и упирается она в пул кадров. Заодно единственный за прогон
    // случай, когда исполняется откат наполовину сделанного выделения.
    let starved = mmap(EXHAUST_BYTES);
    if starved != ERR_NO_SPACE {
        let mut line = Line::new();
        line.str("memtest: 500 MiB answered ");
        line.signed(starved);
        line.str(" instead of 'no space'");
        line.end();
        // Если её всё-таки выдали, держать её незачем — и незачем уносить с
        // собой: возвращаем, чтобы сверка кадров показала настоящую причину
        // расхождения, а не эту.
        if starved > 0 {
            munmap(starved as usize, EXHAUST_BYTES);
        }
        exit(1);
    }
    println("memtest: the pool refused 500 MiB");

    exit(0)
}

/// Что лежит в начале страницы с таким номером.
///
/// Номер страницы, а не адрес: адрес зависит от того, куда ядро положило
/// область, и та же самая проверка на другом запуске сверяла бы другие числа.
/// Печатать в сообщении об ошибке имеет смысл именно номер.
const fn pattern(page: usize) -> u64 {
    (page as u64).wrapping_mul(MIX) ^ MIX
}

/// Разобрать десятичное число. `None` — не число или пусто.
fn parse_u64(text: &str) -> Option<u64> {
    let mut value = 0u64;
    let mut digits = 0;
    for byte in text.bytes() {
        if !byte.is_ascii_digit() {
            return None;
        }
        value = value.checked_mul(10)?.checked_add(u64::from(byte - b'0'))?;
        digits += 1;
    }
    if digits == 0 { None } else { Some(value) }
}
