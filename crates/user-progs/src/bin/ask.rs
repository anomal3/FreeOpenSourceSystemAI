//! Первая программа, которая **спрашивает**.
//!
//! До этой фазы у программы был только выход: она могла напечатать что угодно и
//! не могла узнать ни одной нажатой клавиши. Здесь появляется вторая половина —
//! дескриптор 0, чтение из которого останавливает программу до тех пор, пока
//! человек не наберёт строку.
//!
//! Заодно это первая программа, которая **управляет** терминалом, а не только
//! льёт в него текст: очищает экран, ставит курсор в известное место и печатает
//! цветом. Всё это — обычные последовательности ANSI, те же самые, которые
//! понимает любой терминал; разбирает их ядро, и то, что оно разобрало, видно в
//! журнале.

#![no_std]
#![no_main]

use user_progs::{exit, print, print_u64, println, read_line, window_size};

/// Сколько байт отводится под ответ.
///
/// Массив на стеке, а не растущий буфер: кучи у программы нет, и предел, о
/// котором известно заранее, лучше предела, который однажды кончится молча.
const ANSWER: usize = 64;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    // Размер окна в знаках — отдельным вызовом, потому что иначе его неоткуда
    // взять: программа не знает ни размера экрана, ни размера глифа, ни того,
    // есть ли вообще графика.
    let (cols, rows) = window_size();
    print("ask: window is ");
    print_u64(u64::from(cols));
    print("x");
    print_u64(u64::from(rows));
    println(" cells");

    // Очистка экрана и курсор в левый верхний угол — то, с чего начинает всякая
    // полноэкранная программа. Здесь это ещё и доказательство: ядро назовёт обе
    // последовательности в журнале.
    print("\x1b[2J\x1b[1;1H");

    // Зелёный вопрос, обычный ответ. Цвет сбрасывается сразу же: программа,
    // оставившая свой цвет включённым, перекрасит приглашение оболочки, которая
    // её запустила.
    print("\x1b[32mask: name?\x1b[0m ");

    let mut buffer = [0u8; ANSWER];
    let Some(name) = read_line(&mut buffer) else {
        // Ноль байт означает конец ввода, а не пустую строку: человек нажал
        // Ctrl+D или ввод закончился сам. Различать эти случаи обязана
        // программа — ядро сообщает ровно то, что произошло.
        println("ask: end of input");
        exit(1);
    };

    if name.is_empty() {
        println("ask: nobody answered");
        exit(1);
    }

    print("ask: hello, ");
    print(name);
    println("");

    // И второй раз — чтобы было видно, что чтение не одноразовое и что позиция
    // в потоке ввода не теряется между вызовами.
    print("ask: say something? ");
    let mut second = [0u8; ANSWER];
    match read_line(&mut second) {
        Some(text) => {
            print("ask: heard ");
            print_u64(text.len() as u64);
            print(" bytes: ");
            print(text);
            println("");
        }
        None => println("ask: end of input"),
    }

    println("ask: done");
    exit(0)
}
