//! Программа, которая больше прежнего окна образа (фаза 54).
//!
//! # Что она доказывает
//!
//! Внутри — шесть мегабайт данных только для чтения, то есть один этот файл
//! вдвое больше трёх мегабайт, в которые до фазы 54 обязана была помещаться
//! любая программа целиком. Запуститься она может только если ядро **не
//! читает образ заранее**: сегменты записаны в таблицу областей, а страница
//! приходит с носителя при первом обращении к ней, как у отображённого файла
//! (фаза 41).
//!
//! Три утверждения, каждое своей строкой:
//!
//! 1. Программа запустилась и знает размер своих данных — значит, предел
//!    размера файла снят, а не поднят.
//! 2. Свёртка по каждому тысячному слову сошлась с числом, посчитанным на
//!    хосте, — значит, каждая страница пришла та и на то место: сдвиг на
//!    страницу, нули вместо содержимого или чужая страница дали бы другое
//!    число (FNV-1a чувствительна к порядку, см. `filemap`).
//! 3. Ядро при выходе печатает, сколько страниц образа прочитало. Их обязано
//!    быть не меньше, чем страниц в данных: обход трогает каждую. И больше
//!    страниц, чем держит одна область (четыре мегабайта), — значит, часть
//!    из них была выброшена и прочитана заново, а программа этого не заметила.
//!
//! # Почему данные — повторённая страница
//!
//! Каждая страница одинакова: слово `n` в ней равно `0x5A5A_0000 | n`. Так
//! массив не стоит ничего ни компилятору (повтор константы), ни архиву
//! (сжимается в ничто — образ initrd едет и на телефон, где место считано), а
//! проверить всё равно есть что: одинаковые страницы **разными** не сделает ни
//! одна ошибка загрузчика, но нули, обрезанный хвост и сдвиг внутри страницы
//! видны и на них. Шаг обхода в тысячу слов не делит страницу нацело, и точка
//! касания ползёт по ней.

#![no_std]
#![no_main]

use user_progs::{Line, exit};

/// Слов в странице.
const PAGE_WORDS: usize = 1024;
/// Страниц данных: шесть мегабайт.
const PAGES: usize = 1536;

/// Одна страница образца: слово `n` равно `0x5A5A_0000 | n`.
const fn page() -> [u32; PAGE_WORDS] {
    let mut page = [0u32; PAGE_WORDS];
    let mut i = 0;
    while i < PAGE_WORDS {
        page[i] = 0x5A5A_0000 | i as u32;
        i += 1;
    }
    page
}

const PAGE: [u32; PAGE_WORDS] = page();

/// Шесть мегабайт в `.rodata` — сам предмет проверки.
static DATA: [[u32; PAGE_WORDS]; PAGES] = [PAGE; PAGES];

/// Через сколько слов брать следующее. Не делитель страницы намеренно.
const STRIDE: usize = 1000;

#[unsafe(no_mangle)]
pub extern "C" fn _start(_argc: usize, _argv: *const *const u8) -> ! {
    let bytes = core::mem::size_of_val(&DATA);
    let mut line = Line::new();
    line.str("big: data is ").num(bytes as u64).str(" bytes in the image");
    line.end();

    // Свёртка FNV-1a по каждому тысячному слову. Чтение volatile: обычное
    // чтение константной таблицы компилятор вправе посчитать заранее, и тогда
    // ни одна страница не была бы тронута.
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    let total = PAGES * PAGE_WORDS;
    let mut index = 0usize;
    while index < total {
        let cell = &DATA[index / PAGE_WORDS][index % PAGE_WORDS] as *const u32;
        // SAFETY: адрес внутри статического массива, выровнен на слово.
        let word = unsafe { core::ptr::read_volatile(cell) };
        hash ^= u64::from(word);
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
        index += STRIDE;
    }
    let mut line = Line::new();
    line.str("big: checksum over every 1000th word is ").num(hash);
    line.end();

    // Две точки, известные заранее: середина и самое последнее слово.
    // SAFETY: адреса внутри массива.
    let middle = unsafe { core::ptr::read_volatile(&DATA[777][5] as *const u32) };
    let last = unsafe { core::ptr::read_volatile(&DATA[PAGES - 1][PAGE_WORDS - 1] as *const u32) };
    let ok = middle == 0x5A5A_0005 && last == 0x5A5A_03FF;
    let mut line = Line::new();
    line.str("big: spot checks ").str(if ok { "passed" } else { "FAILED" });
    line.end();

    exit(if ok { 0 } else { 1 });
}
