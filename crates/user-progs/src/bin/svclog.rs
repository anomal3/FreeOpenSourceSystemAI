//! `svclog` — служба, у которой нет другой работы, кроме как быть живой.
//!
//! Существует затем, чтобы у супервизора было за кем следить до появления
//! настоящих служб (клиент DHCP — фаза 35). Ровно поэтому она устроена как
//! настоящая: работает вечно, отзывается в журнал и умирает только тогда, когда
//! её убьют.
//!
//! Отзывается редко и намеренно. Служба, печатающая строку десять раз в
//! секунду, забила бы журнал, по которому проверяется вся остальная система, —
//! а журнал здесь единственное доказательство чего бы то ни было.

#![no_std]
#![no_main]

use user_progs::{error, error_num, exit, pid, sleep_ms, uid};

/// Как часто отзываться.
///
/// Полминуты, а не пять секунд, и причина не в бережливости. Строка службы
/// уходит в ту же серийную линию, по которой стенд проверяет всё остальное, а
/// пишет она мимо замка вывода оболочки — то есть в редком случае может лечь
/// посередине чужой строки. Чем реже отзыв, тем реже этот случай; проверять же
/// живость службы всё равно приходится не отзывом, а тем, что она поднимается
/// после того, как её сняли.
const PERIOD_MS: u64 = 30_000;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    // Первая строка — сразу, а не через пять секунд: она отвечает на вопрос
    // «служба запустилась?», и ответ, приходящий с задержкой, неотличим от
    // «нет».
    error("svclog: up as #");
    error_num(pid() as i64);
    error(", running as uid ");
    error_num(i64::from(uid()));
    error("\n");

    let mut beats: u64 = 0;
    loop {
        sleep_ms(PERIOD_MS);
        beats += 1;
        error("svclog: alive, beat ");
        error_num(beats as i64);
        error("\n");
        // Возврата отсюда не бывает: служба заканчивается только снаружи.
        // Строчка ниже недостижима и стоит здесь ради типа.
        if beats == u64::MAX {
            exit(0);
        }
    }
}
