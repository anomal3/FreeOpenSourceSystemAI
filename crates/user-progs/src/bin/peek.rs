//! Программа, которая пытается прочитать память ядра.
//!
//! Существует ради утверждения, которое появилось вместе с отдельными
//! адресными пространствами: корень таблиц программы — **копия** ядерного, и
//! записи ядра в нём присутствуют. Присутствие отображения и доступ к нему —
//! разные вещи, но проверить это можно только снаружи: изнутри ядра обе ветки
//! выглядят одинаково успешными.
//!
//! Отличие от `crash` принципиальное. Тот обращается по нулевому адресу,
//! который не отображён вообще ни для кого, и отказ там означает лишь
//! «страницы нет». Здесь адрес **отображён**, и отказ означает ровно то, что
//! нужно доказать: страницу ядра из третьего кольца (EL0) не отдают.

#![no_std]
#![no_main]

use user_progs::{exit, println};

/// Начало прямого отображения физической памяти в ядре (`PHYS_MAP_BASE`).
///
/// Адрес выбран так, чтобы быть отображённым заведомо и на обеих архитектурах:
/// прямое отображение строится при запуске и покрывает всю физическую память.
/// На x86-64 запись о нём лежит в копии корня, доставшейся программе; на
/// AArch64 верхняя половина вообще общая, потому что переключается только
/// `TTBR0_EL1`. То есть в обоих случаях отказ придёт не из-за отсутствия
/// трансляции, а из-за прав.
const KERNEL_DIRECT_MAP: usize = 0xFFFF_8000_0000_0000;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    println("about to read kernel memory that this program's own page tables describe");

    // SAFETY: безопасности здесь нет и не предполагается — программа
    // существует, чтобы получить отказ. Ядро обязано снять её, а не исполнить
    // это чтение.
    let value = unsafe { core::ptr::read_volatile(KERNEL_DIRECT_MAP as *const u64) };

    println("the read succeeded, which means kernel memory is reachable from ring 3");
    exit(value as i64 | 1)
}
