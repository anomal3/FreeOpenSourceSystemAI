//! `svcbad` — служба, которая падает при каждом запуске.
//!
//! Нужна затем же, зачем в стенде нужен `/bin/crash`: утверждение «супервизор
//! перестаёт поднимать безнадёжное» нечем проверить на исправной службе. Здесь
//! поломка воспроизводится с первого раза и всегда.
//!
//! Падает **кодом возврата**, а не отказом страницы, и это разные проверки.
//! Отказ снимает ядро, и супервизор увидел бы `EXIT_FAULTED`; ненулевой код
//! возвращает сама программа — то есть проверяется путь, по которому приходит
//! обычная неисправная служба, а не та, что обратилась по нулевому адресу.

#![no_std]
#![no_main]

use user_progs::{Line, exit, pid, sleep_ms};

/// С каким кодом заканчиваться. Не единица: единицу возвращает слишком многое,
/// а по журналу должно быть видно, что это именно она.
const CODE: i64 = 3;

/// Сколько прожить, прежде чем упасть.
///
/// Не ноль. Служба, кончающаяся быстрее, чем супервизор успевает записать её
/// номер, проверяла бы гонку в стенде, а не выдержку супервизора.
const LIVE_MS: u64 = 50;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    Line::to_log()
        .str("svcbad: up as #")
        .signed(pid() as i64)
        .str(", and about to fail on purpose")
        .end();
    sleep_ms(LIVE_MS);
    Line::to_log()
        .str("svcbad: failing with code ")
        .signed(CODE)
        .end();
    exit(CODE)
}
