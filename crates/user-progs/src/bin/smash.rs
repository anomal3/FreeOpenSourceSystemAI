//! Программа, которая переполняет буфер на стеке нарочно.
//!
//! Существует ради утверждения, которое иначе нечем проверить: **переполнение
//! стека кончается не прыжком по чужому адресу, а снятием программы с внятным
//! словом**. Компилятор кладёт в кадр каждой функции со стековым массивом
//! канарейку и сверяет её перед возвратом (`-Z stack-protector=strong`, см.
//! `xtask::build`); эталон лежит в странице процесса, которую ядро заполняет
//! случайными байтами до входа в программу.
//!
//! Без канарейки та же функция вернулась бы по адресу из одних букв `A` и
//! снималась бы ядром за отказ команды — стенд ждёт не этого, а строки
//! `stack smashing detected` и кода 134. Разница между двумя исходами и есть
//! то, что проверяется.
//!
//! Со словом `guard` программа вместо этого пишет в саму страницу процесса —
//! доказывая, что эталон **нельзя** подделать: страница отображена только на
//! чтение, и запись в неё — снятие программы ядром, как запись по нулевому
//! адресу в `crash`.

#![no_std]
#![no_main]

use user_abi::PROCESS_PAGE;
use user_progs::{Args, exit, print, print_u64, println};

/// Переполнить буфер на своём стеке, затерев канарейку.
///
/// Не встраивается: смысл в том, чтобы у функции был **свой** кадр со своей
/// канарейкой и своим адресом возврата, и чтобы возврат из неё состоялся —
/// проверка канарейки стоит именно в эпилоге.
///
/// # Почему до отметки, а не «столько-то байт»
///
/// Расстояние от буфера до канарейки зависит от сборки: в отладочной кадр
/// большой и канарейка далеко, в оптимизированной — впритык. Фиксированное
/// число байт либо не дотянулось бы до неё в отладке, либо в оптимизации
/// перелетело бы вершину стека и дало отказ страницы **раньше** проверки — то
/// есть проверяло бы не то. Поэтому верхнюю границу задаёт вызывающий: адрес
/// своей переменной, лежащей в кадре над нашим. Он заведомо выше и канарейки, и
/// адреса возврата, но ниже вершины стека, так что запись затирает канарейку и
/// не выходит за отображённое ни в одной сборке.
///
/// # Почему одним `memset`, а не циклом
///
/// Цикл здесь съедал сам себя. В отладочной сборке компилятор держит счётчик
/// не в регистре, а в стеке, и на AArch64 он ложился **сразу над буфером**
/// (буфер `sp+0x40`, счётчик `sp+0x50`): дойдя до него, запись делала счётчик
/// числом из букв `A`, то есть больше границы, — и цикл заканчивался, не
/// добравшись до канарейки на `sp+0x98`. Программа спокойно возвращалась, и
/// выглядело это как «канарейки нет». На x86-64 тот же код работал: там
/// счётчик лёг под буфером. У `memset` состояние лежит в **её** кадре, ниже
/// нашего буфера, и затереть себя записью вверх она не может ни в одной сборке.
#[inline(never)]
fn overrun(top: usize) {
    let mut buffer = [0u8; 16];
    let base = buffer.as_mut_ptr();
    let len = top.saturating_sub(base as usize);
    // SAFETY: безопасности здесь нет и не предполагается — в этом весь смысл
    // программы. `[base, top)` целиком лежит в стеке (буфер, остаток нашего
    // кадра и кадр вызывающего), и запись обязана затереть канарейку по дороге.
    unsafe {
        core::ptr::write_bytes(base, b'A', len);
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn _start(argc: usize, argv: *const *const u8) -> ! {
    // SAFETY: значения пришли от ядра ровно в том виде, в каком их описывает
    // договор: массив из `argc` строк, завершённых нулём, в стеке программы.
    let args = unsafe { Args::new(argc, argv) };

    if args.get(1) == Some("guard") {
        println("smash: about to write to the stack guard page");
        // SAFETY: см. модуль — страница отображена только на чтение, и запись
        // обязана дать отказ, который получит программа, а не ядро.
        unsafe {
            core::ptr::write_volatile(PROCESS_PAGE as *mut u64, 0x4141_4141_4141_4141);
        }
        println("smash: the guard page took a write, which means it is not read-only");
        exit(1)
    }

    println("smash: overrunning a 16-byte stack buffer past its frame");
    // Отметка в кадре `_start`: она выше кадра `overrun`, то есть выше его
    // канарейки и адреса возврата, но ниже вершины стека.
    let marker: u8 = 0;
    let top = core::ptr::addr_of!(marker) as usize;
    overrun(core::hint::black_box(top));
    // Сюда доходят только без канарейки — и то лишь если затёртый адрес
    // возврата случайно оказался исполняемым.
    print("smash: returned from the overrun at ");
    print_u64(top as u64);
    println("");
    exit(1)
}
