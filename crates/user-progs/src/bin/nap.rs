//! Программа, которая спит.
//!
//! Разница с `/bin/count`, который отмеряет паузы уступками в цикле, не в
//! длительности, а в том, чего стоит ожидание. Уступающая программа остаётся
//! готовой к исполнению: планировщик возвращает ей процессор на каждом витке,
//! она смотрит на часы и уступает снова. Спящая выходит из очереди совсем — и
//! пока она спит, `tasks` показывает её как `blocked`, а не `ready`.
//!
//! Это и есть проверка фазы: строки `blocked` в системе, где ожидание было
//! кручением, взяться было неоткуда.

#![no_std]
#![no_main]

use user_progs::{exit, pid, print, print_u64, println, sleep_ms, uptime_ms};

/// Сколько спать.
///
/// Достаточно долго, чтобы стенд успел спросить `tasks` и получить ответ, пока
/// программа спит.
const NAP_MS: u64 = 3_000;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    let me = pid();
    let start = uptime_ms();

    print("nap ");
    print_u64(me);
    print(": sleeping ");
    print_u64(NAP_MS);
    println(" ms, asking for nothing");

    sleep_ms(NAP_MS);

    // Проспать **меньше** заказанного нельзя: срок округляется вверх до целого
    // тика. Печатаем измеренное, а не заказанное, — иначе строка подтверждала
    // бы намерение, а не результат.
    print("nap ");
    print_u64(me);
    print(": woke after ");
    print_u64(uptime_ms() - start);
    println(" ms");
    exit(0)
}
