//! Программа, по которой видно, что программ несколько.
//!
//! Печатает несколько строк, уступая процессор между ними, и в каждой называет
//! себя номером. Смысл ровно в этом: две такие программы, запущенные подряд в
//! фоне, дают в журнале чередующиеся строки с разными номерами — то есть
//! доказательство, что обе исполняются, и что между ними переключаются.
//!
//! Номер берётся у ядра ([`user_progs::pid`]), а не выдумывается: он же
//! показывается командой `tasks` в оболочке, потому что программа **и есть**
//! задача планировщика.

#![no_std]
#![no_main]

use user_progs::{exit, pid, print, print_u64, println, uptime_ms, yield_now};

/// Сколько раз программа отметится.
const TICKS: u64 = 5;

/// Сколько миллисекунд проходит между отметками.
///
/// Программа отмеряет их **по часам**, а не по числу уступок, и это не
/// украшение. Без задержки оптимизированная сборка досчитывает до конца за
/// доли миллисекунды — быстрее, чем оболочка успевает получить вторую команду,
/// — и «две программы одновременно» превратилось бы в «две программы подряд».
/// Полсекунды работы делают перекрытие неизбежным в любой сборке.
const STEP_MS: u64 = 120;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    let me = pid();
    let start = uptime_ms();

    for tick in 1..=TICKS {
        // Ожидание — это уступка в цикле: спать программа не умеет, потому что
        // будить её нечем. Заодно и видно, что уступка работает: пока эта
        // программа ждёт, считает вторая.
        let due = start + tick * STEP_MS;
        while uptime_ms() < due {
            yield_now();
        }

        print("count ");
        print_u64(me);
        print(": tick ");
        print_u64(tick);
        print(" of ");
        print_u64(TICKS);
        print(" at ");
        print_u64(uptime_ms());
        println(" ms");
    }

    print("count ");
    print_u64(me);
    println(": done");
    exit(0)
}
