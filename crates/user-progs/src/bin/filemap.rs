//! Программа, доказывающая, что файл действительно виден как память.
//!
//! # Что именно она проверяет
//!
//! Открывает файл, узнаёт его размер, отображает его целиком, **закрывает
//! дескриптор** и только после этого обходит отображение, складывая байты. Три
//! утверждения фазы проверяются здесь ровно этими шагами, и каждый — своим:
//!
//! 1. Содержимое файла читается без [`user_progs::read`] и без буфера: байты
//!    берутся из памяти, куда их никто не копировал. До этой фазы такого адреса
//!    у программы не существовало вовсе.
//! 2. Страницы подкладываются по обращению. Вызов возвращается мгновенно, а
//!    платит за содержимое обход: каждая новая страница — это отказ обращения,
//!    поход на носитель и возврат в ту же инструкцию. Если бы отказ не
//!    обрабатывался, программа не досчитала бы сумму, а умерла бы на первом же
//!    байте.
//! 3. Отображение держит файл **само**. Дескриптор закрывается сразу после
//!    удачного отображения — не для экономии, а потому что это единственная
//!    проверка, отличающая настоящую область от куска, который ядро втихую
//!    привязало к живому дескриптору. Система, где закрытие `fd` снимает
//!    отображение, до этой строки выглядела бы исправной.
//!
//! # Почему сумма, а не сверка с прочитанным
//!
//! Сверка была бы сильнее: прочитать файл обычным `read` в буфер и сравнить
//! побайтно — это доказательство того, что отображение показывает **тот самый**
//! файл, а не какой-нибудь. Но буфера у программы нет (кучи нет, стека 64 КиБ),
//! то есть сверка шла бы кусками, и с закрытым дескриптором она невозможна в
//! принципе — а закрыть его важнее, см. пункт 3 выше.
//!
//! Поэтому здесь отпечаток: сумма детерминирована для данного файла, и сценарий
//! стенда сверяет напечатанное число с известным заранее. Это ловит всё, что
//! меняет байты, — не ту страницу, сдвиг на страницу, нули вместо содержимого, —
//! и не ловит перестановку байтов внутри одного шага обхода. Предел названный, а
//! не забытый: перестановка внутри страницы не является ни одной из ошибок,
//! которыми ошибаются в этом коде.
//!
//! # Почему каждый сотый байт, а не каждый и не каждая страница
//!
//! Каждый байт — это обход в сто раз длиннее ради тех же сведений: страница
//! отображается целиком или не отображается вовсе, и внутри неё второе
//! обращение не проверяет ничего сверх первого.
//!
//! Шаг ровно по странице был бы худшим из вариантов, хотя выглядит самым
//! разумным: 4096 делит смещение нацело, то есть трогался бы **первый байт
//! каждой страницы** — то самое смещение, на котором ошибка выравнивания
//! незаметна. Сотня не делит 4096 нацело (40 шагов и 96 байт остатка), поэтому
//! точка касания ползёт по странице и за сорок одну страницу обходит её почти
//! всю.
//!
//! Сотня меньше страницы — значит ни одна страница не пропущена, и это условие,
//! а не совпадение: шаг больше 4096 оставил бы страницы нетронутыми, и проверка
//! перестала бы что-либо утверждать о подкладывании по отказу. Шаг задаётся
//! аргументом, и запрета на большой здесь нет — но тот, кто его задаёт, теперь
//! знает, что именно он этим выключает.

#![no_std]
#![no_main]

use user_progs::{Args, Line, close, exit, file_size, mmap_file, munmap, open, println};

/// Через сколько байт брать следующий, если не сказали иного.
///
/// Сотня, а не степень двойки, и именно поэтому — см. заголовок: делитель 4096
/// сажал бы обход на одно и то же смещение внутри каждой страницы.
const DEFAULT_STRIDE: usize = 100;

#[unsafe(no_mangle)]
pub extern "C" fn _start(argc: usize, argv: *const *const u8) -> ! {
    // SAFETY: значения пришли от ядра в том виде, в каком их описывает договор.
    let args = unsafe { Args::new(argc, argv) };

    let Some(path) = args.get(1) else {
        println("usage: filemap <path> [stride]");
        exit(2);
    };

    let stride = match args.get(2) {
        None => DEFAULT_STRIDE,
        Some(text) => match parse_usize(text) {
            // Ноль — не «шаг поменьше», а вечный цикл на первом байте: обход
            // никуда не сдвинулся бы ни разу.
            Some(value) if value > 0 => value,
            _ => {
                println("usage: filemap <path> [stride]");
                exit(2);
            }
        },
    };

    let fd = open(path);
    if fd < 0 {
        let mut line = Line::new();
        line.str("filemap: cannot open ").str(path).str(": ");
        line.signed(fd);
        line.end();
        exit(1);
    }

    // Размер спрашивается у **дескриптора**, а не у пути: `stat` отвечает про
    // имя, а имя к этому моменту могло указывать уже на другой файл. Отобразим
    // мы тот, который открыли, — и мерить надо его же.
    let size = file_size(fd);
    if size <= 0 {
        let mut line = Line::new();
        line.str("filemap: cannot size ").str(path).str(": ");
        line.signed(size);
        line.end();
        close(fd);
        exit(1);
    }
    let size = size as usize;

    let mut line = Line::new();
    line.str("filemap: ").str(path).str(" is ").num(size as u64);
    line.str(" bytes");
    line.end();

    // Смещение ноль: файл отображается от начала. Ненулевое обязано быть кратно
    // странице, и проверять это здесь незачем — вызова с другим смещением у нас
    // нет, а ядро на такое отвечает `ERR_BAD_ADDRESS`.
    let addr = mmap_file(fd, 0, size);
    if addr < 0 {
        let mut line = Line::new();
        line.str("filemap: mmap_file refused: ").signed(addr);
        line.end();
        close(fd);
        exit(1);
    }
    let base = addr as usize;

    // И вот ради этой строки половина программы. Дескриптор закрывается
    // **сразу**, до единого обращения к отображению: всё, что читается ниже,
    // читается из области, у которой открытого файла за спиной больше нет.
    // Отложи мы закрытие до конца — и система, в которой область живёт
    // дескриптором, прошла бы проверку, ни разу не показав этого.
    let closed = close(fd);
    if closed != 0 {
        let mut line = Line::new();
        line.str("filemap: close refused: ").signed(closed);
        line.end();
        munmap(base, size);
        exit(1);
    }

    // Свёртка FNV-1a, а не сумма, и причина стоит того, чтобы её назвать.
    // Сумма **не зависит от порядка слагаемых**: отображение, в котором две
    // страницы поменялись местами или ведут на один кадр, даёт ровно тот же
    // ответ, что и исправное. То есть проверка суммой не ловит именно ту
    // ошибку, ради которой её тут и заводят, — и обнаружилось это на числе:
    // сумма по каждому сотому байту тестового файла вышла ровно 127,5 на
    // отсчёт, то есть чистое среднее, которое сойдётся при любой перестановке.
    //
    // Свёртка, где каждый байт умножается на накопленное, к порядку
    // чувствительна: переставленные страницы дают другое число.
    let mut sum: u64 = 0xcbf2_9ce4_8422_2325;
    let mut offset = 0usize;
    while offset < size {
        let cell = (base + offset) as *const u8;
        // SAFETY: адрес лежит внутри области, которую только что отдало ядро:
        // `offset` меньше `size`, а `size` — та самая длина, которую у него
        // просили. Выравнивание для `u8` требуется любое.
        //
        // Чтение **volatile**, и это не суеверие. Обычное чтение памяти,
        // о которой компилятор считает, что знает всё, он вправе поднять из
        // цикла, повторить или выбросить вовсе — сумма при этом сойдётся, а
        // подкладывания страницы по отказу не случится ни разу. Проверка после
        // такой оптимизации доказывала бы работу LLVM, а не работу ядра. Здесь
        // важно не значение, а то, что обращение **произошло**, и сказать это
        // компилятору можно только так.
        let byte = unsafe { core::ptr::read_volatile(cell) };
        // `wrapping_mul`, а не `*`: перенос через край здесь не авария, а сам
        // способ размешивания, и полагаться на его отсутствие было бы и неверно,
        // и хрупко — паника в зависимости от размера входного файла.
        sum ^= u64::from(byte);
        sum = sum.wrapping_mul(0x0000_0100_0000_01b3);
        // `saturating_add`, а не `+`: шаг приходит из командной строки, и
        // достаточно большой превратил бы последнее сложение в переполнение —
        // то есть в панику на отладочной сборке из-за числа, которое человек
        // имел право набрать. Упереться в потолок здесь означает ровно
        // «обход кончился».
        offset = offset.saturating_add(stride);
    }

    let mut line = Line::new();
    line.str("filemap: checksum over every ").num(stride as u64);
    line.str("th byte is ").num(sum);
    line.end();

    // Длина та же, что просили у `mmap_file`: округление до страницы делало
    // ядро, и повторять его здесь нельзя — договор требует совпадения с
    // просьбой, а не с тем, во что она превратилась.
    let freed = munmap(base, size);
    if freed != 0 {
        let mut line = Line::new();
        line.str("filemap: munmap refused: ").signed(freed);
        line.end();
        exit(1);
    }
    println("filemap: unmapped");

    exit(0)
}

/// Разобрать десятичное число. `None` — не число, пусто или не влезло.
fn parse_usize(text: &str) -> Option<usize> {
    let mut value = 0usize;
    let mut digits = 0;
    for byte in text.bytes() {
        if !byte.is_ascii_digit() {
            return None;
        }
        value = value.checked_mul(10)?.checked_add(usize::from(byte - b'0'))?;
        digits += 1;
    }
    if digits == 0 { None } else { Some(value) }
}
