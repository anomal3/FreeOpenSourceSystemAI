//! Программа, которая ломается нарочно.
//!
//! Существует ради одного утверждения, которое иначе нечем проверить:
//! **отказ пользовательской программы не роняет систему**. До этой фазы любое
//! обращение по нулевому адресу означало панику ядра и остановку машины;
//! теперь это должно означать снятую программу и живую оболочку.
//!
//! Проверяется именно запись, а не чтение: страницы ядра из EL0 недоступны
//! вовсе, а нулевая страница не отображена ни для кого — то есть отказ придёт
//! от блока управления памятью, а не от проверки прав.

#![no_std]
#![no_main]

use user_progs::println;

#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    println("about to write to address zero");

    // SAFETY: безопасности здесь нет и не предполагается — в этом весь смысл
    // программы. Запись по нулевому адресу обязана дать отказ страницы, и
    // проверяется, что его получит программа, а не ядро.
    unsafe {
        core::ptr::write_volatile(core::ptr::null_mut::<u64>(), 0xDEAD);
    }

    println("still alive, which means the fault did not happen");
    user_progs::exit(1)
}
