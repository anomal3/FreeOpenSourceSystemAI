// Заголовок и первые инструкции образа, который запускает чужой загрузчик.
//
// # Договор, которому это следует
//
// Тот же, по которому запускается Linux на ARM64, и другого у заводского
// загрузчика телефона нет. К моменту перехода на нас:
//
//   * MMU выключен, кэш данных выключен, кэш инструкций может быть включён;
//   * прерывания замаскированы;
//   * в `x0` — физический адрес дерева устройств, в `x1`..`x3` — нули;
//   * образ лежит по адресу, который загрузчик прочитал из своего заголовка,
//     и первые 64 байта образа — заголовок ниже.
//
// # Почему заголовок именно такой
//
// Первое слово обязано быть исполнимой инструкцией: часть загрузчиков просто
// переходит по началу образа, не читая ничего. Поэтому там переход через
// заголовок. Второе слово в договоре отведено под ещё одну инструкцию и не
// используется. Дальше — смещение, размер, флаги и метка `ARM\x64`, по которой
// загрузчик отличает наш образ от чужого.

.section .text.boot, "ax"
.global _bare_start

_bare_start:
    b       entry                   // code0: переход через заголовок
    .long   0                       // code1: договором отведено, не используется
    .quad   0x80000                 // text_offset: куда положить образ,
                                    //   считая от начала ОЗУ. Это **не**
                                    //   формальность: загрузчик кладёт нас
                                    //   именно сюда, а слинкованы мы под
                                    //   0x40000000 + это число. Первый запуск
                                    //   ушёл с нулём — образ лёг на 512 КиБ
                                    //   ниже, чем ожидал сам, переходы (они
                                    //   PC-относительные) продолжали работать,
                                    //   а указатели на строки смотрели в
                                    //   пустоту. Машина исправно крутилась и
                                    //   молчала — самый неприятный вид отказа.
    .quad   __image_end - _bare_start   // image_size: сколько памяти занять,
                                    //   включая `.bss` и стек, — иначе
                                    //   загрузчик положит следом дерево и мы
                                    //   затрём его собственным стеком
    .quad   0x0000000000000008      // flags: little-endian, страницы 4 КиБ
    .quad   0                       // res2
    .quad   0                       // res3
    .quad   0                       // res4
    .ascii  "ARM\x64"               // метка: по ней нас узнаю́т
    .long   0                       // смещение заголовка PE, у нас его нет

entry:
    // Дерево устройств — единственное, что нам передали, и единственный
    // регистр, который нельзя потерять. Стека ещё нет, поэтому не в стек.
    mov     x19, x0

    // Стек. Свой, а не тот, что оставил загрузчик: чужой указатель показывает
    // в память, которую тот же загрузчик считает своей и вправе переиспользовать.
    adrp    x1, __stack_top
    add     x1, x1, :lo12:__stack_top
    mov     sp, x1

    // `.bss` в файле не хранится — обнулить обязаны мы. Не сделать этого
    // означает получить статические переменные, набитые тем, что лежало в
    // памяти до нас: на телефоне это остатки заставки загрузчика, то есть
    // правдоподобный мусор.
    adrp    x1, __bss_start
    add     x1, x1, :lo12:__bss_start
    adrp    x2, __bss_end
    add     x2, x2, :lo12:__bss_end
1:  cmp     x1, x2
    b.hs    2f
    str     xzr, [x1], #8
    b       1b
2:

    // Таблица векторов — раньше всего остального, что может отказать.
    // Без неё любое исключение уходит по адресу, который оставил чужой
    // загрузчик, и выглядит это как зависшая машина: ни строки, ни признака.
    // Первый же отказ разбора дерева стоил ровно этого — нельзя было отличить
    // «вернули None» от «взяли исключение».
    adrp    x1, vectors
    add     x1, x1, :lo12:vectors
    mrs     x2, CurrentEL
    lsr     x2, x2, #2
    cmp     x2, #2
    b.ne    4f
    msr     vbar_el2, x1
    b       5f
4:  msr     vbar_el1, x1
5:  isb

    // Разрешить SIMD и плавающую точку. После сброса `CPACR_EL1.FPEN` их
    // запрещает, а компилятор берёт векторные регистры на обычное копирование
    // памяти — например, на разбор сорокабайтового заголовка дерева. Первый
    // же такой доступ отдаёт исключение класса 0x07, и без таблицы векторов
    // это выглядело как «разбор дерева вернул None»: машина стояла, метка не
    // печаталась, причина ни на что не указывала.
    mrs     x2, CurrentEL
    lsr     x2, x2, #2
    cmp     x2, #2
    b.ne    11f
    // На EL2 запрет живёт в другом регистре, и бит там обратный: `TFP` = 1
    // означает «перехватывать».
    mrs     x1, cptr_el2
    bic     x1, x1, #(1 << 10)
    msr     cptr_el2, x1
    b       12f
11: mrs     x1, cpacr_el1
    orr     x1, x1, #(3 << 20)      // FPEN = 0b11: не перехватывать ни с EL0, ни с EL1
    msr     cpacr_el1, x1
12: isb

    // Если загрузчик оставил нас на EL2 (а он может: у гипервизора телефона
    // свои планы), спуститься на EL1 нечем без настройки — но и не нужно:
    // всё, что делает этот образ, работает на любом уровне. Уровень
    // печатается, чтобы знать, с чем иметь дело дальше, когда сюда приедет
    // настоящее ядро.
    mrs     x0, CurrentEL
    lsr     x0, x0, #2
    adrp    x1, CURRENT_EL
    add     x1, x1, :lo12:CURRENT_EL
    str     x0, [x1]

    mov     x0, x19
    bl      bare_main

    // `bare_main` не возвращается. Если вернулся — стоим, а не падаем в мусор
    // за концом образа.
3:  wfe
    b       3b

// Обработчик отказа: сказать, что случилось, и встать.
//
// Печатает прямо в порт по известному адресу QEMU, а не через найденный в
// дереве: до дерева мы можем и не дожить, а отказ, о котором нельзя сообщить,
// ничем не лучше зависания. На телефоне этой линии нет, и там признаком отказа
// остаётся неокрасившийся экран — но телефон и не первая машина, на которой
// это запускается.
//
// В `x0` приходит номер вектора: 0..3 — с текущего уровня со стеком EL0,
// 4..7 — с текущего уровня со своим стеком, 8..15 — с нижнего уровня.
fault:
    mov     x9, #0x09000000
    mov     w10, #88                // 'X'
    str     w10, [x9]
    and     w10, w0, #0xf
    cmp     w10, #10
    b.lo    6f
    add     w10, w10, #39           // 'a'..'f'
6:  add     w10, w10, #48           // '0'..'9'
    str     w10, [x9]

    // Синдром: старшие шесть бит — класс исключения, по ним отличают отказ
    // доступа от неверной инструкции, а это разные ошибки в разных местах.
    mrs     x11, CurrentEL
    lsr     x11, x11, #2
    cmp     x11, #2
    b.ne    7f
    mrs     x11, esr_el2
    b       8f
7:  mrs     x11, esr_el1
8:  lsr     x11, x11, #26
    and     x11, x11, #0x3f
    mov     w10, #32                // пробел
    str     w10, [x9]
    // Класс печатается двумя шестнадцатеричными цифрами.
    lsr     w12, w11, #4
    bl      hexdigit
    and     w12, w11, #0xf
    bl      hexdigit
    mov     w10, #13
    str     w10, [x9]
    mov     w10, #10
    str     w10, [x9]
9:  wfe
    b       9b

// Напечатать младшие четыре бита `w12` шестнадцатеричной цифрой.
hexdigit:
    and     w12, w12, #0xf
    cmp     w12, #10
    b.lo    10f
    add     w12, w12, #39
10: add     w12, w12, #48
    str     w12, [x9]
    ret

// Шестнадцать векторов по 128 байт, вся таблица выровнена по 2 КиБ — так
// требует сам процессор, и невыровненная таблица просто не будет принята.
.macro VECTOR id
    .align  7
    mov     x0, #\id
    b       fault
.endm

    .align  11
vectors:
    VECTOR 0
    VECTOR 1
    VECTOR 2
    VECTOR 3
    VECTOR 4
    VECTOR 5
    VECTOR 6
    VECTOR 7
    VECTOR 8
    VECTOR 9
    VECTOR 10
    VECTOR 11
    VECTOR 12
    VECTOR 13
    VECTOR 14
    VECTOR 15

// Уровень исключений, на котором нас запустили. Читается из Rust.
.section .bss, "aw", @nobits
.global CURRENT_EL
.align 3
CURRENT_EL:
    .quad 0
