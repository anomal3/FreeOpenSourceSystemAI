// Заголовок и первые инструкции образа, который запускает чужой загрузчик.
//
// # Договор, которому это следует
//
// Тот же, по которому запускается Linux на ARM64, и другого у заводского
// загрузчика телефона нет. К моменту перехода на нас:
//
//   * MMU выключен, кэш данных выключен, кэш инструкций может быть включён;
//   * прерывания замаскированы;
//   * в `x0` — физический адрес дерева устройств, в `x1`..`x3` — нули;
//   * образ лежит по адресу, который загрузчик прочитал из своего заголовка,
//     и первые 64 байта образа — заголовок ниже.
//
// # Почему заголовок именно такой
//
// Первое слово обязано быть исполнимой инструкцией: часть загрузчиков просто
// переходит по началу образа, не читая ничего. Поэтому там переход через
// заголовок. Второе слово в договоре отведено под ещё одну инструкцию и не
// используется. Дальше — смещение, размер, флаги и метка `ARM\x64`, по которой
// загрузчик отличает наш образ от чужого.

.section .text.boot, "ax"
.global _bare_start

_bare_start:
    b       entry                   // code0: переход через заголовок
    .long   0                       // code1: договором отведено, не используется
    .quad   0x80000                 // text_offset: куда положить образ,
                                    //   считая от начала ОЗУ. Это **не**
                                    //   формальность: загрузчик кладёт нас
                                    //   именно сюда, а слинкованы мы под
                                    //   0x40000000 + это число. Первый запуск
                                    //   ушёл с нулём — образ лёг на 512 КиБ
                                    //   ниже, чем ожидал сам, переходы (они
                                    //   PC-относительные) продолжали работать,
                                    //   а указатели на строки смотрели в
                                    //   пустоту. Машина исправно крутилась и
                                    //   молчала — самый неприятный вид отказа.
    .quad   __image_end - _bare_start   // image_size: сколько памяти занять,
                                    //   включая `.bss` и стек, — иначе
                                    //   загрузчик положит следом дерево и мы
                                    //   затрём его собственным стеком
    .quad   0x0000000000000008      // flags: little-endian, страницы 4 КиБ
    .quad   0                       // res2
    .quad   0                       // res3
    .quad   0                       // res4
    .ascii  "ARM\x64"               // метка: по ней нас узнаю́т
    .long   0                       // смещение заголовка PE, у нас его нет

entry:
    // ВРЕМЕННО: признак жизни в порт QEMU по известному адресу.
    mov     x9, #0x09000000
    mov     w10, #66
    str     w10, [x9]

    // Дерево устройств — единственное, что нам передали, и единственный
    // регистр, который нельзя потерять. Стека ещё нет, поэтому не в стек.
    mov     x19, x0

    // Стек. Свой, а не тот, что оставил загрузчик: чужой указатель показывает
    // в память, которую тот же загрузчик считает своей и вправе переиспользовать.
    adrp    x1, __stack_top
    add     x1, x1, :lo12:__stack_top
    mov     sp, x1

    // `.bss` в файле не хранится — обнулить обязаны мы. Не сделать этого
    // означает получить статические переменные, набитые тем, что лежало в
    // памяти до нас: на телефоне это остатки заставки загрузчика, то есть
    // правдоподобный мусор.
    adrp    x1, __bss_start
    add     x1, x1, :lo12:__bss_start
    adrp    x2, __bss_end
    add     x2, x2, :lo12:__bss_end
1:  cmp     x1, x2
    b.hs    2f
    str     xzr, [x1], #8
    b       1b
2:

    // Если загрузчик оставил нас на EL2 (а он может: у гипервизора телефона
    // свои планы), спуститься на EL1 нечем без настройки — но и не нужно:
    // всё, что делает этот образ, работает на любом уровне. Уровень
    // печатается, чтобы знать, с чем иметь дело дальше, когда сюда приедет
    // настоящее ядро.
    mrs     x0, CurrentEL
    lsr     x0, x0, #2
    adrp    x1, CURRENT_EL
    add     x1, x1, :lo12:CURRENT_EL
    str     x0, [x1]

    mov     x0, x19
    bl      bare_main

    // `bare_main` не возвращается. Если вернулся — стоим, а не падаем в мусор
    // за концом образа.
3:  wfe
    b       3b

// Уровень исключений, на котором нас запустили. Читается из Rust.
.section .bss, "aw", @nobits
.global CURRENT_EL
.align 3
CURRENT_EL:
    .quad 0
